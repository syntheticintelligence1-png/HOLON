PHEADER = "# GENERATED by holon.undo.proofs; untrusted, accepted only if Bend checks it."


def binders(law: dict) -> list[tuple[str, str]]:
    """The law's binders after s, as (Bend name, Bend type) (the hash tables come first, as Reach needs them)."""
    out = []
    for b in law["statement"]["binders"][1:]:
        ty = str(b["type"])
        if ty.startswith("Fn<"):
            continue
        if ty == "Act":
            out.append((b["name"], "M.HAct"))
        elif ty == "Trace":
            out.append((b["name"], "List<&2, M.HAct>"))
        elif ty == "Word":
            out.append((b["name"], "M.W"))
        elif ty.startswith("Val[") and ty.endswith("]"):
            out.append((b["name"], f"U.Val_{ty[4:-1]}"))
        else:
            raise ValueError(f"{law['law_id']}: binder {b['name']}: {ty} has no Bend type here")
    return out


def call(law: dict, fn: str, names: list[str], tables: list[str]) -> str:
    x = U.ghost_x(law["law_id"])
    return f"U.{fn}_{x}(" + ", ".join(names + tables) + ")"


def law_file(law: dict, statement_hash: str, model_import: str, trace_import: str, hashes: list,
             counter: bool = False) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    kw, q = ("exs", "") if counter else ("for", "+")
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", f"import {trace_import} as U", "", f"law {law_name(lid, counter)}:"]
    for n, _h in tb:
        lines.append(f"  {kw} {q}{n}: List<&2, M.HKB>")
    lines += [f"  {kw} {q}s: M.GSt", f"  {kw} r_s: M.Reach<{idx}s>"]
    bs = binders(law)
    for n, ty in bs:
        lines.append(f"  {kw} {q if not ty.startswith('U.Val_') else ''}{n}: {ty}")
    rel = "!=" if counter else "=="
    lines.append(f"  {{{call(law, 'undo', ['s'] + [n for n, _t in bs], [n for n, _h in tb])} {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def inhabitant_law(law: dict, statement_hash: str, model_import: str, trace_import: str, hashes: list) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    x = U.ghost_x(lid)
    lines = [HEADER, f"# non-vacuity of {lid} (statement_hash {statement_hash}): its premises uhit_{x} are inhabited "
             "by a reachable state and binders", "import Base", f"import {model_import} as M",
             f"import {trace_import} as U", "", f"law nv_{lid.lower()}:"]
    for n, _h in tb:
        lines.append(f"  exs {n}: List<&2, M.HKB>")
    lines += ["  exs s: M.GSt", f"  exs r_s: M.Reach<{idx}s>"]
    bs = binders(law)
    for n, ty in bs:
        lines.append(f"  exs {n}: {ty}")
    lines.append(f"  {{{call(law, 'uhit', ['s'] + [n for n, _t in bs], [n for n, _h in tb])} == True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


class Lit(P3.Lit):
    """Witness literals: the typed model's records qualified by M, the trace section's (its register values) by U."""

    def __init__(self, recs: dict, trace_records: set):
        super().__init__(recs)
        self.mine = set(trace_records)

    def text(self, v) -> str:
        if isinstance(v, dict) and "$r" in v and v["$r"] in self.mine:
            fs = self.recs.get(v["$r"])
            vals = v.get("f") or {}
            order = [f for f, _t in fs] if fs is not None else list(vals)
            return f"U.{v['$r']}{{" + ", ".join(self.text(vals[f]) for f in order) + "}"
        return super().text(v)


def _prefix_defs(tb: list, acts: list, states: list, lit: Lit) -> tuple[list[str], str, str]:
    """The prefix's actions, the literal state after each prefix step, one lemma per step (r_k), and the Reach chain;
    (lines, the chain, the state after the prefix)."""
    targs = "".join(f", t_{n}()" for n, _h in tb)
    if len(states) != len(acts):
        raise ValueError(f"{len(acts)} prefix steps but {len(states)} states")
    lines = []
    for i, a in enumerate(acts):
        lines += [f"def w_p{i}() -> M.HAct:\n  {lit.text(a)}", ""]

    def st(k: int) -> str:
        return "M.gh_s0()" if k == 0 else f"s_{k}()"
    for k in range(1, len(acts) + 1):
        lines += [f"def s_{k}() -> M.GSt:\n  {lit.typed(states[k - 1], 'GSt')}", ""]
    for k in range(len(acts)):
        lines += [f"def r_{k}() -> {{{st(k + 1)} == M.gh_step(w_p{k}(), {st(k)}{targs}) : M.GSt}}:\n  {{==}}", ""]
    chain = "M.R0{{==}}"
    for k in range(len(acts)):
        chain = f"M.RStep{{w_p{k}(), {st(k)}, {chain}, r_{k}()}}"
    return lines, chain, st(len(acts))


def _binder_defs(law: dict, values: dict, lit: Lit) -> tuple[list[str], list[str]]:
    """The witness's binders after s as literal definitions (b_<name>), in the law's order."""
    lines, names = [], []
    for n, ty in binders(law):
        v = values[n]
        if ty == "M.HAct":
            text = lit.text(v)
        elif ty.startswith("List<"):
            text = ("[" + ", ".join(lit.text(a) for a in v) + "]") if v else "Nil{}"
        elif ty == "M.W":
            text = lit.word("0x%064x" % int(v))
        else:
            text = lit.text(v)
        lines += [f"def b_{n}() -> {ty}:\n  {text}", ""]
        names.append(f"b_{n}()")
    return lines, names


def counter_proof(law: dict, model_import: str, trace_import: str, laws_import: str, hashes: list, prefix: list,
                  states: list, values: dict, tables: dict, lit: Lit, note: str) -> str:
    """The counter-law proof of one witness: prefix (HAct values) and the decoded state after each prefix step, the
    binders' values (decoded), the hash tables. cz computes undo_<x> at the literals; the counter-law rewrites with it."""
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{n}()" for n, _h in tb]
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {trace_import} as U",
             f"import {laws_import} as Laws", "", f"# class counter: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = _prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    lines += [f"def cz() -> {{{call(law, 'undo', [state] + bnames, targs)} == False{{}} : Bool}}:\n  {{==}}", ""]
    lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
    tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"


def inhabitant_proof(law: dict, model_import: str, trace_import: str, laws_import: str, hashes: list, prefix: list,
                     states: list, values: dict, tables: dict, lit: Lit) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{n}()" for n, _h in tb]
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {trace_import} as U",
             f"import {laws_import} as Laws", ""]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = _prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    lines += [f"def ch() -> {{{call(law, 'uhit', [state] + bnames, targs)} == True{{}} : Bool}}:\n  {{==}}", ""]
    tup = "ch()"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.nv_{lid.lower()}():\n  {tup}")
    return "\n".join(lines) + "\n"
