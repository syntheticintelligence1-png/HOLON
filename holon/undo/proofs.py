"""The Bend files of an UNDO law (BUILD_PLAN I27; the contract is the docstring of tests_m3/test_undo.py, "Laws" and
"Deciding").

  law_file(..)        gen/<M>/laws/<id>/LAWS.bend: the law (forall the hash tables, s: Reach, the law's binders:
                      undo_<x>(..) == True), or for a REFUTED law its counter-law (exists ..: undo_<x>(..) != True);
                      it imports the typed model as M and the trace section as U, and declares exactly one law
  counter_proof(..)   a counter-law proof at a concrete witness: the hash tables, the literal state after each prefix
                      step with its one-step lemma and the Reach chain they make (holon.sorts.proofs3's A30 shape), the
                      witness's binders as literals, and one closed lemma cz: undo_<x> is false at them
  inhabitant_law(..), inhabitant_proof(..)
                      gen/<M>/<id>/nonvac/: a reachable state and binders where uhit_<x> (the premises alone) is true
                      (G11V), in the same shape

Every computation is a closed lemma: r_k computes one prefix step, cz (ch) the law's function at the literal
pre-witness state; the counter-law only rewrites with cz under its binder (holon.sorts.proofs3, A30). Witness literals
are data (a word is M.w_of_limbs([..]), a byte string a list of bytes). Nothing here names a target.
"""
from __future__ import annotations

from ..gen.mlaws import law_name
from ..rules import undo as U
from ..sorts import proofs3 as P3

HEADER = "# GENERATED by holon.undo.proofs from the frozen law IR; do not edit."

