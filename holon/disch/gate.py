"""The gate's checks of the DISCH laws (BUILD_PLAN I31; the contract is the docstring of tests_m3/test_disch.py,
"Gate"), joined by holon.sorts.gate3 into its checks of the same name:

  G1    `holon disch` regenerates gen/<M>/disch/closure.json and conjuncts.json, `holon derive` the DISCH law files,
        and the DISCH section generator gen/<M>/disch/models/<model>.disch.bend, byte for byte
  G5    every PROOF.bend of a decided DISCH law (its proof, counter-law or witness, and its inhabitant) re-checked by
        Bend; G7 the same files by BendTT (--verdict)
  G11   every DISCH law has a record whose statement hash is the registry's and whose artifacts exist
  G11V  every PROVED blocking, revert and external_none law carries a checked, reachable inhabitant of its premises
  G6    every REFUTED DISCH law and every PROVED external law is a passed entry of replay/<M>/disch/report.json with the
        record's trace (a milestone whose DISCH sidecar names no binding: not applicable)
  G9    every DISCH record is valid under the v1 and v2 schemas
  G4    one canary per PROVED blocking law with a named class: the law's statement with xcl widened by w, the first
        writer of its first named class Y (sorted), under perm_Y; the source law's proof must not check against it

Nothing here names a target.
"""
from __future__ import annotations

import json
import re
import shutil
import tempfile
import time
from pathlib import Path

from .. import bend
from ..machine_bend import bname
from ..sorts.proofs3 import rel_import
from . import section as SEC


def _res(ok: bool, detail: str) -> dict:
    return {"passed": bool(ok), "detail": detail}


class DischGate:
    def __init__(self, g3):
        self.g3 = g3
        self.m = g3.m
        self.root = g3.root
        self.gen = g3.gen
        self.results = g3.results
        self.checks: dict = {}
        self.na: dict = {}
        self.canaries: list = []
        dv = json.loads((self.root / "laws" / self.m / "DERIVATION.json").read_text())
        # I31's DISCH laws: the sub-forms holon.disch.run decides (I86's keyed DISCH laws are the bundle laws', with
        # their own checks: holon.bundle.gate)
        from .run import SUBFORMS
        self.entries = {e["law_id"]: e for e in dv["laws"] if e.get("rule") == "DISCH" and e.get("subform") in SUBFORMS}

    def records(self) -> dict:
        out = {}
        for lid in sorted(self.entries):
            p = self.results / f"{lid}.json"
            out[lid] = json.loads(p.read_text()) if p.is_file() else None
        return out

    def proofs(self) -> list:
        out = []
        for lid, r in self.records().items():
            if not r or r.get("status") not in ("PROVED", "REFUTED"):
                continue
            laws = self.root / r["artifacts"]["laws"]
            if r["artifacts"].get("proof"):
                out.append((lid, "primary", self.root / r["artifacts"]["proof"], laws))
            nv = r.get("non_vacuity") or {}
            p = self.gen / lid / "nonvac" / "PROOF.bend"
            if r["status"] == "PROVED" and nv.get("status") == "inhabited" and p.is_file():
                out.append((lid, "nonvac", p, self.root / nv["law"]))
        return out

    # ------------------------------------------------------------------ checks
    def g1(self):
        bad, notes = [], []
        tmp = Path(tempfile.mkdtemp(prefix="holon-gate3-disch-"))
        try:
            p = self.g3.holon(["disch", "--milestone", self.m, "--root", self.root, "--out", tmp / "d"], self.root)
            if p.returncode != 0:
                bad.append(f"holon disch failed: {(p.stdout + p.stderr)[-300:]}")
            else:
                for n in ("closure.json", "conjuncts.json"):
                    a = self.gen / "disch" / n
                    if not a.is_file() or a.read_bytes() != (tmp / "d" / n).read_bytes():
                        bad.append(f"gen/{self.m}/disch/{n} differs from its regeneration")
                notes.append("disch")
            p = self.g3.holon(["derive", "--milestone", self.m, "--root", self.root, "--out", tmp / "l",
                               "--obstructions", tmp / "obs.json"], self.root)
            if p.returncode != 0:
                bad.append(f"holon derive failed: {(p.stdout + p.stderr)[-300:]}")
            else:
                ldir = self.root / "laws" / self.m
                for lid in sorted(self.entries):
                    a, b = ldir / f"{lid}.json", tmp / "l" / f"{lid}.json"
                    if not b.is_file() or a.read_bytes() != b.read_bytes():
                        bad.append(f"laws/{self.m}/{lid}.json differs from its derivation")
                notes.append(f"derive ({len(self.entries)} DISCH laws)")
            bad += self.section_problems()
            notes.append("the DISCH section")
        finally:
            shutil.rmtree(tmp, ignore_errors=True)
        self.checks["G1"] = _res(not bad, f"DISCH regenerated byte-identical: {', '.join(notes)}" if not bad
                                 else f"DISCH differs: {bad[:6]}")

    def sections(self) -> list:
        """(model, analysis, Section, the section file, the typed model import target) of every document."""
        from ..analysis import closure as C
        from ..sorts import model3 as M3
        from ..sorts.evaluate3 import hashes_of
        sc, ans = C.load(self.m, self.root, None)
        out = []
        for model, an in sorted(ans.items()):
            doc_rel = an["_doc"]
            init = M3.init_of(self.m, self.root, None, doc_rel)
            text, mm = M3.generate(self.m, self.root, doc_rel, typed=True, sidecar=None, init=init)
            sec = SEC.Section(an, mm, text, hashes_of(text))
            sdir = self.gen / "disch" / "models"
            target = self.gen / "sorts" / "models" / M3.importable(model)
            out.append((model, an, sec, sdir / SEC.section_file(model), target))
        return out

    def section_problems(self) -> list:
        bad = []
        try:
            secs = self.sections()
        except Exception as e:  # noqa: BLE001
            return [f"the DISCH section cannot be generated: {type(e).__name__}: {e}"]
        for model, _an, sec, path, target in secs:
            text = sec.text(rel_import(path.parent, target))
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                bad.append(f"{path.relative_to(self.root)} differs from its generation")
        return bad

    def g5(self):
        bad, n, slow = [], 0, 0.0
        for lid, label, proof, _laws in self.proofs():
            n += 1
            t = time.time()
            r = bend.check(proof)
            slow = max(slow, time.time() - t)
            if not r.ok:
                bad.append(f"{lid} {label}: {r.first_line}")
        if n == 0:
            self.na["G5"] = "no DISCH law is decided"
            return
        self.checks["G5"] = _res(not bad, f"{n} DISCH proof files re-checked by Bend (slowest {round(slow, 1)} s)"
                                 if not bad else "; ".join(bad[:8]))

    def g7(self):
        bad, n = [], 0
        for lid, label, proof, _laws in self.proofs():
            n += 1
            r = bend.check_verdict(proof)
            if not r.ok:
                bad.append(f"{lid} {label}: BendTT {r.first_line}")
        if n == 0:
            self.na["G7"] = "no DISCH law is decided"
            return
        self.checks["G7"] = _res(not bad, f"{n} DISCH proof files re-checked by BendTT (--verdict)" if not bad
                                 else "; ".join(bad[:8]))

    def g11(self):
        bad = []
        for lid, r in self.records().items():
            if r is None:
                bad.append(f"{lid}: no record")
                continue
            if r.get("statement_hash") != self.g3.registry["statements"].get(lid):
                bad.append(f"{lid}: statement hash differs from the registry")
            for k in ("laws", "model", "disch"):
                if not r["artifacts"].get(k) or not (self.root / r["artifacts"][k]).exists():
                    bad.append(f"{lid}: artifact {k} missing")
        self.checks["G11"] = _res(not bad, f"{len(self.entries)} DISCH records match the registry and name existing "
                                           "artifacts" if not bad else "; ".join(bad[:8]))

    def g11v(self):
        bad, n = [], 0
        for lid, r in self.records().items():
            if not r or r.get("status") != "PROVED" or r.get("subform") == "external":
                continue
            n += 1
            nv = r.get("non_vacuity") or {}
            p = self.gen / lid / "nonvac" / "PROOF.bend"
            if nv.get("status") != "inhabited" or nv.get("reachable") is not True or not p.is_file():
                bad.append(f"{lid}: non-vacuity {nv.get('status')}")
                continue
            if not bend.check(p).ok:
                bad.append(f"{lid}: its inhabitant does not check")
        if n == 0:
            self.na["G11V"] = "no DISCH blocking, revert or external_none law is PROVED"
            return
        self.checks["G11V"] = _res(not bad, f"{n} PROVED DISCH laws carry a checked reachable inhabitant" if not bad
                                   else "; ".join(bad[:8]))

    def g6(self):
        from ..analysis import closure as C
        sc = C.Sidecar(self.m, self.root, None)
        want = {lid: r for lid, r in self.records().items()
                if r and (r.get("status") == "REFUTED" or (r.get("status") == "PROVED" and r.get("witness")))}
        if not sc.binding:
            self.na["G6"] = "the DISCH sidecar names no binding: no real side to replay on"
            return
        rp = self.root / "replay" / self.m / "disch" / "report.json"
        rep = json.loads(rp.read_text()) if rp.is_file() else {"laws": {}}
        bad = []
        for lid, r in sorted(want.items()):
            x = (rep.get("laws") or {}).get(lid)
            if x is None:
                bad.append(f"{lid}: not replayed")
            elif x.get("status") != "passed" or x.get("trace") != r["witness"]["steps"]:
                bad.append(f"{lid}: replay {x.get('status')}")
            elif (r.get("replay") or {}).get("status") != "passed":
                bad.append(f"{lid}: the record's replay is {(r.get('replay') or {}).get('status')}")
        self.checks["G6"] = _res(not bad, f"{len(want)} DISCH witnesses replayed and passed on the real contract"
                                 if not bad else "; ".join(bad[:8]))

    def g9(self):
        from .. import schema as S
        bad = []
        v1 = json.loads((self.root / "schemas" / "result_record.schema.json").read_text())
        v2 = json.loads((self.root / "spec" / "schemas" / "result_record_v2.schema.json").read_text())
        for lid, r in self.records().items():
            if r is None:
                continue
            for name, sch in (("v1", v1), ("v2", v2)):
                errs = S.errors(r, sch)
                if errs:
                    bad.append(f"{lid}: {name} {errs[:2]}")
        self.checks["G9"] = _res(not bad, f"{len(self.entries)} DISCH records valid under v1 and v2" if not bad
                                 else "; ".join(bad[:6]))

    def g4(self):
        recs = self.records()
        todo = [(lid, r) for lid, r in recs.items() if r and r.get("status") == "PROVED"
                and r.get("subform") == "blocking" and (self.named(lid))]
        if not todo:
            self.na["G4"] = "no PROVED DISCH blocking law with a named class: no disch_writer canary"
            return
        secs = {model: (an, sec, path, target) for model, an, sec, path, target in self.sections()}
        for lid, r in todo:
            self.canaries.append(self.canary(lid, r, secs))
        bad = [c for c in self.canaries if c["kind"] == "disch_writer" and not c["rejected"]]
        n = len([c for c in self.canaries if c["kind"] == "disch_writer"])
        self.checks["G4"] = _res(not bad, f"{n} disch_writer canaries rejected" if not bad
                                 else f"disch_writer canaries accepted: {[c['source_law'] for c in bad]}")

    def named(self, lid: str):
        """(Y, w): the first named class of the law's basis element and its first writer, or None."""
        e = self.entries[lid]
        from ..analysis import closure as C
        an, _sc = C.analysis_for(json.loads((self.root / "laws" / self.m / f"{lid}.json").read_text()), self.root)
        if an is None:
            return None
        b = next(x for x in an["basis"] if x["tag"] == e["basis"]["tag"])
        named = (b["classes"].get(e["basis"]["class"]) or {}).get("named") or {}
        if not named:
            return None
        y = sorted(named)[0]
        ws = sorted(named[y])
        return (y, ws[0]) if ws else None

    def canary(self, lid: str, r: dict, secs: dict) -> dict:
        y, w = self.named(lid)
        e = self.entries[lid]
        model = e["basis"]["model"]
        an, sec, spath, target = secs[model]
        x = SEC.law_key(lid)
        text = spath.read_text(encoding="utf-8")
        wb = bname(w)
        own = set(an["classes"][y]["actions"]) if an["classes"][y]["predicate"] is not None else set()
        perm = sec.perm_code(w) if w in own else None
        perm = perm or "True{}"
        m = re.search(rf"(?ms)^def xcl_{re.escape(x)}\(.*?(?=^def |\Z)", text)
        out = {"kind": "disch_writer", "source_law": lid, "writer": w, "class": y, "law": None, "rejected": False,
               "detail": ""}
        if m is None:
            out["detail"] = "the section has no xcl definition for the law"
            return out
        block = m.group(0)
        case = re.search(rf"    case M\.A_{re.escape(wb)}\{{[^\n]*\}}:\n      [^\n]*\n", block)
        if case is None:
            out["detail"] = f"xcl_{x} has no case for {w}"
            return out
        nb = block.replace(case.group(0), f"    case M.A_{wb}{{+ar, en}}:\n      {perm}\n", 1)
        ctext = text.replace(block, nb, 1)
        cs = spath.parent / f"{spath.stem}_canary.bend"
        lp = self.root / r["artifacts"]["laws"]
        pp = self.root / r["artifacts"]["proof"]
        cl = lp.parent / "LAWS_canary.bend"
        cp = pp.parent / "PROOF_canary.bend"
        try:
            cs.write_text(ctext, encoding="utf-8")
            ltext = lp.read_text(encoding="utf-8").replace(rel_import(lp.parent, spath), rel_import(lp.parent, cs))
            cl.write_text(ltext, encoding="utf-8")
            ptext = pp.read_text(encoding="utf-8").replace(rel_import(pp.parent, spath), rel_import(pp.parent, cs))
            ptext = ptext.replace(rel_import(pp.parent, lp), rel_import(pp.parent, cl))
            cp.write_text(ptext, encoding="utf-8")
            res = bend.check(cp)
            out.update({"law": {"law_id": lid, "xcl_widened_by": w, "under": f"perm_{y}", "statement": ltext,
                                "xcl": nb}, "rejected": not res.ok, "detail": res.first_line})
        finally:
            for f in (cs, cl, cp):
                f.unlink(missing_ok=True)
        return out

    def run(self, only: list | None) -> None:
        for k in ("G1", "G5", "G11", "G11V", "G6", "G9", "G7", "G4"):
            if only and k not in only:
                continue
            try:
                getattr(self, k.lower())()
            except Exception as e:  # noqa: BLE001  (a crash is a failed check)
                self.checks[k] = _res(False, f"error: {type(e).__name__}: {e}")


def join(g3, only: list | None) -> None:
    """Run the DISCH checks and join each with gate3's check of the same name (or add it)."""
    dg = DischGate(g3)
    if not dg.entries:
        return
    dg.run(only)
    g3.canaries += dg.canaries
    for k, r in dg.checks.items():
        if k in g3.checks:
            a = g3.checks[k]
            g3.checks[k] = _res(a["passed"] and r["passed"], f"{a['detail']}; DISCH laws: {r['detail']}")
        else:
            why = g3.na.pop(k, None)
            g3.checks[k] = _res(r["passed"], f"DISCH laws: {r['detail']}"
                                + (f"; I30 laws: not applicable ({why})" if why else ""))
    for k, why in dg.na.items():
        if k not in g3.checks:
            g3.na[k] = f"{g3.na[k]}; DISCH laws: {why}" if k in g3.na else f"DISCH laws: {why}"
