"""The DISCH section of a typed model: gen/<M>/disch/models/<model>.disch.bend (BUILD_PLAN I31; the contract is the
docstring of tests_m3/test_disch.py, rule D11 and "Deciding").

It imports I30's typed model (gen/<M>/sorts/models/<model>.bend) as M and never copies it. Every term is compiled by the
typed model's own generator (holon.sorts.model3: the same compiler, the same code for the same subterm), so a blocked
condition and the check it is the blocked condition of share their atoms textually. For each basis element's tag:

  blkv_<tag>(v1.., t, kh..)   B with each read of a literal key as a parameter (when every read is one: a raw slot,
                              or a structural key of literal words, I68), and
  blk_<tag>(st, t, kh..)      B in state st at block.timestamp t
  chk_<tag>(st, t, kh..)      the representative check c's expr in st at block.timestamp t
  excl_<tag>(a)               a is excluded under B (D8)

for each law (x: its id without "L_disch_"):

  xcl_<x>(st, a, e, kh..)     a is in the law's closure and perm_<class> holds (the class's predicate, compiled where
                              the action's own permission check is, at its context x0 from st, the action's arguments
                              and e; true for anyone's actions)
  prem_<x>, concl_<x>         the premise and the conclusion of the sub-form's claim (D11)
  disch_<x>(a, g, t, e, kh..) the claim: d_imp(prem, concl), or prem and concl for an external law

and d_imp, d_time(e) (e's block.timestamp; 0 for a model whose environment has none), d_env(a, e) (a with e as its
environment), reverts(st, a, e, kh..) (a's code is not 0: it reverts). post(a, s, e) is M.gh_step(d_env(a, e), s, kh..).

The file is written under its importable name (<model with _ for .>_disch.bend; Bend import paths are plain names) with
<model>.disch.bend a relative link to it, as holon.sorts.model3 writes the typed model. Nothing here names a target.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

from ..machine_bend import bname, comment
from ..sorts.model3 import Scope, fold_bytes, importable
from ..sorts.proofs3 import model_names, qualify, rel_import

HEADER = "# GENERATED by holon.disch.section from the DISCH analysis and the typed model; do not edit."
SECTION_VERSION = "holon-disch-section/0.1"


class SectionError(ValueError):
    """A construct the section cannot state (named)."""


def law_key(law_id: str) -> str:
    return law_id[len("L_disch_"):]


def tables(hashes: list[str]) -> list[str]:
    return ["kh" if h == "keccak256" else "sh" for h in hashes]


def section_name(model: str) -> str:
    return f"{model}.disch"


def section_file(model: str) -> str:
    return importable(section_name(model))


_SLOAD_LIT = re.compile(r"M\.sload\(st, (M\.W\{[0-9, ]+\})\)")
_CLOSED_TOKENS = {"M.SK", "M.SP_m", "M.W", "M.w0", "Nil"}


def _balanced(text: str, i: int) -> int:
    """The index just after the argument starting at i (up to the ')' that closes the enclosing call, or a top-level
    ',')."""
    depth = 0
    while i < len(text):
        ch = text[i]
        if ch in "([{":
            depth += 1
        elif ch in ")]}":
            if depth == 0:
                return i
            depth -= 1
        elif ch == "," and depth == 0:
            return i
        i += 1
    raise SectionError("an unbalanced storage read")


def closed_key(k: str) -> bool:
    """A literal storage key: a raw slot word M.W{..} or a structural key M.SK{..} of literal words, w0() and literal
    steps (I68: a key that reads no state, argument or table)."""
    if not re.fullmatch(r"[\sA-Za-z0-9_.,{}\[\]()]*", k):
        return False
    toks = set(re.findall(r"(?<![\w.])[A-Za-z_][\w.]*", k))
    return bool(toks) and toks <= _CLOSED_TOKENS


def sload_keys(code: str) -> list[str]:
    """The literal keys of the storage reads M.sload(st, K) of a closed term, in order of first appearance."""
    out: list[str] = []
    head = "M.sload(st, "
    i = code.find(head)
    while i >= 0:
        j = i + len(head)
        e = _balanced(code, j)
        k = code[j:e]
        if code[e:e + 1] == ")" and closed_key(k) and k not in out:
            out.append(k)
        i = code.find(head, i + 1)
    return out


class Section:
    """The DISCH section of one model: the analysis (holon.analysis.closure), the typed model's generator mm (its
    Machine, after generation) and the model text."""

    def __init__(self, an: dict, mm, model_text: str, hashes: list[str]):
        self.an = an
        self.mm = mm
        self.model_text = model_text
        self.names = model_names(model_text)
        self.tabs = tables(hashes)
        self.tparams = "".join(f", +{n}: List<&2, M.HKB>" for n in self.tabs)
        self.targs = "".join(f", {n}" for n in self.tabs)
        self.acts = re.findall(r"(?m)^  A_(\w+)\{ar: AR_\w+, en: HEnv\}$", model_text)
        if not self.acts:
            raise SectionError("the typed model declares no action constructors")
        self.has_time = re.search(r"(?m)^def ge_e_block_timestamp\(", model_text) is not None
        self.basis = {b["tag"]: b for b in an["basis"]}
        self.by_bname = {bname(a): a for a in self.doc_actions()}
        self.blk: dict = {}      # tag -> {"code", "keys": [K..], "v": blkv code or None, "time": bool}
        self.chk: dict = {}      # tag -> code
        self.perm: dict = {}     # action -> its permission predicate as a term of st, ar, e, kh..

    def doc_actions(self) -> list[str]:
        return list(self.mm.checks.keys()) if getattr(self.mm, "checks", None) else []

    # ------------------------------------------------------------------------------------------------ terms
    def closed(self, code: str, action: str) -> str:
        """A condition compiled in an action's scope (a term of its context x) as a term of st, t and the tables:
        the action's storage view is st, its keccak256 / sha256 tables kh / sh, its block.timestamp t; any other part
        of the context is refused (a state condition reads none)."""
        ba = bname(action)
        out = fold_bytes(code).replace(f"ge_e_block_timestamp(gx_{ba}_en(x))", "@T@")
        out = out.replace(f"gx_{ba}_st(x)", "@ST@")
        for n in self.tabs:
            out = out.replace(f"gx_{ba}_{n}(x)", f"@{n.upper()}@")
        if re.search(r"(?<![\w.])x(?![\w{])", out) or "gx_" in out:
            raise SectionError(f"{action}: a state condition reads more of the context than storage and time: "
                               f"{out[:200]}")
        out = qualify(out, self.names)
        out = out.replace("@T@", "t").replace("@ST@", "st")
        for n in self.tabs:
            out = out.replace(f"@{n.upper()}@", n)
        return out

    def at_x0(self, code: str, action: str) -> str:
        """A condition compiled in an action's scope, at its initial context x0(st, ar, e, tables)."""
        ba = bname(action)
        x0 = f"@X0_{ba}@"
        out = re.sub(r"(?<![\w.])x(?![\w{])", lambda _m: x0, fold_bytes(code))
        out = qualify(out, self.names)
        return out.replace(x0, f"M.x0_{ba}(st, ar, e{self.targs})")

    def compile_tag(self, b: dict) -> None:
        a = b["check"].split("#")[0]
        try:
            bcode = self.mm.cond(b["blocked"], Scope(a))
            ccode = self.mm.cond(b["check_expr"], Scope(a))
        except Exception as e:  # noqa: BLE001: the model's compiler refuses the term (named)
            raise SectionError(f"{b['tag']}: the typed model's compiler refuses its blocked condition: {e}") from e
        blk = self.closed(bcode, a)
        keys = sload_keys(blk)
        v = blk
        for i, k in enumerate(keys):
            v = v.replace(f"M.sload(st, {k})", f"v{i}")
        literal = re.search(r"(?<![\w.])st(?![\w{])", v) is None
        self.blk[b["tag"]] = {"code": blk, "keys": keys if literal else [], "v": v if literal else None,
                              "time": re.search(r"(?<![\w.])t(?![\w{])", blk) is not None}
        self.chk[b["tag"]] = self.closed(ccode, a)

    def perm_code(self, action: str) -> str | None:
        """The action's permission predicate at x0(st, ar, e, tables) (None: no permission check)."""
        if action in self.perm:
            return self.perm[action]
        pid = self.an["permission"].get(action)
        if pid is None:
            self.perm[action] = None
            return None
        k = self.mm.cidx_of(action, pid) + 1
        st = [s for s in self.mm.stmts.get(action) or [] if s.get("kind") == "check" and s.get("code") == k]
        if len(st) != 1 or not st[0].get("cond"):
            raise SectionError(f"{action}: its permission check {pid} is not one statement of its program")
        self.perm[action] = self.at_x0(st[0]["cond"], action)
        return self.perm[action]

    # ------------------------------------------------------------------------------------------------ the text
    def text(self, model_import: str) -> str:
        an = self.an
        for b in an["basis"]:
            self.compile_tag(b)
        out = [HEADER, f"# section_version: {SECTION_VERSION}", f"# model: {comment(an['model'])}", "import Base",
               f"import {model_import} as M", ""]
        out.append("# p implies q\ndef d_imp(p: Bool, q: Bool) -> Bool:\n  Bool.or(Bool.not(p), q)\n")
        if self.has_time:
            out.append("# the step's block.timestamp\ndef d_time(e: M.HEnv) -> M.W:\n  M.ge_e_block_timestamp(e)\n")
        else:
            out.append("# the model's environment has no block.timestamp: time is 0\ndef d_time(e: M.HEnv) -> M.W:\n"
                       "  M.w0()\n")
        cases = "".join(f"    case M.A_{x}{{ar, en}}:\n      M.A_{x}{{ar, e}}\n" for x in self.acts)
        out.append(f"# the action a with the environment e\ndef d_env(a: M.HAct, +e: M.HEnv) -> M.HAct:\n  match a:\n"
                   f"{cases}")
        cases = "".join(f"    case M.A_{x}{{+ar, en}}:\n      M.u_nz(M.gx_{x}_cd(M.xr_{x}(st, ar, e{self.targs})))\n"
                        for x in self.acts)
        out.append(f"# the action reverts from st in e (its code is not 0)\n"
                   f"def reverts(+st: M.HSt, a: M.HAct, +e: M.HEnv{self.tparams}) -> Bool:\n  match a:\n{cases}")
        for b in an["basis"]:
            tag = b["tag"]
            blk = self.blk[tag]
            out.append(f"# B of {comment(tag)}: {comment(b['check'])}")
            if blk["v"] is not None:
                vs = "".join(f"+v{i}: M.W, " for i in range(len(blk["keys"])))
                out.append(f"def blkv_{tag}({vs}+t: M.W{self.tparams}) -> Bool:\n  {blk['v']}\n")
                args = "".join(f"M.sload(st, {k}), " for k in blk["keys"])
                out.append(f"def blk_{tag}(+st: M.HSt, +t: M.W{self.tparams}) -> Bool:\n"
                           f"  blkv_{tag}({args}t{self.targs})\n")
            else:
                out.append(f"def blk_{tag}(+st: M.HSt, +t: M.W{self.tparams}) -> Bool:\n  {blk['code']}\n")
            out.append(f"# c of {comment(tag)}: the representative check's expr\n"
                       f"def chk_{tag}(+st: M.HSt, +t: M.W{self.tparams}) -> Bool:\n  {self.chk[tag]}\n")
            ex = set(bname(n) for n in b["excluded"])
            cases = "".join(f"    case M.A_{x}{{_, _}}:\n      {'True{}' if x in ex else 'False{}'}\n" for x in self.acts)
            out.append(f"# the actions excluded under B (D8)\ndef excl_{tag}(a: M.HAct) -> Bool:\n  match a:\n{cases}")
        for law in an["laws"]:
            out += self.law_defs(law)
        return "\n".join(out)

    def xcl_term(self, x: str, members: dict, closure: list[str]) -> str:
        """xcl over a closure: per action, the class's predicate (true for anyone's actions)."""
        cl = set(bname(n) for n in closure)
        cases = []
        for a in self.acts:
            if a not in cl:
                cases.append(f"    case M.A_{a}{{_, _}}:\n      False{{}}\n")
                continue
            name = self.by_bname.get(a, a)
            if members.get(name):
                pc = self.perm_code(name)
                if pc is None:
                    raise SectionError(f"{name}: an action of a class with a predicate has no permission check")
                cases.append(f"    case M.A_{a}{{+ar, en}}:\n      {pc}\n")
            else:
                cases.append(f"    case M.A_{a}{{_, _}}:\n      True{{}}\n")
        return (f"def xcl_{x}(+st: M.HSt, a: M.HAct, +e: M.HEnv{self.tparams}) -> Bool:\n  match a:\n"
                + "".join(cases))

    def law_defs(self, law: dict) -> list[str]:
        an = self.an
        x = law_key(law["law_id"])
        tag = law["tag"]
        sf = law["subform"]
        out = [f"# {law['law_id']} ({sf})"]
        g_st = "M.gh_get_st(g)"
        post = f"M.gh_get_st(M.gh_step(d_env(a, e), g{self.targs}))"
        if sf == "revert":
            member = f"excl_{tag}(a)"
        else:
            cls = law["class"]
            own = set(an["classes"][cls]["actions"]) if an["classes"][cls]["predicate"] is not None else set()
            out.append(self.xcl_term(x, {n: True for n in own}, law["closure"]))
            member = f"xcl_{x}({g_st}, a, e{self.targs})"
        out.append(f"def prem_{x}(+a: M.HAct, +g: M.GSt, +t: M.W, +e: M.HEnv{self.tparams}) -> Bool:\n"
                   f"  Bool.and({member}, Bool.and(blk_{tag}({g_st}, t{self.targs}), M.w_le(t, d_time(e))))\n")
        if sf == "blocking":
            concl = (f"Bool.and(blk_{tag}({g_st}, d_time(e){self.targs}), blk_{tag}({post}, d_time(e){self.targs}))")
        elif sf == "revert":
            concl = f"reverts({g_st}, a, e{self.targs})"
        elif sf == "external":
            concl = f"chk_{tag}({post}, d_time(e){self.targs})"
        else:
            concl = f"Bool.not(chk_{tag}({post}, d_time(e){self.targs}))"
        out.append(f"def concl_{x}(+a: M.HAct, +g: M.GSt, +e: M.HEnv{self.tparams}) -> Bool:\n  {concl}\n")
        args = f"a, g, t, e{self.targs}"
        cargs = f"a, g, e{self.targs}"
        if sf == "external":
            body = f"Bool.and(prem_{x}({args}), concl_{x}({cargs}))"
        else:
            body = f"d_imp(prem_{x}({args}), concl_{x}({cargs}))"
        out.append(f"def disch_{x}(+a: M.HAct, +g: M.GSt, +t: M.W, +e: M.HEnv{self.tparams}) -> Bool:\n  {body}\n")
        return out


def write_section(out_dir: Path, model: str, text: str) -> Path:
    """Write the section under its importable name and link <model>.disch.bend to it; returns the link's path."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    plain = out_dir / section_file(model)
    if not plain.is_file() or plain.read_text(encoding="utf-8") != text:
        plain.write_text(text, encoding="utf-8")
    link = out_dir / f"{section_name(model)}.bend"
    if link.name != plain.name:
        if link.is_symlink() and os.readlink(link) == plain.name:
            return link
        if link.exists() or link.is_symlink():
            link.unlink()
        os.symlink(plain.name, link)
    return link


def build(an: dict, mm, model_text: str, hashes: list[str], out_dir: Path, model_import_target: Path) -> tuple[Path, str]:
    """Generate and write the section of one model; returns (the <model>.disch.bend path, the text)."""
    sec = Section(an, mm, model_text, hashes)
    text = sec.text(rel_import(out_dir, model_import_target))
    return write_section(out_dir, an["model"], text), text
