"""holon land: land a branch on the lead in one deterministic, resumable command (pipeline v2, part D).

  python -m holon land merge [--lead REF]           merge the lead into this branch, resolving what is mechanical
  python -m holon land regen [--milestone M]        regenerate the generated files over the merged tree
  python -m holon land commit [--trailer T ...]     commit the merge; the registry is re-derived inside it
  python -m holon land dirty [--milestone M]        the laws whose records no longer match the registry
  python -m holon land plan --tag T [--push]        a CI-only re-make of the dirty laws (one branch, holon-ci removed)
  python -m holon land apply --from REF             apply a re-make's published outputs to this tree
  python -m holon land bind [--milestone M]         bind only the laws whose binding is missing or stale
  python -m holon land check [--milestone M]        the fast checks (prereg audit, ranking, report)
  python -m holon land lead [--lead REF] --yes      land: a merge commit on the lead whose tree is this branch's
  python -m holon land all [--lead REF]             merge, regen, commit, dirty, check; stops where a person is needed

Every step can be run again after a restart: merge resumes an unfinished merge, regen is deterministic, and dirty,
plan, bind and check read the tree as it is. The state lives in the worktree's git directory (holon-land/state.json),
never in the tree.

Merge resolution. Only these are resolved; any other conflict stops the step with its list:
  append-only logs   the lead's lines, then the branch's new lines (STATEMENT_DIFF, amendments, binding changes)
  plan rows          a conflict hunk made of table rows only: the lead's rows, then the branch's new rows
  JSON documents     a three-way structural merge, the lead first (predictions, schemas and their adoption copies);
                     a value both sides changed differently stops the step
  generated files    the lead's version, regenerated by `regen` (registry, derivation, law files, reports, ranking,
                     metrics, status, evidence, diagrams, carrier documents)
  law outputs        a record or a law's generated files changed on both sides: the lead's version, and the law is
                     dirty (each side decided it on a tree the other side's change was not in)
Nothing here names a target.
"""
