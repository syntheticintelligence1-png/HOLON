class Stop(Exception):
    """A step that needs a person: the message says what."""


# ------------------------------------------------------------------------------------------------ git and state
def git(*args: str, check: bool = True, cwd: Path | None = None) -> str:
    r = subprocess.run(["git", *args], capture_output=True, text=True, cwd=cwd)
    if check and r.returncode != 0:
        raise Stop(f"git {' '.join(args)}: {(r.stderr or r.stdout).strip()[:400]}")
    return r.stdout.strip()


def landing_module(name: str, root: Path):
    """holon.<name> as the landing tree has it (root/holon/<name>.py), not as the tree this file was run from: a
    landing may run land.py from another worktree (before the merge brings land.py in), and the resolvers must use the
    merged tree's own code. For a module that imports only the standard library (holon.aggregate): a relative import
    inside it would bind to this file's package."""
    import importlib
    import importlib.util
    f = Path(root) / "holon" / f"{name}.py"
    here = Path(__file__).resolve().parent / f"{name}.py"
    if here.is_file() and here.read_bytes() == f.read_bytes():
        return importlib.import_module(f"{__package__}.{name}")
    spec = importlib.util.spec_from_file_location(f"holon_landing_{name}", f)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def outcome_paths(key: str, root: Path) -> list[str]:
    """The iteration key's outcome_paths, as the branch (HEAD) holds the key: its per-key source, else its milestone's
    aggregate. Each is a path or a path prefix (a directory, or a file-name prefix such as laws/M3/L_own_)."""
    for rel in [f"spec/{m}/predictions/{key}.json" for m in ("M2", "M3", "M4", "M5")] + \
               [f"spec/{m}/predictions.json" for m in ("M2", "M3", "M4", "M5")]:
        r = subprocess.run(["git", "show", f"HEAD:{rel}"], capture_output=True, text=True)
        if r.returncode != 0:
            continue
        v = json.loads(r.stdout)
        k = v if rel.endswith(f"/{key}.json") else (v.get("iterations") or {}).get(key)
        if isinstance(k, dict) and isinstance(k.get("outcome_paths"), list):
            return [str(x) for x in k["outcome_paths"]]
    raise Stop(f"no outcome_paths for key {key} on this branch")


def revert_outputs(base: str, head: str, lead: str, own: list[str]) -> list[str]:
    """Every output (OUTPUTS) the branch changed since the merge base, outside its outcome paths, set to the lead's
    version (removed when the lead has none). Returns those paths."""
    out = []
    for path in git("diff", "--name-only", "--no-renames", base, head).splitlines():
        if not path or not any(matches(p, path) for p in OUTPUTS) or any(path.startswith(o) for o in own):
            continue
        if subprocess.run(["git", "cat-file", "-e", f"{lead}:{path}"], capture_output=True).returncode == 0:
            git("checkout", lead, "--", path)
        else:
            git("rm", "-q", "-f", "--ignore-unmatch", "--", path)
        out.append(path)
    return out


def dropped(st: dict, root: Path) -> list[str]:
    """The branch's outputs that `merge --key` reverted (revert_outputs) and nothing brought back: each reverted path
    under gen/M*/ that no regen step writes (GENERATED) and no law owns (LAW_OUTPUTS), whose bytes in the worktree
    differ from the branch head's. Such a path holds the lead's version, or none, where the branch had its own; I94's
    cutover files and I95's binding record were lost this way. A re-make (apply) or a re-derivation that restores the
    branch's bytes clears it."""
    out, head = [], st.get("head")
    for path in st.get("reverted") or []:
        if not head or not matches("gen/M*/**", path) or any(matches(p, path) for p in GENERATED) \
                or any(rx.fullmatch(path) for rx in LAW_OUTPUTS):
            continue
        r = subprocess.run(["git", "cat-file", "blob", f"{head}:{path}"], capture_output=True)
        f = root / path
        if (f.read_bytes() if f.is_file() else None) != (r.stdout if r.returncode == 0 else None):
            out.append(path)
    return out


def record_status(text: str | None) -> str | None:
    """A record's status (PROVED, REFUTED, UNKNOWN), or None for a missing or unreadable one."""
    try:
        v = json.loads(text) if text else None
    except ValueError:
        return None
    return v.get("status") if isinstance(v, dict) else None


def blob(stage: int, path: str) -> str | None:
    r = subprocess.run(["git", "show", f":{stage}:{path}"], capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else None


def top() -> Path:
    return Path(git("rev-parse", "--show-toplevel"))


def state_file() -> Path:
    return Path(git("rev-parse", "--absolute-git-dir")) / "holon-land" / "state.json"


def load_state() -> dict:
    p = state_file()
    return json.loads(p.read_text()) if p.is_file() else {}


def save_state(st: dict) -> None:
    p = state_file()
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(st, indent=1, sort_keys=True) + "\n")


def merging() -> bool:
    return subprocess.run(["git", "rev-parse", "-q", "--verify", "MERGE_HEAD"], capture_output=True).returncode == 0


def holon(cmd: str, root: Path) -> tuple[int, str]:
    r = subprocess.run([sys.executable, "-m", "holon", *cmd.split()], capture_output=True, text=True, cwd=root)
    return r.returncode, (r.stdout or "") + (r.stderr or "")


def matches(pattern: str, path: str) -> bool:
    rx = re.escape(pattern).replace(r"\*\*", ".*").replace(r"\*", "[^/]*")
    return re.fullmatch(rx, path) is not None


def kind_of(path: str) -> tuple[str, str | None]:
    if AGGREGATE.fullmatch(path) and (top() / "holon" / "aggregate.py").is_file():
        return "aggregate", AGGREGATE.fullmatch(path).group(1)
    for rx in LAW_OUTPUTS:
        m = rx.fullmatch(path)
        if m:
            return "law", m.group(1)
    for kind, pats in (("log", LOGS), ("rows", ROWS), ("json", JSON3), ("generated", GENERATED)):
        if any(matches(p, path) for p in pats):
            return kind, None
    return "other", None


# ------------------------------------------------------------------------------------------------ the resolvers
def union_lines(base: str | None, ours: str, theirs: str) -> tuple[str, int]:
    """An append-only file: the lead's (theirs) lines, then the branch's (ours) lines that neither the lead nor the base
    holds, in the branch's order. Returns (text, number of the branch's lines appended)."""
    b = set((base or "").splitlines())
    t = theirs.splitlines()
    ts = set(t)
    add = [ln for ln in ours.splitlines() if ln not in ts and ln not in b]
    out = t + add
    return ("\n".join(out) + "\n") if out else "", len(add)


HUNK = re.compile(r"^<<<<<<< [^\n]*\n(.*?)(?:^\|\|\|\|\|\|\| [^\n]*\n.*?)?^=======\n(.*?)^>>>>>>> [^\n]*\n",
                  re.S | re.M)


def union_rows(text: str) -> str | None:
    """A file with conflict markers whose every hunk holds table rows (or blank lines) on both sides: each hunk becomes
    the lead's rows, then the branch's rows the lead lacks. None when a hunk holds anything else."""
    def rows(s: str) -> bool:
        return all(not ln.strip() or ln.lstrip().startswith("|") for ln in s.splitlines())
    bad = False

    def one(m: re.Match) -> str:
        nonlocal bad
        ours, theirs = m.group(1), m.group(2)
        if not (rows(ours) and rows(theirs)):
            bad = True
            return m.group(0)
        t = theirs.splitlines()
        return "".join(ln + "\n" for ln in t + [ln for ln in ours.splitlines() if ln not in set(t)])
    out = HUNK.sub(one, text)
    return None if bad or "<<<<<<< " in out else out


class Conflict(Exception):
    pass


def merge_json(b, o, t, where: str = "$"):
    """Three-way merge, the lead (t) first: object keys in the lead's order, then the branch's new keys; lists the
    lead's items, then the branch's new items; a string both sides extended from the base, the lead's then the branch's
    extension. Anything both sides changed differently raises Conflict."""
    if o == t:
        return o
    if o == b:
        return t
    if t == b:
        return o
    if isinstance(o, dict) and isinstance(t, dict):
        b = b if isinstance(b, dict) else {}
        out = {}
        for k in list(t) + [k for k in o if k not in t]:
            if k in o and k in t:
                out[k] = merge_json(b.get(k), o[k], t[k], f"{where}.{k}")
            elif k in t:
                if k in b:
                    raise Conflict(f"{where}.{k}: the branch removed it, the lead changed it")
                out[k] = t[k]
            else:
                if k in b:
                    raise Conflict(f"{where}.{k}: the lead removed it, the branch changed it")
                out[k] = o[k]
        return out
    if isinstance(o, list) and isinstance(t, list):
        b = b if isinstance(b, list) else []
        if any(x not in o for x in b) or any(x not in t for x in b):
            raise Conflict(f"{where}: a side removed a list item")
        return list(t) + [x for x in o if x not in t and x not in b]
    if isinstance(o, str) and isinstance(t, str) and isinstance(b, str) and o.startswith(b) and t.startswith(b):
        return t + o[len(b):]
    raise Conflict(f"{where}: both sides changed it differently")


def json_format(text: str):
    """(indent, ensure_ascii) that reproduce text byte for byte with json.dumps, else None."""
    v = json.loads(text)
    for ind in (2, 1, 4, None):
        for ea in (False, True):
            s = json.dumps(v, indent=ind, ensure_ascii=ea)
            if s + "\n" == text or s == text:
                return ind, ea, text.endswith("\n")
    return None


# ------------------------------------------------------------------------------------------------ steps
def step_merge(a) -> int:
    root = top()
    st = load_state()
    if not merging():
        if git("status", "--porcelain"):
            raise Stop("the worktree has uncommitted changes: commit or remove them first")
        git("fetch", "-q", "origin", a.lead.split("/", 1)[1] if a.lead.startswith("origin/") else a.lead, check=False)
        lead_sha = git("rev-parse", a.lead)
        if subprocess.run(["git", "merge-base", "--is-ancestor", lead_sha, "HEAD"]).returncode == 0:
            print(f"holon land: this branch already holds {a.lead} ({lead_sha[:8]}); nothing to merge")
            st.update(lead=a.lead, lead_sha=lead_sha, merged=True)
            save_state(st)
            return 0
        st = {"lead": a.lead, "lead_sha": lead_sha, "head": git("rev-parse", "HEAD"), "resolved": {}, "dirty_both": []}
        own = outcome_paths(a.key, root) if a.key else None
        base = git("merge-base", "HEAD", lead_sha)
        r = subprocess.run(["git", "merge", "--no-commit", "--no-ff", lead_sha], capture_output=True, text=True)
        if r.returncode not in (0, 1):
            raise Stop(f"git merge: {(r.stderr or r.stdout).strip()[:400]}")
        if own is not None:
            st["key"], st["own"] = a.key, own
            st["reverted"] = revert_outputs(base, st["head"], lead_sha, own)
            print(f"holon land: {len(st['reverted'])} outputs the branch changed outside {a.key}'s outcome paths take "
                  "the lead's version")
        save_state(st)
    left = []
    for path in [p for p in git("diff", "--name-only", "--diff-filter=U").splitlines() if p]:
        kind, lid = kind_of(path)
        try:
            how = resolve(path, kind, lid, root, st)
        except Conflict as e:
            how = None
            print(f"  {path}: {e}")
        if how is None:
            left.append(path)
        else:
            st["resolved"][path] = how
    for copy in sorted((root / "docs" / "adoption").glob("*/schemas/*.json")) if (root / "docs/adoption").is_dir() else []:
        src = root / "spec" / "schemas" / copy.name
        if src.is_file() and src.read_bytes() != copy.read_bytes():
            left.append(f"{copy.relative_to(root)} (differs from spec/schemas/{copy.name})")
    st["merged"] = not left
    save_state(st)
    for path, how in sorted(st["resolved"].items()):
        print(f"  resolved {path}: {how}")
    if left:
        print("holon land: resolve these by hand, `git add` them, then run `holon land merge` again:")
        for p in left:
            print(f"  {p}")
        return 2
    print(f"holon land: merge of {st['lead']} ({st['lead_sha'][:8]}) resolved; {len(st['dirty_both'])} laws decided on "
          "both sides are dirty")
    return 0


def resolve(path: str, kind: str, lid: str | None, root: Path, st: dict) -> str | None:
    base, ours, theirs = blob(1, path), blob(2, path), blob(3, path)
    if kind == "aggregate":
        # A's per-key sources: absorb what the branch's aggregate holds and no source does (a branch made before the
        # split keeps its own keys), then the lead's, then write the aggregate from the union of the sources; a key
        # whose value differs between an aggregate and its source stops here (a prereg key is never edited)
        # a milestone's two aggregates are resolved together: split reads both, and a conflicted one still holds git's
        # markers, so each side's pair is written whole (that side's committed versions) before its split
        m = lid
        if m in st.setdefault("aggregates_done", []):
            git("add", "-A", "--", f"spec/{m}")
            return "regenerated from the per-key sources with its milestone's other aggregate"
        AG = landing_module("aggregate", root)
        pair = [rel for rel in (f"spec/{m}/predictions.json", f"spec/{m}/amendments.jsonl") if AGGREGATE.fullmatch(rel)]
        for rev in ("HEAD", "MERGE_HEAD"):
            for rel in pair:
                r = subprocess.run(["git", "show", f"{rev}:{rel}"], capture_output=True, text=True)
                if r.returncode == 0:
                    (root / rel).write_text(r.stdout)
                elif (root / rel).exists():
                    (root / rel).unlink()
            AG.split(m, root)
        AG.write(m, root)
        git("add", "-A", "--", f"spec/{m}")
        st["aggregates_done"].append(m)
        return "regenerated from the per-key sources (the branch's and the lead's absorbed first)"
    if kind in ("generated", "law"):
        if theirs is None:
            git("rm", "-q", "-f", "--", path)
        else:
            git("checkout", "--theirs", "--", path)
            git("add", "--", path)
        if kind == "generated":
            return "the lead's version, regenerated by regen"
        # a record decided on both sides: the lead's stands when both reached the same status (the branch re-made it
        # under its own, older tree; `dirty` still re-makes it if the merged statement differs from the record's), and
        # the law is re-made on the merged tree when the sides disagree (the branch's change may be what decided it)
        so, sl = record_status(ours), record_status(theirs)
        if so == sl and so is not None:
            return f"the lead's version (both sides {so})"
        if lid not in st["dirty_both"]:
            st["dirty_both"].append(lid)
        return f"the lead's version; {lid} is dirty (the branch {so or 'deleted it'}, the lead {sl or 'deleted it'})"
    if ours is None or theirs is None:
        return None          # a side deleted it: not mechanical
    if kind == "log":
        text, n = union_lines(base, ours, theirs)
        if path.endswith(".jsonl"):
            for ln in text.splitlines():
                if ln.strip():
                    json.loads(ln)
        (root / path).write_text(text)
        git("add", "--", path)
        return f"the lead's lines, then the branch's {n} new lines"
    if kind == "rows":
        out = union_rows((root / path).read_text())
        if out is None:
            return None
        (root / path).write_text(out)
        git("add", "--", path)
        return "the lead's rows, then the branch's new rows"
    if kind == "json":
        fmt = json_format(theirs)
        if fmt is None:
            return None
        ind, ea, nl = fmt
        m = merge_json(json.loads(base) if base else None, json.loads(ours), json.loads(theirs))
        (root / path).write_text(json.dumps(m, indent=ind, ensure_ascii=ea) + ("\n" if nl else ""))
        git("add", "--", path)
        return "three-way structural merge, the lead first"
    return None


def step_regen(a) -> int:
    root = top()
    if (root / "holon" / "aggregate.py").is_file():    # A: the aggregates from their per-key sources first
        AG = landing_module("aggregate", root)
        for d in sorted((root / "spec").glob("M*/predictions")):
            AG.regenerate(d.parent.name, root)
    base = load_state().get("lead_sha") or "HEAD"
    moved = [p for p in git("diff", "--name-only", base, "--", f"results/{a.milestone}").splitlines()
             if re.fullmatch(rf"results/{a.milestone}/L_[^/]+\.json", p)]
    for cmd, need in REGEN:
        if need and not (root / need.format(m=a.milestone)).is_file():
            continue
        if cmd.startswith("metrics") and not moved:
            # metrics are computed from the records (and its timing file is wall-clock): only when records moved
            print(f"  holon {cmd.format(m=a.milestone)}: skipped (no record differs from {base[:8]})")
            continue
        c = cmd.format(m=a.milestone)
        rc, out = holon(c, root)
        if rc != 0:
            raise Stop(f"holon {c} failed (exit {rc}):\n{out[-1500:]}")
        print(f"  holon {c}: ok")
    git("add", "-A")
    print(f"holon land: regenerated; {len(git('diff', '--cached', '--name-only').splitlines())} paths staged")
    return 0


def step_migrate(a) -> int:
    """An iteration branch's laws born under hash scheme 1 land under the milestone's scheme 2 (PV2A): one
    hash_migration line each, built by statement_diff.hash_migration_entry from the branch's own law file (its old hash
    the branch's registry entry) and appended only when its check accepts it. A law the lead already carries, or one
    born under scheme 2, needs none. Run after regen (derive wrote the merged laws), on the landing's merge."""
    root, st = top(), load_state()
    head = st.get("head")
    if not head:
        raise Stop("no merge state: run `holon land merge` first")
    from importlib import import_module
    SD = import_module(f"{__package__}.statement_diff")
    m = a.milestone
    reg = json.loads((root / "laws" / m / "REGISTRY.json").read_text())["statements"]
    lines = [json.loads(x) for x in (root / SD.LOG).read_text().splitlines() if x.strip()]
    have = {(e.get("law_id"), e.get("new_hash")) for e in lines if e.get("kind") == "hash_migration"}
    r = subprocess.run(["git", "show", f"{head}:laws/{m}/REGISTRY.json"], capture_output=True, text=True)
    branch_reg = json.loads(r.stdout)["statements"] if r.returncode == 0 else {}
    lead_reg = {}
    r = subprocess.run(["git", "show", f"{st['lead_sha']}:laws/{m}/REGISTRY.json"], capture_output=True, text=True)
    if r.returncode == 0:
        lead_reg = json.loads(r.stdout)["statements"]
    n = bad = 0
    for lid, h in sorted(reg.items()):
        if lid in lead_reg or lid not in branch_reg or branch_reg[lid] == h or (lid, h) in have:
            continue
        law = json.loads((root / "laws" / m / f"{lid}.json").read_text())
        old = json.loads(git("show", f"{head}:laws/{m}/{lid}.json"))
        if law.get("hash_scheme", 1) != 2 or old.get("hash_scheme", 1) != 1:
            continue
        e = SD.hash_migration_entry(old, m, root, f"born on the {st.get('key') or 'branch'} branch under scheme 1 "
                                                   f"({old.get('rule_catalog_version')}); scheme 2 on landing")
        if e.get("new_hash") != h:
            print(f"  {lid}: its migration gives {e.get('new_hash')}, the registry {h}: not appended")
            bad += 1
            continue
        res = SD.append(e, root)
        print(f"  {lid}: {'appended' if res.get('ok') else 'REFUSED'}: {str(res.get('reason'))[:160]}")
        n += bool(res.get("ok"))
        bad += not res.get("ok")
    git("add", "--", SD.LOG.as_posix())
    print(f"holon land: {n} hash_migration line(s) appended for the branch's scheme-1 laws, {bad} not")
    return 1 if bad else 0


def step_commit(a) -> int:
    st = load_state()
    staged = git("diff", "--cached", "--name-only")
    if not merging() and not staged:
        print("holon land: nothing to commit")
        return 0
    if merging() and git("diff", "--name-only", "--diff-filter=U"):
        raise Stop("unresolved conflicts remain: run `holon land merge`")
    head = f"Merge {st.get('lead', 'the lead')} ({st.get('lead_sha', '')[:8]}) with holon land" if merging() else \
        "holon land: regenerated outputs"
    body = [f"- {p}: {how}" for p, how in sorted((st.get("resolved") or {}).items())]
    if st.get("dirty_both"):
        body.append(f"- laws decided on both sides, now dirty: {', '.join(sorted(st['dirty_both']))}")
    body.append("- regenerated over the merged tree: " + ", ".join(c.split()[0] for c, _n in REGEN))
    msg = head + "\n\n" + "\n".join(body) + "\n" + ("\n" + "\n".join(a.trailer) + "\n" if a.trailer else "")
    if merging():
        # the lead is the merge commit's FIRST parent, as on a pull request's merge ref: an append-only log merged
        # lead-first then extends every version on HEAD's first-parent chain, which is what G2 and `holon bind`
        # check (statement_diff.merged_lines), so they hold on this branch's head and not only on the lead's commit
        tree, lead_sha, own = git("write-tree"), git("rev-parse", "MERGE_HEAD"), git("rev-parse", "HEAD")
        r = subprocess.run(["git", "commit-tree", tree, "-p", lead_sha, "-p", own, "-F", "-"], input=msg, text=True,
                           capture_output=True)
        if r.returncode != 0:
            raise Stop(f"git commit-tree: {(r.stderr or r.stdout).strip()[:400]}")
        git("merge", "--quit")   # the index and the worktree stay; MERGE_HEAD goes
        git("update-ref", "-m", "holon land: merge commit, the lead first", "HEAD", r.stdout.strip(), own)
    else:
        r = subprocess.run(["git", "commit", "-q", "-F", "-"], input=msg, text=True, capture_output=True)
        if r.returncode != 0:
            raise Stop(f"git commit: {(r.stderr or r.stdout).strip()[:400]}")
    print(f"holon land: committed {git('rev-parse', '--short', 'HEAD')}")
    return 0


def dirty_laws(root: Path, m: str, st: dict) -> dict[str, str]:
    reg = json.loads((root / "laws" / m / "REGISTRY.json").read_text())["statements"]
    out = {}
    for lid, sh in sorted(reg.items()):
        p = root / "results" / m / f"{lid}.json"
        if not p.is_file():
            out[lid] = "new"
        elif json.loads(p.read_text()).get("statement_hash") != sh:
            out[lid] = "statement changed"
        elif lid in (st.get("dirty_both") or []):
            out[lid] = "decided on both sides"
        else:
            tp = root / "traces" / m / f"{lid}.json"
            if tp.is_file():     # B: a decision trace that no longer holds (an input changed)
                from . import trace
                why = trace.check(root, json.loads(tp.read_text()))
                if why:
                    out[lid] = f"inputs changed: {why}"
    return out


def step_dirty(a) -> int:
    root, st = top(), load_state()
    d = dirty_laws(root, a.milestone, st)
    st.setdefault("dirty", {})[a.milestone] = d
    save_state(st)
    by: dict[str, int] = {}
    for lid in d:
        by[lid.split("_")[1]] = by.get(lid.split("_")[1], 0) + 1
    print(f"holon land: {len(d)} dirty laws in {a.milestone}" + (f" ({', '.join(f'{k} {v}' for k, v in sorted(by.items()))})"
                                                                if d else ""))
    for lid, why in d.items():
        print(f"  {lid}: {why}")
    return 0


# I84's bundle sub-forms (holon.rules.bundle2.SUBFORMS, named here so that planning imports no rule module): their laws
# are decided over the claims modules `holon bundle2 laws` writes from a forge run, so one job regenerates those, decides
# the laws and replays their witnesses (the re-make template's cmd bundle2).
BUNDLE2_SUBFORMS = ("link_domain", "public_input", "self_controlled")
# I86's bundle-law sub-forms (holon.rules.bundle.RULE_SUBFORMS): decided by `holon run`, then their witnesses replayed
# on the real bundle (`holon bundle replay-laws`, a forge run), in one job (the re-make template's cmd bundle).
BUNDLE_SUBFORMS = ("payer", "conservation", "keyed_blocking", "keyed_external", "keyed_external_none", "push")
# I92's SYM member sub-forms (holon.rules.symb.SUBFORMS): decided by `holon run` (holon.symb.lawrun), one job, apart
# from I34's sharded SYM laws.
SYMB_SUBFORMS = ("member_tau", "member_sentinel", "sentinel_inv")
# I93's PAR Go sub-forms (holon.rules.gox.SUBFORMS): decided by `holon run` (holon.gox.lawrun) from the committed replays
# of `holon gox replay`, one job of their own (no lean step).
GOX_SUBFORMS = ("go_round_trip", "go_branch", "go_recompute")


def jobs_for(root: Path, m: str, laws: list[str], restamp: bool) -> list[dict]:
    """The re-make matrix: one job per slow law (typed SORT, FACT attribution, UNDO pair and residue), DISCH and SYM in
    shards, every other rule (and sub-form) in one job; PAR's run, lean, run; the M1/M2 and T32 re-stamps on request.

    An UNDO pair or residue law's kernel time ranges from 2 to about 100 minutes on CI (I68's re-makes), so one job
    holding several of them runs for their sum; one job per law runs for the slowest."""
    groups: dict[str, list[str]] = {}
    for lid in laws:
        law = json.loads((root / "laws" / m / f"{lid}.json").read_text())
        r, s = law["rule"], law.get("subform")
        if s in BUNDLE2_SUBFORMS:   # I84's bundle laws: their claims modules first, then the deciders, then the replay
            g = "bundle2"
        elif s in BUNDLE_SUBFORMS:  # I86's bundle laws: the deciders, then the replay
            g = "bundle"
        elif r == "SORT" and s in ("realize", "as_member", "reinterpret", "tag"):
            g = f"typed-{lid}"
        elif r == "FACT" and "_attr_" in lid:
            g = f"fact-attr-{lid}"
        elif r == "UNDO" and s in ("pair", "residue"):
            g = f"undo-{s}-{lid}"
        elif r == "PAR" and s in GOX_SUBFORMS:   # I93's Go laws: one job of their own
            g = "gox"
        elif r == "PAR":
            g = "pinit" if s == "init_chain" else "par"
        elif r == "SYM" and s in SYMB_SUBFORMS:   # I92's member laws: one job of their own
            g = "symb"
        elif r in ("DISCH", "SYM"):
            g = r.lower()
        else:
            g = r.lower() + (f"-{s}" if s and r in ("UNDO", "FACT") else "")
        groups.setdefault(g, []).append(lid)
    jobs, n = [], 0
    for g in sorted(groups):
        ls = sorted(groups[g])
        if g.startswith(("typed-", "fact-attr-", "undo-pair-", "undo-residue-")):
            name = f"{g.split('-L_')[0]}-{n}"
            n += 1
            shards = [(name, ls)]
        elif g in ("disch", "sym"):
            k = 5 if g == "disch" else 4
            parts = [ls[i::max(1, -(-len(ls) // k))] for i in range(max(1, -(-len(ls) // k)))]
            shards = [(f"{g}-{i}", p) for i, p in enumerate(parts) if p]
        else:
            shards = [(g, ls)]
        for name, part in shards:
            extra = "--law-timebox 540 --deadline @DEADLINE@" if g == "disch" else \
                ("--deadline @DEADLINE@" if g.startswith("fact-attr-") or g == "undo-cancel" else "")
            jobs.append({"name": name, "laws": ",".join(part), "extra": extra, "lean": "yes" if g == "par" else "",
                         "cmd": g if g in ("bundle2", "bundle") else ""})
    if restamp:
        jobs += [{"name": "m12", "laws": "", "extra": "", "lean": "", "cmd": "m12"},
                 {"name": "t32", "laws": "", "extra": "", "lean": "", "cmd": "t32"}]
    return jobs


def step_plan(a) -> int:
    root, st = top(), load_state()
    d = (st.get("dirty") or {}).get(a.milestone)
    if d is None:
        d = dirty_laws(root, a.milestone, st)
    if not d and not a.restamp and not a.derivation:
        print("holon land: no dirty law; nothing to re-make")
        return 0
    rules = {json.loads((root / "laws" / a.milestone / f"{lid}.json").read_text())["rule"] for lid in d}
    jobs = jobs_for(root, a.milestone, sorted(d), a.restamp)
    if a.derivation:   # I89's stage 2 (product, equivalence pair, the five decisions, splits) on a runner's pinned kernels
        jobs.append({"name": "derivation", "laws": "", "extra": "", "lean": "", "cmd": "derivation"})
    tpl = (root / ".github" / "ci" / "remake.template.yml").read_text()
    matrix = "".join(f"          - name: {j['name']}\n            laws: {j['laws']}\n            extra: '{j['extra']}'\n"
                     f"            lean: '{j['lean']}'\n            cmd: '{j['cmd']}'\n" for j in jobs)
    filt = []
    if (root / "holon" / "goreplay.py").is_file():   # every Go replay (I67's go-op, I90's count, I35's OWN laws)
        filt.append('python -u -m holon replay-go --milestone {m} 2>&1 | tee -a "$RUNNER_TEMP/run.log"')
    filt.append('python -u -m holon refute --milestone {m} --only filter 2>&1 | tee -a "$RUNNER_TEMP/run.log"')
    if "SYM" in rules and (root / "holon" / "sym.py").is_file():
        filt.append('python -u -m holon sym --milestone {m} --aggregate 2>&1 | tee -a "$RUNNER_TEMP/run.log"')
    y = (tpl.replace("@HEADER@", f"CI only ({a.tag}), not for merge: holon land plan's re-make of {len(d)} dirty "
                     f"{a.milestone} laws, then the final filter; the publish job pushes every job's files to "
                     f"claude/ci-{a.tag}-out-<run id>.")
         .replace("@TAG@", a.tag).replace("@MATRIX@", matrix).replace("@ORDER@", " ".join(j["name"] for j in jobs))
         .replace("@FILTER@", "\n          ".join(f.format(m=a.milestone) for f in filt)))
    tmp = state_file().parent / f"plan-{a.tag}"
    git("worktree", "add", "-q", "--detach", str(tmp), "HEAD")
    try:
        (tmp / ".github" / "workflows" / f"holon-{a.tag}.yml").write_text(y)
        if (tmp / ".github" / "workflows" / "holon-ci.yml").is_file():
            git("rm", "-q", ".github/workflows/holon-ci.yml", cwd=tmp)
        git("add", "-A", cwd=tmp)
        msg = (f"CI only (not for merge): {a.tag}, a re-make of {len(d)} dirty {a.milestone} laws in {len(jobs)} jobs "
               "(holon land plan)\n" + ("\n" + "\n".join(a.trailer) + "\n" if a.trailer else ""))
        subprocess.run(["git", "commit", "-q", "-F", "-"], input=msg, text=True, check=True, cwd=tmp)
        sha = git("rev-parse", "HEAD", cwd=tmp)
        if a.push:
            git("push", "-q", "origin", f"HEAD:refs/heads/claude/ci-{a.tag}", cwd=tmp)
            print(f"holon land: pushed claude/ci-{a.tag} ({sha[:8]}): {len(jobs)} jobs over {len(d)} laws; outputs "
                  f"arrive on claude/ci-{a.tag}-out-<run id>")
        else:
            print(f"holon land: planned {len(jobs)} jobs over {len(d)} laws at {sha[:8]} (not pushed; --push pushes it)")
    finally:
        git("worktree", "remove", "--force", str(tmp), check=False)
    return 0


def step_apply(a) -> int:
    root = top()
    ref = a.source
    git("fetch", "-q", "origin", ref.split("/", 1)[1] if ref.startswith("origin/") else ref, check=False)
    if subprocess.run(["git", "rev-parse", "-q", "--verify", f"{ref}^{{commit}}"], capture_output=True).returncode != 0:
        ref = f"origin/{ref}"   # the outputs branch as `plan` names it (claude/ci-<tag>-out-<run id>), fetched above
    tops = [x for x in git("ls-tree", "--name-only", ref).splitlines() if x.endswith("-out")]
    order = ["filter-out"] if "filter-out" in tops else sorted(tops)
    n = 0
    for job in order:
        r = subprocess.run(["git", "show", f"{ref}:{job}/changed.tgz"], capture_output=True)
        if r.returncode != 0:
            print(f"  {job}: no changed.tgz")
            continue
        with tarfile.open(fileobj=io.BytesIO(r.stdout)) as t:
            safe = [x for x in t.getmembers() if not x.name.startswith(("/", ".")) and ".." not in Path(x.name).parts]
            ms = [x for x in safe if x.isfile()]
            # A model's second name is a symbolic link to the file beside it (holon.sorts.model3.write_model_file:
            # <name>.bend -> its importable name), and records and traces name the link. A link member is applied
            # only when it names a sibling file, never a path that leaves its directory.
            ls = [x for x in safe if x.issym() and x.linkname not in ("", ".", "..") and "/" not in x.linkname]
            for x in ms:
                dest = root / x.name
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(t.extractfile(x).read())
            for x in ls:
                dest = root / x.name
                dest.parent.mkdir(parents=True, exist_ok=True)
                if dest.is_symlink() and os.readlink(dest) == x.linkname:
                    continue
                if dest.is_symlink() or dest.is_file():
                    dest.unlink()
                os.symlink(x.linkname, dest)
            n += len(ms) + len(ls)
            print(f"  {job}: {len(ms)} files" + (f", {len(ls)} links" if ls else ""))
    git("add", "-A")
    print(f"holon land: applied {n} files from {ref}")
    return 0


def step_bind(a) -> int:
    root = top()
    reg = json.loads((root / "laws" / a.milestone / "REGISTRY.json").read_text())["statements"]
    bp = root / "spec" / "bindings" / f"{a.milestone}.json"
    have = json.loads(bp.read_text()).get("laws", {}) if bp.is_file() else {}
    stale = sorted(lid for lid, sh in reg.items() if (have.get(lid) or {}).get("statement_hash") != sh)
    if not stale:
        print("holon land: every binding is current")
        return 0
    rc, out = holon(f"bind --milestone {a.milestone} --laws {','.join(stale)} --accept-change holon-land", root)
    print(out[-1500:])
    if rc != 0:
        raise Stop(f"holon bind refused ({len(stale)} laws); see above")
    git("add", "-A")
    return 0


def step_check(a) -> int:
    root = top()
    bad = 0
    for cmd, want, need in ((f"audit prereg --milestone {a.milestone}", "PREREG OK", None),
                            (f"rank --milestone {a.milestone} --check", "RANKING OK", "holon/rank.py"),
                            (f"report --milestone {a.milestone} --check", "REPORT OK", "holon/report.py")):
        if need and not (root / need).is_file():
            continue
        rc, out = holon(cmd, root)
        ok = rc == 0 and want in out
        bad += not ok
        print(f"  holon {cmd}: {'ok' if ok else 'FAILED'}")
        if not ok:
            print("    " + "\n    ".join(out.strip().splitlines()[-6:]))
    lost = dropped(load_state(), root)
    if lost:
        bad += 1
        print(f"  {len(lost)} outputs the branch changed were reverted by the merge (outside its key's outcome paths) "
              "and nothing re-derived them: run each one's generator, or name it in the key's outcome_paths:")
        for p in lost:
            print(f"    {p}")
    return 1 if bad else 0


def step_lead(a) -> int:
    if not a.yes:
        raise Stop("landing pushes the lead: confirm CI is green on this branch's head, then pass --yes")
    if merging() or git("status", "--porcelain"):
        raise Stop("the worktree is not clean")
    branch = a.lead.split("/", 1)[1] if a.lead.startswith("origin/") else a.lead
    git("fetch", "-q", "origin", branch)
    lead_sha = git("rev-parse", a.lead)
    if subprocess.run(["git", "merge-base", "--is-ancestor", lead_sha, "HEAD"]).returncode != 0:
        raise Stop(f"the lead moved to {lead_sha[:8]}: run `holon land merge` again")
    head = git("rev-parse", "HEAD")
    msg = (a.message or f"Merge {git('rev-parse', '--abbrev-ref', 'HEAD')} ({head[:8]}) with holon land") + "\n" + \
        ("\n" + "\n".join(a.trailer) + "\n" if a.trailer else "")
    r = subprocess.run(["git", "commit-tree", f"{head}^{{tree}}", "-p", lead_sha, "-p", head, "-F", "-"], input=msg,
                       text=True, capture_output=True)
    if r.returncode != 0:
        raise Stop(f"git commit-tree: {r.stderr.strip()[:300]}")
    sha = r.stdout.strip()
    git("push", "-q", "origin", f"{sha}:refs/heads/{branch}")
    print(f"holon land: landed: {branch} is now {sha[:8]} (merge of {head[:8]} onto {lead_sha[:8]})")
    return 0


def step_all(a) -> int:
    for f in (step_merge, step_regen, step_commit, step_dirty, step_check):
        rc = f(a)
        if rc:
            return rc
    return 0


def selftest() -> int:
    assert matches("gen/M*/diagram/**", "gen/M3/diagram/a/b.json") and not matches("laws/M*/*.json", "laws/M3/d/x.json")
    assert kind_of("results/M3/L_x_y.json") == ("law", "L_x_y") and kind_of("docs/STATUS.md")[0] == "generated"
    assert union_lines("a\n", "a\nb\nc\n", "a\nd\n") == ("a\nd\nb\nc\n", 2)
    t = "x\n<<<<<<< ours\n| I2 | b |\n=======\n| I1 | a |\n>>>>>>> lead\ny\n"
    assert union_rows(t) == "x\n| I1 | a |\n| I2 | b |\ny\n"
    assert union_rows("<<<<<<< o\nprose\n=======\n| r |\n>>>>>>> t\n") is None
    m = merge_json({"k": {"a": 1}, "s": "x"}, {"k": {"a": 1, "c": 3}, "s": "x."}, {"k": {"a": 1, "b": 2}, "s": "x!"})
    assert list(m["k"]) == ["a", "b", "c"]
    try:
        merge_json({"v": 1}, {"v": 2}, {"v": 3})
        raise AssertionError("no conflict raised")
    except Conflict:
        pass
    assert json_format(json.dumps({"a": [1]}, indent=1) + "\n") == (1, False, True)
    assert record_status('{"status": "REFUTED"}') == "REFUTED" and record_status(None) is None
    assert record_status("<<<<<<< not json") is None
    import tempfile
    cwd = os.getcwd()
    with tempfile.TemporaryDirectory(prefix="holon-land-selftest-") as t:
        try:   # the merge commit puts the lead first, so a log merged lead-first extends HEAD's first-parent chain
            os.chdir(t)
            for c in (("init", "-q", "-b", "lead"), ("config", "user.email", "selftest@holon"),
                      ("config", "user.name", "selftest"), ("config", "commit.gpgsign", "false")):
                git(*c)
            Path("log.jsonl").write_text("a\n")
            git("add", "-A")
            git("commit", "-q", "-m", "base")
            git("checkout", "-q", "-b", "br")
            Path("log.jsonl").write_text("a\nb\n")
            git("commit", "-q", "-am", "branch line")
            git("checkout", "-q", "lead")
            Path("log.jsonl").write_text("a\nc\n")
            git("commit", "-q", "-am", "lead line")
            lead, _ = git("rev-parse", "HEAD"), git("checkout", "-q", "br")
            own = git("rev-parse", "HEAD")
            subprocess.run(["git", "merge", "--no-commit", "--no-ff", lead], capture_output=True)
            Path("log.jsonl").write_text(union_lines("a\n", "a\nb\n", "a\nc\n")[0])
            git("add", "log.jsonl")
            save_state({"lead": "lead", "lead_sha": lead, "head": own, "resolved": {"log.jsonl": "union"},
                        "dirty_both": []})
            step_commit(argparse.Namespace(trailer=[]))
            assert (git("rev-parse", "HEAD^1"), git("rev-parse", "HEAD^2")) == (lead, own), "the lead is not first"
            assert git("rev-parse", "br") == git("rev-parse", "HEAD") and not merging() and not git("status", "--porcelain")
            assert git("show", "HEAD:log.jsonl").startswith(git("show", f"{lead}:log.jsonl"))
            # an output the merge reverted counts as dropped until its branch bytes are back (#110's binding record)
            Path("gen/M3/cutover").mkdir(parents=True)
            Path("gen/M3/cutover/m.bend").write_text("branch\n")
            git("add", "-A")
            git("commit", "-q", "-m", "a branch output")
            st = {"head": git("rev-parse", "HEAD"), "reverted": ["gen/M3/cutover/m.bend", "gen/M3/evidence.json",
                                                                 "gen/M3/laws/L_a/LAWS.bend", "results/M3/L_a.json"]}
            Path("gen/M3/cutover/m.bend").unlink()
            assert dropped(st, Path(t)) == ["gen/M3/cutover/m.bend"]
            Path("gen/M3/cutover/m.bend").write_text("lead\n")
            assert dropped(st, Path(t)) == ["gen/M3/cutover/m.bend"]
            Path("gen/M3/cutover/m.bend").write_text("branch\n")
            assert dropped(st, Path(t)) == [] and dropped({}, Path(t)) == []
        finally:
            os.chdir(cwd)
    print("holon land selftest: ok")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="holon land", description=__doc__.split("\n\n")[0])
    ap.add_argument("step", choices=("merge", "regen", "migrate", "commit", "dirty", "plan", "apply", "bind", "check", "lead",
                                     "all", "selftest"))
    ap.add_argument("--lead", default=LEAD)
    ap.add_argument("--key", help="merge: the branch's iteration key; its outputs outside the key's outcome_paths take "
                                  "the lead's version")
    ap.add_argument("--milestone", default="M3")
    ap.add_argument("--tag", help="plan: the re-make's name (workflow holon-<tag>, branch claude/ci-<tag>)")
    ap.add_argument("--push", action="store_true", help="plan: push the CI-only branch")
    ap.add_argument("--restamp", action="store_true", help="plan: add the M1/M2 and T32 re-stamp jobs")
    ap.add_argument("--derivation", action="store_true",
                    help="plan: add a job that re-decides I88's derivation law set with I89's Bend engine "
                         "(holon derivation bend-decide), when the landing moves a model its equivalence pair imports")
    ap.add_argument("--from", dest="source", help="apply: the outputs ref (claude/ci-<tag>-out-<run id>)")
    ap.add_argument("--message", help="lead: the landing commit's title")
    ap.add_argument("--trailer", action="append", default=[], help="a trailer line for the commits this makes")
    ap.add_argument("--yes", action="store_true", help="lead: CI is green on this branch's head")
    a = ap.parse_args(argv)
    if a.step == "selftest":
        return selftest()
    if a.step == "plan" and not a.tag:
        ap.error("plan needs --tag")
    if a.step == "apply" and not a.source:
        ap.error("apply needs --from")
    try:
        return {"merge": step_merge, "regen": step_regen, "migrate": step_migrate, "commit": step_commit,
                "dirty": step_dirty, "plan": step_plan,
                "apply": step_apply, "bind": step_bind, "check": step_check, "lead": step_lead,
                "all": step_all}[a.step](a)
    except Stop as e:
        print(f"holon land: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
