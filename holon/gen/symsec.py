"""The sym section of rule SYM over I30's typed model and I68's structural store (BUILD_PLAN I34; whitepaper §5.4,
§8.3, §8.4; the contract is rules J2, J3, J5 and J7 of the docstring of tests_m3/test_sym.py).

  gen/<M>/sym/models/<model>.bend   imports the typed model gen/<M>/sorts/models/<model>.bend as M and defines, from the
                                    document, the milestone's sort solution and holon.sym's analysis (never from names):

  sy_time_key(k)     the structural key k holds a Time word: a storage Time word of the assignment (storage:<family> or
                     storage:<family>.<member>) at its family's base slot, offset and member slot
  sy_tau_g(g, d)     τ_d on a state: d added to the word at every Time key the store holds (J2)
  sy_tau_x(x, d)     τ_d on an act: block.timestamp + d, every Time-typed argument + d, and the answer word of every
                     recorded call whose selector is a call the assignment types T_Time (call:<I>.<f>) + d
  sy_pi_g(g, a, b)   π_{a,b} on a state: the key word of every address-keyed family swapped (a ↔ b), and every
                     address-typed register (a packed field in place) swapped
  sy_pi_x(x, a, b)   π_{a,b} on an act: its address-typed arguments, the caller, the contract's own address, the keys of
                     the account-code table, and every recorded call's receiver and address-typed calldata arguments
                     (located by the call's selector and its argument's head slot) swapped
  sy_mem_<role>      a role's members in a state (J1): the addresses its predicate admits and the values its registers
                     hold; a register family keyed by a mapping has registers no step wrote, which hold address(0)
  sy_ok_<n>          per law: the claim (J3), its premises as the antecedent of an implication; a Bool
  sy_hit_<n>         per law: its premises alone (G11V's non-vacuity target)

The comparison of two runs (tau, pi): their observations (success, the return data or revert data, the logs; UNDO's
UOb) and their states (every key either store holds reads the same word; the ghost components equal), the generator
applied to the first run's (π also maps the logs' address-typed words by the events' signatures and an address-typed
return word). omega compares the two orders' stores on the sink-reaching keys (holon.sym's sinks: the families a
guard of another action or a view's return reads; a packed scalar on its sink fields alone). sentinel compares the
word the site's write term gives, in the action's context, with the register's constant.

What the generators leave out (disclosed in each record, and the replay on the real contract compares both runs):
  - a key the store does not hold is not translated (the store is a finite map; on the real contract an unwritten
    slot is zero in both runs as well). J3's "a key absent from the store reading d" is not representable here, and
    neither is π on the address(0) every unwritten address register holds: the I34 report states both (a Surprise and
    a Question for the human), and each record's sym.notes;
  - a recorded call's answer is mapped by π in its arguments only (the facts record no answer types), and a call
    whose argument types the facts do not determine is not mapped (named in the section's header).

combined(): the same definitions unqualified, after the typed model's text, as one module the JavaScript evaluator
runs (holon.sorts.evaluate3). Nothing here names a target.
"""
