def env_field(name: str) -> str:
    return "e_" + re.sub(r"[^A-Za-z0-9_]", "_", name)


def record_fields(model_text: str, tname: str) -> list[str]:
    """The field names of the single-constructor record type tname of the model."""
    m = re.search(rf"(?m)^type {re.escape(tname)} is Data:\n  {re.escape(tname)}\{{([^\n]*)\}}\n", model_text)
    if not m:
        raise GenError(f"the typed model has no record type {tname}")
    parts, depth, cur = [], 0, ""
    for ch in m.group(1):
        depth += (ch == "<") - (ch == ">")
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += ch
    parts.append(cur)
    return [f.split(":")[0].strip() for f in parts if f.strip()]


class Types:
    """Solidity types of document terms, as far as the facts determine them (None where they do not)."""

    def __init__(self, doc: dict):
        self.doc = doc
        self.st = {f["name"]: f for f in storage_families(doc)}

    def param(self, action: dict, name: str):
        for p in action.get("params") or []:
            if p.get("name") == name:
                return p
        return None

    def struct_field(self, fields: list, name: str):
        for f in fields or []:
            if f.get("name") == name:
                return f.get("type")
        return None

    def of(self, action: dict, t):
        if isinstance(t, bool):
            return "bool"
        if isinstance(t, int):
            return "uint256"
        if not isinstance(t, list) or not t:
            return None
        h = t[0]
        if h == "caller" or (h == "env" and len(t) > 1 and t[1] in ADDR_ENV) or h == "this":
            return "address"
        if h == "env":
            return "uint256"
        if h == "param" and len(t) == 2:
            p = self.param(action, t[1])
            return p.get("type") if p else None
        if h == "storage" and len(t) == 2:
            f = self.st.get(t[1]) or {}
            return f.get("value") if f.get("kind") == "scalar" else None
        if h == "map" and len(t) >= 3 and isinstance(t[1], list) and t[1][:1] == ["storage"]:
            f = self.st.get(t[1][1]) or {}
            v = f.get("value")
            return v if isinstance(v, str) and not v.startswith("struct") else None
        if h == "member" and len(t) == 3:
            base = t[1]
            if isinstance(base, list) and base[:1] == ["map"] and isinstance(base[1], list) and base[1][:1] == ["storage"]:
                return self.struct_field((self.st.get(base[1][1]) or {}).get("fields"), t[2])
            if isinstance(base, list) and base[:1] == ["param"]:
                p = self.param(action, base[1]) or {}
                return self.struct_field(p.get("fields"), t[2])
            return None
        if h == "keccak256":
            return "bytes32"
        if h == "str":
            return "bytes"
        if h in ARITH:
            return "uint256"
        if h in CMPS:
            return "bool"
        return None


class SymSection(Trace):
    """The sym section of one document's typed model: its generators and the claims of its SYM laws."""

    def __init__(self, mm, model_text: str, doc: dict, hashes: list, elements: list, assignment: dict):
        super().__init__(mm, model_text, doc, hashes, [])
        self.syms = elements
        self.assignment = assignment
        self.types = Types(doc)
        self.fams = {f["name"]: f for f in storage_families(doc)}
        self.tw = S.time_words(assignment, doc)
        self.env_fields = record_fields(model_text, "HEnv")
        self.notes: list[str] = []
        self._fields: dict = {}

    # ---------------------------------------------------------- literals and small helpers
    def lit(self, n: int) -> str:
        return self.code(wlit(int(n)))

    def W(self) -> str:
        return self.Q("W")

    def disj(self, terms: list[str]) -> str:
        if not terms:
            return "False{}"
        out = terms[-1]
        for t in reversed(terms[:-1]):
            out = f"Bool.or({t}, {out})"
        return out

    def conj(self, terms: list[str]) -> str:
        if not terms:
            return "True{}"
        out = terms[-1]
        for t in reversed(terms[:-1]):
            out = f"Bool.and({t}, {out})"
        return out

    # ---------------------------------------------------------- locations of the document's storage
    def family(self, f: str):  # noqa: D401 - the document's family (not the compiled model's)
        fam = self.fams.get(f)
        if fam is None:
            raise GenError(f"{f}: not a storage family of the document")
        return fam

    def locations(self, path: str) -> list[tuple]:
        """[(base, offset, depth, member slot, bit offset, width)] of a register path <family>[.<member>]: a scalar
        (depth 0: the key SK{slot, member slot, []}) or a one-level mapping's value or value member (depth 1: SK{base,
        0, [SP_m{_, member slot}]})."""
        fname, _, mem = path.partition(".")
        f = self.family(fname)
        kind = f.get("kind")
        if mem:
            m = next((x for x in f.get("fields") or [] if x.get("name") == mem), None)
            if m is None:
                raise GenError(f"{path}: no member {mem}")
            off, width, mslot = int(m.get("offset") or 0), m.get("width") or 256, int(m.get("slot") or 0)
        else:
            off, width, mslot = int(f.get("offset") or 0), f.get("width") or 256, 0
        if kind == "scalar":
            return [(int(f["slot"]), mslot, 0, 0, 8 * off, int(width))]
        if kind == "mapping":
            v = f.get("value")
            if isinstance(v, str) and v.startswith("mapping"):
                raise GenError(f"{path}: a nested mapping (only one-level mapping registers are located here)")
            return [(int(f["slot"]), 0, 1, mslot, 8 * off, int(width))]
        raise GenError(f"{path}: a {kind} family is not located here")

    def key_test(self, loc: tuple, k: str = "k") -> str:
        """A Bool over the key variable k (an SK): k is at the location (any mapping key)."""
        base, o, depth, mslot, _off, _w = loc
        return f"sy_at_{depth}({k}, {self.lit(base)}, {self.lit(o)}, {self.lit(mslot)})"

    def address_locations(self) -> list[tuple]:
        """Every address-typed register of the document: (path, location)."""
        out = []
        for name, f in sorted(self.fams.items()):
            if f.get("kind") == "scalar" and f.get("value") == "address":
                out.append((name, self.locations(name)[0]))
            for m in f.get("fields") or []:
                if m.get("type") == "address" and f.get("kind") in ("scalar", "mapping"):
                    out.append((f"{name}.{m['name']}", self.locations(f"{name}.{m['name']}")[0]))
            if f.get("kind") == "mapping" and f.get("value") == "address":
                out.append((name, self.locations(name)[0]))
        return out

    def address_keyed(self) -> list[int]:
        return sorted(int(f["slot"]) for f in self.fams.values()
                      if f.get("kind") == "mapping" and f.get("key") == "address")

    def time_locations(self) -> list[tuple]:
        return [(w, self.locations(w[len("storage:"):])[0]) for w in self.tw if w.startswith("storage:")]

    # ---------------------------------------------------------- calls
    def call_sigs(self) -> list[dict]:
        """Every external call the document's actions make: {fn, selector (4 ints), types, address_args,
        time_answer}; a call whose argument types the facts do not determine has selector None."""
        if getattr(self, "_calls", None) is not None:
            return self._calls
        seen: dict = {}
        time_calls = {w[len("call:"):] for w in self.tw if w.startswith("call:")}
        for a in self.doc.get("actions") or []:
            for c in a.get("calls") or []:
                fn = c.get("fn")
                if not fn or fn.startswith("address.") or fn in seen:
                    continue
                types = [self.types.of(a, t) for t in c.get("args") or []]
                short = fn.split(".")[-1]
                sel = None
                if all(t is not None for t in types):
                    sig = f"{short}({','.join(types)})"
                    sel = list(keccak256(sig.encode())[:4])
                    if f"[{', '.join(str(x) for x in sel)}]" not in self.text:
                        self.notes.append(f"call {sig}: its selector is not in the typed model (not mapped)")
                        sel = None
                else:
                    self.notes.append(f"call {fn}: argument types not determined by the facts (not mapped by π)")
                seen[fn] = {"fn": fn, "selector": sel, "types": types,
                            "address_args": [i for i, t in enumerate(types) if t == "address"],
                            "time_answer": fn in time_calls}
        self._calls = [seen[k] for k in sorted(seen)]
        return self._calls

    def sel_test(self, sel: list, cd: str = "cd") -> str:
        return f"{self.Q('b_eq')}(List.take(&2, U32, {cd}, 4n), [{', '.join(str(x) for x in sel)}])"

    # ---------------------------------------------------------- packed fields
    def field(self, off: int, width: int) -> tuple[str, str]:
        """(getter, setter) names of the field of width bits at bit offset off: limb permutations and masks when the
        offset is a multiple of 32 (the kernels evaluate them in a few steps), the word's division otherwise."""
        key = (int(off), int(width))
        if key in self._fields:
            return self._fields[key]
        W = self.W()
        g, st = f"sy_get_{off}_{width}", f"sy_put_{off}_{width}"
        mask = (1 << width) - 1
        if off % 32 == 0:
            k = off // 32
            for name, fn in ((f"sy_shr{k}", lambda a: a[k:] + ["0"] * k), (f"sy_shl{k}", lambda a: ["0"] * k + a[:8 - k])):
                if name not in self.mine:
                    limbs = [f"a{i}" for i in range(8)]
                    self.add(f"def {name}(w: {W}) -> {W}:\n  match w:\n    case {W}{{{', '.join(limbs)}}}:\n"
                             f"      {W}{{{', '.join(fn(limbs))}}}")
            hole = ((1 << 256) - 1) ^ (mask << off)
            self.add(f"def {g}(+w: {W}) -> {W}:\n  {self.Q('w_and')}(sy_shr{k}(w), {self.lit(mask)})")
            self.add(f"def {st}(+w: {W}, +f: {W}) -> {W}:\n  {self.Q('w_or')}({self.Q('w_and')}(w, {self.lit(hole)}), "
                     f"sy_shl{k}({self.Q('w_and')}(f, {self.lit(mask)})))")
        else:
            p, q = self.lit(1 << off), self.lit(1 << width)
            self.add(f"def {g}(+w: {W}) -> {W}:\n  {self.Q('w_mod')}({self.Q('w_div')}(w, {p}), {q})")
            self.add(f"def {st}(+w: {W}, +f: {W}) -> {W}:\n  {self.Q('w_add')}({self.Q('w_sub')}(w, "
                     f"{self.Q('w_mul')}({g}(w), {p})), {self.Q('w_mul')}({self.Q('w_mod')}(f, {q}), {p}))")
        self._fields[key] = (g, st)
        return g, st

    # ---------------------------------------------------------- the fixed part of the sym section
    def sym_fixed(self) -> None:
        W, SK, SP, KV, HSt, GSt = (self.Q(n) for n in ("W", "SK", "SP", "KV", "HSt", "GSt"))
        weq, ite = self.Q("w_eq"), self.Q("ite")
        self.add(f"def sy_pw(+w: {W}, +a: {W}, +b: {W}) -> {W}:\n"
                 f"  {ite}({W}, {weq}(w, a), b, {ite}({W}, {weq}(w, b), a, w))")
        # key shapes: depth 0 (a scalar's literal key), depth 1 (a one-level mapping's register, any key word)
        self.add(f"def sy_p0(p: List<&2, {SP}>) -> Bool:\n  match p:\n    case Nil{{}}:\n      True{{}}\n"
                 "    case Con{h, t}:\n      False{}")
        self.add(f"def sy_p1h(h: {SP}, t: List<&2, {SP}>, +j: {W}) -> Bool:\n  match h:\n"
                 f"    case {self.Q('SP_m')}{{k, o}}:\n      Bool.and(sy_p0(t), {weq}(o, j))")
        self.add(f"def sy_p1(p: List<&2, {SP}>, +j: {W}) -> Bool:\n  match p:\n    case Nil{{}}:\n      False{{}}\n"
                 "    case Con{h, t}:\n      sy_p1h(h, t, j)")
        self.add(f"def sy_at_0(k: {SK}, +b: {W}, +o: {W}, +j: {W}) -> Bool:\n  match k:\n"
                 f"    case {SK}{{kb, ko, kp}}:\n      Bool.and({weq}(kb, b), Bool.and({weq}(ko, o), sy_p0(kp)))")
        self.add(f"def sy_at_1(k: {SK}, +b: {W}, +o: {W}, +j: {W}) -> Bool:\n  match k:\n"
                 f"    case {SK}{{kb, ko, kp}}:\n      Bool.and({weq}(kb, b), Bool.and({weq}(ko, o), sy_p1(kp, j)))")
        # the semantic equality of two stores: every key either holds reads the same word in both
        self.add(f"def sy_sub1(h: {KV}, +xs: List<&2, {KV}>, +ys: List<&2, {KV}>) -> Bool:\n  match h:\n"
                 f"    case {KV}{{+k, v}}:\n      {weq}({self.Q('kv_get')}(xs, k), {self.Q('kv_get')}(ys, k))")
        self.add(f"def sy_sub(zs: List<&2, {KV}>, +xs: List<&2, {KV}>, +ys: List<&2, {KV}>) -> Bool:\n  match zs:\n"
                 "    case Nil{}:\n      True{}\n    case Con{h, t}:\n      Bool.and(sy_sub1(h, xs, ys), sy_sub(t, xs, ys))")
        self.add(f"def sy_sl_eq(+xs: List<&2, {KV}>, +ys: List<&2, {KV}>) -> Bool:\n"
                 "  Bool.and(sy_sub(xs, xs, ys), sy_sub(ys, xs, ys))")
        GKT = self.Q("GKT")
        self.add(f"def sy_gkt_eq(a: {GKT}, b: {GKT}) -> Bool:\n  match a b:\n"
                 f"    case {GKT}{{ak, at}} {GKT}{{bk, bt}}:\n      Bool.and({weq}(ak, bk), {self.Q('tg_eq')}(at, bt))")
        self.add(f"def sy_gkts_eq(a: List<&2, {GKT}>, b: List<&2, {GKT}>) -> Bool:\n  match a b:\n"
                 "    case Nil{} Nil{}:\n      True{}\n    case Nil{} Con{y, ys}:\n      False{}\n"
                 "    case Con{x, xs} Nil{}:\n      False{}\n    case Con{x, xs} Con{y, ys}:\n"
                 "      Bool.and(sy_gkt_eq(x, y), sy_gkts_eq(xs, ys))")
        self.ghost_eq()
        self.add(f"def sy_uos_eq(u: UOS, v: UOS) -> Bool:\n  match u v:\n    case UOS{{o1, g1, c1}} UOS{{o2, g2, c2}}:\n"
                 "      Bool.and(ux_ob_eq(o1, o2), sy_g_eq(g1, g2))")
        self.add("# a run the model cannot observe: an unanswered external call or the loop fuel\n"
                 f"def sy_limit(+c: U32) -> Bool:\n  Bool.or(U32.is_eq(c, {LIMIT_CODES[0]}), U32.is_eq(c, {LIMIT_CODES[1]}))")
        self.add(f"def sy_code(u: UOS) -> U32:\n  ux_uos_c(u)")
        self.add(f"def sy_post(u: UOS) -> {GSt}:\n  ux_uos_g(u)")
        self.add(f"def sy_st_of(+g: {GSt}) -> {HSt}:\n  {self.Q('gh_get_st')}(g)")

    def ghost_eq(self) -> None:
        """The equality of two states: their stores semantically, every ghost component structurally."""
        GSt = self.Q("GSt")
        fields = record_fields(self.text, "GSt")
        if not fields or fields[0] != "st":
            raise GenError("the typed model's GSt does not start with its store st")
        f1 = ", ".join(f"{f}1" for f in fields)
        f2 = ", ".join(f"{f}2" for f in fields)
        parts = [f"sy_sl_eq(sy_sl(st1), sy_sl(st2))"]
        for f in fields[1:]:
            m = re.search(rf"(?m)^type GSt is Data:\n  GSt\{{[^\n]*\b{re.escape(f)}: List<&2, GKT>", self.text)
            if not m:
                raise GenError(f"the ghost component {f} is not a list of GKT (no equality is generated for it)")
            parts.append(f"sy_gkts_eq({f}1, {f}2)")
        self.add(f"def sy_sl(s: {self.Q('HSt')}) -> List<&2, {self.Q('KV')}>:\n  match s:\n"
                 f"    case {self.Q('HSt')}{{sl}}:\n      sl")
        self.add(f"def sy_g_eq(a: {GSt}, b: {GSt}) -> Bool:\n  match a b:\n"
                 f"    case {GSt}{{{f1}}} {GSt}{{{f2}}}:\n      {self.conj(parts)}")

    # ---------------------------------------------------------- tau
    def tau_defs(self) -> None:
        W, KV, HSt, GSt, HAct, HEnv, HCall = (self.Q(n) for n in ("W", "KV", "HSt", "GSt", "HAct", "HEnv", "HCall"))
        locs = self.time_locations()
        tests = [self.key_test(loc) for _w, loc in locs]
        for _w, loc in locs:
            if loc[4] != 0 or loc[5] != 256:
                raise GenError(f"{_w}: a packed Time word (τ adds d to whole words only)")
        self.add(f"# the Time words of the store: {', '.join(w for w, _l in locs) or 'none'}\n"
                 f"def sy_time_key(+k: {self.Q('SK')}) -> Bool:\n  {self.disj(tests)}")
        two64 = self.lit(1 << 64)
        self.add(f"def sy_fit(+v: {W}, +d: {W}) -> Bool:\n  Bool.and({self.Q('w_lt')}(v, {two64}), Bool.and("
                 f"{self.Q('w_lt')}(d, {two64}), {self.Q('w_lt')}({self.Q('w_add')}(v, d), {two64})))")
        self.add(f"def sy_tau_v(c: Bool, +v: {W}, +d: {W}) -> {W}:\n  match c:\n    case True{{}}:\n"
                 f"      {self.Q('w_add')}(v, d)\n    case False{{}}:\n      v")
        self.add(f"def sy_tau_kv(h: {KV}, +d: {W}) -> {KV}:\n  match h:\n    case {KV}{{+k, v}}:\n"
                 f"      {KV}{{k, sy_tau_v(sy_time_key(k), v, d)}}")
        self.add(f"def sy_tau_kvs(xs: List<&2, {KV}>, +d: {W}) -> List<&2, {KV}>:\n  match xs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_tau_kv(h, d), sy_tau_kvs(t, d)}")
        self.add(f"def sy_tau_st(s: {HSt}, +d: {W}) -> {HSt}:\n  match s:\n    case {HSt}{{sl}}:\n"
                 f"      {HSt}{{sy_tau_kvs(sl, d)}}")
        self.add(f"# τ_d on a state (J2)\ndef sy_tau_g(+g: {GSt}, +d: {W}) -> {GSt}:\n"
                 f"  {self.Q('gh_set_st')}(g, sy_tau_st({self.Q('gh_get_st')}(g), d))")
        self.add(f"def sy_fits_kv(h: {KV}, +d: {W}) -> Bool:\n  match h:\n    case {KV}{{+k, +v}}:\n"
                 "      ux_imp(sy_time_key(k), sy_fit(v, d))")
        self.add(f"def sy_fits_kvs(xs: List<&2, {KV}>, +d: {W}) -> Bool:\n  match xs:\n"
                 "    case Nil{}:\n      True{}\n    case Con{h, t}:\n      Bool.and(sy_fits_kv(h, d), sy_fits_kvs(t, d))")
        self.add(f"def sy_fits_g(+g: {GSt}, +d: {W}) -> Bool:\n  sy_fits_kvs(sy_sl({self.Q('gh_get_st')}(g)), d)")
        # the act: block.timestamp, the Time-answer calls, the Time-typed arguments
        tsel = [c["selector"] for c in self.call_sigs() if c["time_answer"] and c["selector"]]
        missing = [c["fn"] for c in self.call_sigs() if c["time_answer"] and not c["selector"]]
        if missing:
            raise GenError(f"a Time-answer call whose selector is not determined: {missing}")
        self.add(f"def sy_tsel(+cd: List<&2, U32>) -> Bool:\n  {self.disj([self.sel_test(s) for s in tsel])}")
        self.add(f"def sy_tau_call(h: {HCall}, +d: {W}) -> {HCall}:\n  match h:\n"
                 f"    case {HCall}{{to, +cd, ok, +ret}}:\n      {HCall}{{to, cd, ok, {self.Q('ite')}(List<&2, U32>, "
                 f"sy_tsel(cd), {self.Q('b_of_w')}({self.Q('w_add')}({self.Q('w_of_b32')}(ret), d)), ret)}}")
        self.add(f"def sy_tau_calls(xs: List<&2, {HCall}>, +d: {W}) -> List<&2, {HCall}>:\n  match xs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_tau_call(h, d), sy_tau_calls(t, d)}")
        self.add(f"def sy_fits_call(h: {HCall}, +d: {W}) -> Bool:\n  match h:\n"
                 f"    case {HCall}{{to, +cd, ok, +ret}}:\n      ux_imp(sy_tsel(cd), sy_fit({self.Q('w_of_b32')}(ret), d))")
        self.add(f"def sy_fits_calls(xs: List<&2, {HCall}>, +d: {W}) -> Bool:\n  match xs:\n"
                 "    case Nil{}:\n      True{}\n    case Con{h, t}:\n      Bool.and(sy_fits_call(h, d), sy_fits_calls(t, d))")
        fs = self.env_fields
        if "env:block.timestamp" in self.tw and "e_block_timestamp" not in fs:
            raise GenError("block.timestamp is a Time word but the model's environment has no e_block_timestamp")
        new, fits = [], []
        for f in fs:
            if f == "e_block_timestamp" and "env:block.timestamp" in self.tw:
                new.append(f"{self.Q('w_add')}({f}, d)")
                fits.append(f"sy_fit({f}, d)")
            elif f == "e_calls":
                new.append("sy_tau_calls(e_calls, d)")
                fits.append("sy_fits_calls(e_calls, d)")
            else:
                new.append(f)
        pat = ", ".join(("+" + f) if f in ("e_block_timestamp", "e_calls") else f for f in fs)
        self.add(f"def sy_tau_en(en: {HEnv}, +d: {W}) -> {HEnv}:\n  match en:\n    case {HEnv}{{{pat}}}:\n"
                 f"      {HEnv}{{{', '.join(new)}}}")
        self.add(f"def sy_fits_en(en: {HEnv}, +d: {W}) -> Bool:\n  match en:\n    case {HEnv}{{{pat}}}:\n"
                 f"      {self.conj(fits)}")
        targs = {w[len("param:"):] for w in self.tw if w.startswith("param:")}
        cases_x, cases_f = [], []
        for a in self.actions:
            A = self.Q(f"A_{a}")
            tp = sorted(p.split(".", 1)[1] for p in targs if p.split(".", 1)[0] == a)
            if tp:
                arf = record_fields(self.text, f"AR_{a}")
                AR = self.Q(f"AR_{a}")
                apat = ", ".join(("+" + f) if f in tp else f for f in arf)
                self.add(f"def sy_tau_ar_{a}(ar: {AR}, +d: {W}) -> {AR}:\n  match ar:\n    case {AR}{{{apat}}}:\n"
                         f"      {AR}{{{', '.join((self.Q('w_add') + f'({f}, d)') if f in tp else f for f in arf)}}}")
                self.add(f"def sy_fits_ar_{a}(ar: {AR}, +d: {W}) -> Bool:\n  match ar:\n    case {AR}{{{apat}}}:\n"
                         f"      {self.conj([f'sy_fit({f}, d)' for f in tp])}")
                cases_x.append(f"    case {A}{{ar, en}}:\n      {A}{{sy_tau_ar_{a}(ar, d), sy_tau_en(en, d)}}")
                cases_f.append(f"    case {A}{{ar, en}}:\n      Bool.and(sy_fits_ar_{a}(ar, d), sy_fits_en(en, d))")
            else:
                cases_x.append(f"    case {A}{{ar, en}}:\n      {A}{{ar, sy_tau_en(en, d)}}")
                cases_f.append(f"    case {A}{{ar, en}}:\n      sy_fits_en(en, d)")
        self.add(f"# τ_d on an act (J2)\ndef sy_tau_x(x: {HAct}, +d: {W}) -> {HAct}:\n  match x:\n" + "\n".join(cases_x))
        self.add(f"def sy_fits_x(x: {HAct}, +d: {W}) -> Bool:\n  match x:\n" + "\n".join(cases_f))
        self.add(f"def sy_tau_uos(u: UOS, +d: {W}) -> UOS:\n  match u:\n    case UOS{{o, g, c}}:\n"
                 "      UOS{o, sy_tau_g(g, d), c}")

    # ---------------------------------------------------------- pi
    def pi_defs(self) -> None:
        W, SK, SP, KV, HSt, GSt, HAct, HEnv, HCall, HLog = (self.Q(n) for n in (
            "W", "SK", "SP", "KV", "HSt", "GSt", "HAct", "HEnv", "HCall", "HLog"))
        ite, weq = self.Q("ite"), self.Q("w_eq")
        akeys = self.address_keyed()
        self.add(f"# the address-keyed families' base slots: {akeys}\ndef sy_akey(+b: {W}) -> Bool:\n"
                 f"  {self.disj([f'{weq}(b, {self.lit(s)})' for s in akeys])}")
        self.add(f"def sy_pi_kw(c: Bool, +k: {W}, +a: {W}, +b: {W}) -> {W}:\n  match c:\n    case True{{}}:\n"
                 "      sy_pw(k, a, b)\n    case False{}:\n      k")
        self.add(f"def sy_pi_sp(+b0: {W}, h: {SP}, +a: {W}, +b: {W}) -> {SP}:\n  match h:\n"
                 f"    case {self.Q('SP_m')}{{k, o}}:\n      {self.Q('SP_m')}{{sy_pi_kw(sy_akey(b0), k, a, b), o}}")
        self.add(f"def sy_pi_p(+b0: {W}, p: List<&2, {SP}>, +a: {W}, +b: {W}) -> List<&2, {SP}>:\n  match p:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_pi_sp(b0, h, a, b), t}")
        self.add(f"def sy_pi_k(k: {SK}, +a: {W}, +b: {W}) -> {SK}:\n  match k:\n    case {SK}{{+kb, ko, kp}}:\n"
                 f"      {SK}{{kb, ko, sy_pi_p(kb, kp, a, b)}}")
        locs = self.address_locations()
        chain = "v"
        for i, (path, loc) in enumerate(locs):
            g, st = self.field(loc[4], loc[5])
            self.add(f"def sy_pi_v_{i}_m(c: Bool, +v: {W}, +a: {W}, +b: {W}) -> {W}:\n  match c:\n"
                     f"    case True{{}}:\n      {st}(v, sy_pw({g}(v), a, b))\n    case False{{}}:\n      v")
            self.add(f"# {path}\ndef sy_pi_v_{i}(+k: {SK}, +v: {W}, +a: {W}, +b: {W}) -> {W}:\n"
                     f"  sy_pi_v_{i}_m({self.key_test(loc)}, v, a, b)")
            chain = f"sy_pi_v_{i}(k, {chain}, a, b)"
        self.add(f"# the address-typed registers: {', '.join(p for p, _l in locs) or 'none'}\n"
                 f"def sy_pi_v(+k: {SK}, +v: {W}, +a: {W}, +b: {W}) -> {W}:\n  {chain}")
        self.add(f"def sy_pi_kv(h: {KV}, +a: {W}, +b: {W}) -> {KV}:\n  match h:\n    case {KV}{{+k, v}}:\n"
                 f"      {KV}{{sy_pi_k(k, a, b), sy_pi_v(k, v, a, b)}}")
        self.add(f"def sy_pi_kvs(xs: List<&2, {KV}>, +a: {W}, +b: {W}) -> List<&2, {KV}>:\n  match xs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_pi_kv(h, a, b), sy_pi_kvs(t, a, b)}")
        self.add(f"def sy_pi_st(s: {HSt}, +a: {W}, +b: {W}) -> {HSt}:\n  match s:\n    case {HSt}{{sl}}:\n"
                 f"      {HSt}{{sy_pi_kvs(sl, a, b)}}")
        self.add(f"# π_(a,b) on a state (J2)\ndef sy_pi_g(+g: {GSt}, +a: {W}, +b: {W}) -> {GSt}:\n"
                 f"  {self.Q('gh_set_st')}(g, sy_pi_st({self.Q('gh_get_st')}(g), a, b))")
        # a 32-byte word of a byte string at a byte offset, swapped
        self.add(f"def sy_pi_at_go(+bs: List<&2, U32>, hd: List<&2, U32>, +tl: List<&2, U32>, +a: {W}, +b: {W}) -> "
                 "List<&2, U32>:\n"
                 f"  List.append(&2, U32, hd, List.append(&2, U32, {self.Q('b_of_w')}(sy_pw({self.Q('w_of_b32')}("
                 f"List.take(&2, U32, tl, 32n)), a, b)), List.drop(&2, U32, tl, 32n)))")
        self.add(f"def sy_pi_at(+bs: List<&2, U32>, +n: Nat, +a: {W}, +b: {W}) -> List<&2, U32>:\n"
                 f"  sy_pi_at_go(bs, List.take(&2, U32, bs, n), List.drop(&2, U32, bs, n), a, b)")
        # calls: the receiver, and the address-typed arguments of each call whose selector is known
        calls = [c for c in self.call_sigs() if c["selector"] and c["address_args"]]
        body = "cd"
        for c in reversed(calls):
            mapped = "cd"
            for i in c["address_args"]:
                mapped = f"sy_pi_at({mapped}, {4 + 32 * i}n, a, b)"
            body = f"{ite}(List<&2, U32>, {self.sel_test(c['selector'])}, {mapped}, {body})"
        self.add(f"# calldata: {', '.join(c['fn'] for c in calls) or 'no call with an address argument'}\n"
                 f"def sy_pi_cd(+cd: List<&2, U32>, +a: {W}, +b: {W}) -> List<&2, U32>:\n  {body}")
        self.add(f"def sy_pi_call(h: {HCall}, +a: {W}, +b: {W}) -> {HCall}:\n  match h:\n"
                 f"    case {HCall}{{to, cd, ok, ret}}:\n      {HCall}{{sy_pw(to, a, b), sy_pi_cd(cd, a, b), ok, ret}}")
        self.add(f"def sy_pi_calls(xs: List<&2, {HCall}>, +a: {W}, +b: {W}) -> List<&2, {HCall}>:\n  match xs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_pi_call(h, a, b), sy_pi_calls(t, a, b)}")
        KB = self.Q("KB")
        self.add(f"def sy_pi_kb(h: {KB}, +a: {W}, +b: {W}) -> {KB}:\n  match h:\n    case {KB}{{k, c}}:\n"
                 f"      {KB}{{sy_pw(k, a, b), c}}")
        self.add(f"def sy_pi_kbs(xs: List<&2, {KB}>, +a: {W}, +b: {W}) -> List<&2, {KB}>:\n  match xs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_pi_kb(h, a, b), sy_pi_kbs(t, a, b)}")
        fs = self.env_fields
        addr_env = {env_field(n) for n in ADDR_ENV}
        new = []
        for f in fs:
            if f in addr_env:
                new.append(f"sy_pw({f}, a, b)")
            elif f == "e_calls":
                new.append("sy_pi_calls(e_calls, a, b)")
            elif f == "e_code":
                new.append("sy_pi_kbs(e_code, a, b)")
            else:
                new.append(f)
        self.add(f"def sy_pi_en(en: {HEnv}, +a: {W}, +b: {W}) -> {HEnv}:\n  match en:\n"
                 f"    case {HEnv}{{{', '.join(fs)}}}:\n      {HEnv}{{{', '.join(new)}}}")
        cases = []
        for a in self.actions:
            A = self.Q(f"A_{a}")
            act = self.by_name.get(a) or {}
            ap = [p["name"] for p in act.get("params") or [] if p.get("type") == "address"]
            nested = [p["name"] for p in act.get("params") or []
                      if any(f.get("type") == "address" for f in p.get("fields") or [])]
            if nested:
                raise GenError(f"{a}: a struct argument with an address member (not mapped here): {nested}")
            if ap:
                AR = self.Q(f"AR_{a}")
                arf = record_fields(self.text, f"AR_{a}")
                miss = [p for p in ap if p not in arf]
                if miss:
                    raise GenError(f"{a}: address parameters {miss} are not fields of AR_{a}")
                self.add(f"def sy_pi_ar_{a}(ar: {AR}, +a: {W}, +b: {W}) -> {AR}:\n  match ar:\n"
                         f"    case {AR}{{{', '.join(arf)}}}:\n"
                         f"      {AR}{{{', '.join(f'sy_pw({f}, a, b)' if f in ap else f for f in arf)}}}")
                cases.append(f"    case {A}{{ar, en}}:\n      {A}{{sy_pi_ar_{a}(ar, a, b), sy_pi_en(en, a, b)}}")
            else:
                cases.append(f"    case {A}{{ar, en}}:\n      {A}{{ar, sy_pi_en(en, a, b)}}")
        self.add(f"# π_(a,b) on an act (J2)\ndef sy_pi_x(x: {HAct}, +a: {W}, +b: {W}) -> {HAct}:\n  match x:\n"
                 + "\n".join(cases))
        self.log_defs()

    def log_defs(self) -> None:
        """π on the logs: each event's address-typed words (an indexed one in its topic, another in its data head)."""
        W, HLog = self.Q("W"), self.Q("HLog")
        ite, weq = self.Q("ite"), self.Q("w_eq")
        events: dict = {}
        for a in self.doc.get("actions") or []:
            for e in a.get("events") or []:
                if e.get("anonymous") or not e.get("topic0") or not e.get("signature"):
                    continue
                types = e["signature"][e["signature"].index("(") + 1:-1].split(",") if "()" not in e["signature"] else []
                idx = e.get("indexed") or [False] * len(types)
                topics, data = [], []
                ti = di = 0
                for t, ix in zip(types, idx):
                    if ix:
                        ti += 1
                        if t == "address":
                            topics.append(ti)
                    else:
                        if t == "address":
                            data.append(di)
                        di += 1
                if topics or data:
                    events[e["topic0"]] = (e["signature"], topics, data)
        self.add(f"def sy_pi_ws(xs: List<&2, {W}>, n: Nat, +a: {W}, +b: {W}) -> List<&2, {W}>:\n  match xs n:\n"
                 "    case Nil{} _:\n      Nil{}\n    case Con{h, t} 0n:\n      Con{sy_pw(h, a, b), t}\n"
                 "    case Con{h, t} 1n+p:\n      Con{h, sy_pi_ws(t, p, a, b)}")
        body = "HL{t, d}".replace("HL", HLog)
        for t0, (sig, topics, data) in sorted(events.items(), reverse=True):
            tt, dd = "t", "d"
            for i in topics:
                tt = f"sy_pi_ws({tt}, {i}n, a, b)"
            for j in data:
                dd = f"sy_pi_at({dd}, {32 * j}n, a, b)"
            body = (f"{ite}({HLog}, {weq}({self.Q('w_nth')}(t, 0n), {self.lit(int(t0, 16))}), {HLog}{{{tt}, {dd}}}, "
                    f"{body})")
        self.add(f"# the events with address-typed words: {', '.join(v[0] for v in events.values()) or 'none'}\n"
                 f"def sy_pi_log(h: {HLog}, +a: {W}, +b: {W}) -> {HLog}:\n  match h:\n    case {HLog}{{+t, +d}}:\n"
                 f"      {body}")
        self.add(f"def sy_pi_logs(xs: List<&2, {HLog}>, +a: {W}, +b: {W}) -> List<&2, {HLog}>:\n  match xs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      Con{sy_pi_log(h, a, b), sy_pi_logs(t, a, b)}")
        for a in self.actions:
            act = self.by_name.get(a) or {}
            r = act.get("returns")
            addr = r is not None and self.types.of(act, r) == "address"
            ret = f"{self.Q('ite')}(List<&2, U32>, ok, sy_pi_at(d, 0n, a, b), d)" if addr else "d"
            self.add(f"def sy_pi_ob_{a}(o: UOb, +a: {W}, +b: {W}) -> UOb:\n  match o:\n"
                     f"    case UOb{{+ok, +d, lg}}:\n      UOb{{ok, {ret}, sy_pi_logs(lg, a, b)}}")
            self.add(f"def sy_pi_uos_{a}(u: UOS, +a: {W}, +b: {W}) -> UOS:\n  match u:\n"
                     f"    case UOS{{o, g, c}}:\n      UOS{{sy_pi_ob_{a}(o, a, b), sy_pi_g(g, a, b), c}}")

    def role_defs(self, role: str) -> None:
        """sy_mem_<role>(g, w): w is a member of the role in g (J1)."""
        W, GSt, KV = self.Q("W"), self.Q("GSt"), self.Q("KV")
        terms, regs = [], []
        for a in self.doc.get("actions") or []:
            p = a.get("principal")
            if not (isinstance(p, dict) and p.get("modifier")):
                continue
            mod = p["modifier"][4:] if p["modifier"].startswith("only") else p["modifier"]
            if mod[:1].lower() + mod[1:] != role:
                continue
            pred = p.get("predicate")
            if (isinstance(pred, list) and len(pred) == 3 and pred[0] == "map" and pred[2] == ["caller"]
                    and isinstance(pred[1], list) and pred[1][:1] == ["storage"]):
                f = self.family(pred[1][1])
                if f.get("kind") != "mapping" or f.get("key") != "address":
                    raise GenError(f"role {role}: its predicate's family {pred[1][1]} is not address-keyed")
                base, _o, _d, _m, off, width = self.locations(pred[1][1])[0]
                fg, _fs = self.field(off, width)
                t = (f"{self.Q('w_nz')}({fg}({self.Q('sload')}(sy_st_of(g), {self.Q('SK')}{{{self.lit(base)}, "
                     f"{self.Q('w0')}(), [{self.Q('SP_m')}{{w, {self.Q('w0')}()}}]}})))")
                if t not in terms:
                    terms.append(t)
            elif not (isinstance(pred, list) and pred[:1] == ["call"]):
                raise GenError(f"role {role}: a predicate of an unsupported shape {str(pred)[:80]}")
        for a in self.doc.get("actions") or []:
            for wr in a.get("writes") or []:
                v, fam = wr.get("value"), self.fams.get(wr.get("family")) or {}
                if isinstance(v, list) and v[:1] == ["struct"]:
                    types = {f["name"]: f.get("type") for f in fam.get("fields") or []}
                    for name, val in v[2]:
                        if name == role and val == ["caller"] and types.get(name) == "address":
                            path = f"{wr['family']}.{name}"
                            if path not in regs:
                                regs.append(path)
                elif v == ["caller"] and fam.get("value") == "address" and wr.get("family") == role:
                    if wr["family"] not in regs:
                        regs.append(wr["family"])
        for i, path in enumerate(regs):
            loc = self.locations(path)[0]
            fg, _fs = self.field(loc[4], loc[5])
            self.add(f"# a register of the role {role}: {path}\n"
                     f"def sy_rh_{bname(role)}_{i}(h: {KV}, +w: {W}) -> Bool:\n  match h:\n    case {KV}{{+k, v}}:\n"
                     f"      Bool.and({self.key_test(loc)}, {self.Q('w_eq')}({fg}(v), w))")
            self.add(f"def sy_rm_{bname(role)}_{i}(xs: List<&2, {KV}>, +w: {W}) -> Bool:\n  match xs:\n"
                     "    case Nil{}:\n      False{}\n    case Con{h, t}:\n"
                     f"      Bool.or(sy_rh_{bname(role)}_{i}(h, w), sy_rm_{bname(role)}_{i}(t, w))")
            terms.append(f"sy_rm_{bname(role)}_{i}(sy_sl(sy_st_of(g)), w)")
            if loc[2] == 1:   # a mapping register family: the registers no step wrote hold address(0)
                z = f"Bool.not({self.Q('w_nz')}(w))"
                if z not in terms:
                    terms.append(z)
        if not terms:
            raise GenError(f"role {role}: no predicate or register to read its members from")
        self.add(f"# the members of the role {role} in g (J1): {len(terms)} way(s) to be one\n"
                 f"def sy_mem_{bname(role)}(+g: {GSt}, +w: {W}) -> Bool:\n  {self.disj(terms)}")

    def sink_defs(self) -> None:
        """sy_sink_eq(xs, ys): the two stores agree on every sink-reaching key (J5)."""
        W, SK, KV = self.Q("W"), self.Q("SK"), self.Q("KV")
        sinks = sorted(S._sinks(self.doc))
        maps, scal = [], []
        for f in sinks:
            fam = self.fams.get(f)
            if fam is None:
                continue
            if fam.get("kind") == "mapping":
                maps.append(int(fam["slot"]))
            elif fam.get("kind") == "scalar":
                for path in [f] + [f"{f}.{m['name']}" for m in fam.get("fields") or []]:
                    if path == f and fam.get("fields"):
                        continue
                    scal.append((path, self.locations(path)[0]))
        weq = self.Q("w_eq")
        key_terms = [f"sy_at_b(k, {self.lit(b)})" for b in sorted(set(maps))]
        key_terms += [self.key_test(loc) for _p, loc in scal]
        self.add(f"def sy_at_b(k: {SK}, +b: {W}) -> Bool:\n  match k:\n    case {SK}{{kb, ko, kp}}:\n"
                 f"      Bool.and({weq}(kb, b), Bool.not(sy_p0(kp)))")
        self.add(f"# the sink families: {', '.join(sinks) or 'none'}\n"
                 f"def sy_sink_key(+k: {SK}) -> Bool:\n  {self.disj(key_terms)}")
        cmp = []
        for b in sorted(set(maps)):
            cmp.append(f"ux_imp(sy_at_b(k, {self.lit(b)}), {weq}(v1, v2))")
        for path, loc in scal:
            fg, _fs = self.field(loc[4], loc[5])
            cmp.append(f"ux_imp({self.key_test(loc)}, {weq}({fg}(v1), {fg}(v2)))")
        self.add(f"def sy_sink_cmp(+k: {SK}, +v1: {W}, +v2: {W}) -> Bool:\n  {self.conj(cmp)}")
        self.add(f"def sy_sk1(h: {KV}, +xs: List<&2, {KV}>, +ys: List<&2, {KV}>) -> Bool:\n  match h:\n"
                 f"    case {KV}{{+k, v}}:\n      ux_imp(sy_sink_key(k), sy_sink_cmp(k, {self.Q('kv_get')}(xs, k), "
                 f"{self.Q('kv_get')}(ys, k)))")
        self.add(f"def sy_sks(zs: List<&2, {KV}>, +xs: List<&2, {KV}>, +ys: List<&2, {KV}>) -> Bool:\n  match zs:\n"
                 "    case Nil{}:\n      True{}\n    case Con{h, t}:\n      Bool.and(sy_sk1(h, xs, ys), sy_sks(t, xs, ys))")
        # sy_sink_eq compares the sink-reaching entries alone (sy_snk keeps them in order, so kv_get of a sink key finds
        # the entry it finds in the whole store, and every other entry passed vacuously): the same Bool, and a counter-law
        # converts each filtered store once (holon.symd.proofs) instead of looking every key up in both whole stores
        self.add(f"def sy_snk_c(b: Bool, +h: {KV}, +r: List<&2, {KV}>) -> List<&2, {KV}>:\n  match b:\n"
                 "    case True{}:\n      Con{h, r}\n    case False{}:\n      r")
        self.add(f"def sy_snk_h(h: {KV}, +r: List<&2, {KV}>) -> List<&2, {KV}>:\n  match h:\n"
                 f"    case {KV}{{+k, v}}:\n      sy_snk_c(sy_sink_key(k), {KV}{{k, v}}, r)")
        self.add(f"# the store's sink-reaching entries, in order\n"
                 f"def sy_snk(zs: List<&2, {KV}>) -> List<&2, {KV}>:\n  match zs:\n"
                 "    case Nil{}:\n      Nil{}\n    case Con{h, t}:\n      sy_snk_h(h, sy_snk(t))")
        self.add(f"def sy_sink_eq2(+fx: List<&2, {KV}>, +fy: List<&2, {KV}>) -> Bool:\n"
                 "  Bool.and(sy_sks(fx, fx, fy), sy_sks(fy, fx, fy))")
        self.add(f"def sy_sink_eq(+xs: List<&2, {KV}>, +ys: List<&2, {KV}>) -> Bool:\n"
                 "  sy_sink_eq2(sy_snk(xs), sy_snk(ys))")

    # ---------------------------------------------------------- the laws
    def is_act(self, a: str) -> None:
        if f"sy_is_{a}" in self.mine:
            return
        cases = [f"    case {self.Q(f'A_{c}')}{{ar, en}}:\n      {'True{}' if c == a else 'False{}'}" for c in self.actions]
        self.add(f"def sy_is_{a}(x: {self.Q('HAct')}) -> Bool:\n  match x:\n" + "\n".join(cases))

    def law_tau(self, n: int, e: dict) -> None:
        a = bname(e["basis"]["action"])
        self.is_act(a)
        GSt, HAct, W = self.Q("GSt"), self.Q("HAct"), self.Q("W")
        prem = f"Bool.and(sy_is_{a}(x), Bool.and(sy_fits_g(g, d), sy_fits_x(x, d)))"
        sig = f"+g: {GSt}, +x: {HAct}, +d: {W}{self.hsig()}"
        self.add(f"# {e['law_id']}: τ_d commutes with a step of {e['basis']['action']} (J3 tau)\n"
                 f"def sy_ok_{n}({sig}) -> Bool:\n  ux_imp({prem}, sy_uos_eq(ux_ostep(sy_tau_x(x, d), sy_tau_g(g, d)"
                 f"{self.hargs()}), sy_tau_uos(ux_ostep(x, g{self.hargs()}), d)))")
        self.add(f"def sy_hit_{n}({sig}) -> Bool:\n  {prem}")

    def law_pi(self, n: int, e: dict) -> None:
        b = e["basis"]
        a, role = bname(b["action"]), bname(b["role"])
        self.is_act(a)
        GSt, HAct, W = self.Q("GSt"), self.Q("HAct"), self.Q("W")
        prem = (f"Bool.and(sy_is_{a}(x), Bool.and(Bool.not({self.Q('w_eq')}(a, b)), Bool.and(sy_mem_{role}(g, a), "
                f"sy_mem_{role}(g, b))))")
        sig = f"+g: {GSt}, +x: {HAct}, +a: {W}, +b: {W}{self.hsig()}"
        self.add(f"# {e['law_id']}: π_(a,b) within the role {b['role']} commutes with a step of {b['action']} (J3 pi)\n"
                 f"def sy_ok_{n}({sig}) -> Bool:\n  ux_imp({prem}, sy_uos_eq(ux_ostep(sy_pi_x(x, a, b), sy_pi_g(g, a, b)"
                 f"{self.hargs()}), sy_pi_uos_{a}(ux_ostep(x, g{self.hargs()}), a, b)))")
        self.add(f"def sy_hit_{n}({sig}) -> Bool:\n  {prem}")

    def law_omega(self, n: int, e: dict) -> None:
        b = e["basis"]
        xa, yb = bname(b["a"]), bname(b["b"])
        self.is_act(xa)
        self.is_act(yb)
        GSt, HAct = self.Q("GSt"), self.Q("HAct")
        sig = f"+g: {GSt}, +x: {HAct}, +y: {HAct}{self.hsig()}"
        ok = lambda u: f"U32.is_eq(sy_code({u}), 0)"  # noqa: E731
        # the two first steps from g, then each order's second step
        self.add(f"def sy_om_{n}_c(+uxy: UOS, +uyx: UOS) -> Bool:\n  ux_imp(Bool.and({ok('uxy')}, {ok('uyx')}), "
                 f"sy_sink_eq(sy_sl(sy_st_of(sy_post(uxy))), sy_sl(sy_st_of(sy_post(uyx)))))")
        self.add(f"def sy_om_{n}_h(+uxy: UOS, +uyx: UOS) -> Bool:\n  Bool.and({ok('uxy')}, {ok('uyx')})")
        for mode in ("c", "h"):
            imp = "ux_imp" if mode == "c" else "Bool.and"
            self.add(f"def sy_om_{n}_{mode}2(+ux: UOS, +uy: UOS, +x: {HAct}, +y: {HAct}{self.hsig()}) -> Bool:\n"
                     f"  {imp}(Bool.and({ok('ux')}, {ok('uy')}), sy_om_{n}_{mode}(ux_ostep(y, sy_post(ux){self.hargs()}), "
                     f"ux_ostep(x, sy_post(uy){self.hargs()})))")
        prem = f"Bool.and(sy_is_{xa}(x), sy_is_{yb}(y))"
        self.add(f"# {e['law_id']}: where both orders of x ({b['a']}) and y ({b['b']}) execute, they agree on every "
                 f"sink-reaching key (J3 omega)\ndef sy_ok_{n}({sig}) -> Bool:\n  ux_imp({prem}, sy_om_{n}_c2("
                 f"ux_ostep(x, g{self.hargs()}), ux_ostep(y, g{self.hargs()}), x, y{self.hargs()}))")
        self.add(f"def sy_hit_{n}({sig}) -> Bool:\n  Bool.and({prem}, sy_om_{n}_h2(ux_ostep(x, g{self.hargs()}), "
                 f"ux_ostep(y, g{self.hargs()}), x, y{self.hargs()}))")

    def site_term(self, e: dict):
        b = e["basis"]
        reg = b["register"]
        for act, src, val in S.write_values(self.doc, reg):
            if act == b["action"] and src == b["src"] and val != b["constant"]:
                return val
        raise GenError(f"{e['law_id']}: the site {b['action']} {b['src']} of {reg} is not in the document")

    def law_sentinel(self, n: int, e: dict) -> None:
        """The site's write term is compiled in the call's initial context x0_<a>(st, ar, en, kh) (the document's terms
        read the pre-state, the arguments and the environment); the premise block.timestamp >= 1, where the term reads
        the clock, is stated as block.timestamp != 0 (the same proposition of an unsigned word)."""
        b = e["basis"]
        a = bname(b["action"])
        self.is_act(a)
        GSt, HAct, X = self.Q("GSt"), self.Q("HAct"), self.Q(f"X_{a}")
        term = self.site_term(e)
        val = self.compile_word(b["action"], term)
        reads_ts = ["env", "block.timestamp"] in list(S._walk(term))
        c = int(b["constant"])
        claim = f"{self.Q('w_nz')}(sy_v_{n}(x0))" if c == 0 else f"Bool.not({self.Q('w_eq')}(sy_v_{n}(x0), {self.lit(c)}))"
        prem = [f"U32.is_eq({self.Q(f'gx_{a}_cd')}(xr), 0)"]
        if reads_ts:
            prem.append(f"{self.Q('w_nz')}({self.Q('ge_e_block_timestamp')}(en))")
        self.add(f"# the word the site {b['src']} writes to {b['register']}, in the initial context of the call of "
                 f"{b['action']}\ndef sy_v_{n}(+x: {X}) -> {self.Q('W')}:\n  {val}")
        for mode in ("c", "h"):
            body = f"ux_imp({self.conj(prem)}, {claim})" if mode == "c" else self.conj(prem)
            self.add(f"def sy_sn_{n}_{mode}(+xr: {X}, +x0: {X}, +en: {self.Q('HEnv')}) -> Bool:\n  {body}")
        hs = self.hsig()
        for mode, other, fn in (("c", "True{}", "sy_ok"), ("h", "False{}", "sy_hit")):
            cases = []
            for cn in self.actions:
                if cn == a:
                    st = f"{self.Q('gh_get_st')}(g)"
                    cases.append(f"    case {self.Q(f'A_{cn}')}{{+ar, +en}}:\n      sy_sn_{n}_{mode}({self.Q(f'xr_{a}')}("
                                 f"{st}, ar, en{self.hargs()}), {self.Q(f'x0_{a}')}({st}, ar, en{self.hargs()}), en)")
                else:
                    cases.append(f"    case {self.Q(f'A_{cn}')}{{ar, en}}:\n      {other}")
            lead = (f"# {e['law_id']}: a successful call of {b['action']} (block.timestamp >= 1 where the site reads it) "
                    f"writes a word other than {c} at {b['src']} (J3 sentinel)\n") if mode == "c" else ""
            self.add(f"{lead}def {fn}_{n}(+g: {GSt}, x: {HAct}{hs}) -> Bool:\n  match x:\n" + "\n".join(cases))

    # ---------------------------------------------------------- the module
    def law_fn(self) -> dict:
        """{law id: (n, subform)}: the section's function index of each law (sy_ok_<n>, sy_hit_<n>)."""
        return {e["law_id"]: (n, e["subform"]) for n, e in enumerate(self.syms)}

    def build(self) -> list[str]:
        self.defs, self.mine = [], set()
        self._fields = {}
        self.fixed()
        self.observations()
        self.sym_fixed()
        subs = {e["subform"] for e in self.syms}
        if "tau" in subs:
            self.tau_defs()
        if "pi" in subs:
            self.pi_defs()
            for role in sorted({e["basis"]["role"] for e in self.syms if e["subform"] == "pi"}):
                self.role_defs(role)
        if "omega" in subs:
            self.sink_defs()
        for n, e in enumerate(self.syms):
            getattr(self, f"law_{e['subform']}")(n, e)
        clash = sorted(m for m in self.mine if m in self.names and not (self.q and m == "run"))
        if clash:
            raise GenError(f"the sym section's names clash with the typed model's: {clash}")
        return self.defs


def module_text(mm, model_text: str, doc: dict, hashes: list, elements: list, assignment: dict,
                model_import: str) -> tuple[str, list]:
    """gen/<M>/sym/models/<model>.bend: the sym section, importing the typed model as M; and the section's notes."""
    sec = SymSection(mm, model_text, doc, hashes, elements, assignment)
    defs = sec.build()
    head = [HEADER, f"# {SECTION_VERSION}; laws: {len(elements)}"]
    head += [f"# note: {n}" for n in sec.notes]
    head += ["import Base", f"import {model_import} as M", ""]
    return "\n".join(head) + "\n" + "\n".join(defs), sec.notes


def combined_text(mm, model_text: str, doc: dict, hashes: list, elements: list, assignment: dict) -> str:
    """The typed model's text followed by the sym section unqualified: one module for the JavaScript evaluator."""
    sec = SymSection(mm, model_text, doc, hashes, elements, assignment)
    sec.q = ""
    defs = sec.build()
    return model_text.rstrip("\n") + "\n\n# ---- holon.gen.symsec (evaluation copy)\n" + "\n".join(defs)
