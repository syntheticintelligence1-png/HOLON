"""Proof generators, one per obligation class (whitepaper §9.2 loop 3, §10.4).

Generators are untrusted: their output counts only if Bend accepts it. They never see
law ids; they dispatch on the *shape* of the emitted statement, so a fix to a generator
propagates to every law of its class (AGENTS.md rule 4).

  open_refl      open every record binder, then `{==}`. Proof by computation: decides
                 codec/layout equalities over symbolic fields (PAR, layout lemmas).
  version_split  for a claim P(b) == Q(b) over a byte string b where P and Q dispatch on
                 the version byte: case on b, then a lemma over n = U32.to_nat(b[0]) that
                 splits n into 0n..Kn, (K+1)n+p and closes each case by `{==}`.
  counter        a counter-law `exs x. lhs != rhs` with a concrete witness, closed by
                 rewriting through the model's equality function (BEND_PRIMER §5.4).
"""
from __future__ import annotations

import re

from .. import facts as F
from . import model as G
from .laws import MODEL_ALIAS, Emitted

HEADER = ["# GENERATED by holon.gen.proofs; untrusted, accepted only if Bend checks it.", "import Base"]


def _imports(model_import: str) -> list[str]:
    return HEADER + [f"import {model_import} as {MODEL_ALIAS}", "import ./LAWS.bend as Laws", ""]


def open_refl(em: Emitted, facts: dict, model_import: str) -> str | None:
    if any(t != "Header" for _, t in em.binders):
        return None
    pat = f"{MODEL_ALIAS}.Hdr{{" + ", ".join(G.cell_names(facts)) + "}"
    lines = [f"# class open_refl: open {len(em.binders)} record binder(s), then reflexivity",
             f"def Laws.{em.name}({', '.join(v for v, _ in em.binders)}):"]
    ind = 2
    for v, _ in em.binders:
        # distinct pattern variables per binder
        p = pat if len(em.binders) == 1 else re.sub(r"(\w+_\d+)", rf"{v}_\1", pat)
        lines += [" " * ind + f"match {v}:", " " * (ind + 2) + f"case {p}:"]
        ind += 4
    lines.append(" " * ind + "{==}")
    return "\n".join(_imports(model_import) + lines) + "\n"


_PRED_CALL = re.compile(rf"^{MODEL_ALIAS}\.(\w+)\((\w+)\)$")


def version_split(em: Emitted, facts: dict, model_import: str) -> str | None:
    if len(em.binders) != 1 or em.binders[0][1] != "Bytes" or em.pins:
        return None
    var = em.binders[0][0]
    ml, mr = _PRED_CALL.match(em.lhs), _PRED_CALL.match(em.rhs)
    if not (ml and mr and ml.group(2) == var and mr.group(2) == var):
        return None
    fl, fr = ml.group(1), mr.group(1)
    fns = facts["functions"]
    if fns.get(fl, {}).get("kind") != "predicate" or fns.get(fr, {}).get("kind") != "predicate":
        return None
    k = max(G.max_version_const(fns[fl]["rules"]), G.max_version_const(fns[fr]["rules"]))
    lemma = f"{em.name}_at"
    lines = [f"# class version_split: {fl} and {fr} agree at every version byte n (cases 0n..{k}n, {k + 1}n+p)",
             f"def {lemma}(n: Nat, t: {G.BYTES}) -> {{{MODEL_ALIAS}.{fl}_at(n, t) == {MODEL_ALIAS}.{fr}_at(n, t) : Bool}}:",
             "  match n:"]
    for pat, _ in G.nat_cases(k):
        lines += [f"    case {pat}:", "      {==}"]
    lines += ["", f"def Laws.{em.name}({var}):", f"  match {var}:", "    case Nil{}:", "      {==}",
              "    case Con{h, t}:", f"      {lemma}(U32.to_nat(h), t)"]
    return "\n".join(_imports(model_import) + lines) + "\n"


GENERATORS = [("open_refl", open_refl), ("version_split", version_split)]


# ---------------------------------------------------------------- counter-laws
def literal(ir_type: str, value, facts: dict) -> str:
    """Bend literal of a canonical-JSON witness value."""
    if ir_type == "Bytes":
        return G._list([str(x) for x in bytes.fromhex(value[2:])])
    if ir_type == "Header":
        w = F.widths(facts)
        cells = []
        for f in F.header_fields(facts):
            b = bytes.fromhex(value[f["name"]][2:])
            if len(b) != w[f["name"]]:
                raise ValueError(f"witness field {f['name']} has {len(b)} bytes, expected {w[f['name']]}")
            cells += [str(x) for x in b]
        return f"{MODEL_ALIAS}.Hdr{{" + ", ".join(cells) + "}"
    raise ValueError(ir_type)


def substitute(side: str, em: Emitted, lits: dict[str, str]) -> str:
    """The claim side at the witness: binder occurrences replaced by literals."""
    out = side
    for v, _ in em.binders:
        pinned = f"pin_{v}({v})"
        out = out.replace(pinned, f"Laws.pin_{v}({lits[v]})") if v in em.pins else \
            re.sub(rf"(?<![\w.]){re.escape(v)}(?![\w])", lits[v], out)
    return out


def counter(em: Emitted, facts: dict, model_import: str, witness: dict) -> str:
    lits = {v: literal(t, witness[v], facts) for v, t in em.binders}
    at_lhs = substitute(em.lhs, em, lits)
    eq = f"{MODEL_ALIAS}.{G.EQ_FN[em.claim_type]}"
    tup = ", ".join(lits[v] for v, _ in em.binders)
    lines = ["# class counter: concrete witness; the motive is Unit at the lhs and Empty at the rhs",
             f"def Laws.{em.name}():",
             f"  ({tup}, e => (%e : {MODEL_ALIAS}.is_true({eq}(_, {at_lhs}))",
             "  Unit{}))"]
    return "\n".join(_imports(model_import) + lines) + "\n"
