"""holon-ir/0.3 codec laws over a holon-facts/0.1 document (BUILD_PLAN I24; rule PAR's codec sub-forms over the M0
fact format; the contract is "Deciding the laws" in the docstring of tests_m3/test_derive_par.py).

Such a law is decided with the M0 machinery, unchanged: the model of holon.gen.model, the proof generators of
holon.gen.proofs, the candidate spaces of holon.refute and holon.gen.proofs.counter. Only the statement's form differs
from holon-ir/0.1: "binders" (every one universal) where 0.1 has "forall", and the term {"bool": b}, which is
True{}/False{} of type Bool. to01 rewrites the first; type_of, term and emit extend holon.gen.laws's by the second.
Premises are applied by pinning, exactly as holon.gen.laws does (a premise it cannot express leaves the law UNKNOWN).
Nothing here edits the M0 generators: M0's records and generated files stay byte-identical.
"""
from __future__ import annotations

from .. import facts as F
from ..model_eval import CompiledModel, ModelError, value_in
from ..refute import Search, _decode, candidates, describe_space, subterms
from . import laws as LG
from . import model as G
from .laws import MODEL_ALIAS, Emitted, Unsupported, bend_type, collect_pins, hexbytes, law_name, pin_def

MODEL_IMPORT = "../../model/{}.bend"


def is_facts01(doc: dict) -> bool:
    return isinstance(doc, dict) and doc.get("facts_version") == "holon-facts/0.1"


def to01(law: dict) -> dict:
    """The law with its holon-ir/0.3 binders as holon-ir/0.1's "forall" (every binder universal, else Unsupported)."""
    st = law["statement"]
    bs = st.get("binders", [])
    if any(b.get("q", "forall") != "forall" for b in bs):
        raise Unsupported("a codec law over a holon-facts/0.1 document is universal")
    if (st.get("scope") or {"kind": "unbounded"}).get("kind") != "unbounded":
        raise Unsupported(f"scope {st.get('scope')}")
    return {**law, "statement": {"forall": [{"name": b["name"], "type": b["type"]} for b in bs],
                                 "assume": list(st.get("assume", [])), "claim": st["claim"]}}


def type_of(t: dict, types: dict, facts: dict) -> str:
    if isinstance(t, dict) and set(t) == {"bool"}:
        return "Bool"
    if isinstance(t, dict) and "call" in t:
        fn = t["call"]
        if fn not in facts["functions"]:
            raise Unsupported(f"unknown function {fn}")
        arg_t, res_t = F.fn_types(facts, fn)
        if len(t["args"]) != 1 or type_of(t["args"][0], types, facts) != arg_t:
            raise Unsupported(f"ill-typed call {t}")
        return res_t
    if isinstance(t, dict) and "some" in t:
        if type_of(t["some"], types, facts) != "Fields":
            raise Unsupported(f"Some over a non-Fields term {t}")
        return "MaybeFields"
    return LG.type_of(t, types, facts)


def term(t: dict, env: dict) -> str:
    if isinstance(t, dict) and set(t) == {"bool"}:
        return "True{}" if t["bool"] else "False{}"
    if isinstance(t, dict) and "call" in t:
        return f"{MODEL_ALIAS}.{t['call']}({', '.join(term(a, env) for a in t['args'])})"
    if isinstance(t, dict) and "some" in t:
        return f"{{Some{{{term(t['some'], env)}}} : {G.MAYBE_FIELDS}}}"
    return LG.term(t, env)


def emit(law01: dict, facts: dict, model_import: str, counter: bool = False, header_note: str = "") -> Emitted:
    """holon.gen.laws.emit, with {"bool"} terms (law01: to01's form)."""
    st = law01["statement"]
    types = LG.binder_types(law01)
    pins = collect_pins(law01, facts)
    claim = st["claim"]
    if set(claim) != {"eq"}:
        raise Unsupported("a codec law states one equation")
    a, b = claim["eq"]
    ta, tb = type_of(a, types, facts), type_of(b, types, facts)
    if ta != tb:
        raise Unsupported(f"claim sides have different types {ta} / {tb}")
    env = {v: (f"pin_{v}({v})" if v in pins else v) for v in types}
    lhs, rhs = term(a, env), term(b, env)
    name = law_name(law01["law_id"], counter)
    q = "exs" if counter else "for"
    rel = "!=" if counter else "=="
    lines = ["# GENERATED by holon.gen.codec01 from the frozen law IR; do not edit.",
             f"# law_id: {law01['law_id']}   statement_hash: {header_note}",
             "import Base", f"import {model_import} as {MODEL_ALIAS}", ""]
    for v in sorted(pins):
        lines += pin_def(facts, v, pins[v]) + [""]
    lines += [f"law {name}:"] + [f"  {q} {v}: {bend_type(t)}" for v, t in types.items()]
    lines += [f"  {{{lhs} {rel} {rhs} : {G.BEND_TYPE[ta]}}}"]
    return Emitted(name, "\n".join(lines) + "\n", ta, lhs, rhs, list(types.items()), pins)


# ---------------------------------------------------------------- refutation (holon.refute's spaces)
def _jobs_terms(law01: dict, facts: dict):
    types = LG.binder_types(law01)
    a, b = law01["statement"]["claim"]["eq"]
    subs = [x for side in (a, b) for x in subterms(side)]
    sub_t = [type_of(x, types, facts) for x in subs]
    return types, [a, b] + subs, type_of(a, types, facts), sub_t


def search(law01: dict, facts: dict, model: CompiledModel, batch: int = 256) -> Search:
    """holon.refute.search over the same candidates, typing {"bool"} sides (the evaluator reads {"bool": b} as b)."""
    pins = collect_pins(law01, facts)
    types, terms, res_t, sub_t = _jobs_terms(law01, facts)
    out = Search(bound=describe_space(law01, facts))
    cands = list(candidates(law01, facts, pins))
    for i in range(0, len(cands), batch):
        chunk = cands[i:i + batch]
        jobs = [{"terms": terms, "env": {v: value_in(types[v], x[v], facts) for v in types}} for _, x in chunk]
        for (label, env), vals in zip(chunk, model.run_jobs(jobs)):
            out.tried += 1
            try:
                lj, rj = _decode(vals, res_t, sub_t)
            except (ValueError, ModelError):
                out.undefined += 1
                continue
            if lj != rj:
                out.witness, out.difference = env, {"lhs": lj, "rhs": rj}
                out.notes.append(f"hit: {label}")
                return out
    return out


# ---------------------------------------------------------------- non-vacuity (holon.inhabit's 0.1 class)
def inhabitant_witness(law01: dict, facts: dict) -> dict:
    """The pins, zeros elsewhere (holon.inhabit.pin_witness)."""
    from ..inhabit import pin_witness
    return pin_witness(law01, facts)


def inhabitant_texts(law: dict, facts: dict, model_stem: str, witness: dict, note: str = "") -> tuple[str, str, str]:
    """(law name, LAWS.bend, PROOF.bend) of the inhabitant of a codec law's premises (holon.inhabit.texts_01's class:
    the pins through the model's getters, at the pin header): law is the holon-ir/0.3 law, note its statement hash."""
    from ..inhabit import law_name as nv_name, pins_of
    from . import proofs as PG
    law01 = to01(law)
    if pins_of(law01) is None or any(b["type"] != "Header" for b in law01["statement"]["forall"]):
        raise Unsupported("premise form not supported by the holon-ir/0.1 inhabitant class")
    binders = law01["statement"]["forall"]
    pins = pins_of(law01)
    name = nv_name(law["law_id"])
    imp = MODEL_IMPORT.format(model_stem)
    lines = [f"# GENERATED by holon.gen.codec01: non-vacuity inhabitant of {law['law_id']} ({note}).",
             "import Base", f"import {imp} as M", "", f"law {name}:"]
    lines += [f"  exs {b['name']}: M.Hdr" for b in binders]
    props = []
    for (v, f), hexv in sorted(pins.items()):
        bs = ", ".join(str(x) for x in hexbytes(hexv))
        props.append(f"{{M.get_{f}({v}) == [{bs}] : List<&2, U32>}}")
    lines += [f"  exs c{i}: {p}" for i, p in enumerate(props[:-1])] + [f"  {props[-1]}"]
    parts = [PG.literal("Header", witness[b["name"]], facts) for b in binders] + ["{==}"] * len(props)
    tup = parts[-1]
    for p in reversed(parts[:-1]):
        tup = f"({p}, {tup})"
    proof = "\n".join(["# GENERATED by holon.gen.codec01; accepted only if Bend checks it.", "import Base",
                       f"import {imp} as M", "import ./LAWS.bend as Laws", "",
                       "# class evaluate: the pin header, then every premise by computation",
                       f"def Laws.{name}():", f"  {tup}"]) + "\n"
    return name, "\n".join(lines) + "\n", proof
