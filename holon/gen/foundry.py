"""Per-witness Foundry tests (I40; whitepaper §10.9): a witness's concrete calls, written from its calldata and the
document's action interface, never from a per-action table.

  test_text(name, steps, expected, deploy, obstruction) -> Solidity source

deploy: {"kind": "new", "import": <path>, "contract": <name>} (a test milestone with no binding: the contract created
with no argument) or {"kind": "harness", "import": <path>, "contract": <harness contract>, "init": [..]} (the binding's
deployment: the harness's holonDeploy(0, init)). Each step: vm.warp, vm.blobhashes, vm.deal when it sends value,
vm.prank and the call; every step's outcome is logged ("HOLON <i> ok|rev: <return data>") and asserted against the
witness's (ok, or the revert data of its key: Panic(code) or Error(reason)); the obstruction the law claims is the
last step's outcome, or, for a state obstruction, the storage words the test reads after the last step.
"""
from __future__ import annotations

import re

PANIC_SELECTOR = "4e487b71"
ERROR_SELECTOR = "08c379a0"


def revert_data(key: str) -> str | None:
    """The revert data of an outcome key: "panic:0x11" -> Panic(0x11); a reason string -> Error(reason); a hex string
    -> itself. None when the key fixes no data."""
    if key.startswith("panic:"):
        return PANIC_SELECTOR + "%064x" % int(key.split(":", 1)[1], 16)
    if key.startswith("0x"):
        return key[2:]
    b = key.encode("utf-8")
    return (ERROR_SELECTOR + "%064x" % 32 + "%064x" % len(b) + b.hex().ljust(((len(b) + 31) // 32) * 64, "0"))


def sanitize(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def test_text(name: str, steps: list[dict], expected: list[str], deploy: dict, slots: list | None = None,
              note: str = "", stored: list | None = None) -> str:
    """stored: byte strings (hex) of which the last steps must have stored one's keccak256 in a storage word of the
    called contract (the words written after the deployment, vm.record / vm.accesses)."""
    cname = "HolonWitness_" + sanitize(name)
    lines = ["// SPDX-License-Identifier: MIT",
             f"// Generated by holon.gen.foundry (I40): {note}".rstrip(),
             "pragma solidity =0.8.24;", ""]
    vmi = "HolonVm_" + sanitize(name)
    lines += [f"interface {vmi} {{", "    function blobhashes(bytes32[] calldata) external;", "}", ""]
    if deploy["kind"] == "new":
        lines += ['import {Test} from "forge-std/Test.sol";',
                  f'import {{{deploy["contract"]}}} from "{deploy["import"]}";', "",
                  f"contract {cname} is Test {{"]
    else:
        lines += [f'import {{{deploy["contract"]}}} from "{deploy["import"]}";', "",
                  f"contract {cname} is {deploy['contract']} {{"]
    lines += ["    function holonStep(address t, uint256 i, address caller, uint256 value, uint256 ts, bytes32[] memory bh,",
              "                       bytes memory data) internal returns (bool ok, bytes memory ret) {",
              "        vm.warp(ts);",
              f"        {vmi}(address(vm)).blobhashes(bh);",
              "        if (value > 0) vm.deal(caller, caller.balance + value);",
              "        vm.prank(caller);",
              "        (ok, ret) = t.call{value: value}(data);",
              '        emit log_named_bytes(string(abi.encodePacked("HOLON ", vm.toString(i), ok ? " ok" : " rev")), ret);',
              "    }", "",
              "    function test_witness() public {"]
    if deploy["kind"] == "new":
        lines.append(f"        address t = address(new {deploy['contract']}());")
    else:
        init = ", ".join(str(int(x)) for x in deploy.get("init") or [])
        n = len(deploy.get("init") or [])
        lines.append(f"        uint256[] memory init = new uint256[]({n});")
        for i, x in enumerate(deploy.get("init") or []):
            lines.append(f"        init[{i}] = {int(x)};")
        lines.append("        address t = holonDeploy(0, init);")
        del init
    lines += ["        bool ok;", "        bytes memory ret;", "        bool all = true;"]
    if stored is not None:
        lines.append("        vm.record();")
    for i, (s, want) in enumerate(zip(steps, expected)):
        env = s["env"]
        bh = env.get("blobhash") or []
        lines.append(f"        {{ // step {i}: {s['action']}")
        lines.append(f"            bytes32[] memory bh = new bytes32[]({len(bh)});")
        for j, b in enumerate(bh):
            lines.append(f"            bh[{j}] = bytes32(uint256({int(str(b), 0)}));")
        cd = s["calldata"][2:] if s["calldata"].startswith("0x") else s["calldata"]
        lines.append(f"            (ok, ret) = holonStep(t, {i}, address(uint160({int(str(env['caller']), 0)})), "
                     f"{int(str(env.get('msg.value', 0)), 0)}, {int(str(env['block.timestamp']), 0)}, bh, hex\"{cd}\");")
        if want == "ok":
            lines.append("            all = all && ok;")
        else:
            key = want[4:] if want.startswith("rev ") else want
            data = revert_data(key)
            lines.append(f"            all = all && !ok && keccak256(ret) == keccak256(hex\"{data}\");")
        lines.append("        }")
    for slot, word in slots or []:
        lines.append(f"        all = all && vm.load(t, bytes32(uint256({int(slot)}))) == bytes32(uint256({int(word)}));")
    if stored is not None:
        lines += ["        {", "            (, bytes32[] memory written) = vm.accesses(t);", "            bool found = false;",
                  "            for (uint256 j = 0; j < written.length; j++) {",
                  "                bytes32 w = vm.load(t, written[j]);"]
        for h in stored:
            hx = h[2:] if h.startswith("0x") else h
            lines.append(f"                if (w == keccak256(hex\"{hx}\")) found = true;")
        lines += ["            }", '            emit log_named_string("HOLON stored", found ? "true" : "false");',
                  "            all = all && found;", "        }"]
    lines += ['        assertTrue(all, "the witness\'s outcomes");', "    }", "}", ""]
    return "\n".join(lines)
