"""Emitted Go tests (I40; the Go half of the emitted tests that replace the hand harnesses): one test per Go library
side, calling the extracted function or method on the witness's input.

The function comes from its extraction (a holon-facts/0.3 Go document names it as "(pkg.T).m" or "(*pkg.T).m"); the
witness's record is built by reflection from its field paths (a dotted path walks embedded and nested structs; an
unsigned integer field takes the big-endian value of its bytes, a byte array or byte slice the bytes), so the emitter
holds no per-type table. The test logs the result ("HOLON out <hex>") and asserts it equals the bytes the model gives
the Go side on the witness: it passes iff the real Go code computes what the model says it does.

  method_of(source) -> (package path, receiver type, method, pointer) | None
  test_text(pkg, name, recv, method, fields, want_hex, note) -> Go source
  workspace(checkout, ws, pkg_dir) -> module dir     a scratch copy of the package's module and the workspace modules
                                                     it imports, under one go.work
  run(go, ws, module, pkg_rel, name) -> {"passed", "out", "command", "exit"}
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
from pathlib import Path

SOURCE = re.compile(r"^\((\*?)([\w./-]+)\.(\w+)\)\.(\w+)$")
NO_BUN_CONFIG = shutil.ignore_patterns(".env", ".env.*", "bunfig.toml")


def method_of(source: str):
    m = SOURCE.match(source or "")
    if not m:
        return None
    return m.group(2), m.group(3), m.group(4), bool(m.group(1))


def sanitize(s: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def test_text(pkg: str, name: str, recv: str, method: str, fields: dict, want_hex: str, note: str = "") -> str:
    lines = [f"// Code generated by holon refute (I40). DO NOT EDIT.", f"// {note}" if note else "//",
             f"package {pkg}", "", "import (", '\t"encoding/hex"', '\t"math/big"', '\t"reflect"', '\t"strings"',
             '\t"testing"', ")", "",
             f"func holonField_{name}(v reflect.Value, path string) reflect.Value {{",
             '\tfor _, p := range strings.Split(path, ".") {',
             "\t\tif v.Kind() == reflect.Ptr {", "\t\t\tv = v.Elem()", "\t\t}", "\t\tv = v.FieldByName(p)", "\t}",
             "\treturn v", "}", "",
             f"func holonSet_{name}(t *testing.T, v reflect.Value, h string) {{",
             '\tb, err := hex.DecodeString(strings.TrimPrefix(h, "0x"))', "\tif err != nil || !v.IsValid() {",
             '\t\tt.Fatalf("HOLON bad field %v %v", err, v.IsValid())', "\t}", "\tswitch v.Kind() {",
             "\tcase reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:",
             "\t\tv.SetUint(new(big.Int).SetBytes(b).Uint64())", "\tcase reflect.Array:",
             "\t\treflect.Copy(v, reflect.ValueOf(b))", "\tcase reflect.Slice:", "\t\tv.SetBytes(b)", "\tdefault:",
             '\t\tt.Fatalf("HOLON field kind %v", v.Kind())', "\t}", "}", "",
             f"func TestHolon_{name}(t *testing.T) {{", f"\tvar x {recv}", "\trv := reflect.ValueOf(&x).Elem()"]
    for path in sorted(fields):
        lines.append(f'\tholonSet_{name}(t, holonField_{name}(rv, "{path}"), "{fields[path]}")')
    lines += [f"\tgot := x.{method}()", '\tt.Logf("HOLON out 0x%x", []byte(got))',
              f'\tif hex.EncodeToString(got) != "{want_hex.removeprefix("0x")}" {{',
              '\t\tt.Fatalf("HOLON differs from the model")', "\t}", "}", ""]
    return "\n".join(lines)


def _module_root(checkout: Path, pkg_dir: str) -> str:
    d = Path(pkg_dir)
    while str(d) not in ("", "."):
        if (checkout / d / "go.mod").is_file():
            return str(d)
        d = d.parent
    raise ValueError(f"no go.mod above {pkg_dir}")


def _modpath(gomod: Path) -> str:
    m = re.search(r"(?m)^module\s+(\S+)", gomod.read_text())
    return m.group(1) if m else ""


def workspace(checkout: Path, ws: Path, pkg_dir: str) -> str:
    mod = _module_root(checkout, pkg_dir)
    dirs = [mod]
    work = checkout / "go.work"
    if work.is_file():
        texts = "\n".join(p.read_text(errors="replace") for p in (checkout / mod).rglob("*.go"))
        for d in re.findall(r"(?m)^\s*\./(\S+)\s*$", work.read_text()):
            if d == mod or not (checkout / d / "go.mod").is_file():
                continue
            mp = _modpath(checkout / d / "go.mod")
            if mp and re.search(rf'"{re.escape(mp)}(/[^"]*)?"', texts):
                dirs.append(d)
    shutil.rmtree(ws, ignore_errors=True)
    ws.mkdir(parents=True)
    for d in sorted(dirs):
        shutil.copytree(checkout / d, ws / d, symlinks=True, ignore=NO_BUN_CONFIG)
    gv = re.search(r"(?m)^go\s+\S+", work.read_text()) if work.is_file() else None
    (ws / "go.work").write_text((gv.group(0) if gv else "go 1.24.0") + "\n\nuse (\n"
                                + "".join(f"\t./{d}\n" for d in sorted(dirs)) + ")\n")
    if (checkout / "go.work.sum").is_file():
        shutil.copy(checkout / "go.work.sum", ws / "go.work.sum")
    return mod


def package_name(checkout: Path, pkg_dir: str) -> str:
    for f in sorted((checkout / pkg_dir).glob("*.go")):
        if f.name.endswith("_test.go"):
            continue
        m = re.search(r"(?m)^package\s+(\w+)", f.read_text(errors="replace"))
        if m:
            return m.group(1)
    raise ValueError(f"no Go package in {pkg_dir}")


def run(go: str, ws: Path, module: str, pkg_rel: str, name: str, timeout: int = 3600) -> dict:
    env = {k: v for k, v in os.environ.items() if k not in ("GOWORK", "GOFLAGS")}
    env["GOTOOLCHAIN"] = "local"
    cmd = [go, "test", f"./{pkg_rel}", "-run", f"^TestHolon_{name}$", "-v", "-count=1"]
    try:
        p = subprocess.run(cmd, cwd=ws / module, env=env, capture_output=True, text=True, timeout=timeout)
        out, code = p.stdout + p.stderr, p.returncode
    except subprocess.TimeoutExpired:
        out, code = "", None
    m = re.search(r"HOLON out (0x[0-9a-f]*)", out)
    return {"passed": code == 0 and f"--- PASS: TestHolon_{name}" in out, "out": m.group(1) if m else None,
            "exit": code, "command": f"(cd {module} && GOTOOLCHAIN=local go test ./{pkg_rel} -run '^TestHolon_{name}$' "
                                     f"-v -count=1)", "tail": out.replace(str(ws), "<scratch>")[-600:]}
