"""C driver generator: give the M0 model a `main` that evaluates IR jobs (whitepaper §8.7; BUILD_PLAN I16).

`bend driver.bend -o driver.c` emits C and clang builds it into a native executable (BEND_PRIMER §2,
`bend guide` "Tooling"); both need a `main`. This module writes that `main` as Bend, generated from
the facts, next to the model `holon.gen.model` generates from the same facts. Python never evaluates a
model function: holon.model_native encodes jobs as an instruction stream, the binary runs them on the
compiled model, and Python decodes the values it writes.

Files (generate(facts_path) -> {name: text}, byte-identical across calls):
  <model>.bend   the model, exactly holon.gen.model.generate(facts, facts_sha256)
  driver.bend    `import ./<model>.bend as M` plus the evaluator and `main`

The driver uses only Base effects (IO.args, File.open/size/read_bytes/write_bytes/close): no foreign
import, no hole, no @unsafe, no `!` (clang 18 cannot build `!` calls, BUILD_PLAN §1.4).

Instruction stream (the file named by argv[1]): pairs of bytes (op, arg), run left to right by one
structural recursion over the list.
  (0, b)  append byte b to the literal buffer
  (1, 0)  push the buffer as Bytes, clear it
  (2, 0)  push the buffer as a Header (exactly the header width, else an error value), clear it
  (3, k)  push environment slot k            (4, 0)  pop into the next environment slot
  (5, f)  call fact function f (FUNCTIONS order) on the popped value
  (6, i)  header field i (facts field order) of the popped value
  (7, 0)  some(popped value)                 (8, 0)  pop and write the value to the output
  (9, 0)  end of job: clear stack and environment, write the job marker
A value of the wrong shape for a step becomes the error value (written as an error, like eval.mjs's
{"error": msg}); an unknown op writes the error marker too.

Output (the file named by argv[2]): tagged values. A cell list is its cells (c < 254 as one byte,
anything else as 254 then four big-endian bytes, so 0xDEAD survives) closed by 255.
  1 cells: Bytes   2 b: Bool (b in {0, 1})   3 {10 cells}* 11: Fields   4: None
  5 {10 cells}* 11: Some(Fields)   6 cells: Header   7: error   9: end of job
"""
from __future__ import annotations

from pathlib import Path

from .. import facts as F
from . import model as G

DRIVER = "driver.bend"

# Op codes of the instruction stream (shared with holon.model_native).
OP_BYTE, OP_BYTES, OP_HDR, OP_LOAD, OP_STORE, OP_CALL, OP_FIELD, OP_SOME, OP_EMIT, OP_END = range(10)
# Output tags.
T_BYTES, T_BOOL, T_FIELDS, T_NONE, T_SOME, T_HDR, T_ERR, T_END = 1, 2, 3, 4, 5, 6, 7, 9
T_ITEM, T_CLOSE, ESC, EOL = 10, 11, 254, 255

# IR type -> (Val constructor, Bend type of its payload)
VAL = {"Bytes": "VBytes", "Header": "VHdr", "Bool": "VBool", "Fields": "VFields", "MaybeFields": "VMaybe"}


class Unsupported(ValueError):
    pass


def model_file(facts_path) -> str:
    from ..model_eval import model_name
    return f"{model_name(facts_path)}.bend"


def functions(facts: dict) -> list[str]:
    """Fact functions the driver can call, in a fixed order (the op argument of a call is the index)."""
    out = sorted(facts["functions"])
    if len(out) > 255:
        raise Unsupported("more than 255 fact functions")
    return out


def fields(facts: dict) -> list[str]:
    out = [f["name"] for f in F.header_fields(facts)]
    if len(out) > 255:
        raise Unsupported("more than 255 header fields")
    return out


def _nat_cases(n: int) -> list[str]:
    return [f"{i}n" for i in range(n)] + [f"{n}n+p"]


def _hdr_cells(facts: dict) -> list[str]:
    return G.cell_names(facts)


def _gen(facts: dict, model: str) -> str:
    cells = _hdr_cells(facts)
    fns = functions(facts)
    flds = fields(facts)
    L: list[str] = [
        "# GENERATED by holon.gen.cdriver from facts; do not edit (fix the generator instead).",
        "# The native driver of the model: evaluates IR jobs read from argv[1], writes values to argv[2].",
        "import Base",
        f"import ./{model} as M",
        "",
        "type Val is Data:",
        "  VBytes{bs: List<&2, U32>}",
        "  VHdr{h: M.Hdr}",
        "  VBool{b: Bool}",
        "  VFields{fs: List<&2, List<&2, U32>>}",
        "  VMaybe{m: Maybe<&2, List<&2, List<&2, U32>>>}",
        "  VErr{}",
        "",
        "type St is Data:",
        "  St{buf: List<&2, U32>, stk: List<&2, Val>, env: List<&2, Val>, out: List<&2, U32>}",
        "",
    ]
    # header from its cells (in declaration order); any other length is an error value
    pat = "".join(f"Con{{{c}, " for c in cells) + "Nil{}" + "}" * len(cells)
    L += ["def header_of(b: List<&2, U32>) -> Val:", "  match b:", f"    case {pat}:",
          "      VHdr{M.Hdr{" + ", ".join(cells) + "}}", "    case _:", "      VErr{}", ""]
    L += ["def hdr_cells(h: M.Hdr) -> List<&2, U32>:", "  match h:",
          "    case M.Hdr{" + ", ".join(cells) + "}:", "      [" + ", ".join(cells) + "]", ""]
    # output: cells as bytes, with an escape for values >= 254
    L += [
        "def put_cell_if(small: Bool, +c: U32, out: List<&2, U32>) -> List<&2, U32>:",
        "  match small:",
        "    case True{}:",
        "      Con{c, out}",
        "    case False{}:",
        f"      Con{{U32.and(c, 255), Con{{U32.and(U32.shrn(c, 8n), 255), Con{{U32.and(U32.shrn(c, 16n), 255), "
        f"Con{{U32.shrn(c, 24n), Con{{{ESC}, out}}}}}}}}}}",
        "",
        "def put_cell(+c: U32, out: List<&2, U32>) -> List<&2, U32>:",
        f"  put_cell_if(U32.is_lt(c, {ESC}), c, out)",
        "",
        "def put_cells(bs: List<&2, U32>, out: List<&2, U32>) -> List<&2, U32>:",
        "  match bs:",
        "    case Nil{}:",
        f"      Con{{{EOL}, out}}",
        "    case Con{c, t}:",
        "      put_cells(t, put_cell(c, out))",
        "",
        "def put_fields(fs: List<&2, List<&2, U32>>, out: List<&2, U32>) -> List<&2, U32>:",
        "  match fs:",
        "    case Nil{}:",
        f"      Con{{{T_CLOSE}, out}}",
        "    case Con{f, t}:",
        f"      put_fields(t, put_cells(f, Con{{{T_ITEM}, out}}))",
        "",
        "def put_bool(b: Bool, out: List<&2, U32>) -> List<&2, U32>:",
        "  match b:",
        "    case True{}:",
        f"      Con{{1, Con{{{T_BOOL}, out}}}}",
        "    case False{}:",
        f"      Con{{0, Con{{{T_BOOL}, out}}}}",
        "",
        "def put_maybe(m: Maybe<&2, List<&2, List<&2, U32>>>, out: List<&2, U32>) -> List<&2, U32>:",
        "  match m:",
        "    case None{}:",
        f"      Con{{{T_NONE}, out}}",
        "    case Some{fs}:",
        f"      put_fields(fs, Con{{{T_SOME}, out}})",
        "",
        "def put_val(v: Val, out: List<&2, U32>) -> List<&2, U32>:",
        "  match v:",
        "    case VBytes{bs}:",
        f"      put_cells(bs, Con{{{T_BYTES}, out}})",
        "    case VHdr{h}:",
        f"      put_cells(hdr_cells(h), Con{{{T_HDR}, out}})",
        "    case VBool{b}:",
        "      put_bool(b, out)",
        "    case VFields{fs}:",
        f"      put_fields(fs, Con{{{T_FIELDS}, out}})",
        "    case VMaybe{m}:",
        "      put_maybe(m, out)",
        "    case VErr{}:",
        f"      Con{{{T_ERR}, out}}",
        "",
    ]
    # one adapter per fact function: the argument's shape is checked, the model computes
    for fn in fns:
        arg_t, res_t = F.fn_types(facts, fn)
        if arg_t not in ("Header", "Bytes") or res_t not in VAL:
            raise Unsupported(f"{fn}: {arg_t} -> {res_t}")
        L += [f"def call_{fn}(v: Val) -> Val:", "  match v:", f"    case {VAL[arg_t]}{{x}}:",
              f"      {VAL[res_t]}{{M.{fn}(x)}}", "    case _:", "      VErr{}", ""]
    L += ["def call_at(f: Nat, v: Val) -> Val:", "  match f:"]
    for i, pat in enumerate(_nat_cases(len(fns))):
        L += [f"    case {pat}:", f"      call_{fns[i]}(v)" if i < len(fns) else "      VErr{}"]
    L.append("")
    for name in flds:
        L += [f"def field_{name}(v: Val) -> Val:", "  match v:", "    case VHdr{h}:",
              f"      VBytes{{M.get_{name}(h)}}", "    case _:", "      VErr{}", ""]
    L += ["def field_at(i: Nat, v: Val) -> Val:", "  match i:"]
    for i, pat in enumerate(_nat_cases(len(flds))):
        L += [f"    case {pat}:", f"      field_{flds[i]}(v)" if i < len(flds) else "      VErr{}"]
    L.append("")
    L += [
        "def some_of(v: Val) -> Val:",
        "  match v:",
        "    case VFields{fs}:",
        "      VMaybe{Some{fs}}",
        "    case _:",
        "      VErr{}",
        "",
        "def env_get(env: List<&2, Val>, k: Nat) -> Val:",
        "  match env k:",
        "    case Nil{} _:",
        "      VErr{}",
        "    case Con{v, t} 0n:",
        "      v",
        "    case Con{v, t} 1n+p:",
        "      env_get(t, p)",
        "",
        "# the value on top of the stack, or the error value on an empty stack",
        "def top(stk: List<&2, Val>) -> Val:",
        "  match stk:",
        "    case Nil{}:",
        "      VErr{}",
        "    case Con{v, t}:",
        "      v",
        "",
        "def rest(stk: List<&2, Val>) -> List<&2, Val>:",
        "  match stk:",
        "    case Nil{}:",
        "      Nil{}",
        "    case Con{v, t}:",
        "      t",
        "",
        "def step_at(op: Nat, +arg: U32, +buf: List<&2, U32>, +stk: List<&2, Val>, +env: List<&2, Val>, "
        "+out: List<&2, U32>) -> St:",
        "  match op:",
        f"    case {OP_BYTE}n:",
        "      St{Con{arg, buf}, stk, env, out}",
        f"    case {OP_BYTES}n:",
        "      St{Nil{}, Con{VBytes{List.reverse(&2, U32, buf)}, stk}, env, out}",
        f"    case {OP_HDR}n:",
        "      St{Nil{}, Con{header_of(List.reverse(&2, U32, buf)), stk}, env, out}",
        f"    case {OP_LOAD}n:",
        "      St{buf, Con{env_get(env, U32.to_nat(arg)), stk}, env, out}",
        f"    case {OP_STORE}n:",
        "      St{buf, rest(stk), List.append(&2, Val, env, [top(stk)]), out}",
        f"    case {OP_CALL}n:",
        "      St{buf, Con{call_at(U32.to_nat(arg), top(stk)), rest(stk)}, env, out}",
        f"    case {OP_FIELD}n:",
        "      St{buf, Con{field_at(U32.to_nat(arg), top(stk)), rest(stk)}, env, out}",
        f"    case {OP_SOME}n:",
        "      St{buf, Con{some_of(top(stk)), rest(stk)}, env, out}",
        f"    case {OP_EMIT}n:",
        "      St{buf, rest(stk), env, put_val(top(stk), out)}",
        f"    case {OP_END}n:",
        f"      St{{Nil{{}}, Nil{{}}, Nil{{}}, Con{{{T_END}, out}}}}",
        f"    case {OP_END + 1}n+p:",
        f"      St{{buf, stk, env, Con{{{T_ERR}, out}}}}",
        "",
        "def step(op: Nat, +arg: U32, st: St) -> St:",
        "  match st:",
        "    case St{+buf, +stk, +env, +out}:",
        "      step_at(op, arg, buf, stk, env, out)",
        "",
        "# run the instruction stream: one structural recursion over its (op, arg) pairs",
        "def run(prog: List<&2, U32>, st: St) -> St:",
        "  match prog:",
        "    case Nil{}:",
        "      st",
        "    case Con{op, Nil{}}:",
        f"      step({OP_END + 1}n, 0, st)",
        "    case Con{op, Con{arg, t}}:",
        "      run(t, step(U32.to_nat(op), arg, st))",
        "",
        "def output(st: St) -> List<&2, U32>:",
        "  match st:",
        "    case St{buf, stk, env, out}:",
        "      List.reverse(&2, U32, out)",
        "",
        "def eval(prog: List<&2, U32>) -> List<&2, U32>:",
        "  output(run(prog, St{Nil{}, Nil{}, Nil{}, Nil{}}))",
        "",
        "def wrote(pair: File & Result<&1, &1, U32 & String, Unit>) -> IO(File):",
        "  (file, result) = pair",
        "  do IO<File>:",
        "    IO.pass(Unit, result)",
        "    return file",
        "",
        "def read_got(pair: File & Result<&1, &1, U32 & String, List<&2, U32>>) -> IO(List<&2, U32>):",
        "  (file, result) = pair",
        "  do IO<List<&2, U32>>:",
        "    xs : List<&2, U32> <- IO.pass(List<&2, U32>, result)",
        "    File.close(file)",
        "    return xs",
        "",
        "def read_sized(pair: File & Result<&1, &1, U32 & String, U32>) -> IO(List<&2, U32>):",
        "  (file, result) = pair",
        "  do IO<List<&2, U32>>:",
        "    n : U32 <- IO.pass(U32, result)",
        "    r : File & Result<&1, &1, U32 & String, List<&2, U32>> <- File.read_bytes(file, n)",
        "    read_got(r)",
        "",
        "def read_all(f: File) -> IO(List<&2, U32>):",
        "  do IO<List<&2, U32>>:",
        "    p : File & Result<&1, &1, U32 & String, U32> <- File.size(f)",
        "    read_sized(p)",
        "",
        "def serve(inp: String, outp: String) -> IO(Unit):",
        "  do IO<Unit>:",
        "    f : File <- IO.try(File, File.open(inp, \"r\"))",
        "    prog : List<&2, U32> <- read_all(f)",
        "    g : File <- IO.try(File, File.open(outp, \"w\"))",
        "    w : File & Result<&1, &1, U32 & String, Unit> <- File.write_bytes(g, eval(prog))",
        "    g : File <- wrote(w)",
        "    File.close(g)",
        "",
        "def serve_args(xs: List<String>) -> IO(Unit):",
        "  match xs:",
        "    case Con{prog, Con{inp, Con{outp, Nil{}}}}:",
        "      serve(inp, outp)",
        "    case _:",
        "      IO.die(Unit, 2, \"usage: driver JOBS OUT\")",
        "",
        "def main() -> IO(Unit):",
        "  do IO<Unit>:",
        "    xs : List<String> <- IO.args()",
        "    serve_args(xs)",
    ]
    return "\n".join(L) + "\n"


def generate(facts_path) -> dict[str, str]:
    """{file name: text}: the model and its native driver, a pure function of the facts file."""
    facts_path = Path(facts_path)
    facts = F.load(facts_path)
    sha = F.sha256_file(facts_path)
    model = model_file(facts_path)
    if model == DRIVER:
        raise Unsupported(f"the model file name {model} collides with the driver")
    return {model: G.generate(facts, sha), DRIVER: _gen(facts, model)}
