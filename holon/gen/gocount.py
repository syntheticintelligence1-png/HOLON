"""Deciding the laws of a Go count component (BUILD_PLAN row I90 = I38b; whitepaper §7.6, §5.1 PAR; the contract is
rules C4-C6 of the docstring of tests_m3/test_go_counts.py; the component itself is holon.diagram.gocount).

The model gen/<M>/model/<component>.bend, generated from the count document alone (generate):

  * the carrier's model is a parameter's length, a Nat (parametric counts): no channel reads an element's value, so no
    per-element cell is modelled;
  * a channel <name>(n: Nat) -> Nat is the count its field records after one call of its function on a parameter of
    length n, from the receiver's zero value: an item channel n (its field holds n items of its width); a wrap channel
    of width w U32.to_nat(U32.and(U32.from_nat(n), 2^w - 1)), which is n mod 2^w for every n since 2^w divides 2^32
    (Base's unary Nat.divmod runs out of BendTT's fuel well below the lengths these laws need; the U32 round trip does
    not);
  * eq_count and is_true are the counter-laws' equality and motive, untrusted (BEND_PRIMER 5.4).

Deciding (decide): a law's claim must be two channels of the component applied to its one binder, else it is UNKNOWN
unsearched. Its candidates are 2^w for each distinct wrap width w of the two channels, ascending, then 0. A law is
REFUTED at the first candidate whose counter-law Bend accepts; the record's difference is the compiled model's
evaluation at it (holon/js/linked.mjs). Else UNKNOWN: no proof generator covers a law over counts here. Nothing here
names a target: every constant (the widths, the candidates) is read from the document.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from .. import bend

ALIAS = "M"
ROOT = Path(__file__).resolve().parents[2]
DRIVER = ROOT / "holon" / "js" / "linked.mjs"   # evaluates calls on a compiled model (shared with holon.gen.linked)
NAT_LITERAL_MAX = (1 << 32) - 1                 # BEND_PRIMER 4: Nat literals work up to 4294967295n
KINDS = ("item", "wrap")
PRELUDE_DEFS = ("eq_count", "is_true")


class Unsupported(Exception):
    """A document or statement form this generator cannot express faithfully (the law stays UNKNOWN)."""


# ====================================================================== the model (C4)
PRELUDE = '''def eq_count(a: Nat, b: Nat) -> Bool:
  Nat.is_eq(a, b)

def is_true(b: Bool) -> Type:
  match b:
    case True{}:
      Unit
    case False{}:
      Empty
'''


def check_channel(name: str, c: dict) -> None:
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name) or name in PRELUDE_DEFS:
        raise Unsupported(f"channel name {name!r}")
    w = c.get("width")
    if c.get("kind") not in KINDS or not isinstance(w, int) or isinstance(w, bool) or w < 1:
        raise Unsupported(f"channel {name}: kind {c.get('kind')!r} width {w!r}")
    if c["kind"] == "wrap" and w > 32:
        raise Unsupported(f"channel {name}: a wrap width above 32 bits")


def channel_text(name: str, c: dict) -> str:
    check_channel(name, c)
    head = (f"# {name}: {c['kind']} channel of {c['param']} in {c['field']} ({c['width']}"
            + (" bytes per item" if c["kind"] == "item" else " bits") + f"; store {c.get('site')})")
    if c["kind"] == "item":
        body = "  n"
    else:
        body = f"  U32.to_nat(U32.and(U32.from_nat(n), {(1 << c['width']) - 1}))"
    return "\n".join([head, f"def {name}(n: Nat) -> Nat:", body, ""])


def generate(doc: dict, sha: str) -> str:
    """The component model (rule C4)."""
    head = [f"# GENERATED by holon.gen.gocount from the count document {doc['component']} (sha256 {sha}); do not edit.",
            "import Base", "", PRELUDE]
    body = [channel_text(name, c) for name, c in sorted(doc["channels"].items())]
    return "\n".join(head) + "\n" + "\n".join(body)


def value(c: dict, n: int) -> int:
    """A channel's count at length n, written out as the model states it (for the record's cross-check only)."""
    check_channel("channel", c)
    return n if c["kind"] == "item" else n % (1 << c["width"])


class CompiledModel:
    """A component model compiled with the pinned Bend to an ES module (cached by the text's hash)."""

    def __init__(self, source: Path, artifact: Path, doc: dict, cfg: dict | None):
        self.source, self.artifact, self.doc, self.cfg = source, artifact, doc, cfg

    @classmethod
    def build(cls, doc: dict, sha: str, name: str, cfg: dict | None = None) -> "CompiledModel":
        text = generate(doc, sha)
        h = hashlib.sha256(text.encode()).hexdigest()
        src = bend.build_dir(ROOT) / "gocount" / h[:16] / f"{name}.bend"
        src.parent.mkdir(parents=True, exist_ok=True)
        if not src.exists() or src.read_text() != text:
            src.write_text(text)
        art = src.with_suffix(".mjs")
        stamp = src.with_suffix(".src.sha256")
        if not (art.exists() and stamp.exists() and stamp.read_text() == h):
            r = bend.run([src.name, "-o", art.name], cwd=src.parent, cfg=cfg)
            if r.code != 0 or not art.exists():
                raise RuntimeError(f"bend failed to compile {src}: {r.out[:2000]}")
            stamp.write_text(h)
        return cls(src, art, doc, cfg)

    def calls(self, exprs: list) -> list:
        """The compiled model's values of calls (holon/js/linked.mjs): untrusted, like every evaluation; Bend decides."""
        if not exprs:
            return []
        node = (self.cfg or bend.config()).get("node", "node")
        p = subprocess.run([node, f"--stack-size={max(bend.js_stack_bytes(self.cfg) // 1024, 984)}", str(DRIVER)],
                           input=json.dumps({"module": str(self.artifact), "calls": exprs}), capture_output=True,
                           text=True, timeout=1800)
        if p.returncode != 0:
            raise RuntimeError(f"node evaluation failed: {p.stderr[-2000:]}")
        return json.loads(p.stdout)["results"]

    def values(self, names: list[str], ns: list[int]) -> dict[str, list[int]]:
        """{channel: [its count at each length]} by the compiled model."""
        exprs = [{"fn": c, "args": [{"val": {"nat": str(n)}}]} for c in names for n in ns]
        res = self.calls(exprs)
        out, k = {}, 0
        for c in names:
            row = []
            for _ in ns:
                r = res[k]
                k += 1
                if not isinstance(r, int) or isinstance(r, bool):
                    raise RuntimeError(f"the compiled model's {c} gave {str(r)[:200]}")
                row.append(r)
            out[c] = row
        return out


# ====================================================================== laws
@dataclass
class Emitted:
    name: str
    text: str
    binder: str
    lhs: str
    rhs: str
    channels: list            # the two channels the claim names, in claim order


def law_name(law_id: str, counter: bool = False) -> str:
    return ("cl_" if counter else "") + law_id.lower()


def _side(doc: dict, t, binder: str) -> str:
    if isinstance(t, dict) and set(t) == {"call", "args"} and t["args"] == [{"var": binder}] \
            and t["call"] in doc["channels"]:
        return t["call"]
    raise Unsupported(f"a claim side {t!r} is not a channel of the component over the binder")


def emit(law: dict, doc: dict, model_import: str, counter: bool = False, note: str = "") -> Emitted:
    """LAWS.bend of a count law, or its counter-law (the exs form of BEND_PRIMER 5.4)."""
    st = law["statement"]
    bs = st.get("binders") or []
    if len(bs) != 1 or bs[0].get("q") != "forall" or bs[0].get("type") != doc["carrier"]["id"] or st.get("assume"):
        raise Unsupported("a count law has one forall binder over the carrier and no premise")
    if set(st.get("claim") or {}) != {"eq"} or len(st["claim"]["eq"]) != 2:
        raise Unsupported("a count law states one equation")
    b = bs[0]["name"]
    if not re.fullmatch(r"[a-z_][A-Za-z0-9_]*", b):
        raise Unsupported(f"binder name {b!r}")
    a, c = (_side(doc, x, b) for x in st["claim"]["eq"])
    for n in (a, c):
        check_channel(n, doc["channels"][n])
    lhs, rhs = f"{ALIAS}.{a}({b})", f"{ALIAS}.{c}({b})"
    name = law_name(law["law_id"], counter)
    q, pre = ("exs", "") if counter else ("for", "+")
    lines = ["# GENERATED by holon.gen.gocount from the frozen law IR; do not edit.",
             f"# law_id: {law['law_id']}   statement_hash: {note}", "import Base", f"import {model_import} as {ALIAS}",
             "", f"law {name}:", f"  {q} {pre}{b}: Nat", f"  {{{lhs} {'!=' if counter else '=='} {rhs} : Nat}}"]
    return Emitted(name, "\n".join(lines) + "\n", b, lhs, rhs, [a, c])


def nat_literal(n: int) -> str:
    """A Nat as a Bend term: a literal up to 4294967295n, else a sum of literals."""
    if not isinstance(n, int) or isinstance(n, bool) or n < 0:
        raise Unsupported(f"a count {n!r}")
    if n <= NAT_LITERAL_MAX:
        return f"{n}n"
    return f"Nat.add({NAT_LITERAL_MAX}n, {nat_literal(n - NAT_LITERAL_MAX)})"


HEADER = ["# GENERATED by holon.gen.gocount; untrusted, accepted only if Bend checks it.", "import Base"]


def counter_proof(em: Emitted, model_import: str, n: int) -> str:
    """The counter-law's proof at a concrete length (BEND_PRIMER 5.4), its motive the model's equality at the lhs."""
    w = nat_literal(n)
    at_lhs = re.sub(rf"(?<![\w.]){re.escape(em.binder)}(?![\w])", lambda _m: w, em.lhs)
    lines = HEADER + [f"import {model_import} as {ALIAS}", "import ./LAWS.bend as Laws", "",
                      "# class counter: a concrete length; the motive is Unit at the lhs and Empty at the rhs",
                      f"def Laws.{em.name}():", f"  ({w}, e => (%e : {ALIAS}.is_true({ALIAS}.eq_count(_, {at_lhs}))",
                      "  Unit{}))"]
    return "\n".join(lines) + "\n"


@dataclass
class Decision:
    status: str
    em: Emitted | None = None
    statement: Emitted | None = None
    check: object = None
    witness: dict | None = None
    difference: dict | None = None
    bound: str | None = None
    attempts: list = field(default_factory=list)


def candidates(doc: dict, names: list[str]) -> list[int]:
    """Rule C5's candidates for a law over these channels: 2^w per distinct wrap width w, ascending, then 0."""
    return sorted({1 << doc["channels"][c]["width"] for c in names if doc["channels"][c]["kind"] == "wrap"}) + [0]


def decide(law: dict, cm: CompiledModel, ld: Path, pd: Path, model_import_l: str, model_import_p: str, cfg: dict,
           shash: str, write_pair, accepted) -> Decision:
    """Rule C5. Every status is Bend's: REFUTED only through a LAWS.bend / PROOF.bend pair Bend accepts."""
    doc = cm.doc
    try:
        stmt = emit(law, doc, model_import_l, note=shash)
        cem = emit(law, doc, model_import_l, counter=True, note=shash)
    except Unsupported as e:
        return Decision("UNKNOWN", attempts=[{"kind": "emit", "error": f"unsupported statement form: {e}"}],
                        bound="not searched: the emitter cannot express this statement faithfully (rule C5)")
    attempts, tried = [], []
    for n in candidates(doc, cem.channels):
        tried.append(str(n))
        for x in {ld, pd}:
            shutil.rmtree(x, ignore_errors=True)
        try:
            proof = counter_proof(cem, model_import_p, n)
        except Unsupported as e:
            attempts.append({"kind": "refute", "candidate": n, "error": str(e)})
            continue
        pf = write_pair(ld, pd, cem.text, proof)
        rr = bend.check(pf, cfg)
        ok, why = accepted(rr, pf, ld / "LAWS.bend", cem, proof)
        attempts.append({"kind": "counter-law", "generator": "counter", "candidate": n, "exit_code": rr.code,
                         "marker": rr.marker, "seconds": rr.seconds, **({} if ok else {"error": why})})
        if ok:
            got = cm.values(cem.channels, [n])   # the record's difference is the compiled model's
            lhs, rhs = got[cem.channels[0]][0], got[cem.channels[1]][0]
            mirror = [value(doc["channels"][c], n) for c in cem.channels]
            if mirror != [lhs, rhs]:
                attempts.append({"kind": "mirror", "error": f"the generator's own reading {mirror} differs from the "
                                                             f"compiled model's {[lhs, rhs]}"})
            return Decision("REFUTED", em=cem, statement=stmt, check=rr, witness={cem.binder: n},
                            difference={"lhs": lhs, "rhs": rhs}, attempts=attempts)
    for x in {ld, pd}:
        shutil.rmtree(x, ignore_errors=True)
    return Decision("UNKNOWN", statement=stmt, attempts=attempts,
                    bound=(f"no candidate refutes it in the compiled model (candidate lengths: {', '.join(tried)}); no "
                           "proof generator covers a law over counts here (rule C5)"))


# ====================================================================== the ledger bundle (C6b)
def _slug(s: str) -> str:
    out = re.sub(r"[^A-Za-z0-9-]+", "-", s).strip("-")
    return out or "assumption"


TEXTS = {
    "A-gocount-length": "A channel's argument is the length of its parameter, a Nat (parametric counts): no channel "
                        "reads an element's value (an item channel appends one fixed-width item per element, a wrap "
                        "channel converts the length), so the parameter is modelled by its length alone; replay "
                        "concretizes a length n as n zero elements (rules C4, C7).",
    "A-gocount-receiver": "A channel is the count its field records after one call of its function on the receiver's "
                          "zero value (a wrap channel's field starts at 0, an item channel's field empty); the "
                          "function's other parameters are not modelled, and replay passes their zero values (rules "
                          "C4, C7).",
    "A-gocount-store": "A channel is one store fact of the Go document: a wrap store runs once per call and an item "
                       "store once per element of the range loop over the parameter; the function's paths, its other "
                       "stores to the field and its panics are not read (rule C1)."}


def declared_bundle(doc: dict, rel: str, sha: str, root: Path) -> dict:
    """The ledger bundle of a count model (holon.records; rule C6b): every assumption the Go document declares, each
    introduced by the channels' definitions, and the model's own A-gocount-length, A-gocount-receiver and
    A-gocount-store, each introduced by every channel's definition. The prelude's equality and motive are the one
    no_assumption group."""
    chans = sorted(doc["channels"])
    drel = doc["document"]
    try:
        src = json.loads((Path(root) / drel).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        src = {}
    entries, seen = [], set(TEXTS)
    for i, a in enumerate(src.get("assumptions") or []):
        if not isinstance(a, dict) or not isinstance(a.get("id"), str):
            continue
        aid = _slug(a["id"])
        while aid in seen:
            aid += "-2"
        seen.add(aid)
        entries.append({"id": aid, "kind": "abstraction", "source": f"{drel}#/assumptions/{i}",
                        "text": a.get("text", ""), "introduced_by": chans})
    for k in sorted(TEXTS):
        entries.append({"id": k, "kind": "abstraction", "source": f"{rel}#/channels", "text": TEXTS[k],
                        "introduced_by": chans})
    return {"facts": rel, "facts_sha256": sha, "model": f"model/{doc['component']}",
            "doc": "The model of a count document (holon.gen.gocount): the assumptions its Go document declares, and the "
                   "count model's own (generated from the document, never hand-written).",
            "entries": entries,
            "no_assumption": [{"defs": list(PRELUDE_DEFS), "why": "the counter-laws' equality and motive of the "
                                                                  "generator prelude; no modelling choice"}]}
