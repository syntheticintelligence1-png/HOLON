def files() -> dict[str, str]:
    """The fixed texts by their path under the output directory."""
    return {LAWS_FILE: CORE_LAWS_TEXT, PROOF_FILE: CORE_PROOF_TEXT, LEAN_FILE: LEAN_TEXT}


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


class Refused(RuntimeError):
    """A checker is missing: nothing is written."""


def laws_of(laws_text: str) -> list[str]:
    """The laws a LAWS.bend declares, in order (comments removed as Bend removes them)."""
    return re.findall(r"(?m)^law\s+(\w+)\s*:", bend.strip_comments(laws_text))


def filled(proof_text: str, laws: list[str]) -> list[str]:
    """The laws of `laws` that the proof file fills with a top-level def <alias>.<law>(, <alias> being the alias it
    imports ./LAWS.bend under."""
    m = re.search(r"(?m)^import \./LAWS\.bend as (\w+)\s*$", proof_text)
    if not m:
        return []
    alias = re.escape(m.group(1))
    code = bend.strip_comments(proof_text)
    return sorted(n for n in laws if re.search(rf"(?m)^def {alias}\.{re.escape(n)}\(", code))


def kernels(cfg_root: Path) -> dict:
    """Check the three texts with both Bend kernels and Lean in a scratch directory; the report's "files" part.
    Raises Refused when bend, bend --verdict or Lean is missing."""
    cfg = bend.config(cfg_root)
    if not bend.verdict_available():
        raise Refused("bend --verdict (BendTT) needs Lean, which is not on PATH")
    laws = laws_of(CORE_LAWS_TEXT)
    with tempfile.TemporaryDirectory(prefix="holon-theory2-") as tmp:
        tmp = Path(tmp)
        for rel, text in files().items():
            (tmp / rel).parent.mkdir(parents=True, exist_ok=True)
            (tmp / rel).write_text(text, encoding="utf-8")
        proof = tmp / PROOF_FILE
        try:
            b = bend.check(proof, cfg)
            v = bend.check_verdict(proof, cfg)
        except FileNotFoundError as e:
            raise Refused(str(e)) from None
        fills = filled(CORE_PROOF_TEXT, laws)
        complete = fills == sorted(laws) and bool(laws)
        bres = "checked" if b.ok and complete else "rejected"
        vres = "checked" if v.ok and complete else "rejected"
        lcfg = lean.config(cfg_root)
        r = lean.check_text(LEAN_TEXT, tmp / "lean-check", expect=list(LEAN_THEOREMS), cfg=lcfg)
        if r["result"] == "unavailable":
            raise Refused(f"Lean is unavailable: {r['out'].strip()[:300]}")
    audited = sorted(t for t, ax in r["theorems"].items() if ax is not None)
    return {PROOF_FILE: {"sha256": sha256_text(CORE_PROOF_TEXT), "bend": bres, "verdict": vres, "laws": fills},
            LEAN_FILE: {"sha256": sha256_text(LEAN_TEXT), "lean": r["result"], "axioms": r["axioms"],
                        "theorems": audited}}


def report(cfg_root: Path) -> str:
    return dumps({"report_version": REPORT_VERSION, "files": kernels(cfg_root)})


def owned_files(out: Path) -> dict[str, bytes]:
    """Every file under <out>/core and <out>/lean, by its path under out."""
    res = {}
    for d in OWNED_DIRS:
        base = out / d
        if base.is_dir():
            for p in sorted(base.rglob("*")):
                if p.is_file() or p.is_symlink():
                    res[p.relative_to(out).as_posix()] = p.read_bytes() if p.is_file() else b""
    return res


def write(out: Path, report_text: str | None) -> None:
    want = files()
    for rel in owned_files(out):
        if rel not in want:
            (out / rel).unlink()
    for d in OWNED_DIRS:  # empty directories left by removed files
        base = out / d
        if base.is_dir():
            for p in sorted(base.rglob("*"), key=lambda q: len(q.parts), reverse=True):
                if p.is_dir() and not any(p.iterdir()):
                    p.rmdir()
    for rel, text in want.items():
        p = out / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.is_file() or p.read_text(encoding="utf-8") != text:
            p.write_text(text, encoding="utf-8")
    if report_text is not None:
        p = out / REPORT
        if not p.is_file() or p.read_text(encoding="utf-8") != report_text:
            p.write_text(report_text, encoding="utf-8")


def differences(out: Path, report_text: str | None) -> list[str]:
    """What --check finds: owned files that differ from a fresh build, are missing or are extra."""
    want = {rel: text.encode("utf-8") for rel, text in files().items()}
    have = owned_files(out)
    diff = [f"{rel}: {'missing' if rel not in have else 'extra' if rel not in want else 'differs'}"
            for rel in sorted(set(want) | set(have)) if want.get(rel) != have.get(rel)]
    if report_text is not None:
        p = out / REPORT
        if not p.is_file():
            diff.append(f"{REPORT}: missing")
        elif p.read_bytes() != report_text.encode("utf-8"):
            diff.append(f"{REPORT}: differs")
    return diff


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="holon theory2", description=__doc__.split("\n", 1)[0])
    ap.add_argument("--milestone", required=True)
    ap.add_argument("--root", default=None, help="repository root (default: this checkout)")
    ap.add_argument("--out", default=None, help="output directory (default: <root>/gen/M3/theory2)")
    ap.add_argument("--kernels", action="store_true", help="check the files with bend, bend --verdict and Lean, and "
                                                           "write report.json")
    ap.add_argument("--check", action="store_true", help="exit 1 if a file differs from a fresh build; write nothing")
    a = ap.parse_args(argv)
    if a.milestone != MILESTONE:
        print(f"{REFUSED} theory core II is emitted for {MILESTONE} only, not {a.milestone}", file=sys.stderr)
        return 2
    root = Path(a.root).resolve() if a.root else ROOT
    out = Path(a.out).resolve() if a.out else root / DEFAULT_OUT
    report_text = None
    if a.kernels:
        try:
            report_text = report(root)
        except Refused as e:
            print(f"{REFUSED} {e}", file=sys.stderr)
            return 2
    if a.check:
        diff = differences(out, report_text)
        for d in diff:
            print(f"holon theory2: {d}")
        if diff:
            return 1
        print(f"holon theory2: {out} is up to date")
        return 0
    write(out, report_text)
    print(f"holon theory2: wrote {out}" + (" (with report.json)" if report_text is not None else ""))
    if report_text is not None:
        rep = json.loads(report_text)["files"]
        print(f"  {PROOF_FILE}: bend {rep[PROOF_FILE]['bend']}, verdict {rep[PROOF_FILE]['verdict']}, "
              f"{len(rep[PROOF_FILE]['laws'])} laws filled")
        print(f"  {LEAN_FILE}: lean {rep[LEAN_FILE]['lean']}, axioms {rep[LEAN_FILE]['axioms']}, "
              f"{len(rep[LEAN_FILE]['theorems'])} theorems")
