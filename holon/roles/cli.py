"""`python -m holon roles` (I104; rules R1, R2, R4 and R5 of tests_m6/test_i104_roles.py).

Writes into --out-dir:
  roles.json        holon-roles/0.1: the inputs with their sha256, the proposal (sha256, proposer) in mode static+ai,
                    every role with roles_source and evidence, the dropped proposals, the rejected candidates, and the
                    sha256 of every sidecar written
  link.json         holon.frontends.link's sidecar (when a link role exists)
  go_ops.json       holon.diagram.goops's sidecar holon-go-ops/0.1 (when a component exists)
  go_laws.json      holon.gox.basis's sidecar holon-gox/0.1 (when a gox document exists), with its two companions
                    roles_compression.json (no compression role: enc null, so no premise) and, when the document's
                    extraction config is not under the root, roles_go_config.json (no primitives)
  derive_extracted.json   the adoption of every input (holon.diagram.linked's default adoption sidecar)
  sort_types.json, disch.json, undo.json, fact.json   the typed sidecars over the transitions documents, with no
                    hypothesis (I51's generic protocol values)
Paths inside the sidecars are relative to the root, as for a sidecar under spec/<M>/lib/.
--install copies each sidecar to <root>/spec/<M>/lib/ where none exists (a hand sidecar wins); --roles auto replaces
the role sidecars (link, go_ops, go_laws and its companions) there too, never the typed ones.
Exit 0 written; 2 refused (a document missing or unreadable, a malformed or model-naming proposal), nothing written.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import infer as I
from . import propose as P

VERSION = "holon-roles/0.1"
ROLE_SIDECARS = ("link.json", "go_ops.json", "go_laws.json", "roles_compression.json", "roles_go_config.json")
TYPED = ("sort_types.json", "disch.json", "undo.json", "fact.json", "derive_extracted.json")


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def _prov(r: dict) -> dict:
    return {"roles_source": r["roles_source"], "evidence": r["evidence"]}


def sidecars(milestone: str, res: dict, roles: list, dropped: list) -> dict:
    lib = f"spec/{milestone}/lib"
    out: dict = {}
    links = [r for r in roles if r["sidecar"] == "link"]
    if links:
        out["link.json"] = {"doc": f"Generated by holon roles (I104): link roles inferred from the documents (rules "
                                   f"link_tag_length, link_value) or proposed; each role carries roles_source and "
                                   f"evidence. No value is stated here.",
                            "roles": {r["id"]: {"solidity": r["solidity"], "go": r["go"], **_prov(r)} for r in links}}
    ops_doc = res.get("go_ops_document")
    comps = {}
    for r in [r for r in roles if r["sidecar"] == "go_ops"]:
        doc = r.get("document") or ops_doc
        if ops_doc is None:
            ops_doc = doc
        if doc != ops_doc:
            dropped.append({"sidecar": "go_ops", "id": r["id"], "reason": f"names {doc}, not the sidecar's {ops_doc}"})
            continue
        comps[r["id"]] = {"carrier": r["carrier"], "reach": r["reach"], **_prov(r)}
    if comps:
        out["go_ops.json"] = {"go_ops_version": "holon-go-ops/0.1", "document": ops_doc, "components": comps,
                              "doc": "Generated by holon roles (I104): Go-op components over every carrier type "
                                     "(rule go_ops_carrier) or proposed; reach is not inferred."}
    gox = res.get("gox")
    rec = [r for r in roles if r["sidecar"] == "go_laws" and "go" in r]
    if gox is None and rec:
        gox = {"document": rec[0]["go"]["document"], "config": None}
    if gox is not None:
        recompute = {}
        for r in rec:
            if r["go"]["document"] != gox["document"]:
                dropped.append({"sidecar": "go_laws", "id": r["id"],
                                "reason": f"names {r['go']['document']}, not the gox document {gox['document']}"})
                continue
            recompute[r["id"]] = {"go": r["go"], "solidity": r["solidity"], **_prov(r)}
        cfg = gox.get("config")
        if cfg is None:
            cfg = f"{lib}/roles_go_config.json"
            out["roles_go_config.json"] = {"doc": "Generated by holon roles (I104): the gox document's extraction "
                                                  "config is not under the root; no primitive is known.",
                                           "primitives": {}}
        out["roles_compression.json"] = {"doc": "Generated by holon roles (I104): no compression role is inferred, so "
                                                "no go_branch law takes a compression premise.", "codec": {"enc": None}}
        out["go_laws.json"] = {"gox_version": "holon-gox/0.1", "document": gox["document"], "config": cfg,
                               "compression": f"{lib}/roles_compression.json", "hypz_len": None,
                               "recompute": recompute,
                               "doc": "Generated by holon roles (I104): the gox document (rule gox_document) and the "
                                      "recompute roles (rule hash_store, or proposed). No value is stated here."}
    out["derive_extracted.json"] = {"derive_extracted_version": "holon-derive-extracted/0.1",
                                    "doc": "Generated by holon roles (I104): the adoption of every input document.",
                                    "documents": sorted(d.rel for d in res["docs"]), "reextraction": [],
                                    "width": False}
    trans = res.get("transitions") or []
    if trans:
        st = f"{lib}/sort_types.json"
        gen = "Generated by holon roles (I104): the typed sidecar over the transitions documents, with no hypothesis."
        out["sort_types.json"] = {"sort_types_version": "holon-sort-types/0.1", "doc": gen, "documents": trans,
                                  "seeds": "spec/M3/lib/sort_seeds.json", "binding": None,
                                  "search": dict(I.GENERIC_SEARCH)}
        out["disch.json"] = {"disch_version": "holon-disch/0.1", "doc": gen, "documents": trans, "binding": None,
                             "hypotheses": {}, "hypothesis_verdicts": None, "model_sidecar": st,
                             "r0": {"doc": "the zero storage (no deployment)", "keys": {}, "proxy_slots": [],
                                    "values": {}}, "search": dict(I.GENERIC_SEARCH)}
        out["undo.json"] = {"undo_version": "holon-undo/0.1", "doc": gen, "observation": ["status", "ret", "logs",
                                                                                         "calls"],
                            "premise": "nz", "search": dict(I.GENERIC_UNDO_SEARCH), "sort_types": st}
        out["fact.json"] = {"fact_version": "holon-fact/0.1", "doc": gen, "documents": trans, "binding": None,
                            "hypotheses": {}, "verdicts": {}, "sort_types": st,
                            "search": {**I.GENERIC_UNDO_SEARCH, "time_candidates":
                                       "E - 1, E and E + 1 for every term E an atom of a check of the candidate step "
                                       "compares with block.timestamp, evaluated on the candidate state, and the "
                                       "trace's own times (never 0, never decreasing)"},
                            "measure": {"fresh": ["0x" + "01" + "00" * 30 + "01", "0x" + "01" + "00" * 30 + "02"],
                                        "max_length": 3}, "term_size": "spec/M3/lib/term_size.json"}
    return out


def _goops_refusal(g, r: dict) -> str | None:
    """Why holon.diagram.goops refuses the proposed component (None: it builds)."""
    from ..diagram import goops as GO
    from ..diagram.linked import LinkedError, SidecarError
    if g is None:
        return "the Go document is not an input"
    try:
        GO.carrier_id(str(r.get("carrier")))
        GO.document(r["id"], {"carrier": r.get("carrier"), "reach": r.get("reach")}, g.rel, g.raw, g.doc)
    except (LinkedError, SidecarError, KeyError, TypeError) as e:
        return f"{type(e).__name__}: {str(e)[:160]}"
    return None


def build(root: Path, milestone: str, rels: list, mode: str, proposed: Path | None) -> dict:
    res = I.infer(root, rels)
    roles, dropped, prov = list(res["roles"]), [], None
    if mode == "static+ai" and proposed is not None:
        p, prov = P.read(proposed)
        prov = {"path": Path(proposed).name, **prov}
        roles, dropped = P.merge(roles, P.roles_of(p))
        docs = {d.rel: d for d in res["docs"]}
        kept = []
        for r in roles:
            if r["roles_source"] == "ai_proposal" and r["sidecar"] == "go_laws" and "go" in r:
                g = docs.get(r["go"]["document"])
                why = None if g is not None else "the Go document is not an input"
                for fn in (r["go"]["functions"] if g is not None else []):
                    why = why or I._recompute_refusal(root, g, I.go_config_of(root, g)[1], r["id"], fn,
                                                      r["solidity"].get("document"), r["solidity"].get("action"),
                                                      r["solidity"].get("store"))
                if why:
                    dropped.append({"sidecar": r["sidecar"], "id": r["id"], "reason": f"the producer refuses it: {why}"})
                    continue
            if r["roles_source"] == "ai_proposal" and r["sidecar"] == "go_ops":
                why = _goops_refusal(docs.get(r.get("document") or res.get("go_ops_document")), r)
                if why:
                    dropped.append({"sidecar": r["sidecar"], "id": r["id"], "reason": f"the producer refuses it: {why}"})
                    continue
            kept.append(r)
        roles = kept
    side = sidecars(milestone, res, roles, dropped)
    texts = {n: dumps(v) for n, v in sorted(side.items())}
    man = {"roles_version": VERSION, "milestone": milestone, "mode": mode,
           "inputs": [{"path": d.rel, "sha256": I.sha256_bytes(d.raw), "kind": d.kind} for d in res["docs"]],
           "proposed": prov, "roles": sorted(roles, key=lambda r: (r["sidecar"], r["id"])),
           "dropped": sorted(dropped, key=lambda d: (d["sidecar"], d["id"])),
           "rejected": sorted(res["rejected"], key=lambda r: (r["document"], r["carrier"])),
           "sidecars": {n: I.sha256_bytes(t.encode()) for n, t in texts.items()}}
    texts["roles.json"] = dumps(man)
    return texts


def install(root: Path, milestone: str, texts: dict, roles_mode: str) -> list:
    lib = Path(root) / "spec" / milestone / "lib"
    lib.mkdir(parents=True, exist_ok=True)
    done = []
    for n, t in sorted(texts.items()):
        if n == "roles.json":
            continue
        p = lib / n
        if p.exists() and not (roles_mode == "auto" and n in ROLE_SIDECARS):
            continue
        p.write_text(t)
        done.append(n)
    if roles_mode == "auto":
        for n in ROLE_SIDECARS:
            if n not in texts and (lib / n).exists() and n in ("link.json", "go_ops.json", "go_laws.json"):
                (lib / n).unlink()   # auto: a hand role sidecar with no generated counterpart is not used
                done.append(f"-{n}")
    return done


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="holon roles", description="infer the role sidecars of a target (I104)")
    ap.add_argument("--milestone", required=True)
    ap.add_argument("--root", default=".")
    ap.add_argument("--documents", required=True, help="comma-separated extracted documents, relative to --root")
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--mode", choices=("static", "static+ai"), default="static")
    ap.add_argument("--proposed", help="the proposal file (holon-roles-proposed/0.1), read in mode static+ai only")
    ap.add_argument("--install", action="store_true", help="also place the sidecars under <root>/spec/<M>/lib/")
    ap.add_argument("--roles", choices=("hand", "auto"), default="hand",
                    help="with --install: hand keeps every existing sidecar; auto replaces the role sidecars")
    a = ap.parse_args(argv)
    root = Path(a.root)
    rels = sorted({x for x in a.documents.split(",") if x})
    try:
        texts = build(root, a.milestone, rels, a.mode, Path(a.proposed) if a.proposed else None)
    except (I.RolesError, OSError) as e:
        print(f"holon roles: {e}", file=sys.stderr)
        return 2
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)
    for n, t in texts.items():
        (out / n).write_text(t)
    man = json.loads(texts["roles.json"])
    print(f"holon roles: {len(man['roles'])} roles ({', '.join(sorted(n for n in texts if n != 'roles.json'))}) "
          f"-> {out}")
    if a.install:
        print(f"holon roles: installed {install(root, a.milestone, texts, a.roles) or 'nothing'}")
    return 0
