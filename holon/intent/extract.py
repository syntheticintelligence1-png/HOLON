"""Extraction for the intent lane (key I55 design T2): the transitions document of the contract an atom documents, made
by the factory's Solidity frontend (holon.frontends.solidity, I17/I19) from a sidecar the lane generates.

The sidecar and the document are written under gen/M5/intent/facts/<contract>.{sidecar,extracted}.json. A control is
compiled from this checkout at its pinned bytes (target.commit null: no checkout check); a target file from the
checkout config/holon.json extract.sources names, at the atom's commit.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .common import GEN, dumps

_CONTRACT = re.compile(r"^\s*(?:abstract\s+)?(contract|library|interface)\s+([A-Za-z_][A-Za-z0-9_]*)")
SOLC_VERSION = "0.8.24"   # the factory's pinned compiler (config/holon.json replay.solc)


class ExtractFailed(Exception):
    pass


def contract_at(text: str, line: int) -> str | None:
    """The contract whose body holds 1-based `line`: the last contract header at or above it."""
    name = None
    for k, raw in enumerate(text.split("\n")[:line], start=1):
        m = _CONTRACT.match(raw)
        if m and m.group(1) == "contract":
            name = m.group(2)
        elif m:
            name = None
    return name


def sidecar(repo: str, commit, path: str, contract: str) -> dict:
    return {"sidecar_version": 1, "frontend": "solidity",
            "doc": "Generated by holon.intent.extract (I55): the transitions of the contract an intent clause documents.",
            "target": {"repo": repo, "commit": commit, "scope": f"intent lane: the transitions of {contract}"},
            "sources": [path],
            "compiler": {"version": SOLC_VERSION, "settings": {"evmVersion": "cancun", "optimizer": {"enabled": False}}},
            "transitions": {"contract": contract, "commit_interfaces": []},
            "output": f"{GEN}/facts/{contract}.extracted.json"}


def extract(root: Path, repo: str, commit, path: str, contract: str, source: Path, write: bool = True,
            problems: list | None = None) -> tuple[str, dict]:
    """(repo-relative path of the transitions document, the document); ExtractFailed with the frontend's reason.
    write=False (a --check): nothing is written; a sidecar or document that differs from the one on disk is a problem
    (the frontend reads the sidecar from disk, so a check runs on the committed sidecar)."""
    from ..frontends import ExtractionError, Refused
    from ..frontends.solidity import extract_document
    side = sidecar(repo, commit, path, contract)
    sp = root / GEN / "facts" / f"{contract}.sidecar.json"
    text = dumps(side)
    if write:
        sp.parent.mkdir(parents=True, exist_ok=True)
        sp.write_text(text, encoding="utf-8")
    elif not sp.is_file() or sp.read_text(encoding="utf-8") != text:
        if problems is not None:
            problems.append(str(sp))
        raise ExtractFailed(f"{sp} differs from the generated sidecar")
    try:
        doc = extract_document(side, sp, root, source=source)
    except (ExtractionError, Refused, ValueError, KeyError) as e:
        raise ExtractFailed(str(e).splitlines()[0][:300]) from None
    rel = side["output"]
    out = root / rel
    body = dumps(doc)
    if write:
        out.write_text(body, encoding="utf-8")
    elif not out.is_file() or out.read_text(encoding="utf-8") != body:
        if problems is not None:
            problems.append(str(out))
    return rel, json.loads(body)
