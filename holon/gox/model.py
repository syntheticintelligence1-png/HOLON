"""The Bend models of the Go part of rule PAR (I93; contract rules G8 and G9 of tests_m3/test_go_laws.py): for each law, a
module gen/<M>/gox/<law id>.bend, its LAWS.bend (the law, or the counter-law) and its PROOF.bend, all generated from the
basis element (holon.gox.basis).

  go_round_trip   byte cells as U32 variables, one per cell of each input value; enc the entry's cells, dec the decoder's
                  length test and reads; the law {dec(enc(x..)) == Some{[cells of v]}} is proved by reflexivity.
  go_branch       Go int as Nat; gb_ok(vars) = not(premises) or claim, the premises p's shared conditions, the size test,
                  q's other conditions and HypZ_len at the compressing call; the claim q's value equals p's. The
                  counter-law exhibits G9's witness and a counter-model length e = CB(|X|) and is proved by computation.
  go_recompute    bytes as U32 cells, lists for byte strings; pg the Go preimage (the loop's carried value folded over its
                  counted range), ps the Solidity preimage (its fixed prefix cells, then the loop's words as a list hc
                  with |hc| = 32 count); the counter-law shows no Solidity input meets the witness's Go preimage, by
                  cases on the count (a length argument).

Every name comes from the basis; nothing here names a target.
"""
from __future__ import annotations

import json
import re

NAT_OPS = {"+": "Nat.add", "-": "Nat.sub", "*": "Nat.mul"}
NAT_CMP = {"<=": "Nat.is_le", "<": "Nat.is_lt", ">": "Nat.is_gt", ">=": "Nat.is_ge", "==": "Nat.is_eq"}
HEADER = "# GENERATED by holon.gox.model from the law's basis element; do not edit.\n"


class ModelDebt(ValueError):
    """A term the model does not translate: the law is UNKNOWN, with this reason."""


def ident(*parts) -> str:
    s = "_".join(str(p) for p in parts)
    return re.sub(r"[^A-Za-z0-9_]", "_", s)


def law_name(lid: str, counter: bool = False) -> str:
    return ("cl_" if counter else "") + lid.lower()


LIB = '''def app(xs: List<&2, U32>, ys: List<&2, U32>) -> List<&2, U32>:
  match xs:
    case Nil{}:
      ys
    case Con{h, t}:
      Con{h, app(t, ys)}

def len(xs: List<&2, U32>) -> Nat:
  match xs:
    case Nil{}:
      0n
    case Con{_, t}:
      Nat.add(1n, len(t))

def take(n: Nat, xs: List<&2, U32>) -> List<&2, U32>:
  match n xs:
    case 0n _:
      Nil{}
    case 1n+p Nil{}:
      Nil{}
    case 1n+p Con{h, t}:
      Con{h, take(p, t)}

def drop(n: Nat, xs: List<&2, U32>) -> List<&2, U32>:
  match n xs:
    case 0n _:
      xs
    case 1n+p Nil{}:
      Nil{}
    case 1n+p Con{_, t}:
      drop(p, t)

def ite_nat(c: Bool, a: Nat, b: Nat) -> Nat:
  match c:
    case True{}:
      a
    case False{}:
      b

def is_true(b: Bool) -> Type:
  match b:
    case True{}:
      Unit
    case False{}:
      Empty

def is_false(b: Bool) -> Type:
  match b:
    case True{}:
      Empty
    case False{}:
      Unit
'''


# ====================================================================== Go terms -> Bend (Nat, Bool, lists)
class Tr:
    """Translates Go terms of one law; collects its variables in order of first use."""

    def __init__(self, call=None):
        self.vars: dict = {}       # name -> (kind, term) in first-use order; kind nat | bool | list
        self.call = call           # the go_branch compressing call [callee, [X]]

    def var(self, name: str, kind: str, term) -> str:
        if name not in self.vars:
            self.vars[name] = (kind, term)
        return name

    def leaf_name(self, t) -> str:
        if t[:1] == ["param"]:
            return ident(t[1])
        if t[:1] == ["field"] and isinstance(t[1], list):
            return ident(self.leaf_name(t[1]), t[2])
        raise ModelDebt(f"a leaf {json.dumps(t)[:80]}")

    def nat(self, t) -> str:
        if not isinstance(t, list) or not t:
            raise ModelDebt(f"a term {t!r}")
        tag = t[0]
        if tag == "const" and isinstance(t[1], int) and t[1] >= 0:
            return f"{t[1]}n"
        if tag == "op" and t[1] in NAT_OPS:
            a, b = self.nat(t[2]), self.nat(t[3])
            if t[1] == "*" and re.fullmatch(r"\d+n", a):
                a, b = b, a           # the symbolic factor first: Nat.mul recurses on its first argument
            if t[1] == "+" and re.fullmatch(r"\d+n", b):
                a, b = b, a           # the constant first: Nat.add recurses on its first argument
            return f"{NAT_OPS[t[1]]}({a}, {b})"
        if tag == "convert" and t[1] in ("int", "uint", "uint64", "int64"):
            return self.nat(t[2])
        if tag == "param" or tag == "field":
            return self.var("i_" + self.leaf_name(t), "nat", t)
        if tag == "len":
            return self.length(t[1])
        raise ModelDebt(f"a Nat term {json.dumps(t)[:100]}")

    def length(self, x) -> str:
        if isinstance(x, list) and x[:1] == ["append"]:
            return f"Nat.add({self.length(x[1])}, {self.length(x[2])})"
        if isinstance(x, list) and x[:1] == ["slice"]:
            if x[3] is not None:
                return f"Nat.sub({self.nat(x[3])}, {self.nat(x[2]) if x[2] is not None else '0n'})"
            return self.length(x[1])
        if isinstance(x, list) and x[:1] == ["alloc"] and x[2] is not None:
            return self.nat(x[2])
        if isinstance(x, list) and x[:1] == ["nil"]:
            return "0n"
        if isinstance(x, list) and x[:1] == ["result"] and self.call is not None \
                and x[1] == ["call", self.call[0], self.call[1]] and x[2] == 0:
            return self.var("e", "nat", ["len", x])
        if isinstance(x, list) and x[:1] in (["param"], ["field"]):
            return self.var("n_" + self.leaf_name(x), "nat", ["len", x])
        raise ModelDebt(f"a length of {json.dumps(x)[:100]}")

    def boolean(self, c) -> str:
        if isinstance(c, list) and c[:1] == ["bool"]:
            return "True{}" if c[1] else "False{}"
        if not (isinstance(c, list) and len(c) == 3):
            raise ModelDebt(f"a condition {json.dumps(c)[:100]}")
        op, a, b = c
        if op in ("==", "!=") and b == ["nil"] and isinstance(a, list) and a[:1] == ["result"] \
                and self.call is not None and a[1] == ["call", self.call[0], self.call[1]] and a[2] == 1:
            ok = self.var("ok", "bool", ["ok", a[1]])
            return ok if op == "==" else f"Bool.not({ok})"
        if op == "!=":
            return f"Bool.not(Nat.is_eq({self.nat(a)}, {self.nat(b)}))"
        if op in NAT_CMP:
            return f"{NAT_CMP[op]}({self.nat(a)}, {self.nat(b)})"
        raise ModelDebt(f"a condition {json.dumps(c)[:100]}")


def conj(xs: list) -> str:
    if not xs:
        return "True{}"
    out = xs[0]
    for x in xs[1:]:
        out = f"Bool.and({out}, {x})"
    return out


def cb_term(t, n: str) -> str:
    """The sidecar's CB term over n (Nat; >> k is division by 2^k, ? an ite)."""
    if t == "n":
        return n
    if isinstance(t, int):
        return f"{t}n"
    op, *a = t
    if op == "?":
        c = a[0]
        if not (isinstance(c, list) and c[0] == "<"):
            raise ModelDebt("a CB condition")
        return f"ite_nat(Nat.is_lt({cb_term(c[1], n)}, {cb_term(c[2], n)}), {cb_term(a[1], n)}, {cb_term(a[2], n)})"
    if op == ">>":
        return f"Nat.div({cb_term(a[0], n)}, {2 ** a[1]}n)"
    if op in ("+", "-"):
        return f"{NAT_OPS[op]}({cb_term(a[0], n)}, {cb_term(a[1], n)})"
    raise ModelDebt(f"a CB operator {op}")


def cb_eval(t, n: int) -> int:
    if t == "n":
        return n
    if isinstance(t, int):
        return t
    op, *a = t
    if op == "?":
        c = a[0]
        return cb_eval(a[1], n) if cb_eval(c[1], n) < cb_eval(c[2], n) else cb_eval(a[2], n)
    x, y = cb_eval(a[0], n), cb_eval(a[1], n)
    return {"+": x + y, "-": max(0, x - y), ">>": x >> y}[op]


# ====================================================================== binders (the law IR's)
def binders(e: dict) -> list:
    b = e["basis"]
    if e["subform"] == "go_round_trip":
        return [(ident("x", k), f"Bytes({v['width']})") for k, v in enumerate(b["inputs"])]
    if e["subform"] == "go_branch":
        tr = branch_tr(b)
        return [(n, "Bool" if k == "bool" else "Nat") for n, (k, _t) in tr.vars.items()]
    rc = recompute_parts(b)
    return [(n, "List<Nat>" if k == "list" else ("Bool" if k == "bool" else "Nat")) for n, k in rc["go_vars"]]


# ====================================================================== go_round_trip
def round_trip_module(b: dict, lid: str) -> dict:
    names = {}
    for k, v in enumerate(b["inputs"]):
        names[json.dumps(v["value"], sort_keys=True)] = [ident("x", k, j) for j in range(v["width"])]
    cells = []
    for c in b["cells"]:
        if c[:1] == ["const"]:
            cells.append(str(c[1]))
        elif c[:1] == ["byte"]:
            cells.append(names[json.dumps(c[1], sort_keys=True)][c[2]])
        else:
            raise ModelDebt(f"a cell {c}")
    params = [n for v in b["inputs"] for n in names[json.dumps(v["value"], sort_keys=True)]]
    reads = []
    for r in b["reads"]:
        reads.append(f"take({r['width']}n, drop({r['offset']}n, b))")
    if len(reads) != 1:
        raise ModelDebt("a decoder with several reads")
    v = b["reads"][0]["value"]
    want = names[json.dumps(v, sort_keys=True)]
    n = ident("gr", lid)
    text = (HEADER + "import Base\n\n" + LIB + "\n"
            + f"def {n}_enc({', '.join(f'{p}: U32' for p in params)}) -> List<&2, U32>:\n  [{', '.join(cells)}]\n\n"
            + f"def {n}_sel(ok: Bool, +b: List<&2, U32>) -> Maybe<List<&2, U32>>:\n  match ok:\n    case True{{}}:\n"
            + f"      Some{{{reads[0]}}}\n    case False{{}}:\n      None{{}}\n\n"
            + f"def {n}_dec(+b: List<&2, U32>) -> Maybe<List<&2, U32>>:\n"
            + f"  {n}_sel(Nat.is_eq(len(b), {b['length']}n), b)\n")
    claim = (f"{{M.{n}_dec(M.{n}_enc({', '.join(params)})) == Some{{[{', '.join(want)}]}} : Maybe<List<&2, U32>>}}")
    return {"module": text, "params": params, "claim": claim}


def round_trip_files(b: dict, lid: str, sh: str, mod_rel: str) -> tuple:
    m = round_trip_module(b, lid)
    laws = (HEADER + f"# law_id: {lid}   statement_hash: {sh}\nimport Base\nimport {mod_rel} as M\n\n"
            + f"law {law_name(lid)}:\n" + "".join(f"  for +{p}: U32\n" for p in m["params"]) + f"  {m['claim']}\n")
    proof = (HEADER + "import Base\n" + f"import {mod_rel} as M\nimport ../../laws/{lid}/LAWS.bend as Laws\n\n"
             + f"# reflexivity: dec reads back the cells enc wrote\ndef Laws.{law_name(lid)}({', '.join(m['params'])}):\n"
             + "  {==}\n")
    return m["module"], laws, proof


# ====================================================================== go_branch
def branch_tr(b: dict) -> Tr:
    tr = Tr(call=[b["call"], [b["arg"]]])
    for c in b["shared"] + [b["test"]] + b["extra"]:
        tr.boolean(c)
    tr.boolean(b["q_value"])
    tr.length(b["arg"])
    if b.get("hypz_len"):
        tr.var("ok", "bool", ["ok", ["call", b["call"], [b["arg"]]]])
    return tr


def branch_module(b: dict, lid: str) -> dict:
    tr = branch_tr(b)
    prem = [tr.boolean(c) for c in b["shared"] + [b["test"]] + b["extra"]]
    lx = tr.length(b["arg"])
    if b.get("hypz_len"):
        e = tr.length(["result", ["call", b["call"], [b["arg"]]], 0])
        hz = f"Bool.or(Bool.not(Bool.and(ok, Bool.not(Nat.is_eq({lx}, 0n)))), Nat.is_le({e}, cb({lx})))"
        prem.append(hz)
    qv = tr.boolean(b["q_value"])
    pv = b["p_value"]
    if pv[:1] != ["bool"]:
        raise ModelDebt(f"p's value {pv}")
    claim = qv if pv[1] else f"Bool.not({qv})"
    n = ident("gb", lid)
    vs = list(tr.vars.items())
    params = ", ".join(f"+{v}: {'Bool' if k == 'bool' else 'Nat'}" for v, (k, _t) in vs)
    cb = ""
    if b.get("hypz_len"):
        cb = f"def cb(+n: Nat) -> Nat:\n  {cb_term(b['hypz_len']['cb'], 'n')}\n\n"
    text = (HEADER + "import Base\n\n" + LIB + "\n" + cb
            + f"def {n}_ok({params}) -> Bool:\n  Bool.or(Bool.not({conj(prem)}), {claim})\n")
    return {"module": text, "vars": vs, "name": n}


def branch_witness(b: dict) -> dict:
    """G9: the smallest blob count (every int leaf of the bound at 1), |X| at the bound with all of it in X's last slice
    operand (the other length leaves 0), the call succeeding, and the counter-model length e = CB(|X|)."""
    tr = branch_tr(b)
    vals = {}
    bound_tr = Tr()
    bound_tr.nat(b["bound"])
    for v in bound_tr.vars:
        vals[v] = 1
    x_tr = Tr(call=tr.call)
    x_tr.length(b["arg"])
    xs = [v for v in x_tr.vars if v != "e"]
    bound = nat_eval(b["bound"], vals)
    for v in xs:
        vals[v] = 0
    if not xs:
        raise ModelDebt("X has no length leaf")
    vals[xs[-1]] = bound
    for v, (k, _t) in tr.vars.items():
        if v not in vals:
            vals[v] = True if k == "bool" else 0
    if b.get("hypz_len"):
        vals["e"] = cb_eval(b["hypz_len"]["cb"], bound)
    else:
        vals["e"] = bound + 1
    return {"values": {v: vals[v] for v in tr.vars}, "bound": bound, "x_length": bound, "last": xs[-1]}


def nat_eval(t, vals: dict) -> int:
    tr = Tr()
    src = tr.nat(t)
    return _ev(src, vals)


def _ev(src: str, vals: dict):
    """Evaluate a translated Nat/Bool expression (the Bend text this module writes) in Python."""
    env = {"True{}": True, "False{}": False}

    def tok(s):
        return re.findall(r"[A-Za-z_][A-Za-z0-9_.]*(?:\{\})?|\d+n|[(),]", s)

    ts = tok(src)
    pos = [0]

    def parse():
        t = ts[pos[0]]
        pos[0] += 1
        if t in env:
            return env[t]
        if re.fullmatch(r"\d+n", t):
            return int(t[:-1])
        if pos[0] < len(ts) and ts[pos[0]] == "(":
            pos[0] += 1
            args = []
            while ts[pos[0]] != ")":
                args.append(parse())
                if ts[pos[0]] == ",":
                    pos[0] += 1
            pos[0] += 1
            return FN[t](*args)
        return vals[t]
    return parse()


FN = {"Nat.add": lambda a, b: a + b, "Nat.sub": lambda a, b: max(0, a - b), "Nat.mul": lambda a, b: a * b,
      "Nat.div": lambda a, b: a // b, "Nat.is_le": lambda a, b: a <= b, "Nat.is_lt": lambda a, b: a < b,
      "Nat.is_gt": lambda a, b: a > b, "Nat.is_ge": lambda a, b: a >= b, "Nat.is_eq": lambda a, b: a == b,
      "Bool.not": lambda a: not a, "Bool.and": lambda a, b: a and b, "Bool.or": lambda a, b: a or b,
      "ite_nat": lambda c, a, b: a if c else b}


def branch_eval(b: dict, lid: str, values: dict) -> bool:
    """gb_ok at values, evaluated in Python as Bend computes it (to pick and confirm a witness)."""
    m = branch_module(b, lid)
    body = m["module"].split(f"def {m['name']}_ok(", 1)[1].split("\n", 1)[1].strip()
    if b.get("hypz_len"):
        FN["cb"] = lambda n: cb_eval(b["hypz_len"]["cb"], n)
    return _ev(body, values)


def branch_files(b: dict, lid: str, sh: str, mod_rel: str, counter: bool, w: dict | None) -> tuple:
    m = branch_module(b, lid)
    vs, n = m["vars"], m["name"]
    args = ", ".join(v for v, _ in vs)
    typ = {v: ("Bool" if k == "bool" else "Nat") for v, (k, _t) in vs}
    head = HEADER + f"# law_id: {lid}   statement_hash: {sh}\nimport Base\nimport {mod_rel} as M\n\n"
    if not counter:
        laws = head + f"law {law_name(lid)}:\n" + "".join(f"  for +{v}: {typ[v]}\n" for v, _ in vs) \
            + f"  {{M.{n}_ok({args}) == True{{}} : Bool}}\n"
        return m["module"], laws, None
    laws = head + f"law {law_name(lid, True)}:\n" + "".join(f"  exs {v}: {typ[v]}\n" for v, _ in vs) \
        + f"  {{M.{n}_ok({args}) != True{{}} : Bool}}\n"
    lit = {v: (("True{}" if w["values"][v] else "False{}") if typ[v] == "Bool" else f"{w['values'][v]}n")
           for v, _ in vs}
    wargs = ", ".join(lit[v] for v, _ in vs)
    tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for v, _ in reversed(vs):
        tup = f"({lit[v]}, {tup})"
    proof = (HEADER + "import Base\n" + f"import {mod_rel} as M\nimport ../../laws/{lid}/LAWS.bend as Laws\n\n"
             + f"# witness (G9): {json.dumps(w['values'], sort_keys=True)}\n"
             + f"def cz() -> {{M.{n}_ok({wargs}) == False{{}} : Bool}}:\n  {{==}}\n\n"
             + "def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})\n\n"
             + f"def Laws.{law_name(lid, True)}():\n  {tup}\n")
    return m["module"], laws, proof


# ====================================================================== go_recompute
def _shift_store(w):
    """[mstore, off, [<<, x, s]] -> (off, x, nbytes)."""
    if w[0] == "mstore" and isinstance(w[1], int) and isinstance(w[2], list) and w[2][0] == "<<" \
            and isinstance(w[2][2], int) and (256 - w[2][2]) % 8 == 0:
        return w[1], w[2][1], (256 - w[2][2]) // 8
    return None


def sol_layout(sol: dict) -> dict:
    """The Solidity preimage: prefix cells (offset < the loop's base: [kind, ...]) and the loop (base, word, count)."""
    v = sol["value"]
    mem, off, ln = v[1][1][1:], v[1][2], v[1][3]
    if off != 0:
        raise ModelDebt("a slice not at offset 0")
    cells: dict = {}
    loop = None
    for w in mem:
        st = _shift_store(w)
        if st is not None:
            o, x, nb = st
            for k in range(32):
                cells[o + k] = ["byte", x, k] if k < nb else ["const", 0]
            continue
        if w[0] == "when" and isinstance(w[2], list) and w[2][0] == "mloop":
            body = w[2][4]
            if len(body) != 1 or body[0][0] != "mstore":
                raise ModelDebt("a memory loop of several stores")
            o = body[0][1]
            if not (o[0] == "+" and isinstance(o[1], int) and o[2][0] == "*" and o[2][1] == 32 and o[2][2] == w[2][2]):
                raise ModelDebt("a memory loop that is not base + 32 iter")
            loop = {"base": o[1], "count": w[2][3], "value": body[0][2]}
            continue
        raise ModelDebt(f"a memory write {json.dumps(w)[:80]}")
    if loop is None:
        raise ModelDebt("no memory loop")
    want = ["+", loop["base"], ["*", 32, loop["count"]]]
    if ln != want:
        raise ModelDebt("a slice length other than base + 32 count")
    prefix = [cells.get(k, ["const", 0]) for k in range(loop["base"])]
    return {"prefix": prefix, "loop": loop}


def _go_names(t, acc: list) -> None:
    if isinstance(t, list):
        if t[:1] == ["field"] and isinstance(t[1], list) and t[1][:1] == ["param"]:
            if t not in acc:
                acc.append(t)
            return
        for x in t:
            _go_names(x, acc)


class GoList:
    """Go byte-string and count terms of a go_recompute law as Bend (lists of U32 cells and Nat)."""

    def __init__(self, loop):
        self.loop = loop
        self.lists, self.nats, self.bools = {}, {}, {}

    def name(self, t, kind: str) -> str:
        tr = Tr()
        n = ident({"list": "b", "nat": "k", "bool": "h"}[kind], tr.leaf_name(t))
        {"list": self.lists, "nat": self.nats, "bool": self.bools}[kind].setdefault(n, t)
        return n

    def nat(self, t, iv: str = "i") -> str:
        if t[:1] == ["iv"]:
            return iv
        if t[:1] == ["const"]:
            return f"{t[1]}n"
        if t[:1] == ["op"] and t[1] in NAT_OPS:
            a, b = self.nat(t[2], iv), self.nat(t[3], iv)
            if t[1] == "*" and re.fullmatch(r"\d+n", a):
                a, b = b, a
            if t[1] == "+" and re.fullmatch(r"\d+n", b):
                a, b = b, a
            return f"{NAT_OPS[t[1]]}({a}, {b})"
        if t[:1] == ["convert"]:
            return self.nat(t[2], iv)
        if t[:1] == ["field"]:
            return self.name(t, "nat")
        if t[:1] == ["len"]:
            return f"len({self.lst(t[1], iv)})"
        if t[:1] == ["cap"]:
            return f"len({self.lst(t[1], iv)})"   # cap read as len: a stronger premise (hi <= len)
        raise ModelDebt(f"a Go count {json.dumps(t)[:80]}")

    def lst(self, t, iv: str = "i", acc: str = "acc") -> str:
        if t == ["nil"]:
            return "Nil{}"
        if t[:1] == ["carried"]:
            return acc
        if t[:1] == ["append"]:
            return f"app({self.lst(t[1], iv, acc)}, {self.lst(t[2], iv, acc)})"
        if t[:1] == ["slice"]:
            base = self.lst(t[1], iv, acc)
            lo = self.nat(t[2], iv) if t[2] is not None else "0n"
            if t[3] is None:
                return f"drop({lo}, {base})"
            return f"take(Nat.sub({self.nat(t[3], iv)}, {lo}), drop({lo}, {base}))"
        if t[:1] == ["field"]:
            return self.name(t, "list")
        raise ModelDebt(f"a Go byte string {json.dumps(t)[:80]}")


def recompute_parts(b: dict) -> dict:
    loop = b.get("loop")
    g = GoList(loop)
    out: dict = {}
    if loop is not None:
        if len(loop.get("carried") or []) != 1 or loop.get("step") != 1 or loop.get("cmp") != "<":
            raise ModelDebt("a loop other than one carried value counted by 1")
        (car,) = loop["carried"]
        ups = {json.dumps(c["updates"].get(car["name"]), sort_keys=True) for c in loop["continue"]}
        if len(ups) != 1:
            raise ModelDebt("continue paths with different updates")
        upd = json.loads(ups.pop())
        out["init"] = g.lst(car["init"])
        out["update"] = g.lst(upd, "i", "acc")
        out["start"] = g.nat(loop["init"])
        out["limit"] = g.nat(loop["limit"])
        # G6/G8: no iteration panics; a panic path's trigger is its last condition (the bound site), read with cap as len
        trig = []
        for pp in loop["panics"]:
            c = pp["cond"][-1]
            if not (isinstance(c, list) and c[0] == ">" and len(c) == 3):
                raise ModelDebt("a panic trigger that is not a bound")
            trig.append(f"Nat.is_le({g.nat(c[1], 'i')}, {g.nat(c[2], 'i')})")
        out["safe"] = conj(trig)
    out["pre"] = g.lst(b["preimage"], "i", "carry")
    hb = []
    for c in b["exit_cond"]:
        if isinstance(c, list) and c[0] in ("==", "!=") and c[2] == ["nil"] and isinstance(c[1], list) \
                and c[1][:1] == ["field"]:
            h = g.name(c[1], "bool")
            hb.append(h if c[0] == "==" else f"Bool.not({h})")
    out["exit"] = conj(hb)
    out["go_vars"] = [(n, "list") for n in g.lists] + [(n, "nat") for n in g.nats] + [(n, "bool") for n in g.bools]
    out["g"] = g
    return out


def recompute_module(b: dict, lid: str) -> dict:
    p = recompute_parts(b)
    g = p["g"]
    lists, nats = list(g.lists), list(g.nats)
    n = ident("rc", lid)
    pl = ", ".join([f"+{x}: List<&2, U32>" for x in lists] + [f"+{x}: Nat" for x in nats])
    al = ", ".join(lists + nats)
    text = HEADER + "import Base\n\n" + LIB + "\n"
    if b.get("loop") is not None:
        text += (f"def {n}_fold(fuel: Nat, +i: Nat, acc: List<&2, U32>, {pl}) -> List<&2, U32>:\n  match fuel:\n"
                 f"    case 0n:\n      acc\n    case 1n+f:\n"
                 f"      {n}_fold(f, Nat.add(i, 1n), {p['update']}, {al})\n\n")
        text += (f"def {n}_safe(fuel: Nat, +i: Nat, {pl}) -> Bool:\n  match fuel:\n    case 0n:\n      True{{}}\n"
                 f"    case 1n+f:\n      Bool.and({p['safe']}, {n}_safe(f, Nat.add(i, 1n), {al}))\n\n")
        carry = f"{n}_fold(Nat.sub({p['limit']}, {p['start']}), {p['start']}, {p['init']}, {al})"
        text += (f"def {n}_pg({pl}) -> List<&2, U32>:\n"
                 f"  {p['pre'].replace('carry', carry)}\n\n")
        text += (f"def {n}_prem({pl}, h: Bool) -> Bool:\n"
                 f"  Bool.and(h, {n}_safe(Nat.sub({p['limit']}, {p['start']}), {p['start']}, {al}))\n\n")
    else:
        text += f"def {n}_pg({pl}) -> List<&2, U32>:\n  {p['pre']}\n\n"
        text += f"def {n}_prem({pl}, h: Bool) -> Bool:\n  h\n\n"
    lay = sol_layout(b["solidity"])
    svars = []
    cells = []
    for c in lay["prefix"]:
        if c[:1] == ["const"]:
            cells.append(str(c[1]))
        else:
            v = ident("s", Tr().leaf_name(c[1]) if isinstance(c[1], list) and c[1][:1] in (["param"], ["field"])
                      else _sol_leaf(c[1]), c[2])
            svars.append(v)
            cells.append(v)
    text += (f"def {n}_ps({', '.join(f'{v}: U32' for v in svars)}, hc: List<&2, U32>) -> List<&2, U32>:\n"
             f"  app([{', '.join(cells)}], hc)\n")
    return {"module": text, "name": n, "lists": lists, "nats": nats, "svars": svars, "base": lay["loop"]["base"],
            "parts": p}


def _sol_leaf(t) -> str:
    if isinstance(t, list) and t[:1] == ["member"]:
        return ident(_sol_leaf(t[1]), t[2])
    if isinstance(t, list) and t[:1] == ["param"]:
        return ident(t[1])
    raise ModelDebt(f"a Solidity leaf {json.dumps(t)[:80]}")


def recompute_files(b: dict, lid: str, sh: str, mod_rel: str, w: dict) -> tuple:
    """The counter-law only: every Go data hash is some on-chain one is refuted by the witness w (its Go state), if the
    length argument decides it; else ModelDebt."""
    m = recompute_module(b, lid)
    n, base = m["name"], m["base"]
    go_len = w["go_preimage_length"]
    js = [j for j in range(go_len + 2) if base + 32 * j > go_len]
    if any(base + 32 * j == go_len for j in range(go_len + 1)):
        raise ModelDebt("the Go preimage's length is an on-chain length (no length argument)")
    top = js[0]
    sv = m["svars"]
    sp = ", ".join(f"{v}: U32" for v in sv)
    sa = ", ".join(sv)
    gl = ", ".join(f"w_{x}()" for x in m["lists"] + m["nats"])
    laws = (HEADER + f"# law_id: {lid}   statement_hash: {sh}\nimport Base\nimport {mod_rel} as M\n\n"
            + f"law {law_name(lid, True)}:\n"
            + "".join(f"  exs {x}: List<&2, U32>\n" for x in m["lists"])
            + "".join(f"  exs {x}: Nat\n" for x in m["nats"]) + "  exs h: Bool\n"
            + f"  exs pr: {{M.{n}_prem({', '.join(m['lists'] + m['nats'])}, h) == True{{}} : Bool}}\n"
            + "".join(f"  for +{v}: U32\n" for v in sv) + "  for +cnt: Nat\n  for +hc: List<&2, U32>\n"
            + "  for p: {M.len(hc) == Nat.mul(cnt, 32n) : Nat}\n"
            + f"  {{M.{n}_ps({sa}, hc) != M.{n}_pg({', '.join(m['lists'] + m['nats'])}) : List<&2, U32>}}\n")
    defs = ""
    for x in m["lists"]:
        cells = w["lists"][x]
        defs += f"def w_{x}() -> List<&2, U32>:\n  [{', '.join(str(c) for c in cells)}]\n\n"
    for x in m["nats"]:
        defs += f"def w_{x}() -> Nat:\n  {w['nats'][x]}n\n\n"
    pg = f"M.{n}_pg({gl})"
    cases = ""
    for j in range(top):
        cases += f"    case {j}n:\n      false_ne_true(r)\n"
    cases += f"    case {top}n+k:\n      false_ne_true(r)\n"
    proof = (HEADER + "import Base\n" + f"import {mod_rel} as M\nimport ../../laws/{lid}/LAWS.bend as Laws\n\n"
             + f"# witness (G9): {json.dumps({k: v for k, v in w.items() if k != 'lists'}, sort_keys=True)}\n"
             + defs
             + "def false_ne_true(p: {False{} == True{} : Bool}) -> Empty:\n  (%p : M.is_false(_)\n  Unit{})\n\n"
             + f"def go_len() -> {{Nat.is_eq(M.len({pg}), {go_len}n) == True{{}} : Bool}}:\n  {{==}}\n\n"
             + f"def prem() -> {{M.{n}_prem({gl}, True{{}}) == True{{}} : Bool}}:\n  {{==}}\n\n"
             + f"def sym_e({sp}, +hc: List<&2, U32>, e: {{M.{n}_ps({sa}, hc) == {pg} : List<&2, U32>}}) -> "
             + f"{{{pg} == M.{n}_ps({sa}, hc) : List<&2, U32>}}:\n"
             + f"  (%e : {{_ == M.{n}_ps({sa}, hc) : List<&2, U32>}}\n  {{==}})\n\n"
             + f"def t1({sp}, +hc: List<&2, U32>, s: {{{pg} == M.{n}_ps({sa}, hc) : List<&2, U32>}}) -> "
             + f"{{Nat.is_eq(Nat.add({base}n, M.len(hc)), {go_len}n) == True{{}} : Bool}}:\n"
             + f"  (%s : {{Nat.is_eq(M.len(_), {go_len}n) == True{{}} : Bool}}\n  go_len())\n\n"
             + f"def t2(cnt: Nat, +hc: List<&2, U32>, p: {{M.len(hc) == Nat.mul(cnt, 32n) : Nat}}, "
             + f"t: {{Nat.is_eq(Nat.add({base}n, M.len(hc)), {go_len}n) == True{{}} : Bool}}) -> "
             + f"{{Nat.is_eq(Nat.add({base}n, Nat.mul(cnt, 32n)), {go_len}n) == True{{}} : Bool}}:\n"
             + f"  (%p : {{Nat.is_eq(Nat.add({base}n, _), {go_len}n) == True{{}} : Bool}}\n  t)\n\n"
             + f"def cases(cnt: Nat, r: {{Nat.is_eq(Nat.add({base}n, Nat.mul(cnt, 32n)), {go_len}n) == True{{}} : "
             + f"Bool}}) -> Empty:\n  match cnt:\n{cases}\n"
             + f"def Laws.{law_name(lid, True)}():\n"
             + f"  ({', ('.join(f'w_{x}()' for x in m['lists'] + m['nats'])}, (True{{}}, (prem(), "
             + " => ".join(sv + ["cnt", "hc", "p", "e"])
             + f" => cases(cnt, t2(cnt, hc, p, t1({sa}, hc, sym_e({sa}, hc, e))))"
             + ")" * (len(m["lists"]) + len(m["nats"]) + 2) + "\n")
    return m["module"], laws, proof


def recompute_witness(b: dict) -> dict:
    """G9: the fewest loop iterations whose replay has a correspondence (at least one, so the batch has a last block),
    each byte string the loop slices of exactly the length those iterations read (zeros), and the empty rest."""
    m = recompute_module(b, "w")
    p = m["parts"]
    g = p["g"]
    loop = b["loop"]
    if loop is None:
        raise ModelDebt("no loop: no fewest-iterations witness")
    lim = loop["limit"]
    lim_names = []
    _go_names(lim, lim_names)
    if len(lim_names) != 1:
        raise ModelDebt("a loop limit over several fields")
    kname = g.name(lim_names[0], "nat")
    (car,) = loop["carried"]
    upd = loop["continue"][0]["updates"][car["name"]]
    sl = [x for x in [upd[2]] if isinstance(x, list) and x[:1] == ["slice"]]
    if not sl:
        raise ModelDebt("an update that slices nothing")
    src = g.name(sl[0][1], "list")
    hi = sl[0][3]
    reach = _ev(GoList(loop).nat(hi, "i"), {"i": 0})          # the first iteration reads [lo, hi) at i = 0
    stride = _ev(GoList(loop).nat(hi, "i"), {"i": 1}) - reach
    stride = stride if stride > 0 else reach
    lists = {x: [] for x in m["lists"]}
    lists[src] = [0] * (reach + max(0, stride - reach))       # one iteration's stride of zero bytes
    nats = {x: 0 for x in m["nats"]}
    nats[kname] = 1
    go = _go_eval(b, lists, nats)
    return {"appends": 1, "lists": lists, "nats": nats, "go_preimage_length": len(go), "go_preimage": go,
            "rest": [x for x in m["lists"] if x != src]}


def _go_eval(b: dict, lists: dict, nats: dict) -> list:
    """The Go preimage at a concrete state, by the loop's semantics (Python, for the witness record)."""
    loop = b["loop"]
    (car,) = loop["carried"]
    upd = loop["continue"][0]["updates"][car["name"]]

    def val(t, i, acc):
        if t == ["nil"]:
            return []
        if t[:1] == ["carried"]:
            return acc
        if t[:1] == ["append"]:
            return val(t[1], i, acc) + val(t[2], i, acc)
        if t[:1] == ["slice"]:
            base = val(t[1], i, acc)
            lo = num(t[2], i) if t[2] is not None else 0
            hi = num(t[3], i) if t[3] is not None else len(base)
            return base[lo:hi]
        if t[:1] == ["field"]:
            return lists[GoList(loop).name(t, "list")]
        raise ModelDebt(f"a Go term {t}")

    def num(t, i):
        if t[:1] == ["iv"]:
            return i
        if t[:1] == ["const"]:
            return t[1]
        if t[:1] == ["op"]:
            a, c = num(t[2], i), num(t[3], i)
            return {"+": a + c, "-": max(0, a - c), "*": a * c}[t[1]]
        if t[:1] == ["convert"]:
            return num(t[2], i)
        if t[:1] == ["field"]:
            return nats[GoList(loop).name(t, "nat")]
        raise ModelDebt(f"a Go count {t}")

    acc = val(car["init"], 0, [])
    for i in range(num(loop["init"], 0), num(loop["limit"], 0)):
        acc = val(upd, i, acc)
    return val(b["preimage"], 0, acc)
