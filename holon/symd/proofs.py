"""The Bend files of rule SYM's laws over the typed model and its sym section (BUILD_PLAN I34; the contract is rule J6
of the docstring of tests_m3/test_sym.py).

  law_file(law, n, ..)          gen/<M>/laws/<id>/LAWS.bend: for every hash table, reachable state s and binder,
                                U.sy_ok_<n>(s, binders.., tables) == True (or, for a REFUTED law, the counter-law:
                                there exist them with sy_ok_<n> != True); it imports the typed model as M and the sym
                                section as U. A Nat binder (tau's d) is a word here: the claim's fits64 premise bounds
                                it below 2^64, so the word and the number quantify the same claim
  counter_proof(..)             the counter-law's proof: UNDO's shape (holon.undo.proofs: the witness's hash tables,
                                the literal state after each prefix step, its Reach chain, the binders' literals), cz
                                computing sy_ok_<n> false at the literals
  inhabitant_law / _proof       G11V: there exist a reachable state and binders where sy_hit_<n> (the premises) holds
  sentinel_proof(..)            the sentinel law whose site writes the clock (the document's term ["env",
                                "block.timestamp"]): by cases on the act; at the site's action the claim reduces to
                                ux_imp(Bool.and(c, p), p) with p the clock's non-zeroness (the site's word in the call's
                                initial context is the act's own clock), which holds by cases on c and p

What is not generated (NO_PROOF names it in the record): an equivariance proof of a tau or pi law (a relational mirror
of the action's statement chain under the generator: every statement commuting with τ or π, I33's Word lemmas over
the structural store) and a reorder proof of an omega law; a sentinel site whose word is not the clock needs a Reach
invariant (I68's S10 shape) that is not built here. Such a law without a counter-law stays UNKNOWN. Nothing here
names a target.
"""
from __future__ import annotations

from ..gen.mlaws import law_name
from ..machine_bend import bname
from ..sorts import proofs3 as P3
from ..sorts.proofs3 import PHEADER
from ..undo import proofs as UP

HEADER = "# GENERATED by holon.symd.proofs from the frozen law IR and the sym section; do not edit."
NO_PROOF = {
    "tau": ("no equivariance proof generator: τ_d commuting with a step needs a relational mirror of the action's "
            "statement chain (each statement under τ: Time + Dur, Time - Time, two-Time comparisons, the checked "
            "additions under fits64) over the structural store, which is not built"),
    "pi": ("no equivariance proof generator: π_(a,b) commuting with a step needs a relational mirror of the action's "
           "statement chain (address equality off {a, b}, keyed maps under the key swap, the recorded calls' "
           "arguments) over the structural store, which is not built"),
    "omega": ("no reorder proof generator: the two orders' agreement on the sink-reaching keys needs a relational "
              "mirror of both actions' statement chains, which is not built"),
    "sentinel": ("the site's word is not the clock: the sentinel needs a Reach invariant (I68's S10 shape: the invariant "
                 "at s0, one step lemma per action), which is not built"),
}


def binders(law: dict) -> list[tuple[str, str]]:
    out = []
    for b in law["statement"]["binders"][1:]:
        ty = str(b["type"])
        if ty == "Act":
            out.append((b["name"], "M.HAct"))
        elif ty in ("Word", "Nat"):
            out.append((b["name"], "M.W"))
        else:
            raise ValueError(f"{law['law_id']}: binder {b['name']}: {ty} has no Bend type here")
    return out


def call(fn: str, n: int, names: list[str], tables: list[str]) -> str:
    return f"U.{fn}_{n}(" + ", ".join(names + tables) + ")"


def law_file(law: dict, n: int, statement_hash: str, model_import: str, sym_import: str, hashes: list,
             counter: bool = False) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{t}, " for t, _h in tb)
    kw, q = ("exs", "") if counter else ("for", "+")
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", f"import {sym_import} as U", "", f"law {law_name(lid, counter)}:"]
    for t, _h in tb:
        lines.append(f"  {kw} {q}{t}: List<&2, M.HKB>")
    lines += [f"  {kw} {q}s: M.GSt", f"  {kw} r_s: M.Reach<{idx}s>"]
    bs = binders(law)
    for b, ty in bs:
        lines.append(f"  {kw} {q}{b}: {ty}")
    rel = "!=" if counter else "=="
    lines.append(f"  {{{call('sy_ok', n, ['s'] + [b for b, _t in bs], [t for t, _h in tb])} {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def inhabitant_law(law: dict, n: int, statement_hash: str, model_import: str, sym_import: str, hashes: list) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{t}, " for t, _h in tb)
    lines = [HEADER, f"# non-vacuity of {lid} (statement_hash {statement_hash}): its premises sy_hit_{n} are inhabited "
             "by a reachable state and binders", "import Base", f"import {model_import} as M",
             f"import {sym_import} as U", "", f"law nv_{lid.lower()}:"]
    for t, _h in tb:
        lines.append(f"  exs {t}: List<&2, M.HKB>")
    lines += ["  exs s: M.GSt", f"  exs r_s: M.Reach<{idx}s>"]
    bs = binders(law)
    for b, ty in bs:
        lines.append(f"  exs {b}: {ty}")
    lines.append(f"  {{{call('sy_hit', n, ['s'] + [b for b, _t in bs], [t for t, _h in tb])} == True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def _binder_defs(law: dict, values: dict, lit) -> tuple[list[str], list[str]]:
    lines, names = [], []
    for b, ty in binders(law):
        v = values[b]
        text = lit.word("0x%064x" % int(v)) if ty == "M.W" else lit.text(v)
        lines += [f"def b_{b}() -> {ty}:\n  {text}", ""]
        names.append(f"b_{b}()")
    return lines, names


def counter_proof(law: dict, n: int, model_import: str, sym_import: str, laws_import: str, hashes: list,
                  prefix: list, states: list, values: dict, tables: dict, lit, note: str) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{t}()" for t, _h in tb]
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", "", f"# class counter: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = UP._prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    lines += [f"def cz() -> {{{call('sy_ok', n, [state] + bnames, targs)} == False{{}} : Bool}}:\n  {{==}}", ""]
    lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
    tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"


def inhabitant_proof(law: dict, n: int, model_import: str, sym_import: str, laws_import: str, hashes: list,
                     prefix: list, states: list, values: dict, tables: dict, lit) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{t}()" for t, _h in tb]
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", ""]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = UP._prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    lines += [f"def ch() -> {{{call('sy_hit', n, [state] + bnames, targs)} == True{{}} : Bool}}:\n  {{==}}", ""]
    tup = "ch()"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.nv_{lid.lower()}():\n  {tup}")
    return "\n".join(lines) + "\n"


class NoProof(ValueError):
    pass


class SymLit(UP.Lit):
    """Witness literals with the sym section's records (UOS, UOb) qualified by U in typed rendering as well."""

    def typed(self, v, ty: str) -> str:
        if isinstance(v, dict) and "$r" in v and v["$r"] in self.mine:
            name = v["$r"]
            fs = self.recs.get(name) or []
            vals = v.get("f") or {}
            return f"U.{name}{{" + ", ".join(self.typed(vals[f], t) for f, t in fs) + "}"
        return super().typed(v, ty)


def sentinel_proof(law: dict, n: int, site_term, action: str, actions: list[str], model_import: str,
                   sym_import: str, laws_import: str, hashes: list) -> str:
    """The proof of a sentinel law whose site writes the clock (see the module docstring), or NoProof."""
    if site_term != ["env", "block.timestamp"]:
        raise NoProof(NO_PROOF["sentinel"])
    tb = P3.tabs_binders(hashes)
    if [t for t, _h in tb] != ["kh"]:
        raise NoProof("the sentinel proof is written for one keccak256 table")
    a = bname(action)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", "",
             "# class clock_site: the site writes the act's own clock, nonzero by the premise",
             "def imp_and_self(c: Bool, p: Bool) -> {U.ux_imp(Bool.and(c, p), p) == True{} : Bool}:",
             "  match c p:"]
    for c in ("True{}", "False{}"):
        for p in ("True{}", "False{}"):
            lines += [f"    case {c} {p}:", "      {==}"]
    lines += ["", f"def Laws.{law_name(law['law_id'], False)}(kh, s, r_s, x):", "  match x:"]
    for cn in actions:
        if cn == a:
            lines += [f"    case M.A_{cn}{{+ar, +en}}:",
                      f"      imp_and_self(U32.is_eq(M.gx_{a}_cd(M.xr_{a}(M.gh_get_st(s), ar, en, kh)), 0), "
                      f"M.w_nz(M.ge_e_block_timestamp(en)))"]
        else:
            lines += [f"    case M.A_{cn}{{_, _}}:", "      {==}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------------------ the split counter-law
def _motives(sub: str, n: int, act: str, S: str, X: str, KH: str, extra: dict) -> tuple[str, list, str]:
    """(the claim's premise over the literals, [(lemma name, the motive with _ at the run the lemma replaces)], the last
    goal) of sy_ok_<n>'s body (holon.gen.symsec law_tau, law_pi, law_omega), the rewrites in order."""
    F = "False{}"
    if sub in ("tau", "pi"):
        if sub == "tau":
            D = extra["d"]
            prem = f"Bool.and(U.sy_is_{act}({X}), Bool.and(U.sy_fits_g({S}, {D}), U.sy_fits_x({X}, {D})))"
            r2 = f"U.ux_ostep(U.sy_tau_x({X}, {D}), U.sy_tau_g({S}, {D}), {KH})"
            back = lambda u1: f"U.sy_tau_uos({u1}, {D})"  # noqa: E731
        else:
            A, B, role = extra["a"], extra["b"], extra["role"]
            prem = (f"Bool.and(U.sy_is_{act}({X}), Bool.and(Bool.not(M.w_eq({A}, {B})), Bool.and(U.sy_mem_{role}({S}, {A}), "
                    f"U.sy_mem_{role}({S}, {B}))))")
            r2 = f"U.ux_ostep(U.sy_pi_x({X}, {A}, {B}), U.sy_pi_g({S}, {A}, {B}), {KH})"
            back = lambda u1: f"U.sy_pi_uos_{act}({u1}, {A}, {B})"  # noqa: E731
        r1 = f"U.ux_ostep({X}, {S}, {KH})"
        steps = [("e_pre", f"{{U.ux_imp(_, U.sy_uos_eq({r2}, {back(r1)})) == {F} : Bool}}"),
                 ("e_u2", f"{{U.ux_imp(True{{}}, U.sy_uos_eq(_, {back(r1)})) == {F} : Bool}}"),
                 ("e_u1", f"{{U.ux_imp(True{{}}, U.sy_uos_eq(l_u2(), {back('_')})) == {F} : Bool}}")]
        last = f"{{U.ux_imp(True{{}}, U.sy_uos_eq(l_u2(), {back('l_u1()')})) == {F} : Bool}}"
        return prem, steps, last
    Y, a, b = extra["y"], extra["a_act"], extra["b_act"]
    prem = f"Bool.and(U.sy_is_{a}({X}), U.sy_is_{b}({Y}))"
    c2 = lambda ux, uy: f"U.sy_om_{n}_c2({ux}, {uy}, {X}, {Y}, {KH})"  # noqa: E731
    oks = "Bool.and(U32.is_eq(U.sy_code(l_ux()), 0), U32.is_eq(U.sy_code(l_uy()), 0))"
    rxy = f"U.ux_ostep({Y}, U.sy_post(l_ux()), {KH})"
    ryx = f"U.ux_ostep({X}, U.sy_post(l_uy()), {KH})"
    steps = [("e_pre", f"{{U.ux_imp(_, {c2(f'U.ux_ostep({X}, {S}, {KH})', f'U.ux_ostep({Y}, {S}, {KH})')}) == {F} : Bool}}"),
             ("e_ux", f"{{U.ux_imp(True{{}}, {c2('_', f'U.ux_ostep({Y}, {S}, {KH})')}) == {F} : Bool}}"),
             ("e_uy", f"{{U.ux_imp(True{{}}, {c2('l_ux()', '_')}) == {F} : Bool}}"),
             ("e_uxy", f"{{U.ux_imp(True{{}}, U.ux_imp({oks}, U.sy_om_{n}_c(_, {ryx}))) == {F} : Bool}}"),
             ("e_uyx", f"{{U.ux_imp(True{{}}, U.ux_imp({oks}, U.sy_om_{n}_c(l_uxy(), _))) == {F} : Bool}}")]
    last = f"{{U.ux_imp(True{{}}, U.ux_imp({oks}, U.sy_om_{n}_c(l_uxy(), l_uyx()))) == {F} : Bool}}"
    return prem, steps, last


def counter_proof_split(law: dict, n: int, sub: str, model_import: str, sym_import: str, laws_import: str,
                        hashes: list, prefix: list, states: list, values: dict, tables: dict, lit, runs: dict,
                        basis: dict, note: str) -> str:
    """The counter-law proof with one kernel conversion per run (A30's shape): the literal result of each run the
    claim makes (runs: tau/pi {u1: x from s, u2: g x from g s}; omega {ux, uy: x, y from s; uxy: y after x; uyx: x
    after y}) as a lemma {literal == run} by computation, the premise {True == premise}, and cz rewriting the claim's
    runs with them, so that the last conversion compares literals only."""
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{t}()" for t, _h in tb]
    KH = ", ".join(targs)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", "", f"# class counter_split: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = UP._prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    names = [b for b, _t in binders(law)]
    X = "b_x()"
    extra = {k: f"b_{k}()" for k in names if k != "x"}
    if sub == "pi":
        extra["role"] = bname(basis["role"])
        act = bname(basis["action"])
    elif sub == "tau":
        act = bname(basis["action"])
    else:
        act = ""
        extra.update(a_act=bname(basis["a"]), b_act=bname(basis["b"]))
    prem, steps, last = _motives(sub, n, act, state, X, KH, extra)
    order = ["u1", "u2"] if sub in ("tau", "pi") else ["ux", "uy", "uxy", "uyx"]
    for k in order:
        lines += [f"def l_{k}() -> U.UOS:\n  {lit.typed(runs[k], 'UOS')}", ""]
    run_terms = {"u1": f"U.ux_ostep({X}, {state}, {KH})"}
    if sub == "tau":
        run_terms["u2"] = f"U.ux_ostep(U.sy_tau_x({X}, b_d()), U.sy_tau_g({state}, b_d()), {KH})"
    elif sub == "pi":
        run_terms["u2"] = f"U.ux_ostep(U.sy_pi_x({X}, b_a(), b_b()), U.sy_pi_g({state}, b_a(), b_b()), {KH})"
    else:
        run_terms = {"ux": f"U.ux_ostep({X}, {state}, {KH})", "uy": f"U.ux_ostep(b_y(), {state}, {KH})",
                     "uxy": f"U.ux_ostep(b_y(), U.sy_post(l_ux()), {KH})",
                     "uyx": f"U.ux_ostep({X}, U.sy_post(l_uy()), {KH})"}
    for k in order:
        lines += [f"def e_{k}() -> {{l_{k}() == {run_terms[k]} : U.UOS}}:\n  {{==}}", ""]
    lines += [f"def e_pre() -> {{True{{}} == {prem} : Bool}}:\n  {{==}}", ""]
    lines += [f"def e_last() -> {last}:\n  {{==}}", ""]
    proof = "e_last()"
    for name, motive in reversed(steps):
        proof = f"(%{name}() : {motive}\n  {proof})"
    lines += [f"def cz() -> {{{call('sy_ok', n, [state] + bnames, targs)} == False{{}} : Bool}}:\n  {proof}", ""]
    lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
    tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"
