"""The Bend files of rule SYM's laws over the typed model and its sym section (BUILD_PLAN I34; the contract is rule J6
of the docstring of tests_m3/test_sym.py).

  law_file(law, n, ..)          gen/<M>/laws/<id>/LAWS.bend: for every hash table, reachable state s and binder,
                                U.sy_ok_<n>(s, binders.., tables) == True (or, for a REFUTED law, the counter-law:
                                there exist them with sy_ok_<n> != True); it imports the typed model as M and the sym
                                section as U. A Nat binder (tau's d) is a word here: the claim's fits64 premise bounds
                                it below 2^64, so the word and the number quantify the same claim
  counter_proof(..)             the counter-law's proof: UNDO's shape (holon.undo.proofs: the witness's hash tables,
                                the literal state after each prefix step, its Reach chain, the binders' literals), cz
                                computing sy_ok_<n> false at the literals
  inhabitant_law / _proof       G11V: there exist a reachable state and binders where sy_hit_<n> (the premises) holds
  sentinel_proof(..)            the sentinel law whose site writes the clock (the document's term ["env",
                                "block.timestamp"]): by cases on the act; at the site's action the claim reduces to
                                ux_imp(Bool.and(c, p), p) with p the clock's non-zeroness (the site's word in the call's
                                initial context is the act's own clock), which holds by cases on c and p

What is not generated (NO_PROOF names it in the record): an equivariance proof of a tau or pi law (a relational mirror
of the action's statement chain under the generator: every statement commuting with τ or π, I33's Word lemmas over
the structural store) and a reorder proof of an omega law; a sentinel site whose word is not the clock needs a Reach
invariant (I68's S10 shape) that is not built here. Such a law without a counter-law stays UNKNOWN. Nothing here
names a target.
"""
from __future__ import annotations

import re

from ..gen.mlaws import law_name
from ..machine_bend import bname
from ..sorts import proofs3 as P3
from ..sorts.proofs3 import PHEADER
from ..undo import proofs as UP

HEADER = "# GENERATED by holon.symd.proofs from the frozen law IR and the sym section; do not edit."
NO_PROOF = {
    "tau": ("no equivariance proof generator: τ_d commuting with a step needs a relational mirror of the action's "
            "statement chain (each statement under τ: Time + Dur, Time - Time, two-Time comparisons, the checked "
            "additions under fits64) over the structural store, which is not built"),
    "pi": ("no equivariance proof generator: π_(a,b) commuting with a step needs a relational mirror of the action's "
           "statement chain (address equality off {a, b}, keyed maps under the key swap, the recorded calls' "
           "arguments) over the structural store, which is not built"),
    "omega": ("no reorder proof generator: the two orders' agreement on the sink-reaching keys needs a relational "
              "mirror of both actions' statement chains, which is not built"),
    "sentinel": ("the site's word is not the clock: the sentinel needs a Reach invariant (I68's S10 shape: the invariant "
                 "at s0, one step lemma per action), which is not built"),
}


def binders(law: dict) -> list[tuple[str, str]]:
    out = []
    for b in law["statement"]["binders"][1:]:
        ty = str(b["type"])
        if ty == "Act":
            out.append((b["name"], "M.HAct"))
        elif ty in ("Word", "Nat"):
            out.append((b["name"], "M.W"))
        else:
            raise ValueError(f"{law['law_id']}: binder {b['name']}: {ty} has no Bend type here")
    return out


def call(fn: str, n: int, names: list[str], tables: list[str]) -> str:
    return f"U.{fn}_{n}(" + ", ".join(names + tables) + ")"


def law_file(law: dict, n: int, statement_hash: str, model_import: str, sym_import: str, hashes: list,
             counter: bool = False) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{t}, " for t, _h in tb)
    kw, q = ("exs", "") if counter else ("for", "+")
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", f"import {sym_import} as U", "", f"law {law_name(lid, counter)}:"]
    for t, _h in tb:
        lines.append(f"  {kw} {q}{t}: List<&2, M.HKB>")
    lines += [f"  {kw} {q}s: M.GSt", f"  {kw} r_s: M.Reach<{idx}s>"]
    bs = binders(law)
    for b, ty in bs:
        lines.append(f"  {kw} {q}{b}: {ty}")
    rel = "!=" if counter else "=="
    lines.append(f"  {{{call('sy_ok', n, ['s'] + [b for b, _t in bs], [t for t, _h in tb])} {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def inhabitant_law(law: dict, n: int, statement_hash: str, model_import: str, sym_import: str, hashes: list) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{t}, " for t, _h in tb)
    lines = [HEADER, f"# non-vacuity of {lid} (statement_hash {statement_hash}): its premises sy_hit_{n} are inhabited "
             "by a reachable state and binders", "import Base", f"import {model_import} as M",
             f"import {sym_import} as U", "", f"law nv_{lid.lower()}:"]
    for t, _h in tb:
        lines.append(f"  exs {t}: List<&2, M.HKB>")
    lines += ["  exs s: M.GSt", f"  exs r_s: M.Reach<{idx}s>"]
    bs = binders(law)
    for b, ty in bs:
        lines.append(f"  exs {b}: {ty}")
    lines.append(f"  {{{call('sy_hit', n, ['s'] + [b for b, _t in bs], [t for t, _h in tb])} == True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def _binder_defs(law: dict, values: dict, lit) -> tuple[list[str], list[str]]:
    lines, names = [], []
    for b, ty in binders(law):
        v = values[b]
        text = lit.word("0x%064x" % int(v)) if ty == "M.W" else lit.text(v)
        lines += [f"def b_{b}() -> {ty}:\n  {text}", ""]
        names.append(f"b_{b}()")
    return lines, names


def counter_proof(law: dict, n: int, model_import: str, sym_import: str, laws_import: str, hashes: list,
                  prefix: list, states: list, values: dict, tables: dict, lit, note: str) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{t}()" for t, _h in tb]
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", "", f"# class counter: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = UP._prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    lines += [f"def cz() -> {{{call('sy_ok', n, [state] + bnames, targs)} == False{{}} : Bool}}:\n  {{==}}", ""]
    lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
    tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"


def inhabitant_proof(law: dict, n: int, model_import: str, sym_import: str, laws_import: str, hashes: list,
                     prefix: list, states: list, values: dict, tables: dict, lit) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    targs = [f"t_{t}()" for t, _h in tb]
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", ""]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = UP._prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    lines += [f"def ch() -> {{{call('sy_hit', n, [state] + bnames, targs)} == True{{}} : Bool}}:\n  {{==}}", ""]
    tup = "ch()"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    for t in reversed(targs):
        tup = f"({t}, {tup})"
    lines.append(f"def Laws.nv_{lid.lower()}():\n  {tup}")
    return "\n".join(lines) + "\n"


class NoProof(ValueError):
    pass


def constructors(model_text: str) -> dict:
    """{constructor: [(field, type)]} of every constructor of the model's sum types (one per line of a type block)."""
    out: dict = {}
    for block in re.finditer(r"(?m)^type \w+(?:<[^>]*>)? is Data:\n((?:  \w+\{[^\n]*\}\n)+)", model_text):
        for line in block.group(1).splitlines():
            m = re.match(r"^  (\w+)\{(.*)\}$", line)
            if not m:
                continue
            parts, depth, cur = [], 0, ""
            for ch in m.group(2):
                depth += (ch == "<") - (ch == ">")
                if ch == "," and depth == 0:
                    parts.append(cur)
                    cur = ""
                else:
                    cur += ch
            parts.append(cur)
            out[m.group(1)] = [(f.split(":", 1)[0].strip(), f.split(":", 1)[1].strip()) for f in parts if ":" in f]
    return out


class SymLit(UP.Lit):
    """Witness literals with the sym section's records (UOS, UOb) qualified by U in typed rendering as well, and the
    model's sum-type constructors (an act's A_<action>) typed from their declarations."""

    def __init__(self, recs: dict, trace_records: set, ctors: dict | None = None):
        super().__init__(recs, trace_records)
        self.ctors = dict(ctors or {})

    def typed(self, v, ty: str) -> str:
        if isinstance(v, dict) and "$r" in v:
            name = v["$r"]
            vals = v.get("f") or {}
            if name in self.mine:
                fs = self.recs.get(name) or []
                return f"U.{name}{{" + ", ".join(self.typed(vals[f], t) for f, t in fs) + "}"
            if self.recs.get(name) is None and name in self.ctors:
                fs = self.ctors[name]
                return f"M.{name}{{" + ", ".join(self.typed(vals[f], t) for f, t in fs) + "}"
        return super().typed(v, ty)


def sentinel_proof(law: dict, n: int, site_term, action: str, actions: list[str], model_import: str,
                   sym_import: str, laws_import: str, hashes: list) -> str:
    """The proof of a sentinel law whose site writes the clock (see the module docstring), or NoProof."""
    if site_term != ["env", "block.timestamp"]:
        raise NoProof(NO_PROOF["sentinel"])
    tb = P3.tabs_binders(hashes)
    if [t for t, _h in tb] != ["kh"]:
        raise NoProof("the sentinel proof is written for one keccak256 table")
    a = bname(action)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", "",
             "# class clock_site: the site writes the act's own clock, nonzero by the premise",
             "def imp_and_self(c: Bool, p: Bool) -> {U.ux_imp(Bool.and(c, p), p) == True{} : Bool}:",
             "  match c p:"]
    for c in ("True{}", "False{}"):
        for p in ("True{}", "False{}"):
            lines += [f"    case {c} {p}:", "      {==}"]
    lines += ["", f"def Laws.{law_name(law['law_id'], False)}(kh, s, r_s, x):", "  match x:"]
    for cn in actions:
        if cn == a:
            lines += [f"    case M.A_{cn}{{+ar, +en}}:",
                      f"      imp_and_self(U32.is_eq(M.gx_{a}_cd(M.xr_{a}(M.gh_get_st(s), ar, en, kh)), 0), "
                      f"M.w_nz(M.ge_e_block_timestamp(en)))"]
        else:
            lines += [f"    case M.A_{cn}{{_, _}}:", "      {==}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------------------ the split counter-law
def _generic(sub: str, n: int, act: str, role: str, a_act: str, b_act: str, hit: bool = False) -> tuple[str, list, list]:
    """The generic lemma gz of a counter-law over variables only (no literal: both kernels check it by rewriting and
    one unfolding of the claim), and the shape it is applied at: ([(hypothesis name, its type over the variables)],
    [(literal name, its Bend type, the term its lemma equates with it, over the variables)]). gz proves
    {sy_ok_<n>(g, binders.., kh) == False} from each hypothesis {term == literal} and the last one, {the claim's body
    over the literals == False}, rewriting top-level positions of the goal (Equal.cong with a function argument is
    not accepted by BendTT, these are). With hit (omega only), the lemma hz proves {sy_hit_<n>(..) == True} the same
    way: the inhabitant's runs are the counter-law's four."""
    if sub in ("tau", "pi"):
        if sub == "tau":
            bs = [("d", "M.W")]
            prem = f"Bool.and(U.sy_is_{act}(x), Bool.and(U.sy_fits_g(g, d), U.sy_fits_x(x, d)))"
            gx, gs, back = "U.sy_tau_x(x, d)", "U.sy_tau_g(g, d)", (lambda u: f"U.sy_tau_uos({u}, d)")
        else:
            bs = [("a", "M.W"), ("b", "M.W")]
            prem = (f"Bool.and(U.sy_is_{act}(x), Bool.and(Bool.not(M.w_eq(a, b)), Bool.and(U.sy_mem_{role}(g, a), "
                    f"U.sy_mem_{role}(g, b))))")
            gx, gs, back = "U.sy_pi_x(x, a, b)", "U.sy_pi_g(g, a, b)", (lambda u: f"U.sy_pi_uos_{act}({u}, a, b)")
        lits = [("px", "M.HAct", gx), ("ps", "M.GSt", gs), ("u2", "U.UOS", "U.ux_ostep(px, ps, kh)"),
                ("u1", "U.UOS", "U.ux_ostep(x, g, kh)"), ("pu1", "U.UOS", back("u1"))]
        fin = f"U.ux_imp({prem}, U.sy_uos_eq(u2, pu1))"
        r1 = "U.ux_ostep(x, g, kh)"
        chain = [("efin", "_"),
                 ("epu1", f"U.ux_imp({prem}, U.sy_uos_eq(u2, _))"),
                 ("eu1", f"U.ux_imp({prem}, U.sy_uos_eq(u2, {back('_')}))"),
                 ("eu2", f"U.ux_imp({prem}, U.sy_uos_eq(_, {back(r1)}))"),
                 ("eps", f"U.ux_imp({prem}, U.sy_uos_eq(U.ux_ostep(px, _, kh), {back(r1)}))"),
                 ("epx", f"U.ux_imp({prem}, U.sy_uos_eq(U.ux_ostep(_, {gs}, kh), {back(r1)}))")]
    else:
        bs = [("y", "M.HAct")]
        prem = f"Bool.and(U.sy_is_{a_act}(x), U.sy_is_{b_act}(y))"
        oks = "Bool.and(U32.is_eq(U.sy_code(ux), 0), U32.is_eq(U.sy_code(uy), 0))"
        lits = [("ux", "U.UOS", "U.ux_ostep(x, g, kh)"), ("uy", "U.UOS", "U.ux_ostep(y, g, kh)"),
                ("uxy", "U.UOS", "U.ux_ostep(y, U.sy_post(ux), kh)"), ("uyx", "U.UOS", "U.ux_ostep(x, U.sy_post(uy), kh)")]
        # the claim's outer connectives: ux_imp for the counter-law's sy_ok, Bool.and for the inhabitant's sy_hit
        f, md = ("Bool.and", "h") if hit else ("U.ux_imp", "c")
        fin = f"{f}({prem}, {f}({oks}, U.sy_om_{n}_{md}(uxy, uyx)))"
        head = [("efin", "_")]
        if not hit:
            # the counter-law's last comparison, sy_om_<n>_c unfolded: the two orders' stores, each filtered to its
            # sink-reaching entries (U.sy_snk) by a lemma of its own, compared as literals
            snk = lambda u: f"U.sy_snk(U.sy_sl(U.sy_st_of(U.sy_post({u}))))"  # noqa: E731
            lits += [("fx", "List<&2, M.KV>", snk("uxy")), ("fy", "List<&2, M.KV>", snk("uyx"))]
            ok2 = "Bool.and(U32.is_eq(U.sy_code(uxy), 0), U32.is_eq(U.sy_code(uyx), 0))"
            fin = f"U.ux_imp({prem}, U.ux_imp({oks}, U.ux_imp({ok2}, U.sy_sink_eq2(fx, fy))))"
            head += [("efy", f"U.ux_imp({prem}, U.ux_imp({oks}, U.ux_imp({ok2}, U.sy_sink_eq2(fx, _))))"),
                     ("efx", f"U.ux_imp({prem}, U.ux_imp({oks}, U.ux_imp({ok2}, U.sy_sink_eq2(_, {snk('uyx')}))))")]
        chain = head + [
                 ("euyx", f"{f}({prem}, {f}({oks}, U.sy_om_{n}_{md}(uxy, _)))"),
                 ("euxy", f"{f}({prem}, {f}({oks}, U.sy_om_{n}_{md}(_, U.ux_ostep(x, U.sy_post(uy), kh))))"),
                 ("euy", f"{f}({prem}, U.sy_om_{n}_{md}2(ux, _, x, y, kh))"),
                 ("eux", f"{f}({prem}, U.sy_om_{n}_{md}2(_, U.ux_ostep(y, g, kh), x, y, kh))")]
    if hit and sub != "omega":
        raise ValueError("the split inhabitant is written for omega (tau's and pi's sy_hit is their premise alone)")
    fn, val, lemma = ("sy_hit", "True", "hz") if hit else ("sy_ok", "False", "gz")
    names = ["g", "x"] + [b for b, _t in bs] + ["kh"]
    sig = (["-g: M.GSt", "-x: M.HAct"] + [f"-{b}: {t}" for b, t in bs] + ["-kh: List<&2, M.HKB>"]
           + [f"-{k}: {t}" for k, t, _e in lits])
    hyps = [(f"e{k}", f"{{{term} == {k} : {t}}}") for k, t, term in lits] + [("efin", f"{{{fin} == {val}{{}} : Bool}}")]
    sy = f"U.{fn}_{n}({', '.join(names)})"
    lines = [f"def {lemma}({', '.join(sig + [f'{h}: {ty}' for h, ty in hyps])}) -> {{{sy} == {val}{{}} : Bool}}:"]
    for h, hole in chain:
        lines.append(f"  %{h} : {{{sy} == {hole} : Bool}}")
    lines.append("  {==}")
    return "\n".join(lines) + "\n", hyps, lits


def counter_proof_split(law: dict, n: int, sub: str, model_import: str, sym_import: str, laws_import: str,
                        hashes: list, prefix: list, states: list, values: dict, tables: dict, lit, runs: dict,
                        basis: dict, note: str) -> str:
    """The counter-law proof with one kernel conversion per run of the claim (A30's shape): each run's literal result,
    and each generator's image, a lemma {term == literal} by computation over literals only (the kernels share
    nothing: an image passed unevaluated would be recomputed at every read of the state); the last lemma compares
    literals; gz (_generic) assembles them into sy_ok_<n> == False at the witness."""
    return _split(law, n, sub, model_import, sym_import, laws_import, hashes, prefix, states, values, tables, lit, runs,
                  basis, note, hit=False)


def inhabitant_proof_split(law: dict, n: int, model_import: str, sym_import: str, laws_import: str, hashes: list,
                           prefix: list, states: list, values: dict, tables: dict, lit, runs: dict, basis: dict,
                           note: str) -> str:
    """The omega inhabitant's proof in the counter-law's split shape: sy_hit_<n> == True at the inhabitant by hz, the
    four runs each one conversion (the plain proof's single conversion of sy_hit is one BendTT does not accept)."""
    return _split(law, n, "omega", model_import, sym_import, laws_import, hashes, prefix, states, values, tables, lit,
                  runs, basis, note, hit=True)


def _split(law: dict, n: int, sub: str, model_import: str, sym_import: str, laws_import: str, hashes: list,
           prefix: list, states: list, values: dict, tables: dict, lit, runs: dict, basis: dict, note: str,
           hit: bool) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    if [t for t, _h in tb] != ["kh"]:
        raise ValueError("the split counter-law is written for one keccak256 table")
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {sym_import} as U",
             f"import {laws_import} as Laws", "", f"# class {'inhabitant_split' if hit else 'counter_split'}: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = UP._prefix_defs(tb, prefix, states, lit)
    lines += body
    bl, bnames = _binder_defs(law, values, lit)
    lines += bl
    act = bname(basis.get("action") or "")
    gz, hyps, lits = _generic(sub, n, act, bname(basis.get("role") or ""), bname(basis.get("a") or ""),
                              bname(basis.get("b") or ""), hit=hit)
    lines += [gz]
    sub_map = {"g": state, "x": "b_x()", "kh": "t_kh()"}
    for b, _t in binders(law)[1:]:
        sub_map[b] = f"b_{b}()"
    for k, _t, _e in lits:
        sub_map[k] = f"l_{k}()"

    def inst(text: str) -> str:
        return re.sub(r"(?<![\w.])(" + "|".join(sorted(map(re.escape, sub_map), key=len, reverse=True)) + r")(?![\w(])",
                      lambda m: sub_map[m.group(1)], text)
    for k, t, _e in lits:
        lines += [f"def l_{k}() -> {t}:\n  {lit.typed(runs[k], re.sub(r'(?<![\w.])[MU][.]', '', t))}", ""]
    for h, ty in hyps:
        lines += [f"def {h}() -> {inst(ty)}:\n  {{==}}", ""]
    names = ["g", "x"] + [b for b, _t in binders(law)[1:]] + ["kh"]
    args = [sub_map[v] for v in names] + [f"l_{k}()" for k, _t, _e in lits] + [f"{h}()" for h, _ty in hyps]
    if hit:
        lines += [f"def ch() -> {{{call('sy_hit', n, [state] + bnames, ['t_kh()'])} == True{{}} : Bool}}:\n"
                  f"  hz({', '.join(args)})", ""]
        tup = "ch()"
    else:
        lines += [f"def cz() -> {{{call('sy_ok', n, [state] + bnames, ['t_kh()'])} == False{{}} : Bool}}:\n"
                  f"  gz({', '.join(args)})", ""]
        lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
        tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for b in reversed(bnames):
        tup = f"({b}, {tup})"
    tup = f"({state}, ({chain}, {tup}))"
    tup = f"(t_kh(), {tup})"
    lines.append(f"def Laws.{('nv_' + lid.lower()) if hit else law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"
