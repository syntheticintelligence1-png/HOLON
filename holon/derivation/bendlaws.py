"""I89 stage 2 (the contract is the docstring of tests_m3/test_derivation_bend.py, rules S1-S6): I88's frozen
derivation laws decided by the checker over the consumer's Bend model, as I88's decider's consumer model.

  holon derivation decide --model holon.derivation.bendlaws      (I88's decider; consumer_model(root) is here)
  python -m holon derivation bend-decide [--check]               the same run, and results/M3/derivation/bend/

The product module gen/M3/derivation/bend/product.bend (generated here, holon.derivation.bendproof writes the proofs)
imports the consumer model (holon.derivation.bendgen), the committing contract's typed model (holon.sorts.model3;
Reach is its Reach over its keccak table) and I24's linked header component, and defines the terms of I88's
vocabulary from the documents and the sidecars:

  the commit (I85's J3, on the typed model)   is_<action>; last_ok (the step's check code is 0); the committed header
                                              (the preimage, in the keccak table, of the word the step writes to the
                                              header family's register, its key compiled by the typed model's own
                                              compiler, holon.undo.trace); committed_ok_<G> / committed_<G> (the header
                                              component's getter G); input_<m> (a member of the commit parameter)
  the join (J1, J2)                           batch_of: the consumer's batch of the commit, cb(p) in its blobs field,
                                              the contexts argument (or nil) in its contexts field
  the consumer                                derive_ok, txs_data (the decoder's argument: the run with a decoder that
                                              stops it there), derived_<F>, derived_sum_<f>, derived_blocks, trailing,
                                              derived_batch (the receiver, its references resolved), circuit_accepts
                                              (circ of the step's statement: the committed header and cb(p))
  the hypotheses                              ok_payload, ok_txs (a transaction is an opaque token, M2's convention: n
                                              as n zero bytes) and HypB, HypT, HypC_* as types (their frozen
                                              statements, every premise kept)

A law is rendered from its frozen IR statement: the law (LAWS.bend: law_id.lower(), every binder and premise as `for`)
or its counter-law ("cl_" + law_id.lower(), the exs form: every binder and premise a witness, the claim negated). A
Reach binder is the typed model's (kh, s, r_s: Reach<kh, s>), the established rendering of the document's keccak256.
Nothing here names a target: names come from the documents, the sidecars and the generated models.
"""
