"""I89 stage 2: the equivalence of a rendering deviation, checked (the contract is the docstring of
tests_m3/test_derivation_bend.py; the coordinator's rule: equivalence is checked, never argued).

I88's term blobs_match is a Bool (its vocabulary: x's blob hashes, blobhash(i), are vh of cb(p)'s blobs in order, then
zero). It applies vh to every blob, and a Bend closure is affine, so no Bend def computes it from vh. The product module
(holon.derivation.bendlaws) renders the law premise `blobs_match == true` as the proposition the Bool decides, over
exactly the prefix the Bool checks (bm_rel: each index below the longer of the hashes and the blobs), and states the
Bool itself on vh's image list gs of the blobs (bm_bool, blobs_match_b; imgs ties gs to vh). This module writes
gen/M3/derivation/bend/equiv/LAWS.bend and PROOF.bend:

  blobs_match_of_bool   for every gs with imgs(vh, cb(p), gs): is_true(blobs_match_b(x, gs)) -> blobs_match(x, p, cb, vh)
  bool_of_blobs_match   for every such gs: blobs_match(x, p, cb, vh) -> is_true(blobs_match_b(x, gs))
  imgs_unique           the image list is unique: imgs(vh, bl, g1) -> imgs(vh, bl, g2) -> g1 == g2

The proofs are generated: Word.cmp, U32.is_eq and the typed model's word equality w_eq decide equality (by induction on
the word's width and over the word's limbs, as the typed model declares them), then an induction over the two lists.
Bend and BendTT check the pair; the gate (holon.derivation.bendgate) requires both. Nothing here names a target.
"""
from __future__ import annotations

