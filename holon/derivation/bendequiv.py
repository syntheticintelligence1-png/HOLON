def limbs(typed_text: str) -> list:
    """The typed model's word W: its limbs' names, each a U32."""
    m = re.search(r"(?m)^type W is Data:\n  W\{([^}]*)\}", typed_text)
    if not m:
        raise Unsupported("the typed model declares no word type W")
    out = []
    for f in m.group(1).split(","):
        n, _, t = f.partition(":")
        if t.strip() != "U32":
            raise Unsupported(f"the word's limb {n.strip()} is not a U32")
        out.append(n.strip())
    return out


def w_eq_body(n: int) -> str:
    """The typed model's w_eq over n limbs, as it must read for the proofs below (checked against the model's text)."""
    body = f"U32.is_eq(a{n - 1}, b{n - 1})"
    for i in range(n - 2, -1, -1):
        body = f"Bool.and(U32.is_eq(a{i}, b{i}), {body})"
    return body


