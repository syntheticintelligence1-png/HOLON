def word_text(ls: list) -> str:
    """w_eq_sound, w_refl and w_eq_complete over the typed model's word of len(ls) limbs."""
    n = len(ls)
    A = [f"a{i}" for i in range(n)]
    B = [f"b{i}" for i in range(n)]

    def chain(i: int, xs: list, ys: list) -> str:
        if i == n - 1:
            return f"U32.is_eq({xs[i]}, {ys[i]})"
        return f"Bool.and(U32.is_eq({xs[i]}, {ys[i]}), {chain(i + 1, xs, ys)})"
    pa, pb = ", ".join("+" + a for a in A), ", ".join("+" + b for b in B)
    out = ["# ---------------------------------------------------------------- the typed model's w_eq decides equality",
           "def w_eq_sound(a: M.W, b: M.W) -> {M.w_eq(a, b) == True{} : Bool} -> {a == b : M.W}:", "  match a b:",
           f"    case M.W{{{pa}}} M.W{{{pb}}}:", "      +e0 =>"]
    for i in range(n - 1):
        out.append(f"        +e{i + 1} = and_r(U32.is_eq(a{i}, b{i}), {chain(i + 1, A, B)}, e{i})")
    for i in range(n):
        tgt = A[:i] + ["_"] + B[i + 1:]
        fact = f"and_l(U32.is_eq(a{i}, b{i}), {chain(i + 1, A, B)}, e{i})" if i < n - 1 else f"e{n - 1}"
        out.append(f"        %u_eq(a{i}, b{i}, {fact}) : {{M.W{{{', '.join(A)}}} == M.W{{{', '.join(tgt)}}} : M.W}}")
    out += ["        {==}", "", "def w_refl(a: M.W) -> {True{} == M.w_eq(a, a) : Bool}:", "  match a:",
            f"    case M.W{{{pa}}}:"]
    for i in range(n):
        parts = ["True{}" if j < i else ("_" if j == i else f"U32.is_eq(a{j}, a{j})") for j in range(n)]
        s = parts[-1]
        for q in reversed(parts[:-1]):
            s = f"Bool.and({q}, {s})"
        out.append(f"      %u_refl(a{i}) : {{True{{}} == {s} : Bool}}")
    out += ["      {==}", "",
            "def w_eq_complete(a: M.W, b: M.W) -> {a == b : M.W} -> {M.w_eq(a, b) == True{} : Bool}:", "  +e =>",
            "    %e : {M.w_eq(a, _) == True{} : Bool}", "    Equal.sym(Bool, True{}, M.w_eq(a, a), w_refl(a))", ""]
    return "\n".join(out)


def texts(I: Inputs, product_path) -> dict:
    """{path: text} of the equivalence's LAWS.bend and PROOF.bend, beside the product module."""
    ip, ttext, _key, _slot = I.typed()
    ls = limbs(ttext)
    want = w_eq_body(len(ls))
    m = re.search(r"(?m)^def w_eq\(a: W, b: W\) -> Bool:\n  match a b:\n    case W\{([^}]*)\} W\{([^}]*)\}:\n      (.*)$",
                  ttext)
    if not m or [x.strip() for x in m.group(1).split(",")] != [f"a{i}" for i in range(len(ls))] \
            or [x.strip() for x in m.group(2).split(",")] != [f"b{i}" for i in range(len(ls))] \
            or m.group(3).strip() != want:
        raise Unsupported("the typed model's w_eq is not the limbs' U32.is_eq chain the proofs read")
    d = product_path.parent / DIR
    imports = [("C", rel_import(d, I.root / I.model_rel)), ("M", rel_import(d, ip)), ("P", rel_import(d, product_path))]
    head = [EHEADER, "import Base"] + [f"import {p} as {a}" for a, p in imports]
    laws = "\n".join(head) + "\n" + LAWS
    proof = "\n".join(head + ["import ./LAWS.bend as Laws", ""]) + "\n" + GENERIC + "\n" + word_text(ls) + "\n" + \
        LISTS + PROOFS
    return {d / "LAWS.bend": laws, d / "PROOF.bend": proof}
