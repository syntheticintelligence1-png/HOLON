# ====================================================================== literals
def nat_list(bs) -> str:
    return "[" + ", ".join(f"{int(b)}n" for b in bs) + "]" if len(bs) else "Nil{}"


def u32_list(bs) -> str:
    return "[" + ", ".join(str(int(b)) for b in bs) + "]" if len(bs) else "Nil{}"


def word_lit(v: int) -> str:
    if v == 0:
        return "M.w0()"
    return "M.w_of_limbs([" + ", ".join(str((v >> (32 * i)) & 0xFFFFFFFF) for i in range(8)) + "])"


def kh_lit(kh: dict) -> str:
    rows = []
    for k, v in sorted(kh.items()):
        b = bytes.fromhex(k[2:])
        rows.append("M.HKB{" + u32_list(list(b)) + ", " + word_lit(int(v)) + "}")
    return "[" + ", ".join(rows) + "]" if rows else "Nil{}"


def succ(n: int, base: str) -> str:
    out = base
    for _ in range(n):
        out = f"1n+({out})"
    return out


# ====================================================================== the commit on the typed model
class Commit:
    """The witness's commit: the typed model's step from its deployment state, the external calls answered by I85's
    product rules (the sidecar's calls by function name), the keccak table the real keccak of every key it reads."""

    def __init__(self, root: Path, I):
        from ..sorts import run3
        from ..machine import load_extracted
        self.root, self.I = root, I
        self.ctx = run3.Ctx("M3", root, None, None, None, log=lambda *a: None)
        self.ev, self.init, self.factory, self.mm, self.doc = self.ctx.model(I.rollup_rel)
        self.mach = load_extracted(I.rollup_rel, root)
        self.rules = {}
        for c in I.pr["calls"]:
            sig = self.mach.call_signature(c["fn"])
            if sig is None or not sig.get("selector"):
                raise Unsupported(f"the call {c['fn']} has no selector")
            self.rules[sig["selector"].lower()] = c["answer"]

    def close(self):
        self.ctx.close()

    def step(self, args: dict, env: dict) -> dict:
        """{"code", "act" (the HAct literal), "kh" (the keccak table), "env"} of the commit from the deployment state."""
        from ..sorts import search3 as S3
        from ..sorts.proofs3 import Lit
        M = self.factory()
        M.hints = S3.Hints(None)
        st = S3.Step(self.I.action, args, dict(env, calls=[]))
        code = None
        for _ in range(16):
            code, _n, calls = M.run_step(M.s0(), st, save=False)
            have = {(c["to"], c["data"]) for c in st.env["calls"]}
            new = False
            for to, data in calls:
                if to is None:
                    continue
                to = "0x" + to[-40:].lower()
                if (to, data) in have:
                    continue
                rule = self.rules.get(data[:10].lower())
                if rule == "true":
                    ret = "0x%064x" % 1
                elif rule == "timestamp":
                    ret = "0x%064x" % int(st.env["block.timestamp"])
                else:
                    raise Unsupported(f"no product rule answers the call {data[:10]}")
                st.env["calls"].append({"to": to, "data": data, "ok": True, "ret": ret})
                new = True
            if not new:
                break
        st.env.pop("_unanswered", None)
        env_full = M.full_env(st)
        r, kh, _sh = self.ev.run_fix(self.I.action, self.init.get("storage") or {}, args, env_full)
        out = self.ev.outcome(self.I.action, r.out, self.init.get("storage") or {})
        act = Lit(self.ev.recs).text(M.act(st))
        return {"code": code, "status": out["status"], "guard": out.get("guard"), "act": act, "kh": kh,
                "env": {k: v for k, v in env_full.items() if k != "code"}}


# ====================================================================== the node driver
def node_trace(mjs: Path, req: dict, stack_mb: int = 2048) -> dict:
    from .. import bend
    node = bend.config().get("node", "node")
    node = shutil.which(node) or node
    launcher = [sys.executable, "-I", "-S", "-c", bend._STACK_LAUNCHER, str(stack_mb * 1024 * 1024)]
    p = subprocess.run(launcher + [node, f"--stack-size={stack_mb * 1000}", str(DRIVER)],
                       input=json.dumps({"module": str(mjs), **req}), capture_output=True, text=True, timeout=7200)
    if p.returncode != 0:
        raise DerivationError(f"the witness module's evaluation failed: {p.stderr[-2000:]}")
    return json.loads(p.stdout)


def compile_module(rel: str, text: str, deps: dict) -> Path:
    """A module compiled to an ES module by the local Bend in the cache (outside the repository): a mirror holding it at
    rel beside copies of the files it imports (deps: mirror path -> source file), keyed by all their contents."""
    from .. import bend
    from .bendrun import cache_dir
    key = {"rel": rel, "text": hashlib.sha256(text.encode()).hexdigest(),
           "deps": {k: hashlib.sha256(Path(v).read_bytes()).hexdigest() for k, v in sorted(deps.items())}}
    d = cache_dir() / "witness" / hashlib.sha256(json.dumps(key, sort_keys=True).encode()).hexdigest()[:32]
    src = d / rel
    mjs = src.with_suffix(".mjs")
    if mjs.is_file():
        return mjs
    for r, s in deps.items():
        p = d / r
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.is_file():
            shutil.copyfile(s, p)
    src.parent.mkdir(parents=True, exist_ok=True)
    src.write_text(text, encoding="utf-8")
    part = src.with_suffix(".part.mjs")
    r = bend.run([src.name, "-o", part.name], cwd=src.parent, timeout=3600)
    if r.code != 0 or not part.is_file():
        raise DerivationError(f"bend could not compile the witness module: {r.out[-2000:]}")
    os.replace(part, mjs)
    return mjs


# ====================================================================== text helpers
def qualify(code: str, names: set, prefix: str, values: set = frozenset()) -> str:
    """The module's names in code prefixed: calls and constructors, and the defs in values used as values."""
    def sub(m):
        n = m.group(1)
        return (prefix + n if n in names else n) + m.group(2)
    code = re.sub(r"(?<![\w.])([A-Za-z_]\w*)(\s*[({])", sub, code)
    if values:
        code = re.sub(r"(?<![\w.])([A-Za-z_]\w*)(?![\w({.])", lambda m: prefix + m.group(1) if m.group(1) in values
                      else m.group(1), code)
    return code


def def_bodies(text: str) -> dict:
    """{name: (params text, return type, one-line body)} of a module's one-line defs."""
    out = {}
    for m in re.finditer(r"(?m)^def (\w+)\((.*)\) -> (.*):\n  ([^\n]+)\n\n", text):
        out[m.group(1)] = (m.group(2), m.group(3), m.group(4))
    return out


def param_names(params: str) -> list:
    return [p.split(":")[0].strip().lstrip("+-") for p in split_top(params)]


def fn_params(params: str) -> list:
    """The indices of a def's function-typed parameters (a closure: its type an arrow)."""
    return [i for i, p in enumerate(split_top(params)) if "->" in p.split(":", 1)[-1]]


def subst_vars(code: str, sub: dict) -> str:
    """Variables replaced by terms (an applied function variable too); qualified names and constructors are kept."""
    return re.sub(r"(?<![\w.])([a-z_]\w*)(?![\w{])", lambda m: sub.get(m.group(1), m.group(1)), code)


# ====================================================================== the witness's definitions
CODEC_TYPES = "List<&2, List<&2, U32>>"


def codec_defs(B: bytes) -> list:
    """et_w / dt_w: token 0 is B (when B is not empty), token 1+k (every token, when B is empty) the marker 256 then k;
    dt_w parses a stream back, its accumulator reversed at the end."""
    A = CODEC_TYPES
    t = bool(B)
    out = []
    if t:
        out.append(f"def tbl() -> List<&2, Nat>:\n  {nat_list(list(B))}\n")
        out.append("def enc1(n: Nat, +rest: List<&2, Nat>) -> List<&2, Nat>:\n  match n:\n    case 0n:\n"
                   "      List.append(&2, Nat, tbl(), rest)\n    case 1n+k:\n      Con{256n, Con{k, rest}}\n")
    else:
        out.append("def enc1(n: Nat, +rest: List<&2, Nat>) -> List<&2, Nat>:\n  Con{256n, Con{n, rest}}\n")
    out += [
        "def et_w(u: List<&2, Nat>) -> List<&2, Nat>:\n  match u:\n    case Nil{}:\n      Nil{}\n    case Con{n, t}:\n"
        "      enc1(n, et_w(t))\n",
        f"type PS is Data:\n  PB{{acc: {A}}}\n  PT{{acc: {A}}}\n  PM{{rem: List<&2, Nat>, acc: {A}}}\n  PE{{}}\n",
        f"def rev_app(xs: {A}, ys: {A}) -> {A}:\n  match xs:\n    case Nil{{}}:\n      ys\n    case Con{{a, t}}:\n"
        "      rev_app(t, Con{a, ys})\n",
        "def fin(st: PS) -> C.DtAns:\n  match st:\n    case PB{acc}:\n      C.DtOk{False{}, rev_app(acc, Nil{})}\n"
        "    case _:\n      C.DtErr{C.VNil{}}\n",
        f"def tb_rest(rem: List<&2, Nat>, acc: {A}) -> PS:\n  match rem:\n    case Nil{{}}:\n"
        "      PB{Con{P.tok(0n), acc}}\n    case Con{r, rs}:\n      PM{Con{r, rs}, acc}\n",
        f"def tb_next(c: Bool, rem: List<&2, Nat>, acc: {A}) -> PS:\n  match c:\n    case True{{}}:\n"
        "      tb_rest(rem, acc)\n    case False{}:\n      PE{}\n",
        f"def start(t: List<&2, Nat>, +b: Nat, acc: {A}) -> PS:\n  match t:\n    case Nil{{}}:\n      PE{{}}\n"
        "    case Con{r, rs}:\n      tb_next(Nat.is_eq(b, r), rs, acc)\n",
        f"def nb(c: Bool, +b: Nat, acc: {A}) -> PS:\n  match c:\n    case True{{}}:\n      PT{{acc}}\n"
        f"    case False{{}}:\n      {'start(tbl(), b, acc)' if t else 'PE{}'}\n",
        "def nxt(st: PS, +b: Nat) -> PS:\n  match st:\n    case PB{acc}:\n      nb(Nat.is_eq(b, 256n), b, acc)\n"
        f"    case PT{{acc}}:\n      PB{{Con{{P.tok({'1n+b' if t else 'b'}), acc}}}}\n    case PM{{rem, acc}}:\n"
        "      start(rem, b, acc)\n    case PE{}:\n      PE{}\n",
        "def pr(bs: List<&2, Nat>, st: PS) -> C.DtAns:\n  match bs:\n    case Nil{}:\n      fin(st)\n"
        "    case Con{b, t}:\n      pr(t, nxt(st, b))\n",
        "def dt_w(bs: List<&2, Nat>) -> C.DtAns:\n  pr(bs, PB{Nil{}})\n",
    ]
    return out


def codec_proofs(B: bytes) -> list:
    A = CODEC_TYPES
    head = (f"def hypt_go(u: List<&2, Nat>, acc: {A}) -> {{pr(et_w(u), PB{{acc}}) == C.DtOk{{False{{}}, "
            f"rev_app(acc, P.toks(u))}} : C.DtAns}}:\n  match u:\n    case Nil{{}}:\n      {{==}}\n    case Con{{n, t}}:\n")
    if B:
        body = ("      match n:\n        case 0n:\n          hypt_go(t, Con{P.tok(0n), acc})\n        case 1n+k:\n"
                "          hypt_go(t, Con{P.tok(1n+k), acc})\n")
    else:
        body = "      hypt_go(t, Con{P.tok(n), acc})\n"
    return ["# HypT's instance: by induction on u, the parser's accumulator generalised", head + body,
            "def hypt_w(u: List<&2, Nat>) -> {dt_w(et_w(u)) == P.ok_txs(u) : C.DtAns}:\n  hypt_go(u, Nil{})\n"]


class Witness:
    """A concrete witness: the commit (Commit.step's act and keccak table), the payload p, the contexts of the
    contexts binders, the blob hash V, the transaction bytes B (the decoder's argument; [] when none)."""

    def __init__(self, act: str, kh: dict, p: bytes, ctxs: dict, V: int, B: bytes):
        self.act, self.kh, self.p, self.ctxs, self.V, self.B = act, kh, p, ctxs, V, B
        self.ts = [0] if B else []

    def defs(self, codec: bool = True) -> list:
        out = ["# ---------------------------------------------------------------- the witness",
               f"def w_kh() -> List<&2, M.HKB>:\n  {kh_lit(self.kh)}\n",
               f"def w_x() -> M.HAct:\n  {self.act}\n",
               f"def w_p() -> List<&2, Nat>:\n  {nat_list(list(self.p))}\n",
               f"def w_ts() -> List<&2, Nat>:\n  {nat_list(self.ts)}\n"]
        for c, b in sorted(self.ctxs.items()):
            out.append(f"def w_{c}() -> List<&2, Nat>:\n  {nat_list(list(b))}\n")
        out += ["# HypB's instance: one blob that is the payload; the blob layer answers its bytes",
                "def cb_w(q: List<&2, Nat>) -> List<&2, C.GV>:\n  [C.VY{P.u32s(q)}]\n",
                "def pl_w(bl: List<&2, C.GV>) -> C.PlAns:\n  match bl:\n    case Con{b, t}:\n      match b:\n"
                "        case C.VY{bs}:\n          C.PlOk{False{}, bs}\n        case _:\n          C.PlOk{False{}, Nil{}}\n"
                "    case Nil{}:\n      C.PlOk{False{}, Nil{}}\n",
                "# the blob hash: a constant word",
                f"def vh_w(b: C.GV) -> M.W:\n  {word_lit(self.V)}\n",
                "# the circuit that accepts every step",
                "def circ_w(st: P.Stmt) -> Bool:\n  True{}\n"]
        if codec:
            out.append("# HypT's instance: a codec of opaque tokens")
            out += codec_defs(self.B)
        return out


# ====================================================================== a counter-law's proof
UNFOLD = ("derive_ok", "txs_data", "trailing", "derived_batch")      # and derived_*, derived_sum_*, derived_blocks
EQS = {"Nat": "Nat.is_eq", "List<&2, Nat>": "P.eq_nats"}


class Gen:
    """The text of one law's files: the module the node driver evaluates (the witness and its runs) and PROOF.bend."""

    def __init__(self, I, product_text: str, consumer_text: str, law: dict, wit: Witness, imports: list,
                 header_alias: str = "H"):
        from .bendlaws import Render
        self.I, self.law, self.wit = I, law, wit
        self.st = law["statement"]
        self.ptext = product_text
        self.pnames = set(re.findall(r"(?m)^def\s+(\w+)\s*\(", product_text)) | \
            set(re.findall(r"(?m)^type\s+(\w+)", product_text)) | \
            {c for body in re.findall(r"(?m)^type\s+\w+[^\n]*\n((?:  \w+\{[^\n]*\n)+)", product_text)
             for c in re.findall(r"(?m)^  (\w+)\{", body)}
        self.bodies = def_bodies(product_text)
        self.pdefs = set(re.findall(r"(?m)^def\s+(\w+)\s*\(", product_text))
        self.entry = Launch(consumer_text, I.info)
        self.imports = imports
        names = [n for n, _t, _d in Render(I).binders(self.st)]
        sub = {"kh": "w_kh()", "r_s": "M.R0{{==}}"}
        for b in self.st["binders"]:
            n, ty = b["name"], b["type"]
            if ty == "Reach":
                sub[n] = "M.gh_s0()"
                sub[f"r_{n}"] = "M.R0{{==}}"
            elif ty == "Act":
                sub[n] = "w_x()"
            elif n in wit.ctxs:
                sub[n] = f"w_{n}()"
            elif n in ("p", "ts"):
                sub[n] = f"w_{n}()"
            elif ty.startswith("Fn<"):
                sub[n] = f"{n}_w"
            else:
                raise Unsupported(f"no witness for the binder {n}: {ty}")
        self.names, self.sub = names, sub
        self.R = Render(I)
        self.runs: dict = {}              # (dtm, ctx) -> run name
        self.lines: list = []
        self.lemmas_open: dict = {}       # (def name, its closure arguments) -> lemma name
        self.steps: dict = {}             # ("go" | "ret", pl, dt) -> step lemma name
        self.bridges: dict = {}           # law-level consumer term -> (name, defs, witness arguments)

    # ------------------------------------------------------------ the witness's terms
    def w(self, term) -> tuple:
        """(Bend text at the witness, type) of an IR term."""
        t, ty = self.R.term(term)
        return subst_vars(t, self.sub), ty

    def run_of(self, dtm: str, ctx: str) -> str:
        key = (dtm, ctx)
        if key not in self.runs:
            self.runs[key] = f"{'m' if 'dt_m' in dtm else 'c'}{len(self.runs)}"
        return self.runs[key]

    # ------------------------------------------------------------ open lemmas (generic, nothing runs)
    def open_lemma(self, name: str, clos: tuple, lname: str) -> str:
        """lname: {body == P.name(params) : T} over variables (a conversion stops at a variable), the closure
        parameters the given closures."""
        params, ret, body = self.bodies[name]
        pn, fn = param_names(params), fn_params(params)
        sub = {pn[i]: c for i, c in zip(fn, clos)}
        keep = []
        for i, p in enumerate(split_top(params)):
            if i not in fn:
                qp = qualify(p, self.pnames, "P.")
                keep.append(re.sub(r"(?<![\w.])(Stmt|BC)(?![\w])", r"P.\1", qp))
        lhs = subst_vars(qualify(body, self.pnames, "P.", self.pdefs - set(pn)), sub)
        call = f"P.{name}({', '.join(sub.get(n, n) for n in pn)})"
        return f"def {lname}({', '.join(keep)}) -> {{{lhs} == {call} : {qualify(ret, self.pnames, 'P.')}}}:\n  {{==}}\n"

    def unfolding(self, call: str) -> tuple:
        """(the lemma application, the body at the call's arguments) of P.<name>(args): the lemma is the def's open
        unfolding at the call's closures, applied to its other arguments."""
        m = re.match(r"P\.(\w+)\((.*)\)$", call)
        name, args = m.group(1), split_top(m.group(2))
        params, _ret, body = self.bodies[name]
        pn, fn = param_names(params), fn_params(params)
        if len(pn) != len(args):
            raise DerivationError(f"{name}: {len(args)} arguments for {len(pn)} parameters")
        key = (name, tuple(args[i] for i in fn))
        if key not in self.lemmas_open:
            self.lemmas_open[key] = f"l_{name}_{sum(1 for k in self.lemmas_open if k[0] == name)}"
        b = subst_vars(qualify(body, self.pnames, "P.", self.pdefs - set(pn)), dict(zip(pn, args)))
        rest = [a for i, a in enumerate(args) if i not in fn]
        return f"{self.lemmas_open[key]}({', '.join(rest)})", b

    @staticmethod
    def first_call(text: str, fn: str) -> str | None:
        i = text.find(fn + "(")
        if i < 0:
            return None
        depth, j = 0, i + len(fn)
        while j < len(text):
            if text[j] == "(":
                depth += 1
            elif text[j] == ")":
                depth -= 1
                if depth == 0:
                    return text[i:j + 1]
            j += 1
        return None

    def value_steps(self, term: str, frame) -> list:
        """The rewrites that take the goal frame(term) to frame(<a closed term>): (lemma, motive) pairs, frame(t) being the
        goal with t in the term's place: the term's unfoldings, its runs replaced by their results."""
        goal = term
        steps = []
        m = re.match(r"P\.(\w+)\(", term)
        fn = m.group(1) if m else None
        unfoldable = fn is not None and (fn in UNFOLD or fn.startswith(("derived_", "derived_sum_")))
        if unfoldable:
            lem, body = self.unfolding(term)
            steps.append((lem, frame("_")))
            goal = body
            while True:                        # inner unfoldings (txs_data in trailing)
                inner = self.first_call(goal, "P.txs_data")
                if inner is None:
                    break
                lem, body = self.unfolding(inner)
                steps.append((lem, frame(goal.replace(inner, "_", 1))))
                goal = goal.replace(inner, body, 1)
            while True:
                call = self.first_call(goal, "P.rm")
                if call is None:
                    break
                args = split_top(call[len("P.rm("):-1])
                r = self.run_of(args[4], args[5])
                steps.append((f"run_{r}()", frame(goal.replace(call, "_", 1))))
                goal = goal.replace(call, f"res_{r}()", 1)
        return steps

    # ------------------------------------------------------------ the law's closures at the witness
    # The translation to BendTT writes a closure variable of the law eta-long (y => cb(y)), so the law instantiated at the
    # witness holds y => (q => cb_w(q))(y), never syntactically the cb_w a lemma names, and the kernel converts without
    # eta: a premise's type would only meet the law's by evaluating both. A statement that mentions the law's closures
    # is therefore a wrapper def over them (W_<name>), applied to the witness's: unfolded, it holds them exactly as the
    # law does. A bridge br_<k> rewrites a consumer term from the law's form to the lemmas' form, over variables (a
    # conversion stops at a variable, so it is cheap).
    def closures(self) -> dict:
        return {n: t for n, t, _d in self.R.binders(self.st) if "->" in t}

    def data_binders(self) -> dict:
        return {n: t for n, t, d in self.R.binders(self.st) if d}

    @staticmethod
    def mentions(text: str, name: str) -> bool:
        return re.search(rf"(?<![\w.]){re.escape(name)}(?![\w])", text) is not None

    def wrap(self, name: str, text: str) -> tuple:
        """(the wrapper def or None, the type at the witness) of a law-level statement."""
        cl = [c for c in self.closures() if self.mentions(text, c)]
        if not cl:
            return None, subst_vars(text, self.sub)
        data = {k: v for k, v in self.sub.items() if k not in cl}
        ps = ", ".join(f"{c}: {self.closures()[c]}" for c in cl)
        d = f"def W_{name}({ps}) -> Type:\n  {subst_vars(text, data)}\n"
        return d, f"W_{name}({', '.join(self.sub[c] for c in cl)})"

    def bridge(self, term: str, ty: str) -> str:
        """The application at the witness of the bridge of a law-level consumer term: {term at the witness's closures ==
        term at the law's}, over the term's data binders."""
        if term not in self.bridges:
            k = len(self.bridges)
            cl = [c for c in self.closures() if self.mentions(term, c)]
            dv = [(n, t) for n, t in self.data_binders().items() if self.mentions(term, n)]
            ts = subst_vars(term, {c: self.sub[c] for c in cl})
            cps = ", ".join(f"{c}: {self.closures()[c]}" for c in cl)
            # erased: a q=2 argument of a closed def is normalised when it is bound (BendTT's val), and the normal
            # form of the witness's step is not the name the goal holds
            dps = ", ".join(f"-{n}: {t}" for n, t in dv)
            dargs = ", ".join(n for n, _t in dv)
            self.bridges[term] = (
                f"br_{k}",
                f"def BR_{k}({cps}{', ' if dv else ''}{dps}) -> Type:\n  {{{ts} == {term} : {ty}}}\n\n"
                f"def br_{k}({dps}) -> BR_{k}({', '.join(self.sub[c] for c in cl)}{', ' if dv else ''}{dargs}):\n"
                "  {==}\n",
                [self.sub[n] for n, _t in dv])
        name, _d, args = self.bridges[term]
        return f"{name}({', '.join(args)})"

    # ------------------------------------------------------------ the plan: premises and claim
    def plan(self) -> dict:
        """{"premises": [(name, kind, data)], "claim": (A_w, B_w, ty, kinds), "values": {val name: (term, ty)}}."""
        from .bendlaws import premise_names as pnames
        pn = pnames(self.st)
        prem = []
        values = {}
        for i, p in enumerate(self.st.get("assume", [])):
            if "hyp" in p:
                prem.append((pn[i], "hyp", p["hyp"]["name"]))
                continue
            a, b = p["eq"]
            if a.get("product") == "blobs_match":
                prem.append((pn[i], "blobs", None))
                values["val_nbh"] = ("List.length(&2, M.W, P.blobhashes(w_x()))", "Nat")
                continue
            aw, ty = self.w(a)
            bw, ty2 = self.w(b)
            ty = ty or ty2
            values[f"val_{pn[i]}_l"] = (aw, ty)
            values[f"val_{pn[i]}_r"] = (bw, ty)
            prem.append((pn[i], "eq", (a, aw, bw, ty)))
        a, b = self.st["claim"]["eq"]
        aw, ty = self.w(a)
        bw, ty2 = self.w(b)
        ty = ty or ty2
        values["val_claim_l"] = (aw, ty)
        values["val_claim_r"] = (bw, ty)
        return {"premises": prem, "claim": (a, b, aw, bw, ty), "values": values}

    @staticmethod
    def consumer_term(t: dict) -> bool:
        k = (t.get("product") or "").split(":")[0]
        return k in ("derive_ok", "txs_data", "derived", "derived_sum", "derived_blocks", "derived_batch",
                     "trailing")

    # ------------------------------------------------------------ the module the node driver evaluates
    def module_text(self, imports: list, codec: bool, values: dict, runs: dict) -> str:
        E = self.entry.E
        lines = ["# GENERATED by holon.derivation.bendproof: a witness module for the node driver (not a proof)",
                 "import Base"] + [f"import {p} as {a}" for a, p in imports] + [""]
        lines += self.wit.defs(codec=codec)
        lines += [
            "def bc_cells(bx: P.BC) -> List<&2, C.GV>:\n  match bx:\n    case P.BC{cells, batch}:\n      cells\n",
            "def bc_batch(bx: P.BC) -> C.GV:\n  match bx:\n    case P.BC{cells, batch}:\n      batch\n",
            "def init_of(bx: P.BC, dtm: List<&2, U32> -> C.DtAns) -> C.MT:\n  match bx:\n    case P.BC{cells, batch}:\n"
            f"      {self.entry.go0('cells', 'batch', 'pl_w', 'dtm')}\n",
            "def stepf(t: C.MT) -> C.MT:\n  C.m_step(t)\n"]
        for (dtm, ctx), r in sorted(runs.items(), key=lambda kv: kv[1]):
            lines += [f"def bc_{r}() -> P.BC:\n  P.batch_of(w_x(), cb_w(w_p()), {ctx})\n",
                      f"def cells_{r}() -> List<&2, C.GV>:\n  bc_cells(bc_{r}())\n",
                      f"def batch_{r}() -> C.GV:\n  bc_batch(bc_{r}())\n",
                      f"def init_{r}() -> C.MT:\n  init_of(bc_{r}(), {dtm})\n"]
        for v, (term, ty) in sorted(values.items()):
            lines.append(f"def {v}() -> {ty}:\n  {term}\n")
        return "\n".join(lines).rstrip("\n") + "\n"

    # ------------------------------------------------------------ the runs' lemmas
    def run_text(self, r: str, dtm: str, ctx: str, js: dict, cells: str, batch: str) -> list:
        states, res = js["states"], js["res"]
        N = len(states)
        out = [f"# ---------------------------------------------------------------- run {r}: P.rm(w_x(), w_p(), cb_w, "
               f"pl_w, {dtm}, {ctx}, P.fuel0()), {N} steps of the machine"]
        out.append(f"def cells_{r}() -> List<&2, C.GV>:\n  {cells}\n")
        out.append(f"def batch_{r}() -> C.GV:\n  {batch}\n")
        out.append(f"def bo_{r}() -> {{P.BC{{cells_{r}(), batch_{r}()}} == P.batch_of(w_x(), cb_w(w_p()), {ctx}) : P.BC}}:\n"
                   "  {==}\n")
        named: dict = {}

        def named_def(kind: str, ty: str, lit: str) -> str:
            key = (kind, lit)
            if key not in named:
                named[key] = f"{kind}_{r}_{sum(1 for k in named if k[0] == kind)}"
                out.append(f"def {named[key]}() -> {ty}:\n  {lit}\n")
            return named[key] + "()"
        S = []
        for s in states:
            pl, dt = s.get("pl") or "pl_w", s.get("dt") or dtm
            st = named_def("st", "List<&2, C.Frame>", s["st"])
            if s["kind"] == "go":
                S.append(("go", named_def("fr", "C.Frame", s["fr"]), st, named_def("h", "List<&2, C.GV>", s["h"]), pl, dt))
            else:
                S.append(("ret", named_def("x", "C.Res", s["x"]), st, pl, dt))
        if not S or S[0][0] != "go" or S[0][4:] != ("pl_w", dtm):
            raise DerivationError(f"run {r}: its first state is not the entry's with the run's closures")
        out.append(f"def res_{r}() -> C.Res:\n  {res}\n")

        def state(s) -> str:
            return f"C.MGo{{{', '.join(s[1:])}}}" if s[0] == "go" else f"C.MRet{{{', '.join(s[1:])}}}"
        go = [state(s) for s in S] + [f"C.MEnd{{res_{r}()}}"]
        out.append(f"def g0_{r}() -> {{{go[0]} == {self.entry.go0(f'cells_{r}()', f'batch_{r}()', 'pl_w', dtm)} : C.MT}}:\n"
                   "  {==}\n")
        for k in range(N):
            out.append(f"def es_{r}_{k}() -> {{{go[k + 1]} == C.m_step({go[k]}) : C.MT}}:\n  {{==}}\n")
        term = f"tr_end(G, res_{r}())"
        for k in range(N - 1, -1, -1):
            lem = self.step_lemma(S[k][0], S[k][-2], S[k][-1])
            term = f"{lem}({succ(N - 1 - k, 'G')}, {', '.join(S[k][1:-2])}, {go[k + 1]}, res_{r}(), es_{r}_{k}(), {term})"
        out.append(f"def chain_{r}(+G: Nat) -> {{res_{r}() == C.m_run({succ(N, 'G')}, {go[0]}) : C.Res}}:\n  {term}\n")
        body, ind = [], "  "
        for d in range(N):
            body.append(f"{ind}match fu{d}:")
            body.append(f"{ind}  case 0n:")
            body.append(f"{ind}    ok => efq({{res_{r}() == C.m_run({succ(d, '0n')}, {go[0]}) : C.Res}}, ok)")
            body.append(f"{ind}  case 1n+{'G' if d == N - 1 else f'fu{d + 1}'}:")
            ind += "    "
        body.append(f"{ind}ok => chain_{r}(G)")
        out.append(f"def fu_{r}(fu0: Nat) -> {{Nat.is_le({N}n, fu0) == True{{}} : Bool}} -> "
                   f"{{res_{r}() == C.m_run(fu0, {go[0]}) : C.Res}}:\n" + "\n".join(body) + "\n")
        fu = "P.fuel0()"
        # run_bc is the machine from its initial state, the cells, the batch and the fuel variables
        out.append(f"def l_rb_{r}(c: List<&2, C.GV>, b: C.GV, F: Nat) -> "
                   f"{{C.m_run(F, {self.entry.go0('c', 'b', 'pl_w', dtm)}) == P.run_bc(P.BC{{c, b}}, F, pl_w, {dtm}) : "
                   "C.Res}:\n  {==}\n")
        rm, _body = self.unfolding(f"P.rm(w_x(), w_p(), cb_w, pl_w, {dtm}, {ctx}, {fu})")
        out.append(
            f"def run_{r}() -> {{res_{r}() == P.rm(w_x(), w_p(), cb_w, pl_w, {dtm}, {ctx}, {fu}) : C.Res}}:\n"
            f"  %{rm} : {{res_{r}() == _ : C.Res}}\n"
            f"  %bo_{r}() : {{res_{r}() == P.run_bc(_, {fu}, pl_w, {dtm}) : C.Res}}\n"
            f"  %l_rb_{r}(cells_{r}(), batch_{r}(), {fu}) : {{res_{r}() == _ : C.Res}}\n"
            f"  %g0_{r}() : {{res_{r}() == C.m_run({fu}, _) : C.Res}}\n"
            f"  fu_{r}({fu}, {{==}})\n")
        return out

    def step_lemma(self, kind: str, pl: str, dt: str) -> str:
        """The name of the lemma of one step from a running ("go") or returning ("ret") state whose closures are pl and
        dt, under a variable fuel F."""
        key = (kind, pl, dt)
        if key not in self.steps:
            self.steps[key] = f"{'tg' if kind == 'go' else 'tt'}_{sum(1 for k in self.steps if k[0] == kind)}"
        return self.steps[key]

    def step_text(self, kind: str, pl: str, dt: str, name: str) -> str:
        if kind == "go":
            ps, s = "fr: C.Frame, st: List<&2, C.Frame>, h: List<&2, C.GV>", f"C.MGo{{fr, st, h, {pl}, {dt}}}"
        else:
            ps, s = "y: C.Res, st: List<&2, C.Frame>", f"C.MRet{{y, st, {pl}, {dt}}}"
        return (f"def {name}(F: Nat, {ps}, s2: C.MT, x: C.Res, es: {{s2 == C.m_step({s}) : C.MT}}, "
                f"ih: {{x == C.m_run(F, s2) : C.Res}}) -> {{x == C.m_run(1n+F, {s}) : C.Res}}:\n"
                "  %es : {x == C.m_run(F, _) : C.Res}\n  ih\n")

    def generic_text(self) -> list:
        return ["# ---------------------------------------------------------------- generic lemmas (variables: nothing "
                "runs)",
                "def sel(b: Bool, A: Type) -> Type:\n  match b:\n    case True{}:\n      A\n    case False{}:\n      Unit\n",
                "def efq(-A: Type, e: {False{} == True{} : Bool}) -> A:\n  %e : sel(_, A)\n  Unit{}\n",
                "# the end of a run, under a variable fuel F",
                "def tr_end(F: Nat, x: C.Res) -> {x == C.m_run(F, C.MEnd{x}) : C.Res}:\n  match F:\n"
                "    case 0n:\n      {==}\n    case 1n+p:\n      {==}\n"]

    # ------------------------------------------------------------ PROOF.bend
    def hyp_args(self, name: str) -> list:
        for p in self.st.get("assume", []):
            if "hyp" in p and p["hyp"]["name"] == name:
                return [a["var"] for a in p["hyp"]["args"]]
        raise DerivationError(f"the law has no premise {name}")

    def hyp_lambda(self, name: str) -> str:
        from .bendlaws import Render
        h = self.I.s88["hypotheses"][name]
        n = len(Render(self.I).binders(h["statement"])) + len(h["statement"].get("assume", []))
        return " ".join(f"a{i} =>" for i in range(n)) + " {==}"

    @staticmethod
    def steps_def(name: str, ty: str, steps: list) -> str:
        out = [f"def {name}() -> {ty}:"] + [f"  %{lem} : {motive}" for lem, motive in steps] + ["  {==}"]
        return "\n".join(out) + "\n"

    def pieces(self, values: dict | None) -> dict:
        """The proof's premises, claim and the lemmas they use (values: the node driver's literals, None to discover the
        runs). A statement over the law's closures is a wrapper's (wrap); a consumer term is first bridged."""
        pl = self.plan()
        pn = premise_names(self.st)
        prem_terms, defs = [], []
        for i, p in enumerate(self.st.get("assume", [])):
            name = pn[i]
            text = self.R.premise(p)
            if "hyp" in p:
                data = p["hyp"]["name"]
                if data == "HypB":
                    prem_terms.append("hypb_w")
                    continue
                if data == "HypT":
                    prem_terms.append("hypt_w")
                    continue
                # a circuit hypothesis whose claim equates two acceptances holds of the circuit that accepts every
                # step (circ_w): both sides compute to True; any other has no instance here
                cl = self.I.s88["hypotheses"][data]["statement"]["claim"]["eq"]
                if not all(isinstance(x, dict) and x.get("product") == "circuit_accepts" for x in cl):
                    raise Unsupported(f"no instance of {data} in a counter-law")
                w, wty = self.wrap(name, text)
                defs += [w] if w else []
                defs.append(f"def pf_{name}() -> {wty}:\n  {self.hyp_lambda(data)}\n")
                prem_terms.append(f"pf_{name}()")
                continue
            a, b = p["eq"]
            w, wty = self.wrap(name, text)
            defs += [w] if w else []
            if a.get("product") == "blobs_match":
                # the witness's one blob: its hash and vh_w's image are the one word; past it both are zero
                n = 1 if values is None else max(1, int(str(values["val_nbh"]).rstrip("n")))
                tup = "Unit{}"
                for _ in range(n):
                    tup = f"({{==}}, {tup})"
                defs.append(f"def pf_{name}() -> {wty}:\n  {tup}\n")
                prem_terms.append(f"pf_{name}()")
                continue
            (A, ya), (B, yb) = self.R.term(a), self.R.term(b)
            ty = ya or yb
            if self.consumer_term(a):
                bw = subst_vars(B, self.sub)

                def frame(t, bw=bw, ty=ty):
                    return f"{{{t} == {bw} : {ty}}}"
                steps = [(self.bridge(A, ty), frame("_"))] + self.value_steps(subst_vars(A, self.sub), frame)
                defs.append(self.steps_def(f"pf_{name}", wty, steps))
            else:
                defs.append(f"def pf_{name}() -> {wty}:\n  {{==}}\n")
            prem_terms.append(f"pf_{name}()")
        a, b = self.st["claim"]["eq"]
        (A, ya), (B, yb) = self.R.term(a), self.R.term(b)
        ty = ya or yb
        if ty not in EQS:
            raise Unsupported(f"a claim of type {ty}")
        lit = {}
        for side, t, T in (("l", a, A), ("r", b, B)):
            if "nat" in t or "bool" in t:
                lit[side] = (T, None)
            else:
                lit[side] = ("?" if values is None else values[f"val_claim_{side}"], f"v_{side}()")
        for side, t, T in (("l", a, A), ("r", b, B)):
            v, lem = lit[side]
            if lem is None:
                continue

            def frame(x, v=v, side=side):
                return f"{{{v} == {x} : {ty}}}" if side == "l" else f"{{{x} == {v} : {ty}}}"
            w, wty = self.wrap(f"v_{side}", frame(T))
            defs += [w] if w else []
            if self.consumer_term(t):
                steps = [(self.bridge(T, ty), frame("_"))] + self.value_steps(subst_vars(T, self.sub), frame)
                defs.append(self.steps_def(f"v_{side}", wty, steps))
            else:
                defs.append(f"def v_{side}() -> {wty}:\n  {{==}}\n")
        w, wty = self.wrap("claim", f"{{{A} == {B} : {ty}}}")
        defs += [w] if w else []
        # lt: {la == lb} from the claim's equation e: v_r, e and v_l rewrite lb to B, B to A, A to la. Every motive is
        # an equation, whose weak head is itself, so each conversion meets its goal by syntax: a motive whose head
        # reduces (is_true(EQ(B, la))) would make the kernel evaluate B in neg's open context, without sharing
        la, lb = lit["l"][0], lit["r"][0]
        body = ([f"  %v_r() : {{{la} == _ : {ty}}}"] if lit["r"][1] else []) + [f"  %e : {{{la} == _ : {ty}}}"] + \
            ["  v_l()" if lit["l"][1] else "  {==}"]
        defs.append(f"def lt(e: {wty}) -> {{{la} == {lb} : {ty}}}:\n" + "\n".join(body) + "\n")
        # Empty is is_true(EQ(lb, la)), which lt rewrites to is_true(EQ(la, la)): Unit
        neg = f"def neg(e: {wty}) -> Empty:\n  %lt(e) : P.is_true({EQS[ty]}(_, {la}))\n  Unit{{}}\n"
        return {"prem": prem_terms, "defs": defs, "neg": neg, "plan": pl}

    def proof_text(self, js: dict, laws_import: str = "./LAWS.bend") -> str:
        """PROOF.bend from the node driver's runs and values (js)."""
        pcs = self.pieces(js["values"])
        pl = pcs["plan"]
        # premises that are hypotheses of the circuit: the instance that accepts every step (its claim by computation)
        prem = list(pcs["prem"])
        out = [PHEADER, f"# class counter: {self.law['law_id']}", "import Base"]
        out += [f"import {p} as {a}" for a, p in self.imports]
        out += [f"import {laws_import} as Laws", ""]
        out += self.wit.defs(codec=True)
        out += ["# ---------------------------------------------------------------- the hypotheses' instances",
                "def hypb_w(q: List<&2, Nat>) -> {pl_w(cb_w(q)) == P.ok_payload(q) : C.PlAns}:\n  {==}\n"]
        out += codec_proofs(self.wit.B)
        out += self.generic_text()
        runs = []
        for (dtm, ctx), r in sorted(self.runs.items(), key=lambda kv: kv[1]):
            j = js["runs"][r]
            runs += self.run_text(r, dtm, ctx, j, js["values"][f"cells_{r}"], js["values"][f"batch_{r}"])
        out.append("# a step of the machine from a running or a returning state, at the witness's closures, under a "
                   "variable fuel F")
        for key, name in sorted(self.steps.items(), key=lambda kv: kv[1]):
            out.append(self.step_text(*key, name))
        out.append("# the product's defs unfolded once, at the witness's closures (the other arguments variables)")
        for (name, clos), lname in sorted(self.lemmas_open.items(), key=lambda kv: kv[1]):
            out.append(self.open_lemma(name, clos, lname))
        out += runs
        out.append("# ---------------------------------------------------------------- the bridges: a consumer term at the "
                   "law's closures is the term at the witness's (over variables)")
        out += [d for _n, d, _a in sorted(self.bridges.values())]
        out.append("# ---------------------------------------------------------------- the premises and the claim")
        out += pcs["defs"]
        out.append(pcs["neg"])
        vals = [self.sub[n] for n in self.names]
        tup = "neg"
        for t in reversed(vals + prem):
            tup = f"({t}, {tup})"
        out.append(f"def Laws.{law_name(self.law['law_id'], True)}():\n  {tup}\n")
        return "\n".join(out).rstrip("\n") + "\n"


# ====================================================================== class hyp_apply
def hyp_apply_proof(I, law: dict, imports: list, laws_import: str = "./LAWS.bend") -> str:
    """PROOF.bend of a law whose claim is the conclusion of one of its hypothesis premises, instantiated at the law's
    own binders (a hypothesis binder is the law's binder of its name and type), every premise of that hypothesis a
    premise of the law (by its rendering): the hypothesis applied (class hyp_apply). Unsupported otherwise."""
    from .bendlaws import Render
    R = Render(I)
    st = law["statement"]
    pn = premise_names(st)
    binders = R.binders(st)
    btype = {n: t for n, t, _d in binders}
    rendered = [R.premise(p) for p in st.get("assume", [])]
    claim = R.eq(st["claim"])
    for i, p in enumerate(st.get("assume", [])):
        if "hyp" not in p:
            continue
        name = p["hyp"]["name"]
        h = I.s88["hypotheses"][name]
        hs = h["statement"]
        sub = dict(zip(h["parameters"], [R.term(a)[0] for a in p["hyp"]["args"]]))
        hb = R.binders(hs)
        if any(btype.get(n) != subst_vars(t, sub) for n, t, _d in hb):
            continue
        if subst_vars(R.eq(hs["claim"]), sub) != claim:
            continue
        used = []
        for hp in hs.get("assume", []):
            r = subst_vars(R.premise(hp), sub)
            if r not in rendered:
                break
            used.append(pn[rendered.index(r)])
        else:
            params = ", ".join([n for n, _t, _d in binders] + pn)
            args = ", ".join([n for n, _t, _d in hb] + used)
            out = [PHEADER, f"# class hyp_apply: {law['law_id']}: the claim is {name}'s conclusion at the law's binders, "
                   f"its premises the law's {', '.join(used)}", "import Base"]
            out += [f"import {q} as {a}" for a, q in imports]
            out += [f"import {laws_import} as Laws", "",
                    f"def Laws.{law_name(law['law_id'], False)}({params}):\n  {pn[i]}({args})\n"]
            return "\n".join(out)
    raise Unsupported(f"{law['law_id']}: no hypothesis premise concludes the claim from the law's premises")
