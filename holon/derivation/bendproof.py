"""I89 stage 2: the witnesses and the Bend proofs of I88's laws (S1-S4; the contract is the docstring of
tests_m3/test_derivation_bend.py). Untrusted: the checker decides every law.

A witness lives on the compiled models: the commit is the typed model's step (holon.sorts.search3, its external calls
answered by I85's product rules, its keccak table the real keccak of every key the step looks up), the consumer runs
are the compiled product module's (node), and the hypotheses' parameters are instances whose hypotheses Bend proves for
every argument:

  cb_w(q) = [VY{q}]          one blob that is the payload itself; pl_w answers PlOk with that blob's bytes (HypB: by
                             computation)
  vh_w(b) = V                a constant word: the commit's blob hash is V (I85's stand-in hash of the real blob)
  et_w / dt_w                a codec of opaque tokens: token 0 is the witness's transaction bytes B (when there are
                             any), token 1+k the marker 256 then k; dt_w parses a stream back (HypT: by induction on u,
                             the parser's accumulator generalised)
  circ_w(st) = True          the circuit that accepts every step (HypC_ignores_trailing's instance: by computation)

The proof of a counter-law (class counter) states every premise and the claim's negation through closed lemmas of one
computation each, so that no kernel conversion runs a computation it does not need (BendTT reduces closed terms with
sharing but rechecks every conversion from scratch, within a fuel of 4e8 steps per definition):

  es_<run>_<k>     {s_{k+1} == C.m_step(s_k)}: one step of the consumer's machine from a literal state (the states
                   are the compiled model's, printed by the node driver)
  tg_, tt_, tr_end a step from a running or a returning state, and the end, under a variable fuel G: the fuel is a
                   variable, so a conversion stops at it; chain_<run>(G) nests them, fu_<run>(F) peels the fuel the
                   machine starts with (Nat.is_le(N, F))
  run_<run>        {res == P.rm(x, p, cb, pl, dtm, ctx, fuel)}: the run's result, through the open lemmas l_rm_ (the run
                   of a step is run_bc of its batch), l_rb_ (run_bc is the machine from its initial state) and the closed
                   lemmas bo_ (the batch) and g0_ (the initial state)
  v_<term>         {T(W) == value}: a product term at the witness, through its open unfolding lemma l_<term>_ and the
                   run lemmas; then a closed computation
  the claim        the negation of {A == B} through Equal.trans / Equal.sym of the value lemmas and a discriminator

A lemma never takes a closure as an argument: its closures are the witness's, written into its statement (one lemma per
tuple of closures). BendTT instantiates a type at a lambda argument annotated ({f : T}, Term.arg), and the annotated
copy is not syntactically the closure the goal holds, so the conversion would fall back to evaluating both sides: the
whole machine where a step was meant.

The proof of a law whose claim is the conclusion of a hypothesis premise whose own premises the law states (class
hyp_apply) applies the premise. Nothing here names a target.
"""
