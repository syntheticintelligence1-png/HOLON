"""Contract laws over a typed model (BUILD_PLAN I33; the contract is the docstring of tests_m3/test_o12_m3.py, rules B1,
B2, B5, B7 and B10): an intended_weak law (holon.contracts K3) whose facts are a holon-facts/0.3 document with a
structural typed model (holon.sorts.model3, I68), stated, searched and recorded on that model.

Emission (B2). LAWS.bend states the law over the typed model M: the hash tables (kh, sh: holon.sorts.proofs3), then for
a Reach binder s the state s: M.GSt and its evidence r_s: M.Reach<tables, s>, M.HAct for an Act binder and M.W for a
Word binder; one premise binder h<i> per assumption; the claim's conjuncts as holon.gen.mlaws states them (exs c<i>, the
last as the body). Each distinct instance of a typed term is one statement helper beside the law (ct_<n>, whose
arguments are the law's binders and tables), so a proof file can neither define nor change them:

  sread[F.M](K.., S)   M.sload(M.gh_get_st(S), key) at I68's canonical key (a scalar SK{b, o, Nil}; a struct member of
                       a scalar SK{b, m.slot, Nil}; a mapping value SK{b, 0, [SP_m{clean(k), m.slot}]}, the key cleaned
                       as holon.sorts.model3.map_key cleans it); a packed member is its field: shifted, then masked
  N(W)                 c3_wnat(W): the limbs' Horner sum, each 2^32 factor 32 doublings (Bend's Nat is unary: no
                       literal or product of 2^32 is ever built, so a small word's N computes in the kernel too)
  A C B                Nat.is_le, Nat.is_lt, Nat.is_eq
  ok(X, S)             c3_ok(X, M.gh_get_st(S), tables): X's constructor, then U32.is_eq(M.chk_<A>(..), 0)
  is[A](X)             c3_is_<A>(X): the constructor alone
  env.E(X)             c3_env_<E>(X): M.ge_e_<E> of X's environment
  step(X, S)           M.gh_step(X, S, tables), the ghost step (the action's post-state when its checks hold, else S)

The same text with the model's names unqualified is the evaluation section (section_text): appended to the typed model,
it is the module the refuter evaluates the word- and Bool-valued helpers in (holon.sorts.evaluate3); the Nat terms
over them (N, +, the comparisons) are computed exactly on the words it returns (Bend's unary Nat makes the compiled N of
a 256-bit word unevaluable), and the counter-law's check computes them again in Bend. Nothing here names a law, a
contract or a target.
"""
from __future__ import annotations

import hashlib
import json
import re

from ..machine_bend import bname
from .model3 import Loc, wlit

VERSION_03 = "holon-facts/0.3"
SUBFORM = "intended_weak"
B1 = ("sread", "wnat", "cmp", "ok", "is", "env")
ENV_FIELDS = ("caller", "msg_value", "block_timestamp", "this", "msg_data_length")
CMP_FN = {"<=": "Nat.is_le", "<": "Nat.is_lt", "==": "Nat.is_eq"}
MASK = (1 << 256) - 1
HEADER = "# GENERATED by holon.sorts.contract3 from the frozen law IR; do not edit."
_QUAL = re.compile(r"(?<![\w.])(SK|SP_m|W|w0|w_and|w_or)(?=[{(])")


class Unsupported(ValueError):
    """The law is not a contract law this module states (named)."""


def term_kind(t) -> str | None:
    """The B1 kind of a term (its exact key set, sread's member optional), or None."""
    if not isinstance(t, dict):
        return None
    ks = set(t)
    if "sread" in t and ks - {"member"} == {"sread", "keys", "from"}:
        return "sread"
    for k, keys in (("wnat", {"wnat"}), ("cmp", {"cmp", "args"}), ("ok", {"ok", "from"}), ("is", {"is", "act"}),
                    ("env", {"env", "of"})):
        if ks == keys:
            return k
    return None


def uses_b1(x) -> bool:
    """Does the statement use a B1 term (I33's typed terms)?"""
    if isinstance(x, dict):
        return term_kind(x) is not None or any(uses_b1(v) for v in x.values())
    if isinstance(x, list):
        return any(uses_b1(v) for v in x)
    return False


def applies(law: dict, facts: dict | None) -> bool:
    """B5: an intended_weak law over a holon-facts/0.3 document (holon run's typed runner decides it)."""
    return (law.get("subform") == SUBFORM and isinstance(facts, dict)
            and facts.get("facts_version") == VERSION_03)


# ---------------------------------------------------------------------------------------------------- the layout
def family(facts: dict, name: str) -> dict:
    for s in facts.get("storage") or []:
        if s.get("name") == name:
            return s
    raise Unsupported(f"no storage family {name!r}")


def depth(fam: dict) -> int:
    n, v = 0, fam
    while isinstance(v, dict) and v.get("kind") == "mapping":
        n += 1
        v = v.get("inner") if isinstance(v.get("inner"), dict) else None
    return n


def key_bytes(label: str) -> tuple[int, bool]:
    """(numberOfBytes, masked?) of a mapping key type as model3.map_key cleans it: an address, bool or uintN key
    narrower than a word is masked to its width; a bytesN or intN key, and a full word, are not."""
    lab = str(label or "uint256")
    if lab == "address":
        return 20, True
    if lab == "bool":
        return 1, True
    m = re.fullmatch(r"u?int(\d+)", lab)
    if m:
        n = int(m.group(1)) // 8
        return n, lab.startswith("uint") and n < 32
    m = re.fullmatch(r"bytes(\d+)", lab)
    if m:
        return int(m.group(1)), False
    raise Unsupported(f"a mapping keyed by {lab}")


def member(fam: dict, name) -> dict | None:
    fs = fam.get("fields") or []
    if not fs:
        if name is not None:
            raise Unsupported(f"{fam['name']} has no member {name!r}")
        return None
    m = next((f for f in fs if f.get("name") == name), None)
    if m is None:
        raise Unsupported(f"{fam['name']}: a read of a struct names one of its members, not {name!r}")
    return m


# ---------------------------------------------------------------------------------------------------- terms
class Terms:
    """The statement helpers of one law: compile(t) gives a Bend expression of a term over the law's binders and
    tables; every B1 instance becomes one helper (memoized by its canonical JSON), written by defs()."""

    def __init__(self, law: dict, facts: dict, tables: list[str], q: str = "M."):
        st = law["statement"]
        self.law, self.f, self.q = law, facts, q
        self.tables = list(tables)
        self.binders = [(b["name"], str(b.get("type", ""))) for b in st.get("binders") or []]
        self.types = dict(self.binders)
        for n, ty in self.binders:
            if ty not in ("Reach", "Act", "Word"):
                raise Unsupported(f"binder {n}: {ty} (a typed contract law binds Reach, Act and Word)")
        if [ty for _n, ty in self.binders].count("Reach") != 1:
            raise Unsupported("a typed contract law binds exactly one Reach state")
        self.acts = [a["name"] for a in facts.get("actions") or [] if isinstance(a, dict) and a.get("name")]
        self.helpers: dict[str, tuple[str, str, str]] = {}    # canonical term -> (name, Bend type, def text)
        self.order: list[str] = []
        self.generic: dict[str, str] = {}                    # name -> def text (c3_wnat, c3_ok, c3_is_<A>, ..)

    # ---------------------------------------------------------- names
    def M(self, name: str) -> str:
        return self.q + name

    def params(self) -> list[tuple[str, str]]:
        """The helpers' parameters: the law's binders (the Reach state as a GSt), then the tables."""
        ty = {"Reach": "GSt", "Act": "HAct", "Word": "W"}
        out = [(bname(n), self.M(ty[t])) for n, t in self.binders]
        return out + [(t, f"List<&2, {self.M('HKB')}>") for t in self.tables]

    def args(self) -> str:
        return ", ".join(n for n, _t in self.params())

    def sig(self) -> str:
        return ", ".join(f"+{n}: {t}" for n, t in self.params())

    def tab_args(self) -> str:
        return "".join(f", {t}" for t in self.tables)

    # ---------------------------------------------------------- generic helpers
    def g_wnat(self) -> str:
        if "c3_wnat" not in self.generic:
            dbl = "n"
            for _ in range(32):
                dbl = f"Nat.double({dbl})"
            limbs = [f"l{i}" for i in range(8)]
            body = f"U32.to_nat({limbs[7]})"
            for i in range(6, -1, -1):
                body = f"Nat.add(U32.to_nat({limbs[i]}), c3_sh32({body}))"
            self.generic["c3_sh32"] = f"# n * 2^32, as 32 doublings\ndef c3_sh32(n: Nat) -> Nat:\n  {dbl}\n"
            self.generic["c3_wnat"] = (
                "# N(w): the word read as a natural number, sum over the limbs of to_nat(l_i) * 2^(32 i) (Horner)\n"
                f"def c3_wnat(w: {self.M('W')}) -> Nat:\n  match w:\n    case {self.M('W')}{{{', '.join(limbs)}}}:\n"
                f"      {body}\n")
        return "c3_wnat"

    def g_ok(self) -> str:
        if "c3_ok" not in self.generic:
            tsig = "".join(f", +{t}: List<&2, {self.M('HKB')}>" for t in self.tables)
            lines = ["# ok(X, S): every check of X's action holds from the store (its chk_<action> is 0)",
                     f"def c3_ok(a: {self.M('HAct')}, +st: {self.M('HSt')}{tsig}) -> Bool:", "  match a:"]
            for a in self.acts:
                b = bname(a)
                lines += [f"    case {self.M('A_' + b)}{{ar, en}}:",
                          f"      U32.is_eq({self.M('chk_' + b)}(st, ar, en{self.tab_args()}), 0)"]
            self.generic["c3_ok"] = "\n".join(lines) + "\n"
        return "c3_ok"

    def g_is(self, a: str) -> str:
        if a not in self.acts:
            raise Unsupported(f"no action {a!r}")
        name = f"c3_is_{bname(a)}"
        if name not in self.generic:
            lines = [f"# is[{a}](X)", f"def {name}(a: {self.M('HAct')}) -> Bool:", "  match a:"]
            for o in self.acts:
                lines += [f"    case {self.M('A_' + bname(o))}{{_, _}}:", f"      {'True' if o == a else 'False'}{{}}"]
            self.generic[name] = "\n".join(lines) + "\n"
        return name

    def g_env(self, e: str) -> str:
        if e not in ENV_FIELDS:
            raise Unsupported(f"no environment field {e!r}")
        name = f"c3_env_{e}"
        if name not in self.generic:
            lines = [f"# env.{e}(X)", f"def {name}(a: {self.M('HAct')}) -> {self.M('W')}:", "  match a:"]
            for o in self.acts:
                lines += [f"    case {self.M('A_' + bname(o))}{{_, en}}:", f"      {self.M('ge_e_' + e)}(en)"]
            self.generic[name] = "\n".join(lines) + "\n"
        return name

    def g_shr(self, k: int) -> str:
        """A right shift by k bits (holon.sorts.model3's shift helpers, written beside the law)."""
        name = f"c3_shr_{k}"
        if name not in self.generic:
            q, r = divmod(k, 32)
            limbs = []
            for i in range(8):
                src, nxt = i + q, i + q + 1
                a = f"a{src}" if src < 8 else None
                b = f"a{nxt}" if nxt < 8 else None
                if r == 0:
                    limbs.append(a or "0")
                    continue
                parts = ([f"U32.shrn({a}, {r}n)"] if a else []) + ([f"U32.shln({b}, {32 - r}n)"] if b else [])
                limbs.append(parts[0] if len(parts) == 1 else (f"U32.or({parts[0]}, {parts[1]})" if parts else "0"))
            pat = ", ".join(f"+a{i}" for i in range(8))
            self.generic[name] = (f"def {name}(a: {self.M('W')}) -> {self.M('W')}:\n  match a:\n"
                                  f"    case {self.M('W')}{{{pat}}}:\n      {self.M('W')}{{{', '.join(limbs)}}}\n")
        return name

    # ---------------------------------------------------------- compiling
    def qual(self, code: str) -> str:
        return _QUAL.sub(lambda m: self.q + m.group(1), code) if self.q else code

    def helper(self, t: dict, ty: str, body: str) -> str:
        key = json.dumps(t, sort_keys=True, separators=(",", ":"))
        if key not in self.helpers:
            from .. import ir
            name = f"ct_{hashlib.sha256(key.encode()).hexdigest()[:12]}"
            text = (f"# {render(t, ir)}\ndef {name}({self.sig()}) -> {ty}:\n  {body}\n")
            self.helpers[key] = (name, ty, text)
            self.order.append(key)
        return f"{self.helpers[key][0]}({self.args()})"

    def type_of(self, t) -> str:
        k = term_kind(t)
        if k in ("sread", "env"):
            return self.M("W")
        if k in ("wnat",) or (isinstance(t, dict) and ("plus" in t or "nat" in t)):
            return "Nat"
        if k in ("cmp", "ok", "is") or (isinstance(t, dict) and "bool" in t):
            return "Bool"
        if isinstance(t, dict) and "var" in t:
            ty = self.types.get(t["var"])
            return {"Act": self.M("HAct"), "Word": self.M("W"), "Reach": self.M("GSt")}.get(ty, "?")
        raise Unsupported(f"no type for {json.dumps(t)[:120]}")

    def state(self, t) -> str:
        """A State term: the Reach binder, or step(X, S)."""
        if isinstance(t, dict) and "var" in t and self.types.get(t["var"]) == "Reach":
            return bname(t["var"])
        if isinstance(t, dict) and set(t) == {"step", "from"}:
            return f"{self.M('gh_step')}({self.act(t['step'])}, {self.state(t['from'])}{self.tab_args()})"
        raise Unsupported(f"not a state term: {json.dumps(t)[:120]}")

    def act(self, t) -> str:
        if isinstance(t, dict) and "var" in t and self.types.get(t["var"]) == "Act":
            return bname(t["var"])
        raise Unsupported(f"not an act term: {json.dumps(t)[:120]}")

    def word(self, t) -> str:
        k = term_kind(t)
        if k in ("sread", "env"):
            return self.compile(t)
        if isinstance(t, dict) and "var" in t and self.types.get(t["var"]) == "Word":
            return bname(t["var"])
        raise Unsupported(f"not a word term: {json.dumps(t)[:120]}")

    def compile(self, t) -> str:
        k = term_kind(t)
        if k == "sread":
            return self.helper(t, self.M("W"), self.sread(t))
        if k == "wnat":
            return self.helper(t, "Nat", f"{self.g_wnat()}({self.word(t['wnat'])})")
        if k == "cmp":
            if t["cmp"] not in CMP_FN or len(t["args"]) != 2:
                raise Unsupported(f"cmp {t.get('cmp')!r}")
            a, b = (self.nat(x) for x in t["args"])
            return self.helper(t, "Bool", f"{CMP_FN[t['cmp']]}({a}, {b})")
        if k == "ok":
            return self.helper(t, "Bool", f"{self.g_ok()}({self.act(t['ok'])}, {self.M('gh_get_st')}"
                                          f"({self.state(t['from'])}){self.tab_args()})")
        if k == "is":
            return self.helper(t, "Bool", f"{self.g_is(t['is'])}({self.act(t['act'])})")
        if k == "env":
            return self.helper(t, self.M("W"), f"{self.g_env(t['env'])}({self.act(t['of'])})")
        if isinstance(t, dict) and "bool" in t:
            return "True{}" if t["bool"] else "False{}"
        if isinstance(t, dict) and set(t) == {"nat"}:
            return f"{int(t['nat'])}n"
        if isinstance(t, dict) and "plus" in t:
            return self.nat(t)
        if isinstance(t, dict) and "var" in t:
            return bname(t["var"])
        raise Unsupported(f"a term outside the typed contract grammar: {json.dumps(t)[:160]}")

    def nat(self, t) -> str:
        if isinstance(t, dict) and set(t) == {"plus"}:
            a, b = t["plus"]
            return f"Nat.add({self.nat(a)}, {self.nat(b)})"
        if isinstance(t, dict) and set(t) == {"nat"}:
            return f"{int(t['nat'])}n"
        if term_kind(t) == "wnat":
            return self.compile(t)
        raise Unsupported(f"not a Nat term: {json.dumps(t)[:120]}")

    def sread(self, t: dict) -> str:
        fam = family(self.f, t["sread"])
        keys = t.get("keys") or []
        if len(keys) != depth(fam):
            raise Unsupported(f"{fam['name']} takes {depth(fam)} key(s)")
        mem = member(fam, t.get("member"))
        mslot = int(mem.get("slot", 0)) if mem else 0
        loc = Loc(int(fam["slot"]))
        v = fam
        for kt in keys:
            kw = self.word(kt)
            nb, masked = key_bytes(v.get("key"))
            if masked:
                kw = f"w_and({kw}, {wlit((1 << (8 * nb)) - 1)})"
            loc = loc.step(kw)
            v = v.get("inner") if isinstance(v.get("inner"), dict) else v
        loc = loc.plus(mslot)
        word = f"{self.M('sload')}({self.M('gh_get_st')}({self.state(t['from'])}), {self.qual(loc.code())})"
        holder = mem if mem is not None else fam
        width = int(holder.get("width", 256) or 256)
        off = int(holder.get("offset", 0) or 0) if (mem is not None or not keys) else 0
        if off:
            word = f"{self.g_shr(8 * off)}({word})"
        if width < 256:
            word = f"{self.M('w_and')}({word}, {self.qual(wlit((1 << width) - 1))})"
        return word

    # ---------------------------------------------------------- props
    def prop(self, p: dict) -> tuple[str, str, str]:
        """(lhs, rhs, Bend type) of an {eq: [A, B]} proposition."""
        if set(p) != {"eq"} or len(p["eq"]) != 2:
            raise Unsupported(f"a proposition {sorted(p)} (typed contract laws state equalities)")
        a, b = p["eq"]
        ty = self.type_of(a)
        if ty == "Nat":
            return self.nat(a), self.nat(b), ty
        return self.compile(a), self.compile(b), ty

    def defs(self) -> list[str]:
        out = [self.generic[k] for k in sorted(self.generic, key=_generic_order)]
        return out + [self.helpers[k][2] for k in self.order]


def _generic_order(name: str) -> tuple:
    return (0 if name in ("c3_sh32", "c3_wnat") else 1, name)


def render(t, ir) -> str:
    try:
        return ir.render_term(t).replace("\n", " ")[:200]
    except Exception:  # noqa: BLE001: the comment is informative only
        return json.dumps(t)[:200]


def claims_of(law: dict) -> list[dict]:
    c = law["statement"]["claim"]
    return list(c["all"]) if isinstance(c, dict) and "all" in c else [c]


# ---------------------------------------------------------------------------------------------------- law files
def law_name(law_id: str, kind: str = "law") -> str:
    """l_<id> (the law), cl_l_<id> (its counter-law) or nv_l_<id> (its inhabitant law), lower-cased."""
    return {"law": "", "counter": "cl_", "nonvac": "nv_"}[kind] + law_id.lower()


def _statement(law: dict, facts: dict, tables: list[str], kind: str, conjunct: int | None):
    tm = Terms(law, facts, tables)
    st = law["statement"]
    prem = [tm.prop(p) for p in st.get("assume") or []]
    cl = [tm.prop(p) for p in claims_of(law)]
    kw = "for" if kind == "law" else "exs"
    lines = [f"law {law_name(law['law_id'], kind)}:"]
    idx = "".join(f"{t}, " for t in tables)
    for t in tables:
        lines.append(f"  {kw} {'+' if kw == 'for' else ''}{t}: List<&2, M.HKB>")
    for n, ty in tm.binders:
        mode = "+" if kw == "for" else ""
        if ty == "Reach":
            lines += [f"  {kw} {mode}{bname(n)}: M.GSt", f"  {kw} r_{bname(n)}: M.Reach<{idx}{bname(n)}>"]
        else:
            lines.append(f"  {kw} {mode}{bname(n)}: {'M.HAct' if ty == 'Act' else 'M.W'}")
    if kind == "nonvac":
        for i, (a, b, ty) in enumerate(prem[:-1]):
            lines.append(f"  exs h{i}: {{{a} == {b} : {ty}}}")
        a, b, ty = prem[-1]
        lines.append(f"  {{{a} == {b} : {ty}}}")
    else:
        for i, (a, b, ty) in enumerate(prem):
            lines.append(f"  {kw} h{i}: {{{a} == {b} : {ty}}}")
        if kind == "counter":
            a, b, ty = cl[conjunct]
            lines.append(f"  {{{a} != {b} : {ty}}}")
        else:
            for i, (a, b, ty) in enumerate(cl[:-1]):
                lines.append(f"  exs c{i}: {{{a} == {b} : {ty}}}")
            a, b, ty = cl[-1]
            lines.append(f"  {{{a} == {b} : {ty}}}")
    return tm, lines, prem, cl


def law_file(law: dict, facts: dict, statement_hash: str, model_import: str, tables: list[str], kind: str = "law",
             conjunct: int | None = None) -> str:
    """LAWS.bend of the law (kind "law"), its counter-law on one conjunct ("counter") or its inhabitant law ("nonvac":
    the premises inhabited, B7)."""
    if kind == "nonvac" and not (law["statement"].get("assume") or []):
        raise Unsupported("an inhabitant law needs premises")
    tm, lines, _p, _c = _statement(law, facts, tables, kind, conjunct)
    what = {"law": "", "counter": f" (counter-law: conjunct {conjunct})", "nonvac": " (non-vacuity: its premises)"}
    head = [HEADER, f"# law_id: {law['law_id']}{what[kind]}   statement_hash: {statement_hash}", "import Base",
            f"import {model_import} as M", "", "# statement helpers (part of the statement: B2)", ""]
    return "\n".join(head) + "\n" + "\n".join(tm.defs()) + "\n" + "\n".join(lines) + "\n"


def section_text(law: dict, facts: dict, tables: list[str]) -> tuple[str, Terms]:
    """The evaluation section: the law's helpers with the model's names unqualified (appended to the typed model)."""
    tm = Terms(law, facts, tables, q="")
    st = law["statement"]
    for p in (st.get("assume") or []) + claims_of(law):
        for x in p.get("eq") or []:
            _walk_compile(tm, x)
    return "\n# ---- the contract law's statement helpers (holon.sorts.contract3)\n" + "\n".join(tm.defs()), tm


def _walk_compile(tm: Terms, t) -> None:
    """Compile every B1 instance of a term (so each has its helper in the section)."""
    k = term_kind(t)
    if k is not None:
        tm.compile(t)
        return
    if isinstance(t, dict):
        for v in t.values():
            _walk_compile(tm, v)
    elif isinstance(t, list):
        for v in t:
            _walk_compile(tm, v)
