"""The typed model's sort operations (I123; HUMAN_ANSWERS Q100 (1); the contract is the docstring of
tests_m6/test_i123_typed_sort_operations.py). Only a typed sidecar naming sort_ops "word" (holon.sorts.typed_sidecar,
written by holon eval holon when its protocol names typed.sort_ops) gets them; every other model is generated by
holon.sorts.model3 byte for byte as before.

Every rule is read from the EVM and Solidity semantics, never from a target's code:

  W1  A typed value (kind t:<sort>, a refined sort's word) is read as the 256-bit word it occupies (model3's to_w: the
      payload of its nominal wrapper) by the word-level operations: & | ^ ~, masks, trunc, sext, wbyte, << >> sar, and +
      and - outside checked code. Their result is an unrefined word (kind w). A sort in the typed model is a nominal
      wrapper T{p: W} over the word, never a predicate on it, so reading the word adds no fact, and a word result
      registers no typed operation (affine, comparison, realize) for a law over the sort to read.
  S1  shl: ["<<", x, n] is x * 2^n mod 2^256, 0 when n >= 256 (model3's t_shl, unchanged).
  S2  shr: [">>", x, n] is floor(x / 2^n), 0 when n >= 256 (model3's t_shr, unchanged).
  S3  sar: ["sar", x, n] reads x as two's complement and is floor(x / 2^n) sign-extended from bit 255; past 255 it is 0
      for x < 2^255 and 2^256 - 1 otherwise. Defined as x < 2^255 ? shr(x, n) : ~shr(~x, n), which is exact: for a
      negative x = -1 - y (y = ~x >= 0), floor(x / 2^n) = -1 - floor(y / 2^n) = ~(y >> n). Solidity's >> on a signed
      type is sar in every pinned release (0.5.0 and later round towards negative infinity).
  C1  checked and unchecked + - apart: a typed + or - whose two typed operands have no affine row (ill-sorted) stays
      refused when a checked operation of the same action reads that term (a panic 17 record: its fits / sfits); outside
      checked code (an unchecked block, assembly, a release below 0.8.0) it is the wrapping word operation w_add /
      w_sub over the operands' words, of kind w. The checked operation's revert is its own check, kept by the model.
  R1  a shift (<< >> sar) by a non-constant amount in a document compiled by a release below 0.8.0 is refused: the term
      does not record the amount's type, and there a negative signed amount reverts (0.8.0 and later reject a signed
      amount at compile time, so the amount is an unsigned word).
  V1  fits and sfits over a value (not an operation): the ABI's validity of a narrow argument. ["fits", N, x] is
      x < 2^N; ["sfits", N, x] is x read as two's complement in [-2^(N-1), 2^(N-1)), which is sext(N, x) == x; both
      True for N >= 256. sfits over an operation stays refused.
  D1  a section over the typed model (holon.undo.trace.Trace and its subclasses) that needs a constant shift the model
      does not define defines it in the section itself, by model3's own shift builder (section_shifts).
"""
from __future__ import annotations

import re

MASK = (1 << 256) - 1
SIGN = 1 << 255
HEADS = frozenset({"sar", "sfits"})   # IR heads model3 compiles only under the opt-in
MODES = ("word",)


def enabled(mm) -> bool:
    return bool(getattr(mm, "sort_ops", False))


def solc_version(doc: dict) -> tuple | None:
    v = ((((doc.get("extraction") or {}).get("toolchain") or {}).get("solc") or {}).get("version"))
    m = re.match(r"(\d+)\.(\d+)\.(\d+)", str(v or ""))
    return tuple(int(x) for x in m.groups()) if m else None


def check_amount(mm, t, sc) -> None:
    """R1: a non-constant shift amount in a document compiled by a release below 0.8.0 (or of no recorded release)."""
    v = solc_version(mm.m.doc)
    if v is None or v < (0, 8, 0):
        from .model3 import GenError
        rel = ".".join(map(str, v)) if v else "no recorded release"
        raise GenError(f"{sc.action}: a shift by a non-constant amount under solc {rel}, below 0.8.0 (R1: the term "
                       f"does not record the amount's type, and a negative signed amount reverts there)")


def _helper(mm, name: str, text: str) -> str:
    from .model3 import _ext_helper
    return _ext_helper(mm, name, text)


def t_sar(mm, t, sc):
    """S3: ["sar", x, n]."""
    from .model3 import wlit
    x = mm.w(t[1], sc)
    n = t[2]
    if isinstance(n, int) and not isinstance(n, bool):
        if n >= 256:
            f = _helper(mm, "w_sar_big", f"def w_sar_big(+a: W) -> W:\n  ite(W, w_lt(a, {wlit(SIGN)}), w0(), "
                                         f"{wlit(MASK)})\n")
            return f"{f}({x})", "w"
        sh = mm.shr(int(n))
        f = _helper(mm, f"w_sar_{n}", f"def w_sar_{n}(+a: W) -> W:\n  ite(W, w_lt(a, {wlit(SIGN)}), {sh}(a), "
                                      f"w_not({sh}(w_not(a))))\n")
        return f"{f}({x})", "w"
    check_amount(mm, t, sc)
    code, _k = mm.var_shift("r", [">>", 0, 0], sc)        # registers the model's variable right shift
    shrv = code.split("(", 1)[0]
    f = _helper(mm, "w_sarv", f"def w_sarv(+a: W, +n: W) -> W:\n  ite(W, w_lt(a, {wlit(SIGN)}), {shrv}(a, n), "
                              f"w_not({shrv}(w_not(a), n)))\n")
    return f"{f}({x}, {mm.w(n, sc)})", "w"


def _fits_inner(t, out: set) -> None:
    from .model3 import canonical
    if isinstance(t, list) and t:
        if t[0] in ("fits", "sfits") and len(t) == 3:
            out.add(canonical(t[2]))
        for x in t[1:]:
            _fits_inner(x, out)


def checked_terms(mm, action: str) -> set:
    """The canonical terms a checked operation of the action reads (the fits / sfits of its checks)."""
    cache = mm.__dict__.setdefault("_sortops_checked", {})
    if action not in cache:
        out: set = set()
        try:
            checks = mm.m.program(action).checks()
        except Exception:      # an action with no program: every term is treated as checked (the discipline holds)
            checks = None
        if checks is None:
            cache[action] = None
        else:
            for c in checks:
                _fits_inner(c.expr, out)
            cache[action] = out
    return cache[action]


def raw_affine(mm, op: str, t, sc, a, b):
    """C1: an ill-sorted typed + or - outside checked code, as the wrapping word operation (kind w); None when the
    discipline holds (the term is read by a checked operation, or the action's checks are not known)."""
    from .model3 import canonical
    ck = checked_terms(mm, sc.action)
    if ck is None or canonical(t) in ck:
        return None
    (ac, ak), (bcode, bk) = a, b
    x = mm.to_w(*mm.unsigned_kind(ac, ak))
    y = mm.to_w(*mm.unsigned_kind(bcode, bk))
    return (f"w_add({x}, {y})" if op == "+" else f"w_sub({x}, {y})"), "w"


def section_shifts(mm, new: set) -> list[str]:
    """D1: the definitions of the constant shifts `new` ({(d, k)}), by model3's own builder."""
    from .model3 import _shift_defs_before_ext
    keep = mm.shifts
    try:
        mm.shifts = set(new)
        return _shift_defs_before_ext(mm)
    finally:
        mm.shifts = keep


def texts() -> list[str]:
    """The Bend text templates this module emits (for the escape-hatch check)."""
    return ["def w_sar_big(+a: W) -> W:\n  ite(W, w_lt(a, S), w0(), M)\n",
            "def w_sar_k(+a: W) -> W:\n  ite(W, w_lt(a, S), w_shr_k(a), w_not(w_shr_k(w_not(a))))\n",
            "def w_sarv(+a: W, +n: W) -> W:\n  ite(W, w_lt(a, S), w_shrv(a, n), w_not(w_shrv(w_not(a), n)))\n",
            "def w_sfits_n(+a: W) -> Bool:\n  w_eq(w_sub(w_xor(w_and(a, K), H), H), a)\n"]


def _is_op(x) -> bool:
    return isinstance(x, list) and len(x) == 3 and x[0] in ("+", "-", "*")


def fits_value(mm, t, sc):
    """V1: ["fits", N, x] over a value x."""
    from .model3 import wlit
    n = int(t[1])
    if n >= 256:
        mm.w(t[2], sc)
        return "True{}", "bool"
    return f"w_lt({mm.w(t[2], sc)}, {wlit(1 << n)})", "bool"


def t_sfits(mm, t, sc):
    """V1: ["sfits", N, x] over a value x (sfits over an operation stays refused)."""
    from .model3 import GenError, canonical
    n = int(t[1])
    x = t[2]
    if (isinstance(x, list) and x and x[0] in ("+", "-", "*", "**", "neg", "sdiv")) or n < 1:
        raise GenError(f"{sc.action}: sfits over {canonical(x)[:80]} (an operation: outside the sort operations)")
    if n >= 256:
        mm.w(x, sc)
        return "True{}", "bool"
    v = mm.w(x, sc)
    f = _helper(mm, f"w_sfits_{n}", f"def w_sfits_{n}(+a: W) -> Bool:\n  w_eq({sext_code(mm, n, 'a')}, a)\n")
    return f"{f}({v})", "bool"


def sext_code(mm, bits: int, a: str) -> str:
    """model3's t_sext over the word code a."""
    from .model3 import wlit
    m = wlit(1 << (bits - 1))
    return f"w_sub(w_xor(w_and({a}, {mm.mask(bits)}), {m}), {m})"
