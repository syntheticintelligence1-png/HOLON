EXTENSIONS = {"spec/M1/facts/morph_rollup.json": ROLLUP_EXT}


def _reason_codes(facts: dict, names: list[str]) -> dict[str, int]:
    used = {int(k) for k in facts.get("reasons", {})}
    nxt = max(used) + 1 if used else 1
    out = {}
    for n in names:
        out[n] = nxt
        nxt += 1
    return out


def sorted_facts(facts: dict, src_rel: str, assignment: dict) -> dict:
    """The sorted facts for one frozen facts file: a deep copy plus the extension and the sort annotations."""
    f = copy.deepcopy(facts)
    ext = EXTENSIONS.get(src_rel, {})
    f["generated"] = {"by": GEN_DOC, "source_facts": src_rel, "source_sha256": assignment.get("facts_sha256")}
    codes = _reason_codes(f, sorted(ext.get("reasons", {})))
    for name, code in codes.items():
        f.setdefault("reasons", {})[str(code)] = ext["reasons"][name]
    for a in ext.get("actions", []):
        a = copy.deepcopy(a)
        for g in a["guards"]:
            if isinstance(g.get("reason"), str):
                g["reason"] = codes[g["reason"]]
        f["actions"].append(a)
    # a debt entry naming an action the (extended) facts now model is stale:
    # extension actions are real actions, so they leave the debt list.
    modelled = {a["name"] for a in f["actions"]}
    if isinstance(f.get("coverage"), dict):
        debt = f["coverage"].get("debt")
        if isinstance(debt, list):
            f["coverage"]["debt"] = [d for d in debt if d not in modelled]
    f["policy_extra"] = list(f.get("policy_extra", [])) + list(ext.get("policy_extra", []))
    for key in ("migrations", "preds", "observers"):
        f.setdefault(key, {}).update(copy.deepcopy(ext.get(key, {})))
    f["sorts"] = {"registers": assignment["registers"], "fields": assignment["fields"], "widths": assignment["widths"],
                  "obligations_open": [o for o in assignment["obligations"] if not o["discharged"]]}
    return f


def write_sorted(facts_path: Path, src_rel: str, assignment: dict, out: Path) -> str:
    facts = json.loads(Path(facts_path).read_text())
    text = json.dumps(sorted_facts(facts, src_rel, assignment), indent=1, sort_keys=False) + "\n"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    return text
