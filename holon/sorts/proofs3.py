"""The Bend files of an I30 law (I30; the contract is the docstring of tests_m3/test_sort_types.py, "Law IR", "The typed
model and its ghost section" and "Proofs, refutation, non-vacuity").

  law_file(law, x, model_rel, hashes, counter)   gen/<M>/laws/<id>/LAWS.bend: the law (forall s: Reach, a: Act and
                                                 the hash tables: coerce_<x>(a, s, ..) == True), or, for a REFUTED law,
                                                 its counter-law (exists ..: coerce_<x>(a, s, ..) != True); it imports
                                                 the typed model as M
  counter_proof(..)                              a counter-law proof: the concrete witness (its hash tables, the
                                                 trace's state as run(prefix, gh_s0()), its Reach chain R0 then one
                                                 RStep per step, and the entry step), every premise by computation
  inhabitant(..)                                 a non-vacuity proof of chit_<x> (G11V): the same shape, for the law
                                                 "exists a reachable state and step that reach a hit"

Witness literals are data: a word is M.w_of_limbs([l0, .., l7]) and a byte string a list of byte literals, so that
spec/M3/lib/term_size.json's measure counts each as one term. Nothing here names a target.
"""
from __future__ import annotations

import os
from pathlib import Path

from ..gen.mlaws import law_name

HEADER = "# GENERATED by holon.sorts.proofs3 from the frozen law IR; do not edit."
PHEADER = "# GENERATED by holon.sorts.proofs3; untrusted, accepted only if Bend checks it."


def rel_import(from_dir: Path, target: Path) -> str:
    return os.path.relpath(Path(target).resolve(), Path(from_dir).resolve()).replace(os.sep, "/")


def tabs_binders(hashes: list[str]) -> list[tuple[str, str]]:
    return [("kh" if h == "keccak256" else "sh", h) for h in hashes]


def law_file(law: dict, statement_hash: str, model_import: str, hashes: list[str], counter: bool = False) -> str:
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    kw = "exs" if counter else "for"
    q = "" if counter else "+"
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", ""]
    lines.append(f"law {law_name(lid, counter)}:")
    for n, _h in tb:
        lines.append(f"  {kw} {q}{n}: List<&2, M.HKB>")
    lines.append(f"  {kw} {q}s: M.GSt")
    lines.append(f"  {kw} r_s: M.Reach<{idx}s>")
    lines.append(f"  {kw} {q}a: M.HAct")
    rel = "!=" if counter else "=="
    lines.append(f"  {{M.coerce_{x}(a, s{''.join(', ' + n for n, _h in tb)}) {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def inhabitant_law(law: dict, statement_hash: str, model_import: str, hashes: list[str]) -> str:
    """gen/<M>/<id>/nonvac/LAWS.bend: a reachable state and a step that reach a hit of the law's coercion."""
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    lines = [HEADER, f"# non-vacuity of {lid} (statement_hash {statement_hash}): the at-site premise chit_{x} is "
             "inhabited by a reachable state and a step", "import Base", f"import {model_import} as M", ""]
    lines.append(f"law nv_{lid.lower()}:")
    for n, _h in tb:
        lines.append(f"  exs {n}: List<&2, M.HKB>")
    lines += ["  exs s: M.GSt", f"  exs r_s: M.Reach<{idx}s>", "  exs a: M.HAct",
              f"  {{M.chit_{x}(a, s{''.join(', ' + n for n, _h in tb)}) == True{{}} : Bool}}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------------------ literals
class Lit:
    """Bend text of the evaluator's JSON values (holon.sorts.evaluate3 encodings), qualified by M."""

    def __init__(self, recs: dict):
        self.recs = recs

    def word(self, h: str) -> str:
        v = int(h, 16)
        if v == 0:
            return "M.w0()"
        limbs = [(v >> (32 * i)) & 0xFFFFFFFF for i in range(8)]
        return "M.w_of_limbs([" + ", ".join(str(x) for x in limbs) + "])"

    def text(self, v) -> str:
        if isinstance(v, bool):
            return "True{}" if v else "False{}"
        if isinstance(v, int):
            return str(v)
        if isinstance(v, list):
            return ("[" + ", ".join(self.text(x) for x in v) + "]") if v else "Nil{}"
        if isinstance(v, dict):
            if "$w" in v:
                return self.word(v["$w"])
            if "$b" in v:
                b = bytes.fromhex(v["$b"][2:])
                return ("[" + ", ".join(str(x) for x in b) + "]") if b else "Nil{}"
            if "$r" in v:
                name = v["$r"]
                fs = self.recs.get(name)
                vals = v.get("f") or {}
                order = [f for f, _t in fs] if fs is not None else list(vals)
                return f"M.{name}{{" + ", ".join(self.text(vals[f]) for f in order) + "}"
        raise ValueError(f"no Bend literal for {str(v)[:120]}")


def counter_proof(law: dict, model_import: str, laws_import: str, hashes: list[str], acts: list, tables: dict,
                  lit: Lit, note: str) -> str:
    """The counter-law proof of one witness: acts are the evaluator's HAct values, the entry step's last."""
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {laws_import} as Laws", ""]
    lines.append(f"# class counter: {note}")
    for n, h in tb:
        rows = []
        for k, val in sorted((tables.get(h) or {}).items()):
            b = bytes.fromhex(k[2:])
            rows.append("M.HKB{" + (("[" + ", ".join(str(c) for c in b) + "]") if b else "Nil{}") + ", "
                        + lit.word("0x%064x" % val) + "}")
        lines.append(f"def t_{n}() -> List<&2, M.HKB>:\n  " + (("[" + ", ".join(rows) + "]") if rows else "Nil{}"))
        lines.append("")
    for i, a in enumerate(acts):
        lines.append(f"def w_a{i}() -> M.HAct:\n  {lit.text(a)}")
        lines.append("")
    targs = "".join(f", t_{n}()" for n, _h in tb)
    tlist = ", ".join(f"t_{n}()" for n, _h in tb)

    def run_of(k: int) -> str:
        pre = "[" + ", ".join(f"w_a{i}()" for i in range(k)) + "]" if k else "Nil{}"
        return f"M.run({pre}, M.gh_s0(){targs})"
    n = len(acts) - 1
    chain = "M.R0{{==}}"
    for k in range(n):
        chain = f"M.RStep{{w_a{k}(), {run_of(k)}, {chain}, {{==}}}}"
    state = run_of(n)
    last = f"w_a{n}()"
    body = (f"({last}, e => (%e : M.is_true(M.eq_bool(_, M.coerce_{x}({last}, {state}{targs})))\n  Unit{{}}))")
    inner = f"({state}, ({chain}, {body}))"
    for _n, _h in reversed(tb):
        pass
    tup = inner
    for nm, _h in reversed(tb):
        tup = f"(t_{nm}(), {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"


def inhabitant_proof(law: dict, model_import: str, laws_import: str, hashes: list[str], acts: list, tables: dict,
                     lit: Lit) -> str:
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {laws_import} as Laws", ""]
    for nm, h in tb:
        rows = []
        for k, val in sorted((tables.get(h) or {}).items()):
            b = bytes.fromhex(k[2:])
            rows.append("M.HKB{" + (("[" + ", ".join(str(c) for c in b) + "]") if b else "Nil{}") + ", "
                        + lit.word("0x%064x" % val) + "}")
        lines.append(f"def t_{nm}() -> List<&2, M.HKB>:\n  " + (("[" + ", ".join(rows) + "]") if rows else "Nil{}"))
        lines.append("")
    for i, a in enumerate(acts):
        lines.append(f"def w_a{i}() -> M.HAct:\n  {lit.text(a)}")
        lines.append("")
    targs = "".join(f", t_{nm}()" for nm, _h in tb)

    def run_of(k: int) -> str:
        pre = "[" + ", ".join(f"w_a{i}()" for i in range(k)) + "]" if k else "Nil{}"
        return f"M.run({pre}, M.gh_s0(){targs})"
    n = len(acts) - 1
    chain = "M.R0{{==}}"
    for k in range(n):
        chain = f"M.RStep{{w_a{k}(), {run_of(k)}, {chain}, {{==}}}}"
    tup = f"({run_of(n)}, ({chain}, (w_a{n}(), {{==}})))"
    for nm, _h in reversed(tb):
        tup = f"(t_{nm}(), {tup})"
    lines.append(f"def Laws.nv_{lid.lower()}():\n  {tup}")
    return "\n".join(lines) + "\n"
