"""The Bend files of an I30 law (I30; the contract is the docstring of tests_m3/test_sort_types.py, "Law IR", "The typed
model and its ghost section" and "Proofs, refutation, non-vacuity").

  law_file(law, x, model_rel, hashes, counter)   gen/<M>/laws/<id>/LAWS.bend: the law (forall s: Reach, a: Act and
                                                 the hash tables: coerce_<x>(a, s, ..) == True), or, for a REFUTED law,
                                                 its counter-law (exists ..: coerce_<x>(a, s, ..) != True); it imports
                                                 the typed model as M
  counter_proof(..)                              a counter-law proof: the concrete witness (its hash tables, the
                                                 literal state after each prefix step, its Reach chain R0 then one
                                                 RStep per step, and the entry step), every premise by computation
  inhabitant(..)                                 a non-vacuity proof of chit_<x> (G11V): the same shape, for the law
                                                 "exists a reachable state and step that reach a hit"

The shape of a proof (A30). Every computation is a closed lemma of one step: r_k states that the literal state after
step k is gh_step of the literal state before it, cz (ch) that the entry step's coerce_<x> is false (chit_<x> true) at
the literal pre-entry state. The Reach chain and the counter-law only cite them: the refutation's binder (e => ..)
rewrites with cz, and nothing runs the model under it, where the BendTT kernel reduces lazily and shares nothing. So
each kernel conversion runs one step, and none re-runs a prefix (I30's form, run(prefix, gh_s0()) in every RStep and
under the binder, ran out of the kernel's fuel on every rollup witness).

Witness literals are data: a word is M.w_of_limbs([l0, .., l7]) and a byte string a list of byte literals, so that
spec/M3/lib/term_size.json's measure counts each as one term. Nothing here names a target.
"""
from __future__ import annotations

import os
import re
from pathlib import Path

from ..gen.mlaws import law_name

HEADER = "# GENERATED by holon.sorts.proofs3 from the frozen law IR; do not edit."
PHEADER = "# GENERATED by holon.sorts.proofs3; untrusted, accepted only if Bend checks it."


def rel_import(from_dir: Path, target: Path) -> str:
    return os.path.relpath(Path(target).resolve(), Path(from_dir).resolve()).replace(os.sep, "/")


def tabs_binders(hashes: list[str]) -> list[tuple[str, str]]:
    return [("kh" if h == "keccak256" else "sh", h) for h in hashes]


def law_file(law: dict, statement_hash: str, model_import: str, hashes: list[str], counter: bool = False) -> str:
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    kw = "exs" if counter else "for"
    q = "" if counter else "+"
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", ""]
    lines.append(f"law {law_name(lid, counter)}:")
    for n, _h in tb:
        lines.append(f"  {kw} {q}{n}: List<&2, M.HKB>")
    lines.append(f"  {kw} {q}s: M.GSt")
    lines.append(f"  {kw} r_s: M.Reach<{idx}s>")
    lines.append(f"  {kw} {q}a: M.HAct")
    rel = "!=" if counter else "=="
    lines.append(f"  {{M.coerce_{x}(a, s{''.join(', ' + n for n, _h in tb)}) {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def inhabitant_law(law: dict, statement_hash: str, model_import: str, hashes: list[str]) -> str:
    """gen/<M>/<id>/nonvac/LAWS.bend: a reachable state and a step that reach a hit of the law's coercion."""
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    lines = [HEADER, f"# non-vacuity of {lid} (statement_hash {statement_hash}): the at-site premise chit_{x} is "
             "inhabited by a reachable state and a step", "import Base", f"import {model_import} as M", ""]
    lines.append(f"law nv_{lid.lower()}:")
    for n, _h in tb:
        lines.append(f"  exs {n}: List<&2, M.HKB>")
    lines += ["  exs s: M.GSt", f"  exs r_s: M.Reach<{idx}s>", "  exs a: M.HAct",
              f"  {{M.chit_{x}(a, s{''.join(', ' + n for n, _h in tb)}) == True{{}} : Bool}}"]
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------------------ literals
class Lit:
    """Bend text of the evaluator's JSON values (holon.sorts.evaluate3 encodings), qualified by M."""

    def __init__(self, recs: dict):
        self.recs = recs

    def word(self, h: str) -> str:
        v = int(h, 16)
        if v == 0:
            return "M.w0()"
        limbs = [(v >> (32 * i)) & 0xFFFFFFFF for i in range(8)]
        return "M.w_of_limbs([" + ", ".join(str(x) for x in limbs) + "])"

    def text(self, v) -> str:
        if isinstance(v, bool):
            return "True{}" if v else "False{}"
        if isinstance(v, int):
            return str(v)
        if isinstance(v, list):
            return ("[" + ", ".join(self.text(x) for x in v) + "]") if v else "Nil{}"
        if isinstance(v, dict):
            if "$w" in v:
                return self.word(v["$w"])
            if "$b" in v:
                b = bytes.fromhex(v["$b"][2:])
                return ("[" + ", ".join(str(x) for x in b) + "]") if b else "Nil{}"
            if "$r" in v:
                name = v["$r"]
                fs = self.recs.get(name)
                vals = v.get("f") or {}
                order = [f for f, _t in fs] if fs is not None else list(vals)
                return f"M.{name}{{" + ", ".join(self.text(vals[f]) for f in order) + "}"
        raise ValueError(f"no Bend literal for {str(v)[:120]}")

    def typed(self, v, ty: str) -> str:
        """A decoded model value (the evaluator's output: words as 0x-strings, byte lists as {"$b"}, records as
        {"$r"}) as a literal of Bend type ty."""
        ty = ty.strip()
        if ty == "W":
            return self.word(v if isinstance(v, str) else v["$w"])
        if ty == "Bool":
            return "True{}" if v else "False{}"
        if ty == "U32":
            return str(int(v))
        if ty == "Nat":
            return f"{int(v)}n"
        if ty.startswith("List<&2, ") and ty.endswith(">"):
            el = ty[len("List<&2, "):-1].strip()
            if el == "U32":
                xs = list(bytes.fromhex(v["$b"][2:])) if isinstance(v, dict) else [int(x) for x in v]
                return ("[" + ", ".join(str(x) for x in xs) + "]") if xs else "Nil{}"
            return ("[" + ", ".join(self.typed(x, el) for x in v) + "]") if v else "Nil{}"
        if isinstance(v, dict) and "$r" in v:
            name = v["$r"]
            fs = self.recs.get(name)
            vals = v.get("f") or {}
            if fs is None:
                if vals:
                    raise ValueError(f"no field types for {name}")
                return f"M.{name}{{}}"
            return f"M.{name}{{" + ", ".join(self.typed(vals[f], t) for f, t in fs) + "}"
        raise ValueError(f"no Bend literal of {ty} for {str(v)[:120]}")


def _table_defs(tb: list, tables: dict, lit: Lit) -> list[str]:
    lines = []
    for n, h in tb:
        rows = []
        for k, val in sorted((tables.get(h) or {}).items()):
            b = bytes.fromhex(k[2:])
            rows.append("M.HKB{" + (("[" + ", ".join(str(c) for c in b) + "]") if b else "Nil{}") + ", "
                        + lit.word("0x%064x" % val) + "}")
        lines.append(f"def t_{n}() -> List<&2, M.HKB>:\n  " + (("[" + ", ".join(rows) + "]") if rows else "Nil{}"))
        lines.append("")
    return lines


def _trace_defs(tb: list, acts: list, states: list, lit: Lit) -> tuple[list[str], str, str]:
    """The witness's actions, the literal state after each prefix step (states[k - 1] after k steps; the deployment is
    M.gh_s0()), one lemma per prefix step (r_k: the state after step k is gh_step of the state before it, both
    literals, so one kernel conversion computes one step), and the Reach chain they make. Returns (lines, the chain,
    the pre-entry state term)."""
    targs = "".join(f", t_{n}()" for n, _h in tb)
    lines = []
    for i, a in enumerate(acts):
        lines.append(f"def w_a{i}() -> M.HAct:\n  {lit.text(a)}")
        lines.append("")
    n = len(acts) - 1
    if len(states) != n:
        raise ValueError(f"{n} prefix steps but {len(states)} states")

    def st(k: int) -> str:
        return "M.gh_s0()" if k == 0 else f"s_{k}()"
    for k in range(1, n + 1):
        lines.append(f"def s_{k}() -> M.GSt:\n  {lit.typed(states[k - 1], 'GSt')}")
        lines.append("")
    for k in range(n):
        lines.append(f"def r_{k}() -> {{{st(k + 1)} == M.gh_step(w_a{k}(), {st(k)}{targs}) : M.GSt}}:\n  {{==}}")
        lines.append("")
    chain = "M.R0{{==}}"
    for k in range(n):
        chain = f"M.RStep{{w_a{k}(), {st(k)}, {chain}, r_{k}()}}"
    return lines, chain, st(n)


def counter_proof(law: dict, model_import: str, laws_import: str, hashes: list[str], acts: list, tables: dict,
                  lit: Lit, note: str, states: list) -> str:
    """The counter-law proof of one witness: acts are the evaluator's HAct values, the entry step's last; states are the
    decoded states after each prefix step. Every premise is a closed lemma that computes one step (A30): r_k for the
    k-th step of the Reach chain, cz for the entry step's coercion. The counter-law only rewrites with them, so no
    kernel conversion runs the model under the refutation's binder (where the kernel's reduction is lazy and shares
    nothing)."""
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    targs = "".join(f", t_{n}()" for n, _h in tb)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {laws_import} as Laws", ""]
    lines.append(f"# class counter: {note}")
    lines += _table_defs(tb, tables, lit)
    body, chain, state = _trace_defs(tb, acts, states, lit)
    lines += body
    last = f"w_a{len(acts) - 1}()"
    lines.append(f"def cz() -> {{M.coerce_{x}({last}, {state}{targs}) == False{{}} : Bool}}:\n  {{==}}")
    lines.append("")
    lines.append("def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})")
    lines.append("")
    tup = f"({state}, ({chain}, ({last}, e => true_ne_false((%e : {{_ == False{{}} : Bool}}\n  cz())))))"
    for nm, _h in reversed(tb):
        tup = f"(t_{nm}(), {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"


def inhabitant_proof(law: dict, model_import: str, laws_import: str, hashes: list[str], acts: list, tables: dict,
                     lit: Lit, states: list) -> str:
    """The non-vacuity proof of a PROVED law (G11V): the same per-step lemmas, and a closed lemma ch for the entry
    step's hit."""
    lid = law["law_id"]
    x = lid[len("L_sort_"):]
    tb = tabs_binders(hashes)
    targs = "".join(f", t_{nm}()" for nm, _h in tb)
    lines = [PHEADER, "import Base", f"import {model_import} as M", f"import {laws_import} as Laws", ""]
    lines += _table_defs(tb, tables, lit)
    body, chain, state = _trace_defs(tb, acts, states, lit)
    lines += body
    last = f"w_a{len(acts) - 1}()"
    lines.append(f"def ch() -> {{M.chit_{x}({last}, {state}{targs}) == True{{}} : Bool}}:\n  {{==}}")
    lines.append("")
    tup = f"({state}, ({chain}, ({last}, ch())))"
    for nm, _h in reversed(tb):
        tup = f"(t_{nm}(), {tup})"
    lines.append(f"def Laws.nv_{lid.lower()}():\n  {tup}")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------------------------------------ coercion_guard
class NoProof(Exception):
    """The generator does not apply (named)."""


def model_names(text: str) -> set:
    """The definitions, types and constructors the model declares (a proof qualifies them with M.)."""
    out = set(re.findall(r"(?m)^def\s+(\w+)\s*\(", text)) | set(re.findall(r"(?m)^type\s+(\w+)", text))
    for body in re.findall(r"(?m)^type\s+\w+[^\n]*\n((?:  \w+\{[^\n]*\n)+)", text):
        out |= set(re.findall(r"(?m)^  (\w+)\{", body))
    return out


def qualify(code: str, names: set) -> str:
    """The model's definitions and constructors in a term, qualified by M (Bend's builtins keep their names)."""
    def sub(m):
        n = m.group(1)
        return ("M." + n if n in names else n) + m.group(2)
    return re.sub(r"(?<![\w.])([A-Za-z_]\w*)(\s*[({])", sub, code)


def _at(cond: str, ctx: str) -> str:
    """A statement's condition (a term of its context x) at a given context term."""
    return re.sub(r"(?<![\w.])x(?![\w{])", lambda _m: ctx, cond)


def _orders(expr) -> list:
    """(A, B) pairs a passed condition establishes as A >= B (unsigned): [">=", A, B], ["<=", B, A], ["!", ["<", A, B]],
    ["!", [">", B, A]], and each conjunct of a conjunction."""
    out = []
    if not isinstance(expr, list) or not expr:
        return out
    h = expr[0]
    if h == ">=" and len(expr) == 3:
        out.append((expr[1], expr[2]))
    elif h == "<=" and len(expr) == 3:
        out.append((expr[2], expr[1]))
    elif h == "!" and len(expr) == 2 and isinstance(expr[1], list) and len(expr[1]) == 3 and expr[1][0] in ("<", ">"):
        a, b = expr[1][1], expr[1][2]
        out.append((a, b) if expr[1][0] == "<" else (b, a))
    elif h == "&&":
        for y in expr[1:]:
            out += _orders(y)
    return out


def _difference(expr):
    """(A, B) of a realization check of a difference: ["fits", n, ["-", A, B]]."""
    if (isinstance(expr, list) and len(expr) == 3 and expr[0] == "fits" and isinstance(expr[2], list)
            and len(expr[2]) == 3 and expr[2][0] == "-"):
        return expr[2][1], expr[2][2]
    return None


def coercion_guard(law: dict, mm, model_text: str, model_import: str, laws_import: str, hashes: list) -> str:
    """The proof of a realize law whose every hit is a realization check (I15's coercion_guard over the typed model).

    For each entry point the action's program is mirrored statement by statement from its context x0(st, ar, en, ..)
    (unconditional writes and events advance the context; each check is a lemma that matches its condition c, with
    the equation {condition == c}): a failing check other than the hit ends the run with its own code, which the law
    accepts by computation; at the hit, a failing realization contradicts ONE earlier passed check that orders the
    same two operands (A >= B), through one lemma by case on the comparison. No reachability is assumed (the lemmas
    hold for every state). Raises NoProof when a statement it cannot mirror (a loop, an external call, a conditional
    write or event) is in the program, or no earlier check orders the operands."""
    from ..rules.sort import canonical, ghost_x
    lid = law["law_id"]
    x = ghost_x(lid)
    if law["subform"] != "realize":
        raise NoProof("coercion_guard decides realize laws")
    names = model_names(model_text)
    tb = tabs_binders(hashes)
    tparams = "".join(f", +{n}: List<&2, M.HKB>" for n, _h in tb)
    targs = "".join(f", {n}" for n, _h in tb)
    per_action: dict = {}
    for h in law["hits"]:
        if h["kind"] != "realization_check":
            raise NoProof(f"{h['action']}: a hit that is not a realization check")
        per_action.setdefault(h["action"], []).append(h["at"])
    out = [PHEADER, "import Base", f"import {model_import} as M", f"import {laws_import} as Laws", "",
           "# class coercion_guard: each entry point's program mirrored from its context x0; at the hit a failing",
           "# realization contradicts one earlier passed check that orders the operands of the realized difference;",
           "# no reachability is assumed (every lemma holds for every state).", "",
           "def efq(-P: Type, x: Empty) -> P:\n  match x:\n",
           "def cg_false_ne_true(e: {False{} == True{} : Bool}) -> Empty:\n"
           "  (%Equal.sym(Bool, False{}, True{}, e) : M.is_true(_)\n  Unit{})\n",
           "def cg_true_ne_false(e: {True{} == False{} : Bool}) -> Empty:\n  (%e : M.is_true(_)\n  Unit{})\n"]
    lemmas: dict = {}
    mirrors: dict = {}
    for a in sorted(per_action):
        ba = re.sub(r"[^A-Za-z0-9_]", "_", a)
        if len(per_action[a]) != 1:
            raise NoProof(f"{a}: {len(per_action[a])} hits in one action")
        K = mm.cidx_of(a, per_action[a][0]) + 1
        stmts = sorted(mm.stmts.get(a) or [], key=lambda r: -r["i"])     # program order (the chain is built backwards)
        ctx = f"M.x0_{ba}(st, ar, en{targs})"
        defs = []
        for r in stmts:
            if not r["top"]:
                continue
            if r["calls"]:
                raise NoProof(f"{a}: an external call at statement {r['i']}")
            if r["kind"] in ("write", "event"):
                if r["cond"] is not None:
                    raise NoProof(f"{a}: a conditional {r['kind']} at statement {r['i']}")
                ctx = f"M.{r['helper']}({ctx})"
                continue
            if r["kind"] != "check":
                raise NoProof(f"{a}: a {r['kind']} record in the program")
            defs.append({"i": r["i"], "helper": r["helper"], "code": r["code"], "raw": r["cond"],
                         "cond": qualify(_at(r["cond"], "@CTX@"), names).replace("@CTX@", ctx), "ctx": ctx,
                         "expr": r["expr"]})
        hit = [j for j, d in enumerate(defs) if d["code"] == K]
        if len(hit) != 1:
            raise NoProof(f"{a}: the hit is not one check of the program")
        hj = hit[0]
        ab = _difference(defs[hj]["expr"])
        if ab is None:
            raise NoProof(f"{a}: the hit is not the realization of a difference")
        src = None
        for j in range(hj):
            if any(canonical([p, q]) == canonical(list(ab)) for p, q in _orders(defs[j]["expr"])):
                src = j
                break
        if src is None:
            raise NoProof(f"{a}: no earlier check orders the operands of the realized difference")
        raw = defs[hj]["raw"]
        m = re.match(r"is_some_(T_\w+)\(realize_(T_\w+)\(", raw)
        if m is None or not raw.endswith("))"):
            raise NoProof(f"{a}: the hit's condition is not a realization")
        tu, ts = m.group(1), m.group(2)
        diff = qualify(_at(raw[m.end():-2], "@CTX@"), names).replace("@CTX@", defs[hj]["ctx"])
        lem = f"cg_rz_{ts}_{tu}"
        lemmas[lem] = (
            f"# the sign of a signed value\n"
            f"def cg_ng_{ts}(v: M.{ts}) -> Bool:\n  match v:\n    case M.{ts}{{ng, p}}:\n      ng\n\n"
            f"# A >= B (not (A < B)) contradicts a failing realization of A - B: by case on A < B\n"
            f"def {lem}_b(b: Bool, +p: M.W, e1: {{Bool.not(b) == True{{}} : Bool}}, "
            f"e2: {{M.is_some_{tu}(M.rzg_{ts}(b, p)) == False{{}} : Bool}}) -> Empty:\n  match b:\n"
            f"    case True{{}}:\n      cg_false_ne_true(e1)\n    case False{{}}:\n      cg_true_ne_false(e2)\n\n"
            f"def {lem}(d: M.{ts}, e1: {{Bool.not(cg_ng_{ts}(d)) == True{{}} : Bool}}, "
            f"e2: {{M.is_some_{tu}(M.realize_{ts}(d)) == False{{}} : Bool}}) -> Empty:\n  match d:\n"
            f"    case M.{ts}{{ng, p}}:\n      {lem}_b(ng, p, e1, e2)\n")
        cz = f"M.cz_{x}_{ba}"
        sig = f"+st: M.HSt, +ar: M.AR_{ba}, +en: M.HEnv{tparams}"
        texts = []                      # the last check first: a definition precedes its use
        for j in range(len(defs) - 1, -1, -1):
            d = defs[j]
            carry = src < j <= hj
            goal = f"{{{cz}(M.o_code(M.xo_{ba}(M.{d['helper']}(c, {d['ctx']})))) == True{{}} : Bool}}"
            es = f", es: {{{defs[src]['cond']} == True{{}} : Bool}}" if carry else ""
            if j + 1 < len(defs):
                n = defs[j + 1]
                pass_es = ", e" if (j == src and src < hj) else (", es" if src < j < hj else "")
                t_branch = f"cg_{x}_{ba}_{n['i']}({n['cond']}, st, ar, en{targs}{pass_es}, {{==}})"
            else:
                t_branch = "{==}"
            if j == hj:
                fgoal = f"{{{cz}(M.o_code(M.xo_{ba}(M.{d['helper']}(False{{}}, {d['ctx']})))) == True{{}} : Bool}}"
                f_branch = f"efq({fgoal}, {lem}({diff}, es, e))"
            else:
                f_branch = "{==}"
            texts.append(f"def cg_{x}_{ba}_{d['i']}(c: Bool, {sig}{es}, e: {{{d['cond']} == c : Bool}}) -> {goal}:\n"
                         f"  match c:\n    case True{{}}:\n      {t_branch}\n    case False{{}}:\n      {f_branch}\n")
        mirrors[ba] = (texts, defs[0])
    for lem in sorted(lemmas):
        out.append(lemmas[lem])
    for ba in sorted(mirrors):
        out += mirrors[ba][0]
    acts = re.findall(r"(?m)^  A_(\w+)\{ar: AR_\w+, en: HEnv\}$", model_text)
    if not acts:
        raise NoProof("the model declares no action constructors")
    cases = []
    for ba in acts:
        if ba not in mirrors:
            cases.append(f"    case M.A_{ba}{{_, _}}:\n      {{==}}\n")
            continue
        d0 = mirrors[ba][1]
        c0 = qualify(_at(d0["raw"], "@CTX@"), names).replace("@CTX@", f"M.x0_{ba}(M.gh_get_st(s), ar, en{targs})")
        cases.append(f"    case M.A_{ba}{{+ar, +en}}:\n      cg_{x}_{ba}_{d0['i']}({c0}, M.gh_get_st(s), ar, en{targs}, "
                     f"{{==}})\n")
    params = "".join(f"{n}, " for n, _h in tb)
    out.append(f"def Laws.{law_name(lid)}({params}s, r_s, a):\n  match a:\n" + "".join(cases))
    return "\n".join(out)
