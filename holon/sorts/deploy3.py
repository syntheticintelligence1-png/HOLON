"""The deployment of a typed milestone's binding: the initial state of the M3 model's Reach (I30; the contract is the
docstring of tests_m3/test_sort_types.py, rule N9 and the `holon model` paragraph).

  deployment(root, binding_rel, doc_rel) -> {"binding", "target", "harness", "storage": {"0x<slot>": "0x<word>"},
                                             "preimages": ["0x.."], "immutables": {name: "0x.."}, "timestamp",
                                             "number", "chainid", "calls": [{"caller", "value", "data", "reverted"}]}

The binding's own harness deploys the real target and its dependencies (its holonDeploy, with the binding's deployment
parameters, holon.fragments_corpus.binding_init: configuration of the deployment, not facts of the code). A generated
test contract inheriting the binding's harness contract records, around that deployment, every storage write to the
target (vm.startStateDiffRecording: the slots are exact), the target's and its implementation's runtime code, and every
call the harness made into the target. The storage is the target's slots after the deployment; the immutables come
from the implementation's code at the compiler's immutable references (holon.replay_fragments.Target); the preimages
are the byte strings the deployment hashed, found by running each recorded call into the target through I20's
evaluator of record (holon.extracted_eval) from the storage before it and recording the inputs of its keccak256 and
sha256 (the search's candidates for byte arguments, such as a header the deployment stored the hash of).

The result is cached outside the repository (~/.holon/cache/m3init/), keyed by the binding, its harness files, the
document, the checkout commit, the deployment parameters and this module's text.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shutil
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CAPTURE = "HolonDeployCaptureTest"


class DeployError(RuntimeError):
    pass


def _cache() -> Path:
    return Path(os.environ.get("HOLON_CACHE") or (Path.home() / ".holon" / "cache")) / "m3init"


def capture_source(binding: dict, root: Path) -> str:
    """The generated capture contract: it inherits the binding's harness contract."""
    name = binding["harness"]["contract"]
    files = binding["harness"]["files"]
    src = next((f for f in files if re.search(rf"(?m)^\s*(abstract\s+)?contract\s+{re.escape(name)}\b",
                                              (Path(root) / f).read_text())), None)
    base = next((f for f in files if re.search(r"(?m)^\s*abstract\s+contract\s+HolonStepBase\b",
                                               (Path(root) / f).read_text())), None)
    if src is None or base is None:
        raise DeployError(f"the binding's harness files define no contract {name} (or no HolonStepBase)")
    return f"""// SPDX-License-Identifier: MIT
// GENERATED by holon.sorts.deploy3: the deployment of the binding's harness, recorded (the M3 model's initial state).
pragma solidity =0.8.24;

import {{{name}}} from "./{Path(src).name}";
import {{HolonStepVm}} from "./{Path(base).name}";

contract {CAPTURE} is {name} {{
    function test_capture() public {{
        SV.pauseGasMetering();
        (, , uint256[] memory init) = holonLoad();
        SV.startStateDiffRecording();
        address target = holonDeploy(0, init);
        HolonStepVm.AccountAccess[] memory acc = SV.stopAndReturnStateDiff();
        holonTarget = target;
        holonLine(string.concat("T 0 ", ha(target), " ", ha(address(this))));
        holonLine(string.concat("K 0 ", hx(target.code)));
        address impl = address(uint160(uint256(SV.load(target, EIP1967_IMPLEMENTATION))));
        if (impl != address(0)) holonLine(string.concat("Q 0 ", ha(impl), " ", hx(impl.code)));
        for (uint256 i = 0; i < acc.length; i++) {{
            if (acc[i].account == target && acc[i].accessor == address(this)
                && acc[i].kind == HolonStepVm.AccountAccessKind.Call) {{
                holonLine(string.concat("I ", dec(i), " ", ha(acc[i].accessor), " ", dec(acc[i].value), " ",
                                        hx(acc[i].data), acc[i].reverted ? " 1" : " 0"));
            }}
            HolonStepVm.StorageAccess[] memory st = acc[i].storageAccesses;
            for (uint256 j = 0; j < st.length; j++) {{
                if (st[j].account != target || !st[j].isWrite) continue;
                holonLine(string.concat("W ", dec(i), " ", SV.toString(abi.encodePacked(st[j].slot)), " ",
                                        SV.toString(abi.encodePacked(st[j].newValue)), st[j].reverted ? " 1" : " 0"));
            }}
        }}
        holonLine(string.concat("Z 0 ", dec(block.timestamp), " ", dec(block.number), " ", dec(block.chainid)));
    }}
}}
"""


def _key(root: Path, binding_rel: str, binding: dict, doc_rel: str, init: list, commit: str | None) -> str:
    h = hashlib.sha256()
    for p in [binding_rel] + list(binding["harness"]["files"]) + [doc_rel]:
        h.update(p.encode() + b"\0" + (Path(root) / p).read_bytes() + b"\0")
    h.update(json.dumps([init, commit]).encode())
    h.update(Path(__file__).read_bytes())
    return h.hexdigest()


def parse(text: str) -> dict:
    out = {"writes": [], "calls": [], "target": None, "harness": None, "code": "0x", "impl": None, "impl_code": None}
    for line in text.splitlines():
        f = line.split(" ")
        if f[0] == "T":
            out["target"], out["harness"] = f[2].lower(), f[3].lower()
        elif f[0] == "K":
            out["code"] = f[2]
        elif f[0] == "Q":
            out["impl"], out["impl_code"] = f[2].lower(), f[3]
        elif f[0] == "W":
            out["writes"].append((int(f[1]), int(f[2], 16), int(f[3], 16), f[4] == "1"))
        elif f[0] == "I":
            out["calls"].append({"entry": int(f[1]), "caller": f[2].lower(), "value": int(f[3]), "data": f[4].lower(),
                                 "reverted": f[5] == "1"})
        elif f[0] == "Z":
            out["timestamp"], out["number"], out["chainid"] = int(f[2]), int(f[3]), int(f[4])
    return out


def run_capture(root: Path, binding_rel: str, binding: dict, doc: dict, init: list, work: Path) -> tuple[dict, Path]:
    from ..replay import check_checkout, morph_path, toolchain
    from ..replay_fragments import _run, forge_build, harness_project
    checkout = None
    if binding["project"]["kind"] == "checkout":
        checkout = morph_path(argparse.Namespace(), root)
        check_checkout(checkout, (doc.get("target") or {}).get("commit"))
    tc = toolchain(argparse.Namespace(forge=None, solc=None, write_pins=False), root)
    proj = harness_project(binding, work, root, checkout, tc)
    (proj / "test" / f"{CAPTURE}.t.sol").write_text(capture_source(binding, root))
    forge_build(proj, tc)
    fin, fout = proj / "holon_deploy_in.json", proj / "holon_deploy_out.txt"
    fin.write_text(json.dumps({"lens": [], "steps": [], "slots": [], "init": init}))
    code, out = _run(["nice", "-n", "10", tc["forge"], "test", "--offline", "--use", tc["solc"], "--match-contract",
                      f"^{CAPTURE}$", "--match-test", r"^test_capture\(\)$"], proj,
                     {"HOLON_STEPS_IN": fin.name, "HOLON_STEPS_OUT": fout.name})
    if code != 0 or not fout.exists():
        raise DeployError(f"the deployment capture failed (exit {code}): {out[-2000:]}")
    return parse(fout.read_text()), proj


def preimages(root: Path, doc_rel: str, cap: dict, source: str | None = None) -> list[str]:
    """The byte strings the deployment hashed: each recorded call into the target, run by holon.extracted_eval from
    the storage before it, with its keccak256 and sha256 inputs recorded."""
    from .. import evm_abi as abi
    from .. import extracted_eval as EV
    from ..machine import load_extracted
    m = load_extracted(Path(root) / doc_rel, Path(root), source=(Path(root) / source) if source else None)
    by_sel = {str(a.get("selector") or "").lower(): n for n, a in m.actions.items() if a.get("selector")}
    seen: list = []
    orig_k, orig_t = EV.keccak, EV.Eval.t_sha256

    def rec_k(b: bytes) -> int:
        h = "0x" + bytes(b).hex()
        if h not in seen:
            seen.append(h)
        return orig_k(b)

    def rec_s(self, t):
        b = self.hash_input(t[1])
        h = "0x" + bytes(b).hex()
        if h not in seen:
            seen.append(h)
        return orig_t(self, t)
    EV.keccak, EV.Eval.t_sha256 = rec_k, rec_s
    try:
        state: dict = {}
        writes = sorted(cap["writes"], key=lambda w: w[0])
        wi = 0
        for c in sorted(cap["calls"], key=lambda c: c["entry"]):
            while wi < len(writes) and writes[wi][0] < c["entry"]:
                if not writes[wi][3]:
                    state[writes[wi][1]] = writes[wi][2]
                wi += 1
            action = by_sel.get(c["data"][:10])
            if action is None or c["reverted"]:
                continue
            try:
                args = abi.decode_args(m.params(action) or [], bytes.fromhex(c["data"][10:]))
            except Exception:  # noqa: BLE001: a call whose calldata the ABI does not decode hashes nothing here
                continue
            env = {"caller": c["caller"], "this": cap["target"], "msg.value": c["value"],
                   "block.timestamp": cap.get("timestamp", 0), "block.number": cap.get("number", 0),
                   "block.chainid": cap.get("chainid", 0), "msg.data.length": (len(c["data"]) - 2) // 2,
                   "blobhash": [], "calls": []}
            EV.step(m, {k: v for k, v in state.items()}, action, args, env)
    finally:
        EV.keccak, EV.Eval.t_sha256 = orig_k, orig_t
    return sorted(seen)


def immutables(proj: Path, binding: dict, doc: dict, cap: dict) -> dict:
    from ..replay_fragments import Target
    tgt = Target.build(proj, binding, doc)
    src = cap.get("impl_code") or cap.get("code") or "0x"
    out = {}
    for name, (start, n) in sorted(tgt.immutables.items()):
        w = src[2 + 2 * start: 2 + 2 * (start + n)]
        if len(w) == 2 * n:
            out[name] = "0x" + w
    return out


def deployment(root: Path, binding_rel: str, doc_rel: str, source: str | None = None) -> dict:
    from ..fragments_corpus import binding_init
    from ..replay_fragments import load_binding
    root = Path(root)
    binding = load_binding(root / binding_rel)
    doc = json.loads((root / doc_rel).read_text(encoding="utf-8"))
    init = binding_init(binding, root)
    commit = (doc.get("target") or {}).get("commit")
    key = _key(root, binding_rel, binding, doc_rel, init, commit)
    cp = _cache() / f"{key}.json"
    if cp.is_file():
        try:
            return json.loads(cp.read_text())
        except ValueError:
            pass
    work = Path(tempfile.mkdtemp(prefix="holon-m3-deploy-"))
    try:
        cap, proj = run_capture(root, binding_rel, binding, doc, init, work)
        storage: dict = {}
        for _e, slot, val, rev in cap["writes"]:
            if not rev:
                storage[slot] = val
        res = {"binding": binding_rel, "target": cap["target"], "harness": cap["harness"],
               "storage": {"0x%064x" % k: "0x%064x" % v for k, v in sorted(storage.items()) if v},
               "preimages": preimages(root, doc_rel, cap, source),
               "immutables": immutables(proj, binding, doc, cap),
               "timestamp": cap.get("timestamp"), "number": cap.get("number"), "chainid": cap.get("chainid"),
               "calls": [{k: c[k] for k in ("caller", "value", "data", "reverted")} for c in cap["calls"]],
               "init": init}
    finally:
        shutil.rmtree(work, ignore_errors=True)
    cp.parent.mkdir(parents=True, exist_ok=True)
    cp.write_text(json.dumps(res, indent=2, sort_keys=True))
    return res
