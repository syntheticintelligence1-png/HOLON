"""Sorts compiled to Bend types (whitepaper 7.8).

Every semantic sort of the frozen assignment becomes a nominal Bend type wrapping its realization
(Nat for machine words); realization, point/duration arithmetic and tag discrimination are total
functions on those types.  A coercion that needs a premise (signed -> unsigned, union -> member,
narrow width) is compiled to a function that *takes the premise as a proof argument*: a program
that lacks the proof does not type-check.  The file is checked with `bend`; the canary file is the
same file with one obligation dropped, and must be rejected.
"""
from __future__ import annotations

from . import grammar as G

HEAD = ["# GENERATED by holon.sorts.bendgen from the frozen sort assignment; do not edit.", "import Base", "",
        "def is_true(b: Bool) -> Type:", "  match b:", "    case True{}:", "      Unit", "    case False{}:", "      Empty", "",
        "def efq(-P: Type, x: Empty) -> P:", "  match x:", "", "",
        "def false_ne_true(e: {False{} == True{} : Bool}) -> Empty:",
        "  (%Equal.sym(Bool, False{}, True{}, e) : is_true(_)", "  Unit{})", ""]


def tname(s: G.Sort) -> str:
    """Bend type name of a sort (nominal: distinct sorts are distinct types)."""
    if s.kind == "Mach":
        return f"S_Mach{s.arg}"
    if s.kind == "Union":
        return "S_U_" + "_".join(tname(m)[2:] for m in s.members)
    base = {"Time": "S_Time", "Dur": "S_SDur" if s.signed else "S_Dur", "Idx": "S_Idx", "Cnt": "S_SCnt" if s.signed else "S_Cnt",
            "Prin": "S_Prin", "Amt": "S_Amt", "Dig": "S_Dig", "Ver": "S_Ver", "Bool": "Bool", "Null": "S_Null"}[s.kind]
    return base + (f"_{s.arg}" if s.arg else "")


def _atoms(assignment: dict) -> list[G.Sort]:
    seen: set = set()
    for table in ("registers", "fields", "lets", "params", "inputs"):
        for txt in assignment.get(table, {}).values():
            try:
                s = G.parse(txt)
            except Exception:
                continue
            for m in G.members(s):
                if m.kind in ("Record", "List", "Bool"):
                    continue
                seen.add(m)
    return sorted(seen)


def type_decl(s: G.Sort) -> list[str]:
    n = tname(s)
    if s.kind == "Null":
        return [f"type {n} is Data:", f"  {n}{{}}", ""]
    if s.kind == "Mach":
        return [f"type {n} is Data:", f"  {n}{{w: Nat}}", ""]
    if s.signed:                                    # 7.1: a signed duration/count is a sign and a magnitude
        return [f"type {n} is Data:", f"  {n}{{neg: Bool, mag: Nat}}", "",
                f"def {n}_neg(x: {n}) -> Bool:", "  match x:", f"    case {n}{{neg, mag}}:", "      neg", "",
                f"def {n}_mag(x: {n}) -> Nat:", "  match x:", f"    case {n}{{neg, mag}}:", "      mag", ""]
    return [f"type {n} is Data:", f"  {n}{{v: Nat}}", "", f"def {n}_v(x: {n}) -> Nat:", "  match x:", f"    case {n}{{v}}:", "      v", ""]


def realize(s: G.Sort) -> list[str]:
    """realize : S -> Mach (7.8).  Unsigned sorts realize unconditionally; a signed sort needs the
    non-negativity premise `neg == False` as an argument (the coercion obligation)."""
    n = tname(s)
    if s.kind in ("Null", "Mach"):
        return []
    if s.signed:
        return [f"def realize_{n[2:]}(x: {n}, nonneg: {{{n}_neg(x) == False{{}} : Bool}}) -> Nat:",
                f"  {n}_mag(x)", ""]
    return [f"def realize_{n[2:]}(x: {n}) -> Nat:", f"  {n}_v(x)", ""]


def affine(atoms: list[G.Sort]) -> list[str]:
    """The affine rules of 7.2 as typed operations; ill-sorted combinations are simply not definable."""
    out = []
    for s in atoms:
        n = tname(s)
        if s.kind == "Time":
            d = tname(G.DUR)
            sd = tname(G.SDUR)
            out += [f"def shift_{n[2:]}(t: {n}, d: {d}) -> {n}:", f"  {n}{{Nat.add({n}_v(t), {d}_v(d))}}", "",
                    f"# Time - Time : signed duration (7.2); its realization needs the sign premise",
                    f"def diff_{n[2:]}(+a: {n}, +b: {n}) -> {sd}:",
                    f"  {sd}{{Nat.is_lt({n}_v(a), {n}_v(b)), Nat.sub(Nat.max({n}_v(a), {n}_v(b)), Nat.min({n}_v(a), {n}_v(b)))}}", ""]
        elif s.kind == "Idx":
            c = tname(G.Sort("Cnt", s.arg))
            sc = tname(G.Sort("Cnt", s.arg, True))
            out += [f"def offset_{n[2:]}(i: {n}, c: {c}) -> {n}:", f"  {n}{{Nat.add({n}_v(i), {c}_v(c))}}", "",
                    f"def dist_{n[2:]}(+a: {n}, +b: {n}) -> {sc}:",
                    f"  {sc}{{Nat.is_lt({n}_v(a), {n}_v(b)), Nat.sub(Nat.max({n}_v(a), {n}_v(b)), Nat.min({n}_v(a), {n}_v(b)))}}", ""]
        elif s.kind in ("Cnt", "Dur", "Amt") and not s.signed:
            out += [f"def add_{n[2:]}(a: {n}, b: {n}) -> {n}:", f"  {n}{{Nat.add({n}_v(a), {n}_v(b))}}", ""]
    return out


def union_types(assignment: dict) -> list[str]:
    """Untagged unions (7.4) become tagged sums; reading a member needs the tag premise."""
    out = []
    done: set = set()
    for table in ("registers", "fields"):
        for txt in assignment.get(table, {}).values():
            try:
                s = G.parse(txt)
            except Exception:
                continue
            if s.kind != "Union" or s in done:
                continue
            done.add(s)
            n = tname(s)
            ctors = [f"  {n}_{tname(m)[2:]}{{x: {tname(m)}}}" for m in s.members]
            out += [f"type {n} is Data:"] + ctors + [""]
            for m in s.members:
                mn = tname(m)
                out += [f"def is_{n[2:]}_{mn[2:]}(u: {n}) -> Bool:", "  match u:"]
                for k in s.members:
                    out += [f"    case {n}_{tname(k)[2:]}{{x}}:", f"      {'True{}' if k == m else 'False{}'}"]
                out.append("")
            for m in s.members:
                if m.kind == "Null":
                    continue
                mn = tname(m)
                out += [f"# union_read premise: the register currently holds the {m} member (ghost tag)",
                        f"def as_{n[2:]}_{mn[2:]}(u: {n}, h: {{is_{n[2:]}_{mn[2:]}(u) == True{{}} : Bool}}) -> {mn}:",
                        "  match u:"]
                for k in s.members:
                    kn = tname(k)
                    out += [f"    case {n}_{kn[2:]}{{x}}:", "      x" if k == m else f"      efq({mn}, false_ne_true(h))"]
                out.append("")
    return out


def width_coercions(assignment: dict) -> list[str]:
    """Narrowing to a realization width w needs the bound premise v < 2^w (7.6)."""
    out = []
    ws = sorted({w for w in assignment.get("widths", {}).values() if w and w < 256})
    for w in ws:
        if w <= 31:
            bound = f"{2 ** w}n"
        else:                                   # Bend nat literals stop at 2^32 - 1
            q, r = divmod(w, 16)
            bound = f"{2 ** r}n"
            for _ in range(q):
                bound = f"Nat.mul({bound}, 65536n)"
        out += [f"def bound_{w}() -> Nat:", f"  {bound}", "",
                f"def narrow_{w}(v: Nat, h: {{Nat.is_lt(v, bound_{w}()) == True{{}} : Bool}}) -> Nat:", "  v", ""]
    return out


CANARIES = ("signed_realize", "union_premise", "width_premise", "affine_point_plus_point")


def sites(assignment: dict) -> list[str]:
    """The obligation sites of the frozen assignment, each discharging its premise explicitly."""
    out = ["# commit site (Rollup.sol:363): W + startTime - t is Time - Time = signed Dur; realizing it needs the sign premise",
           "def site_remaining(+w: S_Dur, +cstart: S_Time, +t: S_Time, nonneg: {S_SDur_neg(diff_Time(shift_Time(cstart, w), t)) == False{} : Bool}) -> Nat:",
           "  realize_SDur(diff_Time(shift_Time(cstart, w), t), nonneg)", ""]
    if 16 in assignment.get("widths", {}).values():
        out += ["# l1TxNum (batch_data.go:41): the sum is narrowed to uint16; the bound premise is decided by evaluation",
                "def site_l1num_ok() -> Nat:", "  narrow_16(Nat.add(65534n, 1n), {==})", ""]
    return out


def generate(assignment: dict, canary_drop: str | None = None) -> str:
    """The Bend sort module.  `canary_drop` names an obligation premise to delete (the file must then fail)."""
    atoms = _atoms(assignment)
    derived: set = set(atoms)
    for s in atoms:                               # the sorts the affine rules produce from the atoms (7.2)
        if s.kind == "Time":
            derived |= {G.DUR, G.SDUR}
        if s.kind == "Idx":
            derived |= {G.Sort("Cnt", s.arg), G.Sort("Cnt", s.arg, True)}
    atoms = sorted(derived)
    body: list[str] = []
    for s in atoms:
        body += type_decl(s)
    for s in atoms:
        body += realize(s)
    body += affine(atoms)
    body += union_types(assignment)
    body += width_coercions(assignment)
    body += sites(assignment)
    if canary_drop == "signed_realize":      # the site realizes the signed duration without its sign premise
        body += ["def canary_remaining(w: S_Dur, cstart: S_Time, t: S_Time) -> Nat:",
                 "  realize_SDur(diff_Time(shift_Time(cstart, w), t))", ""]
    elif canary_drop == "union_premise":     # a union member is read with the wrong tag premise
        u = next((G.parse(t) for t in assignment["fields"].values() if "+" in t and "Prin" in t), None)
        if u is not None:
            n = tname(u)
            m = next(m for m in u.members if m.kind == "Prin")
            o = next(m for m in u.members if m.kind != "Prin")
            body += [f"def canary_union(x: {tname(o)}) -> {tname(m)}:", f"  as_{n[2:]}_{tname(m)[2:]}({n}_{tname(o)[2:]}{{x}}, {{==}})", ""]
    elif canary_drop == "width_premise":     # the bound premise is false for the summed count (2^16)
        body += ["def canary_l1num() -> Nat:", "  narrow_16(Nat.add(65535n, 1n), {==})", ""]
    elif canary_drop == "affine_point_plus_point":   # 7.2: Time + Time is ill-sorted (only Time + Dur shifts a point)
        body += ["def canary_affine(a: S_Time, b: S_Time) -> S_Time:", "  shift_Time(a, b)", ""]
    return "\n".join(HEAD + body).rstrip() + "\n"
