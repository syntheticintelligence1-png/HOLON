"""S2 extractor: `solc --ir-optimized` Yul -> layout facts (M2, docs/M2_SPEC.md §3).

Pipeline (all inputs come from the compiler's own output; nothing is hand-copied):

  1. Driver compilation. Internal library functions are dead code unless called,
     so the extractor generates a `HolonExtractDriver` contract that wraps every
     function of BatchHeaderCodecV0/V1 (signatures parsed from the sources). The
     driver is emitted verbatim into the extraction record; it adds no logic.
  2. `solc --ir-optimized` on the driver gives every codec `fun_*` fragment.
  3. `solc --ir-optimized` on Rollup.sol gives the consumer program:
     `_commitBatchWithBatchData`'s inlined store sequence, `_loadBatchHeader`'s
     version dispatch, `_getBatchVersion`'s empty check, the `version <= 2`
     domain guard and the `_headerLength` selection.
  4. Composition yields a holon-facts/0.1 document plus a fragment program per
     encoder/decoder for the Bend translator (layout_bend.py).

Never reads facts/: the only comparison target is the live compiler output.
"""
