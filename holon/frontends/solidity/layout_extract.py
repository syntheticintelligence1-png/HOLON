# ---------------------------------------------------------------- solc
def solc_version(solc: Path = SOLC) -> str:
    out = subprocess.run([str(solc), "--version"], capture_output=True, text=True)
    m = re.search(r"Version: (\S+)", out.stdout)
    if out.returncode != 0 or not m:
        raise RuntimeError(f"solc --version failed: {out.stderr[:400]}")
    return m.group(1)


def compile_ir(solc: Path, sources: list[str], cwd: Path,
               include: list[str] | None = None, remaps: list[str] | None = None) -> str:
    cmd = [str(solc), "--evm-version", EVM, "--base-path", ".", *sources]
    for p in include or []:
        cmd += ["--include-path", p]
    cmd += remaps or []
    cmd += ["--ir-optimized"]
    r = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)
    if r.returncode != 0:
        raise RuntimeError(f"solc failed: {r.stderr[:3000]}")
    return r.stdout


# ------------------------------------------------------- driver generation
_FN_RX = re.compile(
    r"function\s+(\w+)\s*\(([^)]*)\)\s*internal\s+pure(?:\s+returns\s*\(([^)]*)\))?\s*\{")


def library_functions(src: str) -> list[dict]:
    """Names and signatures of `internal pure` functions of a library, in file order."""
    out = []
    for m in _FN_RX.finditer(src):
        params = [p.strip() for p in m.group(2).split(",") if p.strip()]
        rets = [r.strip() for r in (m.group(3) or "").split(",") if r.strip()]
        out.append({"name": m.group(1), "params": params, "returns": rets})
    return out


def _decl_param(p: str, i: int) -> tuple[str, str]:
    """'uint256 batchPtr' -> ('uint256', 'batchPtr'); 'bytes calldata _h' -> same."""
    toks = p.split()
    if toks[-1].startswith("_"):
        return " ".join(toks[:-1]), toks[-1]
    return " ".join(toks[:-1]) or "uint256", toks[-1]


def gen_driver(morph: Path) -> tuple[str, dict]:
    """The driver contract + index of wrapped functions. Deterministic."""
    lines = ["// SPDX-License-Identifier: MIT",
             "// GENERATED by holon.frontends.solidity.layout_extract: defeats dead-code",
             "// elimination so every internal codec function survives --ir-optimized.",
             "pragma solidity ^0.8.24;"]
    wrapped = {}
    for lib_rel in CODEC_LIBS:
        src = (morph / CONTRACTS / lib_rel).read_text()
        lib = Path(lib_rel).stem
        lines.append(f'import "./{lib_rel}";')
        for fn in library_functions(src):
            wrapped[fn["name"]] = {"lib": lib, "params": fn["params"], "returns": fn["returns"]}
    lines.append("contract HolonExtractDriver {")
    for lib_rel in CODEC_LIBS:
        lib = Path(lib_rel).stem
        src = (morph / CONTRACTS / lib_rel).read_text()
        for fn in library_functions(src):
            decls, args = [], []
            for i, p in enumerate(fn["params"]):
                ty, nm = _decl_param(p, i)
                if not nm or nm == ty:
                    nm = f"a{i}"
                if "calldata" not in ty.split() and ty not in ("uint256", "bytes32", "uint8", "bool", "address"):
                    ty = ty + " memory"
                decls.append(f"{ty} {nm}")
                args.append(nm)
            ret_tys = []
            for r in fn["returns"]:
                rt = r.split()[0]
                ret_tys.append(rt)
            ret = f" returns ({', '.join(ret_tys)})" if ret_tys else ""
            call = f"{lib}.{fn['name']}({', '.join(args)})"
            body = f"return {call};" if ret_tys else f"{call};"
            lines.append(f"    function wrap_{lib}_{fn['name']}({', '.join(decls)}) external pure{ret} {{ {body} }}")
    lines.append("}")
    return "\n".join(lines) + "\n", wrapped


# ---------------------------------------------------------------- fragments
def _expr_src(e: dict) -> str | None:
    return e.get("code") if isinstance(e, dict) else None


class Unsupported(Exception):
    pass


def _resolve(env: dict, name: str, depth: int = 0) -> dict:
    """Follow let-chains x := y / x := convert(y) to a terminal expression."""
    if depth > 12:
        return {"id": name}
    e = env.get(name)
    if e is None:
        return {"id": name}
    if "id" in e:
        return _resolve(env, e["id"], depth + 1)
    if "call" in e and (e["call"].startswith("convert_") or e["call"].startswith("cleanup_")
                        or e["call"].startswith("zero_value_for_split_")) and len(e["args"]) == 1:
        inner = e["args"][0]
        return _resolve(env, inner["id"], depth + 1) if "id" in inner else inner
    return e


def _flatten_assigns(stmts: list[dict], env: dict) -> list[dict]:
    """Collect let/assign bindings in order so call args can be resolved later."""
    for s in stmts:
        if "let" in s and s.get("value") is not None:
            for n in s["let"]:
                env[n] = s["value"]
        elif "assign" in s:
            for n in s["assign"]:
                env[n] = s["value"]
    return stmts


_COND_RX = [
    ("version_ge", re.compile(r"version\s*>=\s*(\d+)")),
    ("version_le", re.compile(r"version\s*<=\s*(\d+)")),
    ("nonempty", re.compile(r"length\s*>\s*0")),
    ("len_ge", re.compile(r"length\s*>=\s*(\w+)")),
    ("len_eq", re.compile(r"length\s*==\s*(\w+)")),
]
_VERSION_IN_RX = re.compile(r"_?version\s*==\s*(\d+)")


def parse_cond(stmt: dict, consts: dict) -> dict | str:
    """Condition of an if/switch statement from its @src-quoted Solidity text.

    Returns a small dict: {"version_ge": n} | {"version_le": n} |
    {"version_in": [..]} | {"len_ge": k} | {"len_eq": k} | {"nonempty": True} |
    "unparsed:<text>"."""
    src = stmt.get("code") or ""
    vs = _VERSION_IN_RX.findall(src)
    if vs and ("||" in src or "if" in src):
        return {"version_in": sorted(int(v) for v in vs)}
    for key, rx in _COND_RX:
        m = rx.search(src)
        if m:
            if m.groups():
                tok = m.group(1)
                if tok.isdigit():
                    return {key: int(tok)}
                if tok in consts:  # BATCH_HEADER_LENGTH-style constant
                    return {key: consts[tok]}
                return f"unparsed:{src}"
            return {key: True}
    return f"unparsed:{src}" if src else {"other": "no-src"}


def _cond_of_expr(e: dict, env: dict) -> dict | str:
    """Fallback: read the condition out of the compiled boolean expression."""
    # iszero(lt(cleanup_uint(x), const)) -> version_ge const
    if "call" in e and e["call"] == "iszero" and e["args"]:
        inner = e["args"][0]
        if "call" in inner and inner["call"] == "lt":
            a, b = inner["args"]
            lit = b.get("lit") if "lit" in b else a.get("lit")
            if lit is not None:
                return {"version_ge": lit}
    if "call" in e and e["call"] == "eq":
        lits = [a["lit"] for a in e["args"] if "lit" in a]
        if lits:
            return {"version_in": lits}
    if "id" in e:
        return _cond_of_expr(_resolve(env, e["id"]), env)
    return "unparsed:expr"


def field_name(lib_fn: str) -> str:
    """storeBatchIndex -> batchIndex, getBatchIndex -> batchIndex."""
    base = re.sub(r"^(store|get|load)", "", lib_fn)
    return base[0].lower() + base[1:] if base else lib_fn


def _mem_write(stmt: dict) -> dict | None:
    """A bare mstore/mstore8 expression statement -> the call node."""
    e = stmt.get("expr")
    if isinstance(e, dict) and e.get("call") in ("mstore", "mstore8"):
        return e
    return None


def _value_shape(e: dict, p: str) -> dict:
    """Classify an mstore/mstore8 value expression."""
    if "call" in e and e["call"] == "shl" and len(e["args"]) == 2:
        s, v = e["args"]
        if "lit" in s:
            return {"shl": s["lit"], "value": v}
    if "call" in e and e["call"] == "shr" and len(e["args"]) == 2:
        s, v = e["args"]
        if "lit" in s:
            return {"shr": s["lit"], "value": v}
    return {"value": e}


def fragment(name: str, fn: dict, unit: Y.YulUnit, consts: dict) -> dict:
    """Classify one codec function into a straight-line fragment."""
    src = unit.src_file(fn) or "?"
    body = fn["body"]
    # find the memory statement and the statements that feed it
    mem_stmts = []
    guards = []
    copies = []
    hashes = []
    reverts = []
    reads = []
    for s in body:
        w = _mem_write(s)
        if w:
            mem_stmts.append((w, s))
            continue
        if "expr" in s and isinstance(s["expr"], dict) and s["expr"].get("call") == "calldatacopy":
            copies.append(s)
            continue
        for n, e in ([*(zip(s.get("let", []), [s.get("value")] * 8))] +
                     [*(zip(s.get("assign", []), [s.get("value")] * 8))]):
            if e is None:
                continue
            if "call" in e and e["call"] in ("shr", "mload"):
                reads.append((s, e))
            if "call" in e and e["call"] == "keccak256":
                hashes.append((s, e))
        if "expr" in s and isinstance(s["expr"], dict) and s["expr"].get("call", "").startswith("require_helper"):
            guards.append(s)
        if "expr" in s and isinstance(s["expr"], dict) and s["expr"].get("call") == "revert":
            reverts.append(s)
        if "if" in s or "switch" in s:
            # a require helper compiled inline: if iszero(cond) { revert }
            leaves = _leaf_calls(s)
            if any(c.startswith("revert") or c == "revert" for c in leaves):
                guards.append(s)
    flat_consts = consts.get("by_stem", {}).get(Path(src).stem, consts.get("by_name", {})) \
        if "by_stem" in consts else consts
    frag = {"fn": name, "file": src, "ast_id": fn.get("ast_id"), "params": fn["params"],
            "returns": fn["returns"], "yul": body}
    consts = flat_consts
    ptr = fn["params"][0] if fn["params"] else None
    if len(mem_stmts) == 1 and not (reads or copies or hashes or guards):
        call, s = mem_stmts[0]
        kind = call["call"]
        off = Y.as_add_offset(call["args"][0], ptr) if ptr else None
        if off is None:
            raise Unsupported(f"{name}: mstore target is not ptr+const: {call['args'][0]}")
        val = _value_shape(call["args"][1], ptr)
        frag.update({"kind": "store", "op": kind, "offset": off, "value": val, "src": s.get("code")})
        return frag
    if len(reads) == 1 and not (mem_stmts or copies or hashes or guards):
        s, e = reads[0]
        width, target = 32, e
        if "call" in e and e["call"] == "shr":
            s_amt, target = e["args"]
            width = (256 - s_amt["lit"]) // 8
        if "call" in target and target["call"] == "mload":
            off = Y.as_add_offset(target["args"][0], ptr) if ptr else None
            if off is None:
                raise Unsupported(f"{name}: mload source is not ptr+const")
            frag.update({"kind": "getter", "offset": off, "width": width, "src": s.get("code")})
            return frag
    if copies or guards:
        frag.update({"kind": "validate", "guards": [_guard_of(s, consts) for s in guards],
                     "copies": copies, "src": (copies or guards or [None])[0].get("code")})
        return frag
    if hashes:
        frag.update({"kind": "hash", "src": hashes[0][0].get("code")})
        return frag
    raise Unsupported(f"{name}: unrecognized fragment shape "
                      f"(writes={len(mem_stmts)} reads={len(reads)} copies={len(copies)} "
                      f"guards={len(guards)} hash={len(hashes)})")


def _leaf_calls(stmt: dict) -> list[str]:
    out = []
    def go(e):
        if isinstance(e, dict):
            if "call" in e:
                out.append(e["call"])
            for v in e.values():
                go(v)
        elif isinstance(e, list):
            for v in e:
                go(v)
    go(stmt)
    return out


def _guard_of(stmt: dict, consts: dict) -> dict:
    return {"src": stmt.get("code"), "cond": parse_cond(stmt, consts)}


# ---------------------------------------------------------------- consumer walk
def _walk(stmts: list[dict], env: dict, conds: list, visit):
    """Depth-first in-order walk tracking enclosing if/switch conditions.

    `visit(s, conds, prev_code)` also receives the code quote of the nearest
    preceding annotated statement: solc puts the @src naming the call on the
    `let` that computes its last argument, not on the call itself."""
    prev_code = None
    for s in stmts:
        if "if" in s:
            c = parse_cond(s, {}) if s.get("code") else _cond_of_expr(s["if"], env)
            _walk(s["body"], env, conds + [c], visit)
            prev_code = s.get("code") or prev_code
            continue
        if "switch" in s:
            c = parse_cond(s, {}) if s.get("code") else _cond_of_expr(s["switch"], env)
            for val, arm in s["cases"]:
                neg = (val == 0)  # case 0 = the NOT-taken side
                _walk(arm, env, conds + [{"not": c} if neg else c], visit)
            prev_code = s.get("code") or prev_code
            continue
        _flatten_assigns([s], env)
        visit(s, list(conds), s.get("code") or prev_code)
        prev_code = s.get("code") or prev_code


def _negate(cond):
    if isinstance(cond, dict):
        if "version_in" in cond:
            return {"version_not_in": cond["version_in"]}
        if "version_ge" in cond:
            return {"version_lt": cond["version_ge"]}
        if "version_le" in cond:
            return {"version_gt": cond["version_le"]}
    return {"not": cond}


def extract_consumer(unit: Y.YulUnit, consts: dict) -> dict:
    """Walk the Rollup consumer program: stores, guards, dispatch, lengths."""
    out = {"stores": [], "guards": [], "dispatch": [], "length_assigns": [],
           "alloc": None, "fmp_writes": [], "edges": [], "nonempty": None}
    env: dict = {}

    fn = unit.functions.get(COMMIT_FN)
    if fn is None:
        raise Unsupported(f"{COMMIT_FN} not found in optimized IR")

    def visit(s, conds, near_code=None):
        e = s.get("expr")
        val = s.get("value") if ("assign" in s or "let" in s) else None
        if isinstance(e, dict) and e.get("call", "").startswith("fun_store"):
            ptr = _resolve(env, e["args"][0]["id"]) if "id" in e["args"][0] else e["args"][0]
            arg = _resolve(env, e["args"][1]["id"]) if "id" in e["args"][1] else e["args"][1]
            out["stores"].append({"fn": e["call"], "ptr": ptr, "value": arg,
                                  "conds": conds, "code": s.get("code") or near_code})
        elif isinstance(e, dict) and e.get("call", "").startswith("require_helper"):
            out["guards"].append({"src": s.get("code"), "cond": parse_cond(s, consts), "conds": conds})
        elif isinstance(e, dict) and e.get("call") == "mstore" and e["args"][0] == {"lit": 64}:
            out["fmp_writes"].append({"stmt": s, "conds": conds})
        elif ("assign" in s and s["assign"] == ["var_headerLength"]) or \
                ("let" in s and s["let"] == ["var_headerLength"] and s.get("value")):
            v = s["value"]
            rv = _resolve(env, v["id"]) if isinstance(v, dict) and "id" in v else v
            out["length_assigns"].append({"value": rv, "conds": conds, "let": "let" in s})
        elif "assign" in s and s["assign"] == ["var_batchPtr"] and isinstance(s["value"], dict) \
                and s["value"].get("call") == "mload" and s["value"]["args"] == [{"lit": 64}]:
            out["alloc"] = {"stmt": s, "conds": conds}
        elif isinstance(val, dict) and val.get("call", "").startswith("fun_computeBatchHash"):
            out["edges"].append({"kind": "keccak256", "stmt": s, "conds": conds})

    _walk(fn["body"], env, [], visit)

    # version dispatch: leaves of fun_loadBatchHeader
    fn = unit.functions.get(DISPATCH_FN)
    if fn is None:
        raise Unsupported(f"{DISPATCH_FN} not found")

    def dvisit(s, conds, near_code=None):
        e = s.get("value") if ("let" in s or "assign" in s) else s.get("expr")
        calls = _leaf_calls(s)
        load = [c for c in calls if c.startswith("fun_loadAndValidate")]
        if load:
            out["dispatch"].append({"codec_fn": load[0], "conds": conds, "code": s.get("code")})
        elif "revert" in calls:
            out["dispatch"].append({"codec_fn": None, "conds": conds, "code": s.get("code"),
                                    "revert": True})
        elif isinstance(e, dict) and e.get("call", "").startswith("require_helper"):
            out["guards"].append({"src": s.get("code"), "cond": parse_cond(s, consts), "conds": conds})
    _walk(fn["body"], dict(env), [], dvisit)

    # empty check from _getBatchVersion: require(length > 0)
    fn = unit.functions.get(VERSION_FN)
    if fn is None:
        raise Unsupported(f"{VERSION_FN} not found")

    def vvisit(s, conds, near_code=None):
        calls = _leaf_calls(s)
        if any(c.startswith("require_helper") for c in calls):
            out["nonempty"] = {"src": s.get("code"), "cond": parse_cond(s, consts)}
    _walk(fn["body"], dict(env), [], vvisit)
    return out


# ---------------------------------------------------------------- constants
def _const_table(unit: Y.YulUnit) -> dict:
    """constant_X() -> {"by_name": {yul fn name: lit}, "by_stem": {file stem: {sol name: lit}}}.

    The same Solidity name can mean different constants in different libraries
    (BATCH_HEADER_LENGTH is 249 in V0 and 257 in V1), so sol names are scoped by
    the @src file of the defining function; unique yul names are flat."""
    by_name, by_stem = {}, {}
    for name, fn in unit.functions.items():
        if not name.startswith("constant_"):
            continue
        for s in fn["body"]:
            v = s.get("value") if "value" in s else None
            if isinstance(v, dict) and "lit" in v:
                sol_name = re.sub(r"_\d+$", "", name[len("constant_"):])
                by_name[name] = v["lit"]
                src = unit.src_file(fn)
                stem = Path(src).stem if src else "?"
                by_stem.setdefault(stem, {})[sol_name] = v["lit"]
    return {"by_name": by_name, "by_stem": by_stem}


# ---------------------------------------------------------------- composition
def _when_of(conds: list) -> dict | None:
    """Fold enclosing conditions into a facts `when` clause, or None.

    Only a *positive* `version_ge` (or version_in/version_le expressed as ge) can
    appear: anything else means the write is gated in a way the facts format
    cannot express."""
    when = None
    for c in conds:
        if not isinstance(c, dict):
            return "unsupported"
        if "version_ge" in c:
            when = {"version_ge": max(when["version_ge"], c["version_ge"]) if when else c["version_ge"]}
        elif "version_in" in c:
            ge = min(c["version_in"])
            when = {"version_ge": max(when["version_ge"], ge) if when else ge}
        elif "not" in c or "version_lt" in c or "version_gt" in c or "version_not_in" in c:
            return "unsupported"
        elif "version_le" in c:
            continue  # domain-wide guard, not a per-op gate
        else:
            return "unsupported"
    return when


def _const_arg(value: dict) -> int | None:
    return value["lit"] if isinstance(value, dict) and "lit" in value else None


def compose(frags: dict, consumer: dict, consts: dict, use_src: dict) -> dict:
    """Codec fragments + consumer program -> the extracted document."""
    debt = []

    # --- domain guard (version <= N) -----------------------------------------
    version_le = None
    for g in consumer["guards"]:
        c = g.get("cond")
        if isinstance(c, dict) and "version_le" in c:
            version_le = c["version_le"]
    if version_le is None:
        debt.append({"element": f"{CONSUMER}:domain", "kind": "guard",
                     "reason": "no `version <= N` require found in commit path"})
        version_le = 0
    versions = list(range(version_le + 1))

    # --- header length by version --------------------------------------------
    base = None
    assigns = []
    for a in consumer["length_assigns"]:
        v = a["value"]
        const_name = v.get("call", "") if isinstance(v, dict) else ""
        lit = consts.get(const_name) or consts.get(const_name.split("(")[0])
        conds = a["conds"]
        if a.get("let") or not conds:
            base = lit
        else:
            assigns.append((conds, lit))
    if base is None:
        debt.append({"element": f"{CONSUMER}:_headerLength", "kind": "expression",
                     "reason": "no unconditional _headerLength := constant found"})

    def length_at(v: int) -> int | None:
        val = base
        for conds, lit in assigns:
            if _conds_hold(conds, v):
                val = lit
        return val

    length_by_version = {str(v): length_at(v) for v in versions}
    if any(x is None for x in length_by_version.values()):
        debt.append({"element": f"{CONSUMER}:_headerLength", "kind": "expression",
                     "reason": "could not resolve header length for some version"})

    # --- encoder ops ----------------------------------------------------------
    ops = []
    for site in consumer["stores"]:
        frag = frag_for(frags, consumer["runit"], site["fn"])
        if frag is None:
            debt.append({"element": f"{CONSUMER}:{site['fn']}", "kind": "call",
                         "reason": "callee not among extracted codec fragments"})
            continue
        if frag["kind"] != "store":
            debt.append({"element": f"{frag['file']}:{frag['fn']}", "kind": frag["kind"],
                         "reason": "called from the store sequence but not a store fragment"})
            continue
        when = _when_of(site["conds"])
        op = {"op": frag["op"], "offset": frag["offset"],
              "code": site.get("code") or frag.get("src")}
        cval = _const_arg(site["value"])
        if cval is not None:
            width = 32 if frag["op"] == "mstore" else 1
            bs = cval.to_bytes(width, "big")
            op["src"] = [{"const": b} if b else {"zeros": 1} for b in bs]
        else:
            name = field_name(re.sub(r"_\d+$", "", re.sub(r"^fun_", "", frag["fn"])))
            name = name[0].lower() + name[1:]
            v = frag["value"]
            if "shl" in v:
                w = (256 - v["shl"]) // 8
                op["src"] = [{"field": name}, {"zeros": v["shl"] // 8}] if w else [{"field": name}]
                op["field_width"] = w
            else:
                op["src"] = [{"field": name}]
                op["field_width"] = 32 if frag["op"] == "mstore" else 1
        if when == "unsupported":
            debt.append({"element": f"{frag['file']}:{frag['fn']}",
                         "kind": "condition",
                         "reason": f"enclosing condition {site['conds']} is not a version_ge gate"})
        elif when:
            op["when"] = when
        ops.append(op)

    enc = {"kind": "encoder", "from": "Header", "to": "Bytes",
           "lang": "solidity-evm-memory", "memory_init": "dirty",
           "domain": {"version_le": version_le},
           "length_by_version": length_by_version, "ops": ops}

    # --- Header fields (ordered by first byte offset) --------------------------
    seen = {}
    for op in ops:
        for item in op["src"]:
            if "field" in item:
                seen.setdefault(item["field"], (op["offset"], op.get("field_width", 32)))
    getters_all = [f for f in frags.values() if f["kind"] == "getter"]
    for g in getters_all:
        gname = field_name(re.sub(r"_\d+$", "", re.sub(r"^fun_", "", g["fn"])))
        seen.setdefault(gname, (g["offset"], g["width"]))
    fields = [{"name": n, "width": w} for n, (_, w) in sorted(seen.items(), key=lambda kv: kv[1][0])]

    # --- ok_sol rules -----------------------------------------------------------
    rules = []
    if consumer.get("nonempty"):
        rules.append({"if": "empty", "then": False,
                      "code": consumer["nonempty"].get("src") or "length > 0 required"})
    for d in consumer["dispatch"]:
        vset = _version_set(d["conds"], version_le)
        if vset is None:
            debt.append({"element": f"{CONSUMER}:{DISPATCH_FN}", "kind": "dispatch",
                         "reason": f"dispatch conditions {d['conds']} not a version set"})
            continue
        if d["codec_fn"] is None:
            rules.append({"if": "otherwise" if vset == "rest" else {"version_in": sorted(vset)},
                          "then": False, "code": d.get("code") or "revert"})
            continue
        g = _load_guard(frag_for(frags, consumer["runit"], d["codec_fn"]))
        # keep the codec's own identity on the rule for provenance
        if g is None:
            debt.append({"element": f"codec:{d['codec_fn']}", "kind": "validate",
                         "reason": "loadAndValidate guard not len_ge/len_eq"})
            continue
        rules.append({"if": {"version_in": sorted(vset)}, "then": g,
                      "code": f"{d['codec_fn']}: {g}"})
    rules.sort(key=lambda r: (r["if"] != "empty", r["if"] == "otherwise",
                              r["if"].get("version_in", [0])[0] if isinstance(r["if"], dict) else 0))
    ok = {"kind": "predicate", "from": "Bytes", "to": "Bool", "lang": "solidity",
          "meaning": "true iff _loadBatchHeader(b) does not revert", "rules": rules}

    # --- dec_sol getters --------------------------------------------------------
    getters = []
    for g in sorted(getters_all, key=lambda x: x["offset"]):
        name = field_name(re.sub(r"_\d+$", "", re.sub(r"^fun_", "", g["fn"])))
        name = name[0].lower() + name[1:]
        when = _getter_when(g, length_by_version)
        ge = {"name": name, "offset": g["offset"], "width": g["width"],
              "code": g.get("src") or g["fn"], "lib": g["file"]}
        if when:
            ge["when"] = when
        getters.append(ge)
    dec = {"kind": "decoder", "from": "Bytes", "to": "Maybe<Fields>", "lang": "solidity",
           "meaning": "None unless ok_sol(b); else the codec getters in offset order",
           "guard": "ok_sol", "getters": getters}
    view = {"kind": "projection", "from": "Header", "to": "Fields",
            "meaning": "header fields in the extracted decoder's getter order",
            "order": [g["name"] for g in getters],
            "when": {g["name"]: g["when"] for g in getters if g.get("when")}}

    # --- fragments for the Bend translator -------------------------------------
    program = _encoder_program(consumer, frags, ops)

    # --- coverage debt for constructs outside the byte-layout model ------------
    for e in consumer["edges"]:
        debt.append({"element": f"{CONSUMER}:{e['kind']}(_batchPtr, _headerLength)",
                     "kind": "edge",
                     "reason": "hash primitive is outside the byte-layout model; recorded as an edge fact"})
    for f in consumer["fmp_writes"]:
        debt.append({"element": f"{CONSUMER}:mstore(0x40, add(_batchPtr, _headerLength))",
                     "kind": "infrastructure",
                     "reason": "free-memory-pointer bump writes outside the tracked header buffer"})
    for g in consumer["guards"]:
        if not (isinstance(g.get("cond"), dict) and "version_le" in g["cond"]):
            debt.append({"element": f"{CONSUMER}:{(g.get('src') or '?')[:80]}",
                         "kind": "precondition",
                         "reason": "input-validity constraint on Header fields, not a byte-layout op"})
    return {"enc_sol": enc, "ok_sol": ok, "dec_sol": dec, "view": view,
            "fields": fields}, debt, program


def _conds_hold(conds: list, v: int) -> bool:
    for c in conds:
        if not isinstance(c, dict):
            return False
        if "version_ge" in c and not v >= c["version_ge"]:
            return False
        if "version_le" in c and not v <= c["version_le"]:
            return False
        if "version_in" in c and v not in c["version_in"]:
            return False
        if "version_lt" in c and not v < c["version_lt"]:
            return False
        if "version_gt" in c and not v > c["version_gt"]:
            return False
        if "version_not_in" in c and v in c["version_not_in"]:
            return False
        if "not" in c:
            return False
    return True


def _version_set(conds: list, version_le: int):
    """Version set a dispatch leaf is reachable at, or 'rest' for the else leaf."""
    pos, neg = set(), set()
    for c in conds:
        if not isinstance(c, dict):
            return None
        if "version_in" in c:
            pos |= set(c["version_in"])
        elif "version_ge" in c:
            pos |= {v for v in range(version_le + 1) if v >= c["version_ge"]}
        elif "version_le" in c:
            pos |= {v for v in range(version_le + 1) if v <= c["version_le"]}
        elif "not" in c:
            inner = c["not"]
            if isinstance(inner, dict) and "version_in" in inner:
                neg |= set(inner["version_in"])
            elif isinstance(inner, dict) and "version_ge" in inner:
                neg |= {v for v in range(10) if v >= inner["version_ge"]}
            else:
                return None
        else:
            return None
    allv = set(range(version_le + 1)) | {version_le + 1}  # include an "other" version
    in_set = (allv & pos) if pos else set()
    out = in_set - neg
    return out if out else "rest"


def _load_guard(frag: dict | None) -> dict | None:
    if frag is None:
        return None
    for g in frag.get("guards", []):
        c = g.get("cond")
        if isinstance(c, dict) and ("len_ge" in c or "len_eq" in c):
            return c
    return None


def _getter_when(g: dict, length_by_version: dict) -> dict | None:
    """A getter is only defined on versions whose length covers its span."""
    vs = [int(v) for v, L in length_by_version.items() if isinstance(L, int) and g["offset"] + g["width"] <= L]
    if not vs:
        return None
    missing = [v for v in map(int, length_by_version) if v not in vs]
    if missing and vs == sorted(vs) and min(vs) > max(missing, default=-1):
        return {"version_ge": min(vs)}
    return None


def _encoder_program(consumer: dict, frags: dict, ops: list) -> list:
    """Straight-line fragment program for the translator (one IR op per site)."""
    prog = [{"op": "alloc", "var": "batchPtr", "init": "fmp"}]
    for f in consumer["fmp_writes"]:
        prog.append({"op": "fmp_write", "stmt": "mstore(0x40, ..)"})
    prog.append({"op": "comment", "text": "encoder: composed store sequence"})
    for op in ops:
        prog.append({"op": op["op"], "offset": op["offset"], "src": op["src"],
                     "when": op.get("when"), "code": op.get("code")})
    for e in consumer["edges"]:
        prog.append({"op": "edge", "kind": e["kind"]})
    return prog


# ---------------------------------------------------------------- codec fun lookup
def codec_frags(dunit: Y.YulUnit, consts: dict) -> tuple[dict, list]:
    """Every compiled fun_* defined inside a codec library file -> its fragment.

    Attribution is by the function's own @src file, so same-named functions in
    different libraries (loadAndValidate) never collide."""
    libs = {Path(p).stem for p in CODEC_LIBS}
    frags, debt = {}, []
    for name in sorted(dunit.functions):
        fn = dunit.functions[name]
        src = dunit.src_file(fn)
        lib = Path(src).stem if src else None
        if lib not in libs or not name.startswith("fun_"):
            continue
        try:
            frags[name] = fragment(name, fn, dunit, consts)
            frags[name]["lib"] = lib
        except Unsupported as e:
            debt.append({"element": f"{src}:{name}", "kind": "fragment", "reason": str(e)})
    return frags, debt


def frag_for(frags: dict, runit: Y.YulUnit, call_name: str) -> dict | None:
    """The driver-side fragment standing for a callee name in the consumer IR."""
    base = re.sub(r"_\d+$", "", call_name[len("fun_"):]) if call_name.startswith("fun_") else call_name
    lib = None
    if call_name in runit.functions:
        src = runit.src_file(runit.functions[call_name])
        lib = Path(src).stem if src else None
    cands = [f for f in frags.values()
             if re.sub(r"_\d+$", "", f["fn"][len("fun_"):]) == base and (lib is None or f["lib"] == lib)]
    return cands[0] if cands else None


def extract(morph: Path = MORPH, solc: Path = SOLC) -> tuple[dict, list, dict]:
    """Run the whole pipeline. Returns (document, debt_items, aux)."""
    morph = Path(morph)
    driver_src, wrapped = gen_driver(morph)
    work = Path(tempfile.mkdtemp(prefix="holon-s2-"))
    (work / "contracts" / "libraries" / "codec").mkdir(parents=True)
    for lib_rel in CODEC_LIBS:
        dst = work / lib_rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text((morph / CONTRACTS / lib_rel).read_text())
    (work / "HolonExtractDriver.sol").write_text(driver_src)

    drv_ir = compile_ir(solc, ["HolonExtractDriver.sol"], work)
    rollup_ir = compile_ir(
        solc, [str(CONSUMER)],
        morph / CONTRACTS,
        include=["node_modules"],
        remaps=["@openzeppelin/contracts-upgradeable/=node_modules/@openzeppelin/contracts-upgradeable/",
                "@openzeppelin/contracts/=node_modules/@openzeppelin/contracts/"])

    dunit = Y.parse_yul(drv_ir)
    runit = Y.parse_yul(rollup_ir)
    dconsts = _const_table(dunit)
    rconsts = _const_table(runit)
    consts = {"by_name": {**dconsts["by_name"], **rconsts["by_name"]},
              "by_stem": {**dconsts["by_stem"], **rconsts["by_stem"]}}

    frags, debt = codec_frags(dunit, consts)

    consumer = extract_consumer(runit, rconsts["by_name"])
    consumer["runit"] = runit
    funcs, debt2, program = compose(frags, consumer, rconsts["by_name"], runit.use_src)
    debt += debt2

    commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=morph, capture_output=True, text=True).stdout.strip()
    doc = {
        "facts_version": "holon-facts/0.1",
        "target": {"repo": "morph-l2/morph", "commit": commit,
                   "scope": "BatchHeaderCodecV0/V1 stores, getters, loadAndValidate; "
                            "Rollup._commitBatchWithBatchData header build, _loadBatchHeader dispatch"},
        "extraction": {"method": "solc --ir-optimized (optimized Yul IR), automated",
                       "tool": {"solc": solc_version(solc), "evm_version": EVM},
                       "driver": {"file": "HolonExtractDriver.sol",
                                  "sha256": hashlib.sha256(driver_src.encode()).hexdigest(),
                                  "purpose": "wraps internal library fns so they survive dead-code elimination"},
                       "ir_sha256": {"driver": hashlib.sha256(drv_ir.encode()).hexdigest(),
                                     "rollup": hashlib.sha256(rollup_ir.encode()).hexdigest()}},
        "types": {"Byte": {"kind": "byte"}, "Bytes": {"kind": "bytes"}, "Bool": {"kind": "bool"},
                  "Fields": {"kind": "list_of_bytes", "doc": "decoded header fields in getter order"},
                  "Header": {"kind": "record", "fields": funcs["fields"]}},
        "functions": {"enc_sol": funcs["enc_sol"], "ok_sol": funcs["ok_sol"],
                      "dec_sol": funcs["dec_sol"], "view": funcs["view"]},
    }
    aux = {"program": program, "frags": {k: {kk: vv for kk, vv in v.items() if kk != "yul"}
                                         for k, v in frags.items()},
           "frag_yul": {k: v["yul"] for k, v in frags.items()},
           "driver_src": driver_src, "consumer": consumer, "consts": consts}
    return doc, debt, aux


def _fmt_json(doc: dict) -> str:
    return json.dumps(doc, indent=2, sort_keys=False, ensure_ascii=True) + "\n"


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog="holon.frontends.solidity.layout_extract",
                                 description="S2: extract BatchHeaderCodec layouts from solc --ir-optimized")
    ap.add_argument("--morph", default=str(MORPH))
    ap.add_argument("--solc", default=str(SOLC))
    ap.add_argument("--out", default=str(ROOT / "spec" / "M2" / "extracted" / "header_layouts.json"))
    ap.add_argument("--debt", default=str(ROOT / "spec" / "M2" / "coverage" / "solidity_layout.json"))
    ap.add_argument("--bend", default=str(ROOT / "gen" / "M2" / "sol_layout" / "morph_header.bend"))
    ap.add_argument("--driver", default=str(ROOT / "spec" / "M2" / "extracted" / "HolonExtractDriver.sol"))
    ap.add_argument("--check", action="store_true", help="re-extract and compare, do not write")
    a = ap.parse_args(argv)

    from . import layout_bend
    doc, debt, aux = extract(Path(a.morph), Path(a.solc))
    text = _fmt_json(doc)
    debt_doc = {"frontend": "solidity/layout", "target_commit": doc["target"]["commit"],
                    "items": sorted(debt, key=lambda x: x["element"])}
    debt_text = json.dumps(debt_doc, indent=2, ensure_ascii=True) + "\n"
    bend_text = layout_bend.generate(doc, aux)

    if a.check:
        cur = Path(a.out).read_text() if Path(a.out).exists() else ""
        ok = cur == text
        print("byte-identical:", ok)
        return 0 if ok else 1
    for path, content in ((a.out, text), (a.debt, debt_text), (a.bend, bend_text),
                          (a.driver, aux["driver_src"])):
        p = Path(path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
        print("wrote", p)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
