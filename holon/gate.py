    def g5(self) -> None:
        bad, n, timing = [], 0, {}
        budget = float(self.cfg["bend"].get("budget_s_per_file", 120))
        for lid, rec, d in self.checked_dirs():
            n += 1
            proof = d / "PROOF.bend"
            if not proof.exists():
                bad.append(f"{lid}: PROOF.bend missing")
                continue
            r = bend.check(proof, self.cfg)
            self.check_outputs.append(r.out)
            timing[lid] = r.seconds
            if not r.ok:
                bad.append(f"{lid}: exit {r.code}, {r.first_line}")
            imp_bad = self.import_problem(rec, proof)   # the checked proof imports its law (F-M2-07)
            if imp_bad:
                bad.append(f"{lid}: {imp_bad}")
            if r.seconds > budget:
                bad.append(f"{lid}: {r.seconds} s exceeds the budget of {budget:g} s per file")
        ne = 0
        for lid, e, w, proof, laws_f in self.entry_proofs():   # SORT-site per-entry counter-laws (I15)
            ne += 1
            if proof is None or not proof.exists():
                bad.append(f"{lid} entry {e}: PROOF.bend missing")
                continue
            r = bend.check(proof, self.cfg)
            self.check_outputs.append(r.out)
            timing[f"{lid}#{e}"] = r.seconds
            if not r.ok:
                bad.append(f"{lid} entry {e}: exit {r.code}, {r.first_line}")
            from .mpipeline import law_import_problem
            imp_bad = law_import_problem(proof, laws_f) if laws_f else "the entry names no LAWS.bend"
            if imp_bad:
                bad.append(f"{lid} entry {e}: {imp_bad}")
            if r.seconds > budget:
                bad.append(f"{lid} entry {e}: {r.seconds} s exceeds the budget of {budget:g} s per file")
        self.timings = {"G5": dict(sorted(timing.items()))}
        slowest = max(timing.values(), default=0)
        self.checks["G5"] = _res(not bad and n > 0, f"{n} proofs re-checked from scratch"
                                 + (f", and {ne} per-entry counter-laws of SORT-site laws" if ne else "")
                                 + f", slowest {slowest} s (budget {budget:g} s per file)" if not bad else "; ".join(bad))

