def _tree(d: Path) -> dict[str, bytes]:
    return {f.relative_to(d).as_posix(): f.read_bytes() for f in sorted(Path(d).rglob("*")) if f.is_file()} \
        if Path(d).is_dir() else {}


def regenerate_m2_outputs(m: str, root: Path, tmp: Path) -> tuple[list[str], str]:
    """Regenerate gen/<m>/diagram (holon diagram), gen/<m>/sorts (holon sorts) and gen/<m>/oracles with
    results/<m>/hypotheses.json (holon oracle check) into tmp from the tree under root, and compare each with the
    committed files byte for byte. A generator whose output is not committed and that has no inputs for m (e.g. a
    test milestone without fact documents) is skipped and named in the note. The extraction sidecars
    spec/<m>/lib/extract_*.json are re-extracted by holon.frontends.regenerate (I17), which names each output it
    compares. Returns (differences, note)."""
    import contextlib
    import io
    root, tmp = Path(root).resolve(), Path(tmp)
    gen = root / "gen" / m
    diffs, done, skipped = [], [], []

    def compare(name: str, got: dict[str, bytes], want: dict[str, bytes]) -> None:
        d = sorted(k for k in set(got) | set(want) if got.get(k) != want.get(k))
        diffs.extend(f"gen/{m}/{name}/{k}" for k in d)
        done.append(f"{name} ({len(want)} files)")

    quiet = contextlib.redirect_stdout(io.StringIO())
    # diagram
    from .diagram import run as diagram_run
    with quiet, contextlib.redirect_stderr(io.StringIO()) as err:
        rc = diagram_run(m, str(tmp / "diagram"), str(root))
    if rc == 0:
        compare("diagram", _tree(tmp / "diagram"), _tree(gen / "diagram"))
    elif (gen / "diagram").exists():
        diffs.append(f"gen/{m}/diagram: holon diagram failed: {err.getvalue().strip()[:300]}")
    else:
        skipped.append("diagram")
    # sorts
    from .sorts import run as sorts_run
    with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()) as err:
        rc = sorts_run(m, str(root), str(tmp / "sorts"), None)
    if rc == 0:   # what holon sorts writes; gen/<m>/sorts/obstructions.json is holon derive's (I15), compared with it
        from .sorts.assign import DOCUMENTS
        mine = {f"{n}.json" for n in DOCUMENTS}
        compare("sorts", _tree(tmp / "sorts"), {k: v for k, v in _tree(gen / "sorts").items() if k in mine})
    elif (gen / "sorts").exists():
        diffs.append(f"gen/{m}/sorts: holon sorts failed: {err.getvalue().strip()[:300]}")
    else:
        skipped.append("sorts")
    # oracle check: the instance laws and results/<m>/hypotheses.json (I3's zero-blob entry kept as written)
    sidecar = root / "spec" / m / "lib" / "oracles.json"
    if sidecar.exists():
        from . import oracle_check
        out = tmp / "oracles"
        try:
            res = oracle_check.check(sidecar, out, root)
        except Exception as e:  # noqa: BLE001
            diffs.append(f"gen/{m}/oracles: holon oracle check failed: {type(e).__name__}: {e}")
        else:
            shown = str(out.resolve())

            def norm(x):
                if isinstance(x, dict):
                    return {k: norm(v) for k, v in x.items()}
                if isinstance(x, list):
                    return [norm(v) for v in x]
                return f"gen/{m}/oracles" + x[len(shown):] if isinstance(x, str) and x.startswith(shown) else x
            res = norm(res)
            compare("oracles", _tree(out), _tree(gen / "oracles"))
            hp = root / "results" / m / "hypotheses.json"
            old = json.loads(hp.read_text()) if hp.exists() else {}
            if oracle_check.ZERO_BLOB in old:
                res[oracle_check.ZERO_BLOB] = old[oracle_check.ZERO_BLOB]
            text = json.dumps(dict(sorted(res.items())), indent=2, sort_keys=True) + "\n"
            if not hp.exists() or hp.read_text() != text:
                diffs.append(f"results/{m}/hypotheses.json")
    elif (gen / "oracles").exists():
        diffs.append(f"gen/{m}/oracles exists without a sidecar spec/{m}/lib/oracles.json to regenerate it")
    else:
        skipped.append("oracles")
    # the rules registry (I15): laws/<m>/ (the laws, DERIVATION.json, REGISTRY.json) and gen/<m>/sorts/obstructions.json,
    # regenerated by holon derive's own computation (holon.rules.compute) from the facts and the frozen assignment
    if (root / "laws" / m / "DERIVATION.json").exists():
        from . import rules
        try:
            res = rules.compute(m, root)
        except Exception as e:  # noqa: BLE001
            diffs.append(f"laws/{m}: holon derive failed: {type(e).__name__}: {e}")
        else:
            want = {f"{lid}.json": rules.dumps(law).encode() for lid, law in res["laws"].items()}
            want["DERIVATION.json"] = res["derivation_text"].encode()
            want["REGISTRY.json"] = rules.dumps(res["registry"]).encode()
            got = {f.name: f.read_bytes() for f in sorted((root / "laws" / m).iterdir())
                   if f.is_file() and (f.name in ("DERIVATION.json", "REGISTRY.json") or f.match(ir.LAW_GLOB))}
            d = sorted(k for k in set(got) | set(want) if got.get(k) != want.get(k))
            diffs.extend(f"laws/{m}/{k}" for k in d)
            ob = root / "gen" / m / "sorts" / "obstructions.json"
            if not ob.exists() or ob.read_bytes() != rules.dumps(res["obstructions"]).encode():
                diffs.append(f"gen/{m}/sorts/obstructions.json")
            done.append(f"derive (laws/{m}: {len(want)} files, gen/{m}/sorts/obstructions.json)")
    # extracted facts (I17): every extraction sidecar spec/<m>/lib/extract_*.json, extracted again by its frontend and
    # compared byte for byte with its committed output (holon.frontends.regenerate)
    from . import frontends
    if frontends.sidecars(m, root):
        fdiffs, fnote = frontends.regenerate(m, root, tmp / "extract")
        diffs.extend(fdiffs)
        done.append(fnote)
    # the Go documents (I18's sidecar spec/<m>/lib/go_frontend.json): covered by G1 from the first iteration that reads
    # them as inputs (I17 contract, lead decision at the I17 prereg), which is I19's linker (holon.frontends.link)
    go_cfg = root / "spec" / m / "lib" / "go_frontend.json"
    if go_cfg.exists() and (root / "spec" / m / "lib" / "link.json").exists():
        try:
            from .frontends import go as gofe
            docs = gofe.extract(go_cfg, None, root)
        except Exception as e:  # noqa: BLE001
            diffs.append(f"spec/{m}/facts/*.go.extracted.json: holon extract go failed: {type(e).__name__}: {e}")
        else:
            for stem in sorted(docs):
                rel = f"spec/{m}/facts/{stem}.go.extracted.json"
                p = root / rel
                if not p.exists() or p.read_text(encoding="utf-8") != gofe.render(docs[stem]):
                    diffs.append(rel)
            done.append(f"go documents ({len(docs)}: holon extract go)")
    # cross-language links (I19): gen/<m>/link.json, regenerated by holon.frontends.link from the extracted documents
    if (root / "spec" / m / "lib" / "link.json").exists():
        from .frontends import link
        try:
            got = link.render(link.compute(m, root))
        except Exception as e:  # noqa: BLE001
            diffs.append(f"gen/{m}/link.json: holon link failed: {type(e).__name__}: {e}")
        else:
            lp = link.report_path(m, root)
            if not lp.exists() or lp.read_bytes() != got:
                diffs.append(f"gen/{m}/link.json")
            done.append(f"gen/{m}/link.json (holon link)")
    elif (gen / "link.json").exists():
        diffs.append(f"gen/{m}/link.json exists without a sidecar spec/{m}/lib/link.json to regenerate it")
    # the extracted model (I20): gen/<m>/extracted/{model.bend, layout.json, window_check.json} (holon model, for every
    # window declaration of the milestone), the differential (holon differential: gen/<m>/abstraction_diff.json,
    # gen/<m>/extracted/m1_view.json, results/<m>/differential.json, results/<m>/extracted_m1/summary.json) and the
    # step refinement record results/<m>/refinement/extracted.json (holon fragments, with a scratch copy of the
    # disagreements file: a run that would file a new disagreement differs)
    ediffs, enotes = regenerate_extracted(m, root, tmp / "extracted")
    diffs.extend(ediffs)
    done.extend(enotes)
    # the optional hevm equivalence (I20): results/<m>/hevm.json, re-run with the pinned hevm and solver when they are
    # installed as pinned (otherwise the note says why it was not regenerated)
    hdiffs, hnotes = regenerate_hevm(m, root, tmp / "hevm")
    diffs.extend(hdiffs)
    done.extend(hnotes)
    note =(f"M2 outputs regenerated byte-identical: {', '.join(done)}" if done else "no M2 outputs to regenerate") + \
        (f"; not applicable (no inputs and nothing committed): {', '.join(skipped)}" if skipped else "")
    return diffs, note


def regenerate_extracted(m: str, root: Path, tmp: Path) -> tuple[list[str], list[str]]:
    """G1 for I20's outputs (regenerate_m2_outputs): (differences, notes)."""
    import contextlib
    import io
    from . import window as W
    root, tmp = Path(root).resolve(), Path(tmp)
    diffs, notes = [], []
    decls = [(p, d) for p, d in W.declarations(root) if p.relative_to(root).parts[1] == m]
    gen = root / "gen" / m / "extracted"
    if not decls:
        if gen.exists():
            diffs.append(f"gen/{m}/extracted exists without a window declaration spec/{m}/lib/window_*.json")
        return diffs, notes
    from . import machine
    for _p, d in decls:
        out = tmp / "model"
        try:
            with contextlib.redirect_stdout(io.StringIO()):
                rc = machine.write_model(d["facts"], out, root, log=lambda *a: None)
        except Exception as e:  # noqa: BLE001
            diffs.append(f"gen/{m}/extracted: holon model failed: {type(e).__name__}: {e}")
            continue
        if rc != 0:
            diffs.append(f"gen/{m}/extracted/model.bend: Bend does not check the regenerated model")
        for f in ("model.bend", "layout.json", "window_check.json"):
            a, b = gen / f, out / f
            if a.exists() != b.exists() or (a.exists() and a.read_bytes() != b.read_bytes()):
                diffs.append(f"gen/{m}/extracted/{f}")
        notes.append(f"gen/{m}/extracted (holon model {d['facts']})")
    from . import differential
    dout = tmp / "differential"
    try:
        with contextlib.redirect_stdout(io.StringIO()), contextlib.redirect_stderr(io.StringIO()):
            differential.run(m, root, log=lambda *a: None, out=dout)
    except Exception as e:  # noqa: BLE001
        diffs.append(f"results/{m}/differential.json: holon differential failed: {type(e).__name__}: {e}")
    else:
        for rel in (f"gen/{m}/abstraction_diff.json", f"gen/{m}/extracted/m1_view.json",
                    f"results/{m}/differential.json", f"results/{m}/extracted_m1/summary.json"):
            a, b = root / rel, dout / rel
            if a.exists() != b.exists() or (a.exists() and a.read_bytes() != b.read_bytes()):
                diffs.append(rel)
        notes.append("the differential (holon differential)")
    rec = root / "results" / m / "refinement" / "extracted.json"
    if rec.exists():
        from .replay_fragments import RECORD_KIND
        if json.loads(rec.read_text()).get("kind") == RECORD_KIND:
            fdir = tmp / "fragments"
            fdir.mkdir(parents=True, exist_ok=True)
            dis = root / "spec" / m / "disagreements.json"
            shutil.copy(dis, fdir / "disagreements.json")
            env = dict(os.environ)
            env["PYTHONPATH"] = str(root) + os.pathsep + env.get("PYTHONPATH", "")
            env["HOLON_BUILD_DIR"] = str(fdir / "build")
            p = subprocess.run([sys.executable, "-m", "holon", "fragments", "--root", str(root), "--out",
                                str(fdir / "extracted.json"), "--details", str(fdir / "details.json"), "--work",
                                str(fdir / "work"), "--disagreements", str(fdir / "disagreements.json"), "--jobs", "2"],
                               cwd=root, env=env, capture_output=True, text=True, timeout=3600)
            got = fdir / "extracted.json"
            if p.returncode not in (0, 1) or not got.exists():
                diffs.append(f"results/{m}/refinement/extracted.json: holon fragments failed: "
                             f"{(p.stdout + p.stderr)[-300:]}")
            elif got.read_bytes() != rec.read_bytes():
                diffs.append(f"results/{m}/refinement/extracted.json")
            elif (fdir / "disagreements.json").read_bytes() != dis.read_bytes():
                diffs.append(f"spec/{m}/disagreements.json (the regenerated run filed new disagreements)")
            for side in ("width_values.json", "window_states.json"):
                a, b = rec.parent / "extracted" / side, fdir / "extracted" / side
                if a.exists() != b.exists() or (a.exists() and a.read_bytes() != b.read_bytes()):
                    diffs.append(f"results/{m}/refinement/extracted/{side}")
            notes.append(f"results/{m}/refinement/extracted.json (holon fragments)")
    return diffs, notes


def regenerate_hevm(m: str, root: Path, tmp: Path) -> tuple[list[str], list[str]]:
    """G1 for results/<m>/hevm.json (holon hevm with the binding replay/<m>/hevm_store.json): (differences, notes). The
    record is regenerated and compared byte for byte when the pinned hevm and its solver are installed as pinned
    (config/holon.json "hevm"); otherwise the note says why it was not regenerated."""
    from . import hevm_equiv as H
    root, tmp = Path(root).resolve(), Path(tmp)
    rec, binding = root / "results" / m / "hevm.json", root / "replay" / m / "hevm_store.json"
    if not rec.exists():
        return [], []
    if not binding.exists():
        return [f"results/{m}/hevm.json exists without its binding replay/{m}/hevm_store.json"], []
    try:
        pin = H.pins(root)
    except H.HevmError as e:
        return [f"results/{m}/hevm.json: {e}"], []
    hevm, why_h = H.find_tool(None, "HOLON_HEVM", pin)
    solver, why_s = H.find_tool(None, "HOLON_HEVM_SOLVER", pin["solver"])
    if hevm is None or solver is None:
        return [], [f"results/{m}/hevm.json not regenerated (the pinned hevm or solver is not installed: "
                    f"{why_h or why_s})"]
    tmp.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["PYTHONPATH"] = str(root) + os.pathsep + env.get("PYTHONPATH", "")
    got = tmp / "hevm.json"
    p = subprocess.run([sys.executable, "-m", "holon", "hevm", "--binding", binding.relative_to(root).as_posix(),
                        "--out", str(got), "--work", str(tmp / "work")], cwd=root, env=env, capture_output=True,
                       text=True, timeout=3600)
    if p.returncode != 0 or not got.exists():
        return [f"results/{m}/hevm.json: holon hevm failed: {(p.stdout + p.stderr)[-300:]}"], []
    if got.read_bytes() != rec.read_bytes():
        return [f"results/{m}/hevm.json"], []
    return [], [f"results/{m}/hevm.json (holon hevm)"]


def _load(p: Path):
    return json.loads(Path(p).read_text())


def _resolve(root: Path, p: str | None) -> Path | None:
    if p is None:
        return None
    q = Path(p)
    return q if q.is_absolute() else root / q


class Gate:
    checker: dict | None = None          # bend.fingerprint() of the checker GENV accepted
    timings: dict | None = None          # {"G5": {law_id: seconds}} once G5 has run
    genv_skip = "skipped: GENV failed"   # why the other checks were not run

    def __init__(self, milestone: str, root: Path):
        self.m, self.root = milestone, Path(root).resolve()
        self.cfg = bend.config(self.root)
        self.checks: dict[str, dict] = {}
        self.canaries: list[dict] = []
        self.bend_version = "not_run"
        self.setup_error = None   # a milestone the gate cannot check (no registry, no laws): every check fails with it
        self.facts_path, self.irv = None, None
        try:
            reg = ir.load_registry(milestone, self.root)
            self.facts_path = self.root / reg.get("facts", "facts/morph_header.json")
            self.irv = ir.ir_version_of(milestone, self.root)
        except (OSError, ValueError, KeyError) as e:
            self.setup_error = f"milestone {milestone} cannot be checked: {type(e).__name__}: {e}"
        self.results = self.root / "results" / milestone
        self.gen = self.root / "gen" / milestone
        self.check_outputs: list[str] = []

    # ------------------------------------------------------------ helpers
    def laws(self) -> list[dict]:
        """The milestone's laws. holon.sorts.gate3 narrows this, with records(), to the laws outside I30's subforms when
        it runs this gate's per-law checks over them (G11V reads it through holon.inhabit.g11v; F30)."""
        return ir.load_laws_any(self.m, self.root)

    def records(self) -> dict[str, dict]:
        out = {}
        for law in ir.load_laws_any(self.m, self.root):
            p = self.results / f"{law['law_id']}.json"
            out[law["law_id"]] = _load(p) if p.exists() else None
        return out

    def checked_dirs(self) -> list[tuple[str, dict, Path]]:
        """(law_id, record, proof dir) for every PROVED/REFUTED record."""
        out = []
        for lid, rec in self.records().items():
            if rec and rec.get("status") in ("PROVED", "REFUTED"):
                proof = _resolve(self.root, rec["artifacts"].get("proof"))
                out.append((lid, rec, proof.parent if proof else self.gen / lid))
        return out

    def entry_proofs(self) -> list[tuple[str, str, dict, Path | None, Path | None]]:
        """(law_id, entry point, entry record, PROOF.bend, LAWS.bend) of every REFUTED entry point of a SORT-site
        record (I15): each per-entry counter-law is a checked proof of its own."""
        out = []
        for lid, rec in self.records().items():
            if not rec or not isinstance(rec.get("witnesses"), dict):
                continue
            for e, w in sorted(rec["witnesses"].items()):
                if isinstance(w, dict) and w.get("status") == "REFUTED":
                    out.append((lid, e, w, _resolve(self.root, w.get("proof")), _resolve(self.root, w.get("laws"))))
        return out

    def norm_records(self, results: Path, gen: Path) -> dict[str, dict]:
        """Records with every `seconds` removed and artifact paths made relative to their gen dir."""
        def strip(x):
            if isinstance(x, dict):
                return {k: strip(v) for k, v in x.items() if k != "seconds"}
            if isinstance(x, list):
                return [strip(v) for v in x]
            return x

        def rel(p):
            if p is None:
                return None
            q = Path(p)
            q = q if q.is_absolute() else self.root / q
            try:
                return q.resolve().relative_to(gen.resolve()).as_posix()
            except ValueError:
                return f"<outside gen>/{q.name}"
        out = {}
        for f in ir.record_files(results):   # every law-id pattern ir.load_laws_any reads (L_*, L3_*, ..)
            r = strip(_load(f))
            if isinstance(r.get("artifacts"), dict):
                r["artifacts"] = {k: (rel(v) if k in ("laws", "proof", "model") else v) for k, v in r["artifacts"].items()}
            if isinstance(r.get("non_vacuity"), dict) and r["non_vacuity"].get("law"):
                r["non_vacuity"] = {**r["non_vacuity"], "law": rel(r["non_vacuity"]["law"])}
            if isinstance(r.get("negation"), dict):   # an ∃-law's negation files (0.3), under the gen dir too
                r["negation"] = {k: (rel(v) if k in ("laws", "proof") else v) for k, v in r["negation"].items()}
            if isinstance(r.get("witnesses"), dict):   # a SORT-site law's per-entry counter-laws (I15)
                r["witnesses"] = {e: ({k: (rel(v) if k in ("laws", "proof") else v) for k, v in w.items()}
                                      if isinstance(w, dict) else w) for e, w in r["witnesses"].items()}
            out[f.stem] = r
        return out

    def claimed_sides(self) -> dict[str, set]:
        from .filter import claimed_sides
        reg = ir.load_registry(self.m, self.root)
        return {law["law_id"]: claimed_sides(law, reg.get("facts_sha256")) for law in ir.load_laws_any(self.m, self.root)}

    def target_commits(self) -> dict[str, str]:
        """facts sha256 -> the target commit named by that facts file."""
        out = {}
        for law in ir.load_laws_any(self.m, self.root):
            fp = self.root / law["facts"] if "facts" in law else self.facts_path
            out[law["facts_sha256"]] = F.load(fp)["target"]["commit"]
        return out

    def g6(self) -> None:
        """REFUTED records bound to the committed replay report (G6). Never raises: a malformed
        record or report is a failure with a reason."""
        from .replay import load_report, witness_sha256
        bad, n, model_only = [], 0, []
        try:
            report = load_report(self.m, self.root)
        except Exception as e:  # noqa: BLE001
            report = None
            bad.append(f"replay report unreadable: {e}")
        targets = self.target_commits()
        recs = self.records()
        for lid, rec in sorted(recs.items()):
            if rec is not None and not isinstance(rec, dict):
                bad.append(f"{lid}: the result record is not an object")
        recs = {lid: rec for lid, rec in recs.items() if isinstance(rec, dict)}
        refuted = {lid: rec for lid, rec in recs.items() if rec.get("status") == "REFUTED"}
        claimed = self.claimed_sides()
        laws_ir = {law["law_id"]: law for law in ir.load_laws_any(self.m, self.root)}
        if report is None:
            if refuted and not bad:
                bad.append(f"no replay report for {len(refuted)} REFUTED records")
        elif not isinstance(report, dict):
            bad.append("replay report is not an object")
        else:
            commit = report.get("morph_commit")
            hashes = report.get("witness_sha256")
            laws = report.get("laws")
            if not isinstance(commit, str) or re.fullmatch(r"[0-9a-f]{40}", commit) is None:
                bad.append(f"replay report morph_commit {commit!r} is not a full 40-hex commit")
                commit = ""
            if not isinstance(hashes, dict) or not isinstance(laws, dict):
                bad.append("replay report lacks witness_sha256 / laws objects")
                hashes, laws = {}, {}
            if report.get("harness_mismatch"):
                bad.append("replay report records a harness mismatch (the harness disagreed with the real code's "
                           "own commitment check)")
            ref = report.get("refinement")
            if isinstance(ref, dict) and ref.get("n_disagreements", 0):
                bad.append(f"replay report records {ref.get('n_disagreements')} refinement disagreements")
            if self.irv == "holon-ir/0.2":
                # holon replay always writes both for M1: a missing or doctored block is a failure
                if report.get("harness_mismatch") is not False:
                    bad.append("M1 replay report must record harness_mismatch: false")
                pa = ref.get("per_action") if isinstance(ref, dict) else None
                if (not isinstance(ref, dict) or ref.get("n_disagreements") != 0 or ref.get("disagreements") != []
                        or not isinstance(pa, dict) or not pa
                        or any(not isinstance(v, dict) or v.get("disagree") != 0 for v in pa.values())):
                    bad.append("M1 replay report lacks a refinement block with 0 disagreements in every count")
            for lid in sorted((set(hashes) | set(laws)) - set(refuted)):
                bad.append(f"{lid}: the replay report lists a law that is not REFUTED")
            for lid, rec in sorted(refuted.items()):
                n += 1
                rp = rec.get("replay")
                if not isinstance(rp, dict) or rp.get("status") != "passed":
                    bad.append(f"{lid}: record replay status is {rp.get('status') if isinstance(rp, dict) else rp!r}, "
                               "not passed")
                    rp = rp if isinstance(rp, dict) else {}
                want = targets.get(rec.get("facts_sha256"), "")
                if not isinstance(want, str) or not want or not commit.startswith(want):
                    bad.append(f"{lid}: report is for target commit {commit[:12] or '?'}, facts target {want or '?'}")
                if not isinstance(rec.get("witness"), dict) or not rec.get("witness"):
                    bad.append(f"{lid}: the REFUTED record has no witness object")
                elif not isinstance(hashes.get(lid), str) or re.fullmatch(r"[0-9a-f]{64}", hashes.get(lid)) is None:
                    bad.append(f"{lid}: the replay report's witness sha256 is not a sha256")
                elif hashes.get(lid) != witness_sha256(rec.get("witness")):
                    bad.append(f"{lid}: witness sha256 differs from the replay report")
                entry = laws.get(lid)
                if not isinstance(entry, dict):
                    bad.append(f"{lid}: not in the replay report")
                    continue
                try:
                    if isinstance(rec.get("witnesses"), dict) and rec.get("site"):   # a SORT-site law (I15)
                        bad += self.g6_site(lid, rec, entry, report, claimed.get(lid), laws_ir[lid])
                    else:
                        bad += self.g6_strict(lid, rec, rp, entry, claimed.get(lid), model_only, laws_ir[lid])
                except Exception as e:  # noqa: BLE001  (a malformed entry fails G6 with a reason)
                    bad.append(f"{lid}: replay entry could not be checked: {type(e).__name__}: {e}")
            bad += self.g6_toolchain(report)
        for lid, rec in sorted(recs.items()):
            if rec.get("status") != "REFUTED" and (rec.get("witness_provenance") is not None
                                                          or rec.get("filter_bin") is not None):
                bad.append(f"{lid}: a {rec.get('status')} record carries witness_provenance / filter_bin")
        self.checks["G6"] = _res(not bad, f"{n} REFUTED records bound to passed replays with strict sides, provenance "
                                          f"and recomputed filter bins; {MODEL_ONLY}: {', '.join(model_only) or 'none'}"
                                 if not bad else "; ".join(bad))

    def g6_strict(self, lid: str, rec: dict, rp: dict, entry: dict, claimed: set | None, model_only: list,
                  law: dict) -> list[str]:
        """I4 (strict, after the I4 review). Every claimed side present and well-formed; each side's
        provenance is the one the IR implies; each side's obstruction_observed and status agree with
        what its logged evidence shows (holon.evidence, the rule the replay applies); M1 traces are the
        ones the witness linearises to; the record's provenance and bin equal the filter recomputed
        from the report. Never reads git and never runs a tool."""
        from . import evidence as E
        from . import filter as FL
        bad: list[str] = []
        m1 = self.irv == "holon-ir/0.2"
        if m1:
            if not isinstance(entry.get("sides"), dict):
                return [f"{lid}: M1 replay entry has no 'sides' object"]
            if not isinstance(entry.get("traces"), list):
                bad.append(f"{lid}: M1 replay entry has no traces")
        else:
            if "sides" in entry:
                bad.append(f"{lid}: M0 replay entry must hold sides only, not a 'sides' object")
            junk = sorted(k for k, v in entry.items() if not isinstance(v, dict))
            if junk:
                bad.append(f"{lid}: M0 replay entry holds non-side keys {junk}")
        raw = entry["sides"] if m1 else {k: v for k, v in entry.items() if k != "sides"}
        for side, v in sorted(raw.items()):
            if not isinstance(v, dict):
                bad.append(f"{lid}: {side} side is not an object")
        ss = {k: v for k, v in raw.items() if isinstance(v, dict)}
        if not ss:
            return bad + [f"{lid}: replay entry has no side"]
        if claimed is not None and set(raw) != claimed:
            bad.append(f"{lid}: replay sides {sorted(raw)} differ from the sides its witness claims {sorted(claimed)} "
                       f"(missing: {sorted(claimed - set(raw)) or 'none'})")
        witness = rec.get("witness")
        hfacts = F.load(self.facts_path) if not m1 else None
        # M1: the registry's rollup facts; M0: the same facts give the commit-path trace of a codec witness
        rfacts = F.load(self.facts_path) if m1 else self.rollup_facts()
        for side, v in sorted(ss.items()):
            st = v.get("status")
            if st not in FL.STATUSES:
                bad.append(f"{lid}: {side} side status {st!r}")
                continue
            obs = v.get("obstruction_observed")
            if not isinstance(obs, bool):
                bad.append(f"{lid}: {side} side obstruction_observed is not a boolean")
            elif obs and st != "passed":
                bad.append(f"{lid}: {side} side observed the obstruction without passing")
            pv = v.get("provenance")
            if not isinstance(pv, str) or pv not in FL.PROVENANCE:
                bad.append(f"{lid}: {side} side provenance {pv!r} is not one of {list(FL.PROVENANCE)}")
            elif pv != E.expected_provenance(law, side):
                bad.append(f"{lid}: {side} side provenance {pv!r}, but the IR implies "
                           f"{E.expected_provenance(law, side)!r}")
            if not isinstance(v.get("observed"), str) or not v.get("observed"):
                bad.append(f"{lid}: {side} side records nothing observed")
            if st in ("passed", "failed") and (not isinstance(v.get("command"), str) or not v.get("command")):
                bad.append(f"{lid}: {side} side records no command")
            if st == "not_applicable":
                if not str(v.get("observed", "")).startswith(MODEL_ONLY):
                    bad.append(f"{lid}: {side} side not replayed and not labelled '{MODEL_ONLY}'")
                else:
                    model_only.append(f"{lid}/{side}")
                    if MODEL_ONLY not in str(rp.get("detail", "")):
                        bad.append(f"{lid}: record says replay passed without saying its {side} side is {MODEL_ONLY}")
                continue
            if st != "passed":
                bad.append(f"{lid}: {side} side replay {st!r}")
            if not isinstance(obs, bool):
                continue
            verdict, why = E.verdict(law, side, v, entry, witness, hfacts, rfacts)
            if verdict == E.CONTRADICTION and st == "passed":
                bad.append(f"{lid}: {side} side passed, but its evidence contradicts the model: {why}")
            elif verdict == E.OBSERVED and st == "passed" and not obs:
                bad.append(f"{lid}: {side} side evidence shows the obstruction but obstruction_observed is false")
            elif verdict == E.NOT_OBSERVED and obs:
                bad.append(f"{lid}: {side} side claims the obstruction, but its evidence does not show it: {why}")
            elif verdict is None and obs != (st == "passed"):
                bad.append(f"{lid}: {side} side obstruction_observed must equal its pass (its harness compares "
                           f"the real output with the witness)")
        if m1:
            want_status = ("passed" if all(s.get("status") == "passed" or
                                           (s.get("status") == "not_applicable" and
                                            str(s.get("observed", "")).startswith(MODEL_ONLY)) for s in ss.values())
                           and any(s.get("status") == "passed" for s in ss.values()) else "failed")
            if entry.get("status") != want_status:
                bad.append(f"{lid}: law-level replay status {entry.get('status')!r}, but its sides give {want_status!r}")
            if entry.get("obstruction_reproduced") is not all(s.get("obstruction_observed") is True for s in ss.values()):
                bad.append(f"{lid}: obstruction_reproduced is not the conjunction of its sides")
            if "solidity" in ss:
                bad += self.g6_traces(lid, law, witness if isinstance(witness, dict) else {}, entry)
                if ss["solidity"].get("status") == "passed":
                    bad += self.g6_trace_agreement(lid, entry)
        want_wp, want_bin = FL.provenance_of(ss), FL.bin_of(ss)
        if rec.get("witness_provenance") != want_wp:
            bad.append(f"{lid}: record witness_provenance {rec.get('witness_provenance')!r} != {want_wp!r} from the report")
        if rec.get("filter_bin") != want_bin:
            bad.append(f"{lid}: record filter_bin {rec.get('filter_bin')!r} != {want_bin!r} recomputed from the report")
        return bad

    def g6_site(self, lid: str, rec: dict, entry: dict, report: dict, claimed: set | None, law: dict) -> list[str]:
        """G6 for a REFUTED SORT-site record (I15): every REFUTED entry point is bound to a passed replay entry that
        observed the obstruction: its trace is the witness's prefix ++ [action], its witness sha256 is the report's,
        every step's real outcome equals the model's, the last step reverts with a realization-check reason of the
        sidecar, and the located Panic lies in the site's span (from the site id); the record's per-entry replay
        agrees with the report; the law-level side is well formed and the filter fields are recomputed from it."""
        from . import evidence as E
        from . import filter as FL
        from .replay import witness_sha256
        from .sorts.sites import load_sidecar, split_site_id
        from .mreplay import in_span
        bad: list[str] = []
        _, span, _ = split_site_id(rec["site"])
        _, _, reasons = load_sidecar(self.m, self.root)
        ents = entry.get("entries") if isinstance(entry.get("entries"), dict) else None
        if ents is None:
            return [f"{lid}: the replay entry of a SORT-site law has no entries"]
        hashes = (report.get("entry_witness_sha256") or {}).get(lid) or {}
        refuted = {e: w for e, w in rec["witnesses"].items() if isinstance(w, dict) and w.get("status") == "REFUTED"}
        for e in sorted(set(ents) - set(refuted)):
            bad.append(f"{lid}: the replay report replays entry point {e}, which the record does not refute")
        for e, w in sorted(refuted.items()):
            x = ents.get(e)
            if not isinstance(x, dict):
                bad.append(f"{lid} entry {e}: not in the replay report")
                continue
            wit = w.get("witness") if isinstance(w.get("witness"), dict) else {}
            sB = next((b["name"] for b in law["statement"]["binders"] if b["type"] == "Reach"), "s")
            aB = next((b["name"] for b in law["statement"]["binders"] if b["type"] == "Act"), "a")
            try:
                want_tr = list(wit[sB]["run"]) + [dict(wit[aB])]
            except (KeyError, TypeError):
                bad.append(f"{lid} entry {e}: the witness is not a run and an action")
                continue
            if x.get("trace") != want_tr:
                bad.append(f"{lid} entry {e}: the replayed trace is not the witness's prefix and action")
            if hashes.get(e) != witness_sha256(wit):
                bad.append(f"{lid} entry {e}: witness sha256 differs from the replay report")
            real, model = x.get("real"), x.get("model")
            if (not isinstance(real, list) or not isinstance(model, list) or len(real) != len(want_tr)
                    or real != model or any(r in ("missing", "rev ?") for r in real)):
                bad.append(f"{lid} entry {e}: the real outcomes {real} are not the model's {model}")
            if x.get("status") != "passed":
                bad.append(f"{lid} entry {e}: replay {x.get('status')!r}")
            last = real[-1] if isinstance(real, list) and real else None
            observed = (x.get("status") == "passed" and any(last == f"rev {r}" for r in sorted(reasons))
                        and in_span(span, x.get("panic_site")))
            if x.get("obstruction_observed") is not True or not observed:
                bad.append(f"{lid} entry {e}: the obstruction is not observed (last step {last}, panic at "
                           f"{x.get('panic_site')}, site span {span})")
