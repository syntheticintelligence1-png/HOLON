"""Generate the `.bend` driver that makes a compiled model callable as a C library.

Bend 2.0.36 emits C (`bend F.bend -o F.c`) around a `main`; defs only get their
own callable segment (FID) when the program graph cannot inline them — a
non-tail self-call is enough. So every driver exposes exactly two uniform
entry points, both recursive in their unreachable tail:

    hcall  (op : Nat, args : List<Nat>)       -> List<Nat>   # single-value edges
    hcall2 (op : Nat, tr   : List<List<Nat>>) -> List<Nat>   # trace edges

`hcall2` is used by state-machine models: `tr` is a trace, one inner list per
step. The host (C shim / cgo / forge vectors) only ever calls FID_HCALL or
FID_HCALL2; everything else is inlined into those segments.

`main` must reference both dispatchers or they are dead-code-eliminated, so it
evaluates them on empty input. The emitted `#define FID_HCALL` / `FID_HCALL2`
in model.c is what bendc.py extracts for the host.

Per model, `flat_ops` and `trace_ops` describe each op: a name and a Bend
expression over `args` (flat) or `tr` (trace) returning List<Nat>. Op ids are
per dispatcher, in list order.
"""
from __future__ import annotations

HELPERS = """\
def at(+xs: List<&2, Nat>, i: Nat, d: Nat) -> Nat:
  match xs i:
    case Nil{} _:
      d
    case Con{h, _} 0n:
      h
    case Con{_, t} 1n+p:
      at(t, p, d)

def nats2u(+xs: List<&2, Nat>) -> List<&2, U32>:
  match xs:
    case Nil{}:
      Nil{}
    case Con{h, t}:
      Con{U32.from_nat(h), nats2u(t)}

def u2nats(+xs: List<&2, U32>) -> List<&2, Nat>:
  match xs:
    case Nil{}:
      Nil{}
    case Con{h, t}:
      Con{U32.to_nat(h), u2nats(t)}

def u2bool(b: Bool) -> List<&2, Nat>:
  match b:
    case False{}:
      Con{0n, Nil{}}
    case True{}:
      Con{1n, Nil{}}

def bool_of(n: Nat) -> Bool:
  match n:
    case 0n:
      False{}
    case 1n+p:
      True{}
"""


def _dispatch(name: str, argty: str, arg: str, nops: int, pref: str = "wf") -> str:
    out = [f"def {name}(op: Nat, {arg}: {argty}) -> List<&2, Nat>:", "  match op:"]
    for i in range(nops):
        out.append(f"    case {i}n:")
        out.append(f"      {pref}{i}({arg})")
    out.append(f"    case {nops}n+p:")
    out.append(f"      Con{{404n, {name}(p, {arg})}}")
    if nops == 0:
        out = [
            f"def {name}(op: Nat, {arg}: {argty}) -> List<&2, Nat>:",
            "  match op:",
            "    case 0n:",
            "      Con{404n, Nil{}}",
            "    case 1n+p:",
            f"      Con{{404n, {name}(p, {arg})}}",
        ]
    return "\n".join(out)


def emit_driver(model_import: str, flat_ops: list[dict], trace_ops: list[dict],
                helpers: str = "") -> str:
    """Return driver.bend source. `model_import` is the relative .bend path."""
    parts = [
        "# GENERATED by holon.native.drivergen — do not edit.",
        "import Base",
        f"import ./{model_import} as M",
        "",
        HELPERS + helpers,
    ]
    for i, o in enumerate(flat_ops):
        parts.append(f"def wf{i}(args: List<&2, Nat>) -> List<&2, Nat>:")
        parts.append(f"  {o['body']}")
        parts.append("")
    parts.append(_dispatch("hcall", "List<&2, Nat>", "args", len(flat_ops)))
    parts.append("")
    for i, o in enumerate(trace_ops):
        parts.append(f"def wt{i}(tr: List<&2, List<&2, Nat>>) -> List<&2, Nat>:")
        parts.append(f"  {o['body']}")
        parts.append("")
    parts.append(_dispatch("hcall2", "List<&2, List<&2, Nat>>", "tr", len(trace_ops), pref="wt"))
    parts.append("")
    parts += [
        "def wflat(args: List<&2, Nat>) -> List<&2, Nat>:",
        "  hcall(0n, args)",
        "",
        "def wtrace(tr: List<&2, List<&2, Nat>>) -> List<&2, Nat>:",
        "  hcall2(0n, tr)",
        "",
        "# main must mention both dispatchers so their segments survive codegen.",
        "def main() -> Nat:",
        "  (List.length(&2, Nat, wflat(Nil{})) + List.length(&2, Nat, wtrace(Nil{})) : Nat)",
        "",
    ]
    return "\n".join(parts)
