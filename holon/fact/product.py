"""The product program of a FACT kernel law and its proof routes (BUILD_PLAN I26; the contract is the docstring of
tests_m3/test_fact.py, "Deciding"); holon.gen.mproofs.product assembles it.

The product program runs the law's two steps side by side: fact_<x> (holon.fact.section) takes each step apart through
fx_sel_<a> (a call of the action or not), each run's blob-hash list apart (empty or an entry and a rest), and pairs the
two runs' success, premises and commitments in fx_k3(d, o1, o2, pt, c). A route proves that claim for every pair of
reachable states and steps:

  guard       each run's program, followed on the typed model's statement chain from x0 (holon.disch.mirror's stepper),
              reverts on every path before its first blob guard, or reaches it; the guard compares the first entry of
              the step's blob-hash list with the zero word, and blobs_wf makes that entry a nonzero word whenever the
              list is not empty, so a step with a non-empty list reverts there. A successful run therefore has the
              empty list, and two successful runs have equal consumers ([] and []). The proof: one lemma per branch of
              the program before the guard (each check's other case is a revert with a literal nonzero code; the guard's
              condition is rewritten to false), the blob guard's condition from blobs_wf, and the product's case split
              (fx_sel of both steps, then the two lists: [] and [] give equal consumers, a non-empty list makes its run
              fail)
  injective   not generated (NoProof, named): equal commitments give equal hashed regions under CF only through a
              keccak256 table lemma over the region's bytes (m_slice of the memory the step wrote), which the typed
              model's memory has no lemma library for
  provenance  not generated (NoProof, named): an invariant over Reach relating A[k].m to the chooser companion needs an
              induction over Reach with a step lemma per action of the model

Every lemma holds for every state (the Reach premise is not used). Nothing here names a target.
"""
from __future__ import annotations

import re

from ..disch.mirror import Branch, Final, Mirror, NoMirror, Next, as_call
from ..gen.mlaws import law_name
from ..machine_bend import bname
from ..rules import fact as RF
from ..sorts.proofs3 import model_names, tabs_binders


class NoProof(ValueError):
    """The route does not apply (named)."""


PHEADER = "# GENERATED by holon.fact.product; untrusted, accepted only if Bend checks it."


ROUTES = ("guard", "injective", "provenance")
NO_ROUTE = {
    "injective": ("not generated: equal commitments give equal hashed regions under CF only through a lemma that a "
                  "keccak256 table entry determines its key's bytes, applied to the memory region the step hashes "
                  "(m_slice of the words it stored); the typed model's memory (m_put, m_slice) has no lemma library, so "
                  "the region's cells cannot be read back from the stored digest in a proof"),
    "provenance": ("not generated: the invariant relating A[k].m to the chooser companion g_P[k] holds along Reach "
                   "only by induction over Reach with one step lemma per action of the model (each keeps the relation "
                   "or writes both); no such per-action invariant generator is built"),
}

_ZERO = re.compile(r"^M\.(?:W\{\s*0(?:\s*,\s*0){7}\s*\}|w0\(\))$")
_WLIT = re.compile(r"M\.W\{\s*(\d+(?:\s*,\s*\d+){7})\s*\}")


def lits(t: str) -> str:
    """A term with every literal word M.W{..} written M.w_of_limbs([..]) (the same value; a literal list is one term
    of the measure)."""
    return _WLIT.sub(lambda m: f"M.w_of_limbs([{m.group(1)}])", t)


def _unwrap(t: str) -> str:
    """t without a nominal wrapper M.T_<S>{p} (one level)."""
    c = as_call(t)
    if c and c[2] == "{" and c[0].startswith("M.T_") and len(c[1]) == 1:
        return c[1][0]
    return t


def blob_first(en: str) -> str:
    return f"M.w_nth(M.ge_e_blobs({en}), 0n)"


def is_blob_guard(cond: str, en: str) -> bool:
    """Is the condition the comparison of the first entry of the step's blob-hash list with the zero word (an
    equality, w_eq or a typed eq_<S>_<S>, either side wrapped in its nominal type)?"""
    c = as_call(cond.strip())
    if not c or c[2] != "(" or len(c[1]) != 2:
        return False
    if not (c[0] == "M.w_eq" or re.fullmatch(r"M\.eq_(\w+)_\1", c[0])):
        return False
    a, b = (_unwrap(x).strip() for x in c[1])
    want = blob_first(en)
    return (a == want and bool(_ZERO.match(b))) or (b == want and bool(_ZERO.match(a)))


class Guard:
    """The guard route of one kernel law: the lemmas, then the law's proof term."""

    FIXED = ("st", "ar", "en")

    def __init__(self, model_text: str, law_id: str, action: str, hashes: list):
        self.law_id = law_id
        self.x = RF.ghost_x(law_id)
        self.a = bname(action)
        self.action = action
        self.tabs = [n for n, _h in tabs_binders(hashes)]
        self.names = model_names(model_text)
        try:
            self.mi = Mirror(model_text, self.a, self.names)
        except NoMirror as e:
            raise NoProof(f"{action}: {e}") from None
        self.defs: list = []
        self.lemmas = 0
        self.hit = None                  # (fn, cond) of the blob guard
        self.x0 = None

    # ---------------------------------------------------------- text pieces
    def tp(self) -> str:
        return "".join(f", +{n}: List<&2, M.HKB>" for n in self.tabs)

    def ta(self) -> str:
        return "".join(f", {n}" for n in self.tabs)

    def fixed_params(self) -> str:
        return f"+st: M.HSt, +ar: M.AR_{self.a}, +en: M.HEnv{self.tp()}"

    def fixed_args(self) -> str:
        return f"st, ar, en{self.ta()}"

    def x0_term(self) -> str:
        return f"M.x0_{self.a}({self.fixed_args()})"

    def rec(self, args: list) -> str:
        """A branch's record argument: x0 when it is x0's record (no statement before it changed the context)."""
        if len(args) != 1:
            raise NoProof(f"{self.action}: a branch with {len(args)} further arguments")
        r = args[0].strip()
        return self.x0_term() if r == self.x0 else lits(r)

    def goal(self, fn: str, c: str, args: list) -> str:
        return f"{{U32.is_eq(M.gx_{self.a}_cd({fn}({c}, {self.rec(args)})), 0) == False{{}} : Bool}}"

    # ---------------------------------------------------------- the chain before the blob guard
    def term(self, node) -> str:
        """The proof that the step's code is not 0 at this node (every path reverts or reaches the blob guard)."""
        if isinstance(node, Next):
            return self.term(self.mi.step(node.j, node.fields))
        if isinstance(node, Final):
            cd = node.fields[self.mi.field_names.index("cd")].strip()
            if re.fullmatch(r"\d+", cd) and int(cd) != 0:
                return "{==}"
            raise NoProof(f"{self.action}: a path of its program ends with code {cd[:60]} before any blob guard")
        if isinstance(node, Branch):
            if node.fn.startswith(f"M.k_{self.a}_") and is_blob_guard(node.cond, "en"):
                return self.guard_lemma(node)
            return self.branch_lemma(node)
        raise NoProof(f"{self.action}: an evaluation result the stepper cannot state ({type(node).__name__})")

    def branch_lemma(self, br: Branch) -> str:
        self.lemmas += 1
        if self.lemmas > MAX_LEMMAS:
            raise NoProof(f"{self.action}: more than {MAX_LEMMAS} branches before the blob guard")
        name = f"pq{self.lemmas}"
        then_t, else_t = self.term(br.then), self.term(br.other)
        self.defs.append(f"def {name}(c: Bool, {self.fixed_params()}, eb: {{pg(en) == False{{}} : Bool}}) -> "
                         f"{self.goal(br.fn, 'c', br.args)}:\n  match c:\n    case True{{}}:\n      {then_t}\n"
                         f"    case False{{}}:\n      {else_t}\n")
        return f"{name}({lits(br.cond)}, {self.fixed_args()}, eb)"

    def guard_lemma(self, br: Branch) -> str:
        """The blob guard: its condition is false (eb), so the check takes its revert."""
        cond = lits(br.cond)
        if self.hit is not None and self.hit != (br.fn, cond):
            raise NoProof(f"{self.action}: two different blob guards on its paths")
        if self.hit is None:
            self.hit = (br.fn, cond)
            fin = br.other
            if not isinstance(fin, Final):
                raise NoProof(f"{self.action}: the blob guard's failing case does not revert")
            cd = fin.fields[self.mi.field_names.index("cd")].strip()
            if not (re.fullmatch(r"\d+", cd) and int(cd) != 0):
                raise NoProof(f"{self.action}: the blob guard's failing case ends with code {cd[:60]}")
            motive = self.goal(br.fn, "_", br.args)
            self.defs.append(f"def ph({self.fixed_params()}, eb: {{pg(en) == False{{}} : Bool}}) -> "
                             f"{self.goal(br.fn, 'pg(en)', br.args)}:\n"
                             f"  (%Equal.sym(Bool, pg(en), False{{}}, eb) : {motive}\n  {{==}})\n")
        return f"ph({self.fixed_args()}, eb)"

    def chain(self) -> str:
        """The lemmas of the action's program from x0; returns the proof term of {code(xr) != 0} in st, ar, en."""
        x0 = self.mi.x0_fields("st", "ar", "en", self.tabs)
        self.x0 = f"M.X_{self.a}{{{', '.join(x0)}}}"
        t = self.term(self.mi.step(self.mi.first, x0))
        if self.hit is None:
            raise NoProof(f"{self.action}: no path of its program reaches a blob guard (a check comparing the first "
                          "blob-hash entry with the zero word)")
        return t

    # ---------------------------------------------------------- the whole proof
    def text(self, model_import: str, section_import: str, laws_import: str) -> str:
        x, a = self.x, self.a
        first = self.chain()
        _fn, cond = self.hit
        pgc = cond
        if pgc.count("M.ge_e_blobs(en)") != 1:
            raise NoProof(f"{self.action}: the blob guard reads the blob-hash list {pgc.count('M.ge_e_blobs(en)')} times")
        motive = pgc.replace("M.ge_e_blobs(en)", "_")
        X = f"F.fx_ok_{x}"
        tp, ta = self.tp(), self.ta()
        # the guard's condition, and the code of a step from s (the success fx_s_<x> reads)
        pg = f"# the blob guard's condition\ndef pg(+en: M.HEnv) -> Bool:\n  {pgc}\n"
        head = [f"def pe(+h: M.W, +t: List<&2, M.W>, +en: M.HEnv, e: {{Con{{h, t}} == M.ge_e_blobs(en) : "
                f"List<&2, M.W>}}, ez: {{M.w_eq(h, M.w0()) == False{{}} : Bool}}) -> {{pg(en) == False{{}} : Bool}}:\n"
                f"  (%e : {{{motive} == False{{}} : Bool}}\n  ez)\n"]
        head.append("def af(+p: Bool, +q: Bool, e: {q == False{} : Bool}) -> {Bool.and(p, q) == False{} : Bool}:\n"
                    "  match p:\n    case True{}:\n      e\n    case False{}:\n      {==}\n")
        # a non-empty list of one run: blobs_wf fails (its first entry is the zero word) or the run reverts
        sbody = first.replace("st, ar, en", "M.gh_get_st(s), ar, en")
        sbody = re.sub(r"(?<![\w.])st(?![\w])", "M.gh_get_st(s)", sbody)
        head.append(f"def pz(z: Bool, +h: M.W, +t: List<&2, M.W>, +ar: M.AR_{a}, +en: M.HEnv, +s: M.GSt{tp}, "
                    f"ez: {{M.w_eq(h, M.w0()) == z : Bool}}, e: {{Con{{h, t}} == M.ge_e_blobs(en) : List<&2, M.W>}}) -> "
                    f"{{Bool.and(F.fx_wfw(z, Bool.and(F.fx_top(h), F.fx_wf(t))), F.fx_s_{x}(ar, en, s{ta})) == False{{}} "
                    f": Bool}}:\n  match z:\n    case True{{}}:\n      {{==}}\n    case False{{}}:\n"
                    f"      af(Bool.and(F.fx_top(h), F.fx_wf(t)), F.fx_s_{x}(ar, en, s{ta}), "
                    f"{sbody.replace(', eb)', ', pe(h, t, en, e, ez))')})\n")
        head.append(f"def p1(+d: Bool, o1: Bool, +o2: Bool, +pt: Bool, +c: Bool, e: {{o1 == False{{}} : Bool}}) -> "
                    f"{{F.fx_k3(d, o1, o2, pt, c) == True{{}} : Bool}}:\n  match d:\n    case True{{}}:\n      {{==}}\n"
                    f"    case False{{}}:\n      (%Equal.sym(Bool, o1, False{{}}, e) : "
                    f"{{F.fx_k3(False{{}}, _, o2, pt, c) == True{{}} : Bool}}\n      {{==}})\n")
        head.append(f"def p2(+o1: Bool, o2: Bool, +pt: Bool, +c: Bool, e: {{o2 == False{{}} : Bool}}) -> "
                    f"{{F.fx_k3(False{{}}, o1, o2, pt, c) == True{{}} : Bool}}:\n  match o1:\n    case True{{}}:\n"
                    f"      (%Equal.sym(Bool, o2, False{{}}, e) : {{F.fx_k3(False{{}}, True{{}}, _, pt, c) == True{{}} : "
                    f"Bool}}\n      {{==}})\n    case False{{}}:\n      {{==}}\n")
        two = f"+ar1: M.AR_{a}, +en1: M.HEnv, +s1: M.GSt, +ar2: M.AR_{a}, +en2: M.HEnv, +s2: M.GSt{tp}"
        args = f"ar1, en1, s1, ar2, en2, s2{ta}"
        rest = f"F.fx_pt_{x}({ta[2:]}), F.fx_c_{x}({args})"
        pz1 = f"pz(M.w_eq(h1, M.w0()), h1, t1, ar1, en1, s1{ta}, {{==}}, e1)"
        pz2 = f"pz(M.w_eq(h2, M.w0()), h2, t2, ar2, en2, s2{ta}, {{==}}, e2)"
        head.append(f"def pl(+b1: List<&2, M.W>, +b2: List<&2, M.W>, {two}, e1: {{b1 == M.ge_e_blobs(en1) : "
                    f"List<&2, M.W>}}, e2: {{b2 == M.ge_e_blobs(en2) : List<&2, M.W>}}) -> "
                    f"{{F.fk3_{x}(b1, b2, {args}) == True{{}} : Bool}}:\n  match b1:\n    case Nil{{}}:\n"
                    f"      match b2:\n        case Nil{{}}:\n          {{==}}\n        case Con{{+h2, +t2}}:\n"
                    f"          p2({X}(Nil{{}}, ar1, en1, s1{ta}), {X}(Con{{h2, t2}}, ar2, en2, s2{ta}), {rest}, {pz2})\n"
                    f"    case Con{{+h1, +t1}}:\n      p1(F.fx_ws_eq(Con{{h1, t1}}, b2), {X}(Con{{h1, t1}}, ar1, en1, s1{ta}), "
                    f"{X}(b2, ar2, en2, s2{ta}), {rest}, {pz1})\n")
        head.append(f"def pm(o1: F.FxO_{a}, +s1: M.GSt, o2: F.FxO_{a}, +s2: M.GSt{tp}) -> "
                    f"{{F.fk1_{x}(o1, s1, o2, s2{ta}) == True{{}} : Bool}}:\n  match o1 o2:\n"
                    f"    case F.FxS_{a}{{+ar1, +en1}} F.FxS_{a}{{+ar2, +en2}}:\n"
                    f"      pl(M.ge_e_blobs(en1), M.ge_e_blobs(en2), {args}, {{==}}, {{==}})\n"
                    f"    case F.FxS_{a}{{_, _}} F.FxN_{a}{{}}:\n      {{==}}\n    case F.FxN_{a}{{}} _:\n      {{==}}\n")
        main = (f"def Laws.{law_name(self.law_id)}({ta[2:]}, s1, r_s1, x1, s2, r_s2, x2):\n"
                f"  pm(F.fx_sel_{a}(x1), s1, F.fx_sel_{a}(x2), s2{ta})\n")
        pre = [PHEADER, "import Base", f"import {model_import} as M", f"import {section_import} as F",
               f"import {laws_import} as Laws", "",
               f"# route guard: {self.action}'s blob guard ({self.hit[0]}) makes a successful step's blob-hash list "
               "empty, so two successful runs have equal consumers", ""]
        return "\n".join(pre) + "\n" + "\n".join([pg] + self.defs + head + [main])


def has_blob_guard(model_text: str, action_b: str) -> bool:
    """Does any check of the action's statement chain read the first blob-hash entry (a candidate blob guard)?"""
    body = re.findall(rf"(?ms)^def s_{re.escape(action_b)}_\d+\(.*?(?=^def |\Z)", model_text)
    return any("w_nth(ge_e_blobs(" in b and f"k_{action_b}_" in b for b in body)


MAX_LEMMAS = 400          # the chain's branch lemmas before the blob guard: past this, the route is refused (named)


def guard_proof(model_text: str, law: dict, basis: dict, hashes: list, model_import: str, section_import: str,
                laws_import: str) -> str:
    """The guard route's PROOF.bend of a kernel law, or NoProof naming why the route does not apply."""
    if law.get("subform") != "kernel":
        raise NoProof("the guard route is a kernel route")
    if not has_blob_guard(model_text, bname(basis["action"])):
        raise NoProof(f"{basis['action']}: no check of its program reads the first blob-hash entry (no blob guard)")
    try:
        return Guard(model_text, law["law_id"], basis["action"], hashes).text(model_import, section_import,
                                                                            laws_import)
    except NoMirror as e:
        raise NoProof(f"{basis['action']}: the stepper cannot follow its program before the blob guard: {e}") from None
    except RecursionError:
        raise NoProof(f"{basis['action']}: its program's paths before the blob guard are too deep to follow") from None


def product(route: str, model_text: str, law: dict, basis: dict, hashes: list, model_import: str, section_import: str,
            laws_import: str) -> str:
    """The product program's proof of a FACT law by one route (holon.gen.mproofs.product), or NoProof."""
    if route == "guard":
        return guard_proof(model_text, law, basis, hashes, model_import, section_import, laws_import)
    if route in NO_ROUTE:
        raise NoProof(NO_ROUTE[route])
    raise NoProof(f"no route {route}")
