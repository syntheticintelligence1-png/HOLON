class FLit(Lit):
    """Witness literals: the typed model's records qualified by M, the FACT section's (sec: its record names) by F."""

    def __init__(self, recs: dict, sec: set):
        super().__init__(recs, set())
        self.sec = set(sec)

    def _rec(self, v, field):
        name = v["$r"]
        fs = self.recs.get(name)
        vals = v.get("f") or {}
        if fs is None:
            if vals:
                raise ValueError(f"no field types for {name}")
            return f"F.{name}{{}}"
        return f"F.{name}{{" + ", ".join(field(vals[f], t) for f, t in fs) + "}"

    def text(self, v) -> str:
        if isinstance(v, dict) and v.get("$r") in self.sec:
            return self._rec(v, lambda x, _t: self.text(x))
        return super().text(v)

    def typed(self, v, ty: str) -> str:
        if isinstance(v, dict) and v.get("$r") in self.sec:
            return self._rec(v, self.typed)
        return super().typed(v, ty)


_DEF = re.compile(r"^def (\w+)\((.*)\) -> (.+):$")
_OPEN, _CLOSE = "([{", ")]}"
# the skeleton's connectives (the section's fixed definitions and Base's), each with its arity and meaning
CONNECTIVES = {"fx_k3": (5, lambda d, o1, o2, pt, c: d or not (o1 and o2 and pt and c)),
               "fx_imp": (2, lambda c, b: (not c) or b),
               "Bool.and": (2, lambda a, b: a and b),
               "Bool.not": (1, lambda a: not a)}


def _split(text: str, angle: bool = False) -> list[str]:
    """text split at its top-level commas (angle: <..> nests too, for types)."""
    out, depth, cur = [], 0, []
    opens, closes = _OPEN + ("<" if angle else ""), _CLOSE + (">" if angle else "")
    for ch in text:
        if ch in opens:
            depth += 1
        elif ch in closes:
            depth -= 1
        if ch == "," and depth == 0:
            out.append("".join(cur).strip())
            cur = []
        else:
            cur.append(ch)
    if "".join(cur).strip():
        out.append("".join(cur).strip())
    return out


def _callp(t: str):
    """(head, argument texts) when t is exactly one call head(..), else None."""
    t = t.strip()
    m = re.match(r"^([A-Za-z_][\w.]*)\(", t)
    if not m:
        return None
    depth = 0
    for i in range(m.end() - 1, len(t)):
        if t[i] in _OPEN:
            depth += 1
        elif t[i] in _CLOSE:
            depth -= 1
            if depth == 0:
                return (m.group(1), _split(t[m.end():i])) if i == len(t) - 1 else None
    return None


class Shape:
    """What the by-parts form reads from the FACT section: its module text (the single-expression definitions it
    unfolds, the names it qualifies by F), the law's subform and action, and for an attribution witness the decoded
    run_fact value (state and companions) after each step of its trace."""

    def __init__(self, module_text: str, subform: str, action: str, rstates: list | None = None):
        self.subform, self.action, self.rstates = subform, action, list(rstates or [])
        self.defs: dict = {}
        self.names: set = set()
        self.types: set = set()
        lines = module_text.splitlines()
        for i, ln in enumerate(lines):
            m = _DEF.match(ln)
            if m:
                self.names.add(m.group(1))
                body = lines[i + 1] if i + 1 < len(lines) else ""
                if body.startswith("  ") and not (i + 2 < len(lines) and lines[i + 2].startswith("  ")):
                    self.defs[m.group(1)] = ([(q.lstrip("+").split(":", 1)[0].strip(), q.split(":", 1)[1].strip())
                                              for q in _split(m.group(2), angle=True)], body.strip())
            t = re.match(r"^type (\w+) is", ln)
            if t:
                self.types.add(t.group(1))
                self.names.add(t.group(1))
                for ln2 in lines[i + 1:]:
                    c = re.match(r"^  (\w+)\{", ln2)
                    if not c:
                        break
                    self.names.add(c.group(1))

    def qual(self, expr: str) -> str:
        """The section's names called or constructed in expr, qualified by F."""
        return re.sub(r"(?<![\w.])([A-Za-z_]\w*)(?=[({])",
                      lambda m: ("F." + m.group(1)) if m.group(1) in self.names else m.group(1), expr)

    def qual_type(self, ty: str) -> str:
        return re.sub(r"(?<![\w.])([A-Za-z_]\w*)(?![\w.])",
                      lambda m: ("F." + m.group(1)) if m.group(1) in self.types else m.group(1), ty)


def _subst(expr: str, m: dict) -> str:
    """The variables of expr (names neither called, constructed nor qualified) replaced by m's texts, in one pass."""
    return re.sub(r"(?<![\w.])([A-Za-z_]\w*)(?![\w.({])", lambda g: m.get(g.group(1), g.group(1)), expr)


def _tree(t: str):
    c = _callp(t)
    if c and c[0] in CONNECTIVES and len(c[1]) == CONNECTIVES[c[0]][0]:
        return ("op", c[0], [_tree(a) for a in c[1]])
    return ("leaf", t.strip())


def _leaves(tr) -> list[str]:
    return [tr[1]] if tr[0] == "leaf" else [x for a in tr[2] for x in _leaves(a)]


def _skel(tr, it, shape: Shape) -> str:
    if tr[0] == "leaf":
        return next(it)
    head = shape.qual(tr[1] + "(")[:-1]
    return f"{head}(" + ", ".join(_skel(a, it, shape) for a in tr[2]) + ")"


def _value(tr, it) -> bool:
    if tr[0] == "leaf":
        return next(it)
    return CONNECTIVES[tr[1]][1](*[_value(a, it) for a in tr[2]])


def forced(tr, target: bool) -> tuple | None:
    """The leaf values at which the skeleton has the law's value, when exactly one assignment gives it."""
    n = len(_leaves(tr))
    if n == 0 or n > 12:
        return None
    hits = [vs for vs in itertools.product((False, True), repeat=n) if _value(tr, iter(vs)) == target]
    return hits[0] if len(hits) == 1 else None


def _btxt(b: bool) -> str:
    return "True{}" if b else "False{}"


class _Parts:
    """The by-parts definitions of one law at one witness (see the module docstring). fn: "fact" or "fhit"; target:
    the value the proof shows (False for a counter-law, True for an inhabitant). build() returns (definitions, the
    binder terms in the law's order, the proof of {fn(..) == target}) or None when the form does not apply."""

    def __init__(self, law: dict, shape: Shape, tb: list, fn: str, target: bool, lit: Lit):
        self.law, self.shape, self.tb, self.fn, self.target, self.lit = law, shape, tb, fn, target, lit
        self.x = RF.ghost_x(law["law_id"])
        self.a = bname(shape.action)
        self.flit = FLit(lit.recs, shape.names)
        self.tabs = [n for n, _h in tb]

    def _common(self, tree, leaves_vars: list[str], inst: dict) -> tuple[list[str], str, str] | None:
        """kk, the leaf lemmas and kv; (lines, the leaves at the literals, kv's application)."""
        vals = forced(tree, self.target)
        if vals is None:
            return None
        n = len(vals)
        cs = [f"c{i}" for i in range(n)]
        T = _btxt(self.target)
        lines = [f"def kk({', '.join(f'{c}: Bool' for c in cs)}) -> Bool:\n  {_skel(tree, iter(cs), self.shape)}", ""]
        sig = ", ".join([f"+{c}: Bool" for c in cs] + [f"e{i}: {{{_btxt(v)} == c{i} : Bool}}" for i, v in enumerate(vals)])
        body = "{==}"
        for i in reversed(range(n)):
            args = [_btxt(vals[j]) if j < i else ("_" if j == i else cs[j]) for j in range(n)]
            body = f"(%e{i} : {{kk({', '.join(args)}) == {T} : Bool}}\n  {body})"
        lines += [f"def kv({sig}) -> {{kk({', '.join(cs)}) == {T} : Bool}}:\n  {body}", ""]
        lv = [_subst(l, inst) for l in leaves_vars]
        for i, (v, l) in enumerate(zip(vals, lv)):
            lines += [f"def l{i}() -> {{{_btxt(v)} == {l} : Bool}}:\n  {{==}}", ""]
        return lines, ", ".join(lv), f"kv({', '.join(lv + [f'l{i}()' for i in range(n)])})"

    def _act(self, name: str, v, done: dict) -> tuple[list[str], str, str] | None:
        """The literal (ar, en) of an action value as a_<name>, e_<name> (shared by equal values)."""
        if not (isinstance(v, dict) and v.get("$r") == f"A_{self.a}"):
            return None
        key = repr(v)
        if key in done:
            return [], *done[key]
        f = v.get("f") or {}
        lines = [f"def a_{name}() -> M.AR_{self.a}:\n  {self.lit.text(f['ar'])}", "",
                 f"def e_{name}() -> M.HEnv:\n  {self.lit.text(f['en'])}", ""]
        done[key] = (f"a_{name}()", f"e_{name}()")
        return lines, *done[key]

    def kernel(self, states: dict, values: dict):
        sh = self.shape
        pre = "fk" if self.fn == "fact" else "fh"
        entry, split = sh.defs.get(f"{pre}2_{self.x}"), sh.defs.get(f"{pre}3_{self.x}")
        if entry is None or split is None:
            return None
        c = _callp(entry[1])
        if c is None or c[0] != f"{pre}3_{self.x}" or len(c[1]) != len(split[0]):
            return None
        tree = _tree(split[1])
        m = {q: arg for (q, _t), arg in zip(split[0], c[1])}
        leaves = [sh.qual(_subst(l, m)) for l in _leaves(tree)]
        vars_ = [q for q, _t in entry[0]]
        acts = [n for n, ty in binders(self.law) if ty == "M.HAct"]
        reach = [n for n, ty in binders(self.law) if ty == "M.GSt"]
        if len(acts) != 2 or len(reach) != 2 or [n for n, _ty in binders(self.law)] != [reach[0], acts[0], reach[1], acts[1]]:
            return None
        want = {"ar1", "en1", "s1", "ar2", "en2", "s2", *self.tabs}
        if set(vars_) != want:
            return None
        lines, inst, terms, done = [], {}, {}, {}
        for k, (sn, xn) in enumerate(zip(reach, acts), 1):
            got = self._act(xn, values[xn], done)
            if got is None:
                return None
            ls, ar, en = got
            lines += ls
            inst.update({f"ar{k}": ar, f"en{k}": en, f"s{k}": states[sn]})
            terms[sn], terms[xn] = states[sn], f"M.A_{self.a}{{{ar}, {en}}}"
        inst.update({n: f"t_{n}()" for n in self.tabs})
        com = self._common(tree, leaves, inst)
        if com is None:
            return None
        cl, _lv, kv = com
        lines += cl
        sig = ", ".join(f"+{q}: {sh.qual_type(t)}" for q, t in entry[0])
        vterm = {reach[0]: "s1", reach[1]: "s2", acts[0]: f"M.A_{self.a}{{ar1, en1}}",
                 acts[1]: f"M.A_{self.a}{{ar2, en2}}"}
        lhs = f"kk({', '.join(leaves)})"
        lines += [f"def sz({sig}) -> {{{lhs} == {_call_x(self.law, self.fn, [vterm[reach[0]], vterm[acts[0]], vterm[reach[1]], vterm[acts[1]]], self.tabs)} : Bool}}:\n  {{==}}", ""]
        T = _btxt(self.target)
        order = [terms[n] for n, _ty in binders(self.law)]
        goal = _call_x(self.law, self.fn, order, [f"t_{n}()" for n in self.tabs])
        proof = (f"(%sz({', '.join(inst[q] for q in vars_)}) : {{_ == {T} : Bool}}\n  {kv})")
        return lines, order, goal, proof

    def attribution(self, values: dict):
        sh = self.shape
        pre = "fa" if self.fn == "fact" else "fh"
        split, one = sh.defs.get(f"{pre}2_{self.x}"), f"F.{pre}1_{self.x}"
        step = sh.defs.get("fx_step")
        if split is None or f"{pre}1_{self.x}" not in sh.names or "run_fact" not in sh.names:
            return None
        names = [n for n, _ty in binders(self.law)]
        if [ty for _n, ty in binders(self.law)] != ["List<&2, M.HAct>", "M.HAct"]:
            return None
        pn, yn = names
        vars_ = [q for q, _t in split[0]]
        if vars_ != ["ar", "en", "s", "g", "p", *self.tabs]:
            return None
        tree = _tree(split[1])
        leaves = [sh.qual(l) for l in _leaves(tree)]
        acts, rst = list(values[pn]), self.shape.rstates
        if len(rst) != len(acts):
            return None
        lines, done = [], {}
        got = self._act(yn, values[yn], done)
        if got is None:
            return None
        ls, ar, en = got
        lines += ls
        tabs = [f"t_{n}()" for n in self.tabs]
        for i, a in enumerate(acts):
            lines += [f"def pw_{i}() -> M.HAct:\n  {self.lit.text(a)}", ""]
        for k, r in enumerate(rst, 1):
            f = r.get("f") or {}
            lines += [f"def ps_{k}() -> M.GSt:\n  {self.lit.typed(f['s'], 'GSt')}", "",
                      f"def pg_{k}() -> F.FxG:\n  {self.flit.typed(f['g'], 'FxG')}", ""]
        n = len(acts)
        r0 = "F.FxR{M.gh_s0(), F.fx_g0()}"

        def rlit(k: int) -> str:
            return r0 if k == 0 else f"F.FxR{{ps_{k}(), pg_{k}()}}"
        for k in range(n):
            lines += [f"def q{k}() -> {{{rlit(k + 1)} == F.fx_step({rlit(k)}, pw_{k}(){''.join(', ' + t for t in tabs)}) "
                      f": F.FxR}}:\n  {{==}}", ""]
        P = ("[" + ", ".join(f"pw_{i}()" for i in range(n)) + "]") if n else "Nil{}"
        Y = f"M.A_{self.a}{{{ar}, {en}}}"
        S, G = (f"ps_{n}()", f"pg_{n}()") if n else ("M.gh_s0()", "F.fx_g0()")
        inst = {"ar": ar, "en": en, "s": S, "g": G, "p": P, **{t: f"t_{t}()" for t in self.tabs}}
        com = self._common(tree, leaves, inst)
        if com is None:
            return None
        cl, _lv, kv = com
        lines += cl
        T = _btxt(self.target)
        sig1 = ", ".join(f"+{q}: {sh.qual_type(t)}" for q, t in split[0])
        lines += [f"def sz1({sig1}) -> {{kk({', '.join(leaves)}) == {one}(F.FxR{{s, g}}, M.A_{self.a}{{ar, en}}, p"
                  f"{''.join(', ' + t for t in self.tabs)}) : Bool}}:\n  {{==}}", ""]
        # sz2: the trace's (state, companions) after each step rewritten in, innermost first
        targs = "".join(f", {t}" for t in self.tabs)
        ws = [f"w{i}" for i in range(n)]
        Pv = ("[" + ", ".join(ws) + "]") if n else "Nil{}"

        def rv(k: int) -> str:
            return r0 if k == 0 else f"F.FxR{{S{k}, G{k}}}"
        eqs = [f"e{k}: {{{rv(k + 1)} == F.fx_step({rv(k)}, w{k}{targs}) : F.FxR}}" for k in range(n)]
        sig2 = ", ".join([f"+{w}: M.HAct" for w in ws] + [f"+S{k}: M.GSt, +G{k}: F.FxG" for k in range(1, n + 1)]
                         + ["+y: M.HAct"] + [f"+{t}: List<&2, M.HKB>" for t in self.tabs] + eqs)
        lhs2 = f"{one}({rv(n)}, y, {Pv}{targs})"
        body = "{==}"
        for k in reversed(range(n)):
            inner = "_"
            for j in range(k + 1, n):
                inner = f"F.fx_step({inner}, w{j}{targs})"
            body = f"(%e{k} : {{{lhs2} == {one}({inner}, y, {Pv}{targs}) : Bool}}\n  {body})"
        lines += [f"def sz2({sig2}) -> {{{lhs2} == {_call_x(self.law, self.fn, [Pv, 'y'], self.tabs)} : Bool}}:\n"
                  f"  {body}", ""]
        a2 = [f"pw_{i}()" for i in range(n)] + [x for k in range(1, n + 1) for x in (f"ps_{k}()", f"pg_{k}()")] + [Y] \
            + tabs + [f"q{k}()" for k in range(n)]
        a1 = [inst[q] for q in vars_]
        goal = _call_x(self.law, self.fn, [P, Y], tabs)
        proof = (f"(%sz2({', '.join(a2)}) : {{_ == {T} : Bool}}\n  (%sz1({', '.join(a1)}) : {{_ == {T} : Bool}}\n  {kv}))")
        return lines, [P, Y], goal, proof

    def build(self, states: dict, values: dict):
        try:
            return self.kernel(states, values) if self.shape.subform == "kernel" else self.attribution(values)
        except (KeyError, ValueError, IndexError):
            return None


def _call_x(law: dict, fn: str, names: list[str], tables: list[str]) -> str:
    return f"F.{fn}_{RF.ghost_x(law['law_id'])}(" + ", ".join(list(names) + list(tables)) + ")"


def _body(law: dict, tb: list, prefixes: dict, values: dict, lit: Lit, shape: Shape | None, fn: str,
          target: bool) -> tuple[list[str], list[str], dict, str, str]:
    """The witness's definitions, the binders' terms, their Reach chains, and the closed lemma's left side with its
    proof: by parts when a Shape is given and the form applies, else one computation ({==})."""
    targs = [f"t_{n}()" for n, _h in tb]
    lines, states, chains = _runs(law, tb, prefixes, lit)
    if shape is not None:
        got = _Parts(law, shape, tb, fn, target, lit).build(states, values)
        if got is not None:
            pl, terms, goal, proof = got
            return lines + pl, terms, chains, goal, proof
    bl, terms = _values(law, values, lit, states)
    return lines + bl, terms, chains, _call(law, fn, terms, targs), "{==}"


def counter_proof(law: dict, model_import: str, section_import: str, laws_import: str, hashes: list,
                  prefixes: dict, values: dict, tables: dict, lit: Lit, note: str, shape: Shape | None = None) -> str:
    """The counter-law proof of one witness. prefixes: {Reach binder: (prefix HAct values, the decoded state after each
    prefix step)}; values: the other binders' values (HAct values, or lists of them); tables: the hash tables. cz
    computes fact_<x> at the literals (by parts with a Shape); the counter-law rewrites with it."""
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    lines = _head(model_import, section_import, laws_import) + [f"# class counter: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, terms, chains, goal, proof = _body(law, tb, prefixes, values, lit, shape, "fact", False)
    lines += body
    lines += [f"def cz() -> {{{goal} == False{{}} : Bool}}:\n  {proof}", ""]
    lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
    last = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {_tuple(law, tb, terms, chains, last)}")
    return "\n".join(lines) + "\n"


def inhabitant_proof(law: dict, model_import: str, section_import: str, laws_import: str, hashes: list,
                     prefixes: dict, values: dict, tables: dict, lit: Lit, shape: Shape | None = None) -> str:
    lid = law["law_id"]
    tb = P3.tabs_binders(hashes)
    lines = _head(model_import, section_import, laws_import)
    lines += P3._table_defs(tb, tables, lit)
    body, terms, chains, goal, proof = _body(law, tb, prefixes, values, lit, shape, "fhit", True)
    lines += body
    lines += [f"def ch() -> {{{goal} == True{{}} : Bool}}:\n  {proof}", ""]
    lines.append(f"def Laws.nv_{lid.lower()}():\n  {_tuple(law, tb, terms, chains, 'ch()')}")
    return "\n".join(lines) + "\n"
