def binders(law: dict) -> list[tuple[str, str]]:
    """The law's binders before the hash tables, as (Bend name, Bend type): a Reach binder is a state (M.GSt) whose
    Reach proof r_<name> follows it."""
    out = []
    for b in law["statement"]["binders"]:
        ty = str(b["type"])
        if ty.startswith("Fn<"):
            continue
        if ty == "Reach":
            out.append((b["name"], "M.GSt"))
        elif ty == "Act":
            out.append((b["name"], "M.HAct"))
        elif ty == "Trace":
            out.append((b["name"], "List<&2, M.HAct>"))
        else:
            raise ValueError(f"{law['law_id']}: binder {b['name']}: {ty} has no Bend type here")
    return out


def _call(law: dict, fn: str, names: list[str], tables: list[str]) -> str:
    return f"F.{fn}_{RF.ghost_x(law['law_id'])}(" + ", ".join(names + tables) + ")"


def _decl(law: dict, hashes: list, kw: str, q: str) -> list[str]:
    tb = P3.tabs_binders(hashes)
    idx = "".join(f"{n}, " for n, _h in tb)
    lines = [f"  {kw} {q}{n}: List<&2, M.HKB>" for n, _h in tb]
    for n, ty in binders(law):
        lines.append(f"  {kw} {q}{n}: {ty}")
        if ty == "M.GSt":
            lines.append(f"  {kw} r_{n}: M.Reach<{idx}{n}>")
    return lines


def law_file(law: dict, statement_hash: str, model_import: str, section_import: str, hashes: list,
             counter: bool = False) -> str:
    lid = law["law_id"]
    tb = [n for n, _h in P3.tabs_binders(hashes)]
    kw, q = ("exs", "") if counter else ("for", "+")
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", f"import {section_import} as F", "", f"law {law_name(lid, counter)}:"]
    lines += _decl(law, hashes, kw, q)
    rel = "!=" if counter else "=="
    lines.append(f"  {{{_call(law, 'fact', [n for n, _t in binders(law)], tb)} {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def inhabitant_law(law: dict, statement_hash: str, model_import: str, section_import: str, hashes: list) -> str:
    lid = law["law_id"]
    tb = [n for n, _h in P3.tabs_binders(hashes)]
    x = RF.ghost_x(lid)
    lines = [HEADER, f"# non-vacuity of {lid} (statement_hash {statement_hash}): its premises and antecedent fhit_{x} "
             "are inhabited by a reachable state and step", "import Base", f"import {model_import} as M",
             f"import {section_import} as F", "", f"law nv_{lid.lower()}:"]
    lines += _decl(law, hashes, "exs", "")
    lines.append(f"  {{{_call(law, 'fhit', [n for n, _t in binders(law)], tb)} == True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def _prefix_defs(tag: str, tb: list, acts: list, states: list, lit: Lit) -> tuple[list[str], str, str]:
    """One run's prefix: its actions, the literal state after each step, one lemma per step (r<tag>_k) and the Reach
    chain they make; (lines, the chain, the state after the prefix)."""
    targs = "".join(f", t_{n}()" for n, _h in tb)
    if len(states) != len(acts):
        raise ValueError(f"{len(acts)} prefix steps but {len(states)} states")
    lines = []
    for i, a in enumerate(acts):
        lines += [f"def w{tag}_{i}() -> M.HAct:\n  {lit.text(a)}", ""]

    def st(k: int) -> str:
        return "M.gh_s0()" if k == 0 else f"s{tag}_{k}()"
    for k in range(1, len(acts) + 1):
        lines += [f"def s{tag}_{k}() -> M.GSt:\n  {lit.typed(states[k - 1], 'GSt')}", ""]
    for k in range(len(acts)):
        lines += [f"def r{tag}_{k}() -> {{{st(k + 1)} == M.gh_step(w{tag}_{k}(), {st(k)}{targs}) : M.GSt}}:\n  {{==}}",
                  ""]
    chain = "M.R0{{==}}"
    for k in range(len(acts)):
        chain = f"M.RStep{{w{tag}_{k}(), {st(k)}, {chain}, r{tag}_{k}()}}"
    return lines, chain, st(len(acts))


def _head(model_import: str, section_import: str, laws_import: str) -> list[str]:
    return [PHEADER, "import Base", f"import {model_import} as M", f"import {section_import} as F",
            f"import {laws_import} as Laws", ""]


def _values(law: dict, values: dict, lit: Lit, states: dict) -> tuple[list[str], list[str]]:
    """The binders' terms (a Reach binder: its state's term from states) and the definitions of the others (b_<n>)."""
    lines, terms, seen = [], [], {}
    for n, ty in binders(law):
        if ty == "M.GSt":
            terms.append(states[n])
            continue
        v = values[n]
        key = repr((ty, v))
        if key in seen:                 # a binder with another's value (an inhabitant's x2 = x1) shares its definition
            terms.append(seen[key])
            continue
        seen[key] = f"b_{n}()"
        if ty == "M.HAct":
            text = lit.text(v)
        else:
            text = ("[" + ", ".join(lit.text(a) for a in v) + "]") if v else "Nil{}"
        lines += [f"def b_{n}() -> {ty}:\n  {text}", ""]
        terms.append(f"b_{n}()")
    return lines, terms


def _runs(law: dict, tb: list, prefixes: dict, lit: Lit) -> tuple[list[str], dict, dict]:
    """The prefix definitions of each Reach binder (equal prefixes share one), its state term and its chain."""
    lines, states, chains, done = [], {}, {}, {}
    for i, (n, ty) in enumerate(binders(law)):
        if ty != "M.GSt":
            continue
        acts, sts = prefixes[n]
        key = repr((acts, sts))
        if key not in done:
            body, chain, state = _prefix_defs(str(len(done) + 1), tb, acts, sts, lit)
            lines += body
            done[key] = (chain, state)
        chains[n], states[n] = done[key]
    return lines, states, chains


def _tuple(law: dict, tb: list, terms: list[str], chains: dict, last: str) -> str:
    """The existential tuple: the tables, then each binder (a Reach binder with its chain), then the last component."""
    names = [n for n, _t in binders(law)]
    tup = last
    for n, t in reversed(list(zip(names, terms))):
        if n in chains:
            tup = f"({t}, ({chains[n]}, {tup}))"
        else:
            tup = f"({t}, {tup})"
    for n, _h in reversed(tb):
        tup = f"(t_{n}(), {tup})"
    return tup


