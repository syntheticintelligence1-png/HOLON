"""The Bend files of a FACT law (BUILD_PLAN I26; the contract is the docstring of tests_m3/test_fact.py, "Laws" and
"Deciding").

  law_file(..)        gen/<M>/laws/<id>/LAWS.bend: the law (forall the hash tables and the law's binders, each Reach
                      binder a state with its Reach proof: fact_<x>(..) == True), or for a REFUTED law its counter-law
                      (exists ..: fact_<x>(..) != True); it imports the typed model as M and the FACT section as F, and
                      declares exactly one law
  counter_proof(..)   a counter-law proof at a concrete witness: the hash tables, the literal state after each prefix
                      step of each run with its one-step lemma and the Reach chain they make (holon.undo.proofs' shape),
                      the witness's steps as literals, and one closed lemma cz: fact_<x> is false at them
  inhabitant_law(..), inhabitant_proof(..)
                      gen/<M>/<id>/nonvac/: a kernel law's reachable state and step at which fhit_<x> (the premises and
                      the antecedent, both runs the same step from the same state) is true (G11V), in the same shape

Every computation is a closed lemma (r_k one prefix step, cz or ch the law's function at the literals); the
counter-law only rewrites with cz under its binder. Witness literals are data. Nothing here names a target.

By parts (BendTT's pinned fuel, Q22). One closed lemma that evaluates the whole function at the witness can exceed
BendTT's fuel while each of its parts fits (two successful calls and the commitments after both are four evaluations of
the action). With a Shape (the section's text), cz and ch are built from parts instead:
  kk(c..)       the split function's connective skeleton (fx_k3, fx_imp, Bool.and, Bool.not) over its leaves
  l<i>          one closed lemma per leaf: its value at the literals, {==}
  kv(c.., e..)  the skeleton at those values is the law's value, over Bool variables
  sz, sz1, sz2  over variables, where evaluation stops at a variable: the law's function equals kk of its leaves
                (a kernel law: fact or fhit at two calls of the action, through fk2/fh2; an attribution law: fa1/fh1 at
                (s, g) and a call of the action, then fact or fhit at a trace whose state and companions after each
                step are rewritten in, one step lemma q<k> each)
Each kernel conversion then compares terms that are syntactically equal or stuck at the same variable; the leaf values
are the ones the skeleton forces for the law's value (a unique assignment, or the closed lemma as before).
"""
