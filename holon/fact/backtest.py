"""The FACT back-test against M1 (BUILD_PLAN I26 and §2 invariant 7; the contract is the docstring of
tests_m3/test_fact.py, "Back-test against M1", rules FB1-FB4).

  holon fact --milestone M3 --backtest   writes results/M3/fact/backtest.json and gen/M3/fact/backtest/

FB1  the map is the FACT sidecar's "backtest" (fixed at the prereg), read and never recomputed.
FB2  witness transfer: when the M1 law and its analogue are both REFUTED, the analogue's witness moves to the M1 model's
     inputs by the map's move (principals by the binding's table, the owner the one caller of the deployment's calls;
     the clock by the offset, with wait steps joining the shared prefix; blob hashes to tokens; the commit input's fields
     to the M1 act), and the M1 law's counter-law at the moved witness (the law text of gen/M1/<old>/LAWS.bend, its
     model import moved) is written to gen/M3/fact/backtest/W_<old>/ and must be accepted by Bend.
FB3  the CF bridge: CF(fn, S), S the distinct blob-token lists of the moved commit acts, stated for every pair of
     distinct elements and proved by evaluation in gen/M3/fact/backtest/CF_<fn>_<old>/, accepted by Bend.
FB4  the table: acceptance "witness" iff both are REFUTED and both bridges check; otherwise an open gap of kind
     "implication".

The back-test reads laws/M1/<old>.json's record and law file, results/M1/<old>.json, the M1 model and the analogue's
record; no hand fact document. Nothing here names a target.
"""
from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path

from .. import bend
from ..rules import fact as RF

HEADER = "# GENERATED by holon.fact.backtest; untrusted, accepted only if Bend checks it."
COMMIT_ACTS = ("commit",)          # M1 acts whose blob lists the CF bridge covers: those whose op starts with these


def canon(o) -> str:
    return json.dumps(o, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _num(v) -> int:
    if isinstance(v, bool):
        return int(v)
    if isinstance(v, str):
        return int(v, 16) if v.lower().startswith("0x") else int(v)
    return int(v)


def blob_token(h, mv: dict):
    """A blob versioned hash as an M1 blob token (the map's table, else blobEnc's inverse), or None."""
    n = _num(h)
    tab = {_num(k): v for k, v in (mv.get("blob_tokens") or {}).items()}
    if n in tab:
        return tab[n]
    if (n >> 248) == 0x01 and (n & ((1 << 248) - 1)) not in tab.values():
        return n & ((1 << 248) - 1)
    return None


def deployment_owner(root: Path, milestone: str, model: str) -> str | None:
    """The principal that deployed and configured the contract: the one caller of every call of the typed model's
    initial state (gen/<M>/sorts/models/<model>.init.json); None when the calls have several callers."""
    p = Path(root) / "gen" / milestone / "sorts" / "models" / f"{model}.init.json"
    try:
        calls = json.loads(p.read_text())["calls"]
    except (OSError, ValueError, KeyError):
        return None
    callers = {str(c.get("caller")).lower() for c in calls}
    return callers.pop() if len(callers) == 1 else None


def input_of(step: dict) -> dict | None:
    """A commit step's input struct (the action's one struct argument), or None."""
    args = step.get("args")
    vals = list(args.values()) if isinstance(args, dict) else list(args or [])
    if len(vals) == 1 and isinstance(vals[0], dict):
        return vals[0]
    return None


def move_kernel_witness(w: dict, mv: dict, owner: str | None, acts: set) -> dict | None:
    """The M1 inputs (p, c1, c2) of a kernel witness under the map's move; None when the two runs do not share their
    prefix or a value has no M1 image."""
    runs = w["runs"]
    if canon(runs[0]["prefix"]) != canon(runs[1]["prefix"]):
        return None
    prin = {k.lower(): v for k, v in (mv.get("principals") or {}).items()}
    if owner is not None:
        prin[owner.lower()] = mv["owner_token"]
    clock = [int(mv["m1_clock0"])]

    def act(step: dict, out: list) -> None:
        env = step["env"]
        t = int(env["block.timestamp"]) - int(mv["clock_offset"])
        if t > clock[0]:
            out.append({"op": "wait", "dt": t - clock[0]})
            clock[0] = t
        who = prin.get(str(env["caller"]).lower())
        if who is None:
            raise KeyError(env["caller"])
        name = step["action"]
        x = input_of(step)
        if name not in acts or x is None:
            raise KeyError(name)
        hdr = str(x["parentBatchHeader"])[2:]
        toks = [blob_token(h, mv) for h in env.get("blobhash") or []]
        if None in toks:
            raise KeyError("blob")
        out.append({"op": name, "who": who, "ver": _num(x["version"]), "parent": int(hdr[2:18], 16),
                    "n": _num(x["numL1Messages"]), "lbn": _num(x["lastBlockNumber"]), "prev": _num(x["prevStateRoot"]),
                    "post": _num(x["postStateRoot"]), "blobs": toks})
    try:
        p: list = []
        for s in runs[0]["prefix"]:
            act(s, p)
        pre = clock[0]
        c1: list = []
        act(runs[0]["x"], c1)
        clock[0] = pre
        c2: list = []
        act(runs[1]["x"], c2)
    except (KeyError, ValueError, TypeError):
        return None
    w1 = [x for x in c1 if x["op"] == "wait"]
    w2 = [x for x in c2 if x["op"] == "wait"]
    if canon(w1) != canon(w2):
        return None
    return {"p": p + w1, "c1": c1[-1], "c2": c2[-1]}


# ------------------------------------------------------------------------------------------------ Bend text
def act_fields(model_text: str) -> dict:
    """The M1 model's action constructors: {op: [(field, type)]} from `type HAct`."""
    m = re.search(r"(?ms)^type HAct is Data:\n((?:  \w+\{[^\n]*\}\n)+)", model_text)
    if not m:
        raise ValueError("the M1 model declares no HAct")
    out = {}
    for line in m.group(1).splitlines():
        c = re.match(r"\s*A_(\w+)\{(.*)\}\s*$", line)
        if c:
            fs = [p.strip() for p in c.group(2).split(",") if p.strip()]
            out[c.group(1)] = [(f.split(":")[0].strip(), f.split(":", 1)[1].strip()) for f in fs]
    return out


def lit(v, ty: str) -> str:
    ty = ty.strip()
    if ty == "Nat":
        return f"{int(v)}n"
    if ty == "Bool":
        return "True{}" if v else "False{}"
    if ty.startswith("List<") and ty.endswith(">"):
        el = ty[ty.index(",") + 1:-1].strip() if "," in ty else ty[5:-1]
        return ("[" + ", ".join(lit(x, el) for x in v) + "]") if v else "Nil{}"
    raise ValueError(f"no M1 literal of type {ty}")


def act_lit(a: dict, fields: dict) -> str:
    fs = fields.get(a["op"])
    if fs is None:
        raise ValueError(f"the M1 model has no act {a['op']}")
    return f"M.A_{a['op']}{{" + ", ".join(lit(a[f], t) for f, t in fs) + "}"


EQFN = {"List<&2, Nat>": "M.eq_list_nat", "Nat": "Nat.is_eq", "Bool": "M.eq_bool"}


def counter_law_files(old_laws: str, model_import: str, moved: dict, fields: dict) -> tuple[str, str, str]:
    """(LAWS.bend, PROOF.bend, the law's name) of the M1 counter-law at the moved witness: the law text of the M1 law
    file with its model import moved, and a proof giving the witness for each exists binder, {==} for each premise and
    the claim's two sides separated through the model's equality function (the M1 counter proofs' shape)."""
    lines = old_laws.splitlines()
    law_at = next(i for i, ln in enumerate(lines) if re.match(r"^law\s+\w+\s*:", ln))
    name = re.match(r"^law\s+(\w+)\s*:", lines[law_at]).group(1)
    head = [ln for ln in lines[:law_at] if not ln.startswith("import ") and not ln.startswith("#")]
    laws = "\n".join([HEADER.replace("untrusted, accepted only if Bend checks it", "the M1 law of the back-test"),
                      "import Base", f"import {model_import} as M"] + head + lines[law_at:]) + "\n"
    parts, claim = [], None
    for ln in lines[law_at + 1:]:
        s = ln.strip()
        m = re.match(r"^exs\s+(\w+)\s*:\s*(.*)$", s)
        if m:
            n, ty = m.group(1), m.group(2)
            if ty.startswith("{"):
                parts.append("{==}")
            elif n in moved:
                v = moved[n]
                if ty.startswith("List<"):
                    parts.append(("[" + ", ".join(act_lit(a, fields) for a in v) + "]") if v else "Nil{}")
                else:
                    parts.append(act_lit(v, fields))
            else:
                raise ValueError(f"no moved value for the binder {n}")
            continue
        m = re.match(r"^\{(.*)\s!=\s(.*)\s:\s(.*)\}$", s)
        if m:
            claim = m.groups()
    if claim is None:
        raise ValueError("the M1 law is not a counter-law with a disequality claim")
    lhs, _rhs, ty = claim
    eq = EQFN.get(ty.strip())
    if eq is None:
        raise ValueError(f"no equality function for {ty}")
    for n, v in moved.items():
        val = (("[" + ", ".join(act_lit(a, fields) for a in v) + "]") if v else "Nil{}") if isinstance(v, list) \
            else act_lit(v, fields)
        lhs = re.sub(rf"(?<![\w.]){re.escape(n)}(?![\w(])", val, lhs)
    tup = f"e => (%e : M.is_true({eq}(_, {lhs}))\n  Unit{{}})"
    for p in reversed(parts):
        tup = f"({p}, {tup})"
    proof = "\n".join([HEADER, "import Base", f"import {model_import} as M", "import ./LAWS.bend as Laws", "",
                       "# class counter: the moved witness, premises by computation, sides separated by an equality "
                       "function", f"def Laws.{name}():", f"  {tup}"]) + "\n"
    return laws, proof, name


def cf_files(fn: str, ver: str, S: list, model_import: str, old: str) -> tuple[str, str]:
    """CF(fn, S) by computation: one law per pair of distinct elements of S, M.d_blob_hash(ver, a) != (.., b)."""
    pairs = [(i, j) for i in range(len(S)) for j in range(i + 1, len(S))]
    laws = [HEADER.replace("untrusted, accepted only if Bend checks it", f"CF({fn}, S) of the {old} back-test"),
            "import Base", f"import {model_import} as M", ""]
    proof = [HEADER, "import Base", f"import {model_import} as M", "import ./LAWS.bend as Laws", ""]
    for i, j in pairs:
        a, b = lit(S[i], "List<&2, Nat>"), lit(S[j], "List<&2, Nat>")
        name = f"cf_{fn}_{i}_{j}"
        laws += [f"law {name}:", f"  {{M.d_blob_hash({ver}, {a}) != M.d_blob_hash({ver}, {b}) : Nat}}", ""]
        proof += [f"def Laws.{name}():", f"  e => (%e : M.is_true(Nat.is_eq(_, M.d_blob_hash({ver}, {a})))\n  Unit{{}})",
                  ""]
    return "\n".join(laws), "\n".join(proof)


def _check(d: Path, laws: str, proof: str, names: list) -> tuple[str, str]:
    """Write and check a LAWS/PROOF pair: ("checked" | "rejected", detail)."""
    shutil.rmtree(d, ignore_errors=True)
    d.mkdir(parents=True, exist_ok=True)
    (d / "LAWS.bend").write_text(laws, encoding="utf-8")
    (d / "PROOF.bend").write_text(proof, encoding="utf-8")
    declared = re.findall(r"(?m)^law\s+(\w+)\s*:", laws)
    if sorted(declared) != sorted(names) or bend.escape_hatches(laws + proof):
        return "rejected", f"declares {declared}"
    r = bend.check(d / "PROOF.bend")
    return ("checked", r.marker) if r.ok else ("rejected", r.first_line)


# ------------------------------------------------------------------------------------------------ the table
def build(milestone: str, root: Path, sc) -> dict:
    root = Path(root)
    bt = sc.backtest or {}
    against = bt.get("against")
    mv = bt.get("move") or {}
    out_dir = root / "gen" / milestone / "fact" / "backtest"
    model_path = root / str(mv.get("model"))
    model_text = model_path.read_text(encoding="utf-8")
    fields = act_fields(model_text)
    cf = bt.get("cf_bridge") or {}
    rows, gaps = [], []
    for row in bt.get("rows") or []:
        old, new = row["old"], row["new"]
        old_rec = json.loads((root / "results" / str(against) / f"{old}.json").read_text())
        np = root / "results" / milestone / f"{new}.json"
        new_rec = json.loads(np.read_text()) if np.is_file() else {}
        old_st, new_st = old_rec.get("status"), new_rec.get("status")
        r = {"old": old, "old_status": old_st, "old_statement_hash": old_rec.get("statement_hash"), "new": new,
             "new_status": new_st, "same_status": old_st == new_st, "moved": None,
             "witness_transfer": {"law": None, "status": None}, "cf_bridge": {"fn": cf.get("fn"), "set": None,
                                                                              "law": None, "status": None},
             "acceptance": None, "implication": "missing", "gap": None}
        why = None
        if old_st == "REFUTED" and new_st == "REFUTED":
            de = {e["law_id"]: e for e in json.loads((root / "laws" / milestone / "DERIVATION.json").read_text())
                  ["laws"]}.get(new) or {}
            model = RF.model_of(str(de.get("facts") or ""))
            acts = {(de.get("basis") or {}).get("action")}
            moved = move_kernel_witness(new_rec["witness"], mv, deployment_owner(root, milestone, model), acts)
            r["moved"] = moved
            if moved is None:
                why = "the analogue's witness does not move to the M1 inputs"
            else:
                d = out_dir / f"W_{old}"
                imp = os.path.relpath(model_path, d).replace(os.sep, "/")
                old_laws = (root / "gen" / str(against) / old / "LAWS.bend").read_text(encoding="utf-8")
                sh = old_rec.get("statement_hash")
                if sh and sh not in old_laws:
                    why = f"gen/{against}/{old}/LAWS.bend is not the law of the record's statement hash"
                else:
                    try:
                        laws, proof, name = counter_law_files(old_laws, imp, moved, fields)
                        st, det = _check(d, laws, proof, [name])
                    except (ValueError, StopIteration, KeyError) as e:
                        st, det = "rejected", str(e)
                    r["witness_transfer"] = {"law": f"gen/{milestone}/fact/backtest/W_{old}/LAWS.bend", "status": st}
                    if st != "checked":
                        why = f"the M1 counter-law at the moved witness is rejected: {det}"
                    commits = [a for a in moved["p"] + [moved["c1"], moved["c2"]]
                               if str(a.get("op", "")).startswith(COMMIT_ACTS)]
                    S = [json.loads(x) for x in sorted({canon(a["blobs"]) for a in commits})]
                    dc = out_dir / f"CF_{cf.get('fn')}_{old}"
                    imp2 = os.path.relpath(model_path, dc).replace(os.sep, "/")
                    cl, cp = cf_files(str(cf.get("fn")), "2n", S, imp2, old)
                    names = [f"cf_{cf.get('fn')}_{i}_{j}" for i in range(len(S)) for j in range(i + 1, len(S))]
                    cst, cdet = _check(dc, cl, cp, names) if names else ("checked", "a single element")
                    r["cf_bridge"] = {"fn": cf.get("fn"), "set": S,
                                      "law": f"gen/{milestone}/fact/backtest/CF_{cf.get('fn')}_{old}/LAWS.bend",
                                      "status": cst}
                    if cst != "checked" and why is None:
                        why = f"CF({cf.get('fn')}, S) is not checked: {cdet}"
        else:
            why = f"the statuses are {old_st} (M1) and {new_st} (M3): the witness transfer needs both REFUTED"
        if why is None:
            r["acceptance"], r["implication"] = "witness", "accepted"
        else:
            gid = f"BT-{old}"
            r["gap"] = gid
            gaps.append({"id": gid, "kind": "implication", "old": old, "new": new, "why": why})
        rows.append(r)
    return {"document": "fact_backtest", "milestone": milestone, "against": against,
            "map": {"path": sc.rel, "sha256": RF.sha256_bytes(sc.path.read_bytes())}, "rows": rows,
            "gaps": gaps, "complete": not gaps, "exit_blockers": [g["id"] for g in gaps]}


def write(milestone: str, root: Path, sc) -> dict:
    b = build(milestone, root, sc)
    p = Path(root) / "results" / milestone / "fact" / "backtest.json"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(RF.dumps(b), encoding="utf-8")
    return b
