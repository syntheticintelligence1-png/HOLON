"""The FACT section over I30's typed model (BUILD_PLAN I26; the contract is the docstring of tests_m3/test_fact.py, "Laws":
the semantics of fact_<x>, the chooser companion and fhit_<x>).

  gen/<M>/fact/models/<model>.fact.bend   imports the typed model gen/<M>/sorts/models/<model>.bend as M and defines

  the premises (F8)  fx_wf(xs): every entry of a blob-hash list is a nonzero word (not equal to the zero word) whose top
                     byte is 0x01; fx_cf(t): CF over a hash table (two entries with one value have one key: the table
                     holds the keys the law's steps hash); fx_nz(t): no entry of a table is the zero word; fx_hyp_<i>():
                     a closed premise hypothesis, the document constant against the sidecar's recorded value
  kernel laws        fact_<x>(s1, x1, s2, x2, tables): if the premises hold, x1 and x2 are calls of the action, both
                     succeed (x1 from s1, x2 from s2) and the commitment F at x1's write key after x1 equals F at x2's
                     write key after x2, then blobs(x1) == blobs(x2); otherwise true. fhit_<x>: the premises and that
                     antecedent (G11V's non-vacuity target)
  -- the ghost marker: nothing above it names what follows --
  chooser_<P>        a ghost companion per pinned family P (Prop 6.19 augmentation; never read by real code): key ->
                     address or bottom, bottom everywhere initially; each whole write of P at key k a successful step
                     makes sets it to the step's caller when the taken branch is fresh and not the literal 0, bottom
                     when it is the literal 0, and leaves it on a copy
  run_fact           the state and the companions after a trace from Reach's initial state (a reverted step changes
                     neither: the typed model's gh_step)
  attribution laws   fact_<x>(p, y, tables): with (s, g) after p, if the premises hold and y is a call of w that succeeds
                     from s and writes P at key k by its copy branch (the pin), then g_P[k] is bottom or A[k].m after y
                     equals g_P[k]; otherwise true. fhit_<x>: the premises, y succeeding through the pin, g_P[k] not bottom

The kernel claim is fx_k3(d, o1, o2, pt, c): (o1 and o2 and pt and c) implies d, matched in that order, with d the
consumers' equality, o1 and o2 each run's blobs_wf and success (fx_ok_<x>), pt the table premises and the closed
hypotheses, c equal commitments; a step is taken apart through fx_sel_<a> (a call of the action or not). A proof
splits on each argument in turn.

Above them, holon.undo.trace's observation of one step (ux_ostep: success, data, logs, and the state after it), what
the replay compares with the real contract; fx_cmw_<x> (the committed word) and fx_who_<x> (the chooser at the key y
pins) are what the replay and the record report.

combined_text(): the same definitions unqualified after the typed model's text, one module for the evaluator
(holon.sorts.evaluate3), so the search evaluates fact_<x> exactly as Bend states it. Nothing here names a target.
"""
from __future__ import annotations

from ..machine_bend import bname
from ..rules import fact as RF
from ..sorts.model3 import GenError, wlit
from ..undo import trace as T

HEADER = "# GENERATED by holon.fact.section from the extracted document and the FACT laws; do not edit."
SECTION_VERSION = "holon-fact-section/0.1"
GHOST_MARKER = "# ---- GHOST: the chooser companions and what reads them (no definition above names them) ----"
TOP_MASK, TOP_ONE = 0xFF000000, 0x01000000      # the top byte of a word's highest 32-bit limb, and 0x01 there


def _copy_path(v, C):
    """The value's branch structure toward the copy C: True when v is C, False when v holds no C, else ("?", c, t, e)."""
    if v == C:
        return True
    if RF.is_op(v, "?") and len(v) == 4:
        t, e = _copy_path(v[2], C), _copy_path(v[3], C)
        if t is False and e is False:
            return False
        return ("?", v[1], t, e)
    return False


def _zero_path(v):
    """The branch structure toward the literal 0 (a clear), in the same form."""
    if v == 0 and not isinstance(v, bool):
        return True
    if RF.is_op(v, "?") and len(v) == 4:
        t, e = _zero_path(v[2]), _zero_path(v[3])
        if t is False and e is False:
            return False
        return ("?", v[1], t, e)
    return False


class Section(T.Trace):
    """The FACT section of one document's typed model."""

    def __init__(self, mm, model_text: str, doc: dict, hashes: list, elements: list, hypotheses: dict):
        super().__init__(mm, model_text, doc, hashes, elements)
        self.hyps = dict(hypotheses or {})
        self.options: set = set()
        self.pinned = sorted({e["basis"]["content"] for e in elements if e["subform"] == "attribution"})

    # ---------------------------------------------------------- helpers
    def tab_args(self) -> str:
        return ", ".join(p for p, _h in self.hp)

    def cond_bool(self, action: str, term) -> str:
        """A document condition of `action` as a Bool in the action's pre-context x (nonzero is true)."""
        return f"{self.Q('w_nz')}({self.compile_word(action, term)})"

    def branch_bool(self, action: str, path) -> str:
        """A _copy_path / _zero_path structure as a Bool in the action's context x."""
        if path is True:
            return "True{}"
        if path is False:
            return "False{}"
        _q, c, t, e = path
        return f"fx_ite({self.cond_bool(action, c)}, {self.branch_bool(action, t)}, {self.branch_bool(action, e)})"

    def wkey(self, action: str, at: str):
        a = self.by_name[bname(action)]
        w = a["writes"][int(at[len("writes["):-1])]
        k, whole = RF.wkey(w)
        if not whole or k is None:
            raise GenError(f"{action} {at}: not a whole keyed write")
        return w, k

    def reg_words(self, f: str, st: str, key: str) -> list[str]:
        """The raw words of F's register at key in state st (one per slot of its value type)."""
        _slot, _kt, _vt, n = self.slots_of(f)
        return [f"{self.Q('sload')}({st}, {self.reg_slot(f, key, i)})" for i in range(n)]

    def member_word(self, f: str, member: str, st: str, key: str) -> str:
        """The value of member m of F's struct register at key, in state st, as a word."""
        fam = self.family(f)
        t = self.mm.m.type_of(fam.type)
        vt = self.mm.m.type_of(t["value"])
        mem = next((m for m in vt.get("members") or [] if m.get("label") == member), None)
        if mem is None:
            raise GenError(f"{f}: no member {member}")
        slot = self.reg_slot(f, key, int(mem["slot"]))
        code = self.code(self.mm.read_word(st, slot, int(mem.get("offset") or 0), mem["type"]))
        used = {n for n in __import__("re").findall(r"(?<![\w.])([A-Za-z_]\w*)\s*[({]", code)}
        missing = sorted(n for n in used if n not in self.names and n not in ("Nil", "Con", "True", "False", "st", "k"))
        if missing:
            raise GenError(f"{f}.{member}: the read needs definitions the typed model does not hold ({missing})")
        return code

    def and_all(self, terms: list[str]) -> str:
        out = "True{}"
        for t in reversed(terms):
            out = t if out == "True{}" else f"Bool.and({t}, {out})"
        return out

    # ---------------------------------------------------------- the fixed part
    def fixed(self) -> None:
        W, HKB = self.Q("W"), self.Q("HKB")
        self.add("def fx_imp(c: Bool, b: Bool) -> Bool:\n  match c:\n    case True{}:\n      b\n    case False{}:\n"
                 "      True{}")
        self.add("def fx_ite(c: Bool, a: Bool, b: Bool) -> Bool:\n  match c:\n    case True{}:\n      a\n"
                 "    case False{}:\n      b")
        self.add("# the kernel claim (o1 and o2 and pt and c) implies d: d the consumers' equality, o1 and o2 each run's\n"
                 "# blobs_wf and success, pt the table and closed premises, c equal commitments (matched in that order)\n"
                 "def fx_k3(d: Bool, o1: Bool, o2: Bool, pt: Bool, c: Bool) -> Bool:\n  match d:\n    case True{}:\n"
                 "      True{}\n    case False{}:\n      match o1:\n        case False{}:\n          True{}\n"
                 "        case True{}:\n          match o2:\n            case False{}:\n              True{}\n"
                 "            case True{}:\n              match pt:\n                case False{}:\n"
                 "                  True{}\n                case True{}:\n                  Bool.not(c)")
        self.add(f"def fx_ws_eq(a: List<&2, {W}>, b: List<&2, {W}>) -> Bool:\n  match a b:\n"
                 "    case Nil{} Nil{}:\n      True{}\n    case Nil{} Con{y, ys}:\n      False{}\n"
                 "    case Con{x, xs} Nil{}:\n      False{}\n    case Con{x, xs} Con{y, ys}:\n"
                 f"      Bool.and({self.Q('w_eq')}(x, y), fx_ws_eq(xs, ys))")
        self.add(f"# the top byte of a word is 0x01\ndef fx_top(w: {W}) -> Bool:\n  match w:\n"
                 f"    case {W}{{a0, a1, a2, a3, a4, a5, a6, a7}}:\n"
                 f"      U32.is_eq(U32.and(a7, {TOP_MASK}), {TOP_ONE})")
        self.add("# blobs_wf on one entry: z is whether the entry is the zero word, rest the rest of the check\n"
                 "def fx_wfw(z: Bool, rest: Bool) -> Bool:\n  match z:\n    case True{}:\n"
                 "      False{}\n    case False{}:\n      rest")
        self.add(f"# blobs_wf: every entry of a blob-hash list is a nonzero word whose top byte is 0x01\n"
                 f"def fx_wf(xs: List<&2, {W}>) -> Bool:\n  match xs:\n    case Nil{{}}:\n      True{{}}\n"
                 f"    case Con{{+h, t}}:\n      fx_wfw({self.Q('w_eq')}(h, {self.Q('w0')}()), Bool.and(fx_top(h), fx_wf(t)))")
        self.add(f"# NZ over one hash table: no entry is the zero word\ndef fx_nz(xs: {self.ht()}) -> Bool:\n"
                 f"  match xs:\n    case Nil{{}}:\n      True{{}}\n    case Con{{h, t}}:\n      match h:\n"
                 f"        case {HKB}{{b, v}}:\n          Bool.and({self.Q('w_nz')}(v), fx_nz(t))")
        self.add(f"# CF of one entry against the rest of a table: an equal value has an equal key\n"
                 f"def fx_cf1(+b: List<&2, U32>, +v: {W}, xs: {self.ht()}) -> Bool:\n  match xs:\n"
                 f"    case Nil{{}}:\n      True{{}}\n    case Con{{h, t}}:\n      match h:\n"
                 f"        case {HKB}{{b2, v2}}:\n          Bool.and(fx_imp({self.Q('w_eq')}(v, v2), "
                 f"{self.Q('b_eq')}(b, b2)), fx_cf1(b, v, t))")
        self.add(f"# CF over a hash table: two entries with one value have one key\ndef fx_cf(xs: {self.ht()}) -> Bool:\n"
                 f"  match xs:\n    case Nil{{}}:\n      True{{}}\n    case Con{{h, +t}}:\n      match h:\n"
                 f"        case {HKB}{{b, v}}:\n          Bool.and(fx_cf1(b, v, t), fx_cf(t))")
        tabs = []
        for p, _h in self.hp:
            tabs += [f"fx_cf({p})", f"fx_nz({p})"]
        sig = ", ".join(f"+{p}: {self.ht()}" for p, _h in self.hp)
        self.add(f"# the table premises: cf and nz of every hash table\ndef fx_tabs({sig}) -> Bool:\n  "
                 f"{self.and_all(tabs)}")
        doc_consts = self.doc.get("constants") or {}
        self.hyp_fns: dict = {}
        for i, (hid, h) in enumerate(sorted(self.hyps.items())):
            if h.get("role") != "premise" or not h.get("constant"):
                continue
            c = doc_consts.get(h["constant"])
            n = RF.MF._int(c) if hasattr(RF, "MF") else None
            if n is None or h.get("value") is None:
                continue
            fn = f"fx_hyp_{i}"
            self.hyp_fns[hid] = fn
            self.add(f"# premise hyp:{hid}: the document constant {h['constant']} is the recorded value\n"
                     f"def {fn}() -> Bool:\n  {self.Q('w_eq')}({self.code(wlit(n))}, {self.code(wlit(int(h['value'], 16)))})")

    def premise_terms(self, e: dict, lists: list[str]) -> list[str]:
        """The law's premises over the blob-hash lists of its steps: blobs_wf of each list, the tables, the hyp ones."""
        out = [f"fx_wf({x})" for x in lists]
        out.append(f"fx_tabs({self.tab_args()})")
        for p in e["premises"]:
            if p.startswith("hyp:"):
                fn = self.hyp_fns.get(p[4:])
                if fn is None:
                    raise GenError(f"{e['law_id']}: premise {p} has no closed definition")
                out.append(f"{fn}()")
        return out

    # ---------------------------------------------------------- kernel laws
    def option(self, a: str) -> None:
        """FxO_<a>: a step that is a call of action a (its arguments and environment) or not one."""
        if a in self.options:
            return
        self.options.add(a)
        AR, HEnv, HAct = self.Q(f"AR_{a}"), self.Q("HEnv"), self.Q("HAct")
        self.add(f"# a step as a call of {a}, or not one\ntype FxO_{a} is Data:\n  FxS_{a}{{ar: {AR}, en: {HEnv}}}\n"
                 f"  FxN_{a}{{}}")
        cases = []
        for c in self.actions:
            if c == a:
                cases.append(f"    case {self.Q(f'A_{c}')}{{ar, en}}:\n      FxS_{a}{{ar, en}}")
            else:
                cases.append(f"    case {self.Q(f'A_{c}')}{{ar, en}}:\n      FxN_{a}{{}}")
        self.add(f"def fx_sel_{a}(x: {HAct}) -> FxO_{a}:\n  match x:\n" + "\n".join(cases))

    def kernel(self, e: dict) -> None:
        x = RF.ghost_x(e["law_id"])
        b = e["basis"]
        a = bname(b["action"])
        F = b["commitment"]
        _w, key = self.wkey(b["action"], b["at"])
        GSt, W = self.Q("GSt"), self.Q("W")
        X = self.Q(f"X_{a}")
        self.option(a)
        self.add(f"# the key {b['action']} writes {F} at ({b['at']}), in its context\n"
                 f"def fx_key_{x}(+x: {X}) -> {W}:\n  {self.compile_word(b['action'], key)}")
        ws1 = self.reg_words(F, "st1", "k1")
        ws2 = self.reg_words(F, "st2", "k2")
        eqs = [f"{self.Q('w_eq')}({u}, {v})" for u, v in zip(ws1, ws2)]
        self.add(f"# {F} at k1 in st1 equals {F} at k2 in st2\ndef fx_cmeq_{x}(+st1: {self.Q('HSt')}, +k1: {W}, "
                 f"+st2: {self.Q('HSt')}, +k2: {W}{self.hsig()}) -> Bool:\n  {self.and_all(eqs)}")
        self.add(f"# the first word of {F} at k in st (the committed value the replay reports)\n"
                 f"def fx_cmw_{x}(+st: {self.Q('HSt')}, +k: {W}{self.hsig()}) -> {W}:\n  {self.reg_words(F, 'st', 'k')[0]}")
        st = self.Q("gh_get_st")
        hs = self.hargs()
        AR, HEnv = self.Q(f"AR_{a}"), self.Q("HEnv")
        run = f"+ar: {AR}, +en: {HEnv}, +s: {GSt}{self.hsig()}"
        self.add(f"# the call (ar, en) of {b['action']} succeeds from s\ndef fx_s_{x}({run}) -> Bool:\n"
                 f"  U32.is_eq({self.Q(f'gx_{a}_cd')}({self.Q(f'xr_{a}')}({st}(s), ar, en{hs})), 0)")
        self.add(f"# one run's part of the premises (blobs_wf of its list) and its success\n"
                 f"def fx_ok_{x}(b: List<&2, {W}>, {run}) -> Bool:\n  Bool.and(fx_wf(b), fx_s_{x}(ar, en, s{hs}))")
        pt = self.premise_terms(e, [])
        self.add(f"# the premises on the tables and the closed hypotheses\ndef fx_pt_{x}({self.hsig()[2:]}) -> Bool:\n"
                 f"  {self.and_all(pt)}")
        two = f"+ar1: {AR}, +en1: {HEnv}, +s1: {GSt}, +ar2: {AR}, +en2: {HEnv}, +s2: {GSt}{self.hsig()}"
        post1 = f"{st}({self.Q(f'gh_go_{a}')}({self.Q(f'xr_{a}')}({st}(s1), ar1, en1{hs}), s1))"
        post2 = f"{st}({self.Q(f'gh_go_{a}')}({self.Q(f'xr_{a}')}({st}(s2), ar2, en2{hs}), s2))"
        k1 = f"fx_key_{x}({self.Q(f'x0_{a}')}({st}(s1), ar1, en1{hs}))"
        k2 = f"fx_key_{x}({self.Q(f'x0_{a}')}({st}(s2), ar2, en2{hs}))"
        self.add(f"# the commitments after the two calls, at their write keys, are equal\ndef fx_c_{x}({two}) -> Bool:\n"
                 f"  fx_cmeq_{x}({post1}, {k1}, {post2}, {k2}{hs})")
        args = f"ar1, en1, s1, ar2, en2, s2{hs}"
        self.add(f"def fk3_{x}(+b1: List<&2, {W}>, +b2: List<&2, {W}>, {two}) -> Bool:\n"
                 f"  fx_k3(fx_ws_eq(b1, b2), fx_ok_{x}(b1, ar1, en1, s1{hs}), fx_ok_{x}(b2, ar2, en2, s2{hs}), "
                 f"fx_pt_{x}({self.tab_args()}), fx_c_{x}({args}))")
        self.add(f"def fh3_{x}(+b1: List<&2, {W}>, +b2: List<&2, {W}>, {two}) -> Bool:\n  "
                 + self.and_all([f"fx_ok_{x}(b1, ar1, en1, s1{hs})", f"fx_ok_{x}(b2, ar2, en2, s2{hs})",
                                 f"fx_pt_{x}({self.tab_args()})", f"fx_c_{x}({args})"]))
        bl = f"{self.Q('ge_e_blobs')}(en1), {self.Q('ge_e_blobs')}(en2)"
        for fn, other in (("fk", "True{}"), ("fh", "False{}")):
            self.add(f"def {fn}2_{x}({two}) -> Bool:\n  {fn}3_{x}({bl}, {args})")
            self.add(f"def {fn}1b_{x}(o2: FxO_{a}, +ar1: {AR}, +en1: {HEnv}, +s1: {GSt}, +s2: {GSt}{self.hsig()}) -> Bool:\n"
                     f"  match o2:\n    case FxS_{a}{{ar2, en2}}:\n      {fn}2_{x}({args})\n    case FxN_{a}{{}}:\n"
                     f"      {other}")
            self.add(f"def {fn}1_{x}(o1: FxO_{a}, +s1: {GSt}, o2: FxO_{a}, +s2: {GSt}{self.hsig()}) -> Bool:\n"
                     f"  match o1:\n    case FxS_{a}{{ar1, en1}}:\n      {fn}1b_{x}(o2, ar1, en1, s1, s2{hs})\n"
                     f"    case FxN_{a}{{}}:\n      {other}")
            name = "fact" if fn == "fk" else "fhit"
            what = (f"{e['law_id']}: equal commitments of two successful calls of {b['action']} imply equal blob lists"
                    if fn == "fk" else f"the premises of {e['law_id']} and its antecedent (G11V)")
            self.add(f"# {what}\ndef {name}_{x}(+s1: {GSt}, x1: {self.Q('HAct')}, +s2: {GSt}, x2: {self.Q('HAct')}"
                     f"{self.hsig()}) -> Bool:\n  {fn}1_{x}(fx_sel_{a}(x1), s1, fx_sel_{a}(x2), s2{hs})")

    # ---------------------------------------------------------- the ghost part
    def ghost(self) -> None:
        W, GSt, HAct = self.Q("W"), self.Q("GSt"), self.Q("HAct")
        self.defs.append(GHOST_MARKER + "\n")
        self.add(f"# one entry of a chooser companion: key, chooser, bottom\ntype FxC is Data:\n  FxC{{k: {W}, a: {W}, b: Bool}}")
        self.add(f"# a companion's value at a key: (chooser, bottom), bottom when unset\ntype FxV is Data:\n"
                 f"  FxV{{a: {W}, b: Bool}}")
        self.add("def fx_vsel(c: Bool, v1: FxV, v2: FxV) -> FxV:\n  match c:\n    case True{}:\n      v1\n"
                 "    case False{}:\n      v2")
        self.add("def fx_gsel(c: Bool, g1: FxG, g2: FxG) -> FxG:\n  match c:\n    case True{}:\n      g1\n"
                 "    case False{}:\n      g2")
        self.add(f"def fx_get(xs: List<&2, FxC>, +k: {W}) -> FxV:\n  match xs:\n    case Nil{{}}:\n"
                 f"      FxV{{{self.Q('w0')}(), True{{}}}}\n    case Con{{h, t}}:\n      match h:\n"
                 f"        case FxC{{k2, a, b}}:\n          fx_vsel({self.Q('w_eq')}(k, k2), FxV{{a, b}}, fx_get(t, k))")
        self.add(f"def fx_put(xs: List<&2, FxC>, +k: {W}, a: {W}, b: Bool) -> List<&2, FxC>:\n  Con{{FxC{{k, a, b}}, xs}}")
        fields = ", ".join(f"chooser_{bname(P)}: List<&2, FxC>" for P in self.pinned)
        self.add(f"# the chooser companions, one per pinned family\ntype FxG is Data:\n  FxG{{{fields}}}")
        names = [f"chooser_{bname(P)}" for P in self.pinned]
        self.add("def fx_g0() -> FxG:\n  FxG{" + ", ".join("Nil{}" for _ in names) + "}")
        self.add(f"# the state and the companions\ntype FxR is Data:\n  FxR{{s: {GSt}, g: FxG}}")
        # per action, the companions' update by its whole writes of each pinned family (program order)
        for c in self.actions:
            act = self.by_name.get(c) or {}
            X0 = self.Q(f"X_{c}")
            body = "g"
            for i, w in enumerate(act.get("writes") or []):
                if w.get("family") not in self.pinned or not RF.unconditional(w):
                    if w.get("family") in self.pinned and not RF.unconditional(w):
                        raise GenError(f"{act.get('name')} writes[{i}]: a conditional write of a pinned family")
                    continue
                k, whole = RF.wkey(w)
                if not whole or k is None:
                    continue
                P = w["family"]
                C = RF.map_read(P, k)
                cp, zp = _copy_path(w["value"], C), _zero_path(w["value"])
                fname = f"fx_gu_{c}_{i}"
                kt = self.compile_word(act["name"], k)
                copy, clear = self.branch_bool(act["name"], cp), self.branch_bool(act["name"], zp)
                field = f"chooser_{bname(P)}"
                upd = ("match g:\n    case FxG{" + ", ".join(names) + "}:\n      FxG{" +
                       ", ".join((f"fx_put({n}, {kt}, {self.Q('ge_e_caller')}({self.Q(f'gx_{c}_en')}(x)), "
                                  f"cl)" if n == field else n) for n in names) + "}")
                self.add(f"# {act.get('name')} writes[{i}] of {P}: a copy leaves the chooser, the literal 0 clears it, "
                         f"a fresh value sets the caller\ndef {fname}_s(cl: Bool, +x: {X0}, g: FxG) -> FxG:\n  {upd}")
                self.add(f"def {fname}(+x: {X0}, +g: FxG) -> FxG:\n  fx_gsel({copy}, g, {fname}_s({clear}, x, g))")
                body = f"{fname}(x, {body})"
            self.add(f"def fx_gu_{c}(+x: {X0}, g: FxG) -> FxG:\n  {body}")
        st = self.Q("gh_get_st")
        hs = self.hargs()
        cases = []
        for c in self.actions:
            cases.append(f"        case {self.Q(f'A_{c}')}{{+ar, +en}}:\n          fx_gs(U32.is_eq({self.Q(f'gx_{c}_cd')}("
                         f"{self.Q(f'xr_{c}')}({st}(s), ar, en{hs})), 0), {self.Q('gh_step')}({self.Q(f'A_{c}')}{{ar, en}}, "
                         f"s{hs}), s, fx_gu_{c}({self.Q(f'x0_{c}')}({st}(s), ar, en{hs}), g), g)")
        self.add(f"def fx_gs(ok: Bool, s2: {GSt}, s: {GSt}, g2: FxG, g: FxG) -> FxR:\n  match ok:\n"
                 "    case True{}:\n      FxR{s2, g2}\n    case False{}:\n      FxR{s, g}")
        self.add(f"# one step of run_fact: a reverted step changes neither the state nor the companions\n"
                 f"def fx_step(r: FxR, a: {HAct}{self.hsig()}) -> FxR:\n  match r:\n    case FxR{{+s, +g}}:\n"
                 "      match a:\n" + "\n".join(cases))
        self.add(f"# run_fact: the state and the companions after a trace from Reach's initial state\n"
                 f"def run_fact(t: List<&2, {HAct}>, r: FxR{self.hsig()}) -> FxR:\n  match t:\n    case Nil{{}}:\n"
                 f"      r\n    case Con{{a, rest}}:\n      run_fact(rest, fx_step(r, a{hs}){hs})")
        self.add(f"def fx_blobs_all(t: List<&2, {HAct}>) -> Bool:\n  match t:\n    case Nil{{}}:\n      True{{}}\n"
                 "    case Con{a, rest}:\n      match a:\n" +
                 "\n".join(f"        case {self.Q(f'A_{c}')}{{ar, en}}:\n          Bool.and(fx_wf({self.Q('ge_e_blobs')}(en)), "
                           "fx_blobs_all(rest))" for c in self.actions))

    def attribution(self, e: dict) -> None:
        x = RF.ghost_x(e["law_id"])
        b = e["basis"]
        w = bname(b["action"])
        P, A, m = b["content"], b["consumer"]["family"], b["consumer"]["member"]
        wr, key = self.wkey(b["action"], b["pin"])
        C = RF.map_read(P, key)
        cp = _copy_path(wr["value"], C)
        if cp is False:
            raise GenError(f"{e['law_id']}: the pin write holds no copy")
        GSt, HAct, W, HSt = self.Q("GSt"), self.Q("HAct"), self.Q("W"), self.Q("HSt")
        X = self.Q(f"X_{w}")
        st, hs = self.Q("gh_get_st"), self.hargs()
        self.add(f"# the key {b['action']} pins {P} at ({b['pin']}), in its context\n"
                 f"def fx_key_{x}(+x: {X}) -> {W}:\n  {self.compile_word(b['action'], key)}")
        self.add(f"# {b['action']} takes the copy branch of its pin\ndef fx_pin_{x}(+x: {X}) -> Bool:\n  "
                 f"{self.branch_bool(b['action'], cp)}")
        self.add(f"# {A}.{m} at key k in st\ndef fx_bond_{x}(+st: {HSt}, +k: {W}{self.hsig()}) -> {W}:\n  "
                 f"{self.member_word(A, m, 'st', 'k')}")
        field = f"chooser_{bname(P)}"
        names = [f"chooser_{bname(Q)}" for Q in self.pinned]
        self.add(f"def fx_ch_{x}(g: FxG, +k: {W}) -> FxV:\n  match g:\n    case FxG{{{', '.join(names)}}}:\n"
                 f"      fx_get({field}, k)")
        AR, HEnv = self.Q(f"AR_{w}"), self.Q("HEnv")
        x0 = f"{self.Q(f'x0_{w}')}({st}(s), ar, en{hs})"
        xr = f"{self.Q(f'xr_{w}')}({st}(s), ar, en{hs})"
        k = f"fx_key_{x}({x0})"
        post = f"{st}({self.Q(f'gh_go_{w}')}({xr}, s))"
        prem = self.and_all(self.premise_terms(e, [f"{self.Q('ge_e_blobs')}(en)"])[:1] + ["fx_blobs_all(p)"]
                            + self.premise_terms(e, [])[0:])
        ok = f"U32.is_eq({self.Q(f'gx_{w}_cd')}({xr}), 0)"
        self.add(f"# whose bond is at risk against who chose the content: bottom, or the chooser\n"
                 f"def fx_cl_{x}(v: FxV, bonded: {W}) -> Bool:\n  match v:\n    case FxV{{a, b}}:\n      match b:\n"
                 f"        case True{{}}:\n          True{{}}\n        case False{{}}:\n"
                 f"          {self.Q('w_eq')}(bonded, a)")
        self.add(f"def fx_cb_{x}(v: FxV) -> Bool:\n  match v:\n    case FxV{{a, b}}:\n      Bool.not(b)")
        self.add(f"def fw2_{x}(+ar: {AR}, +en: {HEnv}, +s: {GSt}, +g: FxG{self.hsig()}) -> FxV:\n  fx_ch_{x}(g, {k})")
        sig = f"+ar: {AR}, +en: {HEnv}, +s: {GSt}, +g: FxG, p: List<&2, {HAct}>{self.hsig()}"
        self.add(f"def fa2_{x}({sig}) -> Bool:\n  fx_imp({prem}, fx_imp({ok}, fx_imp(fx_pin_{x}({x0}), "
                 f"fx_cl_{x}(fx_ch_{x}(g, {k}), fx_bond_{x}({post}, {k}{hs})))))")
        self.add(f"def fh2_{x}({sig}) -> Bool:\n  "
                 f"{self.and_all([prem, ok, f'fx_pin_{x}({x0})', f'fx_cb_{x}(fx_ch_{x}(g, {k}))'])}")
        for fn, other in (("fa", "True{}"), ("fh", "False{}")):
            cases = []
            for c in self.actions:
                if c == w:
                    cases.append(f"        case {self.Q(f'A_{c}')}{{ar, en}}:\n          {fn}2_{x}(ar, en, s, g, p{hs})")
                else:
                    cases.append(f"        case {self.Q(f'A_{c}')}{{ar, en}}:\n          {other}")
            name = "fact" if fn == "fa" else "fhit"
            what = (f"{e['law_id']}: on a recommit through the pin of {P}, the bonded {A}.{m} is the content's chooser"
                    if fn == "fa" else f"the premises of {e['law_id']} and its antecedent (G11V)")
            self.add(f"def {fn}1_{x}(r: FxR, y: {HAct}, p: List<&2, {HAct}>{self.hsig()}) -> Bool:\n"
                     "  match r:\n    case FxR{s, g}:\n      match y:\n" + "\n".join(cases))
            self.add(f"# {what}\ndef {name}_{x}(+p: List<&2, {HAct}>, y: {HAct}{self.hsig()}) -> Bool:\n"
                     f"  {fn}1_{x}(run_fact(p, FxR{{{self.Q('gh_s0')}(), fx_g0()}}{hs}), y, p{hs})")
        cases = []
        for c in self.actions:
            body = f"fw2_{x}(ar, en, s, g{hs})" if c == w else f"FxV{{{self.Q('w0')}(), True{{}}}}"
            cases.append(f"        case {self.Q(f'A_{c}')}{{ar, en}}:\n          {body}")
        self.add(f"def fw1_{x}(r: FxR, y: {HAct}{self.hsig()}) -> FxV:\n  match r:\n    case FxR{{s, g}}:\n"
                 "      match y:\n" + "\n".join(cases))
        self.add(f"# the chooser companion of {P} at the key y pins, after p (bottom when y is not a call of "
                 f"{b['action']})\ndef fx_who_{x}(+p: List<&2, {HAct}>, y: {HAct}{self.hsig()}) -> FxV:\n"
                 f"  fw1_{x}(run_fact(p, FxR{{{self.Q('gh_s0')}(), fx_g0()}}{hs}), y{hs})")

    # ---------------------------------------------------------- the module
    def build(self) -> list[str]:
        self.defs, self.mine, self.options = [], set(), set()
        T.Trace.fixed(self)              # holon.undo.trace's observation of a step (the replay's model side)
        T.Trace.observations(self)
        self.fixed()
        for e in self.elements:
            if e["subform"] == "kernel":
                self.kernel(e)
        if any(e["subform"] == "attribution" for e in self.elements):
            self.ghost()
            for e in self.elements:
                if e["subform"] == "attribution":
                    self.attribution(e)
        # the module's own run is the typed model's run (holon.undo.trace; only where the model is imported as M)
        clash = sorted(n for n in self.mine if n in self.names and not (self.q and n == "run"))
        if clash:
            raise GenError(f"the FACT section's names clash with the typed model's: {clash}")
        return self.defs


def module_text(mm, model_text: str, doc: dict, hashes: list, elements: list, hypotheses: dict,
                model_import: str) -> str:
    """gen/<M>/fact/models/<model>.fact.bend: the FACT section, importing the typed model as M."""
    sec = Section(mm, model_text, doc, hashes, elements, hypotheses)
    defs = sec.build()
    head = [HEADER, f"# {SECTION_VERSION}; laws: {', '.join(e['law_id'] for e in elements) or 'none'}", "import Base",
            f"import {model_import} as M", ""]
    return "\n".join(head) + "\n" + "\n".join(defs)


def combined_text(mm, model_text: str, doc: dict, hashes: list, elements: list, hypotheses: dict) -> str:
    """The typed model's text followed by the FACT section unqualified: one module for the evaluator."""
    sec = Section(mm, model_text, doc, hashes, elements, hypotheses)
    sec.q = ""
    defs = sec.build()
    return model_text.rstrip("\n") + "\n\n# ---- holon.fact.section (evaluation copy)\n" + "\n".join(defs)
