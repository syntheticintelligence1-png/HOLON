"""Targets whose laws a typed test milestone derives and decides (I50): `holon target derive|run --target NAME`.

A target whose run.kind is "typed" (targets/<name>/target.json) names run.milestone (a typed test milestone, T<n> with
n >= 30), run.catalog (a rule-catalog version of holon.rules.CATALOGS) and run.sidecar_rules (the protocol sidecar
whose rules Q1-Q4 give the typed-sorts, UNDO, DISCH and FACT sidecars). Its laws are derived and decided in a scratch
root, as I47's toy target runs: the scratch root holds a copy of holon/, config/ and spec/ (never spec/heldout/), the
target's documents and generated sidecars, and the run's earlier outputs placed where the milestone's commands read
them:

  repo                                    scratch root
  gen/targets/<name>/lib/<x>.json         same path (the sidecars, read by --sidecar flags)
  gen/targets/<name>/sorts/               gen/<M>/sorts/          (holon sorts)
  gen/targets/<name>/disch/               gen/<M>/disch/          (holon disch)
  gen/targets/<name>/laws/                laws/<M>/               (holon derive)
  gen/targets/<name>/run/                 gen/<M>/ but sorts/ and disch/   (the run's models, laws and proofs)
  results/targets/<name>/records/         results/<M>/            (records, summary.json)

so every path a derivation, a record or a proof names is the milestone's own (gen/<M>/..., laws/<M>/...), as for any
test milestone; a check re-creates the scratch root to read them. The commands are the milestone's, unchanged:
holon sorts, holon disch, holon derive --catalog, holon model, holon run (which dispatches each rule to the runner the
milestone pipeline uses). Nothing here names a target.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from . import targets as T

ROOT = Path(__file__).resolve().parents[1]
SIDECARS = ("sort_types", "undo", "disch", "fact")


class TypedFailure(RuntimeError):
    pass


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def load(p: Path):
    return json.loads(Path(p).read_text(encoding="utf-8"))


def _ignore(_d, names):
    return [n for n in names if n in ("__pycache__", "node_modules") or n.endswith(".pyc")]


def run_spec(t: dict) -> dict:
    run = t.get("run") or {}
    if run.get("kind") != "typed":
        raise TypedFailure(f"target {t['name']}: run.kind is {run.get('kind')!r}, not typed")
    return run


def lib(t: dict) -> str:
    return f"gen/targets/{t['name']}/lib"


def mapping(t: dict) -> dict[str, str]:
    """repo directory -> scratch-root directory."""
    m, n = run_spec(t)["milestone"], t["name"]
    return {f"gen/targets/{n}/sorts": f"gen/{m}/sorts", f"gen/targets/{n}/disch": f"gen/{m}/disch",
            f"gen/targets/{n}/laws": f"laws/{m}", f"gen/targets/{n}/run": f"gen/{m}",
            f"results/targets/{n}/records": f"results/{m}"}


def documents(t: dict) -> list[str]:
    return sorted((t.get("extract") or {}).get("documents", {}).values())


# ------------------------------------------------------------------ the sidecars (rules Q1-Q4)
def sidecars(t: dict, root: Path) -> dict[str, dict]:
    run = run_spec(t)
    rules = load(Path(root) / run["sidecar_rules"])["sidecar_rules"]
    m3 = {n: load(Path(root) / "spec" / "M3" / "lib" / f"{n}.json") for n in SIDECARS}
    docs = documents(t)
    ts = f"{lib(t)}/sort_types.json"
    doc = (f"Generated by `holon target derive` (rules Q1-Q4 of {run['sidecar_rules']}): every field is copied from "
           "the development milestone's sidecar of the same name, or fixed by the rule; nothing is chosen for the target.")
    if sorted(k for k in rules if k[:1] == "Q") != ["Q1_sort_types", "Q2_undo", "Q3_disch", "Q4_fact"]:
        raise TypedFailure(f"{run['sidecar_rules']}: the sidecar rules are not Q1-Q4")
    return {
        "sort_types": {"doc": doc, "sort_types_version": "holon-sort-types/0.1", "documents": docs,
                       "seeds": m3["sort_types"]["seeds"], "binding": None, "search": m3["sort_types"]["search"]},
        "undo": {"doc": doc, "undo_version": "holon-undo/0.1", "sort_types": ts,
                 "observation": m3["undo"]["observation"], "premise": m3["undo"]["premise"],
                 "search": m3["undo"]["search"]},
        "disch": {"doc": doc, "disch_version": "holon-disch/0.1", "documents": docs, "binding": None,
                  "model_sidecar": ts, "hypotheses": {}, "search": m3["disch"]["search"]},
        "fact": {"doc": doc, "fact_version": "holon-fact/0.1", "iteration": run.get("iteration", ""),
                 "documents": docs, "sort_types": ts, "binding": None, "hypotheses": {},
                 "search": m3["fact"]["search"], "measure": m3["fact"]["measure"],
                 "term_size": m3["fact"]["term_size"]},
    }


def sidecar_args(t: dict) -> list[str]:
    L = lib(t)
    return ["--sidecar", f"{L}/sort_types.json", "--undo-sidecar", f"{L}/undo.json", "--disch", f"{L}/disch.json",
            "--fact-sidecar", f"{L}/fact.json"]


# ------------------------------------------------------------------ the scratch root
def scratch(t: dict, root: Path, with_outputs: bool = True) -> Path:
    root = Path(root)
    s = Path(tempfile.mkdtemp(prefix="holon-typed-")) / "root"
    s.mkdir(parents=True)
    for d in ("holon", "config"):
        shutil.copytree(root / d, s / d, ignore=_ignore)
    shutil.copytree(root / "spec", s / "spec", ignore=lambda d, names: [n for n in _ignore(d, names)]
                    + (["heldout"] if Path(d).resolve() == (root / "spec").resolve() else []))
    for rel in documents(t):
        (s / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(root / rel, s / rel)
    (s / lib(t)).mkdir(parents=True, exist_ok=True)
    for n, side in sidecars(t, root).items():
        (s / lib(t) / f"{n}.json").write_text(dumps(side), encoding="utf-8")
    if with_outputs:
        for repo_d, sd in sorted(mapping(t).items(), key=lambda kv: kv[1].count("/")):
            src = root / repo_d
            if src.is_dir():
                shutil.copytree(src, s / sd, dirs_exist_ok=True)
    return s


def _holon(s: Path, args: list[str], timeout: int | None = None) -> subprocess.CompletedProcess:
    env = dict(os.environ)
    env["PYTHONPATH"] = str(s)
    env["BEND_NO_TELEMETRY"] = "1"
    env["HOLON_BUILD_DIR"] = str(s.parent / "build")
    env.pop("HOLON_TRACE", None)
    return subprocess.run([sys.executable, "-m", "holon", *args], cwd=s, env=env, capture_output=True, text=True,
                          timeout=timeout)


def _must(p: subprocess.CompletedProcess, what: str) -> None:
    if p.returncode != 0:
        raise TypedFailure(f"{what} exited {p.returncode}: {(p.stdout + p.stderr)[-2500:]}")


def _tree(d: Path, skip: tuple[str, ...] = ()) -> dict[str, bytes]:
    out = {}
    if d.is_dir():
        for f in sorted(d.rglob("*")):
            rel = f.relative_to(d).as_posix()
            if f.is_file() and not any(rel == x or rel.startswith(x + "/") for x in skip) and "__pycache__" not in rel:
                out[rel] = f.read_bytes()
    return out


# ------------------------------------------------------------------ derive
def derive_outputs(t: dict, root: Path) -> dict[str, bytes]:
    """{repo-relative path: bytes} of everything `holon target derive` writes, from a fresh scratch run."""
    run = run_spec(t)
    m = run["milestone"]
    s = scratch(t, root, with_outputs=False)
    try:
        L = lib(t)
        n = t["name"]
        out = {f"{L}/{x}.json": (s / L / f"{x}.json").read_bytes() for x in SIDECARS}
        args = ["derive", "--milestone", m, "--catalog", run["catalog"]] + sidecar_args(t)
        for d in documents(t):
            args += ["--facts", d]
        steps = [("holon sorts", ["sorts", "--milestone", m, "--sidecar", f"{L}/sort_types.json"]),
                 ("holon disch", ["disch", "--milestone", m, "--sidecar", f"{L}/disch.json"]),
                 ("holon derive", args)]
        for what, a in steps:
            p = _holon(s, a)
            if p.returncode != 0:
                # a refused step ends the route: the refusal is the derivation's outcome, recorded (no law exists)
                msg = (p.stderr or p.stdout).strip().replace(str(s) + "/", "")
                out[refusal_path(t)] = dumps({
                    "refusal_version": "holon-target-derive/0.1", "status": "refused", "step": what,
                    "command": ["python", "-m", "holon"] + a, "exit": p.returncode, "message": msg[-2000:],
                    "catalog": run["catalog"], "milestone": m, "documents": documents(t),
                    "doc": "holon target derive stopped at this step: the pinned machinery refused the document, so "
                           "no law was derived. Nothing was changed to make it pass."}).encode()
                return out
        for repo_d, sd in (("sorts", f"gen/{m}/sorts"), ("disch", f"gen/{m}/disch"), ("laws", f"laws/{m}")):
            for rel, b in _tree(s / sd).items():
                out[f"gen/targets/{n}/{repo_d}/{rel}"] = b
        return out
    finally:
        shutil.rmtree(s.parent, ignore_errors=True)


def replay_path(t: dict) -> str:
    return f"results/targets/{t['name']}/replay.json"


def replay_doc(t: dict, summary: dict, ref: dict | None) -> dict:
    """One entry per REFUTED law. With binding null there is no deployment to replay on (route R3), so every entry is
    not_run with that reason."""
    why = ("binding null: the target has no deployment in the repo, so the runners have no real contract to replay "
           "the witness on (spec/M4/lib/heldout_run.json route R3)")
    laws = {lid: {"status": "not_run", "reason": why} for lid, st in sorted(summary.items()) if st == "REFUTED"}
    d = {"replay_version": "holon-target-replay/0.1", "target": t["name"], "laws": laws,
         "doc": "the replay results of the held-out run: one entry per REFUTED law (route R3)"}
    if ref is not None:
        d["no_laws"] = f"the derivation was refused at {ref['step']}: {ref['message']}"
    return d


def refusal_path(t: dict) -> str:
    return f"results/targets/{t['name']}/derive_refusal.json"


def refusal(t: dict, root: Path) -> dict | None:
    p = Path(root) / refusal_path(t)
    return load(p) if p.is_file() else None


def _sync(root: Path, writes: dict[str, bytes], dirs: list[str], check: bool, cmd: str) -> int:
    have = {}
    for d in dirs:
        for rel, b in _tree(Path(root) / d).items():
            have[f"{d}/{rel}"] = b
    if check:
        bad = sorted(set(have) ^ set(writes)) + sorted(k for k in writes if k in have and have[k] != writes[k])
        for k in bad:
            print(f"holon target {cmd}: {k} differs from a fresh run")
        if not bad:
            print(f"holon target {cmd}: up to date ({len(writes)} files)")
        return 1 if bad else 0
    for d in dirs:
        shutil.rmtree(Path(root) / d, ignore_errors=True)
    for rel, b in sorted(writes.items()):
        p = Path(root) / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(b)
    print(f"holon target {cmd}: wrote {len(writes)} files under {', '.join(dirs)}")
    return 0


def derive(name: str, root: Path, check: bool) -> int:
    t = T.load(name, root)
    n = t["name"]
    dirs = [lib(t), f"gen/targets/{n}/sorts", f"gen/targets/{n}/disch", f"gen/targets/{n}/laws"]
    outs = derive_outputs(t, root)
    rp = refusal_path(t)
    rc = _sync(root, {k: v for k, v in outs.items() if k != rp}, dirs, check, "derive")
    if check:
        same = (rp in outs) == (Path(root) / rp).is_file() and (rp not in outs or (Path(root) / rp).read_bytes() == outs[rp])
        if not same:
            print(f"holon target derive: {rp} differs from a fresh run")
        rc = max(rc, 0 if same else 1)
    elif rp in outs:
        (Path(root) / rp).parent.mkdir(parents=True, exist_ok=True)
        (Path(root) / rp).write_bytes(outs[rp])
        print(f"holon target derive: REFUSED at {json.loads(outs[rp])['step']}: {json.loads(outs[rp])['message'][-300:]}")
    else:
        (Path(root) / rp).unlink(missing_ok=True)
    return 1 if (rp in outs and not check) else rc


# ------------------------------------------------------------------ run
def run(name: str, root: Path, log=print) -> int:
    t = T.load(name, root)
    rs = run_spec(t)
    m = rs["milestone"]
    n = t["name"]
    ref = refusal(t, root)
    if ref is not None:
        # the derivation was refused: no law exists, so the run decides nothing and no witness can be replayed
        writes = {f"results/targets/{n}/records/summary.json": dumps({}).encode(),
                  replay_path(t): dumps(replay_doc(t, {}, ref)).encode()}
        _sync(root, {k: v for k, v in writes.items() if k != replay_path(t)},
              [f"results/targets/{n}/records", f"gen/targets/{n}/run"], False, "run")
        (Path(root) / replay_path(t)).write_bytes(writes[replay_path(t)])
        log(f"holon target run: {n}: no law to decide (the derivation was refused at {ref['step']})")
        return 0
    if not (Path(root) / f"gen/targets/{n}/laws/DERIVATION.json").is_file():
        raise TypedFailure("no derivation: run `holon target derive` first")
    s = scratch(t, root, with_outputs=True)
    try:
        for d in (f"gen/{m}/sorts/models",):
            shutil.rmtree(s / d, ignore_errors=True)
        _must(_holon(s, ["model", "--milestone", m, "--sidecar", f"{lib(t)}/sort_types.json", "--out",
                         f"gen/{m}/sorts/models"]), "holon model")
        p = _holon(s, ["run", "--milestone", m] + sidecar_args(t) + ["--out", f"results/{m}", "--gen-dir", f"gen/{m}"])
        log(p.stdout[-6000:])
        if p.returncode != 0:
            print(p.stderr[-6000:], file=sys.stderr)
        writes = {}
        for rel, b in _tree(s / f"results/{m}").items():
            writes[f"results/targets/{n}/records/{rel}"] = b
        for rel, b in _tree(s / f"gen/{m}", skip=("sorts/assignment.json", "sorts/conflicts.json",
                                                  "sorts/constraints.json", "sorts/unions.json",
                                                  "sorts/unresolved.json", "disch")).items():
            writes[f"gen/targets/{n}/run/{rel}"] = b
        _sync(root, writes, [f"results/targets/{n}/records", f"gen/targets/{n}/run"], False, "run")
        summ = Path(root) / f"results/targets/{n}/records/summary.json"
        (Path(root) / replay_path(t)).write_text(dumps(replay_doc(t, load(summ) if summ.is_file() else {}, None)))
        return p.returncode
    finally:
        shutil.rmtree(s.parent, ignore_errors=True)


def main(command: str, argv: list[str]) -> int:
    import argparse
    ap = argparse.ArgumentParser(prog=f"holon target {command}")
    ap.add_argument("--target", required=True)
    ap.add_argument("--root")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    root = Path(a.root or ROOT).resolve()
    try:
        if command == "derive":
            return derive(a.target, root, a.check)
        if command == "run":
            return run(a.target, root)
    except (TypedFailure, T.TargetError) as e:
        print(f"holon target {command}: {e}", file=sys.stderr)
        return 2
    raise SystemExit(f"unknown command {command}")
