class Decider:
    def __init__(self, dc: DCtx, gen: Path | None = None, out: Path | None = None, registry: dict | None = None):
        self.dc = dc
        self.gen = Path(gen) if gen else dc.root / "gen" / dc.L.m
        self.out = Path(out) if out else dc.root / "results" / dc.L.m
        self.registry = registry

    def law(self, lid: str) -> dict:
        return json.loads((self.dc.root / "laws" / self.dc.L.m / f"{lid}.json").read_text(encoding="utf-8"))

    def statement_hash(self, lid: str) -> str:
        reg = self.registry or json.loads((self.dc.root / "laws" / self.dc.L.m / "REGISTRY.json").read_text())
        return reg["statements"][lid]

    # ---------------------------------------------------------- link_domain
    def link_domain(self, lid: str, deadline: float | None) -> dict:
        dc = self.dc
        e = dc.cl.laws[lid]
        a = e["basis"]["action"]
        x = LC.claim_x(lid)
        depth = int(dc.search.get("link_domain_max_prefix", 3))
        S = BSearch(dc, e, depth, {"versions": dc.search.get("versions") or []}, deadline)
        attempts, refused = [], []
        t0 = time.time()
        w = None
        try:
            for d, trace, g in S.states(a):
                for st in S.candidates(g, trace, a):
                    S.tick()
                    S.m.run_step(g, st, save=False)
                    act = S.m.act(st)
                    if not S.o.pred(f"fx_la_{x}", [act["f"]["ar"], act["f"]["en"], {"$ref": g}]):
                        continue
                    v = S.o.word(f"fx_lv_{x}", [S.x0(g, st)])
                    i = S.o.word(f"fx_li_{x}", [S.x0(g, st)])
                    r = resolve(dc, v, i)
                    if r["dom"]:
                        continue
                    cand = {"prefix": list(trace), "x": st, "link": {"version": v, "index": i}, "resolution": r,
                            "depth": d}
                    why, cand2 = self.accept_link(S, lid, cand)
                    if why is None:
                        w = cand2
                        break
                    refused.append(why)
                if w is not None:
                    break
        except (US.Budget, US.TimeBox) as ex:
            attempts.append({"kind": "refute", "engine": "holon.bundle2.laws_decide", "found": False,
                             "bound": f"{type(ex).__name__}: {S.cands} candidates"})
        bound = (f"prefix states of at most {depth} steps from the laws' deployment, breadth first "
                 f"({getattr(S, 'visited', 0)} states visited), {S.cands} candidates (versions "
                 f"{dc.search.get('versions')}); {len(refused)} model witnesses refused by the real side")
        attempts.append({"kind": "refute", "engine": "holon.bundle2.laws_decide (LD4)", "found": w is not None,
                         "bound": bound, "seconds": round(time.time() - t0, 1),
                         "refused": refused[:8]})
        if w is None:
            return self.unknown(lid, e, attempts, bound)
        return self.emit_link(lid, e, S, w, attempts)

    def accept_link(self, S: BSearch, lid: str, cand: dict) -> tuple[str | None, dict]:
        """The real side: every prefix step succeeds on the laws' deployment and the action reverts there; the model,
        its prefix steps' external calls answered as the deployment answers them, still runs the prefix and finds the
        antecedent true at the action."""
        dc = self.dc
        steps = list(cand["prefix"]) + [cand["x"]]
        sj = steps_json(dc, S.m, steps)
        r = resolve(dc, cand["link"]["version"], cand["link"]["index"])
        rcall = {"to": 2, "caller": "0x" + "00" * 20, "value": 0, "timestamp": 0,
                 "data": resolver_calldata(dc, cand["link"]["version"], cand["link"]["index"]), "blobs": []}
        try:
            run = dc.forge().traces([[real_call(s) for s in sj] + [rcall]], jobs=1, tag="ldom")[0]
        except Exception as ex:  # noqa: BLE001: a witness the real side cannot run is no witness
            return f"the real side cannot run it: {type(ex).__name__}: {str(ex)[:160]}", cand
        execs = [e for e in run.execs if e.id != "d"]
        member = run.members[0]
        bad = [i for i, e in enumerate(execs[:len(cand["prefix"])]) if not e.ok]
        if bad:
            return f"prefix step {bad[0]} reverts on the deployment", cand
        xe = execs[len(cand["prefix"])]
        if xe.ok:
            return "the action succeeds on the deployment", cand
        rr = execs[-1]
        resolved = "revert" if not rr.ok else ("0x" + rr.ret[-40:] if len(rr.ret) >= 66 else rr.ret)
        if rr.ok and int(rr.ret or "0x0", 16) != 0:
            return "the real callee resolves the arguments", cand
        # the repair: each prefix step's calls as the deployment answers them; the action's own answers stay the
        # model's (the callee as an oracle: the real call reverted)
        pre = [with_calls(st, raw_calls(execs[k], member)) for k, st in enumerate(cand["prefix"])]
        m = dc.factory()
        g = m.s0()
        for st in pre:
            code, g, _c = m.run_step(g, st, save=True)
            if code != 0:
                return "with the deployment's call answers a prefix step fails on the model", cand
        o = US.Obs(m)
        act = m.act(cand["x"])
        if not o.pred(f"fx_la_{LC.claim_x(lid)}", [act["f"]["ar"], act["f"]["en"], {"$ref": g}]):
            return "with the deployment's call answers the antecedent fails on the model", cand
        out = dict(cand, prefix=pre, real={"steps": ["ok"] * len(pre) + ["revert"], "resolution": resolved,
                                           "resolution_model": r["status"]})
        return None, out

    def emit_link(self, lid: str, e: dict, S: BSearch, w: dict, attempts: list) -> dict:
        dc = self.dc
        x = LC.claim_x(lid)
        law = self.law(lid)
        a = e["basis"]["action"]
        r = w["resolution"]
        ab = bname(a)

        def args_of(m, gs):
            act = m.act(w["x"])
            return [act["f"]["ar"], act["f"]["en"], {"$ref": gs[0]}]
        kh, sh, val, states = settle_runs(dc, [w["prefix"]], f"fx_la_{x}", args_of)
        for k in r["keys"]:          # the callee's resolution's keys (one keccak256 table)
            kh.setdefault(k, r["keys"][k])
        m = dc.factory(empty=True, native=False)
        acts = [m.act(st) for st in w["prefix"]]
        xv = m.act(w["x"])
        p = paths(dc, lid, self.gen)
        p["laws"].parent.mkdir(parents=True, exist_ok=True)
        mi, si, vi = imports(dc, p["laws"].parent)
        sh_ = self.statement_hash(lid)
        p["laws"].write_text(claim_law_file(law, sh_, mi, si, vi, dc.cl.hashes, True), encoding="utf-8")
        d = p["proofs"] / "witness"
        d.mkdir(parents=True, exist_ok=True)
        li = P3.rel_import(d, p["laws"])
        tables = {"keccak256": kh, "sha256": sh}
        leaves = [f"fx_la_{x}(ar, en, s, kh)",
                  f"fv_dom({LC.CALLEE_PREFIX}run(vt, fv_s0(), fv_tab(kh)), fv_w(fx_lv_{x}(M.x0_{ab}(M.gh_get_st(s), ar, en, kh), kh)), "
                  f"fv_w(fx_li_{x}(M.x0_{ab}(M.gh_get_st(s), ar, en, kh), kh)), fv_tab(kh))"]
        text = claim_counter_proof(dc, law, d, li, acts, states[0], xv, tables,
                                   f"the witness (link_domain: a prefix of {len(acts)} steps, the action, the callee "
                                   "at its laws' deployment), every premise by computation", a, leaves,
                                   {"vt": "Nil{}"})
        pp = d / "PROOF.bend"
        pp.write_text(text, encoding="utf-8")
        checker, verdict = check(pp)
        attempts.append({"kind": "counter", "checker": checker, "verdict": verdict,
                         "evaluator": "the antecedent holds and the callee's model does not resolve the arguments"})
        ok = checker["marker"] == "ALL PROOFS CHECK" and verdict == "checked"
        wj = {"prefix": steps_json(dc, m, w["prefix"]), "x": steps_json(dc, m, [w["x"]])[0],
              "vt": [], "link": {"version": int(w["link"]["version"]), "index": int(w["link"]["index"])},
              "hashes": {"keccak256": [["0x" + k[2:], hexw(v)] for k, v in sorted(kh.items())]}}
        if not ok:
            attempts.append({"kind": "note", "detail": "the counter-law was not accepted; the law stays UNKNOWN"})
            return self.unknown(lid, e, attempts, "a model witness whose counter-law the checker did not accept",
                                laws_file=p["laws"], counter_failed=True)
        return self.record(lid, e, "REFUTED", attempts, p["laws"], pp, checker, verdict, wj, None,
                           extra={"link": wj["link"], "real": w.get("real")})

    # ---------------------------------------------------------- public_input
    def public_input(self, lids: list, deadline: float | None) -> dict:
        """FP3 for every public_input law of one action at once (one walk, one bucket table per law)."""
        dc = self.dc
        out = {}
        by_action: dict = {}
        for lid in lids:
            by_action.setdefault(dc.cl.laws[lid]["basis"]["action"], []).append(lid)
        for a, ls in sorted(by_action.items()):
            out.update(self.public_input_action(a, sorted(ls), deadline))
        return out

    def public_input_action(self, a: str, lids: list, deadline: float | None) -> dict:
        dc = self.dc
        e0 = dc.cl.laws[lids[0]]
        depth = int(dc.search.get("public_input_max_prefix", 2))
        focus = {k: dc.search.get(k) or [] for k in ("versions", "last_block_numbers", "num_l1_messages")}
        S = BSearch(dc, e0, depth, focus, deadline)
        buckets = {lid: {} for lid in lids}
        found: dict = {}
        refused = {lid: [] for lid in lids}
        t0 = time.time()
        cands = []           # (trace, g, st) of every succeeding candidate, in order
        stop = None
        try:
            for d, trace, g in S.states(a):
                for st in S.candidates(g, trace, a):
                    S.tick()
                    S.m.run_step(g, st, save=False)
                    pi = S.o.word(f"fx_pi_{LC.fact_x(lids[0])}", [S.x0(g, st)])
                    cands.append((trace, g, st))
                    for lid in lids:
                        if lid in found:
                            continue
                        x = LC.fact_x(lid)
                        fh = S.o.word(f"fx_fh_{x}", [S.x0(g, st)])
                        fv = S.o.word(f"fx_fv_{x}", [S.x0(g, st)]) if fh else None
                        fval = None if not fh else fv
                        b = buckets[lid].setdefault(pi, [])
                        for (t1, g1, s1, f1) in b:
                            if f1 == fval:
                                continue
                            act1, act2 = S.m.act(s1), S.m.act(st)
                            if S.o.pred(f"fact_{x}", [{"$ref": g1}, act1, {"$ref": g}, act2]):
                                continue
                            w = {"runs": [{"prefix": list(t1), "x": s1}, {"prefix": list(trace), "x": st}],
                                 "pi": pi, "field": [f1, fval]}
                            why, w2 = self.accept_pi(lid, w)
                            if why is None:
                                found[lid] = w2
                                break
                            refused[lid].append(why)
                        if lid not in found:
                            b.append((trace, g, st, fval))
                    if len(found) == len(lids):
                        break
                if len(found) == len(lids):
                    break
        except (US.Budget, US.TimeBox) as ex:
            stop = f"{type(ex).__name__}"
        res = {}
        for lid in lids:
            e = dc.cl.laws[lid]
            bound = (f"prefixes of at most {depth} steps from the laws' deployment, breadth first "
                     f"({getattr(S, 'visited', 0)} states visited), "
                     f"{len(cands)} succeeding candidates of {a} bucketed by the public input (versions "
                     f"{focus['versions']}, last block numbers {focus['last_block_numbers']}, L1 message counts "
                     f"{focus['num_l1_messages']}); {len(refused[lid])} model witnesses refused by the real side"
                     + (f"; stopped: {stop}" if stop else ""))
            attempts = [{"kind": "refute", "engine": "holon.bundle2.laws_decide (FP3)", "found": lid in found,
                         "bound": bound, "seconds": round(time.time() - t0, 1), "refused": refused[lid][:8]}]
            if lid not in found:
                res[lid] = self.unknown(lid, e, attempts, bound)
            else:
                res[lid] = self.emit_pi(lid, e, found[lid], attempts)
        return res

    def accept_pi(self, lid: str, w: dict) -> tuple[str | None, dict]:
        """The real side: both runs succeed on the laws' deployment; each step's external calls answered as the
        deployment answers them, the model still finds fact_<x> false; the public input each run passes to the callee
        (from the call's calldata) is recorded."""
        dc = self.dc
        m = dc.factory()
        traces = [list(r["prefix"]) + [r["x"]] for r in w["runs"]]
        sjs = [steps_json(dc, m, t) for t in traces]
        try:
            runs = dc.forge().traces([[real_call(s) for s in sj] for sj in sjs], jobs=2, tag="pi")
        except Exception as ex:  # noqa: BLE001
            return f"the real side cannot run it: {type(ex).__name__}: {str(ex)[:160]}", w
        reps = []
        for j, run in enumerate(runs):
            execs = [e for e in run.execs if e.id != "d"]
            bad = [i for i, e in enumerate(execs) if not e.ok]
            if bad:
                return f"run {j + 1}: step {bad[0]} reverts on the deployment", w
            member = run.members[0]
            reps.append([with_calls(st, raw_calls(execs[i], member)) for i, st in enumerate(traces[j])])
        x = LC.fact_x(lid)
        gs = []
        for rep in reps:
            g = m.s0()
            for st in rep[:-1]:
                code, g, _c = m.run_step(g, st, save=True)
                if code != 0:
                    return "with the deployment's call answers a prefix step fails on the model", w
            gs.append(g)
        o = US.Obs(m)
        if o.pred(f"fact_{x}", [{"$ref": gs[0]}, m.act(reps[0][-1]), {"$ref": gs[1]}, m.act(reps[1][-1])]):
            return "with the deployment's call answers the model finds fact true", w
        pis = []
        from .laws import view_hash_index
        hidx = view_hash_index(dc.L.I, dc.cl.laws[lid])
        for run in runs:
            xe = [e for e in run.execs if e.id != "d"][-1]
            callee = run.members[1]
            hits = [d for frm, to, d, _v, _ok, _ret in xe.calls if to == callee]
            pis.append(("0x" + hits[0][10 + 64 * hidx: 10 + 64 * (hidx + 1)]) if hits else None)
        w2 = {"runs": [{"prefix": rep[:-1], "x": rep[-1]} for rep in reps], "pi": w["pi"], "field": w["field"],
              "real": {"runs": ["ok", "ok"], "pi": pis}}
        return None, w2

    def emit_pi(self, lid: str, e: dict, w: dict, attempts: list) -> dict:
        dc = self.dc
        x = LC.fact_x(lid)
        law = self.law(lid)
        r1, r2 = w["runs"]

        def args_of(m, gs):
            return [{"$ref": gs[0]}, m.act(r1["x"]), {"$ref": gs[1]}, m.act(r2["x"])]
        kh, sh, val, states = settle_runs(dc, [r1["prefix"], r2["prefix"]], f"fact_{x}", args_of)
        m = dc.factory(empty=True, native=False)
        prefixes = {"s1": ([m.act(st) for st in r1["prefix"]], states[0]),
                    "s2": ([m.act(st) for st in r2["prefix"]], states[1])}
        values = {"x1": m.act(r1["x"]), "x2": m.act(r2["x"])}
        p = paths(dc, lid, self.gen)
        p["laws"].parent.mkdir(parents=True, exist_ok=True)
        mi, si, _vi = imports(dc, p["laws"].parent)
        sh_ = self.statement_hash(lid)
        p["laws"].write_text(FP.law_file(law, sh_, mi, si, dc.cl.hashes, counter=True).replace(
            "# GENERATED by holon.fact.proofs", "# GENERATED by holon.bundle2.laws_decide (holon.fact.proofs)"),
            encoding="utf-8")
        d = p["proofs"] / "witness"
        d.mkdir(parents=True, exist_ok=True)
        mi, si, _vi = imports(dc, d)
        li = P3.rel_import(d, p["laws"])
        tables = {"keccak256": kh, "sha256": sh}
        shape = FP.Shape(dc.cl.module, "kernel", e["basis"]["action"])
        note = (f"the witness (public_input: two runs with prefixes of {len(r1['prefix'])} and {len(r2['prefix'])} "
                "steps), every premise by computation")
        pp = d / "PROOF.bend"
        pp.write_text(FP.counter_proof(law, mi, si, li, dc.cl.hashes, prefixes, values, tables, dc.lit(), note, shape),
                      encoding="utf-8")
        checker, verdict = check(pp)
        if not (checker["marker"] == "ALL PROOFS CHECK" and verdict == "checked"):
            attempts.append({"kind": "counter", "checker": checker, "verdict": verdict, "form": "by parts"})
            pp.write_text(FP.counter_proof(law, mi, si, li, dc.cl.hashes, prefixes, values, tables, dc.lit(), note),
                          encoding="utf-8")
            checker, verdict = check(pp)
        attempts.append({"kind": "counter", "checker": checker, "verdict": verdict,
                         "evaluator": "fact is false at the witness"})
        ok = checker["marker"] == "ALL PROOFS CHECK" and verdict == "checked"
        wj = {"runs": [{"prefix": steps_json(dc, m, r["prefix"]), "x": steps_json(dc, m, [r["x"]])[0]}
                       for r in w["runs"]],
              "pi": hexw(w["pi"]), "field": [None if f is None else int(f) for f in w["field"]],
              "hashes": {"keccak256": [["0x" + k[2:], hexw(v)] for k, v in sorted(kh.items())]}}
        if not ok:
            return self.unknown(lid, e, attempts, "a model witness whose counter-law the checker did not accept",
                                laws_file=p["laws"], counter_failed=True)
        meas = dict(e["measure"])
        return self.record(lid, e, "REFUTED", attempts, p["laws"], pp, checker, verdict, wj, None,
                           extra={"real": w.get("real")}, measure=meas)

    # ---------------------------------------------------------- self_controlled
    def self_controlled(self, lid: str, deadline: float | None) -> dict:
        dc = self.dc
        e = dc.L.laws[lid]
        cal = dc.L.calibration()
        budget = int(dc.L.side["o35"]["kernel_budget_steps"])
        co = cost_coefficients(cal)
        if cal is None or cal.get("status") != "calibrated":
            att = [{"kind": "refute", "engine": "holon.bundle2.laws_decide (D4)", "found": False,
                    "bound": "uncalibrated: the cost model's calibration record is "
                             + ("missing" if cal is None else f"{cal.get('status')} (max error {cal.get('max_error')})")}]
            return self.unknown(lid, e, att, "uncalibrated")
        ks = kstar(co[0], co[1], dc.L.I.ceiling)
        if ks is None or ks > budget:
            bound = (f"calibrated (c0 {cal['c0']}, c1 {cal['c1']}, max error {cal['max_error']} at the evaluated "
                     f"backlogs); k*_model = {ks} (the least backlog k with c0 + c1 * k > G = {dc.L.I.ceiling}) exceeds "
                     f"the kernel budget of {budget} steps (o35.kernel_budget_steps): no strategy within the budget "
                     "leaves En_G on the model, and a counter-law of k*_model commits is beyond it")
            att = [{"kind": "refute", "engine": "holon.bundle2.laws_decide (D4)", "found": False, "bound": bound,
                    "calibration": {"status": cal["status"], "c0": cal["c0"], "c1": cal["c1"],
                                    "max_error": cal["max_error"]},
                    "k_star_model": ks, "kernel_budget_steps": budget}]
            return self.unknown(lid, e, att, bound)
        return decide_self_controlled(dc.L, dc.cl, lid, self.gen.parent.parent, planted=False, dc=dc, decider=self)

