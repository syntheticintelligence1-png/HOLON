def dumps(o) -> str:
    return json.dumps(o, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def bundle_entries(milestone: str, root: Path) -> dict:
    """{law_id: DERIVATION entry} of the three sub-forms (holon.rules.bundle2.RULE_OF) in laws/<M>/DERIVATION.json."""
    from ..rules import bundle2 as RB
    try:
        dv = json.loads((Path(root) / "laws" / str(milestone) / "DERIVATION.json").read_text())
    except (OSError, ValueError):
        return {}
    return {e["law_id"]: e for e in dv.get("laws") or []
            if isinstance(e, dict) and RB.RULE_OF.get(e.get("subform")) == e.get("rule")}


def _arg(argv: list, name: str):
    for i, x in enumerate(argv):
        if x == name and i + 1 < len(argv):
            return argv[i + 1]
        if x.startswith(name + "="):
            return x.split("=", 1)[1]
    return None


def ids_of(argv: list, root: Path) -> tuple[list, list] | None:
    """(the bundle laws, the other ids) a `holon run --laws ..` names; None without --laws or when it names none."""
    m, laws = _arg(argv, "--milestone"), _arg(argv, "--laws")
    if argv[:1] != ["run"] or not m or not laws:
        return None
    mine = bundle_entries(m, Path(_arg(argv, "--root") or root))
    ids = [x.strip() for x in laws.split(",") if x.strip()]
    hit = [i for i in ids if i in mine]
    if not hit:
        return None
    return hit, [i for i in ids if i not in mine]


def replay_of(L: LawsCtx, lid: str, rec: dict) -> dict | None:
    """The committed replay report's entry for a record when it replays exactly this witness (or, for the
    self_controlled law, this calibration): the record keeps it."""
    if not L.replay_path.is_file():
        return None
    rep = json.loads(L.replay_path.read_text(encoding="utf-8"))
    ent = (rep.get("laws") or {}).get(lid)
    if not ent:
        return None
    key = ent.get("key")
    if key is None or key != replay_key(L, lid, rec):
        return None
    return {"status": ent["status"], "detail": ent["detail"]}


def replay_key(L: LawsCtx, lid: str, rec: dict) -> str:
    if L.laws[lid]["subform"] == "self_controlled":
        return "calibration:" + (file_sha(L.cal_path) if L.cal_path.is_file() else "none")
    return "witness:" + hashlib.sha256(json.dumps(rec.get("witness"), sort_keys=True).encode()).hexdigest()


def main(argv: list) -> int:
    import argparse
    from ..undo.run import parse_deadline
    ap = argparse.ArgumentParser(prog="holon run (bundle laws)")
    ap.add_argument("cmd")
    ap.add_argument("--milestone", required=True)
    ap.add_argument("--laws")
    ap.add_argument("--root")
    ap.add_argument("--out")
    ap.add_argument("--gen-dir")
    ap.add_argument("--deadline")
    a, _rest = ap.parse_known_args(argv)
    root = Path(a.root).resolve() if a.root else Path(__file__).resolve().parents[2]
    deadline = parse_deadline(a.deadline)
    mine = bundle_entries(a.milestone, root)
    ids = sorted(mine) if not a.laws else [x.strip() for x in a.laws.split(",") if x.strip() in mine]
    if not ids:
        return 0
    try:
        L = LawsCtx(root, a.milestone)
        dep = L.committed_deployment()
        cl = Claims(L, dep)
        for p, d in cl.files().items():
            if not p.is_file() or p.read_bytes() != d:
                raise Refused(f"{p.relative_to(root)} is stale (run holon bundle2 laws)")
    except Refused as e:
        print(f"holon run: the bundle laws: refused: {e}", file=sys.stderr)
        return 2
    dc = DCtx(L, cl, log=print)
    out = Path(a.out) if a.out else root / "results" / a.milestone
    gen = Path(a.gen_dir) if a.gen_dir else root / "gen" / a.milestone
    D = Decider(dc, gen=gen, out=out)
    recs = {}
    try:
        pis = [i for i in ids if mine[i]["subform"] == "public_input"]
        for lid in ids:
            sub = mine[lid]["subform"]
            t0 = time.time()
            if sub == "link_domain":
                recs[lid] = D.link_domain(lid, deadline)
            elif sub == "self_controlled":
                recs[lid] = D.self_controlled(lid, deadline)
            else:
                continue
            recs[lid]["seconds"] = round(time.time() - t0, 1)
        if pis:
            t0 = time.time()
            for lid, rec in D.public_input(pis, deadline).items():
                rec["seconds"] = round(time.time() - t0, 1)
                recs[lid] = rec
    finally:
        dc.close()
    out.mkdir(parents=True, exist_ok=True)
    for lid, rec in sorted(recs.items()):
        rp = replay_of(L, lid, rec)
        if rp is not None:
            rec["replay"] = rp
        (out / f"{lid}.json").write_text(dumps(rec), encoding="utf-8")
        print(f"holon run: {lid}: {rec['status']}")
    return 0
