def norm(s: str) -> str:
    return str(s).replace("_", "").lower()


def generator_sha256(root: Path) -> str:
    from ..records import _holon_imports
    seen, todo = set(), list(GEN)
    while todo:
        r = todo.pop()
        if r in seen or not (root / r).is_file():
            continue
        seen.add(r)
        if r.endswith(".py"):
            todo.extend(sorted(_holon_imports(r, root) - seen))
    h = hashlib.sha256()
    for r in sorted(seen):
        h.update(r.encode() + b"\0" + (root / r).read_bytes() + b"\0")
    return h.hexdigest()


def hexw(v: int) -> str:
    return "0x%064x" % (int(v) & ((1 << 256) - 1))


# ------------------------------------------------------------------------------------------------ the context
class DCtx:
    """The claims at the laws' deployment, the evaluator of their combined module, the search model factory."""

    def __init__(self, L: LawsCtx, cl: Claims, log=print):
        self.L, self.cl, self.log = L, cl, log
        self.root = L.root
        ct = cl.combined
        cd = E3.cache_dir().parent / "bundle2laws" / hashlib.sha256(ct.encode()).hexdigest()[:32]
        cd.mkdir(parents=True, exist_ok=True)
        cp = cd / "combined.bend"
        if not cp.is_file() or cp.read_text(encoding="utf-8") != ct:
            tmp = cd / f"combined.{os.getpid()}.part"
            tmp.write_text(ct, encoding="utf-8")
            os.replace(tmp, cp)
        self.ev = E3.Evaluator.build(cp, cl.docm)
        hp = self.root / "results" / L.m / "sorts" / "refinement" / "hints.json"
        self.hints = S3.Hints(json.loads(hp.read_text()) if hp.is_file() else None)
        self.recs = E3.records(ct)
        a = json.loads((self.root / "gen" / L.m / "sorts" / "assignment.json").read_text())
        self.sorts = a["models"][cl.model_name]["assignment"]
        self.search = dict(L.side.get("search") or {})
        self._rev = None
        self._forge = None

    def factory(self, empty: bool = False, native: bool = True) -> S3.Model:
        i = dict(self.cl.init)
        if empty:
            i["preimages"] = []
        return S3.Model(self.ev, i, self.hints, self.root / self.L.doc_rel, native=native)

    def lit(self) -> FP.Lit:
        return FP.Lit(self.recs, set())

    def router_eval(self):
        if self._rev is None:
            from . import Ctx
            from .members import load_member
            bctx = Ctx(self.root, self.L.side["inputs"]["bundle_sidecar"])
            m = next(x for x in bctx.members() if x["name"] == self.cl.router["member"])
            self._rev = E3.Evaluator.build(self.cl.callee_model, load_member(bctx, m))
        return self._rev

    def forge(self):
        if self._forge is None:
            from .laws_calibrate import Laws
            from .laws_forge import Forge
            Lc = Laws(self.root)
            self._forge = Forge(Lc.bctx, Lc.side, None)
        return self._forge

    def close(self):
        self.ev.close()
        if self._rev is not None:
            self._rev.close()


# ------------------------------------------------------------------------------------------------ the callee's domain
def resolve(dc: DCtx, v: int, i: int) -> dict:
    """The callee's resolution of (v, i) on its model from its laws' deployment state: {"status", "word"}."""
    r = dc.cl.router
    ev = dc.router_eval()
    callee = next(m for m in dc.cl.dep["members"] if m["name"] == r["member"])
    params = next(a for a in dc.L.callee_doc(r["member"])["actions"] if a["name"] == r["resolver"])["params"]
    args = {params[0]["name"]: int(v), params[1]["name"]: int(i)}
    state = {k: v2 for k, v2 in sorted(r["storage"].items())}
    env = {"caller": "0x" + "00" * 20, "this": callee["address"], "msg.value": 0,
           "msg.data.length": int(r["env"]["length"]), "calls": [], "block.timestamp": int(dc.cl.dep["timestamp"]),
           "block.number": int(dc.cl.dep["number"]), "block.chainid": int(dc.cl.dep["chainid"])}
    run, kh, _sh = ev.run_fix(r["resolver"], state, args, env)
    f = run.out["f"]
    c = int(f["c"])
    rv = (f["rv"] or {}).get("$b", "0x") if isinstance(f["rv"], dict) else "0x"
    w = int(rv[2:66], 16) if c == 0 and len(rv) >= 66 else None
    return {"status": "ok" if c == 0 else "revert", "word": w, "dom": c == 0 and bool(w), "keys": kh}


# ------------------------------------------------------------------------------------------------ the search
class BSearch(FSR.FactSearch):
    """The prefix walk with the search's value sets (focus) and the action's candidates."""

    def __init__(self, dc: DCtx, entry: dict, depth: int, focus: dict, deadline: float | None = None):
        budget = {"prefix_depth": depth}
        super().__init__(dc.factory, dc.L.I.rollup, dc.sorts, budget, entry, log=dc.log, deadline=deadline)
        self.dc = dc
        self.focus = {norm(k): list(v) for k, v in focus.items()}
        self.depth = depth
        self.maxp = int(self.budget.get("max_prefixes", 3000))

    def focus_leaves(self, sy, a: str) -> list:
        out = []
        for leaf, ty in sy.leaves(a):
            if leaf[0] != "param":
                continue
            n = norm(leaf[-1])
            for k, vals in sorted(self.focus.items()):
                if n == k or n == k[:-1]:
                    out.append((leaf, ty, vals))
        return out

    def variants(self, g: str, trace: list, st: S3.Step) -> list:
        """st with every combination of the focus values (each repaired with them held when it fails), in order."""
        state, pools = self.ref.pools(g, trace)
        sy = S3.Synth(self.m, pools, 0)
        fl = self.focus_leaves(sy, st.action)
        out = []
        if not fl:
            return out
        prev = trace[-1] if trace else None
        for combo in itertools.product(*[vals for _l, _t, vals in fl]):
            c = st
            for (leaf, ty, _vals), v in zip(fl, combo):
                c = sy.assign(c, leaf, ty, v) if c is not None else None
            if c is None:
                continue
            self.tick()
            code, _n, _c = self.m.run_step(g, US.fresh_step(c), save=False)
            if code != 0:
                c2, code = S3.Synth(self.m, pools, 60).synth(g, st.action, prev, self.ref.ts0, start=c,
                                                             freeze={leaf for leaf, _t, _v in fl})
                c = c2
            if c is not None and code == 0:
                out.append(US.fresh_step(c))
        return out

    def successors(self, g: str, trace: list, entry: str) -> list:
        out, seen = [], set()
        for a in S3.relevance(self.doc, entry):
            st, code = self.ref.synth(g, a, trace)
            if st is None or code != 0:
                continue
            for c in [US.fresh_step(st)] + self.variants(g, trace, st):
                if c.key() in seen:
                    continue
                seen.add(c.key())
                code, g2, _calls = self.m.run_step(g, c, save=True)
                if code != 0:
                    self.m.drop([g2])
                    continue
                out.append((trace + [c], g2))
        return out

    def states(self, entry: str):
        """(depth, trace, state) breadth first from the deployment, each state once (fingerprint and clock)."""
        g0 = self.m.s0()
        seen = {(self.m.fingerprint(g0), self.ref.ts0)}
        level = [([], g0)]
        n = 1
        self.visited = 0
        for d in range(self.depth + 1):
            nxt = []
            for trace, g in level:
                self.timebox()
                self.visited += 1
                yield d, trace, g
                if d == self.depth:
                    continue
                for t2, g2 in self.successors(g, trace, entry):
                    key = (self.m.fingerprint(g2), int(t2[-1].env.get("block.timestamp") or 0))
                    if key in seen or n >= self.maxp:
                        continue
                    seen.add(key)
                    n += 1
                    nxt.append((t2, g2))
            level = nxt
            if not level:
                break
        self.n_states = n

    def candidates(self, g: str, trace: list, a: str) -> list:
        st = self.synth(g, a, trace)
        self.tick()
        out = []
        if st is None:
            return out
        first = US.fresh_step(st)
        if self.succeeds(g, first):
            out.append(first)
        for c in self.variants(g, trace, st):
            if c.key() != first.key() and self.succeeds(g, c):
                out.append(c)
        return out

    def x0(self, g: str, st: S3.Step) -> dict:
        act = self.m.act(st)
        a = bname(st.action)
        return {"$call": f"x0_{a}", "args": [self.st_of(g), act["f"]["ar"], act["f"]["en"]] + self.m.tables()}


# ------------------------------------------------------------------------------------------------ the real side
def real_call(st_json: dict) -> dict:
    env = st_json["env"]
    return {"to": 1, "caller": env["caller"], "value": int(env.get("msg.value") or 0),
            "timestamp": int(env.get("block.timestamp") or 0), "data": st_json["calldata"],
            "blobs": list(env.get("blobhash") or [])}


def with_calls(st: S3.Step, calls: list) -> S3.Step:
    env = json.loads(json.dumps(st.env))
    env.pop("_unanswered", None)
    env["calls"] = [dict(c) for c in calls]
    return S3.Step(st.action, json.loads(json.dumps(st.args)), env)


def raw_calls(e, member: str) -> list:
    """The calls a member made during a real step, as the model's environment table takes them."""
    return [{"to": US.norm_to(to), "data": d.lower(), "ok": bool(ok), "ret": ret.lower()}
            for frm, to, d, _v, ok, ret in e.calls if frm == member]


def steps_json(dc: DCtx, m: S3.Model, steps: list) -> list:
    fns = run3.fn_names(dc.cl.docm)
    return [run3.step_json(dc.cl.docm, st, fns) for st in steps]


# ------------------------------------------------------------------------------------------------ settling a witness
def settle_runs(dc: DCtx, prefixes: list, fn: str, args_of) -> tuple[dict, dict, object, list]:
    """The tables (the real hash of exactly the keys the prefixes and fn look up, from empty tables, passed as Bend
    lists), fn's value, and the decoded state after each step of each prefix."""
    prefixes = [[US.fresh_step(st) for st in p] for p in prefixes]
    m = dc.factory(empty=True, native=False)
    n0, r, gs = None, None, []
    for _round in range(8):
        gs = []
        for p in prefixes:
            g = m.s0()
            for st in p:
                code, g, _c = m.run_step(g, st, save=True)
                if code != 0:
                    raise RuntimeError(f"a witness prefix step {st.action} does not succeed (code {code})")
            gs.append(g)
        r = US.Obs(m).settle({"fn": fn, "args": lambda: list(args_of(m, gs))}, None)
        n = (len(m.kh), len(m.sh))
        if n == n0:
            break
        n0 = n
    states = []
    for p in prefixes:
        g = m.s0()
        out = []
        for st in p:
            _code, g, _c = m.run_step(g, st, save=True)
            out.append(m.ev.req({"show": g})["out"])
        states.append(out)
    return dict(m.kh), dict(m.sh), r["out"], states


