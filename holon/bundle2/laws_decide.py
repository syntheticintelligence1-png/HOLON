def imports(dc: DCtx, d: Path) -> tuple[str, str, None]:
    """The law and proof files' imports: the typed model at the laws' deployment (M) and the claims module (F), which
    holds the callee's model's copy (holon.bundle2.laws_claims.callee_copy)."""
    return P3.rel_import(d, dc.cl.model_path), P3.rel_import(d, dc.cl.claims_path), None


def claim_binders(law: dict) -> list:
    """(name, Bend type) of a link_domain or self_controlled law's binders before the tables."""
    out = []
    for b in law["statement"]["binders"]:
        ty = str(b["type"])
        if ty.startswith("Fn<"):
            continue
        out.append((b["name"], {"Reach": "M.GSt", "Act": "M.HAct", "Trace": f"List<&2, F.{LC.CALLEE_PREFIX}HAct>"}[ty]))
    return out


def claim_law_file(law: dict, sh: str, mi: str, si: str, vi: str | None, hashes: list, counter: bool) -> str:
    lid = law["law_id"]
    tb = [n for n, _h in P3.tabs_binders(hashes)]
    kw, q = ("exs", "") if counter else ("for", "+")
    lines = [HEADER, f"# law_id: {lid}   statement_hash: {sh}", "import Base", f"import {mi} as M"]
    if vi:
        lines.append(f"import {vi} as V")
    lines += [f"import {si} as F", "", f"law {law_name(lid, counter)}:"]
    idx = "".join(f"{n}, " for n in tb)
    for n in tb:
        lines.append(f"  {kw} {q}{n}: List<&2, M.HKB>")
    names = []
    for n, ty in claim_binders(law):
        lines.append(f"  {kw} {q}{n}: {ty}")
        names.append(n)
        if ty == "M.GSt":
            lines.append(f"  {kw} r_{n}: M.Reach<{idx}{n}>")
    rel = "!=" if counter else "=="
    lines.append(f"  {{F.claim_{LC.claim_x(lid)}({', '.join(names + tb)}) {rel} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def law_text(law: dict, sh: str, mi: str, si: str, hashes: list, counter: bool) -> str:
    """A bundle law's file (the law, or its counter-law): a public_input law as holon.fact.proofs states a FACT law,
    the others with claim_<x>."""
    if law.get("subform") == "public_input":
        return FP.law_file(law, sh, mi, si, hashes, counter=counter).replace(
            "# GENERATED by holon.fact.proofs", "# GENERATED by holon.bundle2.laws_decide (holon.fact.proofs)")
    return claim_law_file(law, sh, mi, si, None, hashes, counter)


def claim_counter_proof(dc: DCtx, law: dict, d: Path, li: str, prefix: list, states: list, x_val: dict, tables: dict,
                        note: str, a: str, leaves: list, inst_extra: dict) -> str:
    """The counter-law proof of a two-leaf claim (fx_imp(antecedent, consequent)) at one witness, by parts: kk, kv and
    one closed lemma per leaf (holon.fact.proofs' by-parts form), sz unfolding the claim over variables to kk of its
    leaves, the Reach chain of the prefix, and the existential tuple."""
    lid = law["law_id"]
    mi, si, vi = imports(dc, d)
    tb = P3.tabs_binders(dc.cl.hashes)
    tabs = [n for n, _h in tb]
    lit = dc.lit()
    lines = [PHEADER, "import Base", f"import {mi} as M"] + ([f"import {vi} as V"] if vi else []) + \
        [f"import {si} as F", f"import {li} as Laws", "", f"# class counter: {note}"]
    lines += P3._table_defs(tb, tables, lit)
    body, chain, state = FP._prefix_defs("1", tb, prefix, states, lit)
    lines += body
    ab = bname(a)
    f = x_val.get("f") or {}
    lines += [f"def a_x() -> M.AR_{ab}:\n  {lit.text(f['ar'])}", "", f"def e_x() -> M.HEnv:\n  {lit.text(f['en'])}", ""]
    shape = FP.Shape(dc.cl.module, "kernel", a)
    parts = FP._Parts(law, shape, tb, "fact", False, lit)
    tree = FP._tree("fx_imp(A, B)")
    inst = {"ar": "a_x()", "en": "e_x()", "s": state, **{t: f"t_{t}()" for t in tabs}, **inst_extra}
    com = parts._common(tree, [shape.qual(x) for x in leaves], inst)
    if com is None:
        raise RuntimeError("the claim's skeleton has no forced leaf values")
    cl, _lv, kv = com
    lines += cl
    x = LC.claim_x(lid)
    names = [n for n, _ty in claim_binders(law)]
    vars_sig = {"s": "+s: M.GSt", "x": None, "vt": f"vt: List<&2, F.{LC.CALLEE_PREFIX}HAct>"}
    sig = [f"+ar: M.AR_{ab}", "+en: M.HEnv"] + [vars_sig[n] for n in names if vars_sig.get(n)] + \
        [f"+{t}: List<&2, M.HKB>" for t in tabs]
    call_vars = [("M.A_" + ab + "{ar, en}") if n == "x" else n for n in names]
    lhs = f"kk({', '.join(shape.qual(x) for x in leaves)})"
    lines += [f"def sz({', '.join(sig)}) -> {{{lhs} == F.claim_{x}({', '.join(call_vars + tabs)}) : Bool}}:\n  {{==}}",
              ""]
    sz_args = ["a_x()", "e_x()"] + [inst[n] for n in names if vars_sig.get(n)] + [f"t_{t}()" for t in tabs]
    lines += [f"def cz() -> {{F.claim_{x}({', '.join([inst['s'] if n == 's' else ('M.A_' + ab + '{a_x(), e_x()}') if n == 'x' else inst[n] for n in names] + [f't_{t}()' for t in tabs])}) == False{{}} : Bool}}:\n"
              f"  (%sz({', '.join(sz_args)}) : {{_ == False{{}} : Bool}}\n  {kv})", ""]
    lines += ["def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})", ""]
    tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
    for n in reversed(names):
        if n == "s":
            tup = f"({state}, ({chain}, {tup}))"
        elif n == "x":
            tup = f"(M.A_{ab}{{a_x(), e_x()}}, {tup})"
        else:
            tup = f"({inst[n]}, {tup})"
    for t in reversed(tabs):
        tup = f"(t_{t}(), {tup})"
    lines.append(f"def Laws.{law_name(lid, True)}():\n  {tup}")
    return "\n".join(lines) + "\n"


