"""The claims of Bundle II's laws over the typed model at the laws' deployment (BUILD_PLAN row I84 = I37b; the contract
is the docstring of tests_m3/test_bundle2_laws.py, rules LD2-LD3, FP2, D2 and D6).

  <claims>/rollup.bend   the adopted member's typed model (holon.sorts.model3.generate, unchanged) whose initial state is
                         that member's storage at the laws' deployment (the bundle-laws sidecar's deployment, recorded
                         by `holon bundle2 laws`): Reach is reachability from the laws' deployment
  <claims>/claims.bend   imports it as M and the callee member's model (I80's, holon.bundle2.modelx) as V, and defines,
                         beside holon.fact.section's fixed premises (fx_tabs: CF and NZ of the hash table) and its step
                         selectors fx_sel_<a>,

    public_input     fact_<x>(s1, x1, s2, x2, kh): if x1 and x2 are calls of the action, both succeed (x1 from s1, x2
                     from s2), the tables hold CF and NZ and the public inputs (the view's hash argument, compiled from
                     the action's call record) are equal, then the consumer's field of the receiver input is equal in
                     both (both absent, or both present with one value); the kernel shape of holon.fact.section, so
                     holon.fact.proofs states and proves it (fk1/fk1b/fk2/fk3, fhit)
    link_domain      claim_<x>(s, x, vt, kh): if x is a call of the action that succeeds from s and makes its call of
                     the link (its condition in the document holds) under CF and NZ, then the callee's resolution of the
                     call's (version, index) arguments succeeds with a non-zero word from the callee's state after the
                     trace vt of the callee's actions from its laws' deployment (fv_s0); the resolution is the callee's
                     action whose returns term is the receiver of the target action's committed external call
    self_controlled  claim_<x>(s, x, kh): if x is a call of the action that succeeds from s under CF and NZ, then
                     c0 + c1 * iters(s) <= G (the calibrated coefficients, exact rationals scaled to integers; iters the
                     cost site's count term in the call's pre-context)

  combined_text()        the typed model at the laws' deployment followed by the parts over M alone, unqualified: one
                         module for the evaluator (holon.sorts.evaluate3), so the searches evaluate what Bend states.

Every action, member, term and constant comes from the sidecars, the declaration, the analysis and the documents.
"""
from __future__ import annotations

import re
from fractions import Fraction

from ..fact import section as FS
from ..machine_bend import bname
from ..sorts.model3 import GenError, wlit

HEADER = "# GENERATED by holon.bundle2.laws_claims from the bundle-laws analysis; do not edit."
CLAIMS_VERSION = "holon-bundle2-claims/0.1"


def fact_x(lid: str) -> str:
    """The FACT section's name of a public_input law (holon.rules.fact.ghost_x: the id after L_fact_)."""
    return lid[len("L_fact_"):]


def claim_x(lid: str) -> str:
    return lid[len("L_"):]


def scaled(c0, c1, ceiling: int) -> tuple[int, int, int]:
    """(A, B, C) with c0 + c1 * k <= G iff A + B * k <= C, for exact rationals c0, c1 (integers when they are)."""
    c0, c1 = Fraction(c0), Fraction(c1)
    d = c0.denominator * c1.denominator
    return int(c0 * d), int(c1 * d), int(ceiling) * d


def vword(n: int) -> str:
    return "V." + wlit(int(n))


class Claims(FS.Section):
    """The claims section over the typed model at the laws' deployment. laws: {law_id: the analysis entry, with its
    "terms" (the compiled document terms each claim reads)}; router: {"storage", "resolver", "env"} or None;
    cost: {law_id: (A, B, C)} for the self_controlled laws."""

    def __init__(self, mm, model_text: str, doc: dict, hashes: list, laws: dict, router: dict | None, cost: dict):
        super().__init__(mm, model_text, doc, hashes, [], {})
        self.laws = dict(sorted(laws.items()))
        self.router = router
        self.cost = cost
        self.vdefs: list[str] = []

    # ---------------------------------------------------------- shared
    def success(self, x: str, a: str) -> None:
        AR, HEnv, GSt = self.Q(f"AR_{a}"), self.Q("HEnv"), self.Q("GSt")
        self.add(f"# the call (ar, en) of {a} succeeds from s\ndef fx_s_{x}(+ar: {AR}, +en: {HEnv}, +s: {GSt}"
                 f"{self.hsig()}) -> Bool:\n  U32.is_eq({self.Q(f'gx_{a}_cd')}({self.Q(f'xr_{a}')}("
                 f"{self.Q('gh_get_st')}(s), ar, en{self.hargs()})), 0)")

    def x0(self, a: str, ar: str, en: str, s: str) -> str:
        return f"{self.Q(f'x0_{a}')}({self.Q('gh_get_st')}({s}), {ar}, {en}{self.hargs()})"

    def word_fn(self, name: str, a: str, term, what: str) -> None:
        code = self.compile_word(a, term)
        if self.q:   # a generic's type argument (ite(W, ..)) is a bare model type name: qualified too
            code = re.sub(r"(?<![\w.])((?:[A-Za-z_]\w*\.)?ite\()([A-Za-z_]\w*)(?=,)",
                          lambda m: m.group(1) + (self.Q(m.group(2)) if m.group(2) in self.names else m.group(2)), code)
        self.add(f"# {what}\ndef {name}(+x: {self.Q(f'X_{a}')}{self.hsig()}) -> {self.Q('W')}:\n  {code}")

    # ---------------------------------------------------------- public_input (FP2)
    def public_input(self, lid: str, e: dict) -> None:
        x = fact_x(lid)
        b = e["basis"]
        a = bname(b["action"])
        t = e["terms"]
        self.option(a)
        W, GSt, AR, HEnv, HAct = self.Q("W"), self.Q("GSt"), self.Q(f"AR_{a}"), self.Q("HEnv"), self.Q("HAct")
        hs = self.hargs()
        self.word_fn(f"fx_pi_{x}", a, t["pi"], f"the public input {b['action']} passes at {b['src']} (the view's hash "
                                               "argument, from the action's call record)")
        self.word_fn(f"fx_fv_{x}", a, t["field"], f"the consumer's field {b['consumer']['getter']} of the receiver input "
                                                  f"(bytes {b['consumer']['offset']}..{b['consumer']['offset'] + b['consumer']['width']})")
        self.word_fn(f"fx_fh_{x}", a, t["has"], "whether the receiver input holds the field (its length reaches it)")
        self.success(x, a)
        two = f"+ar1: {AR}, +en1: {HEnv}, +s1: {GSt}, +ar2: {AR}, +en2: {HEnv}, +s2: {GSt}{self.hsig()}"
        c1, c2 = self.x0(a, "ar1", "en1", "s1"), self.x0(a, "ar2", "en2", "s2")
        self.add(f"# the fields of the two calls' receiver inputs are equal (both absent, or both present with one value)\n"
                 f"def fx_d_{x}({two}) -> Bool:\n  fx_feq({self.Q('w_nz')}(fx_fh_{x}({c1}{hs})), fx_fv_{x}({c1}{hs}), "
                 f"{self.Q('w_nz')}(fx_fh_{x}({c2}{hs})), fx_fv_{x}({c2}{hs}))")
        self.add(f"# the two calls pass equal public inputs\ndef fx_c_{x}({two}) -> Bool:\n  "
                 f"{self.Q('w_eq')}(fx_pi_{x}({c1}{hs}), fx_pi_{x}({c2}{hs}))")
        self.add(f"# the premises on the tables\ndef fx_pt_{x}({self.hsig()[2:]}) -> Bool:\n  fx_tabs({self.tab_args()})")
        args = f"ar1, en1, s1, ar2, en2, s2{hs}"
        self.add(f"def fk3_{x}({two}) -> Bool:\n  fx_k3(fx_d_{x}({args}), fx_s_{x}(ar1, en1, s1{hs}), "
                 f"fx_s_{x}(ar2, en2, s2{hs}), fx_pt_{x}({self.tab_args()}), fx_c_{x}({args}))")
        self.add(f"def fh3_{x}({two}) -> Bool:\n  " + self.and_all([f"fx_s_{x}(ar1, en1, s1{hs})",
                                                                   f"fx_s_{x}(ar2, en2, s2{hs})",
                                                                   f"fx_pt_{x}({self.tab_args()})",
                                                                   f"fx_c_{x}({args})"]))
        for fn, other in (("fk", "True{}"), ("fh", "False{}")):
            self.add(f"def {fn}2_{x}({two}) -> Bool:\n  {fn}3_{x}({args})")
            self.add(f"def {fn}1b_{x}(o2: FxO_{a}, +ar1: {AR}, +en1: {HEnv}, +s1: {GSt}, +s2: {GSt}{self.hsig()}) -> "
                     f"Bool:\n  match o2:\n    case FxS_{a}{{ar2, en2}}:\n      {fn}2_{x}({args})\n"
                     f"    case FxN_{a}{{}}:\n      {other}")
            self.add(f"def {fn}1_{x}(o1: FxO_{a}, +s1: {GSt}, o2: FxO_{a}, +s2: {GSt}{self.hsig()}) -> Bool:\n"
                     f"  match o1:\n    case FxS_{a}{{ar1, en1}}:\n      {fn}1b_{x}(o2, ar1, en1, s1, s2{hs})\n"
                     f"    case FxN_{a}{{}}:\n      {other}")
            name = "fact" if fn == "fk" else "fhit"
            what = (f"{lid}: equal public inputs of two successful calls of {b['action']} imply equal "
                    f"{b['consumer']['getter']} of their receiver inputs" if fn == "fk"
                    else f"the premises of {lid} and its antecedent (G11V)")
            self.add(f"# {what}\ndef {name}_{x}(+s1: {GSt}, x1: {HAct}, +s2: {GSt}, x2: {HAct}{self.hsig()}) -> Bool:\n"
                     f"  {fn}1_{x}(fx_sel_{a}(x1), s1, fx_sel_{a}(x2), s2{hs})")

    # ---------------------------------------------------------- link_domain (LD2-LD3)
    def link_domain(self, lid: str, e: dict) -> None:
        x = claim_x(lid)
        b = e["basis"]
        a = bname(b["action"])
        t = e["terms"]
        self.option(a)
        GSt, AR, HEnv = self.Q("GSt"), self.Q(f"AR_{a}"), self.Q("HEnv")
        hs = self.hargs()
        self.word_fn(f"fx_lv_{x}", a, t["version"], f"the version argument of {b['fn']} at {b['src']}")
        self.word_fn(f"fx_li_{x}", a, t["index"], f"the index argument of {b['fn']} at {b['src']}")
        self.word_fn(f"fx_lc_{x}", a, t["cond"], f"the condition under which {b['action']} makes that call")
        self.success(x, a)
        one = f"+ar: {AR}, +en: {HEnv}, +s: {GSt}{self.hsig()}"
        c = self.x0(a, "ar", "en", "s")
        self.add(f"# the antecedent: the call succeeds, makes its call of the link, and the tables hold CF and NZ\n"
                 f"def fx_la_{x}({one}) -> Bool:\n  " + self.and_all([f"fx_s_{x}(ar, en, s{hs})",
                                                                     f"{self.Q('w_nz')}(fx_lc_{x}({c}{hs}))",
                                                                     f"fx_tabs({self.tab_args()})"]))
        if self.q == "":
            return            # the callee's part is Bend's alone (the evaluator runs the callee's model separately)
        tab = f"fv_tab({self.tab_args()})"
        dom = (f"fv_dom(V.run(vt, fv_s0(), {tab}), fv_w(fx_lv_{x}({c}{hs})), fv_w(fx_li_{x}({c}{hs})), {tab})")
        self.vdefs.append(f"# {lid}: the antecedent implies the callee's resolution of the call's (version, index)\n"
                          f"def ld3_{x}({one.replace(self.hsig(), '')}, vt: List<&2, V.HAct>{self.hsig()}) -> Bool:\n"
                          f"  fx_imp(fx_la_{x}(ar, en, s{hs}), {dom})\n")
        self.vdefs.append(f"def ld1_{x}(o: FxO_{a}, +s: {GSt}, vt: List<&2, V.HAct>{self.hsig()}) -> Bool:\n"
                          f"  match o:\n    case FxS_{a}{{ar, en}}:\n      ld3_{x}(ar, en, s, vt{hs})\n"
                          f"    case FxN_{a}{{}}:\n      True{{}}\n")
        self.vdefs.append(f"# {lid}: domain coherence at the interface (LD3)\n"
                          f"def claim_{x}(+s: {GSt}, x: {self.Q('HAct')}, vt: List<&2, V.HAct>{self.hsig()}) -> Bool:\n"
                          f"  ld1_{x}(fx_sel_{a}(x), s, vt{hs})\n")

    def callee(self) -> None:
        """The callee's part: the word and table conversions, its laws' deployment state and the resolution."""
        r = self.router
        W, HKB = self.Q("W"), self.Q("HKB")
        limbs = ", ".join(f"a{i}" for i in range(8))
        self.vdefs.append(f"# a word of the caller's model as the callee's\ndef fv_w(w: {W}) -> V.W:\n  match w:\n"
                          f"    case {W}{{{limbs}}}:\n      V.W{{{limbs}}}\n")
        self.vdefs.append(f"def fv_kb(e: {HKB}) -> V.HKB:\n  match e:\n    case {HKB}{{b, v}}:\n      V.HKB{{b, fv_w(v)}}\n")
        self.vdefs.append(f"# the hash table as the callee's model takes it (one keccak256)\n"
                          f"def fv_tab(xs: {self.ht()}) -> List<&2, V.HKB>:\n  match xs:\n    case Nil{{}}:\n      Nil{{}}\n"
                          f"    case Con{{h, t}}:\n      Con{{fv_kb(h), fv_tab(t)}}\n")
        items = [f"V.KW{{{vword(int(k, 16))}, {vword(int(v, 16))}}}" for k, v in sorted(
            r["storage"].items(), key=lambda kv: int(kv[0], 16)) if int(v, 16)]
        self.vdefs.append(f"# the callee's state at the laws' deployment\ndef fv_s0() -> V.HSt:\n  V.HSt{{"
                          + ("[" + ", ".join(items) + "]" if items else "Nil{}") + "}\n")
        env = r["env"]
        self.vdefs.append(f"# the environment of a resolution: no value, the calldata of two words, no external call\n"
                          f"def fv_env() -> V.HEnv:\n  V.HEnv{{{vword(env['caller'])}, Nil{{}}, {vword(env['length'])}, "
                          f"{vword(0)}}}\n")
        res = bname(r["resolver"])
        self.vdefs.append("# the resolution succeeds and returns a non-zero word\ndef fv_out(o: V.HOut) -> Bool:\n"
                          "  match o:\n    case V.HOut{c, rv, po, lg, tw}:\n"
                          "      Bool.and(U32.is_eq(c, 0), V.w_nz(V.b_word(rv, 0n)))\n")
        self.vdefs.append(f"# dom(vs, v, i): {r['resolver']}(v, i) on the callee's model from vs (LD2)\n"
                          f"def fv_dom(+vs: V.HSt, +v: V.W, +i: V.W, +vkh: List<&2, V.HKB>) -> Bool:\n"
                          f"  fv_out(V.run_{res}(vs, V.AR_{res}{{v, i}}, fv_env(), vkh))\n")

    # ---------------------------------------------------------- self_controlled (D2)
    def self_controlled(self, lid: str, e: dict) -> None:
        x = claim_x(lid)
        b = e["basis"]
        a = bname(b["action"])
        self.option(a)
        A, B, C = self.cost[lid]
        GSt, AR, HEnv, W = self.Q("GSt"), self.Q(f"AR_{a}"), self.Q("HEnv"), self.Q("W")
        hs = self.hargs()
        self.word_fn(f"fx_it_{x}", a, b["count"], f"iters: the count term of the cost site {b['span']}")
        self.add(f"# the calibrated cost is within the ceiling: {A} + {B} * it <= {C} (c0 + c1 * it <= G, scaled)\n"
                 f"def fx_le_{x}(+it: {W}) -> Bool:\n  {self.Q('w_le')}({self.Q('w_add')}({self.code(wlit(A))}, "
                 f"{self.Q('w_mul')}({self.code(wlit(B))}, it)), {self.code(wlit(C))})")
        self.success(x, a)
        one = f"+ar: {AR}, +en: {HEnv}, +s: {GSt}{self.hsig()}"
        self.add(f"# the antecedent: the call succeeds and the tables hold CF and NZ\ndef fx_sa_{x}({one}) -> Bool:\n"
                 f"  Bool.and(fx_s_{x}(ar, en, s{hs}), fx_tabs({self.tab_args()}))")
        c = self.x0(a, "ar", "en", "s")
        self.add(f"def ds2_{x}({one}) -> Bool:\n  fx_imp(fx_sa_{x}(ar, en, s{hs}), fx_le_{x}(fx_it_{x}({c}{hs})))")
        self.add(f"def ds1_{x}(o: FxO_{a}, +s: {GSt}{self.hsig()}) -> Bool:\n  match o:\n    case FxS_{a}{{ar, en}}:\n"
                 f"      ds2_{x}(ar, en, s{hs})\n    case FxN_{a}{{}}:\n      True{{}}")
        self.add(f"# {lid}: a successful call is within the gas ceiling (En_G, D2)\n"
                 f"def claim_{x}(+s: {GSt}, x: {self.Q('HAct')}{self.hsig()}) -> Bool:\n  ds1_{x}(fx_sel_{a}(x), s{hs})")

    # ---------------------------------------------------------- the module
    def build(self) -> list[str]:
        self.defs, self.mine, self.options, self.vdefs = [], set(), set(), []
        self.fixed()
        W = self.Q("W")
        self.add(f"# equal fields: both absent, or both present with one value\ndef fx_feq(h1: Bool, v1: {W}, h2: Bool, "
                 f"v2: {W}) -> Bool:\n  match h1:\n    case True{{}}:\n      match h2:\n        case True{{}}:\n"
                 f"          {self.Q('w_eq')}(v1, v2)\n        case False{{}}:\n          False{{}}\n    case False{{}}:\n"
                 f"      Bool.not(h2)")
        for lid, e in self.laws.items():
            {"public_input": self.public_input, "link_domain": self.link_domain,
             "self_controlled": self.self_controlled}[e["subform"]](lid, e)
        if self.q and self.router is not None and any(e["subform"] == "link_domain" for e in self.laws.values()):
            mine, self.vdefs = self.vdefs, []
            self.callee()                   # the callee's part first: Bend reads a name after its definition
            self.vdefs += mine
        clash = sorted(n for n in self.mine if n in self.names)
        if clash:
            raise GenError(f"the claims section's names clash with the typed model's: {clash}")
        return self.defs


CALLEE_PREFIX = "v_"
_TOPDEF = re.compile(r"(?m)^(?:def|type)\s+([A-Za-z_]\w*)")
_CTOR = re.compile(r"^  ([A-Za-z_]\w*)\{")
_V = re.compile(r"(?<![\w.])V\.")


def callee_copy(text: str, prefix: str = CALLEE_PREFIX) -> str:
    """The callee's model text as definitions of this module: every top-level definition, type and constructor of it
    renamed with the prefix (its imports and comment lines dropped), so that one module holds the caller's claims and
    the callee's machine and Bend's kernel form of it is one translation (holon.bindings)."""
    names = set(_TOPDEF.findall(text))
    in_type = False
    for ln in text.splitlines():
        if ln.startswith("type "):
            in_type = True
            continue
        if in_type:
            m = _CTOR.match(ln)
            if m:
                names.add(m.group(1))
                continue
            in_type = False
    body = "\n".join(ln for ln in text.splitlines() if not ln.startswith("import ") and not ln.startswith("#"))
    rx = re.compile(r"(?<![\w.])(" + "|".join(sorted(map(re.escape, names), key=len, reverse=True)) + r")(?!\w)")
    return rx.sub(lambda m: prefix + m.group(1), body).strip("\n") + "\n"


def module_text(mm, model_text: str, doc: dict, hashes: list, laws: dict, router: dict | None, cost: dict,
                model_import: str, callee_text: str | None) -> str:
    sec = Claims(mm, model_text, doc, hashes, laws, router, cost)
    defs = sec.build()
    head = [HEADER, f"# {CLAIMS_VERSION}; laws: {', '.join(sorted(laws)) or 'none'}", "import Base",
            f"import {model_import} as M", ""]
    parts = ["\n".join(head)]
    if sec.vdefs:
        if not callee_text:
            raise GenError("the link_domain claims need the callee's model")
        copy = callee_copy(callee_text)
        clash = sorted(n for n in set(_TOPDEF.findall(copy)) if n in sec.mine)
        if clash:
            raise GenError(f"the callee's copy clashes with the claims section: {clash}")
        parts.append(f"# ---- the callee's model ({router.get('model')}), its names prefixed {CALLEE_PREFIX}\n" + copy)
    parts.append("# ---- the claims\n" + "\n".join(defs + [_V.sub(CALLEE_PREFIX, d) for d in sec.vdefs]))
    return "\n".join(parts)


def combined_text(mm, model_text: str, doc: dict, hashes: list, laws: dict, cost: dict) -> str:
    sec = Claims(mm, model_text, doc, hashes, laws, None, cost)
    sec.q = ""
    defs = sec.build()
    return model_text.rstrip("\n") + "\n\n# ---- holon.bundle2.laws_claims (evaluation copy)\n" + "\n".join(defs)
