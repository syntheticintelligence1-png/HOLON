"""holon bundle2 extract (rules E1, E2, E4, E5 of the contract): generated extraction sidecars, the members'
transitions documents by I19's frontend (unchanged), and the declaration.

For every member that is not adopted (the sidecar's members and extracted_only): the generated sidecar is the base
sidecar with the member's commit, scope, source, contract, commit interfaces and output; the document and its coverage
are computed in a child process (one compile, the frontend's build and coverage_document), bounded by the sidecar's
extract.timeout_s: an extraction error or a timeout is debt {"member", "reason"} and the member has no document.

The declaration lists the members and extracted_only members with their sidecars and documents, the debt, one coverage
entry per generated document (holon.coverage's entry format), the static link rows (rule L2), the public-input views of
the link rows into a COMMIT call (rule E4) and the cost sites (rule E5).
"""
from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

from . import Ctx, Refused, Writer, file_sha, render, sha256_bytes

DECL_VERSION = "holon-bundle2/0.1"

CHILD = r"""
import json, sys
from pathlib import Path
root, side_rel, side_path, src, out = sys.argv[1:6]
sys.path.insert(0, root)
from holon.frontends import ExtractionError, Refused
from holon.frontends.solidity import _check_sidecar, _validate
from holon.frontends.solidity import compile as comp
from holon.frontends.solidity import transitions as T
import hashlib
side = json.loads(Path(side_path).read_text(encoding="utf-8"))
try:
    _check_sidecar(side, side_path)
    cfg = comp.load_config(Path(root))
    compiled = comp.compile_sources(cfg, side, Path(src), storage_layout=True)
    sha = hashlib.sha256(Path(side_path).read_bytes()).hexdigest()
    doc = T.build(compiled, side, side_rel, sha)
    _validate(doc, Path(root))
    cov = T.coverage_document(compiled, side)
except (ExtractionError, Refused) as e:
    Path(out).write_text(json.dumps({"error": f"{type(e).__name__}: {e}"}))
    sys.exit(0)
Path(out).write_text(json.dumps({"doc": doc, "coverage": cov}))
"""


def generated_sidecar(ctx: Ctx, m: dict, base: dict) -> dict:
    s = dict(base)
    s["target"] = dict(base["target"], commit=m["commit"], scope=f"bundle2 member {m['name']} ({m['contract']})")
    s["sources"] = [m["source"]]
    s["transitions"] = {"contract": m["contract"], "commit_interfaces": list(m["commit_interfaces"])}
    s["output"] = f"{ctx.out['documents']}/{m['name']}.json"
    s["doc"] = (f"GENERATED by holon bundle2 extract from {ctx.side_rel} and {ctx.side['base_sidecar']}: the extraction "
                f"sidecar of bundle2 member {m['name']} ({m['contract']}); do not edit (fix the generator instead).")
    return s


def extract_member(ctx: Ctx, m: dict, side_bytes: bytes, side_rel: str, timeout: int) -> dict:
    """{"doc", "coverage"} or {"error"} of one member, from a child process bounded by timeout seconds."""
    with tempfile.TemporaryDirectory(prefix="holon-bundle2-x-") as td:
        sp = Path(td) / "sidecar.json"
        sp.write_bytes(side_bytes)
        out = Path(td) / "out.json"
        cmd = [sys.executable, "-c", CHILD, str(ctx.root), side_rel, str(sp), ctx.source(), str(out)]
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=str(ctx.root))
        except subprocess.TimeoutExpired:
            return {"error": f"the extraction ran past the sidecar's budget of {timeout} s"}
        if p.returncode != 0 or not out.is_file():
            tail = (p.stderr or p.stdout or "").strip().splitlines()[-1:] or ["no output"]
            return {"error": f"the extraction failed: {tail[0][:400]}"}
        return json.loads(out.read_text())


def _rel_doc(ctx: Ctx, name: str) -> str:
    return f"{ctx.out['documents']}/{name}.json"


def static_links(docs: dict, wiring: dict) -> list:
    """Rule L2: [member, action, src, fn, callee, kind, target] for every call record whose receiver is a storage
    family or immutable that the wiring maps to a member; kind action / getter / receive by the callee's document."""
    rows = []
    for m in sorted(docs):
        for a in docs[m]["actions"]:
            for c in a.get("calls") or []:
                rcv = c.get("receiver")
                if not (isinstance(rcv, list) and len(rcv) == 2 and rcv[0] in ("storage", "immutable")):
                    continue
                callee = wiring.get(f"{m}.{rcv[1]}")
                if callee is None:
                    continue
                fn = c["fn"]
                if fn.startswith("address."):
                    rows.append([m, a["name"], c["src"], fn, callee, "receive", "receive"])
                    continue
                f = fn.split(".", 1)[1]
                cd = docs.get(callee) or {"actions": [], "storage": []}
                if f in {x["name"] for x in cd["actions"]}:
                    kind = "action"
                elif f in {x["name"] for x in cd["storage"]}:
                    kind = "getter"
                else:
                    kind = "unresolved"
                rows.append([m, a["name"], c["src"], fn, callee, kind, f])
    rows.sort()
    return rows


def arg_view(t):
    """Rule E4's view of one argument term."""
    if isinstance(t, list) and t:
        h = t[0]
        if h == "word" and len(t) == 3 and isinstance(t[1], list) and len(t[1]) == 2 and t[1][0] == "param" \
                and isinstance(t[2], int):
            return {"input": t[1][1], "from": t[2], "length": 32}
        if h == ">>" and len(t) == 3 and isinstance(t[2], int) and 0 < t[2] < 256 and t[2] % 8 == 0:
            w = arg_view(t[1])
            if set(w) == {"input", "from", "length"} and w["length"] == 32:
                return {"input": w["input"], "from": w["from"], "length": 32 - t[2] // 8}
        if h == "param" and len(t) == 2:
            return {"param": t[1]}
        if h == "immutable" and len(t) == 2:
            return {"immutable": t[1]}
        if h == "keccak256" and len(t) == 2 and isinstance(t[1], list) and t[1][:1] == ["abi.encodePacked"]:
            return {"hash": "keccak256", "packed": [arg_view(x) for x in t[1][1:]]}
    return {"term": t}


def public_input(docs: dict, links: list) -> list:
    """Rule E4: the argument views of every link row of kind action whose call record is a COMMIT edge."""
    out = []
    for m, a, src, fn, _callee, kind, _target in links:
        if kind != "action":
            continue
        act = next(x for x in docs[m]["actions"] if x["name"] == a)
        rec = next((c for c in act.get("calls") or [] if c["src"] == src and c["fn"] == fn and c.get("commit")), None)
        if rec is not None:
            out.append({"member": m, "action": a, "src": src, "fn": fn,
                        "args": [arg_view(x) for x in rec.get("args") or []]})
    return out


def cost_sites(docs: dict) -> list:
    """Rule E5: [member, action, loop src, seq, named by a cost term, count term] per loop record."""
    rows = []
    for m in sorted(docs):
        for a in sorted(docs[m]["actions"], key=lambda x: x["name"]):
            named = {t.get("loop") for t in (a.get("cost") or {}).get("terms") or []}
            for lp in sorted(a.get("loops") or [], key=lambda x: x["seq"]):
                rows.append([m, a["name"], lp["src"], lp["seq"], lp["src"] in named, lp.get("count")])
    return rows


def load_docs(ctx: Ctx) -> dict:
    """The members' documents (the adopted one and the generated ones present on disk), by member name."""
    docs = {}
    for m in ctx.members():
        p = ctx.root / (m["document"] if m.get("adopted") else _rel_doc(ctx, m["name"]))
        if p.is_file():
            docs[m["name"]] = json.loads(p.read_text(encoding="utf-8"))
    return docs


def run(ctx: Ctx, check: bool) -> int:
    side = ctx.side
    base_p = ctx.root / side["base_sidecar"]
    if not base_p.is_file():
        raise Refused(f"{side['base_sidecar']} is missing")
    base = json.loads(base_p.read_text(encoding="utf-8"))
    timeout = int((side.get("extract") or {}).get("timeout_s") or 1800)
    w = Writer(check)
    entries, extracted_only, debt, coverage, docs = [], [], [], [], {}
    for group, target in (("members", entries), ("extracted_only", extracted_only)):
        for m in side.get(group) or []:
            if m.get("adopted"):
                p = ctx.root / m["document"]
                if not p.is_file():
                    raise Refused(f"{m['document']} is missing")
                docs[m["name"]] = json.loads(p.read_text(encoding="utf-8"))
                target.append({"name": m["name"], "contract": m["contract"],
                               "commit": docs[m["name"]]["target"]["commit"], "sidecar": None,
                               "document": {"path": m["document"], "sha256": file_sha(p)}})
                continue
            sc = generated_sidecar(ctx, m, base)
            sb = render(sc)
            srel = f"{ctx.out['sidecars']}/{m['name']}.json"
            w.put(ctx.root / srel, sb)
            print(f"holon bundle2 extract: {m['name']} ({m['contract']}) ...", flush=True)
            res = extract_member(ctx, m, sb, srel, timeout)
            e = {"name": m["name"], "contract": m["contract"], "commit": m["commit"],
                 "sidecar": {"path": srel, "sha256": sha256_bytes(sb)}, "document": None}
            if "error" in res:
                debt.append({"member": m["name"], "reason": res["error"]})
                print(f"holon bundle2 extract: {m['name']}: debt: {res['error']}", flush=True)
            else:
                drel = _rel_doc(ctx, m["name"])
                db = render(res["doc"])
                w.put(ctx.root / drel, db)
                e["document"] = {"path": drel, "sha256": sha256_bytes(db)}
                coverage.append(dict(res["coverage"], document=drel))
                if group == "members":
                    docs[m["name"]] = res["doc"]
                cv = res["coverage"]
                print(f"holon bundle2 extract: {m['name']}: {len(res['doc']['actions'])} actions, "
                      f"{cv['statements']} statements, {len(cv['debt'])} debt, {len(cv['unaccounted'])} unaccounted",
                      flush=True)
            target.append(e)
    links = static_links(docs, side.get("wiring") or {})
    decl = {"bundle2_version": DECL_VERSION, "sidecar": {"path": ctx.side_rel, "sha256": ctx.side_sha},
            "members": entries, "extracted_only": extracted_only, "debt": debt,
            "coverage": sorted(coverage, key=lambda d: d["document"]), "links": links,
            "public_input": public_input(docs, links), "cost_sites": cost_sites(docs)}
    w.put(ctx.path("declaration"), render(decl))
    return w.finish("extract")
