"""The protocol diagram 𝔇 as data: carriers, edges, the diagram (whitepaper §4, Defs 4.1-4.3).

Every object serialises with `to_json()` to plain JSON values. Lists come out sorted by id and
the writer sorts keys, so a diagram is a deterministic function of its inputs (AGENTS.md rule 7).
`Diagram.to_json` also checks the structure: unique ids, known kinds and classes, and edges whose
endpoints are carriers of the same diagram.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field

DIAGRAM_VERSION = "holon-diagram/0.1"
CARRIER_CLASSES = ("rep", "state", "env", "digest", "buffer")
EDGE_KINDS = ("CODEC", "HASH", "STORE", "LOAD", "CONS", "TRANS", "MIG", "SYM")
REACH = ("external", "inductive", "image")
DEBT_KINDS = ("HASH", "UNMODELLED", "ACCESS", "LEDGER", "PRINCIPAL", "SHADOW")


class DiagramError(Exception):
    """A diagram that is not well formed, or a facts construct no adapter maps."""


def _merge(base: dict, extra: dict, what: str) -> dict:
    clash = sorted(set(base) & set(extra))
    if clash:
        raise DiagramError(f"{what}: extra keys {clash} shadow fixed fields")
    out = dict(base)
    out.update(extra)
    return out


@dataclass
class Carrier:
    """Def 4.1: a value set (base_type), a reachable subset (reach) and a refined sort (sort_ref).

    reach: "external" for interface carriers (R^ext, everything any principal can place there),
    "inductive" for state carriers (Reach, generated by S0 and the TRANS edges), "image" for
    carriers populated by the edges into them, None when the facts do not determine it.
    sort_ref stays None until the sorts iterations (I13, I15) assign refined sorts."""
    id: str
    cls: str
    base_type: str
    sort_ref: str | None = None
    interface: bool = False
    reach: str | None = None
    extra: dict = field(default_factory=dict)

    def to_json(self) -> dict:
        if self.cls not in CARRIER_CLASSES:
            raise DiagramError(f"carrier {self.id}: class {self.cls!r} not in {CARRIER_CLASSES}")
        if self.reach is not None and self.reach not in REACH:
            raise DiagramError(f"carrier {self.id}: reach {self.reach!r} not in {REACH}")
        return _merge({"id": self.id, "cls": self.cls, "base_type": self.base_type, "sort_ref": self.sort_ref,
                       "interface": self.interface, "reach": self.reach}, self.extra, f"carrier {self.id}")


@dataclass
class Edge:
    """Def 4.2: kind, interpretation (src -> tgt), component and version labels.

    `access` holds index-sensitive read and write sets: lists of [carrier, key] pairs, where the
    key is an index term rendered as infix text without spaces, "*" (every slot, or the whole of a
    scalar register) or "#" (the length only). TRANS edges also carry a principal class."""
    id: str
    kind: str
    src: str
    tgt: str
    component: str
    version: str | None = None
    partial: bool = False
    env: bool = False
    pseudo: bool = False
    principal_class: str | None = None
    reads: list = field(default_factory=list)
    writes: list = field(default_factory=list)
    extra: dict = field(default_factory=dict)

    def to_json(self) -> dict:
        if self.kind not in EDGE_KINDS:
            raise DiagramError(f"edge {self.id}: kind {self.kind!r} not in {EDGE_KINDS}")
        return _merge({"id": self.id, "kind": self.kind, "src": self.src, "tgt": self.tgt, "component": self.component,
                       "version": self.version, "partial": self.partial, "env": self.env, "pseudo": self.pseudo,
                       "principal_class": self.principal_class,
                       "access": {"reads": sorted_terms(self.reads), "writes": sorted_terms(self.writes)}},
                      self.extra, f"edge {self.id}")


def sorted_terms(terms) -> list[list[str]]:
    return [list(t) for t in sorted({tuple(t) for t in terms})]


def is_index_term(key: str) -> bool:
    return key not in ("*", "#")


@dataclass
class Diagram:
    """Def 4.3, one per fact document."""
    model: str
    facts: str
    facts_sha256: str
    facts_version: str
    carriers: list[Carrier] = field(default_factory=list)
    edges: list[Edge] = field(default_factory=list)
    principal_classes: list[dict] = field(default_factory=list)
    coverage_debt: list[dict] = field(default_factory=list)
    mapped_sections: dict = field(default_factory=dict)
    extra: dict = field(default_factory=dict)

    def carrier(self, cid: str) -> Carrier:
        for c in self.carriers:
            if c.id == cid:
                return c
        raise DiagramError(f"no carrier {cid}")

    def add_carrier(self, c: Carrier) -> Carrier:
        if any(x.id == c.id for x in self.carriers):
            raise DiagramError(f"two carriers named {c.id}")
        self.carriers.append(c)
        return c

    def add_edge(self, e: Edge) -> Edge:
        if any(x.id == e.id for x in self.edges):
            raise DiagramError(f"two edges named {e.id}")
        self.edges.append(e)
        return e

    def debt(self, kind: str, what: str, **more) -> None:
        if kind not in DEBT_KINDS:
            raise DiagramError(f"debt kind {kind!r} not in {DEBT_KINDS}")
        self.coverage_debt.append({"kind": kind, "what": what, **more})

    def index_terms(self) -> list[list[str]]:
        """Every [carrier, term] an edge reads or writes at a specific index of a keyed carrier (one
        with a key_space: a sequence). Accesses to a record's fields are projections, part of the
        product structure, and are not index terms."""
        keyed = {c.id for c in self.carriers if c.extra.get("key_space") is not None}
        out = set()
        for e in self.edges:
            for cid, key in list(e.reads) + list(e.writes):
                if is_index_term(key) and cid in keyed:
                    out.add((cid, key))
        return [list(t) for t in sorted(out)]

    def to_json(self) -> dict:
        cids = [c.id for c in self.carriers]
        if len(set(cids)) != len(cids):
            raise DiagramError("duplicate carrier ids")
        eids = [e.id for e in self.edges]
        if len(set(eids)) != len(eids):
            raise DiagramError("duplicate edge ids")
        for e in self.edges:
            for end in (e.src, e.tgt):
                if end not in cids:
                    raise DiagramError(f"edge {e.id}: endpoint {end} is not a carrier")
            for cid, _ in list(e.reads) + list(e.writes):
                if cid not in cids:
                    raise DiagramError(f"edge {e.id}: access to {cid}, which is not a carrier")
        pids = [p["id"] for p in self.principal_classes]
        if len(set(pids)) != len(pids):
            raise DiagramError("duplicate principal class ids")
        for e in self.edges:
            if e.principal_class is not None and e.principal_class not in pids:
                raise DiagramError(f"edge {e.id}: unknown principal class {e.principal_class}")
        debt = sorted(self.coverage_debt, key=lambda d: json.dumps(d, sort_keys=True))
        base = {"diagram_version": DIAGRAM_VERSION, "model": self.model, "facts": self.facts,
                "facts_sha256": self.facts_sha256, "facts_version": self.facts_version,
                "carriers": [c.to_json() for c in sorted(self.carriers, key=lambda c: c.id)],
                "edges": [e.to_json() for e in sorted(self.edges, key=lambda e: e.id)],
                "principal_classes": sorted(self.principal_classes, key=lambda p: p["id"]),
                "index_terms": self.index_terms(), "coverage_debt": debt,
                "mapped_sections": dict(sorted(self.mapped_sections.items()))}
        return _merge(base, self.extra, "diagram")


def dumps(obj) -> str:
    """The canonical text of a generated diagram: sorted keys, indent 2, trailing newline."""
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"
