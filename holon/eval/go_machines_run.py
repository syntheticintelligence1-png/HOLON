"""python -m holon eval go-machines [--root DIR] [--entries ID,..] [--out PATH] (I105): the smoke measure of the Go
machine frontend on the corpus entries that I51 extracted Go documents from.

For every selected entry (default: every corpus entry I51 ran (results/eval/holon/corpus.json, status run) whose
extracted documents are all Go), at its pre-fix commit, exactly as I51 (holon.eval.holon_run; spec/M4/lib/i51_run.json):
  * the checkout, the Go packages of the entry's .go files, their source (module or generated go.work) and the codec
    frontend's config are I51's own (holon_run.checkout, go_inputs, go_source);
  * holon extract go_machines writes one transitions document per machine of each package;
  * the typed stages over those documents, with I51's generated sidecars: holon sorts, types, model, disch and derive
    (holon_run._rules's first five steps; the runs of derived laws are not made here: I107 scores).
The record, results/M6/I105/corpus.json (canonical JSON, no timings): machines.nil_maps (I110: the nil-map rule the
machine configs were given, as holon.frontends.go_machines.nil_maps_mode reads it); per entry {id, system, repo, prefix_commit,
documents: [{unit, status, reason, machines: [{file, contract, actions, families, kv_families, guards, writes, havoc,
debt: {kind: n}, sha256}]}], machines, actions, stages: {stage: {status, detail}}, pipeline: complete | refused,
refused_at (the first stage not ok, or "extract" when no machine document was written), laws (the number of L*.json
that derive wrote)}. Paths inside the scratch directory, the checkout or the home directory are normalized as I51 does.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
import tempfile
from pathlib import Path

from . import common
from . import holon_run as H

ROOT = Path(__file__).resolve().parents[2]
OUT = "results/M6/I105/corpus.json"
RUN_VERSION = "holon-eval-go-machines/0.1"
STAGES = ("sorts", "types", "model", "disch", "derive")


def dumps(obj) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def default_entries(root: Path) -> list[str]:
    rows = json.loads((root / "results" / "eval" / "holon" / "corpus.json").read_text(encoding="utf-8"))["rows"]
    out = []
    for r in rows:
        docs = [d for d in r.get("documents") or [] if d.get("status") == "extracted"]
        if r.get("status") == "run" and docs and all(d["language"] == "go" for d in docs):
            out.append(r["id"])
    return sorted(out)


def typed(R: H.Runner, S: Path, rel: str, M: str, proto: dict, files: list[str]) -> dict:
    """holon_run._rules's sidecars and its first five steps over the documents (stops at the first that is not ok)."""
    sd = S / rel / "sidecars"
    docs = [f"{rel}/facts/{f}" for f in files]
    side = {
        "sort_types": {"sort_types_version": proto["typed"]["sort_types_version"],
                       "doc": "I105: generated by holon eval go-machines (spec/M4/lib/i51_run.json typed)",
                       "documents": docs, "seeds": proto["typed"]["seeds"], "binding": proto["typed"]["binding"],
                       "search": proto["typed"]["search"]},
        "disch": {**{k: proto["disch"][k] for k in ("disch_version", "binding", "hypotheses", "hypothesis_verdicts",
                                                     "r0", "search")},
                  "doc": "I105: generated by holon eval go-machines (spec/M4/lib/i51_run.json disch)", "documents": docs,
                  "model_sidecar": f"{rel}/sidecars/sort_types.json"},
        "undo": {**{k: proto["undo"][k] for k in ("undo_version", "observation", "premise", "search")},
                 "doc": "I105: generated by holon eval go-machines (spec/M4/lib/i51_run.json undo)",
                 "sort_types": f"{rel}/sidecars/sort_types.json"},
        "fact": {**{k: proto["fact"][k] for k in ("fact_version", "binding", "hypotheses", "verdicts", "search",
                                                   "measure", "term_size")},
                 "doc": "I105: generated by holon eval go-machines (spec/M4/lib/i51_run.json fact)", "documents": docs,
                 "sort_types": f"{rel}/sidecars/sort_types.json"},
    }
    for n, v in side.items():
        (sd / f"{n}.json").write_text(dumps(v))
    ts, ds, us, fs = (f"{rel}/sidecars/{n}.json" for n in ("sort_types", "disch", "undo", "fact"))
    sorts = f"gen/{M}/sorts"
    steps = [("sorts", ["sorts", "--milestone", M, "--root", str(S), "--sidecar", ts, "--out", sorts]),
             ("types", ["types", "--milestone", M, "--root", str(S), "--sidecar", ts, "--out", sorts]),
             ("model", ["model", "--milestone", M, "--root", str(S), "--sidecar", ts, "--out", f"{sorts}/models"]),
             ("disch", ["disch", "--milestone", M, "--root", str(S), "--sidecar", ds, "--out", f"gen/{M}/disch"]),
             ("derive", ["derive", "--milestone", M, "--root", str(S), "--catalog", proto["catalog"], "--sidecar", ts,
                         "--disch", ds, "--undo-sidecar", us, "--fact-sidecar", fs, "--out", f"laws/{M}",
                         "--obstructions", f"{sorts}/obstructions.json"])]
    stages = {}
    for name, args in steps:
        res = R.holon(name, args)
        stages[name] = {"status": res["status"], "detail": res["detail"][-1500:]}
        if res["status"] != "ok":
            break
    return stages


def summarize(doc: dict, data: bytes, name: str) -> dict:
    debt: dict = {}
    for d in doc.get("debt") or []:
        debt[d["kind"]] = debt.get(d["kind"], 0) + 1
    acts = doc.get("actions") or []
    return {"file": name, "contract": doc["contract"], "actions": len(acts), "families": len(doc.get("storage") or []),
            "kv_families": sorted(f["name"] for f in doc.get("storage") or [] if f["kind"] == "mapping"
                                  and f.get("key") == "bytes" and f.get("value") == "bytes"),
            "guards": sum(len(a["guards"]) for a in acts), "writes": sum(len(a["writes"]) for a in acts),
            "havoc": sum(1 for a in acts for w in a["writes"]
                         if isinstance(w["value"], list) and w["value"][:1] == ["unknown"]),
            "debt": dict(sorted(debt.items())), "sha256": hashlib.sha256(data).hexdigest()}


def run_entry(entry: dict, proto: dict, root: Path) -> dict:
    tmp = Path(tempfile.mkdtemp(prefix="holon-i105-"))
    ck = tmp / "checkout"
    ctx = H.Ctx(tmp, ck)
    row = {k: entry[k] for k in ("id", "system", "repo", "prefix_commit")}
    clone = None
    subs: list = []
    try:
        clone, _tree = H.checkout(entry, ck)
        owner, name = common.gh_slug(entry["repo"])
        S = H.scratch_root(root, tmp, f"{owner}/{name}", ck)
        rel = f"results/eval/i105/{entry['id']}"
        (S / rel / "sidecars").mkdir(parents=True)
        (S / rel / "facts").mkdir(parents=True)
        R = H.Runner(ctx, S, proto, {})
        docs, files = [], []
        if proto.get("layout"):   # I108: the submodules at their gitlinked commits (holon.eval.layout L3)
            from . import layout as LY
            subs = LY.submodules(ck, entry["prefix_commit"], entry["repo"], init=True, root=root)
            row["submodules"] = [{k: ctx.norm(v) if isinstance(v, str) else v for k, v in r.items()} for r in subs]
        for d in H.go_inputs(entry, proto, ck):
            if "stem" not in d:
                docs.append({"unit": d.get("unit"), "status": "failed", "reason": d.get("reason"), "machines": []})
                continue
            if proto.get("go_machines"):
                # I108 (--protocol): the protocol's go rules (toolchain, work_replace) and the nil-map opt-in
                src, _how = H.go_source(ck, d.pop("module_dir"), tmp, proto["go"].get("work_replace"))
                if src is None:
                    docs.append({"unit": d.get("unit"), "status": "failed", "reason": _how, "machines": []})
                    continue
            else:
                src, _how = H.go_source(ck, d.pop("module_dir"), tmp)
            cfg = {"config_version": proto["go"]["config_version"],
                   "doc": f"I105: generated from corpus entry {entry['id']} by holon eval go-machines (I51's go config)",
                   "target": {"repo": f"{owner}/{name}", "commit": entry["prefix_commit"]},
                   "source": {"path": "<given by --src>"}, "documents": {d["stem"]: [d["unit"]]},
                   "primitives": dict(proto["go"]["primitives"]), "limits": dict(proto["go"]["limits"])}
            if proto.get("go_machines"):
                cfg["doc"] = f"{proto['iteration']}: generated from corpus entry {entry['id']} by holon eval go-machines"
                if proto["go"].get("toolchain"):
                    cfg["toolchain"] = proto["go"]["toolchain"]
                cfg["machines"] = {"nil_maps": proto["go_machines"]["nil_maps"]}
            cp = S / rel / "sidecars" / f"{d['stem']}.json"
            cp.write_text(dumps(cfg))
            out = tmp / "machines" / d["stem"]
            res = R.holon("extract", ["extract", "go_machines", "--root", str(S), "--config", str(cp), "--src", str(src),
                                      "--out-dir", str(out)])
            ms = []
            if res["status"] == "ok":
                for p in sorted(out.glob("*.extracted.json")):
                    data = p.read_bytes()
                    shutil.copy(p, S / rel / "facts" / p.name)
                    files.append(p.name)
                    ms.append(summarize(json.loads(data.decode("utf-8")), data, p.name))
            docs.append({"unit": d["unit"], "status": "extracted" if res["status"] == "ok" else "failed",
                         "reason": None if res["status"] == "ok" else res["detail"][-1500:], "machines": ms})
        row["documents"] = docs
        row["machines"] = sum(len(d["machines"]) for d in docs)
        row["actions"] = sum(m["actions"] for d in docs for m in d["machines"])
        if files:
            row["stages"] = typed(R, S, rel, proto["milestone"], proto, sorted(files))
        else:
            row["stages"] = {}
        bad = [s for s in STAGES if row["stages"].get(s, {}).get("status") != "ok"]
        row["pipeline"] = "complete" if files and not bad else "refused"
        row["refused_at"] = None if row["pipeline"] == "complete" else (bad[0] if files else "extract")
        row["laws"] = len(list((S / "laws" / proto["milestone"]).glob("L*.json")))
    finally:
        if subs:
            from . import layout as LY
            LY.drop_submodules(ck, subs)
        if clone is not None:
            H.drop_worktree(clone, ck)
        shutil.rmtree(tmp, ignore_errors=True)
    return row


def cli(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(prog="python -m holon eval go-machines")
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--entries")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--protocol", help="a run protocol with a go_machines key (I108); default I51's, as I105 ran")
    a = ap.parse_args(argv)
    root = Path(a.root).resolve()
    proto = common.load_json(root / (a.protocol or "spec/M4/lib/i51_run.json"))
    corpus = {e["id"]: e for e in common.load_json(root / "spec" / "eval" / "corpus.json")["entries"]}
    if a.protocol:
        if not proto.get("go_machines"):
            raise common.Refused(f"{a.protocol} has no go_machines key")
        proto["_path"] = a.protocol
        if a.out == OUT:
            a.out = proto["go_machines"]["out"]
        ids = a.entries.split(",") if a.entries else sorted(
            i for i, e in corpus.items() if any(f.endswith(".go") for f in e["files"]))
    else:
        ids = a.entries.split(",") if a.entries else default_entries(root)
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(max(1, a.jobs)) as ex:
        rows = list(ex.map(lambda i: run_entry(corpus[i], proto, root), ids))
    from ..frontends.go_machines import nil_maps_mode
    # I110 (c; I107's Question 3): the nil-map rule every machine config of the run was given, as the frontend reads it
    # (the protocol's go_machines.nil_maps; without --protocol no config names one, so the frontend's default)
    nil = nil_maps_mode({"machines": {"nil_maps": proto["go_machines"]["nil_maps"]}} if proto.get("go_machines") else {})
    out = {"run_version": RUN_VERSION, "doc": __doc__.split("\n\n")[0].strip(), "milestone": proto["milestone"],
           "machines": {"nil_maps": nil}, "rows": sorted(rows, key=lambda r: r["id"]),
           "summary": {"entries": len(rows), "machines": sum(r["machines"] for r in rows),
                       "actions": sum(r["actions"] for r in rows),
                       "complete": sorted(r["id"] for r in rows if r["pipeline"] == "complete"),
                       "refused_at": {r["id"]: r["refused_at"] for r in sorted(rows, key=lambda r: r["id"])
                                      if r["refused_at"]},
                       "laws": sum(r["laws"] for r in rows)}}
    p = root / a.out
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(dumps(out), encoding="utf-8")
    print(f"holon eval go-machines: {len(rows)} entries, {out['summary']['machines']} machines, "
          f"{out['summary']['actions']} actions, complete {out['summary']['complete']}, laws {out['summary']['laws']} "
          f"-> {a.out}")
    return 0
