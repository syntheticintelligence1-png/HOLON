"""Rule M3: the head members' models, gen/<M>/bundle/models/.

Each member's document compiled by holon.sorts.model3 as `holon model --untyped` compiles one (no sort section), its
initial state the member's storage after the bundle's deployment (replay/<M>/bundle/deployment.json, rule C1). An
action model3 cannot compile is debt with its GenError (models.json), and the model is compiled without it: its steps
are unsupported under M4. models.json: {"models_version", "models": {member: {"path", "sha256", "document_sha256"}},
"debt": [{"member", "action", "error"}]}.
"""
from __future__ import annotations

import hashlib
import json

from . import Ctx, Refused, render, sha256_bytes, write_or_check

MODELS_VERSION = "holon-bundle-models/0.1"


def head_members(ctx: Ctx) -> list:
    return [m for m in ctx.members() if not m.get("adopted") and m.get("commit") == ctx.side["target"]["head"]]


def init_of(ctx: Ctx, name: str) -> dict:
    p = ctx.path(ctx.out("deployment"))
    if not p.is_file():
        raise Refused(f"{ctx.out('deployment')} is missing (holon bundle refine writes it)")
    dep = json.loads(p.read_text(encoding="utf-8"))
    st = dep["members"][name]["storage"]
    return {"binding": ctx.out("deployment"), "storage": dict(st)}


def compile_member(ctx: Ctx, name: str, init: dict) -> tuple:
    """(model text, debt [(action, error)]) of one member: model3's untyped machine, an action it cannot compile
    left out as debt."""
    from ..machine import ExtractedModel
    from ..rules.sort import DocBasis, hash_functions
    from ..sorts import model3
    from ..sorts.typed_sidecar import load as load_ts
    from . import members as M
    rel = ctx.document_rel(ctx.member(name))
    data = ctx.path(rel).read_bytes()
    doc = json.loads(data)
    info = M.info(ctx, name)
    seeds = json.loads(load_ts(ctx.milestone, ctx.root, None).seeds.read_text(encoding="utf-8"))
    mname = model3.model_name(rel)
    assignment = {"models": {mname: {"assignment": {}}}, "sorts_sha256": None, "sites": []}
    storage = {int(k, 16): int(v, 16) for k, v in init["storage"].items()}
    debt: dict = {}
    names = {a["name"] for a in doc["actions"]}
    while True:
        d2 = dict(doc, actions=[a for a in doc["actions"] if a["name"] not in debt])
        m = ExtractedModel(d2, info, None, sha256_bytes(data))
        header = [f"# GENERATED by holon.bundle.model (holon.sorts.model3) from {rel}; do not edit.",
                  f"# facts_sha256: {sha256_bytes(data)}",
                  f"# model_version: {model3.MODEL3_VERSION} (untyped: the sort section off)",
                  f"# initial state: the deployment of {init['binding']} "
                  f"({len([v for v in storage.values() if v])} non-zero slots)",
                  f"# model debt (actions left out): {', '.join(sorted(debt)) or 'none'}"]
        try:
            text, _mm = model3.build_text(m, typed=False, sorts={}, seeds=seeds, init=storage,
                                          hashes=hash_functions(d2) or ["keccak256"],
                                          basis=DocBasis(rel, d2, mname, assignment, seeds), site_rows=[],
                                          header=header)
            return text, sorted(debt.items())
        except model3.GenError as e:
            a = str(e).split(":", 1)[0].strip()
            if a not in names or a in debt:
                return None, [("*", str(e)[:1000])]
            debt[a] = str(e)[:1000]


def build(ctx: Ctx, log=print) -> dict:
    files, models, debt = {}, {}, []
    out = ctx.out("models")
    for m in head_members(ctx):
        text, d = compile_member(ctx, m["name"], init_of(ctx, m["name"]))
        for a, err in d:
            debt.append({"member": m["name"], "action": a, "error": err})
        log(f"{m['name']}: {len(d)} actions in model debt")
        if text is None:
            continue
        bp = f"{out}/{m['name']}.bend"
        files[bp] = text.encode("utf-8")
        files[f"{out}/{m['name']}.init.json"] = render(init_of(ctx, m["name"]))
        models[m["name"]] = {"path": bp, "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                             "document_sha256": sha256_bytes(ctx.path(ctx.document_rel(m)).read_bytes())}
    files[f"{out}/models.json"] = render({"models_version": MODELS_VERSION, "models": models, "debt": debt})
    return files


def main(ctx: Ctx, check: bool, log) -> int:
    return write_or_check(ctx, build(ctx, log), check, owned=[ctx.out("models")], log=log)
