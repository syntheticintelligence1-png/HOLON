"""Rules E1-E5 and L2: the members' generated sidecars and documents, the declaration and the static links.

For every member but the adopted one (and every extracted_only member), the generated extraction sidecar is the bundle
sidecar's base_sidecar with the member's commit, scope, source, contract, commit interfaces and output; the document
is what holon.frontends.solidity extracts from it, over the checkout when the member's commit is its HEAD, else over
the commit's tree materialized from the repository's objects (rule E3, holon.frontends.solidity.trees). A member whose
extraction fails is debt with its error and has no document. The declaration lists the members, the documents, every
generated document's coverage entry (holon.coverage's entry format) and the links of rule L2.
"""
from __future__ import annotations

import json
from pathlib import Path

from . import BUNDLE_VERSION, Ctx, render, sha256_bytes, write_or_check


def generated_sidecar(ctx: Ctx, m: dict) -> dict:
    base = ctx.load(ctx.side["base_sidecar"])
    sc = json.loads(json.dumps(base))
    sc["target"] = dict(base["target"], commit=m["commit"], scope=f"bundle member {m['name']} ({m['contract']})")
    sc["sources"] = [m["source"]]
    sc["transitions"] = {"contract": m["contract"], "commit_interfaces": list(m.get("commit_interfaces") or [])}
    sc["output"] = ctx.document_rel(m)
    sc["doc"] = (f"Generated by holon bundle extract from {ctx.side_rel} (rule E1): {ctx.side['base_sidecar']} with "
                 f"the member's commit, scope, source, contract, commit interfaces and output.")
    return sc


def source_for(ctx: Ctx, commit: str) -> str:
    """The source tree of a commit: the checkout when it is its HEAD, else the commit's tree from git objects (E3)."""
    from ..frontends.solidity import trees
    repo = ctx.source_repo()
    if trees.head(repo) == commit:
        return repo
    paths = (ctx.side.get("acquisition") or {}).get("registry", {}).get("contract", {}).get("build_paths") \
        or ["contracts"]
    return str(trees.tree(repo, commit, paths))


def links(docs: dict, wiring: dict) -> list:
    """Rule L2: [member, action, src, fn, callee, kind, target] for every call record whose receiver is a storage or
    immutable variable the wiring names; kind "receive" for a low-level address call, "action" when the callee's
    document has an action of the called name, "getter" when it has a storage family of that name. Sorted."""
    rows = []
    for name in sorted(docs):
        for act in docs[name]["actions"]:
            for call in act.get("calls") or []:
                rcv = call.get("receiver")
                if not (isinstance(rcv, list) and len(rcv) == 2 and rcv[0] in ("storage", "immutable")):
                    continue
                callee = wiring.get(f"{name}.{rcv[1]}")
                if callee is None:
                    continue
                fn = call["fn"]
                if fn.startswith("address."):
                    rows.append([name, act["name"], call["src"], fn, callee, "receive", "receive"])
                    continue
                f = fn.split(".", 1)[1]
                cd = docs.get(callee) or {"actions": [], "storage": []}
                if any(x["name"] == f for x in cd["actions"]):
                    kind = "action"
                elif any(x["name"] == f for x in cd["storage"]):
                    kind = "getter"
                else:
                    kind = "unresolved"
                rows.append([name, act["name"], call["src"], fn, callee, kind, f])
    return sorted(rows)


def build(ctx: Ctx, log=print) -> dict:
    """{relative path: bytes} of every file extract writes."""
    from ..frontends import ExtractionError
    from ..frontends.solidity import coverage_document, extract_document
    import tempfile
    files, entries, extracted_only, debt, coverage, docs = {}, [], [], [], [], {}
    for m in ctx.all_members():
        if m.get("adopted"):
            rel = m["document"]
            docs[m["name"]] = ctx.load(rel)
            entries.append({"name": m["name"], "contract": m["contract"], "commit": ctx.commit_of(m), "sidecar": None,
                            "document": ctx.ref(rel)})
            continue
        sc = generated_sidecar(ctx, m)
        srel = f"{ctx.out('sidecars')}/{m['name']}.json"
        sdata = render(sc)
        files[srel] = sdata
        sp = ctx.path(srel)
        # the frontend reads the sidecar from disk (its path and sha256 enter the document)
        tmpdir = None
        if not (sp.is_file() and sp.read_bytes() == sdata):
            tmpdir = tempfile.TemporaryDirectory(prefix="holon-bundle-")
            eff = Path(tmpdir.name) / sp.name
            eff.write_bytes(sdata)
        else:
            eff = sp
        try:
            src = source_for(ctx, m["commit"])
            try:
                doc = extract_document(sc, eff, ctx.root, src)
                cov = coverage_document(sc, eff, ctx.root, src)
            except ExtractionError as e:
                debt.append({"member": m["name"], "reason": str(e)[:2000]})
                log(f"{m['name']}: extraction error (debt): {str(e)[:200]}")
                continue
        finally:
            if tmpdir is not None:
                tmpdir.cleanup()
        doc["extraction"]["sidecar"] = {"path": srel, "sha256": sha256_bytes(sdata)}
        drel = sc["output"]
        ddata = render(doc)
        files[drel] = ddata
        docs[m["name"]] = doc
        e = {"name": m["name"], "contract": m["contract"], "commit": m["commit"],
             "sidecar": {"path": srel, "sha256": sha256_bytes(sdata)},
             "document": {"path": drel, "sha256": sha256_bytes(ddata)}}
        (extracted_only if m in (ctx.side.get("extracted_only") or []) else entries).append(e)
        coverage.append(dict(cov, document=drel))
        log(f"{m['name']}: {len(doc['actions'])} actions, {len(cov['debt'])} debt entries, "
            f"{len(cov['unaccounted'])} unaccounted")
    member_docs = {k: v for k, v in docs.items() if any(x["name"] == k for x in ctx.members())}
    decl = {"bundle_version": BUNDLE_VERSION, "sidecar": ctx.ref(ctx.side_rel), "members": entries,
            "extracted_only": extracted_only, "debt": debt, "coverage": sorted(coverage, key=lambda d: d["document"]),
            "links": links(member_docs, ctx.side["wiring"])}
    files[ctx.out("declaration")] = render(decl)
    return files


def main(ctx: Ctx, check: bool, log) -> int:
    files = build(ctx, log)
    return write_or_check(ctx, files, check, owned=[ctx.out("sidecars"), ctx.out("documents")], log=log)
