"""The bundle's laws' artifacts (I86; the contract is the docstring of tests_m3/test_bundle_laws.py, rules LM1-LM2):

  python -m holon bundle laws [--milestone M3] [--root DIR] [--check]

writes, from the milestone's bundle-laws sidecar, the declaration and the member documents (holon.rules.bundle.basis):

  gen/<M>/bundle_laws/laws.json            the basis as holon computes it (every site of the six sub-forms, its law ids)
  gen/<M>/bundle_laws/models/<member>.bend the law model of the adopted member (I69's rule M3: model3's untyped machine,
                                           the bundle deployment's storage as s0); a head member's law model is its I69
                                           model, gen/<M>/bundle/models/<member>.bend
  gen/<M>/bundle_laws/claims/<member>.bend the claims module of each member with a law: every term and predicate a law
                                           names, compiled from the document's terms by the member's own model3
                                           generator (its term compiler, locate and read_word), qualified by M

Claims (rules PY3, CS3, K7, PP2): <x>_key (a payer law's key, over ar and en), <x>_credit (a ledger-class conservation
law's credit, over s, ar, en, kh), <tag>_b (a keyed obligation's blocked condition B(s, k) over kh), in_<class> (a step's
action belongs to the class), b_ok (a step's checks hold), <x> (a keyed law's predicate over kh, s, k, a), <x>_enc and
<x>_field (a push law's leaf preimage over the encoding's arguments, and its index field), x the law id lower-cased.

Nothing here names a target. Exit codes as holon bundle's.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

from . import Ctx, Refused, render, sha256_bytes, write_or_check

LAWS_VERSION = "holon-bundle-laws/0.1"
OUT = "bundle_laws"
HEADER = "# GENERATED by holon.bundle.laws (I86) from the bundle-laws sidecar, the declaration and {doc}; do not edit."


def out_dir(ctx: Ctx) -> str:
    return f"gen/{ctx.milestone}/{OUT}"


def law_model_rel(ctx: Ctx, member: dict) -> str:
    """LM1: the law model of a member: its I69 model, or (the adopted member) the one this command writes."""
    if member.get("adopted"):
        return f"{out_dir(ctx)}/models/{member['name']}.bend"
    return f"{ctx.out('models')}/{member['name']}.bend"


def machine_of(ctx: Ctx, name: str):
    """(model text, the model3 generator that built it) of a member's law model, built as I69's rule M3 builds it."""
    from ..machine import ExtractedModel
    from ..rules.sort import DocBasis, hash_functions
    from ..sorts import model3
    from ..sorts.typed_sidecar import load as load_ts
    from . import members as MB
    from .model import init_of
    m = ctx.member(name)
    rel = ctx.document_rel(m)
    data = ctx.path(rel).read_bytes()
    doc = json.loads(data)
    seeds = json.loads(load_ts(ctx.milestone, ctx.root, None).seeds.read_text(encoding="utf-8"))
    mname = model3.model_name(rel)
    assignment = {"models": {mname: {"assignment": {}}}, "sorts_sha256": None, "sites": []}
    init = init_of(ctx, name)
    storage = {int(k, 16): int(v, 16) for k, v in init["storage"].items()}
    # a head member's machine as I69's rule M3 builds it; the adopted member's as holon.machine.load_extracted loads it
    em = MB.model(ctx, name) if m.get("adopted") else ExtractedModel(doc, MB.info(ctx, name), None, sha256_bytes(data))
    who = "holon.bundle.laws" if m.get("adopted") else "holon.bundle.model"   # a head member's: I69's model, as written
    header = [f"# GENERATED by {who} (holon.sorts.model3) from {rel}; do not edit.",
              f"# facts_sha256: {sha256_bytes(data)}",
              f"# model_version: {model3.MODEL3_VERSION} (untyped: the sort section off)",
              f"# initial state: the deployment of {init['binding']} "
              f"({len([v for v in storage.values() if v])} non-zero slots)",
              "# model debt (actions left out): none"]
    text, mm = model3.build_text(em, typed=False, sorts={}, seeds=seeds, init=storage,
                                 hashes=hash_functions(doc) or ["keccak256"],
                                 basis=DocBasis(rel, doc, mname, assignment, seeds), site_rows=[], header=header)
    return text, mm


class Claims:
    """Terms of a member's document compiled by its model3 generator in a claims scope: the storage view s, the table
    kh, the arguments ar and the environment en are the claims' parameters (gx), and named terms are substituted."""

    def __init__(self, mm, text: str):
        from ..sorts.proofs3 import model_names
        self.mm, self.names = mm, model_names(text)
        self.shifts0 = set(mm.shifts)

    def compile(self, action: str, term, kind: str = "w", subst: list | None = None,
                view: str = "s", ar: str = "ar", en: str = "en") -> str:
        from ..machine import canonical
        from ..sorts import model3 as M3
        from ..sorts.proofs3 import qualify
        mm = self.mm
        sc = M3.Scope(action, "x", {canonical(t): v for t, v in (subst or [])})
        fields = {"kh": "kh", "st": view, "ov": view, "ar": ar, "en": en}

        def gx(_sc, fld):
            if fld not in fields:
                raise M3.GenError(f"a claims term reads the context field {fld}")
            return fields[fld]
        mm.gx = gx
        try:
            if kind == "bool":
                code = mm.cond(term, sc)
            elif kind == "b":
                code = mm.b(term, sc)
            else:
                code = mm.w(term, sc)
        finally:
            del mm.gx
        if set(mm.shifts) != self.shifts0:
            raise Refused(f"a claims term needs a shift the law model does not define: {str(term)[:120]}")
        return qualify(code, self.names)


def claims_module(ctx: Ctx, member: dict, sites: list, text: str, mm) -> str:
    """The claims module of one member (LM2)."""
    from ..machine_bend import bname
    from ..rules import bundle as RB
    cl = Claims(mm, text)
    model_import = os.path.relpath(ctx.path(law_model_rel(ctx, member)), ctx.path(f"{out_dir(ctx)}/claims"))
    lines = [HEADER.format(doc=ctx.document_rel(ctx.member(member["name"]))), "import Base",
             f"import {model_import.replace(os.sep, '/')} as M", ""]
    acts = [a for a in member["doc"]["actions"]]
    hact = [a["name"] for a in acts]
    need_steps = False
    keyed_done = set()
    for lid, sub, site, cls in sites:
        x = lid.lower()
        if sub == "payer":
            if len(site["keys"]) != 1:
                raise Refused(f"{lid}: {len(site['keys'])} keys (one law per key is not this generator's form)")
            a = site["action"]
            code = cl.compile(a, site["keys"][0])
            lines.append(f"# {lid}: the price call's key (PY3)\n"
                         f"def {x}_key(+ar: M.AR_{bname(a)}, +en: M.HEnv) -> M.W:\n  {code}\n")
        elif sub == "conservation" and site["class"] == "ledger":
            lines += _credit_defs(cl, site, x)
        elif sub in ("keyed_blocking", "keyed_external", "keyed_external_none"):
            need_steps = True
            if site["tag"] not in keyed_done:
                keyed_done.add(site["tag"])
                bcode = cl.compile(site["action"], site["blocked"], "bool", subst=[(["var", "k"], ("k", "w"))])
                lines.append(f"# {site['obligation']}: the blocked condition of {site['check']} at the key k (K2)\n"
                             f"def b_{site['tag']}(+s: M.HSt, +k: M.W, +kh: List<&2, M.HKB>) -> Bool:\n  {bcode}\n")
            pre = f"b_{site['tag']}(s, k, kh)"
            post = f"b_{site['tag']}(M.step(a, s, kh), k, kh)"
            on = f"Bool.and(in_{cls}(a), b_ok(a, s, kh))"
            if sub == "keyed_external":
                body = f"Bool.and({pre}, Bool.and({on}, Bool.not({post})))"
            else:
                body = f"Bool.or(Bool.not(Bool.and({pre}, {on})), {post})"
            lines.append(f"# {lid} (K7)\n"
                         f"def {x}(+kh: List<&2, M.HKB>, +s: M.HSt, +k: M.W, +a: M.HAct) -> Bool:\n  {body}\n")
        elif sub == "push":
            lines += _push_defs(cl, site, x)
    if need_steps:
        lines.insert(4, _class_defs(member, sites, hact) + _ok_def(acts))
    return "\n".join(lines).rstrip("\n") + "\n"


def _class_defs(member: dict, sites: list, hact: list) -> str:
    from ..machine_bend import bname
    from ..rules import bundle as RB
    out = []
    seen = set()
    for _lid, sub, site, cls in sites:
        if cls is None or cls in seen:
            continue
        seen.add(cls)
        cl_acts = set(site["classes"][cls])
        cases = "".join(f"    case M.A_{bname(n)}{{ar, en}}:\n      {'True{}' if n in cl_acts else 'False{}'}\n"
                        for n in hact)
        out.append(f"# the actions of the class {cls} (DC1-DC2)\ndef in_{cls}(a: M.HAct) -> Bool:\n  match a:\n{cases}")
    return "\n".join(out)


def _ok_def(acts: list) -> str:
    from ..machine_bend import bname
    cases = "".join(f"    case M.A_{bname(a['name'])}{{ar, en}}:\n"
                    f"      U32.is_eq(M.chk_{bname(a['name'])}(s, ar, en, kh), 0)\n" for a in acts)
    return ("\n# a step's checks all hold (its check code is 0)\n"
            f"def b_ok(a: M.HAct, +s: M.HSt, +kh: List<&2, M.HKB>) -> Bool:\n  match a:\n{cases}\n")


def _credit_defs(cl: Claims, site: dict, x: str) -> list:
    """CS3, ledger class: msg.value's credit, the sum over the credited mapping cells of post(c) - pre(c) when the
    write's value reads c, else post(c); post by M.post_<action>."""
    from ..machine_bend import bname
    a = site["action"]
    doc_act = site["_act"]
    terms = []
    for w in doc_act.get("writes") or []:
        if w["family"] not in site["mapping_ledgers"]:
            continue
        cells = _credited_cells(w)
        for cell in cells:
            pre = cl.compile(a, cell, view="s")
            post = cl.compile(a, cell, view=f"M.post_{bname(a)}(s, ar, en, kh)")
            terms.append(f"M.w_sub({post}, {pre})" if _reads(w.get("value"), cell) else post)
    if not terms:
        raise Refused(f"{site['law_id']}: no credited mapping cell")
    acc = terms[0]
    for t in terms[1:]:
        acc = f"M.w_add({acc}, {t})"
    return [f"# {site['law_id']}: msg.value's credit (CS3, ledger class)\n"
            f"def {x}_credit(+s: M.HSt, +ar: M.AR_{bname(a)}, +en: M.HEnv, +kh: List<&2, M.HKB>) -> M.W:\n  {acc}\n"]


def _reads(t, cell) -> bool:
    if t == cell:
        return True
    return isinstance(t, list) and any(_reads(x, cell) for x in t)


def _credited_cells(w: dict) -> list:
    """The storage cells a write of a mapping family credits with msg.value: the cell itself for a word write, the
    members whose value reads msg.value for a whole-struct write."""
    base = ["storage", w["family"]]
    for acc in w.get("path") or []:
        if acc[0] == "map":
            base = ["map", base, acc[1]]
        elif acc[0] == "member":
            base = ["member", base, acc[1]]
        else:
            raise Refused(f"a credited write at a {acc[0]} accessor")
    v = w.get("value")
    if isinstance(v, list) and v[:1] == ["struct"]:
        return [["member", base, mname] for mname, mv in v[2] if _reads(mv, ["env", "msg.value"])]
    return [base]


def _push_defs(cl: Claims, site: dict, x: str) -> list:
    """PP2: the leaf preimage over the encoding's arguments (one parameter each) and its index field."""
    args = site["arguments"]
    subst, ps = [], []
    for i, (name, ty) in enumerate(args):
        kind = "b" if ty in ("bytes", "string") else "w"
        subst.append((["param", name], (f"a{i}", kind)))
        ps.append(f"+a{i}: {'List<&2, U32>' if kind == 'b' else 'M.W'}")
    enc = cl.compile(site["action"], site["leaf"][1], "b", subst=subst)
    if site["index_offset"] is None:
        raise Refused(f"{site['law_id']}: the index field has no static offset")
    return [f"# {site['law_id']}: the leaf's preimage, abi.encodeWithSignature over the arguments (PP2)\n"
            f"def {x}_enc({', '.join(ps)}) -> List<&2, U32>:\n  {enc}\n",
            f"# {site['law_id']}: the index field, 32 bytes at offset {site['index_offset']} of the preimage (PP2)\n"
            f"def {x}_field(b: List<&2, U32>) -> List<&2, U32>:\n  M.b_take(32n, M.b_drop(b, {site['index_offset']}n), 0)\n"]


# ------------------------------------------------------------------------------------------------ the command
def build(ctx: Ctx, log=print) -> dict:
    from ..rules import bundle as RB
    b = RB.basis(ctx.root, ctx.milestone)
    if b is None:
        raise Refused(f"spec/{ctx.milestone}/lib/{RB.SIDECAR} is missing")
    files = {}
    files[f"{out_dir(ctx)}/laws.json"] = render({
        "bundle_laws_version": LAWS_VERSION, "law_ids": b["law_ids"],
        "payer": b["payer"], "conservation": b["conservation"],
        "keyed": [dict(RB.site_entry("keyed_blocking", k), laws=k["laws"]) for k in b["keyed"]],
        "push": b["push"], "inputs": [{"path": p, "sha256": h} for p, h in sorted(b["inputs"].items())]})
    by_member: dict = {}
    for lid, (sub, mname, site, cls) in sorted(RB.sites(b).items()):
        by_member.setdefault(mname, []).append((lid, sub, site, cls))
    mem = {m["name"]: m for m in b["members"]}
    for mname, sites in sorted(by_member.items()):
        m = mem[mname]
        text, mm = machine_of(ctx, mname)
        if m["adopted"]:
            files[law_model_rel(ctx, m)] = text.encode("utf-8")
        else:
            have = ctx.path(law_model_rel(ctx, m)).read_text(encoding="utf-8")
            if have != text:
                raise Refused(f"{law_model_rel(ctx, m)} is not what holon bundle model writes now (re-make it first)")
        acts = {a["name"]: a for a in m["doc"]["actions"]}
        sites = [(lid, sub, dict(site, _act=acts.get(site.get("action"))) if sub == "conservation" else site, cls)
                 for lid, sub, site, cls in sites]
        files[f"{out_dir(ctx)}/claims/{mname}.bend"] = claims_module(ctx, m, sites, text, mm).encode("utf-8")
        log(f"{mname}: {len(sites)} laws")
    return files


def main(ctx: Ctx, check: bool, log=print) -> int:
    files = build(ctx, log)
    return write_or_check(ctx, files, check, owned=[f"{out_dir(ctx)}/claims", f"{out_dir(ctx)}/models"], log=log)
