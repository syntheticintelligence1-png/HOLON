"""holon run for the bundle laws (I86 = I36b; the contract is the docstring of tests_m3/test_bundle_laws.py, rules
W1-W5, D1-D4 and RC1-RC3):

  python -m holon run --milestone M3 --laws <ids>     the bundle laws a --laws list names (holon.__main__ routes them)

The six sub-forms of holon.rules.bundle are decided over each law's law model (LM1) and its member's claims module
(LM2, gen/<M>/bundle_laws/claims/<member>.bend), the two compiled together (outside the repository, as holon.disch.run
compiles a model with its section) and run by I30's evaluator (holon.sorts.evaluate3) with the real keccak256 of every
key they look up.

  search (W1-W4)  the bundle corpus run once by I69's harness (forge, holon.bundle.harness; cached outside the
                  repository by the inputs' sha256) and by the linked machine (holon.bundle.machine): a candidate is a
                  top-level frame of the law's member, with its input, environment and call answers as the linked
                  machine gave them; its state is the law model's own state chain over the trace's earlier top-level
                  frames of that member, from M.s0 (a step that fails a check leaves it, as M.step does); a keyed
                  candidate pairs the frame with every key the obligation's key term took at an earlier frame of the
                  guarded action; a conservation law with no corpus witness then tries the value variants
  decide (D1-D3)  a witness is written as the counter-law (or, for an existential law, the law's proof) in A30's
                  shape (the hash table, each prefix action and literal state, one closed lemma per prefix step, the
                  Reach chain, the premise and the claim as closed lemmas) and checked by the pinned Bend; a forall law
                  with no witness and no unmet dependency gets its sub-form's proof generator (PY4: the key is the
                  caller term; PP5: cf applied to e, then congruence under the field); anything else is UNKNOWN
  records (RC1)   results/<M>/<id>.json as the typed M3 records are written (holon.records), with the rule, sub-form,
                  dependencies, attempts, bound, replay (holon bundle replay-laws fills it), witness and inhabitant

A witness's environment keeps the linked machine's values, but its code table is reduced to the entries whose removal
changes the step's outcome on the model (the law quantifies over the environment; the reduced one runs the same step
and keeps the proof files small). Nothing here names a target, an action, a class or a law.
"""
