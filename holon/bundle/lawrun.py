def generator_sha256(root: Path) -> str:
    """The digest of the bundle-law deciders' closure: these modules, their holon imports and I30's runner closure."""
    from ..records import _holon_imports
    from ..sorts.run3 import GEN3
    seen, todo = set(), list(GEN_LAWS) + list(GEN3)
    while todo:
        r = todo.pop()
        if r in seen or not (root / r).is_file():
            continue
        seen.add(r)
        if r.endswith(".py"):
            todo.extend(sorted(_holon_imports(r, root) - seen))
    h = hashlib.sha256()
    for r in sorted(seen):
        h.update(r.encode() + b"\0" + (root / r).read_bytes() + b"\0")
    return h.hexdigest()


def bend_version() -> str:
    from ..sorts.run3 import bend_version as bv
    return bv()


def check(p: Path) -> dict:
    """bend2's check of a file, then BendTT's re-check where the environment provides it (D4: recorded, never a
    status)."""
    from .. import bend
    r = bend.check(p)
    out = {"exit_code": r.code, "marker": "ALL PROOFS CHECK" if r.ok else "SOME PROOFS FAIL", "seconds": r.seconds}
    verdict = "not_run"
    if r.ok and bend.verdict_enabled():
        v = bend.check_verdict(p)
        verdict = "checked" if v.ok else ("budget_exhausted" if v.code is None else "failed")
        out["bendtt"] = {"exit_code": v.code, "seconds": v.seconds, "output_tail": (v.out or "")[-800:]}
    if not r.ok:
        out["failing"] = (r.out or "")[-1500:]
    return {"checker": out, "ok": bool(r.ok), "verdict": verdict}


class Decider:
    def __init__(self, lctx: LawCtx, results: Path, gen: Path, jobs: int = 4, log=print):
        from .. import ir
        self.lctx, self.root, self.results, self.gen, self.log = lctx, lctx.root, results, gen, log
        self.jobs = jobs
        self.registry = ir.load_registry(lctx.m, self.root)
        self.models: dict = {}
        self._traces = None
        self._found: dict = {}

    def close(self):
        for m in self.models.values():
            m.close()

    def rel(self, p: Path) -> str:
        p = Path(p)
        try:
            return (p.parent.resolve() / p.name).relative_to(self.root).as_posix()
        except ValueError:
            return p.as_posix()

    def model(self, name: str) -> LawModel:
        if name not in self.models:
            self.models[name] = LawModel(self.lctx, name)
        return self.models[name]

    def searched(self, lm: LawModel) -> tuple:
        """W1-W4 for every searchable law of the member at once (one pass over the corpus), cached."""
        if lm.name not in self._found:
            lids = sorted(lid for lid, (sub, mname, site, _c) in self.lctx.sites.items() if mname == lm.name
                          and sub != "push" and law_lines(lid, sub, site, law_kind(sub)) is not None)
            self._found[lm.name] = search(self.lctx, lm, self.traces(), lids, self.log)
        return self._found[lm.name]

    def traces(self) -> list:
        if self._traces is None:
            b = self.lctx.bctx
            drec, trs = corpus_run(b, self.jobs, self.log)
            corpus = b.load(b.out("corpus"))
            self._traces = corpus_frames(b, drec, corpus, trs, set(self.lctx.members))
        return self._traces

    def paths(self, lid: str) -> dict:
        return {"laws": self.gen / "laws" / lid / "LAWS.bend", "proof": self.gen / "proofs" / lid / "PROOF.bend",
                "nv_laws": self.gen / lid / "nonvac" / "LAWS.bend", "nv_proof": self.gen / lid / "nonvac" / "PROOF.bend"}

    def imports(self, d: Path, mname: str, laws: Path) -> tuple:
        return (rel_import(d, self.lctx.model_path(mname)), rel_import(d, self.lctx.claims_path(mname)),
                rel_import(d, laws))

    def write_law(self, lid: str, sub: str, site: dict, mname: str, kind: str, path: Path) -> Path | None:
        sh = self.registry["statements"][lid]
        text = law_text(lid, sub, site, sh, rel_import(path.parent, self.lctx.model_path(mname)),
                        rel_import(path.parent, self.lctx.claims_path(mname)), kind)
        if text is None:
            return None
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def prefix(self, lm: LawModel, w: Witness, kh: dict) -> tuple:
        """The witness's prefix, re-run on the model with each step's environment reduced (same outcomes): (table
        lines, trace lines, chain, state term, the pre-state's reference)."""
        ref, _val = lm.s0()
        acts, states = [], []
        for act, want in w.chain:
            a = act["$r"][2:]
            name = next(n for n in lm.doc.actions if bname(n) == a)
            en = lm.reduce_env(name, ref, act["f"]["ar"], act["f"]["en"], kh)
            act2 = lm.act(name, act["f"]["ar"], en)
            ref, val = lm.step(act2, ref, kh)
            if val != want:
                raise LawRefused(f"the reduced environment changed a prefix step of {name}")
            acts.append(lm.lit.text(act2))
            states.append(lm.lit.typed(val, "HSt"))
        body, chain, state = _trace_defs(acts, states)
        return body, chain, state, ref

    def decide(self, lid: str) -> dict:
        from ..bend import escape_hatches
        t0 = time.monotonic()
        lctx = self.lctx
        law = lctx.law(lid)
        sub, mname, site, cls = site_of(lctx, lid)
        deps = deps_of(sub, site)
        p = self.paths(lid)
        for q in p.values():
            if q.exists():
                q.unlink()
        attempts, witness, prim, nonvac, status, bound = [], None, None, None, "UNKNOWN", None
        expressible = law_lines(lid, sub, site, law_kind(sub)) is not None
        lm = None
        w = None
        if sub == "push":
            attempts.append({"kind": "search", "found": False, "bound": "no corpus source: the claim is over an erased "
                             "hash and two argument tuples (W1's sources apply to frame laws)"})
        elif not expressible:
            attempts.append({"kind": "search", "found": False,
                             "bound": "not expressible over the M3 model, which records no value outflow (CS3: the "
                                      "sidecar's dependency outflow)"})
        else:
            lm = self.model(mname)
            found, tried = self.searched(lm)
            w = found.get(lid)
            t = tried[lid]
            bound = (f"{t['corpus']} corpus candidates over {len(self.traces())} traces"
                     + (f", {t['value_variant']} value-variant candidates" if sub == "conservation" else ""))
            attempts.append({"kind": "search", "found": w is not None, "bound": bound, "stage": "W1-W4",
                             "source": w.source if w else None})
        if w is not None:
            kind = "exists" if sub == "keyed_external" else "counter"
            lp = self.write_law(lid, sub, site, mname, kind, p["laws"])
            kh = dict(w.kh)
            fr = w.fr
            # the pre-state and the candidate's literals, re-run with the reduced environments
            body, chain, state, ref = self.prefix(lm, w, kh)
            ar = lm.ar(fr["action"], fr["args"])
            env = dict(fr["env"]) if w.value is None else dict(fr["env"], **{"msg.value": w.value})
            en = lm.en(env)
            if sub in KEYED:
                act = lm.act(fr["action"], ar, lm.reduce_env(fr["action"], ref, ar, en, kh))
                j = Judge(lid, sub, site)
                if j.keyed(lm, ref, act, w.key, kh) != (sub == "keyed_external"):
                    raise LawRefused(f"{lid}: the reduced witness does not decide the claim")
                frame = (lm.lit.word(h32(w.key)), lm.lit.text(act))
            else:
                en = lm.reduce_env(fr["action"], ref, ar, en, kh)
                if Judge(lid, sub, site).frame(lm, ref, fr, ar, en, kh) is not False:
                    raise LawRefused(f"{lid}: the reduced witness does not decide the claim")
                frame = (lm.lit.text(ar), lm.lit.text(en))
            tlines = _table_def(kh, lm.lit)
            p["proof"].parent.mkdir(parents=True, exist_ok=True)
            note = (f"witness: trace {w.trace['id']}, frame {fr['k']} ({fr['action']}), source {w.source}; "
                    f"{len(w.chain)} prefix steps of the member")
            p["proof"].write_text(witness_proof(lid, sub, site, kind, self.imports(p["proof"].parent, mname, lp),
                                                (tlines, body, chain, state), frame, note), encoding="utf-8")
            hits = escape_hatches(p["proof"].read_text(encoding="utf-8"))
            chk = check(p["proof"])
            attempts.append({"kind": "exists" if kind == "exists" else "counter", "checker": chk["checker"],
                             "verdict": chk["verdict"], "escape_hatches": hits})
            if chk["ok"] and not hits:
                status = "PROVED" if kind == "exists" else "REFUTED"
                prim = {"proof": self.rel(p["proof"]), "checker": chk["checker"], "verdict": chk["verdict"]}
                witness = self.witness_json(lm, w, kh, sub, site)
                bound = None
                if kind == "exists":   # an existential law's checked proof is its own inhabitant (G11V)
                    nonvac = {"status": "inhabited", "law": self.rel(lp), "witness": witness, "reachable": True,
                              "degenerate": False, "parent_statement_hash": self.registry["statements"][lid],
                              "checker": chk["checker"], "bound": "the checked existential proof is its own inhabitant"}
        elif sub == "push" or (sub == "payer" and all(k == ["caller"] for k in site["keys"])):
            lp = self.write_law(lid, sub, site, mname, "forall", p["laws"])
            p["proof"].parent.mkdir(parents=True, exist_ok=True)
            imps = self.imports(p["proof"].parent, mname, lp)
            p["proof"].write_text(push_proof(lid, site, imps) if sub == "push" else payer_proof(lid, imps),
                                  encoding="utf-8")
            hits = escape_hatches(p["proof"].read_text(encoding="utf-8"))
            chk = check(p["proof"])
            attempts.append({"kind": "proof", "generator": "core_inj_push" if sub == "push" else "caller_key",
                             "checker": chk["checker"], "verdict": chk["verdict"], "escape_hatches": hits})
            if chk["ok"] and not hits:
                status = "PROVED"
                prim = {"proof": self.rel(p["proof"]), "checker": chk["checker"], "verdict": chk["verdict"]}
                nonvac = self.inhabit(lid, sub, site, mname, lm)
                bound = None
        if status == "UNKNOWN":
            if expressible and not p["laws"].exists():
                self.write_law(lid, sub, site, mname, law_kind(sub), p["laws"])
            if p["proof"].exists():
                p["proof"].unlink()
            if deps:
                attempts.append({"kind": "proof", "found": False,
                                 "reason": f"no proof attempted: an unmet dependency ({', '.join(deps)}; CS4, K8)"})
            elif sub not in ("push", "payer") or w is None:
                attempts.append({"kind": "proof", "found": False,
                                 "reason": "no proof generator applies to this sub-form (D2: PY4 and PP5 only)"})
            bound = "; ".join(str(a.get("bound") or a.get("reason") or "") for a in attempts if a.get("bound")
                              or a.get("reason"))
        for d in (p["proof"].parent,):
            if d.exists() and not any(d.iterdir()):
                d.rmdir()
        lpath = p["laws"] if p["laws"].exists() else None
        rec = self.record(law, sub, mname, site, cls, status, witness, attempts, lpath, prim, bound, nonvac, deps)
        rec["seconds"] = round(time.monotonic() - t0, 3)
        return rec

    def inhabit(self, lid: str, sub: str, site: dict, mname: str, lm) -> dict:
        """D2: a checked inhabitant of a PROVED law's premises (gen/<M>/<id>/nonvac/): a corpus frame for PY, x1 = x2
        = the first PP6 sample for PP."""
        p = self.paths(lid)
        lp = self.write_law(lid, sub, site, mname, "nonvac", p["nv_laws"])
        imps = self.imports(p["nv_proof"].parent, mname, lp)
        sh = self.registry["statements"][lid]
        base = {"law": self.rel(lp), "parent_statement_hash": sh, "degenerate": False}
        if sub == "push":
            lm = lm or self.model(mname)
            sample = (self.lctx.side.get("push") or {}).get("samples")[0]
            p["nv_proof"].write_text(push_nonvac_proof(lid, site, imps, sample, lm.lit), encoding="utf-8")
            w_json = {"x1": sample, "x2": sample, "hash": "a constant function"}
            reach = None
        else:
            lm = lm or self.model(mname)
            w = self.first_ok(lm, site)
            if w is None:
                return {**base, "status": "unknown", "witness": None, "reachable": None,
                        "bound": "no corpus frame of the action passes its checks on the model"}
            kh = dict(w.kh)
            body, chain, state, ref = self.prefix(lm, w, kh)
            fr = w.fr
            ar = lm.ar(fr["action"], fr["args"])
            en = lm.reduce_env(fr["action"], ref, ar, lm.en(fr["env"]), kh)
            if lm.chk(fr["action"], ref, ar, en, kh) != 0:
                raise LawRefused(f"{lid}: the inhabitant's frame fails its checks")
            note = f"inhabitant: trace {w.trace['id']}, frame {fr['k']} ({fr['action']}); {len(w.chain)} prefix steps"
            p["nv_proof"].write_text(witness_proof(lid, sub, site, "nonvac", imps,
                                                   (_table_def(kh, lm.lit), body, chain, state),
                                                   (lm.lit.text(ar), lm.lit.text(en)), note), encoding="utf-8")
            w_json = {"trace": w.trace["id"], "frame": fr["k"], "caller": fr["caller"].lower(), "value": str(fr["value"])}
            reach = True
        chk = check(p["nv_proof"])
        if not chk["ok"]:
            return {**base, "status": "unknown", "witness": w_json, "reachable": reach,
                    "bound": f"the inhabitant does not check: {chk['checker'].get('failing', '')[-400:]}"}
        return {**base, "status": "inhabited", "witness": w_json, "reachable": reach, "checker": chk["checker"],
                "bound": "a checked inhabitant of the premises"}

    def first_ok(self, lm: LawModel, site: dict) -> Witness | None:
        """The first corpus frame of the action whose checks hold on the model's own chain."""
        s0_ref, s0_val = lm.s0()
        for tr in self.traces():
            mine = [f for f in tr["frames"] if f["member"] == lm.name]
            if not any(f["action"] == site["action"] for f in mine):
                continue
            kh: dict = {}
            ref, val, chain = s0_ref, s0_val, []
            for fr in mine:
                ar, en = lm.ar(fr["action"], fr["args"]), lm.en(fr["env"])
                if fr["action"] == site["action"] and lm.chk(fr["action"], ref, ar, en, kh) == 0:
                    return Witness("corpus", tr, fr, list(chain), kh)
                act = lm.act(fr["action"], ar, en)
                nref, nval = lm.step(act, ref, kh)
                if nval != val:
                    chain.append((act, nval))
                ref, val = nref, nval
        return None

    def witness_json(self, lm: LawModel, w: Witness, kh: dict, sub: str, site: dict) -> dict:
        fr = w.fr
        out = {"source": w.source, "trace": w.trace["id"], "frame": fr["k"], "action": fr["action"],
               "caller": fr["caller"].lower(), "value": str(fr["value"] if w.value is None else w.value),
               "table": [[k, h32(v)] for k, v in sorted(kh.items())],
               "prefix": len(w.chain), "data": fr["data"].lower()}
        if sub == "payer":
            out["keys"] = [h32(k) for k in (w.keys or [])]
        if sub in KEYED:
            out["key"] = h32(w.key)
            out["key_frame"] = w.key_frame
        return out

    def record(self, law: dict, sub: str, mname: str, site: dict, cls, status: str, witness, attempts: list,
               lp: Path | None, prim, bound, nonvac, deps: list) -> dict:
        from .. import records as R
        lctx = self.lctx
        lid = law["law_id"]
        sh = self.registry["statements"][lid]
        mtext = module_text(lctx, mname)
        cone = R.cone(re.sub(r"(?<![\w.])C\.", "M.", lp.read_text(encoding="utf-8")), mtext) if lp else []
        rec = {"law_id": lid, "statement_hash": sh, "facts_sha256": law["facts_sha256"], "status": status,
               "scope": "unbounded", "premises": [],
               "kernel": {"name": "bend", "version": bend_version(), "verdict": (prim or {}).get("verdict", "not_run")},
               "artifacts": {"laws": self.rel(lp) if lp else None, "proof": (prim or {}).get("proof"),
                             "model": self.rel(lctx.model_path(mname)), "claims": self.rel(lctx.claims_path(mname)),
                             "law_name": law_name(lid, status == "REFUTED")},
               "checker": (prim or {}).get("checker") or {"exit_code": None, "marker": "not_run"},
               "triage": "finding" if status == "REFUTED" else "none",
               "replay": {"status": "not_run", "detail": "holon bundle replay-laws has not run on this witness"}
               if witness is not None else {"status": "not_run", "detail": f"{status}: no witness to replay"},
               "attempts": attempts, "rule": law["rule"], "subform": sub, "member": mname, "dependencies": deps,
               "bundle": {"id": next(iter(x["bundle"] for x in law["statement"]["claim"]["eq"] if "bundle" in x)),
                          "class": cls},
               "bound": bound if status == "UNKNOWN" else None}
        if witness is not None:
            rec["witness"] = witness
        if status == "REFUTED":
            rec["difference"] = {"lhs": False, "rhs": True}
        ann = next((a for a in lctx.side.get("annotations") or [] if a.get("law") == lid), None)
        if ann is not None:   # CS5/RC2: the whitepaper's annotation marks the record, and changes no statement
            rec["triage"] = "annotated"
            rec["annotation"] = {"source": ann["source"], "text": ann.get("why") or ann.get("text") or ""}
        try:
            b, match = R.resolve_bundle(rec["facts_sha256"], law["facts"], self.root, mtext, set(cone), lctx.m)
            assumptions = R.model_assumptions(b["facts_sha256"], set(cone), self.root, law["facts"])
        except R.LedgerError:
            match, assumptions = "none", []
        compiled = self.models[mname].ev.compiled() if mname in self.models else None
        rec.update({"record_version": R.RECORD_VERSION, "prover": "generator",
                    "model_sha256": sha256_file(lctx.model_path(mname)),
                    "claims_sha256": sha256_file(lctx.claims_path(mname)),
                    "compiled_sha256": sha256_file(compiled) if compiled else None,
                    "generator_sha256": generator_sha256(self.root), "cone": cone, "ledger_match": match,
                    "model_assumptions": assumptions, "scope_v2": R.scope_v2(law, rec), "kernels": R.kernels(rec),
                    "independence_class": R.independence_class(rec), "refinement_refs": [],
                    "coverage": None,
                    "non_vacuity": nonvac or {"status": "counter_witness" if status == "REFUTED" else (
                        "witness" if status == "PROVED" else "unknown"),
                        "law": self.rel(lp) if (status in ("REFUTED", "PROVED") and lp) else None,
                        "witness": None, "reachable": True if status in ("REFUTED", "PROVED") else None,
                        "degenerate": None, "parent_statement_hash": sh,
                        "bound": ("the accepted counter-law inhabits the premises" if status == "REFUTED" else
                                  "the accepted existential proof is its own witness" if status == "PROVED"
                                  else "no proof")},
                    "witness_provenance": {"solidity": "internal_harness"} if status == "REFUTED" else None,
                    "filter_bin": "finding" if status == "REFUTED" else None,
                    **R.evidence_fields(law, {"status": status}, self.root)})
        rec["ledger_assumptions"] = sorted(rec["model_assumptions"])
        rec["model_assumptions"] = []
        rec["statement"] = law.get("notes", "")
        return rec


def deps_of(sub: str, site: dict) -> list:
    """CS4 and K8: the named dependencies of a law (I68 for a mapping credit and every keyed_blocking law; outflow
    for a forwarded inflow)."""
    if sub == "conservation":
        return list(site.get("dependencies") or [])
    if sub == "keyed_blocking":
        return ["I68"]
    return []


