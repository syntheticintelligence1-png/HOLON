def bname(n: str) -> str:
    from ..machine_bend import bname as b
    return b(n)


def rel_import(frm: Path, target: Path) -> str:
    return os.path.relpath(Path(target).resolve(), Path(frm).resolve()).replace(os.sep, "/")


def h32(v: int) -> str:
    return "0x%064x" % (int(v) % (1 << 256))


def keccak_int(b: bytes) -> int:
    from ..keccak import keccak256
    return int.from_bytes(keccak256(b), "big")


# ------------------------------------------------------------------------------------------------ the context
class LawCtx:
    """The milestone's bundle (I69's context), the bundle-laws basis and the derived entries of the six sub-forms."""

    def __init__(self, root: Path, milestone: str):
        from . import context
        from ..rules import bundle as RB
        self.root, self.m = Path(root).resolve(), milestone
        self.bctx = context(self.root, milestone)
        self.basis = RB.basis(self.root, milestone)
        if self.basis is None:
            raise LawRefused(f"spec/{milestone}/lib/{RB.SIDECAR} is missing")
        self.side = self.basis["sidecar"]
        self.sites = RB.sites(self.basis)
        self.members = {m["name"]: m for m in self.basis["members"]}

    def member_decl(self, name: str) -> dict:
        return self.bctx.member(name)

    def model_path(self, name: str) -> Path:
        from .laws import law_model_rel
        return self.root / law_model_rel(self.bctx, self.member_decl(name))

    def claims_path(self, name: str) -> Path:
        from .laws import out_dir
        return self.root / out_dir(self.bctx) / "claims" / f"{name}.bend"

    def law(self, lid: str) -> dict:
        p = self.root / "laws" / self.m / f"{lid}.json"
        if not p.is_file():
            raise LawRefused(f"{lid}: laws/{self.m}/{lid}.json is missing (holon derive --milestone {self.m})")
        return json.loads(p.read_text(encoding="utf-8"))


def bundle_entries(milestone: str, root: Path) -> dict:
    """The DERIVATION entries of the bundle laws (holon.rules.bundle's producers: an entry with a member)."""
    from ..rules.bundle import RULE_SUBFORMS
    try:
        dv = json.loads((Path(root) / "laws" / milestone / "DERIVATION.json").read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return {e["law_id"]: e for e in dv.get("laws") or [] if isinstance(e, dict) and e.get("member")
            and RULE_SUBFORMS.get(e.get("subform")) == e.get("rule")}


def is_bundle_law(law: dict) -> bool:
    """A holon-ir/0.3 law whose claim is a bundle term (holon.rules.bundle)."""
    c = (law.get("statement") or {}).get("claim") or {}
    return law.get("ir_version") == "holon-ir/0.3" and any(isinstance(x, dict) and isinstance(x.get("bundle"), str)
                                                          for x in c.get("eq") or [])


def site_of(lctx: LawCtx, lid: str) -> tuple:
    if lid not in lctx.sites:
        raise LawRefused(f"{lid} is not a bundle law of {lctx.m} (holon.rules.bundle's basis)")
    return lctx.sites[lid]


# ------------------------------------------------------------------------------------------------ law files
def _claim(sub: str, site: dict, x: str, rel: str) -> str | None:
    """The claim of a payer or conservation law over binders s, ar, en and kh (None: not expressible, CS3)."""
    if sub == "payer":
        return f"{{C.{x}_key(ar, en) {rel} M.ge_e_caller(en) : M.W}}"
    if site.get("class") == "unaccounted":
        return f"{{M.ge_e_msg_value(en) {rel} M.w0() : M.W}}"
    if site.get("class") == "ledger":
        return f"{{C.{x}_credit(s, ar, en, kh) {rel} M.ge_e_msg_value(en) : M.W}}"
    return None


def push_args(site: dict) -> list:
    """(binder suffix, Bend type) of each argument of a push law's encoding (PP4: a word for address and uint256, a
    byte list for bytes)."""
    return [(f"a{i}", "List<&2, U32>" if ty in ("bytes", "string") else "M.W") for i, (_n, ty) in
            enumerate(site["arguments"])]


def law_lines(lid: str, sub: str, site: dict, kind: str) -> list | None:
    """The binder and claim lines of a bundle law (kind forall, exists, counter or nonvac), or None when the form is
    not expressible."""
    x = lid.lower()
    q = "for" if kind == "forall" else "exs"
    plus = "+" if q == "for" else ""
    if sub == "push":
        args = push_args(site)
        x1 = ", ".join(f"x1_{n}" for n, _t in args)
        x2 = ", ".join(f"x2_{n}" for n, _t in args)
        enc1, enc2 = f"C.{x}_enc({x1})", f"C.{x}_enc({x2})"
        lines = [f"  {q} {'-' if q == 'for' else ''}h: List<&2, U32> -> M.W"]
        lines += [f"  {q} {plus}x1_{n}: {t}" for n, t in args] + [f"  {q} {plus}x2_{n}: {t}" for n, t in args]
        lines.append(f"  {q} cf: {{h({enc1}) == h({enc2}) : M.W}} -> {{{enc1} == {enc2} : List<&2, U32>}}")
        if kind == "nonvac":
            return lines + [f"  {{h({enc1}) == h({enc2}) : M.W}}"]
        lines.append(f"  {q} e: {{h({enc1}) == h({enc2}) : M.W}}")
        rel = "!=" if kind == "counter" else "=="
        return lines + [f"  {{C.{x}_field({enc1}) {rel} C.{x}_field({enc2}) : List<&2, U32>}}"]
    if sub in KEYED:
        if kind == "counter" and sub == "keyed_external":
            return None
        lines = [f"  {q} {plus}kh: List<&2, M.HKB>", f"  {q} {plus}s: M.HSt", f"  {q} r_s: M.Reach<kh, s>",
                 f"  {q} {plus}k: M.W", f"  {q} {plus}a: M.HAct"]
        rel = "!=" if kind == "counter" else "=="
        return lines + [f"  {{C.{x}(kh, s, k, a) {rel} True{{}} : Bool}}"]
    a = bname(site["action"])
    claim = _claim(sub, site, x, "!=" if kind == "counter" else "==")
    if claim is None:
        return None
    lines = [f"  {q} {plus}kh: List<&2, M.HKB>", f"  {q} {plus}s: M.HSt", f"  {q} r_s: M.Reach<kh, s>",
             f"  {q} {plus}ar: M.AR_{a}", f"  {q} {plus}en: M.HEnv"]
    if kind == "nonvac":
        return lines + [f"  {{M.chk_{a}(s, ar, en, kh) == 0 : U32}}"]
    return lines + [f"  {q} ok: {{M.chk_{a}(s, ar, en, kh) == 0 : U32}}", f"  {claim}"]


def law_text(lid: str, sub: str, site: dict, statement_hash: str, model_import: str, claims_import: str,
             kind: str) -> str | None:
    """gen/<M>/laws/<id>/LAWS.bend (kind forall or exists: the law; counter: the counter-law cl_<id> of a forall law)
    or the non-vacuity law nv_<id> (kind nonvac). It imports the law model as M and the claims module as C."""
    body = law_lines(lid, sub, site, kind)
    if body is None:
        return None
    name = f"nv_{lid.lower()}" if kind == "nonvac" else law_name(lid, kind == "counter")
    head = (f"# non-vacuity of {lid} (statement_hash {statement_hash}): its premises are inhabited"
            if kind == "nonvac" else f"# law_id: {lid}   statement_hash: {statement_hash}")
    lines = [LHEADER, head, "import Base", f"import {model_import} as M", f"import {claims_import} as C", "",
             f"law {name}:"] + body
    return "\n".join(lines) + "\n"


def law_kind(sub: str) -> str:
    return "exists" if sub == "keyed_external" else "forall"


def law_file(law: dict, milestone: str, root, statement_hash: str, counter: bool, gen: Path | None = None) -> str | None:
    """The law file of a bundle law as holon run writes it (holon.bindings emits it through this function)."""
    root = Path(root)
    lctx = LawCtx(root, milestone)
    sub, mname, site, _cls = site_of(lctx, law["law_id"])
    d = (gen or root / "gen" / milestone) / "laws" / law["law_id"]
    kind = "counter" if counter else law_kind(sub)
    return law_text(law["law_id"], sub, site, statement_hash, rel_import(d, lctx.model_path(mname)),
                    rel_import(d, lctx.claims_path(mname)), kind)


def module_text(lctx: LawCtx, mname: str) -> str:
    """The claims module followed by the law model: the text a bundle law's cone is computed over (the law file's C.
    names read as M.)."""
    return lctx.claims_path(mname).read_text(encoding="utf-8") + "\n" + lctx.model_path(mname).read_text(encoding="utf-8")


def combined_text(model_text: str, claims_text: str) -> str:
    """The law model and its claims module as one program (the claims' definitions prefixed C_, the model's qualifier
    dropped): what the search evaluates. Never checked, only run."""
    body = "\n".join(ln for ln in claims_text.split("\n") if not ln.startswith("import "))
    names = sorted(set(re.findall(r"(?m)^def (\w+)\(", body)), key=len, reverse=True)
    for n in names:
        body = re.sub(rf"(?<![\w.]){re.escape(n)}(?=\()", "C_" + n, body)
    body = re.sub(r"(?<![\w.])M\.", "", body)
    return model_text.rstrip("\n") + "\n\n" + body + "\n"


# ------------------------------------------------------------------------------------------------ the corpus (W1)
def cache_dir() -> Path:
    return Path(os.environ.get("HOLON_CACHE") or (Path.home() / ".holon" / "cache")) / "bundle_laws"


def corpus_key(bctx) -> str:
    from . import harness as H
    h = hashlib.sha256(CACHE_VERSION.encode())
    for rel in [bctx.out("corpus"), bctx.out("deployment"), bctx.side_rel, "config/holon.json"] + H.harness_files(bctx):
        h.update(rel.encode() + b"\0" + (bctx.root / rel).read_bytes() + b"\0")
    return h.hexdigest()


def corpus_run(bctx, jobs: int, log=print) -> tuple:
    """(the deployment record, the harness's per-trace records) of the bundle corpus: one forge run (I69's harness),
    cached outside the repository by its inputs' sha256. The deployment must be the committed one (rule C1)."""
    import tempfile
    from . import harness as H
    from .refine import deployment_record
    key = corpus_key(bctx)
    cp = cache_dir() / f"{key}.pickle"
    committed = bctx.load(bctx.out("deployment"))
    if cp.is_file():
        try:
            with cp.open("rb") as f:
                drec, trs = pickle.load(f)
            if drec == committed:
                log(f"the corpus run: cached ({cp.name[:16]})")
                return drec, trs
        except Exception:  # noqa: BLE001  (a stale or partial cache is re-made)
            pass
    corpus = bctx.load(bctx.out("corpus"))
    tc = H.toolchain(bctx)
    with tempfile.TemporaryDirectory(prefix="holon-bundle-laws-") as td:
        proj = H.project(bctx, Path(td), tc)
        dep = H.deployment(proj, tc, bctx, log)
        drec = deployment_record(bctx, proj, dep)
        if drec != committed:
            raise LawRefused(f"the harness's deployment is not {bctx.out('deployment')} (holon bundle refine re-makes it)")
        trs = H.run_corpus(proj, tc, bctx, corpus, dep, jobs or 4, log)
    cp.parent.mkdir(parents=True, exist_ok=True)
    tmp = cp.with_name(cp.name + f".{os.getpid()}.part")
    with tmp.open("wb") as f:
        pickle.dump((drec, trs), f)
    os.replace(tmp, cp)
    return drec, trs


def corpus_frames(bctx, drec: dict, corpus: dict, trs: list, members: set) -> list:
    """Per trace: its id, steps and the top-level frames on the given members, each {k, member, action, args, env,
    ok, caller, value, data} as the linked machine gave them (rule W2: M4's environment, the call answers of the
    frame's own call terms)."""
    from .machine import Bundle
    from .refine import apply_writes, blobs_of
    from ..mreplay import encode_step
    names = [m["name"] for m in bctx.members()]
    by_addr = {drec["members"][n]["address"]: n for n in names}
    machine = Bundle(bctx, drec)
    facts = bctx.load(bctx.side["corpus"]["m1"]["facts"])
    out = []
    for tr, rec in zip(corpus["traces"], trs):
        st = {n: {} for n in names}
        apply_writes(st, rec.deploy.writes, names)
        frames = []
        for k, (step, r) in enumerate(zip(tr["steps"], rec.steps)):
            pre = {n: dict(st[n]) for n in names}
            for acct, slot, word in r.pokes:
                pre[by_addr[acct]][slot] = word
            post = {n: dict(pre[n]) for n in names}
            apply_writes(post, r.writes, names)
            st = post
            if r.kind != "call" or not r.frames:
                continue
            top = r.frames[0]
            n = names[top[2]]
            if n not in members:
                continue
            model = machine.models[n]
            sel = top[3]
            action = machine.by_sel[n].get(sel) if sel != "0x" else ("receive" if "receive" in model.actions else None)
            if action is None:
                continue
            r.blobs = blobs_of(encode_step(step["row"], facts)) if "row" in step else []
            machine.run(pre, dict(r.before), r)
            data = bytes.fromhex(r.data[2:])
            try:
                args = machine.decode(model, action, data)
            except Exception:  # noqa: BLE001  (calldata the decoder rejects: no frame of the action)
                continue
            env = machine.env(n, r.caller, r.value, data, 0, [n])
            env.pop("call_hook", None)
            env.pop("return_data", None)
            env["calls"] = machine.answers.get(0, [])
            frames.append({"k": k, "member": n, "action": action, "args": args, "env": env, "ok": not top[5],
                           "caller": r.caller, "value": int(r.value), "data": r.data})
        out.append({"id": tr["id"], "steps": tr["steps"], "frames": frames})
    return out


# ------------------------------------------------------------------------------------------------ the law model
class LawModel:
    """A member's law model and claims module, compiled together and run by I30's evaluator; values are kept in the
    evaluator (saved by name) so that every state is exactly the model's."""

    def __init__(self, lctx: LawCtx, name: str):
        from . import members as MB
        from ..sorts.evaluate3 import Evaluator
        from ..sorts.proofs3 import Lit
        self.lctx, self.name = lctx, name
        self.text = lctx.model_path(name).read_text(encoding="utf-8")
        self.claims = lctx.claims_path(name).read_text(encoding="utf-8")
        ctext = combined_text(self.text, self.claims)
        d = cache_dir() / "models" / hashlib.sha256(ctext.encode("utf-8")).hexdigest()[:32]
        d.mkdir(parents=True, exist_ok=True)
        cp = d / "model.bend"
        if not cp.is_file() or cp.read_text(encoding="utf-8") != ctext:
            cp.write_text(ctext, encoding="utf-8")
        self.doc = MB.model(lctx.bctx, name)
        self.ev = Evaluator.build(cp, self.doc)
        self.lit = Lit(self.ev.recs)
        self.n = 0

    def close(self) -> None:
        self.ev.close()

    def fresh(self) -> str:
        self.n += 1
        return f"v{self.n}"

    def call(self, fn: str, args, kh: dict, save: str | None = None):
        """One call (args: a function of the hash table's encoding), with the real keccak256 of every key it looks up
        added to kh until none is new (a fixpoint). Returns the decoded result."""
        for _ in range(64):
            req = {"fn": fn, "args": args(self.ev.table(kh))}
            if save:
                req["save"] = save
            ans = self.ev.req(req)
            new = [k for k in ans["keys"].get("kh") or [] if k not in kh]
            if not new:
                return ans["out"]
            for k in new:
                kh[k] = keccak_int(bytes.fromhex(k[2:]))
        raise LawRefused(f"{fn}: the hash lookups did not settle")

    def s0(self) -> tuple:
        ref = self.fresh()
        return ref, self.call("s0", lambda _t: [], {}, save=ref)

    def ar(self, action: str, args: dict) -> dict:
        return self.ev.args_in(action, args)

    def en(self, env: dict) -> dict:
        return self.ev.env_in(env)

    @staticmethod
    def act(action: str, ar: dict, en: dict) -> dict:
        return {"$r": f"A_{bname(action)}", "f": {"ar": ar, "en": en}}

    def hout(self, action: str, ref: str, ar: dict, en: dict, kh: dict):
        return self.call(f"run_{bname(action)}", lambda t: [{"$ref": ref}, ar, en, t], kh)

    def chk(self, action: str, ref: str, ar: dict, en: dict, kh: dict) -> int:
        return int(self.call(f"chk_{bname(action)}", lambda t: [{"$ref": ref}, ar, en, t], kh))

    def step(self, act: dict, ref: str, kh: dict) -> tuple:
        nref = self.fresh()
        return nref, self.call("step", lambda t: [act, {"$ref": ref}, t], kh, save=nref)

    def fn(self, name: str, args, kh: dict):
        return self.call(name, args, kh)

    def reduce_env(self, action: str, ref: str, ar: dict, en: dict, kh: dict) -> dict:
        """The environment with its code table reduced to the entries whose removal changes the step's outcome on the
        model (the same HOut), greedily in table order."""
        code_f = next((f for f, k in self.ev.env_keys.items() if k == "code"), None)
        if code_f is None or not en["f"].get(code_f):
            return en
        want = self.hout(action, ref, ar, en, kh)
        trial = {"$r": "HEnv", "f": dict(en["f"], **{code_f: []})}
        if self.hout(action, ref, ar, trial, kh) == want:
            return trial
        keep = list(en["f"][code_f])
        for e in list(keep):
            cand = [x for x in keep if x is not e]
            trial = {"$r": "HEnv", "f": dict(en["f"], **{code_f: cand})}
            if self.hout(action, ref, ar, trial, kh) == want:
                keep = cand
        return {"$r": "HEnv", "f": dict(en["f"], **{code_f: keep})}


# ------------------------------------------------------------------------------------------------ claims (W4)
def _w(v) -> int:
    return int(v, 16) if isinstance(v, str) else int(v)


class Judge:
    """A law's claim at a candidate, on the compiled law model: True (holds), False (fails), None (not a candidate:
    the premise fails or the law has no expressible claim)."""

    def __init__(self, lid: str, sub: str, site: dict):
        self.lid, self.sub, self.site, self.x = lid, sub, site, lid.lower()

    def frame(self, lm: LawModel, ref: str, fr: dict, ar: dict, en: dict, kh: dict) -> bool | None:
        """payer and conservation: the premise ok (the step's checks hold), then the claim."""
        if fr["action"] != self.site["action"]:
            return None
        if lm.chk(fr["action"], ref, ar, en, kh) != 0:
            return None
        if self.sub == "payer":
            key = lm.fn(f"C_{self.x}_key", lambda _t: [ar, en], kh)
            return _w(key) == _w(lm.fn("ge_e_caller", lambda _t: [en], kh))
        cls = self.site.get("class")
        if cls == "unaccounted":
            return _w(lm.fn("ge_e_msg_value", lambda _t: [en], kh)) == 0
        if cls == "ledger":
            credit = lm.fn(f"C_{self.x}_credit", lambda t: [{"$ref": ref}, ar, en, t], kh)
            return _w(credit) == _w(lm.fn("ge_e_msg_value", lambda _t: [en], kh))
        return None

    def keyed(self, lm: LawModel, ref: str, act: dict, k: int, kh: dict) -> bool:
        v = lm.fn(f"C_{self.x}", lambda t: [t, {"$ref": ref}, {"$w": h32(k)}, act], kh)
        return bool(v)


# ------------------------------------------------------------------------------------------------ the search
class Witness:
    def __init__(self, source: str, trace: dict, fr: dict, chain: list, kh: dict, en_value: int | None = None,
                 key: int | None = None, keys: list | None = None, key_frame: int | None = None):
        self.source, self.trace, self.fr, self.chain = source, trace, fr, chain
        self.kh, self.value, self.key, self.keys, self.key_frame = dict(kh), en_value, key, keys, key_frame


def key_of(lctx: LawCtx, site: dict, fr: dict) -> int | None:
    """W3: the obligation's key term at a frame of the guarded action (holon.extracted_eval over the frame's
    arguments and environment)."""
    from ..extracted_eval import Eval
    from . import members as MB
    model = MB.model(lctx.bctx, site["member"] if "member" in site else fr["member"])
    try:
        e = Eval(model, {}, site["action"], fr["args"], fr["env"])
        return int(e.value(e.ev(site["key"]))) % (1 << 256)
    except Exception:  # noqa: BLE001  (a key the evaluator cannot compute is no candidate key)
        return None


def search(lctx: LawCtx, lm: LawModel, traces: list, lids: list, log=print) -> tuple:
    """W1-W4 for the laws of one member: ({law id: Witness}, {law id: {source: candidates tried}})."""
    judges = {lid: Judge(lid, lctx.sites[lid][0], lctx.sites[lid][2]) for lid in lids}
    want_true = {lid: lctx.sites[lid][0] == "keyed_external" for lid in lids}
    found: dict = {}
    variants: dict = {}
    tried = {lid: {"corpus": 0, "value_variant": 0} for lid in lids}
    vv = [int(v) for v in (lctx.side.get("witnesses") or {}).get("value_variants") or []]
    active = [lid for lid in lids if judges[lid].sub != "push" and not (
        judges[lid].sub == "conservation" and judges[lid].site.get("class") not in ("unaccounted", "ledger"))]
    s0_ref, s0_val = lm.s0()
    for tr in traces:
        if all(lid in found for lid in active):
            break
        mine = [f for f in tr["frames"] if f["member"] == lm.name]
        if not mine:
            continue
        kh: dict = {}
        ref, val = s0_ref, s0_val
        chain: list = []           # (act, state after) of each successful step before the candidate
        keys: dict = {}            # law id -> the keys seen so far (W3), in order, with the frame that gave each
        for fr in mine:
            ar, en = lm.ar(fr["action"], fr["args"]), lm.en(fr["env"])
            act = lm.act(fr["action"], ar, en)
            for lid in active:
                if lid in found:
                    continue
                j = judges[lid]
                if j.sub in KEYED:
                    for k, kf in keys.get(lid, []):
                        tried[lid]["corpus"] += 1
                        if j.keyed(lm, ref, act, k, kh) == want_true[lid]:
                            found[lid] = Witness("corpus", tr, fr, list(chain), kh, key=k, key_frame=kf)
                            break
                    continue
                if fr["action"] != j.site["action"]:
                    continue
                r = j.frame(lm, ref, fr, ar, en, kh)
                if r is not None:
                    tried[lid]["corpus"] += 1
                if r is False:
                    w = Witness("corpus", tr, fr, list(chain), kh)
                    if j.sub == "payer":
                        w.keys = [_w(lm.fn(f"C_{j.x}_key", lambda _t: [ar, en], kh))]
                    found[lid] = w
                    continue
                # W1's second source: the value variants of a conservation law's frames that ran ok on the bundle
                if j.sub == "conservation" and fr["ok"] and lid not in variants:
                    for v in vv:
                        en2 = lm.en(dict(fr["env"], **{"msg.value": v}))
                        tried[lid]["value_variant"] += 1
                        if j.frame(lm, ref, fr, ar, en2, kh) is False:
                            variants[lid] = Witness("value_variant", tr, fr, list(chain), kh, en_value=v)
                            break
            for lid in active:
                if judges[lid].sub in KEYED and fr["action"] == judges[lid].site["action"]:
                    k = key_of(lctx, judges[lid].site, fr)
                    if k is not None and k not in [x for x, _f in keys.setdefault(lid, [])]:
                        keys[lid].append((k, fr["k"]))
            nref, nval = lm.step(act, ref, kh)
            if nval != val:
                chain.append((act, nval))
            ref, val = nref, nval
    for lid, w in variants.items():
        if lid not in found:
            found[lid] = w
    log(f"{lm.name}: searched {len(traces)} traces; witnesses for {', '.join(sorted(found)) or 'none'}")
    return found, tried


# ------------------------------------------------------------------------------------------------ proofs
def _trace_defs(acts: list, states: list) -> tuple:
    """The witness's prefix actions and the literal state after each (A30's shape: one closed lemma per step, r_k:
    the state after step k is M.step of the state before it, both literals), and the Reach chain they make."""
    lines = []
    for i, a in enumerate(acts):
        lines += [f"def w_a{i}() -> M.HAct:\n  {a}", ""]
    n = len(acts)

    def st(k: int) -> str:
        return "M.s0()" if k == 0 else f"s_{k}()"
    for k in range(1, n + 1):
        lines += [f"def s_{k}() -> M.HSt:\n  {states[k - 1]}", ""]
    for k in range(n):
        lines += [f"def r_{k}() -> {{{st(k + 1)} == M.step(w_a{k}(), {st(k)}, t_kh()) : M.HSt}}:\n  {{==}}", ""]
    chain = "M.R0{{==}}"
    for k in range(n):
        chain = f"M.RStep{{w_a{k}(), {st(k)}, {chain}, r_{k}()}}"
    return lines, chain, st(n)


def _table_def(kh: dict, lit) -> list:
    rows = []
    for k, v in sorted(kh.items()):
        b = bytes.fromhex(k[2:])
        rows.append("M.HKB{" + (("[" + ", ".join(str(c) for c in b) + "]") if b else "Nil{}") + ", "
                    + lit.word(h32(v)) + "}")
    return [f"def t_kh() -> List<&2, M.HKB>:\n  " + (("[" + ", ".join(rows) + "]") if rows else "Nil{}"), ""]


TRUE_NE_FALSE = "def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})"


def witness_proof(lid: str, sub: str, site: dict, kind: str, imports: tuple, prefix: tuple, frame: tuple,
                  note: str) -> str:
    """The proof of one witness: kind counter (a forall law's counter-law), exists (an existential law) or nonvac (the
    premises' inhabitant). prefix: (table lines, trace lines, chain, state); frame: the candidate's literals."""
    model_i, claims_i, laws_i = imports
    tlines, body, chain, state = prefix
    x = lid.lower()
    lines = [PHEADER, "import Base", f"import {model_i} as M", f"import {claims_i} as C", f"import {laws_i} as Laws",
             "", f"# {note}"] + tlines + body
    name = {"counter": law_name(lid, True), "exists": law_name(lid), "nonvac": f"nv_{lid.lower()}"}[kind]
    if sub in KEYED:
        k_lit, a_lit = frame
        lines += [f"def w_k() -> M.W:\n  {k_lit}", "", f"def w_a() -> M.HAct:\n  {a_lit}", ""]
        want = "False{}" if kind == "counter" else "True{}"
        lines += [f"def cz() -> {{C.{x}(t_kh(), {state}, w_k(), w_a()) == {want} : Bool}}:\n  {{==}}", ""]
        if kind == "counter":
            lines += [TRUE_NE_FALSE, ""]
            proof = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
        else:
            proof = "cz()"
        lines.append(f"def Laws.{name}():\n  (t_kh(), ({state}, ({chain}, (w_k(), (w_a(), {proof})))))")
        return "\n".join(lines) + "\n"
    ar_lit, en_lit = frame
    a = bname(site["action"])
    lines += [f"def w_ar() -> M.AR_{a}:\n  {ar_lit}", "", f"def w_en() -> M.HEnv:\n  {en_lit}", "",
              f"def c_ok() -> {{M.chk_{a}({state}, w_ar(), w_en(), t_kh()) == 0 : U32}}:\n  {{==}}", ""]
    if kind == "nonvac":
        proof = "c_ok()"
    else:
        if sub == "payer":
            lhs = f"C.{x}_key(w_ar(), w_en())"
        elif site.get("class") == "unaccounted":
            lhs = "M.ge_e_msg_value(w_en())"
        else:
            lhs = f"C.{x}_credit({state}, w_ar(), w_en(), t_kh())"
        proof = f"(c_ok(), e => (%e : M.is_true(M.w_eq(_, {lhs}))\n  Unit{{}}))"
    lines.append(f"def Laws.{name}():\n  (t_kh(), ({state}, ({chain}, (w_ar(), (w_en(), {proof})))))")
    return "\n".join(lines) + "\n"


def push_proof(lid: str, site: dict, imports: tuple) -> str:
    """PP5: core_inj_push's step (cf applied to e), then congruence under the field."""
    model_i, claims_i, laws_i = imports
    x = lid.lower()
    args = push_args(site)
    names = [f"x1_{n}" for n, _t in args] + [f"x2_{n}" for n, _t in args]
    x1 = ", ".join(f"x1_{n}" for n, _t in args)
    lines = [PHEADER, "import Base", f"import {model_i} as M", f"import {claims_i} as C", f"import {laws_i} as Laws", "",
             "# class core_inj_push: the CF premise applied to the equal leaves gives equal preimages (Lemma 6.12), "
             "then the index field of equal preimages is equal",
             f"def Laws.{law_name(lid)}(h, {', '.join(names)}, cf, e):",
             f"  %cf(e) : {{C.{x}_field(C.{x}_enc({x1})) == C.{x}_field(_) : List<&2, U32>}}", "  {==}"]
    return "\n".join(lines) + "\n"


def push_nonvac_proof(lid: str, site: dict, imports: tuple, sample: dict, lit) -> str:
    """G11V for PP: x1 = x2 = a PP6 sample, any hash, cf and e by computation."""
    model_i, claims_i, laws_i = imports
    vals = []
    for name, ty in site["arguments"]:
        v = sample[name]
        if ty in ("bytes", "string"):
            b = bytes.fromhex(v[2:]) if isinstance(v, str) else bytes(v)
            vals.append(("[" + ", ".join(str(c) for c in b) + "]") if b else "Nil{}")
        else:
            vals.append(lit.word(h32(int(v, 16) if isinstance(v, str) else int(v))))
    tup = "(p => {==}, {==})"
    for v in reversed(vals + vals):
        tup = f"({v}, {tup})"
    tup = f"(b => M.w0(), {tup})"
    lines = [PHEADER, "import Base", f"import {model_i} as M", f"import {claims_i} as C", f"import {laws_i} as Laws", "",
             "# x1 = x2 = the first PP6 sample, and a constant hash: both premises hold by computation",
             f"def Laws.nv_{lid.lower()}():\n  {tup}"]
    return "\n".join(lines) + "\n"


def payer_proof(lid: str, imports: tuple) -> str:
    """PY4: every key is the caller term, so the claim holds by computation."""
    model_i, claims_i, laws_i = imports
    lines = [PHEADER, "import Base", f"import {model_i} as M", f"import {claims_i} as C", f"import {laws_i} as Laws", "",
             "# class caller_key: every key of the price call is the caller term (PY4), the claim holds by computation",
             f"def Laws.{law_name(lid)}(kh, s, r_s, ar, en, ok):", "  {==}"]
    return "\n".join(lines) + "\n"


