"""The Bend files over the versioned model: a trace's definitions (its states, steps, step equations and reachability
term, rule V8's shape), the PAR-init laws' LAWS.bend (the frozen statement and the counter-law) and the counter-law's
PROOF.bend from a witness (PI6), and the in-flight inhabitants' INHABIT.bend (V8). Every value is a literal of the layer
(holon.versions.bendlit) and every equation is proved by computation ({==}), so a file Bend accepts states the trace the
search found; nothing here is trusted.
"""
from __future__ import annotations

import os
from pathlib import Path

from .bendlit import Lit, step_literal
from .machine import Machine


def law_name(lid: str, counter: bool) -> str:
    return ("cl_" if counter else "") + lid.lower()


def rel_import(frm: Path, target: Path) -> str:
    """The import path of target from a file in directory frm (a plain module name, holon.sorts.model3.importable)."""
    r = os.path.relpath(Path(target), Path(frm)).replace(os.sep, "/")
    return r if r.startswith(".") else "./" + r


def trace_defs(lit: Lit, m: Machine, trace: list, outs: list, kh: dict, table: str = "t_kh") -> list:
    """Definitions of a trace of n steps from vr0: s_0 .. s_n, x_1 .. x_n, r_1 .. r_n (V8's shape), with the hash table
    table() the steps look up."""
    p = lit.p
    tabs = f"{table}()"
    out = [f"def {table}() -> List<&2, {p}.HKB>:\n  {lit.table(kh)}\n",
           f"def s_0() -> {p}.VSt:\n  {p}.vr0()\n"]
    for i, (st, o) in enumerate(zip(trace, outs), 1):
        out.append(f"def s_{i}() -> {p}.VSt:\n  {lit.state(o['state'])}\n")
        out.append(f"def x_{i}() -> {p}.VStep:\n  {step_literal(lit, m, st, o['env'])}\n")
        out.append(f"def r_{i}() -> {{s_{i}() == {p}.vstep(x_{i}(), s_{i - 1}(), {tabs}) : {p}.VSt}}:\n  {{==}}\n")
    return out


def reach_body(p: str, n: int) -> str:
    t = f"{p}.VR0{{{{==}}}}"
    for i in range(1, n + 1):
        t = f"{p}.VRStep{{x_{i}(), s_{i - 1}(), {t}, r_{i}()}}"
    return t


def reach_def(p: str, n: int, name: str = "reach", table: str = "t_kh") -> str:
    return f"def {name}() -> {p}.VReach<{table}(), s_{n}()>:\n  {reach_body(p, n)}\n"


def ok_def(p: str, i: int, table: str = "t_kh") -> str:
    return f"def ok_{i}() -> {{True{{}} == {p}.vok(x_{i}(), s_{i - 1}(), {table}()) : Bool}}:\n  {{==}}\n"


# ------------------------------------------------------------------------------------------------ PAR-init laws
def laws_text(law: dict, statement_hash: str, model_import: str, claim: str, tables: list, counter: bool) -> str:
    """LAWS.bend of a PAR-init law: the frozen statement (forall) or its counter-law (exists), over the layer as M: for
    every hash table, reachable state s, step a and environment e, claim(a, s, e, tables) is true."""
    lid = law["law_id"]
    q = "exs" if counter else "for"
    lines = ["# GENERATED by holon.versions.proofs from the frozen law IR; do not edit.",
             f"# law_id: {lid}   statement_hash: {statement_hash}", "import Base",
             f"import {model_import} as M", "", f"law {law_name(lid, counter)}:"]
    for t in tables:
        lines.append(f"  {q} {t}: List<&2, M.HKB>")
    lines += [f"  {q} s: M.VSt", f"  {q} r: M.VReach<{', '.join(tables)}, s>", f"  {q} a: M.VStep", f"  {q} e: M.VEnv",
              f"  {{M.{claim}(a, s, e, {', '.join(tables)}) {'!=' if counter else '=='} True{{}} : Bool}}", ""]
    return "\n".join(lines)


def tables_of(law: dict) -> list:
    """The hash tables a PAR-init law's statement quantifies over, one per Fn binder (kh for keccak256, sh for sha256)."""
    return ["kh" if b["name"] == "keccak256" else "sh" for b in law["statement"].get("binders", [])
            if str(b.get("type", "")).startswith("Fn<")]


def claim_of(init: dict, element: dict) -> str | None:
    """The layer's claim function of a basis element (the model's init.json layer.claims), None when it has none."""
    return (((init.get("layer") or {}).get("claims") or {}).get(element["init_id"]) or {}).get("function")


def model_paths(milestone: str, root) -> tuple[Path, Path]:
    """(the versioned model as records name it: <model>.bend, a link; the layer module its law files import)."""
    from . import Ctx
    from .model import stem
    ctx = Ctx(root, f"spec/{milestone}/lib/versions.json")
    md = ctx.root / ctx.out("model_dir")
    return md / f"{ctx.model}.bend", md / f"{stem(ctx.model)}.bend"


def law_file(law: dict, milestone: str, root, statement_hash: str, counter: bool, gen: Path | None = None) -> str:
    """A PAR-init law's LAWS.bend as holon.versions.run writes it under gen/<M>/laws/<id>/ (laws_text over the layer,
    with the basis element's claim function): the bound statement and counter-law (holon.bindings)."""
    import json
    from .run import init_entries
    root = Path(root)
    lid = law["law_id"]
    e = init_entries(milestone, root).get(lid)
    if e is None:
        raise KeyError(f"{lid} is not a PAR-init law of {milestone}")
    link, layer = model_paths(milestone, root)
    init = json.loads((link.parent / (link.name[:-len(".bend")] + ".init.json")).read_text(encoding="utf-8"))
    laws_dir = (Path(gen) if gen else root / "gen" / milestone) / "laws" / lid
    return laws_text(law, statement_hash, rel_import(laws_dir, layer), claim_of(init, e["basis"]) or "pinit_none",
                     tables_of(law), counter)


def counter_proof(law: dict, m: Machine, model_import: str, laws_import: str, claim: str, trace: list, outs: list,
                  kh: dict) -> str:
    """PROOF.bend of a PAR-init counter-law from a witness trace (its last step the root step): the trace's
    definitions, the reachability of the state before the root step, the claim false there by computation, and the
    counter-law's witness."""
    lit = Lit("M")
    n = len(trace)
    lines = ["# GENERATED by holon.versions.proofs; untrusted, accepted only if Bend checks it.", "import Base",
             f"import {model_import} as M", f"import {laws_import} as Laws", ""]
    defs = trace_defs(lit, m, trace, outs, kh)
    defs.append(reach_def("M", n - 1, "reach_w"))
    env = outs[-1]["env"]
    defs.append(f"def e_w() -> M.VEnv:\n  {lit.venv(m.venv_fields(), env)}\n")
    defs.append(f"def cz() -> {{M.{claim}(x_{n}(), s_{n - 1}(), e_w(), t_kh()) == False{{}} : Bool}}:\n  {{==}}\n")
    defs.append("def is_true(b: Bool) -> Type:\n  match b:\n    case True{}:\n      Unit\n    case False{}:\n"
                "      Empty\n")
    defs.append("def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : is_true(_)\n  Unit{})\n")
    defs.append(f"def Laws.{law_name(law['law_id'], True)}():\n"
                f"  (t_kh(), (s_{n - 1}(), (reach_w(), (x_{n}(), (e_w(), e => true_ne_false((%e : {{_ == False{{}} : Bool}}"
                f"\n  cz())))))))\n")
    return "\n".join(lines) + "\n" + "\n".join(defs)


# ------------------------------------------------------------------------------------------------ in-flight inhabitants
def inhabit_text(m: Machine, model_import: str, edge: str, trace: list, outs: list, kh: dict, legacy: list) -> str:
    """INHABIT.bend of an edge's in-flight inhabitant (V8's shape): the layer imported as VM; s_0 .. s_n, x_1 .. x_n,
    r_1 .. r_n; ok_<n-1> and ok_<n> (the commit's and the migration's success); lg_1 .. lg_m, each legacy word read at
    its layout coordinate in the state before the migration; and reach, the VReach of s_n. No law."""
    lit = Lit("VM")
    n = len(trace)
    lines = [f"# GENERATED by holon.versions.inhabit: the in-flight inhabitant of {edge}; untrusted, accepted only if "
             "Bend checks it.", "import Base", f"import {model_import} as VM", ""]
    defs = trace_defs(lit, m, trace, outs, kh, table="kh")
    for i in (n - 1, n):
        defs.append(ok_def("VM", i, table="kh"))
    for j, w in enumerate(legacy, 1):
        path = ", ".join(f"VM.VP{{{lit.word(k)}, {lit.word(o)}}}" for k, o in w["path"])
        p = f"[{path}]" if path else "Nil{}"
        defs.append(f"def lg_{j}() -> {{{lit.word(int(str(w['word']), 0))} == VM.vread(s_{n - 1}(), {lit.word(w['base'])}, "
                    f"{lit.word(w['offset'])}, {p}, kh()) : VM.W}}:\n  {{==}}\n")
    defs.append(reach_def("VM", n, "reach", table="kh"))
    return "\n".join(lines) + "\n" + "\n".join(defs)
