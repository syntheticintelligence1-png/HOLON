"""K1, K3: a member at another commit (the sidecar's legacy entry), extracted the way holon.bundle extracts the head
members (the bundle sidecar's base_sidecar with the member's source, contract and commit interfaces, at the legacy
commit's tree), its untyped model (model3 with EXT1, as the bundle's), and eta: each register of the legacy layout mapped
to the head register of the same name, and the head registers the legacy layout lacks, which an upgrade leaves empty.

  gen/<M>/symb/legacy/sidecars/<member>.json   the generated extraction sidecar
  gen/<M>/symb/legacy/<member>.json            the legacy document
  gen/<M>/symb/legacy/<member>.bend, models.json  its model and {"models_version", "models", "debt"}
  gen/<M>/symb/eta_<suffix>.json                eta (K3): {"from", "to", "map", "fresh", "inherited"}
"""
from __future__ import annotations

import hashlib
import json
import tempfile
from pathlib import Path

from . import SYMB_VERSION, Ctx, SymbError


def _render(doc) -> bytes:
    from ..bundle import render
    return render(doc)


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def legacy_spec(ctx: Ctx) -> tuple[dict, dict]:
    lg = ctx.side.get("legacy") or {}
    for k in ("member", "tag", "commit"):
        if not lg.get(k):
            raise SymbError(f"{ctx.side_rel} legacy has no {k}")
    return lg, dict(ctx.bundle.member(lg["member"]), commit=lg["commit"])


def eta(legacy_doc: dict, head_doc: dict, frm: dict, to: dict) -> dict:
    """K3: legacy register -> head register of the same name (its slots both sides), the head registers the legacy
    layout lacks (fresh, empty after the upgrade), and whether the inherited layout is the same."""
    ls = {s["name"]: s for s in legacy_doc["storage"]}
    hs = {s["name"]: s for s in head_doc["storage"]}
    moved = [n for n in ls if n in hs and int(ls[n]["slot"]) != int(hs[n]["slot"])]
    if moved:
        raise SymbError(f"eta: the upgrade moves registers {sorted(moved)}; a layout change is not an empty migration")
    gone = sorted(set(ls) - set(hs))
    if gone:
        raise SymbError(f"eta: the head layout drops registers {gone}")
    return {"symb_version": SYMB_VERSION, "from": frm, "to": to,
            "map": [{"register": n, "from_slot": int(ls[n]["slot"]), "to_slot": int(hs[n]["slot"])} for n in sorted(ls)],
            "fresh": sorted(set(hs) - set(ls)),
            "inherited": (legacy_doc.get("inherited_storage") or []) == (head_doc.get("inherited_storage") or [])}


def build(ctx: Ctx, log=print) -> dict:
    from ..bundle import extract as BX
    from ..bundle import model as BM
    from ..frontends.solidity import extract_document
    lg, m = legacy_spec(ctx)
    name = lg["member"]
    out = ctx.out("legacy")
    files = {}
    sc = BX.generated_sidecar(ctx.bundle, m)
    sc["target"]["scope"] = f"legacy member {name} ({m['contract']}) at {lg['tag']}"
    doc_rel = f"{out}/{name}.json"
    sc["output"] = doc_rel
    sc["doc"] = (f"Generated by holon symb legacy from {ctx.side_rel} and {ctx.bundle.side_rel}: the bundle's "
                 f"base_sidecar with the member's source, contract and commit interfaces at {lg['tag']} "
                 f"({lg['commit']}).")
    srel = f"{out}/sidecars/{name}.json"
    sdata = _render(sc)
    files[srel] = sdata
    sp = ctx.root / srel
    with tempfile.TemporaryDirectory(prefix="holon-symb-") as td:
        eff = sp if (sp.is_file() and sp.read_bytes() == sdata) else Path(td) / sp.name
        if eff != sp:
            eff.write_bytes(sdata)
        src = BX.source_for(ctx.bundle, lg["commit"])
        doc = extract_document(sc, eff, ctx.root, src)
    ddata = _render(doc)
    files[doc_rel] = ddata
    # the model compiles the document on disk (its path names the model): stage it when it differs, and put back what
    # was there afterwards (write_or_check writes it with the rest, or only compares under --check)
    dp = ctx.root / doc_rel
    prev = dp.read_bytes() if dp.is_file() else None
    if prev != ddata:
        dp.parent.mkdir(parents=True, exist_ok=True)
        dp.write_bytes(ddata)
    try:
        text, debt = BM.compile_member(ctx.bundle, name, BM.init_of(ctx.bundle, name), rel=doc_rel)
    finally:
        if prev is None:
            dp.unlink()
        elif prev != ddata:
            dp.write_bytes(prev)
    log(f"{name} at {lg['tag']}: {len(doc['actions'])} actions, {len(debt)} in model debt")
    models = {}
    if text is not None:
        bp = f"{out}/{name}.bend"
        files[bp] = text.encode("utf-8")
        models[name] = {"path": bp, "sha256": _sha(text.encode("utf-8")), "document_sha256": _sha(ddata)}
    files[f"{out}/models.json"] = _render({"models_version": BM.MODELS_VERSION, "models": models,
                                           "debt": [{"member": name, "action": a, "error": e} for a, e in debt]})
    head_rel = ctx.bundle.document_rel(ctx.bundle.member(name))
    head = ctx.bundle.load(head_rel)
    frm = {"tag": lg["tag"], "commit": lg["commit"], "document_sha256": _sha(ddata)}
    to = {"tag": None, "commit": ctx.bundle.commit_of(ctx.bundle.member(name)),
          "document_sha256": _sha((ctx.root / head_rel).read_bytes())}
    files[ctx.out(f"eta_{lg.get('eta', 'enq')}.json")] = _render(eta(doc, head, frm, to))
    return files


def main(ctx: Ctx, check: bool, log) -> int:
    from ..bundle import write_or_check
    files = build(ctx, log)
    return write_or_check(ctx.bundle, files, check, owned=[ctx.out("legacy")], log=log)
