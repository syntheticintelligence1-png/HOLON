class Decider:
    def __init__(self, root: Path, milestone: str, results: Path, gen: Path, jobs: int = 4, log=print):
        from .. import ir
        from . import context
        self.root, self.m, self.jobs, self.log = Path(root).resolve(), milestone, jobs, log
        self.results = (Path(results) if Path(results).is_absolute() else self.root / results).resolve()
        self.gen = (Path(gen) if Path(gen).is_absolute() else self.root / gen).resolve()
        self.sctx = context(self.root, milestone)
        self.bctx = self.sctx.bundle
        self.registry = ir.load_registry(milestone, self.root)
        self.entries = symb_entries(milestone, self.root)
        self.index = json.loads((self.root / self.sctx.out("sections", "index.json")).read_text(encoding="utf-8"))["laws"]
        self.machines: dict = {}
        self._traces = None
        self._found: dict = {}

    def close(self):
        for mm in self.machines.values():
            mm.close()

    def rel(self, p: Path) -> str:
        return Path(p).resolve().relative_to(self.root).as_posix()

    # -------------------------------------------------------------------------------------------- inputs
    def model_path(self, member: str) -> Path:
        return self.root / "gen" / self.m / "bundle" / "models" / f"{member}.bend"

    def section_path(self, member: str) -> Path:
        return self.root / self.sctx.out("sections", f"{member}.bend")

    def machine(self, member: str) -> Machine:
        if member not in self.machines:
            from ..bundle import members as MB
            self.machines[member] = Machine(member, self.model_path(member),
                                            self.section_path(member).read_text(encoding="utf-8"),
                                            MB.model(self.bctx, member))
        return self.machines[member]

    def legacy_machine(self) -> Machine:
        if "@legacy" not in self.machines:
            from ..bundle import members as MB
            from ..machine import ExtractedModel
            lg = self.sctx.side["legacy"]
            rel = self.sctx.out("legacy", f"{lg['member']}.json")
            data = (self.root / rel).read_bytes()
            doc = ExtractedModel(json.loads(data), MB.info(self.bctx, lg["member"]), Path(rel),
                                 hashlib.sha256(data).hexdigest())
            self.machines["@legacy"] = Machine("@legacy", self.root / self.sctx.out("legacy", f"{lg['member']}.bend"),
                                               "", doc)
        return self.machines["@legacy"]

    def traces(self) -> list:
        if self._traces is None:
            from ..bundle.lawrun import corpus_run
            drec, trs = corpus_run(self.bctx, self.jobs, self.log)
            corpus = self.bctx.load(self.bctx.out("corpus"))
            self._traces = member_frames(self.bctx, drec, corpus, trs, set(self.sctx.side["members"]))
        return self._traces

    def is_view(self, member: str, action: str) -> bool:
        doc = self.bctx.load(self.sctx.side["members"][member]["document"])
        a = next((x for x in doc["actions"] if x["name"] == action), {})
        return a.get("mutability") in ("view", "pure")

    def clock_actions(self, member: str) -> set:
        doc = self.bctx.load(self.sctx.side["members"][member]["document"])
        return {a["name"] for a in doc["actions"] if '["env", "block.timestamp"]' in json.dumps(a)}

    # -------------------------------------------------------------------------------------------- searches
    def search_tau(self, lid: str):
        e = self.index[lid]
        member, action = e["member"], self.entries[lid]["basis"]["action"]
        lm = self.machine(member)
        clocked = self.clock_actions(member)
        view = self.is_view(member, action)
        s0ref, s0val = lm.s0()
        tried = 0
        for tr in self.traces():
            frames = [f for f in tr["frames"] if f["member"] == member]
            if not any(f["action"] == action and (f["top"] or view) for f in frames):
                continue
            kh: dict = {}
            ref, val, chain, zeroed = s0ref, s0val, [], set()
            for f in frames:
                # x: a top-level frame, or a view's frame before any change of the member's state in its step (a
                # view's run at that point is a direct call at the step's clock: the replay makes it so)
                if f["action"] == action and (f["top"] or (view and not any(c[0]["k"] == f["k"] for c in chain))):
                    x = lm.act(action, lm.ar(action, f["args"]), lm.en(f["env"]))
                    tried += 1

                    def args(t, ref=ref, x=x):
                        return [{"$ref": ref}, x, {"$w": h32(D)}, t]
                    if lm.fn(f"C_{e['hit']}", args, kh) and not lm.fn(f"C_{e['ok']}", args, kh):
                        return Witness("tau", tr, list(chain), kh, frame=f, x=x, zeroed=set(zeroed)), tried
                z = f["action"] in clocked
                env = _clock(f["env"], 0) if z else f["env"]
                act = lm.act(f["action"], lm.ar(f["action"], f["args"]), lm.en(env))
                nref, nval = lm.step(act, ref, kh)
                if nval != val:
                    chain.append((f, act, nval))
                    if z:
                        zeroed.add(f["k"])
                ref, val = nref, nval
        return None, tried

    def site_of(self, lid: str, w: Witness) -> tuple:
        """(site, site_kind): the comparison site the witness crosses (sy_flip true), else the view's return word."""
        e = self.index[lid]
        lm = self.machine(e["member"])
        ref = self._replay_chain(lm, w)
        kh = dict(w.kh)
        for c in e.get("cmps") or []:
            if not c.get("flip"):
                continue
            if lm.fn(f"C_{c['flip']}", lambda t: [{"$ref": ref}, w.x, {"$w": h32(D)}, t], kh):
                return c["src"], "compare"
        a = next(x for x in self.bctx.load(self.sctx.side["members"][e["member"]]["document"])["actions"]
                 if x["name"] == self.entries[lid]["basis"]["action"])
        return a.get("src"), ("return" if e.get("ret") else "outcome")

    def _replay_chain(self, lm, w: Witness) -> str:
        ref, _v = lm.s0()
        for _f, act, want in w.chain:
            ref, val = lm.step(act, ref, w.kh)
            if val != want:
                raise LawRefused("the witness's chain does not re-run on the model")
        return ref

    def search_inv(self, lid: str, legacy: bool = True) -> tuple:
        """The versioned member's witness of a sentinel invariant (legacy=False: the head only, the contrast)."""
        e = self.index[lid]
        member = e["member"]
        hm = self.machine(member)
        bud = self.sctx.side.get("search") or {}
        pre_n, cont_n, cap = int(bud.get("prefix_steps", 4)), int(bud.get("continuation_steps", 2)), \
            int(bud.get("candidates", 60000))
        tried = 0
        lm = self.legacy_machine() if legacy else None
        lacts = set(lm.doc.actions) if legacy else set()
        for tr in self.traces():
            frames = [f for f in tr["frames"] if f["member"] == member]
            if not frames:
                continue
            kh: dict = {}
            if legacy:
                lref, lval = lm.s0()
                lchain = []
                for i, f in enumerate(frames):
                    if f["action"] not in lacts:
                        continue
                    act = lm.act(f["action"], lm.ar(f["action"], f["args"]), lm.en(f["env"]))
                    nref, nval = lm.step(act, lref, kh)
                    if nval == lval:
                        continue
                    lref, lval = nref, nval
                    lchain.append((f, act, nval))
                    if len(lchain) > pre_n or tried >= cap:
                        break
                    w, t = self._continue(lid, hm, tr, frames[i + 1:], lchain, lval, kh, cont_n)
                    tried += t
                    if w is not None:
                        return w, tried
            else:
                ref, val = hm.s0()
                hchain = []
                if not hm.fn(f"C_{e['ok']}", lambda t: [{"$ref": ref}, t], kh):
                    return Witness("inv", tr, [], kh, head=[]), tried + 1
                tried += 1
                for f in frames:
                    if int(f["env"].get("block.timestamp") or 0) < 1:
                        continue
                    act = hm.act(f["action"], hm.ar(f["action"], f["args"]), hm.en(f["env"]))
                    nref, nval = hm.step(act, ref, kh)
                    if nval == val:
                        continue
                    ref, val = nref, nval
                    hchain.append((f, act, nval))
                    tried += 1
                    if not hm.fn(f"C_{e['ok']}", lambda t, ref=ref: [{"$ref": ref}, t], kh):
                        return Witness("inv", tr, [], kh, head=list(hchain)), tried
                    if len(hchain) >= pre_n + cont_n or tried >= cap:
                        break
        return None, tried

    def _continue(self, lid, hm, tr, rest, lchain, lval, kh, cont_n) -> tuple:
        e = self.index[lid]
        tried = 1
        if not hm.fn(f"C_{e['ok']}", lambda t: [as_input(lval), t], kh):
            return Witness("inv", tr, list(lchain), kh, head=[], up_state=lval), tried
        hchain, cur = [], lval
        for f in rest:
            if len(hchain) >= cont_n:
                break
            if int(f["env"].get("block.timestamp") or 0) < 1:
                continue
            act = hm.act(f["action"], hm.ar(f["action"], f["args"]), hm.en(f["env"]))
            nref = hm.fresh()
            nval = hm.call("step", lambda t, cur=cur: [act, as_input(cur), t], kh, save=nref)
            if nval == cur:
                continue
            hchain.append((f, act, nval))
            cur = nval
            tried += 1
            if not hm.fn(f"C_{e['ok']}", lambda t, cur=cur: [as_input(cur), t], kh):
                return Witness("inv", tr, list(lchain), kh, head=list(hchain), up_state=lval), tried
        return None, tried

    def witness(self, lid: str):
        """(witness or None, tried) of a searched law, cached."""
        if lid not in self._found:
            kind = self.index[lid]["kind"]
            self._found[lid] = self.search_tau(lid) if kind == "tau" else (
                self.search_inv(lid) if kind == "versioned" else (None, 0))
        return self._found[lid]

