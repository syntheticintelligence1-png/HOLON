class Machine(LawModel):
    """A model and its companion module (holon.bundle.lawrun.LawModel's evaluator) over a given document model."""

    def __init__(self, name: str, model_path: Path, companion: str, doc_model):
        from ..sorts.evaluate3 import Evaluator
        from ..sorts.proofs3 import Lit
        self.name = name
        self.text = Path(model_path).read_text(encoding="utf-8")
        self.claims = companion
        ctext = combined_text(self.text, companion)
        d = cache_dir() / "models" / hashlib.sha256(ctext.encode("utf-8")).hexdigest()[:32]
        d.mkdir(parents=True, exist_ok=True)
        cp = d / "model.bend"
        if not cp.is_file() or cp.read_text(encoding="utf-8") != ctext:
            cp.write_text(ctext, encoding="utf-8")
        self.doc = doc_model
        self.ev = Evaluator.build(cp, self.doc)
        self.lit = Lit(self.ev.recs)
        self.n = 0


def member_frames(bctx, drec: dict, corpus: dict, trs: list, members: set) -> list:
    """Per trace: its id, steps and every frame on the given members, top-level and the member-to-member calls the
    linked machine runs (holon.bundle.machine), each {k (the step), idx (its frame), top, member, action, args, env,
    ok, caller, value, data}; a trace stops at a step the machine cannot run."""
    from ..bundle.machine import Bundle
    from ..bundle.refine import apply_writes, blobs_of
    from ..mreplay import encode_step

    class Rec(Bundle):
        def frame(self, name, caller, value, data, parent, stack):
            self.rec.append((len(self.frames), name, caller, value, data))
            return super().frame(name, caller, value, data, parent, stack)
    names = [m["name"] for m in bctx.members()]
    by_addr = {drec["members"][n]["address"]: n for n in names}
    machine = Rec(bctx, drec)
    facts = bctx.load(bctx.side["corpus"]["m1"]["facts"])
    out = []
    for tr, rec in zip(corpus["traces"], trs):
        st = {n: {} for n in names}
        apply_writes(st, rec.deploy.writes, names)
        frames = []
        for k, (step, r) in enumerate(zip(tr["steps"], rec.steps)):
            pre = {n: dict(st[n]) for n in names}
            for acct, slot, word in r.pokes:
                pre[by_addr[acct]][slot] = word
            post = {n: dict(pre[n]) for n in names}
            apply_writes(post, r.writes, names)
            st = post
            if r.kind != "call" or not r.frames:
                continue
            if not any(names[f[2]] in members for f in r.frames):
                continue
            machine.rec = []
            r.blobs = blobs_of(encode_step(step["row"], facts)) if "row" in step else []
            res = machine.run(pre, dict(r.before), r)
            if res.get("status") not in ("ok", "revert"):
                break
            kept = machine._kept()
            for idx, name, caller, value, data in machine.rec:
                if name not in members:
                    continue
                model = machine.models[name]
                sel = "0x" + data[:4].hex() if len(data) >= 4 else "0x"
                action = machine.by_sel[name].get(sel) if data else (
                    "receive" if "receive" in model.actions else None)
                if action is None:
                    continue
                try:
                    args = machine.decode(model, action, data)
                except Exception:  # noqa: BLE001  (calldata the decoder rejects: no frame of the action)
                    continue
                env = machine.env(name, caller, value, data, idx, [name])
                env.pop("call_hook", None)
                env.pop("return_data", None)
                env["calls"] = machine.answers.get(idx, [])
                frames.append({"k": k, "idx": idx, "top": idx == 0, "member": name, "action": action, "args": args,
                               "env": env, "ok": bool(kept[idx]) if idx < len(kept) else False, "caller": caller,
                               "value": int(value), "data": "0x" + data.hex()})
        out.append({"id": tr["id"], "steps": tr["steps"], "frames": frames})
    return out


def as_input(v):
    """A value the evaluator returned, encoded as an argument (a word's hex as {"$w": hex})."""
    if isinstance(v, str) and v.startswith("0x") and len(v) == 66:
        return {"$w": v}
    if isinstance(v, dict) and "$r" in v:
        return {"$r": v["$r"], "f": {k: as_input(x) for k, x in (v.get("f") or {}).items()}}
    if isinstance(v, list):
        return [as_input(x) for x in v]
    return v


def _clock(env: dict, t: int) -> dict:
    return dict(env, **{"block.timestamp": t})


def _jsonable(v):
    if isinstance(v, (bytes, bytearray)):
        return "0x" + bytes(v).hex()
    if isinstance(v, dict):
        return {k: _jsonable(x) for k, x in v.items() if k not in ("code", "balance", "unknown", "msg.data")}
    if isinstance(v, (list, tuple)):
        return [_jsonable(x) for x in v]
    return v


@dataclass
class Witness:
    kind: str                       # tau | inv
    trace: dict
    chain: list                     # [(frame, act, state)]: the state-changing steps (tau: on the member's model)
    kh: dict
    frame: dict | None = None       # tau: x's frame
    x: dict | None = None           # tau: x's act
    head: list = field(default_factory=list)   # inv: the head steps after the upgrade [(frame, act, state)]
    zeroed: set = field(default_factory=set)   # tau: the steps (k) whose clock the walk set to 0
    up_state: object = None         # inv: the upgraded state's value

    def json(self) -> dict:
        def step(f, z):
            return {"k": f["k"], "idx": f["idx"], "action": f["action"], "member": f["member"],
                    "block_timestamp": 0 if z else int(f["env"].get("block.timestamp") or 0)}
        out = {"kind": self.kind, "trace": self.trace["id"], "table": [[k, h32(v)] for k, v in sorted(self.kh.items())],
               "prefix": [step(f, self.kind == "tau" and f["k"] in self.zeroed) for f, _a, _s in self.chain]}
        if self.kind == "tau":
            out.update({"x": {"k": self.frame["k"], "idx": self.frame["idx"], "top": self.frame["top"],
                              "action": self.frame["action"], "data": self.frame["data"],
                              "caller": str(self.frame["caller"]).lower(),
                              "args": _jsonable(self.frame["args"]),
                              "block_timestamp": int(self.frame["env"].get("block.timestamp") or 0)},
                        "d": D, "zeroed": sorted(self.zeroed)})
        else:
            out["head"] = [step(f, False) for f, _a, _s in self.head]
        return out

    def sha256(self) -> str:
        return hashlib.sha256(canon(self.json()).encode()).hexdigest()


# ------------------------------------------------------------------------------------------------ law texts
def _law(lid: str, sh: str, imports: list, binders: list, claim: str, counter: bool) -> str:
    kw, q = ("exs", "") if counter else ("for", "+")
    lines = [LHEADER, f"# law_id: {lid}   statement_hash: {sh}", "import Base"]
    lines += [f"import {p} as {a}" for p, a in imports] + ["", f"law {law_name(lid, counter)}:"]
    for name, ty, dup in binders:
        lines.append(f"  {kw} {q if dup else ''}{name}: {ty}")
    lines.append(f"  {{{claim} {'!=' if counter else '=='} True{{}} : Bool}}")
    return "\n".join(lines) + "\n"


def law_text(e: dict, lid: str, sh: str, d: Path, root: Path, m: str, counter: bool = False) -> str:
    """gen/<M>/laws/<id>/LAWS.bend of a law (counter: its counter-law cl_<id>), from its sections index entry."""
    mem = e["member"]
    model = root / "gen" / m / "bundle" / "models" / f"{mem}.bend"
    sec = root / "gen" / m / "symb" / "sections" / f"{mem}.bend"
    n = e["n"]
    if e["kind"] == "tau":
        return _law(lid, sh, [(rel_import(d, model), "M"), (rel_import(d, sec), "U")],
                    [("kh", "List<&2, M.HKB>", True), ("s", "M.HSt", True), ("r_s", "M.Reach<kh, s>", False),
                     ("x", "M.HAct", True), ("d", "M.W", True)], f"U.{e['ok']}(s, x, d, kh)", counter)
    if e["kind"] == "sentinel":
        return _law(lid, sh, [(rel_import(d, model), "M"), (rel_import(d, sec), "U")],
                    [("kh", "List<&2, M.HKB>", True), ("s", "M.HSt", True), ("r_s", "M.Reach<kh, s>", False),
                     ("x", "M.HAct", True)], f"U.{e['ok']}(s, x, kh)", counter)
    if e["kind"] == "link":
        callee = root / "gen" / m / "bundle" / "models" / f"{e['callee']}.bend"
        return _law(lid, sh, [(rel_import(d, model), "M"), (rel_import(d, callee), "Q"),
                              (rel_import(d, root / e["module"]), "K")],
                    [("kh", "List<&2, M.HKB>", True), ("s", "M.HSt", True), ("q", "Q.HSt", True),
                     ("r_s", "K.LReach<kh, s, q>", False), ("x", "M.HAct", True)],
                    f"K.{e['ok']}(s, q, x, kh)", counter)
    if e["kind"] == "versioned":
        return _law(lid, sh, [(rel_import(d, model), "M"), (rel_import(d, sec), "U"),
                              (rel_import(d, root / e["module"]), "V")],
                    [("kh", "List<&2, M.HKB>", True), ("s", "M.HSt", True), ("r_s", "V.VReach<kh, s>", False)],
                    f"U.{e['ok']}(s, kh)", counter)
    raise ValueError(f"{lid}: no law form for kind {e['kind']}")


def nv_text(e: dict, lid: str, sh: str, d: Path, root: Path, m: str) -> str:
    """The inhabitant law of a sentinel law's premises (G11V): a reachable state and an act where sn_hit holds."""
    mem = e["member"]
    model = root / "gen" / m / "bundle" / "models" / f"{mem}.bend"
    sec = root / "gen" / m / "symb" / "sections" / f"{mem}.bend"
    return "\n".join([LHEADER, f"# non-vacuity of {lid} (statement_hash {sh}): its premises {e['hit']} are inhabited "
                      "by a reachable state and an act", "import Base", f"import {rel_import(d, model)} as M",
                      f"import {rel_import(d, sec)} as U", "", f"law nv_{lid.lower()}:",
                      "  exs kh: List<&2, M.HKB>", "  exs s: M.HSt", "  exs r_s: M.Reach<kh, s>", "  exs x: M.HAct",
                      f"  {{U.{e['hit']}(s, x, kh) == True{{}} : Bool}}"]) + "\n"


