TRUE_NE_FALSE = "def true_ne_false(p: {True{} == False{} : Bool}) -> Empty:\n  (%p : M.is_true(_)\n  Unit{})"


def _table(kh: dict, lit, q: str = "M") -> list:
    rows = []
    for k, v in sorted(kh.items()):
        b = bytes.fromhex(k[2:])
        rows.append(f"{q}.HKB{{" + (("[" + ", ".join(str(c) for c in b) + "]") if b else "Nil{}") + ", "
                    + lit.word(h32(v)) + "}")
    return [f"def t_kh() -> List<&2, {q}.HKB>:\n  " + (("[" + ", ".join(rows) + "]") if rows else "Nil{}"), ""]


def _chain(prefix: str, q: str, acts: list, states: list, start: str, table: str) -> tuple:
    """A Reach chain of literal steps in module q (one closed lemma per step) from the state `start`."""
    lines = []
    for i, a in enumerate(acts):
        lines += [f"def {prefix}a{i}() -> {q}.HAct:\n  {a}", ""]

    def st(k: int) -> str:
        return start if k == 0 else f"{prefix}s{k}()"
    for k in range(1, len(acts) + 1):
        lines += [f"def {prefix}s{k}() -> {q}.HSt:\n  {states[k - 1]}", ""]
    for k in range(len(acts)):
        lines += [f"def {prefix}r{k}() -> {{{st(k + 1)} == {q}.step({prefix}a{k}(), {st(k)}, {table}) : {q}.HSt}}:"
                  f"\n  {{==}}", ""]
    chain = f"{q}.R0{{{{==}}}}"
    for k in range(len(acts)):
        chain = f"{q}.RStep{{{prefix}a{k}(), {st(k)}, {chain}, {prefix}r{k}()}}"
    return lines, chain, st(len(acts))


def sentinel_proof(lid: str, e: dict, acts: list, imports: list) -> str:
    """The proof of a sentinel law whose site writes the clock against the constant 0 (the section's sn_ok shape)."""
    if e.get("constant") != 0:
        raise LawRefused("the sentinel proof is written for the constant 0")
    a = bname(e["action"])
    lines = [_pheader(), "import Base"] + [f"import {p} as {al}" for p, al in imports] + [
        "", "# class clock_site: the site writes the act's own clock, nonzero by the premise",
        "def or_not_and(c: Bool, p: Bool) -> {Bool.or(Bool.not(Bool.and(c, p)), p) == True{} : Bool}:",
        "  match c p:"]
    for c in ("True{}", "False{}"):
        for p in ("True{}", "False{}"):
            lines += [f"    case {c} {p}:", "      {==}"]
    lines += ["", f"def Laws.{law_name(lid)}(kh, s, r_s, x):", "  match x:"]
    for cn in acts:
        if cn == f"A_{a}":
            lines += [f"    case M.{cn}{{+ar, +en}}:",
                      f"      or_not_and(U32.is_eq(M.chk_{a}(s, ar, en, kh), 0), M.w_nz(M.ge_e_block_timestamp(en)))"]
        else:
            lines += [f"    case M.{cn}{{_, _}}:", "      {==}"]
    return "\n".join(lines) + "\n"


def witness_proof(lid: str, imports: list, table: list, body: list, state: str, chain: str, binders: list,
                  goal: str, kind: str, note: str) -> str:
    """A witness proof: kind counter (the counter-law's: the claim is False at the literals) or nonvac (the
    inhabitant's: the premises are True)."""
    lines = [_pheader(), "import Base"] + [f"import {p} as {al}" for p, al in imports] + ["", f"# {note}"]
    lines += table + body
    names = []
    for i, (ty, text) in enumerate(binders):
        lines += [f"def b_{i}() -> {ty}:\n  {text}", ""]
        names.append(f"b_{i}()")
    want = "False{}" if kind == "counter" else "True{}"
    g = goal.format(state=state, binders=", ".join(names))
    lines += [f"def cz() -> {{{g} == {want} : Bool}}:\n  {{==}}", ""]
    if kind == "counter":
        lines += [TRUE_NE_FALSE, ""]
        tup = "e => true_ne_false((%e : {_ == False{} : Bool}\n  cz()))"
        name = law_name(lid, True)
    else:
        tup = "cz()"
        name = f"nv_{lid.lower()}"
    for b in reversed(names):
        tup = f"({b}, {tup})"
    tup = f"(t_kh(), ({state}, ({chain}, {tup})))"
    lines.append(f"def Laws.{name}():\n  {tup}")
    return "\n".join(lines) + "\n"


