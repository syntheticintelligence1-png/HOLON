def head_only(d: Decider) -> dict:
    """P6's contrast: each sentinel invariant's search with the member at the head only and the same budgets."""
    out = {}
    for lid, e in sorted(d.index.items()):
        if e["kind"] != "versioned" or lid not in d.entries:
            continue
        w, tried = d.search_inv(lid, legacy=False)
        out[lid] = {"status": "UNKNOWN" if w is None else "WITNESS",
                    "bound": f"{tried} candidates over {len(d.traces())} corpus traces, the head only (at most "
                             f"{int(d.sctx.side['search'].get('prefix_steps', 4)) + int(d.sctx.side['search'].get('continuation_steps', 2))} "
                             "head steps at the frames' clocks, every one >= 1)",
                    "witness": w.json() if w is not None else None}
    return out


