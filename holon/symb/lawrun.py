    def symb_block(self, lid: str, e: dict, w: Witness) -> dict:
        b = self.entries[lid]["basis"]
        out = {"id": self.entries[lid]["basis"]["member"] + ":" + self.entries[lid]["subform"], "kind": e["kind"]}
        if e["kind"] == "tau":
            site, sk = self.site_of(lid, w)
            out.update({"site": site, "site_kind": sk, "d": D, "action": b["action"]})
        else:
            doc = self.bctx.load(self.sctx.side["members"][e["member"]]["document"])
            view = next(a for a in doc["actions"] if a["name"] == e["view"])
            pre = [{"member": e["member"], "action": f["action"],
                    "block_timestamp": int(f["env"].get("block.timestamp") or 0)} for f, _a, _s in w.chain]
            up = [{"member": e["member"], "action": "upgrade", "from": self.sctx.side["legacy"]["tag"],
                   "to": "head"}]
            post = [{"member": e["member"], "action": f["action"],
                     "block_timestamp": int(f["env"].get("block.timestamp") or 0)} for f, _a, _s in w.head]
            out.update({"site": view.get("src"), "site_kind": "view", "view": e["view"], "prefix": pre + up + post,
                        "premise": "every head step's block_timestamp >= 1 (no block has timestamp 0; disclosed); "
                                   "the legacy model reads no clock"})
        return out

    def counter_text(self, lid: str, e: dict, w: Witness, lp: Path) -> str:
        d = self.paths(lid)["proof"].parent
        imps = self.imports(d, e, lp)
        if e["kind"] == "tau":
            lm = self.machine(e["member"])
            acts = [lm.lit.text(a) for _f, a, _s in w.chain]
            states = [lm.lit.typed(s, "HSt") for _f, _a, s in w.chain]
            body, chain, state = _chain("w_", "M", acts, states, "M.s0()", "t_kh()")
            note = (f"witness: trace {w.trace['id']}, x the top-level frame of step {w.frame['k']} "
                    f"({w.frame['action']}); {len(w.chain)} state-changing prefix steps, the clock of steps "
                    f"{sorted(w.zeroed)} set to 0; d = {D}")
            return witness_proof(lid, imps, _table(w.kh, lm.lit), body, state, chain,
                                 [("M.HAct", lm.lit.text(w.x)), ("M.W", lm.lit.word(h32(D)))],
                                 f"U.{e['ok']}({{state}}, {{binders}}, t_kh())", "counter", note)
        lm, hm = self.legacy_machine(), self.machine(e["member"])
        lq = re.compile(r"(?<![\w.])M\.")
        lacts = [lq.sub("L.", lm.lit.text(a)) for _f, a, _s in w.chain]
        lstates = [lq.sub("L.", lm.lit.typed(s, "HSt")) for _f, _a, s in w.chain]
        lbody, lchain, lstate = _chain("l_", "L", lacts, lstates, "L.s0()", "V.inv_kh(t_kh())")
        cur = f"V.eta({lstate})"
        chain = f"V.VUp{{{lstate}, {lchain}, {{==}}}}"
        body = list(lbody)
        for i, (_f, a, s) in enumerate(w.head):
            body += [f"def h_a{i}() -> M.HAct:\n  {hm.lit.text(a)}", "",
                     f"def h_s{i + 1}() -> M.HSt:\n  {hm.lit.typed(s, 'HSt')}", "",
                     f"def h_t{i}() -> {{M.w_nz(M.ge_e_block_timestamp(U.sy_en(h_a{i}()))) == True{{}} : Bool}}:\n  {{==}}",
                     "", f"def h_r{i}() -> {{h_s{i + 1}() == M.step(h_a{i}(), {cur}, t_kh()) : M.HSt}}:\n  {{==}}", ""]
            chain = f"V.VStep{{h_a{i}(), {cur}, {chain}, h_t{i}(), h_r{i}()}}"
            cur = f"h_s{i + 1}()"
        note = (f"witness: trace {w.trace['id']}; {len(w.chain)} legacy steps, the upgrade, {len(w.head)} head "
                f"steps; the invariant fails at the last state")
        return witness_proof(lid, imps, _table(w.kh, hm.lit), body, cur, chain, [],
                             f"U.{e['ok']}({{state}}, t_kh())", "counter", note)

    def inhabit(self, lid: str, e: dict) -> dict:
        """A checked inhabitant of a sentinel law's premises (gen/<M>/<id>/nonvac/): the first frame of the site's
        action, top-level or a member-to-member call, whose step succeeds on the member's model with its own clock,
        the trace's state-changing frames before it the prefix."""
        p = self.paths(lid)
        sh = self.registry["statements"][lid]
        lm = self.machine(e["member"])
        base = {"parent_statement_hash": sh, "degenerate": False}
        found = None
        s0ref, s0val = lm.s0()
        for tr in self.traces():
            frames = [f for f in tr["frames"] if f["member"] == e["member"]]
            if not any(f["action"] == e["action"] for f in frames):
                continue
            kh: dict = {}
            ref, val, chain = s0ref, s0val, []
            for f in frames:
                act = lm.act(f["action"], lm.ar(f["action"], f["args"]), lm.en(f["env"]))
                if f["action"] == e["action"] and lm.fn(f"C_{e['hit']}", lambda t, ref=ref, act=act:
                                                        [{"$ref": ref}, act, t], kh):
                    found = (tr, f, act, list(chain), kh)
                    break
                nref, nval = lm.step(act, ref, kh)
                if nval != val:
                    chain.append((f, act, nval))
                ref, val = nref, nval
            if found:
                break
        if found is None:
            return {**base, "status": "unknown", "law": None, "witness": None, "reachable": None,
                    "bound": "no frame of the site's action meets the premises on the member's model"}
        tr, f, act, chain, kh = found
        # the literals re-made small: each act's environment reduced to the code-table entries its step needs (the
        # same outcome), and a hash table of only the keys this chain and act look up
        chain, act, kh = self.reduced(lm, chain, act, e["hit"])
        p["nv_laws"].parent.mkdir(parents=True, exist_ok=True)
        p["nv_laws"].write_text(nv_text(e, lid, sh, p["nv_laws"].parent, self.root, self.m), encoding="utf-8")
        acts = [lm.lit.text(a) for _f, a, _s in chain]
        states = [lm.lit.typed(s, "HSt") for _f, _a, s in chain]
        body, ch, state = _chain("w_", "M", acts, states, "M.s0()", "t_kh()")
        imps = self.imports(p["nv_proof"].parent, e, None) + [("./LAWS.bend", "Laws")]
        note = f"inhabitant: trace {tr['id']}, step {f['k']} frame {f['idx']} ({f['action']}); {len(chain)} prefix steps"
        p["nv_proof"].write_text(witness_proof(lid, imps, _table(kh, lm.lit), body, state, ch,
                                               [("M.HAct", lm.lit.text(act))],
                                               f"U.{e['hit']}({{state}}, {{binders}}, t_kh())", "nonvac", note),
                                 encoding="utf-8")
        chk = check(p["nv_proof"])
        wj = {"trace": tr["id"], "step": f["k"], "frame": f["idx"], "action": f["action"], "prefix": len(chain),
              "caller": str(f["caller"]).lower(), "block_timestamp": int(f["env"].get("block.timestamp") or 0)}
        if not chk["ok"]:
            return {**base, "status": "unknown", "law": self.rel(p["nv_laws"]), "witness": wj, "reachable": True,
                    "_checker": chk["checker"],
                    "bound": f"the inhabitant does not check: {chk['checker'].get('failing', '')[-400:]}"}
        return {**base, "status": "inhabited", "law": self.rel(p["nv_laws"]), "witness": wj, "reachable": True,
                "_checker": chk["checker"], "bound": "a checked inhabitant of the premises"}

    def reduced(self, lm, chain: list, act: dict, hit: str) -> tuple:
        """(chain, act, table) re-run from the deployment with each act's environment reduced (holon.bundle.lawrun's
        reduce_env: the code-table entries whose removal changes the step's outcome) and a fresh hash table; the reduced
        chain must reach the same states and the act must still meet the premises."""
        kh: dict = {}
        ref, _v = lm.s0()
        out = []
        for f, a, want in chain:
            name = f["action"]
            en = lm.reduce_env(name, ref, a["f"]["ar"], a["f"]["en"], kh)
            a2 = lm.act(name, a["f"]["ar"], en)
            ref, val = lm.step(a2, ref, kh)
            if val != want:
                raise LawRefused(f"the reduced environment changed a prefix step of {name}")
            out.append((f, a2, val))
        name = next(n for n in lm.doc.actions if bname(n) == act["$r"][2:])
        en = lm.reduce_env(name, ref, act["f"]["ar"], act["f"]["en"], kh)
        a2 = lm.act(name, act["f"]["ar"], en)
        if not lm.fn(f"C_{hit}", lambda t: [{"$ref": ref}, a2, t], kh):
            raise LawRefused("the reduced act no longer meets the premises")
        return out, a2, kh

    def record(self, law: dict, e: dict, status: str, witness, attempts: list, lp: Path, prim, bound, nonvac,
               symb: dict) -> dict:
        from .. import records as R
        from ..bundle.lawrun import bend_version
        lid = law["law_id"]
        sh = self.registry["statements"][lid]
        mem = e["member"]
        mtext = self.section_path(mem).read_text(encoding="utf-8") + "\n" + self.model_path(mem).read_text(
            encoding="utf-8")
        ltext = lp.read_text(encoding="utf-8") if lp.exists() else ""
        roots = re.sub(r"(?<![\w.])[UVK]\.", "M.", ltext)
        roots = "\n".join(ln for ln in roots.splitlines() if not ln.startswith("import ") and "Q." not in ln
                          and "L." not in ln)
        cone = R.cone(roots, mtext)
        rec = {"law_id": lid, "statement_hash": sh, "facts_sha256": law["facts_sha256"], "status": status,
               "scope": "unbounded", "premises": [],
               "kernel": {"name": "bend", "version": bend_version(), "verdict": (prim or {}).get("verdict", "not_run"),
                          **({"verdict_reason": prim["verdict_reason"]} if (prim or {}).get("verdict_reason") else {})},
               "artifacts": {"laws": self.rel(lp) if lp.exists() else None, "proof": (prim or {}).get("proof"),
                             "model": self.rel(self.model_path(mem)), "section": self.rel(self.section_path(mem)),
                             "module": e.get("module"), "law_name": law_name(lid, status == "REFUTED")},
               "checker": (prim or {}).get("checker") or {"exit_code": None, "marker": "not_run"},
               "triage": "finding" if status == "REFUTED" else "none",
               "replay": ({"status": "passed", "detail": f"the real-code replay agrees ({symb.get('replay')})"}
                          if status == "REFUTED" else {"status": "not_applicable",
                                                       "detail": f"{status}: no replayed witness"}),
               "attempts": attempts, "rule": law["rule"], "subform": law["subform"], "member": mem,
               "symb": dict(symb, basis=self.entries[lid]["basis"]),
               "bound": bound if status == "UNKNOWN" else None}
        if symb:
            rec["sym"] = {k: v for k, v in symb.items() if k in ("site", "site_kind", "prefix", "view", "d",
                                                                    "premise", "action")}
        if witness is not None:
            rec["witness"] = witness
        if status == "REFUTED":
            rec["difference"] = {"lhs": False, "rhs": True}
        try:
            b, match = R.resolve_bundle(rec["facts_sha256"], law["facts"], self.root, mtext, set(cone), self.m)
            assumptions = R.model_assumptions(b["facts_sha256"], set(cone), self.root, law["facts"])
        except R.LedgerError:
            match, assumptions = "none", []
        compiled = self.machine(mem).ev.compiled()
        rec.update({"record_version": R.RECORD_VERSION, "prover": "generator",
                    "model_sha256": sha256_file(self.model_path(mem)),
                    "section_sha256": sha256_file(self.section_path(mem)),
                    "compiled_sha256": sha256_file(compiled) if compiled else None,
                    "generator_sha256": generator_sha256(self.root), "cone": cone, "ledger_match": match,
                    "model_assumptions": assumptions, "scope_v2": R.scope_v2(law, rec), "kernels": R.kernels(rec),
                    "independence_class": R.independence_class(rec), "refinement_refs": [], "coverage": None,
                    "non_vacuity": nonvac or {
                        "status": "counter_witness" if status == "REFUTED" else "unknown",
                        "law": self.rel(lp) if status == "REFUTED" else None,
                        "witness": None, "reachable": True if status == "REFUTED" else None, "degenerate": None,
                        "parent_statement_hash": sh,
                        "bound": "the accepted counter-law inhabits the premises" if status == "REFUTED"
                        else "no proof"},
                    "witness_provenance": {"solidity": "internal_harness"} if status == "REFUTED" else None,
                    "filter_bin": "finding" if status == "REFUTED" else None,
                    **R.evidence_fields(law, {"status": status}, self.root)})
        rec["ledger_assumptions"] = sorted(rec["model_assumptions"])
        rec["model_assumptions"] = []
        rec["statement"] = law.get("notes", "")
        return rec


