def o26_path(steps: list[dict]) -> bool:
    """An O26 path (whitepaper App. F2/F6: a revert keeps the stored hash, and a recommit may change the version while
    reusing it): the FIRST step of the trace that commits batch k (commitBatch or commitBatchWithProof; from the
    deployment nothing is stored for k >= 1, so that step writes a fresh value under its own version: a blob's
    versioned hash or the zero versioned hash Z below version 2, an aggregate at version 2), a later revertBatch whose
    range covers k, then the last step recommitting batch k under a version on the other side of 2:
    (v == 2) != (v' == 2). Whether the first commit carried a blob is not part of the shape (F2: Z is reused too)."""
    last = steps[-1]
    k = committed_index(last)
    first = next((i for i, st in enumerate(steps[:-1])
                  if st["action"] in COMMITS and committed_index(st) == k), None)
    if first is None or steps[first]["action"] == "commitState":
        return False
    if (version(steps[first]) == 2) == (version(last) == 2):
        return False
    for rv in steps[first + 1:-1]:
        if rv["action"] == "revertBatch":
            j, c = header_index(rv["args"]["_batchHeader"]), num(rv["args"]["_count"])
            if j <= k < j + c:
                return True
    return False


