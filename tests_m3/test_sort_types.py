def _term_sidecar() -> dict:
    return load_json(TERM_SIDECAR)


def _strip(text: str) -> str:
    keep = []
    for line in text.splitlines():
        s = line.lstrip()
        if s.startswith("#") or s.startswith("import "):
            continue
        keep.append(line.split("#", 1)[0])
    return "\n".join(keep)


def terms(text: str) -> int:
    """The sidecar's measure: comments and imports removed, literal lists collapsed to one placeholder each, then
    tokens plus placeholders."""
    side = _term_sidecar()
    ph, lit, tok = side["placeholder"], re.compile(side["literal_list"]), re.compile(side["tokenizer"])
    t, prev = _strip(text), None
    while prev != t:
        prev, t = t, lit.sub(ph, t)
    return len(tok.findall(t)) + t.count(ph)


def law_blocks(text: str) -> str:
    parts = re.split(r"(?m)^(?=\S)", _strip(text))
    return "".join(p for p in parts if p.startswith("law "))


def bend_imports(path: Path) -> list[tuple[Path, str | None]]:
    """The non-Base imports of a Bend file, resolved against its directory: [(path, alias)]."""
    text = path.read_text(encoding="utf-8")
    out = []
    for target, alias in re.findall(r"^import\s+(\S+)(?:\s+as\s+(\S+))?\s*$", text, re.M):
        if target != "Base":
            out.append(((path.parent / target).resolve(), alias or None))
    return out


def law_names(text: str) -> list[str]:
    return re.findall(r"(?m)^law\s+([\w.]+)", _strip(text))


def cone_chars(laws_rel: str, model_path: Path) -> int:
    """I12-P1's measure, as the sidecar defines it; the law file must import exactly `model_path` as M."""
    B = __import__("holon.bindings", fromlist=["kernel_entries"])
    lb = ROOT / laws_rel
    text = lb.read_text(encoding="utf-8")
    imports = re.findall(r"^import\s+(\S+)(?:\s+as\s+(\S+))?\s*$", text, re.M)
    others = [(p, a) for p, a in imports if p != "Base"]
    if len(others) != 1 or others[0][1] != "M":
        raise AssertionError(f"{laws_rel}: a law file imports Base and exactly one model module as M, got {imports}")
    model = (lb.parent / others[0][0]).resolve()
    if model != model_path.resolve():
        raise AssertionError(f"{laws_rel} imports {model}, not {model_path}")
    entries = B.kernel_entries(model)
    cone = B.kernel_cone(text, entries)
    stmt = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("#"))
    return sum(len(entries[d]) for d in cone) + len(stmt)


def ghost_section(text: str) -> tuple[str, str]:
    if text.count(GHOST_MARKER) != 1:
        raise AssertionError(f"the model holds the ghost marker {text.count(GHOST_MARKER)} times, not once")
    head, ghost = text.split(GHOST_MARKER)
    return head, ghost


def defined(text: str) -> set[str]:
    return set(re.findall(r"(?m)^def\s+([\w.]+)\s*\(", text))


def names_in(name: str, text: str) -> bool:
    return re.search(rf"(?<![\w.]){re.escape(name)}(?![\w])", re.sub(r"#[^\n]*", "", text)) is not None


class _Copy:
    """Commands run in a throwaway copy of the repository."""

    def __init__(self):
        self.repo = copy_repo()
        self.tmp = self.repo.parent
        self.logs: list[str] = []

    def holon(self, args: list[str], timeout: int = 3600):
        p = run_holon([str(a) for a in args], cwd=self.repo, timeout=timeout)
        self.logs.append(f"$ holon {' '.join(str(a) for a in args)} -> {p.returncode}\n"
                         f"{p.stdout[-1500:]}{p.stderr[-1500:]}")
        return p

    def log(self) -> str:
        return "\n".join(self.logs)[-6000:]

    def cleanup(self):
        shutil.rmtree(self.tmp, ignore_errors=True)


