def _split_tuple(t: str) -> list[str]:
    depth, parts, cur = 0, [], ""
    for ch in t:
        if ch == "," and depth == 0:
            parts.append(cur)
            cur = ""
            continue
        depth += ch == "("
        depth -= ch == ")"
        cur += ch
    if cur:
        parts.append(cur)
    return parts


def _ptype(t: str):
    t = t.strip()
    if t.endswith("[]"):
        return ("array", _ptype(t[:-2]))
    if t.startswith("(") and t.endswith(")"):
        return ("tuple", [_ptype(p) for p in _split_tuple(t[1:-1])])
    return ("atom", t)


def _dynamic(tp) -> bool:
    k, x = tp
    if k == "atom":
        return x in ("bytes", "string")
    return True if k == "array" else any(_dynamic(e) for e in x)


def _word(v: int) -> bytes:
    return (v % (1 << 256)).to_bytes(32, "big")


def _bytes(v) -> bytes:
    if isinstance(v, str):
        return bytes.fromhex(v[2:] if v.startswith("0x") else v)
    return bytes(v)


def _enc(tp, v) -> bytes:
    k, x = tp
    if k == "atom":
        if x in ("bytes", "string"):
            b = v.encode() if x == "string" and isinstance(v, str) and not v.startswith("0x") else _bytes(v)
            return _word(len(b)) + b + b"\0" * ((-len(b)) % 32)
        if x == "bool":
            return _word(1 if v else 0)
        if x.startswith("bytes"):
            b = _bytes(v) if not isinstance(v, int) else v.to_bytes(32, "big")
            return b.ljust(32, b"\0")
        if x == "address" or x.startswith("uint"):
            return _word(int(v, 16) if isinstance(v, str) else int(v))
        if x.startswith("int"):
            return _word(int(v))
        raise AssertionError(f"no ABI encoding for {x}")
    if k == "array":
        return _word(len(v)) + _enc_seq([x] * len(v), list(v))
    return _enc_seq(x, list(v))


def _enc_seq(tps, vals) -> bytes:
    head_len = sum(32 if _dynamic(tp) else 32 * _static_words(tp) for tp in tps)
    head, tail = b"", b""
    for tp, v in zip(tps, vals):
        e = _enc(tp, v)
        if _dynamic(tp):
            head += _word(head_len + len(tail))
            tail += e
        else:
            head += e
    return head + tail


def _static_words(tp) -> int:
    k, x = tp
    return sum(_static_words(e) for e in x) if k == "tuple" else 1


def abi_encode(types: list[str], values: list) -> bytes:
    return _enc_seq([_ptype(t) for t in types], values)


