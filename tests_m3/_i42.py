def lean_code(src: str) -> str:
    """A Lean source without its comments (line comments, and block comments, which nest), string literals blanked
    to "": what the statement and command checks of rule T2 read. Written here independently of holon.lean."""
    out, i, depth, n = [], 0, 0, len(src)
    while i < n:
        if depth == 0 and src[i] == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            out.append('""')
            i = j + 1
        elif depth == 0 and src.startswith("--", i):
            j = src.find("\n", i)
            i = n if j < 0 else j
        elif src.startswith("/-", i):
            depth += 1
            i += 2
        elif depth and src.startswith("-/", i):
            depth -= 1
            i += 2
        elif depth:
            i += 1
        else:
            out.append(src[i])
            i += 1
    return "".join(out)


def lean_statement(src: str, name: str) -> str | None:
    """The statement of theorem `name` in a Lean source, comments removed: from `theorem name` up to `:=`, whitespace
    normalized; None unless the source, comments removed, declares `theorem name` exactly once (at a line start)."""
    code = lean_code(src)
    hits = [m.start() for m in re.finditer(rf"(?m)^theorem {re.escape(name)}(?=\s)", code)]
    if len(hits) != 1:
        return None
    i = hits[0]
    j = code.find(":=", i)
    if j < 0:
        return None
    return " ".join(code[i:j].split())


