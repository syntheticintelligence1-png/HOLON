def candidate(cid) -> dict:
    """A candidate's search-space entry (candidates.json) merged with its evaluation (evaluations.json): the batches
    carry both sides' keys."""
    if "cands" not in _CACHE:
        _CACHE["cands"] = {c["id"]: c for c in need(CANDS)["candidates"]}
    meta = _CACHE["cands"].get(cid)
    ev = {c["id"]: c for c in evaluations()["candidates"]}.get(cid)
    if meta is None or ev is None:
        raise AssertionError(f"no candidate {cid}")
    out = dict(meta, commit=ev["commit"])
    out["batches"] = [dict(a, **b) for a, b in zip(meta["batches"], ev["batches"])]
    return out


