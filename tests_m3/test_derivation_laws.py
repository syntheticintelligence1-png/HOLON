class TestInstrument(unittest.TestCase):
    """The frozen inputs are what they say they are (construction; green at the prereg)."""

    def test_the_key_pins_the_instruments(self):
        t = th()
        self.assertEqual(file_sha256(SIDE), t["sidecar_sha256"])
        self.assertEqual(file_sha256(ROOT / "tests_m3" / "_i88.py"), t["instrument_sha256"])
        d = sys.modules[__name__].__doc__
        self.assertEqual(hashlib.sha256(d.encode("utf-8")).hexdigest(), t["contract_docstring_sha256"])
        for rel, sha in t["inputs_sha256"].items():
            self.assertEqual(file_sha256(ROOT / rel), sha, rel)

    def test_the_sidecar_is_the_instruments(self):
        I = instrument()
        i85 = load_json(ROOT / I.I85_SIDECAR)
        action = i85["product"]["commit_action"]
        s = side()
        self.assertEqual(s["laws"], json.loads(json.dumps(I.laws(action))))
        self.assertEqual(s["hypotheses"], json.loads(json.dumps(I.hypotheses(action))))
        self.assertEqual(s["vocabulary"], json.loads(json.dumps(I.vocabulary())))
        self.assertEqual(s["search"], json.loads(json.dumps(I.search(ROOT))))
        self.assertEqual(law_ids(), th()["law_ids"])

    def test_the_o8_pair_differs_only_in_its_hypothesis(self):
        I = instrument()
        a, b = (e for e in side()["laws"] if e["subform"] == "product_trailing")
        sa, sb = json.loads(json.dumps(a["statement"])), json.loads(json.dumps(b["statement"]))
        for st in (sa, sb):
            for p in st["assume"]:
                if isinstance(p.get("hyp"), dict) and p["hyp"]["name"].startswith("HypC_"):
                    p["hyp"]["name"] = "HypC"
        self.assertEqual(sa, sb)
        fams = {side()["hypotheses"][h]["family"] for h in I.hyp_names({"statement": a["statement"]}) +
                I.hyp_names({"statement": b["statement"]}) if h.startswith("HypC_")}
        self.assertEqual(fams, {"HypC"})


