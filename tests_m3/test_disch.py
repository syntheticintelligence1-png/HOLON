    def test_r0_is_the_binding_deployment(self):
        """The sidecar's r0 is the binding's deployment: on I30's capture of it (gen/M3/sorts/models/
        morph_rollup.extracted.init.json, {"storage": {slot: word}, ..}), every scalar path r0 fixes holds that word
        (at its offset and width), every "T" scalar is non-zero, every unlisted scalar is 0, and the non-zero slots
        are exactly the scalars', the mapping entries r0's "keys" name (keccak256(key . slot), plus each listed
        member's slot) and the two EIP-1967 proxy slots."""
        init = need(I30_INIT)
        words = {int(k, 0): int(v, 0) for k, v in init["storage"].items()}
        side = D.load_sidecar(ROOT, SIDECAR_REL)
        doc = load_json(ROOT / DOC_REL)
        lay = R.Layout(doc)
        allowed = {int(s, 16) for s in side["r0"]["proxy_slots"]}
        for name, fam in lay.fam.items():
            if fam.get("kind") != "scalar":
                continue
            slot, off, width = fam["slot"], fam.get("offset", 0), fam.get("width") or 256
            allowed.add(slot)
            v = (words.get(slot, 0) >> (8 * off)) & ((1 << width) - 1)
            want = side["r0"]["values"].get(name, [0])
            if want == ["T"]:
                self.assertNotEqual(v, 0, name)
            else:
                self.assertEqual([v], want, name)
        for fam_name, keys in side["r0"]["keys"].items():
            fam = lay.fam[fam_name]
            for k, members in keys.items():
                base = int.from_bytes(keccak256(int(k, 0).to_bytes(32, "big") + fam["slot"].to_bytes(32, "big")),
                                      "big")
                if members is None:
                    allowed.add(base)
                    self.assertNotEqual(words.get(base, 0), 0, f"{fam_name}[{k}]")
                else:
                    for m in members:
                        f = next(x for x in fam["fields"] if x["name"] == m)
                        allowed.add(base + f["slot"])
                        self.assertNotEqual(words.get(base + f["slot"], 0), 0, f"{fam_name}[{k}].{m}")
        self.assertEqual(sorted(hex(s) for s, w in words.items() if w and s not in allowed), [])


