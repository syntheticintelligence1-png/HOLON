"""I95's build: DISCH's time-monotonicity route over checked subtraction's guard (holon.disch.proofs.TimeMono.mono).

The typed model's prelude defines w_sub_ok(a, b), the guard of a checked subtraction, as w_ge(a, b). The route reads
a clock atom M.w_sub_ok(a, b) as M.w_ge(a, b), so the proofs it already gives for w_ge apply by unfolding:
  W1  for each of w_sub_ok(X, t) (falls with time), w_sub_ok(t, Y) (rises), and w_sub_ok(w_add(X, Y), t) (falls, a
      word sum free of t), the route's proof is accepted by Bend over the typed M3 model's prelude, beside the w_ge
      control that the route proved before I95;
  W2  an atom whose operand holds t inside other word arithmetic (w_add(t, X)) is still refused: words wrap, so such
      an atom need not be monotone in t.
"""
from __future__ import annotations

import os
import shutil
import tempfile
import types
import unittest
from pathlib import Path

from holon import bend
from holon.disch import order as ORDER
from holon.disch import proofs as P

ROOT = Path(__file__).resolve().parents[1]
MODEL = "gen/M3/sorts/models/morph_rollup_extracted.bend"
CASES = [("ge_control", "M.w_ge(X, t)", "+X: M.W", "down"),
         ("sub_ok_falling", "M.w_sub_ok(X, t)", "+X: M.W", "down"),
         ("sub_ok_rising", "M.w_sub_ok(t, Y)", "+Y: M.W", "up"),
         ("sub_ok_sum_falling", "M.w_sub_ok(M.w_add(X, Y), t)", "+X: M.W, +Y: M.W", "down")]


def _mono(atom: str) -> tuple:
    return P.TimeMono.mono(types.SimpleNamespace(g=None, defs=[]), atom, 0)


class TestClockRoute(unittest.TestCase):
    def test_w1_the_route_proves_checked_subtraction_atoms(self):
        defs = []
        for name, atom, params, want in CASES:
            dirn, pf = _mono(atom)
            self.assertEqual(dirn, want, atom)
            body = pf[len("h => "):].replace("@T2@", "T2").replace("@T@", "T")
            a_t, a_t2 = P.at_time(atom, "T"), P.at_time(atom, "T2")
            pre, post = (a_t2, a_t) if dirn == "down" else (a_t, a_t2)
            defs.append(f"def chk_{name}(+T: M.W, +T2: M.W, {params}, hle: {{M.w_le(T, T2) == True{{}} : Bool}}, "
                        f"h: {{{pre} == True{{}} : Bool}}) -> {{{post} == True{{}} : Bool}}:\n  {body}\n")
        # the file sits two levels under gen/M3 so that the model's relative import resolves, as a DISCH proof's does
        tmp = Path(tempfile.mkdtemp(prefix="i95_clock_route_", dir=ROOT / "gen" / "M3" / "proofs"))
        try:
            text = "\n".join(["# I95's route check (generated by the test; never committed)", "import Base",
                              f"import ../../sorts/models/{Path(MODEL).name} as M", "", P.library(True),
                              ORDER.text("M.", True)] + defs)
            (tmp / "PROOF.bend").write_text(text, encoding="utf-8")
            r = bend.check(tmp / "PROOF.bend", timeout=1800)
            out = "\n".join(str(getattr(r, k, "")) for k in ("stdout", "stderr", "out", "err"))
            self.assertIn("ALL PROOFS CHECK", out, out[-2000:])
        finally:
            shutil.rmtree(tmp, ignore_errors=True)

    def test_w2_t_inside_other_arithmetic_stays_refused(self):
        for atom in ("M.w_sub_ok(M.w_add(t, X), Y)", "M.w_sub_ok(Y, M.w_add(X, t))"):
            with self.assertRaises(P.NoProof):
                _mono(atom)


if __name__ == "__main__":
    os.environ.setdefault("BEND_NO_TELEMETRY", "1")
    unittest.main()
