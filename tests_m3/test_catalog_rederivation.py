"""F30: the bookkeeping of a catalog-version re-derivation (milestone M3 after the I30 merge, 4085005).

M3 moved from holon-rules/1.1 (I24, PAR only) to holon-rules/1.2 (I24's PAR producers plus I30's typed SORT). A
holon-ir/0.3 statement hash covers rule_catalog_version, so the 80 PAR statement hashes changed although no claim did.

  catalog_rederivation  the laws/STATEMENT_DIFF.jsonl entry kind for exactly that (holon.statement_diff): accepted only
                        when the two law files are identical with rule_catalog_version masked, the law's producer is the
                        same object in both catalogs, and holon derive under each catalog reproduces each side with its
                        hash from the same basis element; the statement-change tie also needs the entry's two hashes to
                        be the registry change's. Never a claim change, a binding change or a deletion.
  the 80 lines          generated by `python -m holon.statement_diff recatalog --milestone M3 --append`, never by hand.
  spec/bindings/M3.json rebound through the channel (each change covered by its line; nothing but the statement hash
                        changed), with I30's typed laws bound to the typed model as their records name it.
  gate3                 holon.gate's G2 (registry, statement lifecycle, bindings), G8 and G3 run over every M3 law.

Tests that read the repository history fail, never skip, without it (BUILD_PLAN §0.1.4).

F39: later bumps (I27 1.2 -> 1.3, I31 1.3 -> 1.4 and 1.2 -> 1.4 across the merge, I26 1.4 -> 1.5) add lines of the same
kind; the tests above hold for every line, and F30's 80 stay one per PAR law. Lines appended on two branches are ordered
in the log by their merge, not by the registry history the tool walks, so the tool's lines are compared with the
committed ones line for line by (law, old hash, new hash). A REFUTED typed law's checked LAWS.bend is its counter-law
(G2 compares it with the bound counter-law). F35's binding_change lines are checked against the bound model at their
bound commit, which needs the history, so gate3's G2 runs on a clone of the committed tree, not on a copy.
"""
from __future__ import annotations

import copy
import json
import os
import re
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from tests_m3._m3 import ROOT, holon_module, load_json, write_json

LOG = ROOT / "laws" / "STATEMENT_DIFF.jsonl"
KIND = "catalog_rederivation"
OLD_CATALOG, NEW_CATALOG = "holon-rules/1.1", "holon-rules/1.2"
TYPED = ("L_sort_realize_rollup_363_4a64383b", "L_sort_tag_rollup_279_e01ea84a", "L_sort_tag_rollup_406_e01ea84a")
AT = re.compile(r"\(registry change at ([^)]*)\)")


def log_lines(path=LOG) -> list[dict]:
    return [json.loads(x) for x in path.read_text().splitlines() if x.strip()]


class TestCatalogRederivation(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.SD = holon_module("holon.statement_diff")
        cls.lines = [e for e in log_lines() if e.get("kind") == KIND]

    def entry(self) -> dict:
        e = copy.deepcopy(self.lines[0])
        e.pop("accepted", None)
        return e

    def test_the_80_par_laws_each_have_one_line(self):
        """F30's bump (holon-rules/1.1 -> 1.2) has one line per PAR law; every later bump's lines (F39: I27, I31 and
        I26 bumped the catalog again) are lines of the same kind, each between the two catalogs its sides name. The PAR
        laws are those over the linked codec document (I67's laws over a Go-op document, derived after F30, have no F30
        line; nor has I86's push law over a bundle member's document: amended at I86's build)."""
        par = sorted(p.stem for p in (ROOT / "laws" / "M3").glob("L_par_*.json")
                     if not str(json.loads(p.read_text()).get("facts") or "").startswith("gen/M3/goops/")
                     and json.loads(p.read_text()).get("subform") != "push")
        self.assertEqual(len(par), 80)
        f30 = [e for e in self.lines if (e["old_catalog"], e["new_catalog"]) == (OLD_CATALOG, NEW_CATALOG)]
        self.assertEqual(sorted(e["law_id"] for e in f30), par)
        for e in self.lines:
            with self.subTest(law=e["law_id"], catalogs=(e["old_catalog"], e["new_catalog"])):
                self.assertEqual(e["milestone"], "M3")
                self.assertEqual((e["old"]["rule_catalog_version"], e["new"]["rule_catalog_version"]),
                                 (e["old_catalog"], e["new_catalog"]))
                self.assertEqual(self.SD.masked(e["old"]), self.SD.masked(e["new"]))
                self.assertEqual(e["accepted"]["catalogs"], [e["old_catalog"], e["new_catalog"]])

    def test_every_m3_registry_change_is_tied_to_its_line(self):
        """G2's tie on the real history: every M3 statement-hash change since the log was introduced is covered, and
        each change is covered by exactly the line for that law, carrying the registry's two hashes."""
        s = self.SD.scan(LOG, ROOT)
        self.assertTrue(s["git"], "the tie needs the repository history")
        self.assertEqual(s["problems"], [])
        bad, _ = self.SD.tie_problems("M3", ROOT, s)
        self.assertEqual(bad, [])
        rc = self.SD.registry_changes("M3", ROOT)
        ok = [x["entry"] for x in s["entries"] if x.get("ok")]
        tied = []
        for ch in rc["changes"]:
            cov = [e for e in ok if self.SD.covers(e, ch)]
            lines = [e for e in cov if e.get("kind") == KIND]
            with self.subTest(law=ch["law_id"], at=ch["at"]):
                self.assertTrue(cov, "every change is covered")
                if lines:   # a catalog bump: exactly its line, carrying the registry's two hashes
                    self.assertEqual([(e["law_id"], e["old_hash"], e["new_hash"]) for e in lines],
                                     [(ch["law_id"], ch["old_hash"], ch["new_hash"])])
                    tied.append((ch["law_id"], ch["old_hash"], ch["new_hash"]))
        # F39: every catalog line ties a registry change (none is extra), F30's 80 among them
        self.assertEqual(sorted(tied), sorted((e["law_id"], e["old_hash"], e["new_hash"]) for e in self.lines))
        self.assertGreaterEqual(len(tied), 80)

    def test_the_lines_are_what_the_tool_generates(self):
        """Generate, never hand-write: with no line accepted yet, the tool rebuilds exactly the committed lines (F39:
        line for line by law and hashes, since the log orders lines appended on two branches by their merge; a line
        appended before its registry change was committed names the working tree where the tool now names the
        commit), and each acceptance record is the one the check gives on this tree."""
        SD = self.SD
        real = SD.scan

        def without_catalog_lines(path, root):
            s = real(path, root)
            return {**s, "entries": [x for x in s["entries"] if x["entry"].get("kind") != KIND]}
        with mock.patch.object(SD, "scan", without_catalog_lines):
            es, notes = SD.catalog_rederivation_entries("M3", ROOT)
        self.assertEqual(notes, [])

        def key(e):
            return e["law_id"], e["old_hash"], e["new_hash"]

        def where(e):   # the reason names where the registry change sat when the line was generated
            m = AT.search(e["reason"])
            return m.group(1) if m else None

        def masked(e):
            return json.dumps({**{k: v for k, v in e.items() if k != "accepted"},
                               "reason": AT.sub("(registry change at ..)", e["reason"])}, sort_keys=True)
        committed = {key(x): x for x in self.lines}
        self.assertEqual(len(committed), len(self.lines), "one line per registry change")
        self.assertEqual(sorted(key(e) for e in es), sorted(committed))
        for e in es:
            x = committed[key(e)]
            with self.subTest(law=e["law_id"], catalogs=(e["old_catalog"], e["new_catalog"])):
                # F39: a line generated before its registry change was committed names the working tree there
                self.assertIn(where(x), (where(e), "working tree"))
                self.assertEqual(masked(e), masked(x))
                r = SD.check_entry(e, ROOT)
                self.assertTrue(r["ok"], r["reason"])
                self.assertEqual(SD.acceptance(e, r, ROOT), x["accepted"])

    def test_a_claim_change_is_never_a_catalog_rederivation(self):
        SD = self.SD

        def drop_premise(side):
            return lambda e: e[side]["statement"]["assume"].pop()

        def set_(key, value, side=None):
            return lambda e: (e[side] if side else e).__setitem__(key, value)
        cases = {
            "the new claim drops a premise": drop_premise("new"),
            "both sides drop a premise (not what either catalog derives)":
                lambda e: (drop_premise("new")(e), drop_premise("old")(e)),
            "the new notes differ": set_("notes", "edited", "new"),
            "the new facts differ": set_("facts", "spec/M2/facts/morph_rollup.extracted.json", "new"),
            "one catalog on both sides": lambda e: (e["old"].__setitem__("rule_catalog_version", NEW_CATALOG),
                                                    e.__setitem__("old_catalog", NEW_CATALOG)),
            "the entry names another old catalog than the law": set_("old_catalog", "holon-rules/1.0"),
            "an unknown catalog": lambda e: (e["old"].__setitem__("rule_catalog_version", "holon-rules/9.9"),
                                             e.__setitem__("old_catalog", "holon-rules/9.9")),
            "a wrong old hash": set_("old_hash", "sha256:" + "0" * 64),
            "a wrong new hash": set_("new_hash", "sha256:" + "0" * 64),
            "another basis element": lambda e: e["derivation"].__setitem__("basis", {"key": "x"}),
            "another milestone": set_("milestone", "M2"),
            "a holon-ir/0.2 old side": set_("ir_version", "holon-ir/0.2", "old"),
            "two laws": set_("law_id", "L_par_other", "new"),
        }
        self.assertTrue(SD.check_entry(self.entry(), ROOT)["ok"])
        for name, edit in cases.items():
            with self.subTest(case=name):
                e = self.entry()
                edit(e)
                r = SD.check_entry(e, ROOT)
                self.assertFalse(r["ok"], r["reason"])
        e = self.entry()
        e.pop("derivation")
        self.assertFalse(SD.check_entry(e, ROOT)["ok"])

    def test_a_changed_producer_is_rejected(self):
        """A rule change behind a catalog bump is a claim change: the producer must be the same object in both."""
        rules = holon_module("holon.rules")
        e = self.entry()
        cat = rules.CATALOGS[NEW_CATALOG]
        patched = {**cat, "PAR": {**cat["PAR"], e["new"]["subform"]: object()}}
        with mock.patch.dict(rules.CATALOGS, {NEW_CATALOG: patched}):
            r = self.SD.check_entry(e, ROOT)
        self.assertFalse(r["ok"], r["reason"])
        self.assertIn("producer", r["reason"])

    def test_covers_needs_the_registry_hashes(self):
        SD = self.SD
        e = self.entry()
        ch = {"law_id": e["law_id"], "old": e["old"], "new": e["new"], "old_hash": e["old_hash"],
              "new_hash": e["new_hash"]}
        self.assertTrue(SD.covers(e, ch))
        self.assertFalse(SD.covers(e, {k: v for k, v in ch.items() if k != "new_hash"}), "a change without hashes")
        self.assertFalse(SD.covers(e, {**ch, "old_hash": "sha256:" + "1" * 64}), "another old hash")
        self.assertFalse(SD.covers(e, {**ch, "new": None}), "a deletion is only ever a signed weakening")


class TestBindingsM3(unittest.TestCase):
    def test_the_bindings_rederive_and_bind_the_typed_laws(self):
        B = holon_module("holon.bindings")
        bound = load_json(ROOT / "spec" / "bindings" / "M3.json")
        laws, defs, msgs = B.diff(bound, B.derive("M3", ROOT))
        self.assertEqual((laws, defs, msgs), ([], [], []))
        reg = load_json(ROOT / "laws" / "M3" / "REGISTRY.json")["statements"]
        self.assertEqual(sorted(bound["laws"]), sorted(reg))
        for lid in TYPED:
            with self.subTest(law=lid):
                x = bound["laws"][lid]
                self.assertEqual(x["model"], "gen/M3/sorts/models/morph_rollup.extracted.bend")
                self.assertEqual(x["statement_hash"], reg[lid])
                rec = load_json(ROOT / "results" / "M3" / f"{lid}.json")
                text = (ROOT / "gen" / "M3" / "laws" / lid / "LAWS.bend").read_text()
                # the checked LAWS.bend is the bound emission for the record's status (F39: a REFUTED law's is its
                # counter-law, as G2 checks it)
                want = B.bound_counter(x, rec) if rec["status"] == "REFUTED" else x["statement_sha256"]
                self.assertEqual(B.text_sha256(text), want)
                self.assertIn(f"coerce_{lid[len('L_sort_'):]}", " ".join(x["cone"]))

    def test_a_catalog_rederivation_covers_only_a_hash_only_rebinding(self):
        B = holon_module("holon.bindings")
        e = next(x for x in log_lines() if x.get("kind") == KIND)
        lid = e["law_id"]
        self.assertTrue(B.entry_covers(e, lid, e["new"], True, []))
        self.assertFalse(B.entry_covers(e, lid, e["new"], True, ["some_def"]), "a definition changed too")
        self.assertFalse(B.entry_covers(e, lid, e["new"], True, [], hash_only=False), "the emission changed too")
        self.assertFalse(B.entry_covers(e, lid, e["new"], False, ["some_def"]), "never a binding_change")
        x = load_json(ROOT / "spec" / "bindings" / "M3.json")["laws"][lid]
        self.assertTrue(B.hash_only_change({**x, "statement_hash": "a"}, x))
        self.assertFalse(B.hash_only_change({**x, "statement_sha256": "a"}, x))


def clone_repo() -> Path:
    """A scratch clone of the committed repository at HEAD, with its history (its parent directory is removed by the
    caller): F35's binding_change lines are checked against the bound model at their bound commit."""
    d = Path(tempfile.mkdtemp(prefix="holon-test-"))
    # LFS files stay pointers: a checkout without the LFS objects (CI's) cannot smudge them, and G2 reads none
    env = dict(os.environ, GIT_LFS_SKIP_SMUDGE="1")
    p = subprocess.run(["git", "clone", "-q", "--no-hardlinks", str(ROOT), str(d / "repo")], capture_output=True,
                       text=True, env=env)
    if p.returncode != 0:
        shutil.rmtree(d, ignore_errors=True)
        raise AssertionError(f"git clone failed: {p.stderr[-500:]}")
    return d / "repo"


class TestGate3RunsTheLifecycle(unittest.TestCase):
    """In a clone of the committed tree (F39: with the history, which the binding_change lines need), gate3's G2 fails
    where only holon.gate's G2 looks: an unaccepted statement-diff line, and a binding that no longer matches its
    law."""

    def test_g2_fails_on_an_unaccepted_line_and_on_a_stale_binding(self):
        G3 = holon_module("holon.sorts.gate3")
        repo = clone_repo()
        try:
            ok = G3.Gate3("M3", repo).run(["G2"])["checks"]["G2"]
            self.assertTrue(ok["passed"], ok["detail"])
            self.assertIn("statement-change tie", ok["detail"])
            log = repo / "laws" / "STATEMENT_DIFF.jsonl"
            base = log.read_text()
            bad = next(x for x in log_lines(log) if x.get("kind") == KIND)
            bad["new"]["statement"]["assume"].pop()   # a claim change dressed as a catalog re-derivation
            log.write_text(base + json.dumps(bad, sort_keys=True) + "\n")
            r = G3.Gate3("M3", repo).run(["G2"])["checks"]["G2"]
            self.assertFalse(r["passed"], r["detail"])
            self.assertIn("STATEMENT_DIFF", r["detail"])
            log.write_text(base)
            bp = repo / "spec" / "bindings" / "M3.json"
            b = load_json(bp)
            lid = sorted(b["laws"])[0]
            b["laws"][lid]["statement_hash"] = "sha256:" + "0" * 64
            write_json(bp, b)
            r = G3.Gate3("M3", repo).run(["G2"])["checks"]["G2"]
            self.assertFalse(r["passed"], r["detail"])
            self.assertIn(lid, r["detail"])
        finally:
            shutil.rmtree(repo.parent, ignore_errors=True)


