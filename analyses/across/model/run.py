"""Run every (layer, invariant) through the assumption lattice; write results.json and results.md.

Deterministic: sorted action order, sorted assumption subsets, no timestamps, no randomness."""

import json
import sys
from pathlib import Path

from engine import assumption_lattice
from layers import LAYERS


def fmt_state(s):
    if s is None:
        return "-"
    parts = []
    for k, v in s._asdict().items():
        if isinstance(v, frozenset):
            v = "{" + ",".join(sorted(map(str, v))) + "}"
        elif hasattr(v, "_asdict"):
            v = fmt_state(v)
        parts.append(f"{k}={v}")
    return "(" + ", ".join(parts) + ")"


def trace_rows(out):
    return [{"state": fmt_state(a), "action": lab, "next": fmt_state(b)} for (a, lab, b) in out.trace]


def main(out_dir):
    out_dir = Path(out_dir)
    results = []
    for layer in LAYERS:
        for inv_name in sorted(layer.INVARIANTS):
            lat = assumption_lattice(layer, inv_name)
            entry = {
                "layer": layer.NAME,
                "invariant": inv_name,
                "text": layer.INVARIANTS[inv_name].text,
                "assumptions": list(layer.ASSUMPTIONS),
                "holds_under_all": lat["full"].holds,
                "exhaustive": lat["full"].exhaustive,
                "states_explored_under_all": lat["full"].explored,
                "minimal_assumption_sets": lat["minimal"],
                "relaxations": {},
            }
            if lat["unconditional_cex"] is not None:
                entry["unconditional_counterexample"] = trace_rows(lat["unconditional_cex"])
            for a, (base, o) in sorted(lat["relaxations"].items()):
                entry["relaxations"][a] = {
                    "relaxed_from": base,
                    "counterexample_length": len(o.trace),
                    "trace": trace_rows(o),
                }
            results.append(entry)
    (out_dir / "results.json").write_text(json.dumps(results, indent=1, sort_keys=True) + "\n")
    lines = ["# Model-checking results (generated by model/run.py; do not edit)", ""]
    for e in results:
        lines.append(f"## {e['layer']} :: {e['invariant']}")
        lines.append("")
        lines.append(f"- predicate: {e['text']}")
        lines.append(f"- knobs: {', '.join(e['assumptions'])}")
        lines.append(f"- holds with all knobs enforced: {e['holds_under_all']} (exhaustive={e['exhaustive']}, states={e['states_explored_under_all']})")
        ms = ["{" + ", ".join(m) + "}" for m in e["minimal_assumption_sets"]]
        lines.append(f"- minimal assumption sets: {' | '.join(ms) if ms else 'none (fails under every assumption set)'}")
        if "unconditional_counterexample" in e:
            lines.append("- counterexample with ALL knobs enforced:")
            for i, r in enumerate(e["unconditional_counterexample"], 1):
                lines.append(f"  {i}. {r['state']} --[{r['action']}]--> {r['next']}")
        for a, r in sorted(e["relaxations"].items()):
            lines.append(f"- relax {a} (from {r['relaxed_from']} set), shortest counterexample, {r['counterexample_length']} steps:")
            for i, row in enumerate(r["trace"], 1):
                lines.append(f"  {i}. {row['state']} --[{row['action']}]--> {row['next']}")
        lines.append("")
    (out_dir / "results.md").write_text("\n".join(lines))
    for e in results:
        ms = ["{" + ",".join(m) + "}" for m in e["minimal_assumption_sets"]]
        print(f"{e['layer']:24s} {e['invariant']:24s} all={str(e['holds_under_all']):5s} min={' | '.join(ms) if ms else 'NONE'}"
              + "".join(f"  ~{a}:{r['counterexample_length']}" for a, r in sorted(e['relaxations'].items())))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
