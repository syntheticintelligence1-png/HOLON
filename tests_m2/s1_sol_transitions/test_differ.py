"""S1 sol-transitions differ test.

Compares spec/M2/extracted/morph_rollup.json (produced by
holon.frontends.solidity.extract, which never reads the hand facts) against the
hand-written spec/M1/facts/morph_rollup.json. Every hand guard/write must be
recovered (canonically equal after let-expansion) or listed as differ debt with
a kind and a reason. A full report is written to
tests_m2/s1_sol_transitions/differ_report.json (deterministic artifact).
"""

import json
import unittest
from pathlib import Path

from holon.frontends.solidity import differ as differ_mod

REPO = Path(__file__).resolve().parents[2]
HAND = REPO / "spec" / "M1" / "facts" / "morph_rollup.json"
EXTRACTED = REPO / "spec" / "M2" / "extracted" / "morph_rollup.json"
COVERAGE = REPO / "spec" / "M2" / "coverage" / "solidity_transitions.json"
REPORT = Path(__file__).parent / "differ_report.json"

REQUIRED_TOP = ["facts_version", "params", "types", "state", "ghost_state", "defs", "actions",
                "reasons", "principals", "observers", "disch", "consumers"]
DEBT_KINDS = {"not_extracted", "hand_simplification", "oracle_gap", "diverged",
              "unmodelled_member", "unmodelled_value", "unmodelled_call", "unmodelled_write"}


def _load():
    return json.loads(HAND.read_text()), json.loads(EXTRACTED.read_text())


class TestExtractedShape(unittest.TestCase):
    def test_required_keys(self):
        _, e = _load()
        for k in REQUIRED_TOP:
            self.assertIn(k, e, f"missing top-level key {k}")
        self.assertEqual(e["facts_version"], "holon-facts/0.2")

    def test_no_unresolved_tokens(self):
        """No translator sentinels may survive into the emitted facts."""
        s = EXTRACTED.read_text()
        for tok in ("unmodelled", "unbound", "batch_entry"):
            self.assertNotIn(f'"{tok}"', s, f"sentinel {tok} leaked into facts")
        self.assertNotIn('"block"', s, "block.timestamp unresolved")

    def test_all_actions_present(self):
        h, e = _load()
        hn = {a["name"] for a in h["actions"]}
        en = {a["name"] for a in e["actions"]}
        self.assertEqual(hn, en)

    def test_byte_determinism(self):
        """Facts file is regenerated byte-identically by a second extract run."""
        import os
        import holon.frontends.solidity.extract as ex
        import holon.frontends.solidity.astload as al
        spec = ex.load_spec()
        morph = os.path.expanduser(
            os.environ.get(spec["morph_root_env"], spec["morph_root_default"]))
        world = al.run_solc(spec, morph)
        import tempfile
        with tempfile.TemporaryDirectory() as td:
            out = Path(td) / "f.json"
            ex.extract(world, spec, out, None)
            self.assertEqual(EXTRACTED.read_bytes(), out.read_bytes())


class TestDiffer(unittest.TestCase):
    def test_every_hand_item_accounted(self):
        h, e = _load()
        report = differ_mod.diff_facts(h, e)
        REPORT.write_text(json.dumps(report, indent=1, sort_keys=True) + "\n")
        for action, res in sorted(report.items()):
            for m in res["missing"]:
                self.assertIn(m["kind"], DEBT_KINDS, f"{action}: bad debt kind {m['kind']}")
                self.assertTrue(m.get("reason"), f"{action}: missing item without reason: {m['item']}")

    def test_extractor_does_not_read_hand_facts(self):
        """The extractor must never open the hand-written facts file."""
        for p in (REPO / "holon" / "frontends" / "solidity").rglob("*.py"):
            self.assertNotIn("spec/M1", p.read_text(), f"{p.name} references hand facts")


if __name__ == "__main__":
    unittest.main()
